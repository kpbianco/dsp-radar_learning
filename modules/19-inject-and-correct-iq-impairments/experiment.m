subplot(2, 2, 2);
plot(real(corrected_iq_v(trajectory_indices)), ...
    imag(corrected_iq_v(trajectory_indices)), 'o-', ...
    'Color', [0.20 0.55 0.35]);
grid on; axis equal; xlim([-1.3 1.3]); ylim([-1.3 1.3]);
xlabel('I (V)'); ylabel('Q (V)');
title(sprintf('Recovered shear inverse: IRR %.1f dB', stage_irr_db(4)));

subplot(2, 2, [3 4]);
plot(frequency_hz, 20*log10(max(broken_spectrum_v, plot_floor_v)), ...
    '--', 'Color', [0.85 0.25 0.15]);
