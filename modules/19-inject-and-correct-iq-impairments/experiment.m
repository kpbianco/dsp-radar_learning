%% P19: Inject and Correct IQ Impairments
% Guiding question: How do DC offset, gain mismatch, and quadrature error change an IQ spectrum?
% Base MATLAB only. Every impairment and correction is written as an
% explicit I/Q operation so the receiver mechanism remains visible.

%% Visible controls and fixed resource ceilings
random_seed = 1019;
fs_hz = 2048;
record_sample_count = 4096;
tone_frequency_hz = 160;
tone_amplitude_v = 1;
tone_phase_rad = 0.35;
noise_rms_v = 0.002;

dc_i_v = 0.12;
dc_q_v = -0.08;
i_gain = 1.15;
q_gain = 0.85;
quadrature_error_deg = 8;

i_gain_sweep = [1 1.10 1.30];
quadrature_error_sweep_deg = [0 5 15];

max_record_samples = 4096;
max_fft_length = 4096;
max_sweep_cases = 3;
max_stored_numeric_values = 360000;
max_figure_groups = 6;

%% Validate controls before random, signal, FFT, or figure allocation
scalar_controls = [random_seed fs_hz record_sample_count ...
    tone_frequency_hz tone_amplitude_v tone_phase_rad noise_rms_v ...
    dc_i_v dc_q_v i_gain q_gain quadrature_error_deg];
assert(isnumeric(scalar_controls) && isreal(scalar_controls) && ...
    all(isfinite(scalar_controls)), ...
    'P19 scalar controls must be finite real numeric values.');
assert(~islogical(random_seed) && ~islogical(fs_hz) && ...
    ~islogical(record_sample_count) && ~islogical(tone_frequency_hz) && ...
    ~islogical(tone_amplitude_v) && ~islogical(tone_phase_rad) && ...
    ~islogical(noise_rms_v) && ~islogical(dc_i_v) && ...
    ~islogical(dc_q_v) && ~islogical(i_gain) && ...
    ~islogical(q_gain) && ~islogical(quadrature_error_deg), ...
    'P19 controls must not be logical values.');
assert(isscalar(random_seed) && isscalar(fs_hz) && ...
    isscalar(record_sample_count) && isscalar(tone_frequency_hz) && ...
    isscalar(tone_amplitude_v) && isscalar(tone_phase_rad) && ...
    isscalar(noise_rms_v) && isscalar(dc_i_v) && isscalar(dc_q_v) && ...
    isscalar(i_gain) && isscalar(q_gain) && ...
    isscalar(quadrature_error_deg), ...
    'P19 scalar controls must each contain exactly one value.');
assert(random_seed == 1019 && random_seed == floor(random_seed) && ...
    random_seed >= 0 && random_seed <= 2^32-1, ...
    'random_seed must be the canonical unsigned 32-bit seed 1019.');
assert(fs_hz == 2048 && record_sample_count == 4096 && ...
    record_sample_count == floor(record_sample_count) && ...
    mod(record_sample_count, 2) == 0, ...
    'The canonical baseline is 4096 samples at 2048 samples/s.');
assert(tone_frequency_hz == 160 && tone_frequency_hz > 0 && ...
    tone_frequency_hz < fs_hz/2 && ...
    tone_frequency_hz*record_sample_count/fs_hz == ...
    floor(tone_frequency_hz*record_sample_count/fs_hz), ...
    'The tone must be the canonical coherent 160 Hz positive-frequency tone.');
assert(tone_amplitude_v > 0 && tone_amplitude_v <= 2 && ...
    noise_rms_v >= 0 && noise_rms_v <= 0.01, ...
    'Tone amplitude and complex-noise RMS must remain bounded.');
assert(dc_i_v == 0.12 && dc_q_v == -0.08 && ...
    hypot(dc_i_v, dc_q_v) < tone_amplitude_v/2, ...
    'P19 requires the canonical bounded I/Q DC offset.');
assert(i_gain == 1.15 && q_gain == 0.85 && ...
    i_gain > 0 && q_gain > 0, ...
    'P19 requires the canonical positive branch gains.');
assert(quadrature_error_deg == 8 && abs(quadrature_error_deg) < 45, ...
    'The canonical quadrature error must remain inside the invertible range.');
assert(isnumeric(i_gain_sweep) && isvector(i_gain_sweep) && ...
    isreal(i_gain_sweep) && ~islogical(i_gain_sweep) && ...
    all(isfinite(i_gain_sweep)) && isequal(i_gain_sweep, [1 1.10 1.30]), ...
    'i_gain_sweep must be exactly [1 1.10 1.30].');
assert(isnumeric(quadrature_error_sweep_deg) && ...
    isvector(quadrature_error_sweep_deg) && ...
    isreal(quadrature_error_sweep_deg) && ...
    ~islogical(quadrature_error_sweep_deg) && ...
    all(isfinite(quadrature_error_sweep_deg)) && ...
    isequal(quadrature_error_sweep_deg, [0 5 15]), ...
    'quadrature_error_sweep_deg must be exactly [0 5 15].');
assert(all(i_gain_sweep > 0) && ...
    all(abs(quadrature_error_sweep_deg) < 45), ...
    'Every sweep case must remain positive-gain and invertible.');
assert(max_record_samples == 4096 && max_fft_length == 4096 && ...
    max_sweep_cases == 3 && max_stored_numeric_values == 360000 && ...
    max_figure_groups == 6, ...
    'P19 resource ceilings must remain fixed.');
actual_sweep_case_count = numel(i_gain_sweep) + ...
    numel(quadrature_error_sweep_deg);
workspace_vector_equivalents = 52;
figure_vector_equivalents = 24;
resource_safety_vector_equivalents = 4;
estimated_stored_numeric_values = record_sample_count*( ...
    workspace_vector_equivalents + figure_vector_equivalents + ...
    resource_safety_vector_equivalents);
assert(record_sample_count <= max_record_samples && ...
    record_sample_count <= max_fft_length && ...
    numel(i_gain_sweep) <= max_sweep_cases && ...
    numel(quadrature_error_sweep_deg) <= max_sweep_cases && ...
    actual_sweep_case_count <= 2*max_sweep_cases && ...
    estimated_stored_numeric_values <= max_stored_numeric_values && ...
    6 <= max_figure_groups, ...
    'A P19 record, FFT, sweep, storage, or figure ceiling was exceeded.');

% Validation succeeded: replace only this module's previous output state.
close(findall(groot, 'Type', 'figure', 'Tag', 'P19'));
results = struct();

%% Baseline: inject each receiver impairment separately and together
time_s = (0:record_sample_count-1)/fs_hz;
tone_phase_v = 2*pi*tone_frequency_hz*time_s + tone_phase_rad;
private_stream = RandStream('mt19937ar', 'Seed', random_seed);
complex_noise_v = noise_rms_v/sqrt(2)*( ...
    randn(private_stream, 1, record_sample_count) + ...
    1j*randn(private_stream, 1, record_sample_count));
clean_iq_v = tone_amplitude_v*exp(1j*tone_phase_v) + complex_noise_v;
clean_i_v = real(clean_iq_v);
clean_q_v = imag(clean_iq_v);
quadrature_error_rad = quadrature_error_deg*pi/180;

% Direct-conversion receiver model:
% Iraw = gI*I + dI
% Qraw = gQ*(Q*cos(phi) + I*sin(phi)) + dQ
dc_only_iq_v = (clean_i_v + dc_i_v) + ...
    1j*(clean_q_v + dc_q_v);
gain_only_iq_v = i_gain*clean_i_v + 1j*q_gain*clean_q_v;
phase_only_iq_v = clean_i_v + 1j*( ...
    clean_q_v*cos(quadrature_error_rad) + ...
    clean_i_v*sin(quadrature_error_rad));
impaired_iq_v = (i_gain*clean_i_v + dc_i_v) + 1j*( ...
    q_gain*(clean_q_v*cos(quadrature_error_rad) + ...
    clean_i_v*sin(quadrature_error_rad)) + dc_q_v);

reference_positive = exp(-1j*tone_phase_v);
reference_negative = exp(1j*tone_phase_v);
metric_floor_v = 1e-12;
case_iq_v = [clean_iq_v; dc_only_iq_v; gain_only_iq_v; ...
    phase_only_iq_v; impaired_iq_v];
case_names = {'Clean', 'DC only', 'Gain mismatch only', ...
    'Quadrature error only', 'All impairments'};
case_dc_v = zeros(1, 5);
case_desired_v = zeros(1, 5);
case_image_v = zeros(1, 5);
case_irr_db = zeros(1, 5);
case_dc_dbc = zeros(1, 5);
case_iq_correlation = zeros(1, 5);
case_spectrum_v = zeros(5, record_sample_count);
frequency_hz = (-record_sample_count/2:record_sample_count/2-1)* ...
    fs_hz/record_sample_count;

for case_index = 1:5
    case_signal_v = case_iq_v(case_index, :);
    case_dc_v(case_index) = abs(mean(case_signal_v));
    case_desired_v(case_index) = abs(mean( ...
        case_signal_v.*reference_positive));
    case_image_v(case_index) = abs(mean( ...
        case_signal_v.*reference_negative));
    case_irr_db(case_index) = 20*log10(max(case_desired_v(case_index), ...
        metric_floor_v)/max(case_image_v(case_index), metric_floor_v));
    case_dc_dbc(case_index) = 20*log10(max(case_dc_v(case_index), ...
        metric_floor_v)/max(case_desired_v(case_index), metric_floor_v));
    centered_i_v = real(case_signal_v) - mean(real(case_signal_v));
    centered_q_v = imag(case_signal_v) - mean(imag(case_signal_v));
    case_iq_correlation(case_index) = mean(centered_i_v.*centered_q_v)/( ...
        sqrt(mean(centered_i_v.^2))*sqrt(mean(centered_q_v.^2)));
    case_spectrum_v(case_index, :) = abs(fftshift(fft(case_signal_v)))/ ...
        record_sample_count;
end

fprintf('\nP19 separate and combined impairment signatures\n');
for case_index = 1:5
    fprintf('  %-22s DC %+6.1f dBc, image rejection %6.1f dB, rho(I,Q) %+.3f\n', ...
        case_names{case_index}, case_dc_dbc(case_index), ...
        case_irr_db(case_index), case_iq_correlation(case_index));
end

%% Baseline spectra: DC occupies zero; imbalance creates a conjugate image
plot_floor_v = 1e-8;
figure('Name', 'P19 separate IQ impairment spectra', 'Tag', 'P19', ...
    'Color', 'w', 'Position', [50 50 1180 760]);
for case_index = 1:5
    subplot(2, 3, case_index);
    plot(frequency_hz, 20*log10(max(case_spectrum_v(case_index, :), ...
        plot_floor_v)), 'Color', [0.15 0.35 0.75]);
    grid on; xlim([-400 400]); ylim([-100 5]);
    xlabel('Signed frequency (Hz)'); ylabel('Magnitude (dB re 1 V)');
    title(sprintf('%s: IRR %.1f dB, DC %.1f dBc', ...
        case_names{case_index}, case_irr_db(case_index), ...
        case_dc_dbc(case_index)));
end
subplot(2, 3, 6);
axis off;
text(0, 0.8, 'DC offset -> zero-frequency spike', 'FontSize', 11);
text(0, 0.55, 'Gain/phase imbalance -> image at -160 Hz', 'FontSize', 11);
text(0, 0.30, 'Desired tone remains at +160 Hz', 'FontSize', 11);

%% Baseline I/Q trajectories: center shift, ellipse, and tilted axes
trajectory_sample_count = ceil(3*fs_hz/tone_frequency_hz) + 1;
trajectory_indices = 1:trajectory_sample_count;
figure('Name', 'P19 separate IQ impairment trajectories', 'Tag', 'P19', ...
    'Color', 'w', 'Position', [80 70 1180 760]);
for case_index = 1:5
    subplot(2, 3, case_index);
    plot(real(case_iq_v(case_index, trajectory_indices)), ...
        imag(case_iq_v(case_index, trajectory_indices)), 'o-', ...
        'Color', [0.20 0.50 0.70]);
    grid on; axis equal; xlim([-1.6 1.6]); ylim([-1.6 1.6]);
    xlabel('I (V)'); ylabel('Q (V)');
    title(sprintf('%s: center %.2f%+.2fj V', case_names{case_index}, ...
        real(mean(case_iq_v(case_index, :))), ...
        imag(mean(case_iq_v(case_index, :)))));
end
subplot(2, 3, 6);
axis off;
text(0, 0.8, 'Circle centered at origin: balanced I/Q', 'FontSize', 11);
text(0, 0.55, 'Shifted center: DC offset', 'FontSize', 11);
text(0, 0.30, 'Ellipse/tilt: branch gain and phase error', 'FontSize', 11);

%% Staged correction: mean, branch gain, then quadrature shear
estimated_dc_v = mean(impaired_iq_v);
dc_corrected_iq_v = impaired_iq_v - estimated_dc_v;

estimated_i_gain = sqrt(2*mean(real(dc_corrected_iq_v).^2))/ ...
    tone_amplitude_v;
estimated_q_gain = sqrt(2*mean(imag(dc_corrected_iq_v).^2))/ ...
    tone_amplitude_v;
gain_corrected_i_v = real(dc_corrected_iq_v)/estimated_i_gain;
gain_corrected_q_v = imag(dc_corrected_iq_v)/estimated_q_gain;
gain_corrected_iq_v = gain_corrected_i_v + 1j*gain_corrected_q_v;

estimated_iq_correlation = 2*mean( ...
    gain_corrected_i_v.*gain_corrected_q_v)/(tone_amplitude_v^2);
estimated_iq_correlation = max(-1, min(1, estimated_iq_correlation));
estimated_quadrature_error_rad = asin(estimated_iq_correlation);
assert(abs(cos(estimated_quadrature_error_rad)) > 0.5, ...
    'Estimated quadrature shear is too close to singular for correction.');
phase_corrected_q_v = (gain_corrected_q_v - ...
    gain_corrected_i_v*sin(estimated_quadrature_error_rad))/ ...
    cos(estimated_quadrature_error_rad);
corrected_iq_v = gain_corrected_i_v + 1j*phase_corrected_q_v;

stage_iq_v = [impaired_iq_v; dc_corrected_iq_v; ...
    gain_corrected_iq_v; corrected_iq_v];
stage_names = {'Raw combined', 'Mean removed', 'Gains normalized', ...
    'Quadrature shear removed'};
stage_dc_v = zeros(1, 4);
stage_image_v = zeros(1, 4);
stage_irr_db = zeros(1, 4);
stage_spectrum_v = zeros(4, record_sample_count);
for stage_index = 1:4
    stage_signal_v = stage_iq_v(stage_index, :);
    stage_dc_v(stage_index) = abs(mean(stage_signal_v));
    stage_desired_v = abs(mean(stage_signal_v.*reference_positive));
    stage_image_v(stage_index) = abs(mean( ...
        stage_signal_v.*reference_negative));
    stage_irr_db(stage_index) = 20*log10(max(stage_desired_v, ...
        metric_floor_v)/max(stage_image_v(stage_index), metric_floor_v));
    stage_spectrum_v(stage_index, :) = abs(fftshift(fft(stage_signal_v)))/ ...
        record_sample_count;
end
corrected_rmse_v = sqrt(mean(abs(corrected_iq_v-clean_iq_v).^2));

assert(stage_dc_v(2) < 1e-12, ...
    'Mean correction did not remove the measured DC component.');
assert(stage_irr_db(4) > stage_irr_db(1) + 20, ...
    'The staged correction did not materially improve image rejection.');
assert(abs(estimated_quadrature_error_rad-quadrature_error_rad) < 0.01, ...
    'Quadrature-error estimate missed the deterministic baseline tolerance.');

fprintf('\nP19 staged correction\n');
fprintf('  estimated DC: %.4f%+.4fj V (true %.4f%+.4fj V)\n', ...
    real(estimated_dc_v), imag(estimated_dc_v), dc_i_v, dc_q_v);
fprintf('  estimated branch gains: I %.4f, Q %.4f (true %.2f, %.2f)\n', ...
    estimated_i_gain, estimated_q_gain, i_gain, q_gain);
fprintf('  estimated quadrature error: %.3f deg (true %.1f deg)\n', ...
    estimated_quadrature_error_rad*180/pi, quadrature_error_deg);
fprintf('  image rejection: raw %.1f dB -> mean %.1f dB -> gain %.1f dB -> phase %.1f dB\n', ...
    stage_irr_db(1), stage_irr_db(2), stage_irr_db(3), stage_irr_db(4));
fprintf('  final complex-sample RMSE: %.4g V\n', corrected_rmse_v);

figure('Name', 'P19 staged IQ correction', 'Tag', 'P19', ...
    'Color', 'w', 'Position', [110 90 1180 760]);
for stage_index = 1:4
    subplot(2, 2, stage_index);
    plot(frequency_hz, 20*log10(max(stage_spectrum_v(stage_index, :), ...
        plot_floor_v)), 'Color', [0.45 0.20 0.70]);
    grid on; xlim([-400 400]); ylim([-100 5]);
    xlabel('Signed frequency (Hz)'); ylabel('Magnitude (dB re 1 V)');
    title(sprintf('%s: IRR %.1f dB, |DC| %.3g V', ...
        stage_names{stage_index}, stage_irr_db(stage_index), ...
        stage_dc_v(stage_index)));
end

%% Sweep 1: change only I-branch gain mismatch
gain_sweep_irr_db = zeros(size(i_gain_sweep));
gain_sweep_axis_ratio = zeros(size(i_gain_sweep));
clean_tone_iq_v = tone_amplitude_v*exp(1j*tone_phase_v);
figure('Name', 'P19 I branch gain sweep', 'Tag', 'P19', ...
    'Color', 'w', 'Position', [140 100 1180 600]);
for sweep_index = 1:numel(i_gain_sweep)
    case_i_gain = i_gain_sweep(sweep_index);
    sweep_iq_v = case_i_gain*real(clean_tone_iq_v) + ...
        1j*imag(clean_tone_iq_v);
    sweep_desired_v = abs(mean(sweep_iq_v.*reference_positive));
    sweep_image_v = abs(mean(sweep_iq_v.*reference_negative));
    gain_sweep_irr_db(sweep_index) = 20*log10(max(sweep_desired_v, ...
        metric_floor_v)/max(sweep_image_v, metric_floor_v));
    gain_sweep_axis_ratio(sweep_index) = ...
        sqrt(mean(real(sweep_iq_v).^2)/mean(imag(sweep_iq_v).^2));

    subplot(1, numel(i_gain_sweep), sweep_index);
    plot(real(sweep_iq_v(trajectory_indices)), ...
        imag(sweep_iq_v(trajectory_indices)), 'o-', ...
        'Color', [0.85 0.35 0.15]);
    grid on; axis equal; xlim([-1.5 1.5]); ylim([-1.5 1.5]);
    xlabel('I (V)'); ylabel('Q (V)');
    title(sprintf('g_I %.2f: axis %.2f, IRR %.1f dB', ...
        case_i_gain, gain_sweep_axis_ratio(sweep_index), ...
        gain_sweep_irr_db(sweep_index)));
end

%% Sweep 2: change only quadrature phase error
phase_sweep_irr_db = zeros(size(quadrature_error_sweep_deg));
phase_sweep_correlation = zeros(size(quadrature_error_sweep_deg));
figure('Name', 'P19 quadrature error sweep', 'Tag', 'P19', ...
    'Color', 'w', 'Position', [170 110 1180 600]);
for sweep_index = 1:numel(quadrature_error_sweep_deg)
    case_error_rad = quadrature_error_sweep_deg(sweep_index)*pi/180;
    sweep_i_v = real(clean_tone_iq_v);
    sweep_q_v = imag(clean_tone_iq_v)*cos(case_error_rad) + ...
        sweep_i_v*sin(case_error_rad);
    sweep_iq_v = sweep_i_v + 1j*sweep_q_v;
    sweep_desired_v = abs(mean(sweep_iq_v.*reference_positive));
    sweep_image_v = abs(mean(sweep_iq_v.*reference_negative));
    phase_sweep_irr_db(sweep_index) = 20*log10(max(sweep_desired_v, ...
        metric_floor_v)/max(sweep_image_v, metric_floor_v));
    phase_sweep_correlation(sweep_index) = mean(sweep_i_v.*sweep_q_v)/( ...
        sqrt(mean(sweep_i_v.^2))*sqrt(mean(sweep_q_v.^2)));

    subplot(1, numel(quadrature_error_sweep_deg), sweep_index);
    plot(sweep_i_v(trajectory_indices), sweep_q_v(trajectory_indices), ...
        'o-', 'Color', [0.20 0.55 0.35]);
    grid on; axis equal; xlim([-1.3 1.3]); ylim([-1.3 1.3]);
    xlabel('I (V)'); ylabel('Q (V)');
    title(sprintf('phi %g deg: rho %+.3f, IRR %.1f dB', ...
        quadrature_error_sweep_deg(sweep_index), ...
        phase_sweep_correlation(sweep_index), ...
        phase_sweep_irr_db(sweep_index)));
end

%% Broken case: rotate the ellipse instead of undoing its shear
broken_rotated_iq_v = gain_corrected_iq_v* ...
    exp(-1j*estimated_quadrature_error_rad);
broken_desired_v = abs(mean(broken_rotated_iq_v.*reference_positive));
broken_image_v = abs(mean(broken_rotated_iq_v.*reference_negative));
broken_irr_db = 20*log10(max(broken_desired_v, metric_floor_v)/ ...
    max(broken_image_v, metric_floor_v));
broken_spectrum_v = abs(fftshift(fft(broken_rotated_iq_v)))/ ...
    record_sample_count;
corrected_spectrum_v = abs(fftshift(fft(corrected_iq_v)))/ ...
    record_sample_count;
assert(abs(broken_irr_db-stage_irr_db(3)) < 1e-9, ...
    'A global complex rotation must preserve image-rejection magnitude.');

figure('Name', 'P19 broken rotation and shear recovery', 'Tag', 'P19', ...
    'Color', 'w', 'Position', [200 120 1180 650]);
subplot(2, 2, 1);
plot(real(broken_rotated_iq_v(trajectory_indices)), ...
    imag(broken_rotated_iq_v(trajectory_indices)), 'o-', ...
    'Color', [0.85 0.25 0.15]);
grid on; axis equal; xlim([-1.3 1.3]); ylim([-1.3 1.3]);
xlabel('I (V)'); ylabel('Q (V)');
