%% Sweep 2: change only overlap at fixed segment length
overlap_case_count = numel(overlap_fraction_sweep);
overlap_frequency_hz = ...
    (0:(baseline_segment_length/2))*fs_hz/baseline_segment_length;
overlap_welch_psd_v2_per_hz = zeros( ...
    overlap_case_count, baseline_segment_length/2 + 1);
overlap_noise_ripple_db = zeros(1, overlap_case_count);
overlap_effective_average_count = zeros(1, overlap_case_count);

for sweep_index = 1:overlap_case_count
    sweep_overlap_samples = overlap_sweep_samples(sweep_index);
    sweep_hop_samples = overlap_sweep_hop_samples(sweep_index);
    sweep_start = 1:sweep_hop_samples: ...
        (record_sample_count - baseline_segment_length + 1);
    sweep_segment_psd_v2_per_hz = zeros( ...
        numel(sweep_start), baseline_segment_length/2 + 1);
    for segment_index = 1:numel(sweep_start)
        first_sample = sweep_start(segment_index);
        segment_v = record_v(first_sample:(first_sample + baseline_segment_length - 1));
        segment_fft_v = fft(segment_v.*baseline_window, baseline_segment_length);
        segment_two_sided_psd_v2_per_hz = ...
            abs(segment_fft_v).^2/(fs_hz*baseline_window_energy);
        segment_one_sided_psd_v2_per_hz = ...
            segment_two_sided_psd_v2_per_hz(1:(baseline_segment_length/2 + 1));
        segment_one_sided_psd_v2_per_hz(2:end-1) = ...
            2*segment_one_sided_psd_v2_per_hz(2:end-1);
        sweep_segment_psd_v2_per_hz(segment_index, :) = ...
            segment_one_sided_psd_v2_per_hz;
    end
    overlap_welch_psd_v2_per_hz(sweep_index, :) = ...
        mean(sweep_segment_psd_v2_per_hz, 1);
    overlap_noise_ripple_db(sweep_index) = std(10*log10(max( ...
        overlap_welch_psd_v2_per_hz(sweep_index, welch_noise_mask), realmin)));

    % Window-overlap correlation explains why K overlapping segments are
    % not K independent measurements. This approximation includes every
    % nonzero window correlation lag and is used only as an interpretation metric.
    correlation_penalty = 1;
    for lag_index = 1:(numel(sweep_start) - 1)
        lag_samples = lag_index*sweep_hop_samples;
        if lag_samples < baseline_segment_length
            window_correlation = sum( ...
                baseline_window(1:(end - lag_samples)).* ...
                baseline_window((1 + lag_samples):end))/baseline_window_energy;
            correlation_penalty = correlation_penalty + ...
                2*(1 - lag_index/numel(sweep_start))*window_correlation^2;
        end
    end
    overlap_effective_average_count(sweep_index) = ...
        numel(sweep_start)/correlation_penalty;
end

assert(all(diff(overlap_sweep_count) > 0) && ...
    all(overlap_effective_average_count <= overlap_sweep_count + ...
    comparison_tolerance), ...
    'Overlap may add segments but cannot add more independent averages than K.');
assert(all(abs((fs_hz/baseline_segment_length) - ...
    welch_bin_spacing_hz) < comparison_tolerance), ...
    'Overlap must not change segment duration or frequency resolution.');
assert(overlap_effective_average_count(end) < overlap_sweep_count(end) - 1, ...
    'The 75 percent overlap case must expose correlated-average redundancy.');

%% Repeat different seeds: verify the variance claim is not one lucky record
seed_trial_count = numel(seed_sweep);
periodogram_probe_psd_v2_per_hz = zeros(1, seed_trial_count);
welch_probe_psd_v2_per_hz = zeros(1, seed_trial_count);
[~, periodogram_probe_index] = min(abs( ...
    periodogram_frequency_hz - probe_frequency_hz));
[~, welch_probe_index] = min(abs(welch_frequency_hz - probe_frequency_hz));

for trial_index = 1:seed_trial_count
    trial_stream = RandStream('mt19937ar', 'Seed', seed_sweep(trial_index));
    trial_raw_noise_v = randn(trial_stream, 1, record_sample_count);
    trial_noise_v = noise_rms_v*trial_raw_noise_v/ ...
        sqrt(mean(trial_raw_noise_v.^2));
    trial_record_v = strong_tone_v + weak_tone_v + trial_noise_v;

    trial_full_fft_v = fft(trial_record_v.*full_window, record_sample_count);
    trial_full_two_sided_psd_v2_per_hz = ...
        abs(trial_full_fft_v).^2/(fs_hz*full_window_energy);
    trial_full_one_sided_psd_v2_per_hz = ...
        trial_full_two_sided_psd_v2_per_hz(1:(record_sample_count/2 + 1));
    trial_full_one_sided_psd_v2_per_hz(2:end-1) = ...
        2*trial_full_one_sided_psd_v2_per_hz(2:end-1);
    periodogram_probe_psd_v2_per_hz(trial_index) = ...
        trial_full_one_sided_psd_v2_per_hz(periodogram_probe_index);

    trial_segment_probe_psd_v2_per_hz = zeros(1, baseline_segment_count);
    for segment_index = 1:baseline_segment_count
        first_sample = baseline_segment_start(segment_index);
        segment_v = trial_record_v( ...
            first_sample:(first_sample + baseline_segment_length - 1));
        segment_fft_v = fft(segment_v.*baseline_window, baseline_segment_length);
        segment_two_sided_psd_v2_per_hz = ...
            abs(segment_fft_v).^2/(fs_hz*baseline_window_energy);
        trial_segment_probe_psd_v2_per_hz(segment_index) = ...
            2*segment_two_sided_psd_v2_per_hz(welch_probe_index);
    end
    welch_probe_psd_v2_per_hz(trial_index) = ...
        mean(trial_segment_probe_psd_v2_per_hz);
end

periodogram_probe_cv = std(periodogram_probe_psd_v2_per_hz)/ ...
    mean(periodogram_probe_psd_v2_per_hz);
welch_probe_cv = std(welch_probe_psd_v2_per_hz)/ ...
    mean(welch_probe_psd_v2_per_hz);
assert(welch_probe_cv < 0.70*periodogram_probe_cv, ...
    'Across seeds, Welch must reduce probe-bin coefficient of variation.');

%% Broken case: average logarithmic display values instead of linear power
% dB is nonlinear. Averaging 10*log10(P) creates a geometric mean and biases
% the reported level low. Recover by averaging V^2/Hz first, then convert once.
broken_segment_psd_db = 10*log10(max( ...
    baseline_segment_psd_v2_per_hz, realmin));
broken_average_psd_db = mean(broken_segment_psd_db, 1);
recovered_average_psd_db = 10*log10(max(mean( ...
    baseline_segment_psd_v2_per_hz, 1), realmin));
db_averaging_bias_db = recovered_average_psd_db - broken_average_psd_db;
broken_noise_floor_db = median(broken_average_psd_db(welch_noise_mask));
recovered_noise_floor_db = median(recovered_average_psd_db(welch_noise_mask));
recovered_noise_floor_bias_db = ...
    recovered_noise_floor_db - broken_noise_floor_db;

assert(all(db_averaging_bias_db >= -comparison_tolerance), ...
    'Linear-power averaging must not fall below average-in-dB (Jensen inequality).');
assert(recovered_noise_floor_bias_db > 0.5, ...
    'The broken dB average must visibly bias the default noise floor low.');

