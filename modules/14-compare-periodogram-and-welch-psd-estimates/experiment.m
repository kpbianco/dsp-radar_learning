time_s = sample_index/fs_hz;
strong_tone_v = tone_amplitude_v(1)*cos(2*pi*tone_frequency_hz(1)*time_s + ...
    tone_phase_rad(1));
weak_tone_v = tone_amplitude_v(2)*cos(2*pi*tone_frequency_hz(2)*time_s + ...
    tone_phase_rad(2));
stream = RandStream('mt19937ar', 'Seed', random_seed);
raw_noise_v = randn(stream, 1, record_sample_count);
noise_v = noise_rms_v*raw_noise_v/sqrt(mean(raw_noise_v.^2));
record_v = strong_tone_v + weak_tone_v + noise_v;
record_duration_s = record_sample_count/fs_hz;

%% Baseline: one full-record periodogram versus manual Welch averaging
% For real data and an even FFT, form a two-sided density first:
% P2[k] = |FFT{x[n]w[n]}|^2 / (fs*sum(w[n]^2)).
% Keep DC through Nyquist and double only the interior bins. This gives
% V^2/Hz and preserves the window-normalized power under integration.
full_window = 0.5 - 0.5*cos(2*pi*(0:(record_sample_count - 1))/ ...
    (record_sample_count - 1));
full_window_energy = sum(full_window.^2);
full_fft_v = fft(record_v.*full_window, record_sample_count);
full_two_sided_psd_v2_per_hz = ...
    abs(full_fft_v).^2/(fs_hz*full_window_energy);
periodogram_psd_v2_per_hz = ...
    full_two_sided_psd_v2_per_hz(1:(record_sample_count/2 + 1));
periodogram_psd_v2_per_hz(2:end-1) = ...
    2*periodogram_psd_v2_per_hz(2:end-1);
periodogram_frequency_hz = ...
    (0:(record_sample_count/2))*fs_hz/record_sample_count;
periodogram_bin_spacing_hz = fs_hz/record_sample_count;
periodogram_power_v2 = ...
    sum(periodogram_psd_v2_per_hz)*periodogram_bin_spacing_hz;
periodogram_window_power_v2 = ...
    sum(abs(record_v.*full_window).^2)/full_window_energy;
periodogram_power_error_v2 = ...
    abs(periodogram_power_v2 - periodogram_window_power_v2);

baseline_window = 0.5 - 0.5*cos(2*pi*(0:(baseline_segment_length - 1))/ ...
    (baseline_segment_length - 1));
baseline_window_energy = sum(baseline_window.^2);
baseline_window_enbw_hz = ...
    fs_hz*baseline_window_energy/sum(baseline_window)^2;
baseline_segment_start = ...
    1:baseline_hop_samples:(record_sample_count - baseline_segment_length + 1);
assert(numel(baseline_segment_start) == baseline_segment_count, ...
    'Baseline segment-count formula must match explicit slicing.');

baseline_segment_psd_v2_per_hz = ...
    zeros(baseline_segment_count, baseline_segment_length/2 + 1);
baseline_segment_power_error_v2 = zeros(1, baseline_segment_count);
for segment_index = 1:baseline_segment_count
    first_sample = baseline_segment_start(segment_index);
    segment_v = record_v(first_sample:(first_sample + baseline_segment_length - 1));
    windowed_segment_v = segment_v.*baseline_window;
    segment_fft_v = fft(windowed_segment_v, baseline_segment_length);
    segment_two_sided_psd_v2_per_hz = ...
        abs(segment_fft_v).^2/(fs_hz*baseline_window_energy);
    segment_one_sided_psd_v2_per_hz = ...
        segment_two_sided_psd_v2_per_hz(1:(baseline_segment_length/2 + 1));
    segment_one_sided_psd_v2_per_hz(2:end-1) = ...
        2*segment_one_sided_psd_v2_per_hz(2:end-1);
    baseline_segment_psd_v2_per_hz(segment_index, :) = ...
        segment_one_sided_psd_v2_per_hz;
    integrated_segment_power_v2 = sum(segment_one_sided_psd_v2_per_hz)* ...
        fs_hz/baseline_segment_length;
    direct_segment_power_v2 = ...
        sum(abs(windowed_segment_v).^2)/baseline_window_energy;
    baseline_segment_power_error_v2(segment_index) = ...
        abs(integrated_segment_power_v2 - direct_segment_power_v2);
end

% Welch averages linear power density estimates, never their dB display.
welch_psd_v2_per_hz = mean(baseline_segment_psd_v2_per_hz, 1);
welch_frequency_hz = ...
    (0:(baseline_segment_length/2))*fs_hz/baseline_segment_length;
welch_bin_spacing_hz = fs_hz/baseline_segment_length;
welch_power_v2 = sum(welch_psd_v2_per_hz)*welch_bin_spacing_hz;

periodogram_noise_mask = periodogram_frequency_hz >= noise_band_hz(1) & ...
    periodogram_frequency_hz <= noise_band_hz(2);
welch_noise_mask = welch_frequency_hz >= noise_band_hz(1) & ...
    welch_frequency_hz <= noise_band_hz(2);
periodogram_noise_cv = std(periodogram_psd_v2_per_hz(periodogram_noise_mask))/ ...
    mean(periodogram_psd_v2_per_hz(periodogram_noise_mask));
welch_noise_cv = std(welch_psd_v2_per_hz(welch_noise_mask))/ ...
    mean(welch_psd_v2_per_hz(welch_noise_mask));
periodogram_noise_ripple_db = std(10*log10( ...
    max(periodogram_psd_v2_per_hz(periodogram_noise_mask), realmin)));
welch_noise_ripple_db = std(10*log10( ...
    max(welch_psd_v2_per_hz(welch_noise_mask), realmin)));

[~, periodogram_weak_index] = min(abs( ...
    periodogram_frequency_hz - tone_frequency_hz(2)));
[~, welch_weak_index] = min(abs(welch_frequency_hz - tone_frequency_hz(2)));
periodogram_weak_to_noise_db = 10*log10( ...
    periodogram_psd_v2_per_hz(periodogram_weak_index)/ ...
    median(periodogram_psd_v2_per_hz(periodogram_noise_mask)));
welch_weak_to_noise_db = 10*log10( ...
    welch_psd_v2_per_hz(welch_weak_index)/ ...
    median(welch_psd_v2_per_hz(welch_noise_mask)));

assert(periodogram_power_error_v2 < comparison_tolerance && ...
    max(baseline_segment_power_error_v2) < comparison_tolerance, ...
    'One-sided PSD integration must match explicit window-normalized power.');
assert(all(isfinite(welch_psd_v2_per_hz)) && ...
    all(welch_psd_v2_per_hz >= 0), ...
    'Welch PSD values must be finite and nonnegative.');
assert(welch_noise_cv < periodogram_noise_cv && ...
    welch_noise_ripple_db < periodogram_noise_ripple_db, ...
    'Default Welch averaging must stabilize the tone-free noise estimate.');

%% Sweep 1: change only segment length at fixed 50 percent overlap
segment_case_count = numel(segment_length_sweep);
segment_frequency_hz = cell(1, segment_case_count);
segment_welch_psd_v2_per_hz = cell(1, segment_case_count);
segment_bin_spacing_hz = zeros(1, segment_case_count);
segment_hann_main_lobe_width_hz = zeros(1, segment_case_count);
segment_noise_ripple_db = zeros(1, segment_case_count);
segment_weak_valley_prominence_db = zeros(1, segment_case_count);

for sweep_index = 1:segment_case_count
    sweep_segment_length = segment_length_sweep(sweep_index);
    sweep_hop_samples = sweep_segment_length/2;
    sweep_start = 1:sweep_hop_samples: ...
        (record_sample_count - sweep_segment_length + 1);
    sweep_window = 0.5 - 0.5*cos(2*pi*(0:(sweep_segment_length - 1))/ ...
        (sweep_segment_length - 1));
    sweep_window_energy = sum(sweep_window.^2);
    sweep_segment_psd_v2_per_hz = ...
        zeros(numel(sweep_start), sweep_segment_length/2 + 1);
    for segment_index = 1:numel(sweep_start)
        first_sample = sweep_start(segment_index);
        segment_v = record_v(first_sample:(first_sample + sweep_segment_length - 1));
        segment_fft_v = fft(segment_v.*sweep_window, sweep_segment_length);
        segment_two_sided_psd_v2_per_hz = ...
            abs(segment_fft_v).^2/(fs_hz*sweep_window_energy);
        segment_one_sided_psd_v2_per_hz = ...
            segment_two_sided_psd_v2_per_hz(1:(sweep_segment_length/2 + 1));
        segment_one_sided_psd_v2_per_hz(2:end-1) = ...
            2*segment_one_sided_psd_v2_per_hz(2:end-1);
        sweep_segment_psd_v2_per_hz(segment_index, :) = ...
            segment_one_sided_psd_v2_per_hz;
    end
    sweep_welch_psd_v2_per_hz = mean(sweep_segment_psd_v2_per_hz, 1);
    sweep_frequency_hz = ...
        (0:(sweep_segment_length/2))*fs_hz/sweep_segment_length;
    sweep_noise_mask = sweep_frequency_hz >= noise_band_hz(1) & ...
        sweep_frequency_hz <= noise_band_hz(2);
    [~, sweep_strong_index] = min(abs( ...
        sweep_frequency_hz - tone_frequency_hz(1)));
    [~, sweep_weak_index] = min(abs( ...
        sweep_frequency_hz - tone_frequency_hz(2)));
    between_tones = sweep_strong_index:sweep_weak_index;
    valley_psd_v2_per_hz = min(sweep_welch_psd_v2_per_hz(between_tones));

    segment_frequency_hz{sweep_index} = sweep_frequency_hz;
    segment_welch_psd_v2_per_hz{sweep_index} = sweep_welch_psd_v2_per_hz;
    segment_bin_spacing_hz(sweep_index) = fs_hz/sweep_segment_length;
    segment_hann_main_lobe_width_hz(sweep_index) = ...
        4*fs_hz/sweep_segment_length;
    segment_noise_ripple_db(sweep_index) = std(10*log10(max( ...
        sweep_welch_psd_v2_per_hz(sweep_noise_mask), realmin)));
    segment_weak_valley_prominence_db(sweep_index) = 10*log10( ...
        sweep_welch_psd_v2_per_hz(sweep_weak_index)/ ...
        max(valley_psd_v2_per_hz, realmin));
end

assert(all(diff(segment_sweep_count) > 0) && ...
