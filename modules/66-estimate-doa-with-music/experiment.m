%% Local transparent helpers
function [bartlett_db, music_db, eigenvalues, noise_subspace] = ...
        form_spatial_spectra(covariance_matrix, source_count, scan_steering, ...
        floor_db)
    sensor_count = size(covariance_matrix, 1);
    assert(size(covariance_matrix, 2) == sensor_count && ...
        size(scan_steering, 1) == sensor_count && source_count >= 1 && ...
        source_count < sensor_count, 'P66:SpectrumDimensions', ...
        'Covariance, steering grid, and source count are inconsistent.');
    covariance_matrix = (covariance_matrix+covariance_matrix')/2;
    [eigenvectors, eigenvalue_matrix] = eig(covariance_matrix);
    [eigenvalues, eigenvalue_order] = sort(real(diag(eigenvalue_matrix)), ...
        'descend');
    eigenvectors = eigenvectors(:, eigenvalue_order);
    noise_subspace = eigenvectors(:, source_count+1:end);

    bartlett_power = real(sum(conj(scan_steering).* ...
        (covariance_matrix*scan_steering), 1))/sensor_count^2;
    music_denominator = sum(abs(noise_subspace'*scan_steering).^2, 1);
    music_power = 1./max(music_denominator, realmin);
    bartlett_power = bartlett_power/max(bartlett_power);
    music_power = music_power/max(music_power);
    bartlett_db = 10*log10(max(bartlett_power, 10^(floor_db/10)));
    music_db = 10*log10(max(music_power, 10^(floor_db/10)));
end

function peak_angles_deg = select_music_peaks(spectrum_db, scan_angles_deg, ...
        requested_peaks, minimum_separation_deg)
    local_maximum = false(size(spectrum_db));
    local_maximum(2:end-1) = spectrum_db(2:end-1) > ...
        spectrum_db(1:end-2) & spectrum_db(2:end-1) >= ...
        spectrum_db(3:end);
    candidate_indices = find(local_maximum);
    [~, height_order] = sort(spectrum_db(candidate_indices), 'descend');
    candidate_indices = candidate_indices(height_order);
    candidate_indices = candidate_indices(:).';
    selected_indices = zeros(1, requested_peaks);
    selected_count = 0;
    for candidate_index = candidate_indices
        candidate_angle = scan_angles_deg(candidate_index);
        if selected_count == 0 || all(abs(candidate_angle- ...
                scan_angles_deg(selected_indices(1:selected_count))) >= ...
                minimum_separation_deg)
            selected_count = selected_count+1;
            selected_indices(selected_count) = candidate_index;
            if selected_count == requested_peaks
                break;
            end
        end
    end
    peak_angles_deg = nan(1, requested_peaks);
    if selected_count > 0
        peak_angles_deg(1:selected_count) = sort( ...
            scan_angles_deg(selected_indices(1:selected_count)));
    end
end

function rmse_deg = matched_angle_rmse(estimated_angles_deg, true_angles_deg)
    if numel(estimated_angles_deg) ~= numel(true_angles_deg) || ...
            any(~isfinite(estimated_angles_deg))
        rmse_deg = inf;
        return;
    end
    angle_error_deg = sort(estimated_angles_deg)-sort(true_angles_deg);
    rmse_deg = sqrt(mean(angle_error_deg.^2));
end

function [bartlett_contrast_db, music_contrast_db] = midpoint_contrasts( ...
        bartlett_db, music_db, scan_angles_deg, true_angles_deg)
    midpoint_deg = mean(true_angles_deg);
    [~, midpoint_index] = min(abs(scan_angles_deg-midpoint_deg));
    truth_indices = zeros(size(true_angles_deg));
    for source_index = 1:numel(true_angles_deg)
        [~, truth_indices(source_index)] = min(abs( ...
            scan_angles_deg-true_angles_deg(source_index)));
    end
    bartlett_contrast_db = min(bartlett_db(truth_indices))- ...
        bartlett_db(midpoint_index);
    music_contrast_db = min(music_db(truth_indices))-music_db(midpoint_index);
end

function uniforms = private_uniform(seed, count, maximum_private_values)
    assert(isfinite(seed) && seed == floor(seed) && seed >= 1 && ...
        seed < 2147483647, 'P66:Seed', 'Seed must be a valid integer.');
    assert(isfinite(count) && count == floor(count) && count >= 1 && ...
        count <= maximum_private_values, 'P66:PrivateBound', ...
        'Private generator request exceeds the reviewed ceiling.');
    state = double(seed);
    uniforms = zeros(1, count);
    for sample_index = 1:count
        state = mod(16807*state, 2147483647);
        uniforms(sample_index) = state/2147483647;
    end
end

function noise = private_complex_noise(seed, number_rows, number_columns, ...
        maximum_private_values)
    sample_count = number_rows*number_columns;
    uniforms = private_uniform(seed, 2*sample_count, maximum_private_values);
    first = max(uniforms(1:sample_count), realmin);
    second = uniforms(sample_count+1:2*sample_count);
    samples = sqrt(-2*log(first)).*exp(1j*2*pi*second)/sqrt(2);
    noise = reshape(samples, number_rows, number_columns);
end

function validate_controls(c)
    scalar_names = {'seed', 'elements', 'spacing', 'source_snr_db', ...
        'noise_power', 'snapshots', 'scene_snapshots', 'assumed_sources', ...
        'minimum_peak_separation', 'snapshot_sweep_snr_db', ...
        'coherent_phase', 'smoothing_elements', 'max_elements', ...
        'plot_floor_db', ...
        'max_sources', 'max_snapshots', 'max_scan_samples', ...
        'max_sweep_cases', 'max_private_values', 'max_working_values', ...
        'max_figures'};
    for name_index = 1:numel(scalar_names)
        value = c.(scalar_names{name_index});
        assert(isnumeric(value) && ~islogical(value) && isreal(value) && ...
            isscalar(value) && isfinite(value), 'P66:FiniteControls', ...
            '%s must be one finite real numeric scalar.', ...
            scalar_names{name_index});
    end
    integers = [c.seed c.elements c.snapshots c.scene_snapshots ...
        c.assumed_sources c.smoothing_elements c.max_elements c.max_sources ...
        c.max_snapshots c.max_scan_samples c.max_sweep_cases ...
        c.max_private_values c.max_working_values c.max_figures];
    assert(all(integers == floor(integers)) && all(integers > 0), ...
        'P66:IntegerControls', ...
        'Reviewed count controls must be positive integers.');
    assert(c.elements <= c.max_elements && c.scene_snapshots <= ...
        c.max_snapshots && c.snapshots <= c.scene_snapshots && ...
        c.assumed_sources == 2 && c.assumed_sources <= c.max_sources && ...
        c.assumed_sources < c.elements, 'P66:SceneBounds', ...
        'Reviewed scene sizes violate immutable ceilings.');
    assert(c.spacing > 0 && c.spacing <= 0.5 && c.noise_power > 0 && ...
        c.noise_power <= 1e6 && c.minimum_peak_separation > 0 && ...
        c.plot_floor_db >= -200 && c.plot_floor_db <= -10, ...
        'P66:PhysicalControls', ...
        'Spacing, noise power, peak separation, or plot floor is invalid.');
    assert(isnumeric(c.source_angles) && ~islogical(c.source_angles) && ...
        isreal(c.source_angles) && isrow(c.source_angles) && ...
        numel(c.source_angles) == c.assumed_sources && ...
        numel(c.source_angles) <= c.max_sources && ...
        all(isfinite(c.source_angles)) && all(abs(c.source_angles) < 90) && ...
        all(diff(c.source_angles) > 0), 'P66:SourceAngles', ...
        'Source angles must be finite, ordered, distinct, and visible.');
    assert(isnumeric(c.scan_angles) && ~islogical(c.scan_angles) && ...
        isreal(c.scan_angles) && isrow(c.scan_angles) && ...
        numel(c.scan_angles) >= 3 && ...
        numel(c.scan_angles) <= c.max_scan_samples && ...
        all(isfinite(c.scan_angles)) && all(abs(c.scan_angles) < 90) && ...
        all(diff(c.scan_angles) > 0) && ...
        c.scan_angles(1) <= c.source_angles(1) && ...
        c.scan_angles(end) >= c.source_angles(end), 'P66:ScanGrid', ...
        'Scan grid must be finite, ordered, bounded, and cover the sources.');
    validate_real_sweep(c.spacing_sweep, 3, c.max_sweep_cases, ...
        'P66:SpacingCases');
    validate_real_sweep(c.snr_sweep, 3, c.max_sweep_cases, 'P66:SNRCases');
    validate_real_sweep(c.snapshot_sweep, 3, c.max_sweep_cases, ...
        'P66:SnapshotCases');
    validate_real_sweep(c.count_sweep, 3, c.max_sweep_cases, ...
        'P66:CountCases');
    assert(all(c.spacing_sweep > 0) && ...
        c.spacing_sweep(end)/2 <= min(abs(c.scan_angles([1 end]))) && ...
        all(abs(c.snr_sweep) <= 40) && ...
        all(abs([c.source_snr_db c.snapshot_sweep_snr_db]) <= 60) && ...
        all(c.snapshot_sweep == floor(c.snapshot_sweep)) && ...
        c.snapshot_sweep(1) >= c.elements && ...
        c.snapshot_sweep(end) <= c.scene_snapshots && ...
        all(c.count_sweep == floor(c.count_sweep)) && ...
        c.count_sweep(1) >= 1 && c.count_sweep(end) <= c.max_sources && ...
        c.count_sweep(end) < c.elements && ...
        any(c.count_sweep == c.assumed_sources), 'P66:SweepBounds', ...
        'Sweep values exceed the reviewed physical or model bounds.');
    number_subarrays = c.elements-c.smoothing_elements+1;
    assert(c.smoothing_elements > c.assumed_sources && ...
        c.smoothing_elements < c.elements && ...
        number_subarrays >= c.assumed_sources, 'P66:SmoothingBounds', ...
        'Smoothing needs a reduced aperture and enough overlapping subarrays.');
    assert(c.max_elements == 16 && c.max_sources == 4 && ...
        c.max_snapshots == 512 && c.max_scan_samples == 1001 && ...
        c.max_sweep_cases == 8 && c.max_private_values == 20000 && ...
        c.max_working_values == 1000000 && c.max_figures == 6 && ...
        2*c.elements*c.scene_snapshots <= c.max_private_values, ...
        'P66:ResourceBounds', ...
        'Private sample, working-value, or figure ceiling is inconsistent.');
end

function validate_real_sweep(values, minimum_cases, maximum_cases, identifier)
    assert(isnumeric(values) && ~islogical(values) && isreal(values) && ...
        isrow(values) && numel(values) >= minimum_cases && ...
        numel(values) <= maximum_cases && all(isfinite(values)) && ...
        all(diff(values) > 0), identifier, ...
        'Sweep must contain ordered, distinct, finite real values.');
end
