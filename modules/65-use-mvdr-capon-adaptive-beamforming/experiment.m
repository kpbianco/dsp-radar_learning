%% Local transparent helpers
function steering = steering_vector(angle_deg, element_index, spacing)
    steering = exp(1j*2*pi*spacing*element_index*sind(angle_deg));
end

function [weight, loaded_covariance, loading_power, reciprocal_condition] = ...
        form_mvdr_weight(sample_covariance, look_steering, alpha, min_rcond)
    number_elements = size(sample_covariance, 1);
    loading_scale = real(trace(sample_covariance))/number_elements;
    assert(isfinite(loading_scale) && loading_scale > 0, ...
        'P65:LoadingScale', 'Average measured sensor power must be positive.');
    loading_power = alpha*loading_scale;
    loaded_covariance = sample_covariance+loading_power*eye(number_elements);
    loaded_covariance = (loaded_covariance+loaded_covariance')/2;
    reciprocal_condition = rcond(loaded_covariance);
    assert(isfinite(reciprocal_condition) && reciprocal_condition >= min_rcond, ...
        'P65:IllConditioned', ...
        'Refusing an ill-conditioned MVDR solve; increase loading.');
    numerator = loaded_covariance\look_steering;
    denominator = look_steering'*numerator;
    assert(isfinite(real(denominator)) && isfinite(imag(denominator)) && ...
        real(denominator) > 0, 'P65:Normalization', ...
        'MVDR normalization must be finite and positive.');
    weight = numerator/denominator;
end

function metrics = component_metrics(weight, desired_steering, ...
        interferer_steering, desired_power, interferer_power, noise_power)
    desired_response = abs(weight'*desired_steering);
    interferer_response = abs(weight'*interferer_steering);
    weight_energy = real(weight'*weight);
    output_desired = desired_power*desired_response^2;
    output_interference = interferer_power*interferer_response^2;
    output_noise = noise_power*weight_energy;
    output_sinr = output_desired/(output_interference+output_noise);
    metrics = struct( ...
        'desired_power', output_desired, ...
        'interference_power', output_interference, ...
        'noise_power', output_noise, ...
        'desired_response_db', 20*log10(max(desired_response, realmin)), ...
        'interferer_response_db', 20*log10(max(interferer_response, realmin)), ...
        'white_noise_gain_db', 10*log10(1/weight_energy), ...
        'output_sinr_db', 10*log10(output_sinr));
end

function uniforms = private_uniform(seed, count, maximum_private_values)
    assert(isfinite(seed) && seed == floor(seed) && seed >= 1 && ...
        seed < 2147483647, 'P65:Seed', 'Seed must be a valid integer.');
    assert(isfinite(count) && count == floor(count) && count >= 1 && ...
        count <= maximum_private_values, 'P65:PrivateBound', ...
        'Private generator request exceeds the reviewed ceiling.');
    state = double(seed);
    uniforms = zeros(1, count);
    for sample_index = 1:count
        state = mod(16807*state, 2147483647);
        uniforms(sample_index) = state/2147483647;
    end
end

function noise = private_complex_noise(seed, number_rows, number_columns, ...
        maximum_private_values)
    sample_count = number_rows*number_columns;
    uniforms = private_uniform(seed, 2*sample_count, maximum_private_values);
    first = max(uniforms(1:sample_count), realmin);
    second = uniforms(sample_count+1:2*sample_count);
    samples = sqrt(-2*log(first)).*exp(1j*2*pi*second)/sqrt(2);
    noise = reshape(samples, number_rows, number_columns);
end

function validate_controls(c)
    scalar_names = {'seed', 'elements', 'spacing', 'desired_angle', ...
        'interferer_angle', 'desired_snr_db', 'interferer_inr_db', ...
        'noise_power', 'snapshots', 'scene_snapshots', 'loading_alpha', ...
        'mismatch_deg', 'broken_snapshots', 'recovery_alpha', ...
        'max_elements', 'max_snapshots', 'max_scan_samples', ...
        'max_sweep_cases', 'max_private_values', 'max_working_values', ...
        'max_figures', 'min_rcond'};
    for name_index = 1:numel(scalar_names)
        value = c.(scalar_names{name_index});
        assert(isnumeric(value) && ~islogical(value) && isreal(value) && ...
            isscalar(value) && isfinite(value), 'P65:FiniteControls', ...
            '%s must be one finite real numeric scalar.', ...
            scalar_names{name_index});
    end
    integers = [c.seed c.elements c.snapshots c.scene_snapshots ...
        c.broken_snapshots c.max_elements c.max_snapshots c.max_scan_samples ...
        c.max_sweep_cases c.max_private_values c.max_working_values c.max_figures];
    assert(all(integers == floor(integers)) && all(integers > 0), ...
        'P65:IntegerControls', 'Reviewed count controls must be positive integers.');
    assert(c.elements <= c.max_elements && c.scene_snapshots <= c.max_snapshots && ...
        c.snapshots <= c.scene_snapshots && c.broken_snapshots < c.elements, ...
        'P65:SceneBounds', 'Reviewed scene sizes violate immutable ceilings.');
    assert(c.spacing > 0 && c.spacing <= 0.5 && c.noise_power > 0 && ...
        c.loading_alpha > 0 && c.recovery_alpha > 0 && c.min_rcond > 0, ...
        'P65:PhysicalControls', 'Physical and loading controls must be positive.');
    assert(c.desired_angle ~= c.interferer_angle && ...
        all(abs([c.desired_angle c.interferer_angle ...
        c.desired_angle+c.mismatch_deg]) < 90), ...
        'P65:Angles', 'Source angles must be distinct and inside the visible sector.');
    assert(isnumeric(c.scan_angles) && ~islogical(c.scan_angles) && ...
        isreal(c.scan_angles) && isrow(c.scan_angles) && ...
        numel(c.scan_angles) >= 3 && ...
        numel(c.scan_angles) <= c.max_scan_samples && ...
        all(isfinite(c.scan_angles)) && all(diff(c.scan_angles) > 0), ...
        'P65:ScanGrid', 'Scan grid must be finite, ordered, and bounded.');
    assert(isnumeric(c.snapshot_sweep) && ~islogical(c.snapshot_sweep) && ...
        isreal(c.snapshot_sweep) && isrow(c.snapshot_sweep) && ...
        numel(c.snapshot_sweep) >= 3 && ...
        numel(c.snapshot_sweep) <= c.max_sweep_cases && ...
        all(isfinite(c.snapshot_sweep)) && ...
        all(c.snapshot_sweep == floor(c.snapshot_sweep)) && ...
        all(diff(c.snapshot_sweep) > 0) && c.snapshot_sweep(1) >= 1 && ...
        c.snapshot_sweep(end) <= c.scene_snapshots, 'P65:SnapshotCases', ...
        'Snapshot sweep must contain ordered bounded integer prefixes.');
    assert(isnumeric(c.loading_sweep) && ~islogical(c.loading_sweep) && ...
        isreal(c.loading_sweep) && isrow(c.loading_sweep) && ...
        numel(c.loading_sweep) >= 3 && ...
        numel(c.loading_sweep) <= c.max_sweep_cases && ...
        all(isfinite(c.loading_sweep)) && all(c.loading_sweep > 0) && ...
        all(diff(c.loading_sweep) > 0), 'P65:LoadingCases', ...
        'Loading sweep must contain ordered distinct positive values.');
    assert(c.max_elements == 16 && c.max_snapshots == 512 && ...
        c.max_scan_samples == 1001 && c.max_sweep_cases == 8 && ...
        c.max_private_values == 30000 && c.max_working_values == 600000 && ...
        c.max_figures == 5 && 2*c.elements*c.scene_snapshots <= ...
        c.max_private_values, 'P65:ResourceBounds', ...
        'Private sample or figure ceiling is inconsistent.');
