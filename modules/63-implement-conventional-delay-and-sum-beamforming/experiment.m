%% Local helpers: deterministic scene, explicit DAS scan, and validation
function [sensor_data, source_steering, source_snapshots, noise] = ...
    simulate_scene(seed, number_elements, maximum_elements, ...
    spacing_wavelengths, source_angles_deg, snr_db, number_snapshots, ...
    maximum_private_values)
    number_sources = numel(source_angles_deg);
    source_uniforms = private_uniform(seed, ...
        number_sources*number_snapshots, maximum_private_values);
    source_snapshots = reshape(exp(1j*2*pi*source_uniforms), ...
        number_sources, number_snapshots);
    noise = private_complex_noise(seed+1, maximum_elements, ...
        number_snapshots, maximum_private_values);
    noise = noise(1:number_elements, :)*10^(-snr_db/20);
    element_index = (0:number_elements-1).';
    source_steering = exp(1j*2*pi*spacing_wavelengths* ...
        element_index*sind(source_angles_deg));
    sensor_data = source_steering*source_snapshots+noise;
end

function power = scan_power(sensor_data, spacing_wavelengths, ...
    scan_angles_deg, steering_sign)
    number_elements = size(sensor_data, 1);
    element_index = (0:number_elements-1).';
    steering = exp(1j*steering_sign*2*pi*spacing_wavelengths* ...
        element_index*sind(scan_angles_deg));
    weights = steering/number_elements;
    beam_outputs = weights'*sensor_data;
    power = mean(abs(beam_outputs).^2, 2).';
end

function [peak_angles_deg, peak_is_local] = peak_near_angles( ...
    scan_angles_deg, power, ...
    expected_angles_deg, search_radius_deg)
    peak_angles_deg = zeros(size(expected_angles_deg));
    peak_is_local = false(size(expected_angles_deg));
    for source_index = 1:numel(expected_angles_deg)
        candidate_indices = find(abs(scan_angles_deg- ...
            expected_angles_deg(source_index)) <= search_radius_deg);
        assert(~isempty(candidate_indices), 'P63:EmptyPeakWindow', ...
            'Every expected source needs a nonempty bounded search window.');
        [~, local_index] = max(power(candidate_indices));
        selected_index = candidate_indices(local_index);
        peak_angles_deg(source_index) = scan_angles_deg(selected_index);
        peak_is_local(source_index) = selected_index > 1 && ...
            selected_index < numel(power) && ...
            power(selected_index) >= power(selected_index-1) && ...
            power(selected_index) > power(selected_index+1);
    end
end

function relative_db = power_to_relative_db(power, floor_db)
    normalized = power/max(power);
    relative_db = 10*log10(max(normalized, 10^(floor_db/10)));
end

function noise = private_complex_noise(seed, number_rows, ...
    number_columns, maximum_private_values)
    sample_count = number_rows*number_columns;
    uniforms = private_uniform(seed, 2*sample_count, ...
        maximum_private_values);
    first = uniforms(1:2:end);
    second = uniforms(2:2:end);
    samples = sqrt(-2*log(first)).*exp(1j*2*pi*second)/sqrt(2);
    noise = reshape(samples, number_rows, number_columns);
end

function values = private_uniform(seed, count, maximum_count)
    modulus = 2147483647;
    multiplier = 16807;
    assert(isnumeric(seed) && ~islogical(seed) && isreal(seed) && ...
        isscalar(seed) && isfinite(seed) && seed == floor(seed) && ...
        seed >= 1 && seed < modulus, 'P63:BadPrivateSeed', ...
        'Private seed must be an integer in range.');
    assert(isnumeric(count) && ~islogical(count) && isreal(count) && ...
        isscalar(count) && isfinite(count) && count == floor(count) && ...
        count >= 1 && count <= maximum_count, 'P63:BadPrivateCount', ...
        'Private sample count exceeds its immutable ceiling.');
    values = zeros(1, count);
    state = seed;
    for sample_index = 1:count
        state = mod(multiplier*state, modulus);
        values(sample_index) = (state+0.5)/modulus;
    end
end

function validate_controls(c)
    scalar_names = {'baseline_seed', 'number_elements', ...
        'element_spacing_wavelengths', 'source_snr_db', ...
        'number_snapshots', 'plot_floor_db', 'broken_seed', ...
        'peak_search_radius_deg', 'minimum_peak_separation_deg', ...
        'maximum_elements', 'maximum_sources', 'maximum_snapshots', ...
        'maximum_scan_samples', 'maximum_sweep_cases', ...
        'maximum_private_values', 'maximum_working_numeric_values', ...
        'maximum_figures', 'comparison_tolerance'};
    for name_index = 1:numel(scalar_names)
        value = c.(scalar_names{name_index});
        assert(isnumeric(value) && ~islogical(value) && isreal(value) && ...
            isscalar(value) && isfinite(value), 'P63:BadScalarControl', ...
            '%s must be one finite real numeric scalar.', ...
            scalar_names{name_index});
    end
    integer_names = {'baseline_seed', 'number_elements', ...
        'number_snapshots', 'broken_seed', 'maximum_elements', ...
        'maximum_sources', 'maximum_snapshots', 'maximum_scan_samples', ...
        'maximum_sweep_cases', 'maximum_private_values', ...
        'maximum_working_numeric_values', 'maximum_figures'};
    for name_index = 1:numel(integer_names)
        value = c.(integer_names{name_index});
        assert(value == floor(value), 'P63:BadIntegerControl', ...
            '%s must be integer-valued.', integer_names{name_index});
    end
    assert(c.baseline_seed == 6301 && c.broken_seed == 6315 && ...
        c.baseline_seed >= 1 && c.broken_seed < 2147483646, ...
        'P63:BadSeed', 'Reviewed private seeds changed.');
    assert(c.number_elements == 8 && c.maximum_elements == 16 && ...
        c.number_elements >= 2 && ...
        c.number_elements <= c.maximum_elements, 'P63:BadElementCount', ...
        'The reviewed element count or ceiling changed.');
    assert(c.element_spacing_wavelengths == 0.5, ...
        'P63:BadSpacing', 'The reviewed ULA uses half-wavelength spacing.');
    validate_angle_vector(c.source_angles_deg, c.maximum_sources, ...
        'P63:BadSourceAngles');
    assert(isequal(c.source_angles_deg, [-20 25]) && ...
        numel(c.source_angles_deg) == c.maximum_sources && ...
        c.maximum_sources == 2, 'P63:BadSourceAngles', ...
        'The reviewed baseline source angles changed.');
    assert(c.source_snr_db == 10 && c.number_snapshots == 128 && ...
        c.maximum_snapshots == 256 && ...
        c.number_snapshots <= c.maximum_snapshots, ...
        'P63:BadDataControls', 'Reviewed SNR or snapshot controls changed.');
    assert(isnumeric(c.scan_angles_deg) && ~islogical(c.scan_angles_deg) && ...
        isreal(c.scan_angles_deg) && isrow(c.scan_angles_deg) && ...
        all(isfinite(c.scan_angles_deg)) && ...
        numel(c.scan_angles_deg) <= c.maximum_scan_samples && ...
        c.maximum_scan_samples == 2001 && c.scan_angles_deg(1) == -60 && ...
        c.scan_angles_deg(end) == 60 && ...
        all(diff(c.scan_angles_deg) > 0) && ...
        max(abs(diff(c.scan_angles_deg)-0.1)) < 1e-12, ...
        'P63:BadScanGrid', 'The reviewed scan grid is bounded and ordered.');
    validate_sweep(c.source_separation_sweep_deg, c.maximum_sweep_cases, ...
        'P63:BadSeparationSweep');
    assert(isequal(c.source_separation_sweep_deg, [6 12 24]), ...
        'P63:BadSeparationSweep', 'Reviewed separation sweep changed.');
    validate_sweep(c.array_size_sweep, c.maximum_sweep_cases, ...
        'P63:BadArraySweep');
    assert(isequal(c.array_size_sweep, [4 8 16]) && ...
        all(c.array_size_sweep == floor(c.array_size_sweep)) && ...
        max(c.array_size_sweep) <= c.maximum_elements, ...
        'P63:BadArraySweep', 'Reviewed array-size sweep changed.');
    validate_angle_vector(c.array_sweep_source_angles_deg, ...
        c.maximum_sources, 'P63:BadArraySourceAngles');
    assert(isequal(c.array_sweep_source_angles_deg, [-8 8]), ...
        'P63:BadArraySourceAngles', ...
        'Reviewed array-sweep source angles changed.');
    validate_sweep(c.snr_sweep_db, c.maximum_sweep_cases, ...
        'P63:BadSNRSweep');
    assert(isequal(c.snr_sweep_db, [-15 0 15]), ...
        'P63:BadSNRSweep', 'Reviewed SNR sweep changed.');
    validate_sweep(c.snapshot_sweep, c.maximum_sweep_cases, ...
        'P63:BadSnapshotSweep');
    assert(isequal(c.snapshot_sweep, [1 8 128]) && ...
        all(c.snapshot_sweep == floor(c.snapshot_sweep)) && ...
        max(c.snapshot_sweep) <= c.number_snapshots, ...
        'P63:BadSnapshotSweep', 'Reviewed snapshot sweep changed.');
    validate_angle_vector(c.broken_source_angles_deg, c.maximum_sources, ...
        'P63:BadBrokenAngles');
    assert(isequal(c.broken_source_angles_deg, [-20 30]), ...
        'P63:BadBrokenAngles', 'Reviewed broken fixture changed.');
    assert(c.plot_floor_db == -35 && c.peak_search_radius_deg == 5 && ...
        c.minimum_peak_separation_deg == 5 && ...
        c.comparison_tolerance == 1e-10, 'P63:BadMetricControls', ...
        'Reviewed plot or metric controls changed.');
    assert(c.maximum_private_values == 20000 && ...
        c.maximum_working_numeric_values == 500000 && ...
        c.maximum_figures == 5 && c.maximum_sweep_cases == 5, ...
        'P63:BadResourceCeiling', ...
        'Immutable resource ceilings changed.');
    largest_private_request = 2*c.maximum_elements*c.number_snapshots;
    largest_working_request = numel(c.scan_angles_deg)* ...
        c.number_snapshots+2*c.maximum_elements* ...
        c.number_snapshots+c.maximum_elements*numel(c.scan_angles_deg);
    assert(largest_private_request <= c.maximum_private_values && ...
        largest_working_request <= c.maximum_working_numeric_values, ...
        'P63:ResourceEstimate', ...
        'Reviewed arrays exceed an immutable resource ceiling.');
end

function validate_angle_vector(values, maximum_count, error_id)
    assert(isnumeric(values) && ~islogical(values) && isreal(values) && ...
        isrow(values) && ~isempty(values) && all(isfinite(values)) && ...
        all(abs(values) < 60) && numel(values) <= maximum_count && ...
        all(diff(values) > 0), error_id, ...
        'Angles must be finite, ordered, unique, and inside the scan sector.');
end

function validate_sweep(values, maximum_cases, error_id)
    assert(isnumeric(values) && ~islogical(values) && isreal(values) && ...
        isrow(values) && ~isempty(values) && all(isfinite(values)) && ...
        numel(values) <= maximum_cases && all(diff(values) > 0), error_id, ...
        'Sweep must be a finite, strictly increasing bounded row.');
end
