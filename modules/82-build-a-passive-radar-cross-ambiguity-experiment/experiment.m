%% P82: Build a Passive Radar Cross-Ambiguity Experiment
% How can a known broadcast-like reference reveal delayed Doppler-shifted echoes without transmitting?
% Base MATLAB R2016b+; no toolbox, file, network, worker, timer, or GPU use.

old_p82_figures = findall(0, 'Type', 'figure', 'Tag', 'P82');
if ~isempty(old_p82_figures)
    close(old_p82_figures);
end
clear old_p82_figures p82_results
p82_results = run_p82_experiment();

function p82_results = run_p82_experiment()
%% Visible deterministic controls and immutable resource ceilings
baseline_seed = 8201;
sample_rate_hz = 200000;
sample_count = 4096;
samples_per_symbol = 4;
speed_of_light_mps = 3.0e8;
delay_grid_samples = 0:64;
doppler_grid_hz = -1000:50:1000;
target_delay_samples = 24;
target_doppler_hz = 500;
direct_voltage = 2.50;
multipath_voltage = 0.10;
multipath_delay_samples = 11;
target_voltage = 0.18;
surveillance_noise_voltage = 0.08;
baseline_reference_quality_db = 35;
target_delay_sweep_samples = [12 24 48];
target_doppler_sweep_hz = [-500 0 500];
integration_sweep_samples = [1024 2048 4096];
reference_quality_sweep_db = [35 15 5];
under_cancellation_fraction = 0.20;
display_floor_db = -35;
maximum_samples = 8192;
maximum_delay_cells = 129;
maximum_doppler_cells = 81;
maximum_sweep_cases = 4;
maximum_map_evaluations = 16;
maximum_multiply_accumulates = 175000000;
maximum_peak_ambiguity_value_equivalents = 1000000;
maximum_working_value_equivalents = 8000000;
maximum_private_values = 20000;
expected_figure_count = 5;

controls = struct('seed', baseline_seed, 'fs_hz', sample_rate_hz, ...
    'sample_count', sample_count, 'samples_per_symbol', samples_per_symbol, ...
    'c_mps', speed_of_light_mps, 'delay_grid', delay_grid_samples, ...
    'doppler_grid_hz', doppler_grid_hz, 'target_delay', ...
    target_delay_samples, 'target_doppler_hz', target_doppler_hz, ...
    'direct_voltage', direct_voltage, 'multipath_voltage', ...
    multipath_voltage, 'multipath_delay', multipath_delay_samples, ...
    'target_voltage', target_voltage, 'surveillance_noise_voltage', ...
    surveillance_noise_voltage, 'baseline_reference_quality_db', ...
    baseline_reference_quality_db, 'delay_sweep', ...
    target_delay_sweep_samples, 'doppler_sweep_hz', ...
    target_doppler_sweep_hz, 'integration_sweep', ...
    integration_sweep_samples, 'quality_sweep_db', ...
    reference_quality_sweep_db, 'under_cancel_fraction', ...
    under_cancellation_fraction, 'display_floor_db', display_floor_db, ...
    'max_samples', maximum_samples, 'max_delay_cells', ...
    maximum_delay_cells, 'max_doppler_cells', maximum_doppler_cells, ...
    'max_sweep_cases', maximum_sweep_cases, 'max_map_evaluations', ...
    maximum_map_evaluations, 'max_multiply_accumulates', ...
    maximum_multiply_accumulates, 'max_peak_ambiguity_values', ...
    maximum_peak_ambiguity_value_equivalents, 'max_working_values', ...
    maximum_working_value_equivalents, 'max_private_values', ...
    maximum_private_values, 'expected_figures', expected_figure_count);
[predicted_map_count, predicted_multiply_accumulates, ...
    predicted_peak_ambiguity_value_equivalents] = ...
    validate_controls(controls);
executed_map_count = 0;
executed_multiply_accumulates = 0;

%% Make the illuminator and two measured channels
clean_reference = make_broadcast_reference(baseline_seed, sample_count, ...
    samples_per_symbol, maximum_private_values);
reference_noise = private_qpsk(baseline_seed+1, sample_count, ...
    maximum_private_values);
surveillance_noise = private_qpsk(baseline_seed+2, sample_count, ...
    maximum_private_values);
measured_reference = add_reference_noise(clean_reference, reference_noise, ...
    baseline_reference_quality_db);
surveillance = make_surveillance(clean_reference, surveillance_noise, ...
    sample_rate_hz, direct_voltage, multipath_voltage, ...
    multipath_delay_samples, target_voltage, target_delay_samples, ...
    target_doppler_hz, surveillance_noise_voltage);
retained_reference = measured_reference;
retained_surveillance = surveillance;

time_s = (0:sample_count-1)/sample_rate_hz;
bistatic_excess_path_km = delay_grid_samples/sample_rate_hz* ...
    speed_of_light_mps/1000;

fprintf('\nP82 baseline: %.0f ksample/s, %d samples, %.2f ms CPI\n', ...
    sample_rate_hz/1000, sample_count, 1000*sample_count/sample_rate_hz);
fprintf('Target truth: delay %d samples = %.1f km excess path, Doppler %+g Hz\n', ...
    target_delay_samples, speed_of_light_mps*target_delay_samples/ ...
    sample_rate_hz/1000, target_doppler_hz);

figure('Name', 'P82 passive channels and reference spectrum', ...
    'Tag', 'P82', 'Color', 'w');
subplot(2, 1, 1);
plot(1000*time_s(1:320), abs(measured_reference(1:320)), ...
    'LineWidth', 1.0);
hold on;
plot(1000*time_s(1:320), abs(surveillance(1:320))/direct_voltage, ...
    'LineWidth', 1.0);
grid on;
xlabel('Time (ms)');
ylabel('Normalized magnitude');
legend('Measured reference', 'Surveillance / direct gain', ...
    'Location', 'best');
title('One illuminator, two receiving channels');
subplot(2, 1, 2);
reference_spectrum = fftshift(fft(measured_reference));
frequency_axis_khz = (-sample_count/2:sample_count/2-1)* ...
    sample_rate_hz/sample_count/1000;
plot(frequency_axis_khz, normalized_db(reference_spectrum, display_floor_db), ...
    'LineWidth', 1.0);
grid on;
xlabel('Complex-baseband frequency (kHz)');
ylabel('Normalized magnitude (dB)');
title('Broadcast-like reference occupies wide bandwidth');

%% Baseline cross-ambiguity before and after direct-path cancellation
[ambiguity_before, work, matched_voltage_before] = cross_ambiguity( ...
    measured_reference, ...
    surveillance, sample_rate_hz, delay_grid_samples, doppler_grid_hz);
executed_map_count = executed_map_count+1;
executed_multiply_accumulates = executed_multiply_accumulates+work;
[cancelled_surveillance, direct_estimate] = cancel_direct_path( ...
    measured_reference, surveillance);
[ambiguity_after, work, matched_voltage_after] = cross_ambiguity( ...
    measured_reference, ...
    cancelled_surveillance, sample_rate_hz, delay_grid_samples, ...
    doppler_grid_hz);
executed_map_count = executed_map_count+1;
executed_multiply_accumulates = executed_multiply_accumulates+work;

baseline_before = map_metrics(ambiguity_before, delay_grid_samples, ...
    doppler_grid_hz, target_delay_samples, target_doppler_hz);
baseline_after = map_metrics(ambiguity_after, delay_grid_samples, ...
    doppler_grid_hz, target_delay_samples, target_doppler_hz);
zero_doppler_index = find(doppler_grid_hz == 0, 1);
origin_match_suppression_db = 20*log10( ...
    max(matched_voltage_before(zero_doppler_index, 1), eps)/ ...
    max(matched_voltage_after(zero_doppler_index, 1), eps));
assert(baseline_before.peak_delay == 0 && ...
    baseline_before.peak_doppler_hz == 0, 'P82:DirectPathMustDominate', ...
    'The uncancelled map must be dominated by zero-delay, zero-Doppler leakage.');
assert(baseline_after.peak_delay == target_delay_samples && ...
    baseline_after.peak_doppler_hz == target_doppler_hz && ...
    baseline_after.target_contrast_db > 25 && ...
    origin_match_suppression_db > 80, ...
    'P82:TargetRecovery', ...
    'Full direct-path projection must reveal the target at its true cell.');

fprintf('Estimated direct coefficient = %.4f %+.4fj\n', ...
    real(direct_estimate), imag(direct_estimate));
fprintf('Map peak before: (%d samples, %+g Hz); after: (%d samples, %+g Hz)\n', ...
    baseline_before.peak_delay, baseline_before.peak_doppler_hz, ...
    baseline_after.peak_delay, baseline_after.peak_doppler_hz);
fprintf('Origin matched-voltage suppression %.1f dB; target/median contrast %.1f dB\n', ...
    origin_match_suppression_db, baseline_after.target_contrast_db);

figure('Name', 'P82 ambiguity before and after direct cancellation', ...
    'Tag', 'P82', 'Color', 'w');
subplot(1, 2, 1);
common_baseline_peak = max(matched_voltage_before(:));
show_ambiguity(bistatic_excess_path_km, doppler_grid_hz, ...
    matched_voltage_before, common_baseline_peak, display_floor_db, ...
    'Before: direct path owns the map');
subplot(1, 2, 2);
show_ambiguity(bistatic_excess_path_km, doppler_grid_hz, ...
    matched_voltage_after, common_baseline_peak, display_floor_db, ...
    sprintf('After: target at %.1f km, %+g Hz', ...
    bistatic_excess_path_km(target_delay_samples+1), target_doppler_hz));

%% Sweep 1a and 1b: target delay and Doppler move independent coordinates
delay_estimates = zeros(size(target_delay_sweep_samples));
delay_doppler_estimates_hz = zeros(size(target_delay_sweep_samples));
for case_index = 1:numel(target_delay_sweep_samples)
    case_surveillance = make_surveillance(clean_reference, ...
        surveillance_noise, sample_rate_hz, direct_voltage, ...
        multipath_voltage, multipath_delay_samples, target_voltage, ...
        target_delay_sweep_samples(case_index), target_doppler_hz, ...
        surveillance_noise_voltage);
    case_cancelled = cancel_direct_path(measured_reference, case_surveillance);
    [case_map, work] = cross_ambiguity(measured_reference, case_cancelled, ...
        sample_rate_hz, delay_grid_samples, doppler_grid_hz);
    executed_map_count = executed_map_count+1;
    executed_multiply_accumulates = executed_multiply_accumulates+work;
    case_metrics = map_metrics(case_map, delay_grid_samples, ...
        doppler_grid_hz, target_delay_sweep_samples(case_index), ...
        target_doppler_hz);
    delay_estimates(case_index) = case_metrics.peak_delay;
    delay_doppler_estimates_hz(case_index) = case_metrics.peak_doppler_hz;
end
assert(isequal(delay_estimates, target_delay_sweep_samples) && ...
    all(delay_doppler_estimates_hz == target_doppler_hz), ...
    'P82:DelaySweep', ...
    'Changing target delay alone must move only the delay coordinate.');

doppler_delay_estimates = zeros(size(target_doppler_sweep_hz));
doppler_estimates_hz = zeros(size(target_doppler_sweep_hz));
for case_index = 1:numel(target_doppler_sweep_hz)
    case_surveillance = make_surveillance(clean_reference, ...
        surveillance_noise, sample_rate_hz, direct_voltage, ...
        multipath_voltage, multipath_delay_samples, target_voltage, ...
        target_delay_samples, target_doppler_sweep_hz(case_index), ...
        surveillance_noise_voltage);
    case_cancelled = cancel_direct_path(measured_reference, case_surveillance);
    [case_map, work] = cross_ambiguity(measured_reference, case_cancelled, ...
        sample_rate_hz, delay_grid_samples, doppler_grid_hz);
    executed_map_count = executed_map_count+1;
    executed_multiply_accumulates = executed_multiply_accumulates+work;
    case_metrics = map_metrics(case_map, delay_grid_samples, ...
        doppler_grid_hz, target_delay_samples, ...
        target_doppler_sweep_hz(case_index));
    doppler_delay_estimates(case_index) = case_metrics.peak_delay;
    doppler_estimates_hz(case_index) = case_metrics.peak_doppler_hz;
end
assert(all(doppler_delay_estimates == target_delay_samples) && ...
    isequal(doppler_estimates_hz, target_doppler_sweep_hz), ...
    'P82:DopplerSweep', ...
    'Changing target Doppler alone must move only the Doppler coordinate.');

figure('Name', 'P82 target delay and Doppler sweeps', ...
    'Tag', 'P82', 'Color', 'w');
subplot(1, 2, 1);
plot(target_delay_sweep_samples, target_delay_sweep_samples, 'k--', ...
    'LineWidth', 1.0);
hold on;
plot(target_delay_sweep_samples, delay_estimates, 'o-', 'LineWidth', 1.5);
grid on;
xlabel('True target delay (samples)');
ylabel('Estimated target delay (samples)');
legend('Truth', 'Cross-ambiguity peak', 'Location', 'best');
title('Delay moves across columns');
subplot(1, 2, 2);
plot(target_doppler_sweep_hz, target_doppler_sweep_hz, 'k--', ...
    'LineWidth', 1.0);
hold on;
plot(target_doppler_sweep_hz, doppler_estimates_hz, 's-', ...
    'LineWidth', 1.5);
grid on;
xlabel('True target Doppler (Hz)');
ylabel('Estimated target Doppler (Hz)');
legend('Truth', 'Cross-ambiguity peak', 'Location', 'best');
title('Doppler moves across rows');

%% Sweep 2a and 2b: coherent time helps; poor reference quality hurts
integration_time_ms = 1000*integration_sweep_samples/sample_rate_hz;
integration_contrast_db = zeros(size(integration_sweep_samples));
integration_doppler_resolution_hz = sample_rate_hz./ ...
    integration_sweep_samples;
for case_index = 1:numel(integration_sweep_samples)
    case_count = integration_sweep_samples(case_index);
    case_reference = measured_reference(1:case_count);
    case_surveillance = surveillance(1:case_count);
    case_cancelled = cancel_direct_path(case_reference, case_surveillance);
    [case_map, work] = cross_ambiguity(case_reference, case_cancelled, ...
        sample_rate_hz, delay_grid_samples, doppler_grid_hz);
    executed_map_count = executed_map_count+1;
    executed_multiply_accumulates = executed_multiply_accumulates+work;
    case_metrics = map_metrics(case_map, delay_grid_samples, ...
        doppler_grid_hz, target_delay_samples, target_doppler_hz);
    integration_contrast_db(case_index) = case_metrics.target_contrast_db;
end
assert(all(diff(integration_contrast_db) > 2), 'P82:IntegrationSweep', ...
    'Longer coherent time must improve target-to-background contrast.');

quality_target_coherence = zeros(size(reference_quality_sweep_db));
quality_contrast_db = zeros(size(reference_quality_sweep_db));
quality_peak_correct = false(size(reference_quality_sweep_db));
for case_index = 1:numel(reference_quality_sweep_db)
    case_reference = add_reference_noise(clean_reference, reference_noise, ...
        reference_quality_sweep_db(case_index));
    case_cancelled = cancel_direct_path(case_reference, surveillance);
    [case_map, work] = cross_ambiguity(case_reference, case_cancelled, ...
        sample_rate_hz, delay_grid_samples, doppler_grid_hz);
    executed_map_count = executed_map_count+1;
    executed_multiply_accumulates = executed_multiply_accumulates+work;
    case_metrics = map_metrics(case_map, delay_grid_samples, ...
        doppler_grid_hz, target_delay_samples, target_doppler_hz);
    quality_target_coherence(case_index) = case_metrics.target_value;
    quality_contrast_db(case_index) = case_metrics.target_contrast_db;
    quality_peak_correct(case_index) = ...
        case_metrics.peak_delay == target_delay_samples && ...
        case_metrics.peak_doppler_hz == target_doppler_hz;
end
assert(all(diff(quality_target_coherence) < 0) && ...
    quality_contrast_db(1) > quality_contrast_db(end)+8 && ...
    quality_peak_correct(1) && ~quality_peak_correct(end), ...
    'P82:ReferenceQualitySweep', ...
    'A degraded reference must weaken matching and eventually spoil the peak.');

figure('Name', 'P82 integration and reference-quality sweeps', ...
    'Tag', 'P82', 'Color', 'w');
subplot(1, 2, 1);
yyaxis left;
plot(integration_time_ms, integration_contrast_db, 'o-', ...
    'LineWidth', 1.5);
ylabel('Target / median map contrast (dB)');
yyaxis right;
plot(integration_time_ms, integration_doppler_resolution_hz, 's--', ...
    'LineWidth', 1.2);
ylabel('Nominal Doppler resolution 1/T (Hz)');
grid on;
xlabel('Coherent integration time (ms)');
title('Longer CPI integrates the coherent echo');
subplot(1, 2, 2);
plot(reference_quality_sweep_db, quality_target_coherence, 'd-', ...
    'LineWidth', 1.5);
set(gca, 'XDir', 'reverse');
grid on;
xlabel('Reference-channel quality (dB)');
ylabel('Normalized target coherence');
title('Reference mismatch spends processing gain');

%% Intentionally broken case: cancel only 20 percent of the direct estimate
measurement_before_failure = retained_surveillance;
under_cancelled_surveillance = surveillance-under_cancellation_fraction* ...
    direct_estimate*measured_reference;
[broken_ambiguity, work, broken_matched_voltage] = cross_ambiguity( ...
    measured_reference, ...
    under_cancelled_surveillance, sample_rate_hz, delay_grid_samples, ...
    doppler_grid_hz);
executed_map_count = executed_map_count+1;
executed_multiply_accumulates = executed_multiply_accumulates+work;
broken_metrics = map_metrics(broken_ambiguity, delay_grid_samples, ...
    doppler_grid_hz, target_delay_samples, target_doppler_hz);

% Recovery starts from the unchanged measured channels, not the broken map.
[recovered_surveillance, recovered_direct_estimate] = cancel_direct_path( ...
    retained_reference, retained_surveillance);
[recovered_ambiguity, ~, recovered_matched_voltage] = cross_ambiguity( ...
    retained_reference, ...
    recovered_surveillance, sample_rate_hz, delay_grid_samples, ...
    doppler_grid_hz);
executed_map_count = executed_map_count+1;
executed_multiply_accumulates = executed_multiply_accumulates+ ...
    sample_count*numel(delay_grid_samples)*numel(doppler_grid_hz);
recovery_exact_match = isequaln(recovered_surveillance, ...
    cancelled_surveillance) && isequaln(recovered_ambiguity, ...
    ambiguity_after) && isequaln(recovered_matched_voltage, ...
    matched_voltage_after) && recovered_direct_estimate == direct_estimate;
assert(broken_metrics.peak_delay == 0 && ...
    broken_metrics.peak_doppler_hz == 0 && recovery_exact_match && ...
    isequaln(measurement_before_failure, retained_surveillance), ...
    'P82:BrokenRecovery', ...
    'Under-cancellation must fail; fresh full projection must recover exactly.');

figure('Name', 'P82 under-cancellation and recovery', ...
    'Tag', 'P82', 'Color', 'w');
common_failure_peak = max(broken_matched_voltage(:));
subplot(1, 2, 1);
show_ambiguity(bistatic_excess_path_km, doppler_grid_hz, ...
    broken_matched_voltage, common_failure_peak, display_floor_db, ...
    'Broken: 20% cancellation leaves the origin');
subplot(1, 2, 2);
show_ambiguity(bistatic_excess_path_km, doppler_grid_hz, ...
    recovered_matched_voltage, common_failure_peak, display_floor_db, ...
    'Recovered: full projection, unchanged channels');

%% Bounded completion and public retained results
assert(executed_map_count == predicted_map_count && ...
    executed_map_count <= maximum_map_evaluations, 'P82:MapAccounting', ...
    'Cross-ambiguity map accounting or ceiling mismatch.');
assert(executed_multiply_accumulates == predicted_multiply_accumulates && ...
    executed_multiply_accumulates <= maximum_multiply_accumulates, ...
    'P82:WorkAccounting', ...
    'Multiply-accumulate accounting or ceiling mismatch.');
assert(numel(findall(0, 'Type', 'figure', 'Tag', 'P82')) == ...
    expected_figure_count, 'P82:FigureCount', ...
    'The experiment must create exactly five P82 figure groups.');
assert(isequaln(retained_reference, measured_reference) && ...
    isequaln(retained_surveillance, measurement_before_failure), ...
    'P82:MeasurementMutation', ...
    'Failure and recovery must not mutate retained measurements.');
workspace_inventory = whos;
working_value_equivalents = sum([workspace_inventory.bytes])/8;
assert(working_value_equivalents <= maximum_working_value_equivalents, ...
    'P82:WorkingStorage', 'Retained workspace inventory ceiling exceeded.');

p82_results = struct('seed', baseline_seed, 'sample_rate_hz', ...
    sample_rate_hz, 'sample_count', sample_count, ...
    'bistatic_excess_path_km', bistatic_excess_path_km, ...
    'doppler_grid_hz', doppler_grid_hz, 'target_delay_samples', ...
    target_delay_samples, 'target_doppler_hz', target_doppler_hz, ...
    'measured_reference', measured_reference, 'surveillance', surveillance, ...
    'cancelled_surveillance', cancelled_surveillance, ...
    'direct_estimate', direct_estimate, 'ambiguity_before', ...
    ambiguity_before, 'ambiguity_after', ambiguity_after, ...
    'matched_voltage_before', matched_voltage_before, ...
    'matched_voltage_after', matched_voltage_after, ...
    'baseline_before', baseline_before, 'baseline_after', baseline_after, ...
    'origin_match_suppression_db', origin_match_suppression_db, ...
    'delay_estimates', delay_estimates, 'doppler_estimates_hz', ...
    doppler_estimates_hz, 'integration_time_ms', integration_time_ms, ...
    'integration_contrast_db', integration_contrast_db, ...
    'quality_target_coherence', quality_target_coherence, ...
    'quality_contrast_db', quality_contrast_db, ...
    'quality_peak_correct', quality_peak_correct, ...
    'broken_metrics', broken_metrics, 'recovery_exact_match', ...
    recovery_exact_match, 'executed_map_count', executed_map_count, ...
    'executed_multiply_accumulates', executed_multiply_accumulates, ...
    'predicted_peak_ambiguity_value_equivalents', ...
    predicted_peak_ambiguity_value_equivalents, ...
    'working_value_equivalents', working_value_equivalents);
end

function [map_count, multiply_accumulates, ...
    peak_ambiguity_value_equivalents] = validate_controls(c)
scalar_names = {'seed', 'fs_hz', 'sample_count', 'samples_per_symbol', ...
    'c_mps', 'target_delay', 'target_doppler_hz', 'direct_voltage', ...
    'multipath_voltage', 'multipath_delay', 'target_voltage', ...
    'surveillance_noise_voltage', 'baseline_reference_quality_db', ...
    'under_cancel_fraction', 'display_floor_db', 'max_samples', ...
    'max_delay_cells', 'max_doppler_cells', 'max_sweep_cases', ...
    'max_map_evaluations', 'max_multiply_accumulates', ...
    'max_peak_ambiguity_values', 'max_working_values', ...
    'max_private_values', 'expected_figures'};
for index = 1:numel(scalar_names)
    value = c.(scalar_names{index});
    assert(isnumeric(value) && isreal(value) && isscalar(value) && ...
        isfinite(value), 'P82:FiniteScalar', ...
        '%s must be one finite real numeric scalar.', scalar_names{index});
end
vector_names = {'delay_grid', 'doppler_grid_hz', 'delay_sweep', ...
    'doppler_sweep_hz', 'integration_sweep', 'quality_sweep_db'};
for index = 1:numel(vector_names)
    value = c.(vector_names{index});
    assert(isnumeric(value) && isreal(value) && isrow(value) && ...
        ~isempty(value) && all(isfinite(value)), 'P82:FiniteRow', ...
        '%s must be a nonempty finite numeric row.', vector_names{index});
end
integer_names = {'seed', 'sample_count', 'samples_per_symbol', ...
    'target_delay', 'multipath_delay', 'max_samples', 'max_delay_cells', ...
    'max_doppler_cells', 'max_sweep_cases', 'max_map_evaluations', ...
    'max_multiply_accumulates', 'max_peak_ambiguity_values', ...
    'max_working_values', ...
    'max_private_values', 'expected_figures'};
for index = 1:numel(integer_names)
    value = c.(integer_names{index});
    assert(value == floor(value), 'P82:IntegerControl', ...
        '%s must be integer valued.', integer_names{index});
end
assert(c.seed > 0 && c.seed < 2147483647, 'P82:SeedRange', ...
    'Seed must be inside the Park-Miller state range.');
assert(c.fs_hz > 0 && c.c_mps > 0 && c.sample_count >= 256 && ...
    c.samples_per_symbol >= 2 && mod(c.sample_count, ...
    c.samples_per_symbol) == 0, 'P82:SamplingControls', ...
    'Sampling controls must be positive and symbol aligned.');
assert(c.direct_voltage > c.target_voltage && c.target_voltage > 0 && ...
    c.multipath_voltage > 0 && c.surveillance_noise_voltage > 0, ...
    'P82:PositiveAmplitudes', ...
    'Direct, multipath, target, and noise voltages must be physical.');
assert(c.target_delay > 0 && c.multipath_delay > 0 && ...
    c.target_delay ~= c.multipath_delay, 'P82:DistinctPaths', ...
    'Target and static multipath require distinct positive delays.');
assert(c.delay_grid(1) == 0 && all(diff(c.delay_grid) == 1) && ...
    all(c.delay_grid == floor(c.delay_grid)), 'P82:DelayGrid', ...
    'Delay grid must be contiguous nonnegative integer samples.');
assert(all(diff(c.doppler_grid_hz) > 0) && ...
    any(c.doppler_grid_hz == 0), 'P82:DopplerGrid', ...
    'Doppler grid must increase and include zero.');
assert(all(ismember([c.target_delay c.multipath_delay c.delay_sweep], ...
    c.delay_grid)), 'P82:DelaySupport', ...
    'Every modeled and swept delay must lie on the delay grid.');
assert(all(ismember([c.target_doppler_hz c.doppler_sweep_hz], ...
    c.doppler_grid_hz)), 'P82:DopplerSupport', ...
    'Every modeled and swept Doppler must lie on the Doppler grid.');
assert(all(diff(c.delay_sweep) > 0) && ...
    all(diff(c.doppler_sweep_hz) > 0) && ...
    all(diff(c.integration_sweep) > 0) && ...
    all(diff(c.quality_sweep_db) < 0), 'P82:OrderedSweeps', ...
    'Delay, Doppler, time, and descending quality sweeps must be ordered.');
assert(all(c.integration_sweep == floor(c.integration_sweep)) && ...
    c.integration_sweep(1) > max(c.delay_grid) && ...
    c.integration_sweep(end) == c.sample_count, ...
    'P82:IntegrationSupport', ...
    'Integration lengths must be integer, usable, and end at the baseline.');
assert(c.baseline_reference_quality_db > 0 && ...
    all(c.quality_sweep_db > 0) && c.under_cancel_fraction > 0 && ...
    c.under_cancel_fraction < 1 && c.display_floor_db < 0, ...
    'P82:DisplayAndQuality', ...
    'Quality, cancellation fraction, and display floor are invalid.');
assert(c.sample_count <= c.max_samples && ...
    numel(c.delay_grid) <= c.max_delay_cells && ...
    numel(c.doppler_grid_hz) <= c.max_doppler_cells && ...
    max([numel(c.delay_sweep), numel(c.doppler_sweep_hz), ...
    numel(c.integration_sweep), numel(c.quality_sweep_db)]) <= ...
    c.max_sweep_cases && 2*c.sample_count <= c.max_private_values, ...
    'P82:ResourceShape', 'A sample, cell, sweep, or generator ceiling failed.');
assert(all([c.max_samples c.max_delay_cells c.max_doppler_cells ...
    c.max_sweep_cases c.max_map_evaluations c.max_multiply_accumulates ...
    c.max_peak_ambiguity_values c.max_working_values ...
    c.max_private_values c.expected_figures] >= 1), ...
    'P82:PositiveCeilings', 'Every resource ceiling must be positive.');
assert(max(c.delay_grid) < min(c.integration_sweep), ...
    'P82:ValidOverlap', ...
    'Every integration case must retain overlap at the largest delay.');
assert(max(abs(c.doppler_grid_hz)) < c.fs_hz/2, ...
    'P82:DopplerNyquist', 'Doppler grid must remain inside Nyquist.');

map_count = 2+numel(c.delay_sweep)+numel(c.doppler_sweep_hz)+ ...
    numel(c.integration_sweep)+numel(c.quality_sweep_db)+2;
map_sample_total = (2+numel(c.delay_sweep)+ ...
    numel(c.doppler_sweep_hz)+numel(c.quality_sweep_db)+2)* ...
    c.sample_count+sum(c.integration_sweep);
multiply_accumulates = map_sample_total*numel(c.delay_grid)* ...
    numel(c.doppler_grid_hz);
sample_count = c.sample_count;
delay_count = numel(c.delay_grid);
doppler_count = numel(c.doppler_grid_hz);
% Eight-byte value equivalents conservatively count complex arrays twice.
% This covers the largest simultaneous cross_ambiguity helpers, outputs, and
% an elementwise lag-product temporary; retained caller storage is separate.
peak_ambiguity_value_equivalents = 5*sample_count+ ...
    2*delay_count*sample_count+2*doppler_count*sample_count+ ...
    4*doppler_count*delay_count+2*delay_count;
assert(map_count <= c.max_map_evaluations && ...
    multiply_accumulates <= c.max_multiply_accumulates && ...
    peak_ambiguity_value_equivalents <= c.max_peak_ambiguity_values, ...
    'P82:ResourceWork', ...
    'Planned ambiguity work or helper storage exceeds its ceiling.');
end

function reference = make_broadcast_reference(seed, sample_count, ...
    samples_per_symbol, maximum_private_values)
symbol_count = sample_count/samples_per_symbol;
symbols = private_qpsk(seed, symbol_count, maximum_private_values);
impulses = zeros(1, sample_count);
impulses(1:samples_per_symbol:end) = symbols;
pulse_index = -12:12;
sinc_argument = pulse_index/samples_per_symbol;
pulse = ones(size(sinc_argument));
nonzero = sinc_argument ~= 0;
pulse(nonzero) = sin(pi*sinc_argument(nonzero))./ ...
    (pi*sinc_argument(nonzero));
pulse = pulse.*(0.5+0.5*cos(pi*pulse_index/max(abs(pulse_index))));
pulse = pulse/sqrt(sum(abs(pulse).^2));
reference = conv(impulses, pulse, 'same');
reference = reference/sqrt(mean(abs(reference).^2));
end

function measured = add_reference_noise(clean_reference, noise, quality_db)
measured = clean_reference+10^(-quality_db/20)*noise;
measured = measured/sqrt(mean(abs(measured).^2));
end

function surveillance = make_surveillance(reference, noise, sample_rate_hz, ...
    direct_voltage, multipath_voltage, multipath_delay, target_voltage, ...
    target_delay, target_doppler_hz, noise_voltage)
sample_count = numel(reference);
time_s = (0:sample_count-1)/sample_rate_hz;
direct_path = direct_voltage*reference;
static_multipath = multipath_voltage*delayed_copy(reference, multipath_delay);
target_echo = target_voltage*delayed_copy(reference, target_delay).* ...
    exp(1j*2*pi*target_doppler_hz*time_s);
surveillance = direct_path+static_multipath+target_echo+noise_voltage*noise;
end

function delayed = delayed_copy(signal, delay_samples)
assert(isnumeric(delay_samples) && isreal(delay_samples) && ...
    isscalar(delay_samples) && isfinite(delay_samples) && ...
    delay_samples == floor(delay_samples) && delay_samples >= 0 && ...
    delay_samples < numel(signal), 'P82:DelayInput', ...
    'Delay must be one in-record nonnegative integer.');
if delay_samples == 0
    delayed = signal;
else
    delayed = [zeros(1, delay_samples) signal(1:end-delay_samples)];
end
end

function [cancelled, coefficient] = cancel_direct_path(reference, surveillance)
assert(isrow(reference) && isrow(surveillance) && ...
    numel(reference) == numel(surveillance) && ...
    all(isfinite(reference)) && all(isfinite(surveillance)), ...
    'P82:ChannelInput', 'Channels must be equal finite rows.');
reference_energy = sum(abs(reference).^2);
assert(reference_energy > eps, 'P82:ReferenceEnergy', ...
    'Reference energy must be nonzero.');
% argmin_a ||surveillance-a*reference||_2^2 = (r^H y)/(r^H r)
coefficient = sum(conj(reference).*surveillance)/reference_energy;
cancelled = surveillance-coefficient*reference;
end

function [ambiguity, work, matched_voltage] = cross_ambiguity( ...
    reference, surveillance, ...
    sample_rate_hz, delay_grid_samples, doppler_grid_hz)
assert(isrow(reference) && isrow(surveillance) && ...
    numel(reference) == numel(surveillance) && ...
    numel(reference) > max(delay_grid_samples), 'P82:AmbiguityInput', ...
    'Ambiguity channels must be equal rows longer than every delay.');
sample_count = numel(reference);
time_s = (0:sample_count-1)/sample_rate_hz;
lag_products = zeros(numel(delay_grid_samples), sample_count);
reference_energy = zeros(1, numel(delay_grid_samples));
for delay_index = 1:numel(delay_grid_samples)
    lagged_reference = delayed_copy(reference, ...
        delay_grid_samples(delay_index));
    lag_products(delay_index, :) = surveillance.*conj(lagged_reference);
    reference_energy(delay_index) = sum(abs(lagged_reference).^2);
end
doppler_kernel = exp(-1j*2*pi*(doppler_grid_hz(:)*time_s));
coherent_sum = doppler_kernel*lag_products.';
normalization = sqrt(sum(abs(surveillance).^2)*reference_energy);
ambiguity = abs(coherent_sum)./normalization;
matched_voltage = abs(coherent_sum)./reference_energy;
work = sample_count*numel(delay_grid_samples)*numel(doppler_grid_hz);
end

function metrics = map_metrics(ambiguity, delay_grid, doppler_grid_hz, ...
    target_delay, target_doppler_hz)
[peak_value, linear_index] = max(ambiguity(:));
[doppler_index, delay_index] = ind2sub(size(ambiguity), linear_index);
target_delay_index = find(delay_grid == target_delay, 1);
target_doppler_index = find(doppler_grid_hz == target_doppler_hz, 1);
zero_delay_index = find(delay_grid == 0, 1);
zero_doppler_index = find(doppler_grid_hz == 0, 1);
target_value = ambiguity(target_doppler_index, target_delay_index);
background = ambiguity;
background(max(1, target_doppler_index-1): ...
    min(size(background, 1), target_doppler_index+1), ...
    max(1, target_delay_index-2): ...
    min(size(background, 2), target_delay_index+2)) = NaN;
finite_background = background(isfinite(background));
background_median = median(finite_background);
metrics = struct('peak_value', peak_value, 'peak_delay', ...
    delay_grid(delay_index), 'peak_doppler_hz', ...
    doppler_grid_hz(doppler_index), 'target_value', target_value, ...
    'target_contrast_db', 20*log10(max(target_value, eps)/ ...
    max(background_median, eps)), 'origin_value', ...
    ambiguity(zero_doppler_index, zero_delay_index));
end

function show_ambiguity(path_axis_km, doppler_axis_hz, ambiguity, ...
    common_peak, display_floor_db, heading)
imagesc(path_axis_km, doppler_axis_hz, ...
    20*log10(max(abs(ambiguity)/max(common_peak, eps), ...
    10^(display_floor_db/20))));
axis xy;
scale_bar = colorbar;
scale_bar.Label.String = 'Matched voltage / common peak (dB)';
caxis([display_floor_db 0]);
xlabel('Bistatic excess path (km)');
ylabel('Doppler (Hz)');
title(heading);
end

function values_db = normalized_db(values, floor_db)
magnitude = abs(values);
peak = max(magnitude(:));
values_db = 20*log10(max(magnitude/max(peak, eps), 10^(floor_db/20)));
end

function values = private_qpsk(seed, count, maximum_values)
uniform_values = private_uniform(seed, 2*count, maximum_values);
in_phase = 2*(uniform_values(1:2:end) >= 0.5)-1;
quadrature = 2*(uniform_values(2:2:end) >= 0.5)-1;
values = (in_phase+1j*quadrature)/sqrt(2);
values = values-mean(values);
values = values/sqrt(mean(abs(values).^2));
end

function values = private_uniform(seed, count, maximum_values)
assert(isnumeric(seed) && isreal(seed) && isscalar(seed) && ...
    isfinite(seed) && seed == floor(seed) && seed > 0 && ...
    seed < 2147483647, 'P82:PrivateSeed', ...
    'Private seed must be one valid Park-Miller state.');
assert(isnumeric(count) && isreal(count) && isscalar(count) && ...
    isfinite(count) && count == floor(count) && count >= 1 && ...
    count <= maximum_values, 'P82:PrivateCount', ...
    'Private generator count exceeds its finite ceiling.');
values = zeros(1, count);
state = seed;
for index = 1:count
    state = mod(16807*state, 2147483647);
    values(index) = state/2147483647;
end
end
