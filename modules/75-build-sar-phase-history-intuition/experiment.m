%% Local transparent helpers
function validate_controls(controls)
vector_names = {'cross_range_sweep_m', 'aperture_sweep_m', ...
    'focus_cross_range_m'};
for vector_index = 1:numel(vector_names)
    name = vector_names{vector_index};
    value = controls.(name);
    if ~isnumeric(value) || ~isreal(value) || isempty(value) || ...
            size(value, 1) ~= 1 || any(~isfinite(value))
        error('P75:ControlShape', ...
            '%s must be a finite real nonempty row vector.', name);
    end
end
scalar_names = {'seed', 'c_mps', 'carrier_hz', 'closest_range_m', ...
    'target_cross_range_m', 'aperture_length_m', 'platform_spacing_m', ...
    'range_min_m', 'range_max_m', 'range_spacing_m', ...
    'envelope_sigma_m', 'target_voltage', 'snr_db', ...
    'max_aperture_samples', 'max_fast_time_samples', ...
    'max_focus_candidates', 'max_sweep_cases', 'max_private_values', ...
    'max_working_values', 'max_figures', 'max_phase_step_rad'};
for scalar_index = 1:numel(scalar_names)
    name = scalar_names{scalar_index};
    value = controls.(name);
    if ~isnumeric(value) || ~isreal(value) || numel(value) ~= 1 || ...
            ~isfinite(value)
        error('P75:ControlScalar', '%s must be a finite real scalar.', name);
    end
end
if controls.seed ~= floor(controls.seed) || controls.seed < 1 || ...
        controls.seed >= 2147483647
    error('P75:Seed', 'Seed must be an integer in [1, 2147483646].');
end
positive_names = {'c_mps', 'carrier_hz', 'closest_range_m', ...
    'aperture_length_m', 'platform_spacing_m', 'range_spacing_m', ...
    'envelope_sigma_m', 'target_voltage', 'max_aperture_samples', ...
    'max_fast_time_samples', 'max_focus_candidates', 'max_sweep_cases', ...
    'max_private_values', 'max_working_values', 'max_figures', ...
    'max_phase_step_rad'};
for scalar_index = 1:numel(positive_names)
    if controls.(positive_names{scalar_index}) <= 0
        error('P75:PositiveControl', '%s must be positive.', ...
            positive_names{scalar_index});
    end
end
if controls.range_max_m <= controls.range_min_m || controls.range_min_m <= 0
    error('P75:FastTimeAxis', 'Fast-time range limits must be positive and ordered.');
end
noise_rms = controls.target_voltage*10^(-controls.snr_db/20);
if ~isfinite(noise_rms) || noise_rms < 0
    error('P75:NoiseScale', ...
        'The derived additive-noise RMS must be finite and nonnegative.');
end
if controls.max_phase_step_rad >= pi
    error('P75:PhaseStepLimit', 'The phase-step safety limit must be below pi.');
end
if any(diff(controls.focus_cross_range_m) <= 0)
    error('P75:FocusGrid', 'Focus coordinates must increase strictly.');
end
if any(controls.aperture_sweep_m <= 0) || ...
        any(controls.aperture_sweep_m > controls.aperture_length_m)
    error('P75:ApertureSweepRange', ...
        'Swept apertures must be positive subsets of the baseline aperture.');
end
baseline_half_grid_ratio = controls.aperture_length_m/ ...
    (2*controls.platform_spacing_m);
fast_time_grid_ratio = (controls.range_max_m-controls.range_min_m)/ ...
    controls.range_spacing_m;
if abs(baseline_half_grid_ratio-round(baseline_half_grid_ratio)) > 1.0e-9
    error('P75:BaselineApertureGrid', ...
        'Baseline half-aperture must land exactly on the position grid.');
end
if abs(fast_time_grid_ratio-round(fast_time_grid_ratio)) > 1.0e-9
    error('P75:FastTimeGrid', ...
        'Fast-time endpoints must land exactly on the range grid.');
end
if any(mod(controls.aperture_sweep_m/2, controls.platform_spacing_m) > ...
        1.0e-9 & abs(mod(controls.aperture_sweep_m/2, ...
        controls.platform_spacing_m)-controls.platform_spacing_m) > 1.0e-9)
    error('P75:ApertureGrid', ...
        'Every aperture half-length must land on the baseline position grid.');
end
aperture_samples = round(controls.aperture_length_m/ ...
    controls.platform_spacing_m)+1;
fast_time_samples = round((controls.range_max_m-controls.range_min_m)/ ...
    controls.range_spacing_m)+1;
if aperture_samples > controls.max_aperture_samples || ...
        fast_time_samples > controls.max_fast_time_samples || ...
        numel(controls.focus_cross_range_m) > controls.max_focus_candidates
    error('P75:ResourceCeilings', ...
        'Aperture, fast-time, or focus grid exceeds its immutable ceiling.');
end
if numel(controls.cross_range_sweep_m) > controls.max_sweep_cases || ...
        numel(controls.aperture_sweep_m) > controls.max_sweep_cases
    error('P75:SweepCeiling', 'A sweep exceeds its immutable case ceiling.');
end
private_values = 2*aperture_samples*fast_time_samples;
if private_values > controls.max_private_values
    error('P75:PrivateCeiling', ...
        'The private noise generator request exceeds its ceiling.');
end
predicted_working_values = ...
    12*aperture_samples*fast_time_samples + ...
    20*aperture_samples*numel(controls.cross_range_sweep_m) + ...
    12*aperture_samples*numel(controls.focus_cross_range_m) + ...
    20*(aperture_samples+fast_time_samples+ ...
    numel(controls.focus_cross_range_m));
if predicted_working_values > controls.max_working_values
    error('P75:WorkingPreflight', ...
        'Conservative working-storage prediction exceeds its ceiling.');
end
wavelength_m = controls.c_mps/controls.carrier_hz;
platform_position_m = -controls.aperture_length_m/2: ...
    controls.platform_spacing_m:controls.aperture_length_m/2;
reviewed_targets_m = [controls.target_cross_range_m ...
    controls.cross_range_sweep_m controls.focus_cross_range_m];
for target_index = 1:numel(reviewed_targets_m)
    range_m = sqrt(controls.closest_range_m^2 + ...
        (platform_position_m-reviewed_targets_m(target_index)).^2);
    phase_rad = -4*pi*(range_m-controls.closest_range_m)/wavelength_m;
    if max(abs(diff(phase_rad))) >= controls.max_phase_step_rad
        error('P75:SpatialAliasing', ...
            'A reviewed geometry exceeds the adjacent phase-step limit.');
    end
    if min(range_m)-4*controls.envelope_sigma_m < controls.range_min_m || ...
            max(range_m)+4*controls.envelope_sigma_m > controls.range_max_m
        error('P75:EchoSupport', ...
            'Fast-time range axis does not contain the reviewed echo support.');
    end
end
end

function [slant_range_m, delay_s, phase_rad, received, clean, noise] = ...
        simulate_point_target(seed, platform_position_m, fast_time_range_m, ...
        target_cross_range_m, closest_range_m, wavelength_m, c_mps, ...
        envelope_sigma_m, target_voltage, snr_db, max_private_values)
slant_range_m = sqrt(closest_range_m^2 + ...
    (platform_position_m-target_cross_range_m).^2);
delay_s = 2*slant_range_m/c_mps;
% Subtracting closest_range_m removes one common phase rotation only.
phase_rad = -4*pi*(slant_range_m-closest_range_m)/wavelength_m;
range_offset_m = fast_time_range_m(:).'-slant_range_m(:);
range_envelope = exp(-0.5*(range_offset_m/envelope_sigma_m).^2);
clean = target_voltage*range_envelope.*exp(1j*phase_rad(:));
noise_rms = target_voltage*10^(-snr_db/20);
unit_noise = private_complex_noise(seed, numel(clean), max_private_values);
noise = noise_rms*reshape(unit_noise, size(clean));
received = clean+noise;
end

function score = explicit_cross_range_score(measurement, platform_position_m, ...
        candidate_cross_range_m, closest_range_m, wavelength_m)
measurement = measurement(:);
normalizer = sum(abs(measurement));
if normalizer <= 0 || ~isfinite(normalizer)
    error('P75:FocusInput', ...
        'Cross-range score needs a finite nonzero aperture measurement.');
end
score = zeros(size(candidate_cross_range_m));
for candidate_index = 1:numel(candidate_cross_range_m)
    candidate_range_m = sqrt(closest_range_m^2 + ...
        (platform_position_m-candidate_cross_range_m(candidate_index)).^2);
    candidate_phase_rad = -4*pi*(candidate_range_m-closest_range_m)/ ...
        wavelength_m;
    candidate_phasor = exp(1j*candidate_phase_rad(:));
    score(candidate_index) = abs(sum(measurement.*conj(candidate_phasor)))/ ...
        normalizer;
end
end

function values = private_complex_noise(seed, count, maximum_count)
if ~isscalar(seed) || ~isfinite(seed) || seed ~= floor(seed) || ...
        seed < 1 || seed >= 2147483647
    error('P75:PrivateSeed', 'Private seed is outside the supported range.');
end
if ~isscalar(count) || ~isfinite(count) || count ~= floor(count) || ...
        count < 1 || 2*count > maximum_count
    error('P75:PrivateCount', 'Private generator request exceeds its ceiling.');
end
uniforms = zeros(1, 2*count);
state = seed;
for sample_index = 1:2*count
    state = mod(16807*state, 2147483647);
    uniforms(sample_index) = state/2147483647;
end
radius = sqrt(-2*log(max(uniforms(1:2:end), realmin)));
angle_rad = 2*pi*uniforms(2:2:end);
values = radius.*exp(1j*angle_rad)/sqrt(2);
end
