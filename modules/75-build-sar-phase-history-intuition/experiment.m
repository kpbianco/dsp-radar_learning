%% Sweep 1: change only target cross-range position
cross_range_case_count = numel(target_cross_range_sweep_m);
cross_range_slant_m = zeros(cross_range_case_count, aperture_sample_count);
cross_range_phase_rad = zeros(cross_range_case_count, aperture_sample_count);
cross_range_vertex_m = zeros(1, cross_range_case_count);
cross_range_phase_step_rad = zeros(1, cross_range_case_count);

for case_index = 1:cross_range_case_count
    case_target_cross_range_m = target_cross_range_sweep_m(case_index);
    case_slant_m = sqrt(closest_range_m^2 + ...
        (platform_position_m-case_target_cross_range_m).^2);
    case_phase_rad = -4*pi*(case_slant_m-closest_range_m)/wavelength_m;
    cross_range_slant_m(case_index, :) = case_slant_m;
    cross_range_phase_rad(case_index, :) = case_phase_rad;
    [~, vertex_index] = min(case_slant_m);
    cross_range_vertex_m(case_index) = platform_position_m(vertex_index);
    cross_range_phase_step_rad(case_index) = max(abs(diff(case_phase_rad)));
end

assert(max(abs(cross_range_vertex_m-target_cross_range_sweep_m)) < ...
    platform_spacing_m/2+1.0e-12, 'P75:CrossRangeVertex', ...
    'Every phase-history vertex must follow target cross-range.');
assert(max(cross_range_phase_step_rad) < maximum_adjacent_phase_step_rad, ...
    'P75:CrossRangeAliasing', ...
    'Cross-range sweep must remain spatially unaliased.');
assert(max(abs(cross_range_phase_rad(1, :)- ...
    cross_range_phase_rad(3, end:-1:1))) < 1.0e-10, ...
    'P75:CrossRangeMirror', ...
    'Equal-range symmetric targets must produce mirrored phase histories.');

