aperture_phase_turns = cell(1, aperture_case_count);
aperture_sample_counts = zeros(1, aperture_case_count);
aperture_phase_span_turns = zeros(1, aperture_case_count);
aperture_angular_span_deg = zeros(1, aperture_case_count);

for case_index = 1:aperture_case_count
    case_aperture_m = aperture_length_sweep_m(case_index);
    keep = abs(platform_position_m) <= case_aperture_m/2+1.0e-12;
    case_positions_m = platform_position_m(keep);
    case_slant_m = sqrt(closest_range_m^2 + ...
        (case_positions_m-target_cross_range_m).^2);
    case_phase_turns = -2*(case_slant_m-closest_range_m)/wavelength_m;
    aperture_positions_m{case_index} = case_positions_m;
    aperture_phase_turns{case_index} = case_phase_turns;
    aperture_sample_counts(case_index) = numel(case_positions_m);
    aperture_phase_span_turns(case_index) = ...
        max(case_phase_turns)-min(case_phase_turns);
    aperture_angular_span_deg(case_index) = 2*atan2d( ...
        case_aperture_m/2, closest_range_m);
end

assert(all(diff(aperture_sample_counts) > 0) && ...
    all(diff(aperture_phase_span_turns) > 0) && ...
