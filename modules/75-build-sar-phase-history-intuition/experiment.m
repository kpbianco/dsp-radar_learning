%% Intentionally broken case: discard phase; recover unchanged complex I/Q
ridge_indices = zeros(aperture_sample_count, 1);
complex_aperture_measurement = zeros(aperture_sample_count, 1);
for aperture_index = 1:aperture_sample_count
    [~, ridge_indices(aperture_index)] = min(abs( ...
        fast_time_range_m-slant_range_m(aperture_index)));
    complex_aperture_measurement(aperture_index) = ...
        raw_phase_history(aperture_index, ridge_indices(aperture_index));
end
measurement_before_recovery = complex_aperture_measurement;
magnitude_only_measurement = abs(complex_aperture_measurement);
recovered_complex_measurement = complex_aperture_measurement;

broken_focus_score = explicit_cross_range_score( ...
    magnitude_only_measurement, platform_position_m, focus_cross_range_m, ...
    closest_range_m, wavelength_m);
recovered_focus_score = explicit_cross_range_score( ...
    recovered_complex_measurement, platform_position_m, focus_cross_range_m, ...
    closest_range_m, wavelength_m);
[broken_peak_score, broken_peak_index] = max(broken_focus_score);
[recovered_peak_score, recovered_peak_index] = max(recovered_focus_score);
broken_peak_cross_range_m = focus_cross_range_m(broken_peak_index);
recovered_peak_cross_range_m = focus_cross_range_m(recovered_peak_index);

assert(isequaln(complex_aperture_measurement, ...
    measurement_before_recovery), 'P75:SameDataRecovery', ...
    'Recovery must not mutate or regenerate the complex measurement.');
assert(abs(recovered_peak_cross_range_m-target_cross_range_m) <= 0.25 && ...
    recovered_peak_score > 0.90 && broken_peak_score < 0.15, ...
    'P75:BrokenRecovery', ...
    'Magnitude-only data must fail while unchanged complex I/Q focuses.');

fprintf('\nBroken case: abs(I/Q) across the aperture\n');
fprintf('Broken best coordinate/score: %.2f m / %.4f\n', ...
    broken_peak_cross_range_m, broken_peak_score);
fprintf('Recovered best coordinate/score: %.2f m / %.4f\n', ...
    recovered_peak_cross_range_m, recovered_peak_score);
fprintf('Recovery reused the unchanged %d-look complex record.\n', ...
