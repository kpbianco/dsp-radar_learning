results = struct();

%% Deterministic QPSK and explicit pulse-shaped waveform (P24 dependency)
private_stream = RandStream('mt19937ar', 'Seed', random_seed);
qpsk_bits = double(rand(private_stream, 2, symbol_count) >= 0.5);
qpsk_symbols = ((2*qpsk_bits(1, :)-1) + ...
    1j*(2*qpsk_bits(2, :)-1))/sqrt(2);
ideal_qpsk_points = [-1-1j -1+1j 1-1j 1+1j]/sqrt(2);

upsampled_symbols = complex(zeros(1, symbol_count*samples_per_symbol));
upsampled_symbols(1:samples_per_symbol:end) = qpsk_symbols;

rrc_time_symbols = ...
    (-baseline_span_symbols*samples_per_symbol/2: ...
    baseline_span_symbols*samples_per_symbol/2)/samples_per_symbol;
rrc_pulse = zeros(size(rrc_time_symbols));
for tap_index = 1:numel(rrc_time_symbols)
    x = rrc_time_symbols(tap_index);
    if abs(x) < 1e-12
        rrc_pulse(tap_index) = 1 + baseline_rolloff*(4/pi - 1);
    elseif abs(abs(x) - 1/(4*baseline_rolloff)) < 1e-12
        rrc_pulse(tap_index) = baseline_rolloff/sqrt(2)*( ...
            (1 + 2/pi)*sin(pi/(4*baseline_rolloff)) + ...
            (1 - 2/pi)*cos(pi/(4*baseline_rolloff)));
    else
        rrc_pulse(tap_index) = ( ...
            sin(pi*x*(1-baseline_rolloff)) + ...
            4*baseline_rolloff*x*cos(pi*x*(1+baseline_rolloff)))/( ...
            pi*x*(1-(4*baseline_rolloff*x)^2));
    end
end
rrc_pulse = rrc_pulse/sqrt(sum(abs(rrc_pulse).^2));
matched_filter = conj(fliplr(rrc_pulse));
transmitted_waveform = conv(upsampled_symbols, rrc_pulse);
direct_matched_waveform = conv(transmitted_waveform, matched_filter);
total_pulse_group_delay_samples = numel(rrc_pulse)-1;
noise_variance = 10^(-baseline_esn0_db/10);
noise_sigma = sqrt(noise_variance);

assert(abs(sum(abs(rrc_pulse).^2)-1) < 1e-12, ...
    'The transmit pulse must have unit energy.');
assert(max(abs(matched_filter-conj(fliplr(rrc_pulse)))) < 1e-12, ...
    'The receive filter must be the conjugate time reverse of the pulse.');

%% Baseline multipath: add delayed copies before matched filtering
baseline_channel_impulse = complex(zeros(1, ...
    1 + max(baseline_path_delays_symbols)*samples_per_symbol));
for path_index = 1:numel(baseline_path_gains)
    sample_index = 1 + ...
        baseline_path_delays_symbols(path_index)*samples_per_symbol;
    baseline_channel_impulse(sample_index) = ...
        baseline_path_gains(path_index);
end
baseline_channel_output = conv(transmitted_waveform, ...
    baseline_channel_impulse);
baseline_noise_unit = (randn(private_stream, 1, ...
    numel(baseline_channel_output)) + 1j*randn(private_stream, 1, ...
    numel(baseline_channel_output)))/sqrt(2);
baseline_received_waveform = baseline_channel_output + ...
    noise_sigma*baseline_noise_unit;
baseline_matched_waveform = conv(baseline_received_waveform, matched_filter);

baseline_symbol_channel = complex(zeros(1, ...
    1 + max(baseline_path_delays_symbols)));
baseline_symbol_channel(1 + baseline_path_delays_symbols) = ...
    baseline_path_gains;
baseline_sample_count = symbol_count + max(baseline_path_delays_symbols);
baseline_sample_indices = 1 + total_pulse_group_delay_samples + ...
    (0:baseline_sample_count-1)*samples_per_symbol;
baseline_samples = baseline_matched_waveform(baseline_sample_indices);

% H*w is the combined channel/equalizer impulse response. ZF uses the
% leading square system to force [1,0,...,0] for 31 output samples. MMSE
% minimizes ||H*w-delta||^2 + lambda*||w||^2 over the complete response.
baseline_combined_length = ...
    numel(baseline_symbol_channel) + equalizer_tap_count - 1;
baseline_convolution_matrix = complex(zeros( ...
    baseline_combined_length, equalizer_tap_count));
for column_index = 1:equalizer_tap_count
    row_indices = column_index: ...
        column_index + numel(baseline_symbol_channel) - 1;
    baseline_convolution_matrix(row_indices, column_index) = ...
        baseline_symbol_channel(:);
end
equalizer_target = complex(zeros(baseline_combined_length, 1));
equalizer_target(1) = 1;
baseline_zf_equalizer = ...
    baseline_convolution_matrix(1:equalizer_tap_count, :) \ ...
    equalizer_target(1:equalizer_tap_count);
baseline_mmse_equalizer = (baseline_convolution_matrix' * ...
    baseline_convolution_matrix + ...
    noise_variance*eye(equalizer_tap_count)) \ ...
    (baseline_convolution_matrix'*equalizer_target);

baseline_zf_output = conv(baseline_samples, ...
    baseline_zf_equalizer.');
baseline_mmse_output = conv(baseline_samples, ...
    baseline_mmse_equalizer.');
baseline_unequalized = baseline_samples(1:symbol_count);
baseline_zf_symbols = baseline_zf_output(1:symbol_count);
baseline_mmse_symbols = baseline_mmse_output(1:symbol_count);
metric_indices = metric_guard_symbols+1:symbol_count-metric_guard_symbols;
metric_reference = qpsk_symbols(metric_indices);

baseline_unequalized_evm_pct = 100*sqrt(mean(abs( ...
    baseline_unequalized(metric_indices)-metric_reference).^2));
baseline_zf_evm_pct = 100*sqrt(mean(abs( ...
    baseline_zf_symbols(metric_indices)-metric_reference).^2));
baseline_mmse_evm_pct = 100*sqrt(mean(abs( ...
    baseline_mmse_symbols(metric_indices)-metric_reference).^2));
baseline_zf_noise_gain_db = 10*log10(sum(abs(baseline_zf_equalizer).^2));
baseline_mmse_noise_gain_db = ...
    10*log10(sum(abs(baseline_mmse_equalizer).^2));

baseline_unequalized_detected = [real(baseline_unequalized) >= 0; ...
    imag(baseline_unequalized) >= 0];
baseline_zf_detected = [real(baseline_zf_symbols) >= 0; ...
    imag(baseline_zf_symbols) >= 0];
baseline_mmse_detected = [real(baseline_mmse_symbols) >= 0; ...
    imag(baseline_mmse_symbols) >= 0];
baseline_unequalized_ser = mean(any( ...
    baseline_unequalized_detected(:, metric_indices) ~= ...
    qpsk_bits(:, metric_indices), 1));
baseline_zf_ser = mean(any(baseline_zf_detected(:, metric_indices) ~= ...
    qpsk_bits(:, metric_indices), 1));
baseline_mmse_ser = mean(any(baseline_mmse_detected(:, metric_indices) ~= ...
    qpsk_bits(:, metric_indices), 1));

baseline_frequency_response = fftshift(fft(baseline_symbol_channel, ...
    spectrum_fft_length));
normalized_frequency = (-spectrum_fft_length/2: ...
    spectrum_fft_length/2-1)/spectrum_fft_length;
baseline_minimum_response_db = 20*log10( ...
    max(min(abs(baseline_frequency_response)), 1e-12));

assert(baseline_zf_evm_pct < baseline_unequalized_evm_pct && ...
    baseline_mmse_evm_pct < baseline_unequalized_evm_pct, ...
    'Both baseline equalizers should reduce the multipath EVM.');

%% Sweep 1: change only the one-symbol echo gain
echo_sweep_minimum_response_db = zeros(size(echo_gain_sweep));
echo_sweep_unequalized_evm_pct = zeros(size(echo_gain_sweep));
echo_sweep_mmse_evm_pct = zeros(size(echo_gain_sweep));
for sweep_index = 1:numel(echo_gain_sweep)
    sweep_symbol_channel = baseline_symbol_channel;
    sweep_symbol_channel(2) = ...
        echo_gain_sweep(sweep_index)*exp(1j*0.45);
    sweep_channel_impulse = complex(zeros(size(baseline_channel_impulse)));
    sweep_channel_impulse(1:samples_per_symbol:end) = ...
        sweep_symbol_channel;
    sweep_channel_output = conv(transmitted_waveform, sweep_channel_impulse);
    sweep_received = sweep_channel_output + ...
        noise_sigma*baseline_noise_unit(1:numel(sweep_channel_output));
    sweep_matched = conv(sweep_received, matched_filter);
    sweep_samples = sweep_matched(baseline_sample_indices);

    sweep_matrix = complex(zeros(baseline_combined_length, ...
        equalizer_tap_count));
    for column_index = 1:equalizer_tap_count
        row_indices = column_index: ...
            column_index + numel(sweep_symbol_channel) - 1;
        sweep_matrix(row_indices, column_index) = sweep_symbol_channel(:);
    end
    sweep_target = equalizer_target;
    sweep_mmse = (sweep_matrix'*sweep_matrix + ...
        noise_variance*eye(equalizer_tap_count)) \ ...
        (sweep_matrix'*sweep_target);
    sweep_equalized = conv(sweep_samples, sweep_mmse.');
    sweep_equalized = sweep_equalized(1:symbol_count);
    echo_sweep_unequalized_evm_pct(sweep_index) = 100*sqrt(mean(abs( ...
        sweep_samples(metric_indices)-metric_reference).^2));
    echo_sweep_mmse_evm_pct(sweep_index) = 100*sqrt(mean(abs( ...
        sweep_equalized(metric_indices)-metric_reference).^2));
    sweep_response = fft(sweep_symbol_channel, spectrum_fft_length);
    echo_sweep_minimum_response_db(sweep_index) = 20*log10( ...
        max(min(abs(sweep_response)), 1e-12));
end

%% Broken case: a nearly cancelling echo creates a deep spectral null
broken_channel_impulse = complex(zeros(1, ...
    1 + max(broken_path_delays_symbols)*samples_per_symbol));
for path_index = 1:numel(broken_path_gains)
    sample_index = 1 + ...
        broken_path_delays_symbols(path_index)*samples_per_symbol;
    broken_channel_impulse(sample_index) = broken_path_gains(path_index);
end
broken_channel_output = conv(transmitted_waveform, broken_channel_impulse);
broken_noise_unit = (randn(private_stream, 1, numel(broken_channel_output)) + ...
    1j*randn(private_stream, 1, numel(broken_channel_output)))/sqrt(2);
broken_received = broken_channel_output + noise_sigma*broken_noise_unit;
broken_matched = conv(broken_received, matched_filter);
broken_sample_count = symbol_count + max(broken_path_delays_symbols);
broken_sample_indices = 1 + total_pulse_group_delay_samples + ...
    (0:broken_sample_count-1)*samples_per_symbol;
broken_samples = broken_matched(broken_sample_indices);
broken_symbol_channel = broken_path_gains;

broken_combined_length = ...
    numel(broken_symbol_channel) + equalizer_tap_count - 1;
broken_matrix = complex(zeros(broken_combined_length, equalizer_tap_count));
for column_index = 1:equalizer_tap_count
    row_indices = column_index: ...
        column_index + numel(broken_symbol_channel) - 1;
    broken_matrix(row_indices, column_index) = broken_symbol_channel(:);
end
broken_target = complex(zeros(broken_combined_length, 1));
broken_target(1) = 1;
broken_zf_equalizer = broken_matrix(1:equalizer_tap_count, :) \ ...
    broken_target(1:equalizer_tap_count);
broken_zf_output = conv(broken_samples, broken_zf_equalizer.');
broken_zf_symbols = broken_zf_output(1:symbol_count);
broken_zf_evm_pct = 100*sqrt(mean(abs( ...
    broken_zf_symbols(metric_indices)-metric_reference).^2));
broken_zf_noise_gain_db = 10*log10(sum(abs(broken_zf_equalizer).^2));

% Sweep 2 changes only lambda. The case nearest the known sample-noise
% variance is the deliberate recovery from aggressive near-null inversion.
regularization_evm_pct = zeros(size(regularization_sweep));
regularization_noise_gain_db = zeros(size(regularization_sweep));
regularization_residual_isi_pct = zeros(size(regularization_sweep));
regularized_equalizers = complex(zeros(equalizer_tap_count, ...
    numel(regularization_sweep)));
for sweep_index = 1:numel(regularization_sweep)
    lambda = regularization_sweep(sweep_index);
    regularized_equalizers(:, sweep_index) = ( ...
        broken_matrix'*broken_matrix + lambda*eye(equalizer_tap_count)) \ ...
        (broken_matrix'*broken_target);
    regularized_output = conv(broken_samples, ...
        regularized_equalizers(:, sweep_index).');
    regularized_symbols = regularized_output(1:symbol_count);
    regularization_evm_pct(sweep_index) = 100*sqrt(mean(abs( ...
        regularized_symbols(metric_indices)-metric_reference).^2));
    regularization_noise_gain_db(sweep_index) = 10*log10(sum(abs( ...
        regularized_equalizers(:, sweep_index)).^2));
    combined_response = broken_matrix* ...
        regularized_equalizers(:, sweep_index);
    regularization_residual_isi_pct(sweep_index) = 100*sqrt(sum(abs( ...
        combined_response-broken_target).^2));
end
[~, recovery_index] = min(abs(regularization_sweep-noise_variance));
recovered_mmse_equalizer = regularized_equalizers(:, recovery_index);
recovered_mmse_output = conv(broken_samples, ...
    recovered_mmse_equalizer.');
recovered_mmse_symbols = recovered_mmse_output(1:symbol_count);
recovered_mmse_evm_pct = regularization_evm_pct(recovery_index);
recovered_mmse_noise_gain_db = ...
    regularization_noise_gain_db(recovery_index);

broken_frequency_response = fftshift(fft(broken_symbol_channel, ...
    spectrum_fft_length));
broken_minimum_response_db = 20*log10( ...
    max(min(abs(broken_frequency_response)), 1e-12));
assert(broken_minimum_response_db < -50, ...
    'The broken channel must contain the intended deep spectral null.');
assert(recovered_mmse_evm_pct < broken_zf_evm_pct && ...
    recovered_mmse_noise_gain_db < broken_zf_noise_gain_db, ...
    'Regularization should reduce near-null EVM and noise enhancement.');

