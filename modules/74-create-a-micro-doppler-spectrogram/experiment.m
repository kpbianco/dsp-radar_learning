    'duration_s', observation_duration_s, ...
    'bulk_velocity_mps', bulk_radial_velocity_mps, ...
    'swing_speed_mps', swing_speed_mps, ...
    'swing_rate_hz', swing_rate_hz, ...
    'scatterer_voltage', scatterer_voltage, ...
    'scatterer_phase_rad', scatterer_start_phase_rad, ...
    'snr_db', input_snr_db, ...
    'window_samples', baseline_window_samples, ...
    'overlap_samples', baseline_overlap_samples, ...
    'stft_fft_length', baseline_stft_fft_length, ...
    'spectrum_fft_length', spectrum_fft_length, ...
    'speed_sweep_mps', swing_speed_sweep_mps, ...
    'carrier_sweep_hz', carrier_sweep_hz, ...
    'window_sweep_samples', window_sweep_samples, ...
    'overlap_fraction', window_overlap_fraction, ...
    'max_samples', maximum_slow_time_samples, ...
    'max_stft_fft', maximum_stft_fft_length, ...
    'max_spectrum_fft', maximum_spectrum_fft_length, ...
    'max_frames', maximum_stft_frames, ...
    'max_sweep_cases', maximum_sweep_cases, ...
    'max_private_values', maximum_private_values, ...
    'max_working_values', maximum_working_value_equivalents, ...
    'max_figures', maximum_figures);
validate_controls(controls);

sample_count = round(observation_duration_s*slow_time_sample_rate_hz);
slow_time_s = (0:sample_count-1)/slow_time_sample_rate_hz;
wavelength_m = speed_of_light_mps/carrier_frequency_hz;
bulk_doppler_hz = 2*bulk_radial_velocity_mps/wavelength_m;
swing_doppler_extent_hz = 2*swing_speed_mps/wavelength_m;

%% Baseline: explicit component motion and seeded complex return
[baseline_return, baseline_clean_return, component_velocity_mps, ...
    component_phase_rad, baseline_noise] = simulate_micro_doppler( ...
    baseline_seed, slow_time_s, carrier_frequency_hz, ...
    speed_of_light_mps, bulk_radial_velocity_mps, swing_speed_mps, ...
    swing_rate_hz, scatterer_voltage, scatterer_start_phase_rad, ...
    input_snr_db, maximum_private_values);
component_doppler_hz = 2*component_velocity_mps/wavelength_m;
composite_unwrapped_phase_rad = unwrap(angle(baseline_return));

full_window = explicit_hann(sample_count);
full_spectrum_raw = fftshift(fft(baseline_return.*full_window, ...
    spectrum_fft_length))/sum(full_window);
full_frequency_raw_hz = (-spectrum_fft_length/2: ...
    spectrum_fft_length/2-1)*slow_time_sample_rate_hz/ ...
    spectrum_fft_length;
% The selected-range-bin convention inherited from P70-P73 is
% exp(-j 2 pi f_d t) for positive approaching Doppler. Reverse both data
% and axis so the displayed physical convention increases left to right.
full_spectrum = full_spectrum_raw(end:-1:1);
full_frequency_hz = -full_frequency_raw_hz(end:-1:1);
full_spectrum_db = magnitude_to_relative_db(full_spectrum, plot_floor_db);

[baseline_stft, baseline_stft_time_s, baseline_stft_frequency_hz] = ...
    explicit_stft(baseline_return, slow_time_sample_rate_hz, ...
    baseline_window_samples, baseline_overlap_samples, ...
    baseline_stft_fft_length, maximum_stft_frames);
baseline_stft_db = magnitude_to_relative_db(baseline_stft, plot_floor_db);

assert(abs(bulk_doppler_hz-192.0) < 1.0e-10, 'P74:BulkDoppler', ...
    'The reviewed 24 GHz bulk Doppler must be 192 Hz.');
assert(abs(swing_doppler_extent_hz-320.0) < 1.0e-10, ...
    'P74:SwingExtent', ...
    'The reviewed limb excursion must be +/-320 Hz around bulk.');
assert(all(component_doppler_hz(1, :) == bulk_doppler_hz), ...
    'P74:TorsoRidge', 'Torso Doppler must remain constant.');
assert(max(abs(component_doppler_hz(2, :)-bulk_doppler_hz)) > 319.9, ...
    'P74:LimbTrack', 'The baseline limb must traverse its reviewed extent.');

fprintf('\nP74 baseline: torso plus two swinging limb scatterers\n');
fprintf('Wavelength: %.6f m; slow-time sample rate: %.0f Hz\n', ...
    wavelength_m, slow_time_sample_rate_hz);
fprintf('Bulk velocity/Doppler: %.2f m/s / %.1f Hz\n', ...
    bulk_radial_velocity_mps, bulk_doppler_hz);
fprintf('Limb velocity excursion: +/-%.2f m/s; Doppler excursion: +/-%.1f Hz\n', ...
    swing_speed_mps, swing_doppler_extent_hz);
fprintf('Baseline STFT: %d samples (%.1f ms), %d frames, %.3f Hz FFT spacing\n', ...
    baseline_window_samples, 1000*baseline_window_samples/ ...
    slow_time_sample_rate_hz, numel(baseline_stft_time_s), ...
    slow_time_sample_rate_hz/baseline_stft_fft_length);

figure('Name', 'P74 baseline phase spectrum and spectrogram', ...
    'Tag', 'P74', 'NumberTitle', 'off');
subplot(3, 1, 1);
plot(slow_time_s, composite_unwrapped_phase_rad, 'k-', 'LineWidth', 0.8);
grid on;
xlabel('Slow time (s)');
ylabel('Unwrapped composite phase (rad)');
title('Raw coherent return: phase slope changes as scatterers add');
subplot(3, 1, 2);
plot(full_frequency_hz, full_spectrum_db, 'b-', 'LineWidth', 1.0);
hold on;
plot([bulk_doppler_hz bulk_doppler_hz], [plot_floor_db 0], 'k--', ...
    'DisplayName', 'Bulk Doppler');
grid on;
xlabel('Signed Doppler frequency (Hz, + approaching)');
ylabel('Magnitude relative to dwell maximum (dB)');
title('One dwell-wide FFT contains energy but discards when it occurred');
xlim([-700 850]);
ylim([plot_floor_db 2]);
subplot(3, 1, 3);
imagesc(baseline_stft_time_s, baseline_stft_frequency_hz, baseline_stft_db);
axis xy;
hold on;
plot(slow_time_s, component_doppler_hz(1, :), 'w--', 'LineWidth', 1.0);
plot(slow_time_s, component_doppler_hz(2, :), 'w:', 'LineWidth', 0.9);
plot(slow_time_s, component_doppler_hz(3, :), 'w:', 'LineWidth', 0.9);
xlabel('Slow time (s)');
ylabel('Signed Doppler frequency (Hz, + approaching)');
title('Explicit STFT: constant bulk ridge with periodic limb tracks');
