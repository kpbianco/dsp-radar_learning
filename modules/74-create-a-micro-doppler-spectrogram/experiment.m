speed_of_light_mps = 3.0e8;
carrier_frequency_hz = 24.0e9;
slow_time_sample_rate_hz = 4800.0;
observation_duration_s = 4.0;
bulk_radial_velocity_mps = 1.2;       % positive means approaching
swing_speed_mps = 2.0;                % peak limb speed around the torso
swing_rate_hz = 1.5;
scatterer_voltage = [1.0 0.35 0.28];  % torso, limb A, limb B
scatterer_start_phase_rad = [0 0.7 -0.9];
input_snr_db = 25.0;
baseline_window_samples = 512;
baseline_overlap_samples = 384;
baseline_stft_fft_length = 2048;
spectrum_fft_length = 32768;
swing_speed_sweep_mps = [1.0 2.0 3.0];
carrier_sweep_hz = [10.0 24.0 77.0]*1.0e9;
window_sweep_samples = [192 512 1536];
window_overlap_fraction = 0.75;
plot_floor_db = -55.0;

maximum_slow_time_samples = 20000;
maximum_stft_fft_length = 4096;
maximum_spectrum_fft_length = 65536;
maximum_stft_frames = 1000;
