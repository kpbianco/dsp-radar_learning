%% Local transparent helpers
function validate_controls(controls)
vector_names = {'scatterer_voltage', 'scatterer_phase_rad', ...
    'speed_sweep_mps', 'carrier_sweep_hz', 'window_sweep_samples'};
for index = 1:numel(vector_names)
    values = controls.(vector_names{index});
    assert(isnumeric(values) && isrow(values) && ~isempty(values) && ...
        isreal(values) && all(isfinite(values)), 'P74:MalformedVector', ...
        '%s must be a finite, real, nonempty numeric row vector.', ...
        vector_names{index});
end
scalar_names = {'seed', 'c_mps', 'carrier_hz', 'sample_rate_hz', ...
    'duration_s', 'bulk_velocity_mps', 'swing_speed_mps', ...
    'swing_rate_hz', 'snr_db', 'window_samples', 'overlap_samples', ...
    'stft_fft_length', 'spectrum_fft_length', 'overlap_fraction', ...
    'max_samples', 'max_stft_fft', 'max_spectrum_fft', 'max_frames', ...
    'max_sweep_cases', 'max_private_values', 'max_working_values', ...
    'max_figures'};
for index = 1:numel(scalar_names)
    value = controls.(scalar_names{index});
    assert(isnumeric(value) && isscalar(value) && isreal(value) && ...
        isfinite(value), 'P74:MalformedScalar', ...
        '%s must be one finite real numeric scalar.', scalar_names{index});
end
assert(controls.seed == floor(controls.seed) && controls.seed >= 1 && ...
    controls.seed < 2147483647, 'P74:Seed', ...
    'Seed must be an integer in the Park-Miller state range.');
assert(controls.c_mps > 0 && controls.carrier_hz > 0 && ...
    controls.sample_rate_hz > 0 && controls.duration_s > 0 && ...
    controls.swing_rate_hz > 0, 'P74:PositiveControls', ...
    'Physical rates, duration, carrier, and propagation speed must be positive.');
assert(controls.swing_speed_mps >= 0 && ...
    all(controls.speed_sweep_mps >= 0) && ...
    all(controls.carrier_sweep_hz > 0), 'P74:PhysicalControls', ...
    'Swing speeds must be nonnegative and carrier values positive.');
assert(numel(controls.scatterer_voltage) == 3 && ...
    numel(controls.scatterer_phase_rad) == 3 && ...
    all(controls.scatterer_voltage >= 0), 'P74:Scatterers', ...
    'The reviewed torso/two-limb model needs three nonnegative amplitudes and phases.');
sample_count_local = round(controls.duration_s*controls.sample_rate_hz);
assert(sample_count_local >= controls.window_samples && ...
    sample_count_local <= controls.max_samples, 'P74:SampleCeiling', ...
    'Slow-time record length is invalid or exceeds its resource ceiling.');
assert(controls.window_samples == floor(controls.window_samples) && ...
    controls.overlap_samples == floor(controls.overlap_samples) && ...
    controls.window_samples >= 8 && controls.overlap_samples >= 0 && ...
    controls.overlap_samples < controls.window_samples, ...
    'P74:STFTGeometry', 'Window and overlap must define a positive integer hop.');
assert(controls.overlap_fraction >= 0 && controls.overlap_fraction < 1, ...
    'P74:OverlapFraction', ...
    'Sweep overlap fraction must be at least zero and less than one.');
assert(all(controls.window_sweep_samples == ...
    floor(controls.window_sweep_samples)) && ...
    all(controls.window_sweep_samples >= 8) && ...
    all(controls.window_sweep_samples <= sample_count_local), ...
    'P74:WindowSweep', 'Every window sweep case must fit the record.');
assert(controls.stft_fft_length == floor(controls.stft_fft_length) && ...
    controls.stft_fft_length >= max([controls.window_samples ...
    controls.window_sweep_samples]) && ...
    controls.stft_fft_length <= controls.max_stft_fft && ...
    mod(controls.stft_fft_length, 2) == 0, 'P74:STFTFFT', ...
    'STFT FFT length must be even, fit every window, and stay bounded.');
assert(controls.spectrum_fft_length == ...
    floor(controls.spectrum_fft_length) && ...
    controls.spectrum_fft_length >= sample_count_local && ...
    controls.spectrum_fft_length <= controls.max_spectrum_fft && ...
    mod(controls.spectrum_fft_length, 2) == 0, 'P74:SpectrumFFT', ...
    'Spectrum FFT length must be even, cover the record, and stay bounded.');
assert(numel(controls.speed_sweep_mps) <= controls.max_sweep_cases && ...
    numel(controls.carrier_sweep_hz) <= controls.max_sweep_cases && ...
    numel(controls.window_sweep_samples) <= controls.max_sweep_cases, ...
    'P74:ResourceCeilings', 'A controlled sweep exceeds its case ceiling.');
maximum_swing_speed_mps = max([controls.swing_speed_mps ...
    controls.speed_sweep_mps]);
maximum_carrier_hz = max([controls.carrier_hz ...
    controls.carrier_sweep_hz]);
maximum_velocity_mps = abs(controls.bulk_velocity_mps)+ ...
    maximum_swing_speed_mps;
maximum_doppler_hz = 2*maximum_velocity_mps* ...
    maximum_carrier_hz/controls.c_mps;
assert(maximum_doppler_hz < controls.sample_rate_hz/2, ...
    'P74:DopplerNyquist', ...
    'The reviewed carrier/speed sweeps must stay inside slow-time Nyquist.');
minimum_hop = min(controls.window_sweep_samples- ...
    floor(controls.overlap_fraction*controls.window_sweep_samples));
maximum_frames_local = floor((sample_count_local- ...
    min(controls.window_sweep_samples))/minimum_hop)+1;
assert(maximum_frames_local <= controls.max_frames, 'P74:FrameCeiling', ...
    'The shortest reviewed window creates too many STFT frames.');
baseline_hop = controls.window_samples-controls.overlap_samples;
baseline_frames = floor((sample_count_local-controls.window_samples)/ ...
    baseline_hop)+1;
window_hops = controls.window_sweep_samples- ...
    floor(controls.overlap_fraction*controls.window_sweep_samples);
window_frames = floor((sample_count_local-controls.window_sweep_samples)./ ...
    window_hops)+1;
total_stft_frames = baseline_frames*(1+ ...
    numel(controls.speed_sweep_mps)+numel(controls.carrier_sweep_hz)+2)+ ...
    sum(window_frames);
% Each retained STFT has complex data (two eight-byte equivalents) and a
% real dB view. Remaining signals, axes, spectra, and controls receive a
% deliberately conservative fixed allowance.
predicted_value_equivalents = 3*controls.stft_fft_length* ...
    total_stft_frames+30*sample_count_local+ ...
    4*controls.spectrum_fft_length;
assert(predicted_value_equivalents <= controls.max_working_values, ...
    'P74:WorkingPreflight', ...
    'Predicted retained workspace exceeds its pre-allocation ceiling.');
assert(2*sample_count_local <= controls.max_private_values, ...
    'P74:PrivateCeiling', ...
    'Private complex-noise generation exceeds its value ceiling.');
assert(controls.max_figures == 5 && controls.max_working_values > 0, ...
    'P74:ImmutableCeilings', ...
    'Reviewed figure and working-value ceilings must remain explicit.');
end

function [received, clean, velocity_mps, phase_rad, noise] = ...
    simulate_micro_doppler(seed, time_s, carrier_hz, c_mps, ...
    bulk_velocity_mps, swing_speed_mps, swing_rate_hz, ...
    scatterer_voltage, scatterer_phase_rad, snr_db, max_private_values)
wavelength_m = c_mps/carrier_hz;
swing_angle_rad = 2*pi*swing_rate_hz*time_s;
velocity_mps = [bulk_velocity_mps*ones(size(time_s)); ...
    bulk_velocity_mps+swing_speed_mps*cos(swing_angle_rad); ...
    bulk_velocity_mps+swing_speed_mps*cos(swing_angle_rad+pi)];
radial_advance_m = [bulk_velocity_mps*time_s; ...
    bulk_velocity_mps*time_s+swing_speed_mps/(2*pi*swing_rate_hz)* ...
    sin(swing_angle_rad); ...
    bulk_velocity_mps*time_s+swing_speed_mps/(2*pi*swing_rate_hz)* ...
    sin(swing_angle_rad+pi)];
phase_rad = -4*pi*radial_advance_m/wavelength_m+ ...
    scatterer_phase_rad(:)*ones(1, numel(time_s));
component_returns = scatterer_voltage(:)*ones(1, numel(time_s)).* ...
    exp(1j*phase_rad);
clean = sum(component_returns, 1);
unit_noise = private_complex_noise(seed, 1, numel(time_s), ...
    max_private_values);
nominal_signal_rms = sqrt(sum(scatterer_voltage.^2));
noise_rms = nominal_signal_rms*10^(-snr_db/20);
noise = noise_rms*unit_noise;
received = clean+noise;
end

function window = explicit_hann(length_samples)
assert(length_samples >= 2 && length_samples == floor(length_samples), ...
    'P74:HannLength', 'Hann length must be an integer of at least two.');
index = 0:length_samples-1;
window = 0.5-0.5*cos(2*pi*index/(length_samples-1));
end

function [stft_values, frame_time_s, frequency_hz] = explicit_stft( ...
    signal, sample_rate_hz, window_samples, overlap_samples, ...
    fft_length, maximum_frames)
assert(isnumeric(signal) && isrow(signal) && ~isempty(signal) && ...
    all(isfinite(signal)), 'P74:STFTInput', ...
    'STFT input must be a finite nonempty numeric row vector.');
assert(window_samples >= 2 && window_samples == floor(window_samples) && ...
    overlap_samples >= 0 && overlap_samples == floor(overlap_samples) && ...
    overlap_samples < window_samples && fft_length >= window_samples && ...
    fft_length == floor(fft_length) && mod(fft_length, 2) == 0, ...
    'P74:STFTParameters', 'STFT geometry is malformed.');
hop_samples = window_samples-overlap_samples;
frame_count = floor((numel(signal)-window_samples)/hop_samples)+1;
assert(frame_count >= 1 && frame_count <= maximum_frames, ...
    'P74:FrameCeiling', 'STFT frame count is invalid or exceeds its ceiling.');
window = explicit_hann(window_samples);
stft_raw = complex(zeros(fft_length, frame_count));
frame_time_s = zeros(1, frame_count);
for frame_index = 1:frame_count
    first_sample = (frame_index-1)*hop_samples+1;
    indices = first_sample:first_sample+window_samples-1;
    frame = signal(indices).*window;
    stft_raw(:, frame_index) = fftshift(fft(frame, fft_length)).'/ ...
        sum(window);
    frame_time_s(frame_index) = ((first_sample-1)+ ...
        (window_samples-1)/2)/sample_rate_hz;
end
frequency_raw_hz = (-fft_length/2:fft_length/2-1)* ...
    sample_rate_hz/fft_length;
stft_values = stft_raw(end:-1:1, :);
frequency_hz = -frequency_raw_hz(end:-1:1);
end

function relative_db = magnitude_to_relative_db(values, floor_db)
magnitude = abs(values);
reference = max(magnitude(:));
assert(isfinite(reference) && reference > 0, 'P74:DBReference', ...
    'Relative-dB conversion needs a finite positive reference.');
relative_db = 20*log10(max(magnitude/reference, 10^(floor_db/20)));
end

function peak_frequency_hz = peak_stft_frequency(stft_values, frequency_hz)
integrated_power = sum(abs(stft_values).^2, 2);
[~, peak_index] = max(integrated_power);
peak_frequency_hz = frequency_hz(peak_index);
end

function noise = private_complex_noise(seed, rows, columns, maximum_values)
value_count = rows*columns;
assert(rows >= 1 && columns >= 1 && rows == floor(rows) && ...
    columns == floor(columns) && 2*value_count <= maximum_values, ...
    'P74:PrivateCeiling', ...
    'Private noise dimensions are invalid or exceed the resource ceiling.');
uniforms = private_uniform(seed, 2*value_count, maximum_values);
radius = sqrt(-2*log(max(uniforms(1:2:end), realmin)));
phase = 2*pi*uniforms(2:2:end);
values = radius.*exp(1j*phase)/sqrt(2);
noise = reshape(values, rows, columns);
end

function values = private_uniform(seed, count, maximum_values)
assert(seed == floor(seed) && seed >= 1 && seed < 2147483647, ...
    'P74:PrivateSeed', 'Private generator seed is out of range.');
assert(count == floor(count) && count >= 1 && count <= maximum_values, ...
    'P74:PrivateCount', 'Private generator request exceeds its ceiling.');
state = seed;
values = zeros(1, count);
for index = 1:count
    state = mod(16807*state, 2147483647);
    values(index) = state/2147483647;
end
end
