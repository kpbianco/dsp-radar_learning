%% P74: Create a Micro-Doppler Spectrogram
% Guiding question:
% How do rotating or swinging target parts produce time-varying Doppler around bulk motion?
%
% Base MATLAB only. Component velocity, integrated phase, coherent addition,
% full-dwell Doppler processing, and every STFT frame are explicit.

close(findall(0, 'Type', 'figure', 'Tag', 'P74'));
clear p74_results;

%% Visible deterministic controls and immutable resource ceilings
