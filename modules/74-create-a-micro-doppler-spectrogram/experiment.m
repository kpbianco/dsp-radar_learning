%% Sweep 1: change only peak swing speed and reuse one additive-noise record
speed_case_count = numel(swing_speed_sweep_mps);
speed_stft_db = cell(1, speed_case_count);
speed_stft_time_s = cell(1, speed_case_count);
speed_stft_frequency_hz = cell(1, speed_case_count);
speed_expected_low_hz = zeros(1, speed_case_count);
speed_expected_high_hz = zeros(1, speed_case_count);
speed_noise_by_case = cell(1, speed_case_count);

for case_index = 1:speed_case_count
    case_speed_mps = swing_speed_sweep_mps(case_index);
    [case_return, ~, ~, ~, speed_noise_by_case{case_index}] = ...
        simulate_micro_doppler(baseline_seed+100, slow_time_s, ...
        carrier_frequency_hz, speed_of_light_mps, ...
        bulk_radial_velocity_mps, case_speed_mps, swing_rate_hz, ...
        scatterer_voltage, scatterer_start_phase_rad, input_snr_db, ...
        maximum_private_values);
    [case_stft, speed_stft_time_s{case_index}, ...
        speed_stft_frequency_hz{case_index}] = explicit_stft( ...
        case_return, slow_time_sample_rate_hz, baseline_window_samples, ...
        baseline_overlap_samples, baseline_stft_fft_length, ...
        maximum_stft_frames);
    speed_stft_db{case_index} = magnitude_to_relative_db( ...
        case_stft, plot_floor_db);
    case_extent_hz = 2*case_speed_mps/wavelength_m;
    speed_expected_low_hz(case_index) = bulk_doppler_hz-case_extent_hz;
    speed_expected_high_hz(case_index) = bulk_doppler_hz+case_extent_hz;
end

for case_index = 2:speed_case_count
    assert(isequaln(speed_noise_by_case{1}, speed_noise_by_case{case_index}), ...
        'P74:SpeedSweepIsolation', ...
        'Every speed case must reuse the same deterministic additive noise.');
end
assert(all(diff(speed_expected_high_hz) > 0) && ...
    all(diff(speed_expected_low_hz) < 0), 'P74:SpeedSweepExtent', ...
    'Increasing swing speed must widen both sides around fixed bulk Doppler.');

fprintf('\nSwing-speed sweep (m/s): %s\n', ...
    mat2str(swing_speed_sweep_mps, 3));
fprintf('Expected limb Doppler lows (Hz): %s\n', ...
    mat2str(speed_expected_low_hz, 4));
fprintf('Expected limb Doppler highs (Hz): %s\n', ...
    mat2str(speed_expected_high_hz, 4));

figure('Name', 'P74 swing-speed sweep', 'Tag', 'P74', ...
    'NumberTitle', 'off');
for case_index = 1:speed_case_count
    subplot(speed_case_count, 1, case_index);
    imagesc(speed_stft_time_s{case_index}, ...
        speed_stft_frequency_hz{case_index}, speed_stft_db{case_index});
