function mixed = mix_error_templates(smooth_template, random_template, alpha)
assert(isrow(smooth_template) && isrow(random_template) && ...
    numel(smooth_template) == numel(random_template) && ...
    isscalar(alpha) && isfinite(alpha) && alpha >= 0 && alpha <= 1, ...
    'P80:ErrorMixture', ...
    'Error templates and mixture fraction are incompatible.');
mixed = normalize_zero_mean_rms((1-alpha)*smooth_template+ ...
    alpha*random_template);
end

function normalized = normalize_zero_mean_rms(values)
assert(isnumeric(values) && isreal(values) && isrow(values) && ...
    all(isfinite(values)), 'P80:TemplateInput', ...
    'Error template must be a finite real row vector.');
centered_values = values-mean(values);
scale = root_mean_square(centered_values);
assert(scale > eps, 'P80:TemplateScale', ...
    'Error template must have nonzero RMS.');
normalized = centered_values/scale;
end

function value = root_mean_square(values)
value = sqrt(mean(abs(values).^2));
end

function output = centered(values)
output = values-mean(values);
end

function value = centered_rmse(first, second)
assert(isvector(first) && isvector(second) && numel(first) == numel(second), ...
    'P80:PhaseMetricShape', 'Phase vectors must have equal length.');
difference = centered(first(:).')-centered(second(:).');
value = root_mean_square(difference);
end

function values = private_uniform(seed, count, maximum_count)
assert(isnumeric(seed) && isreal(seed) && isscalar(seed) && ...
    isfinite(seed) && seed == floor(seed) && seed >= 1 && ...
    seed < 2147483647, 'P80:GeneratorSeed', ...
    'Private generator seed is invalid.');
assert(isnumeric(count) && isreal(count) && isscalar(count) && ...
    isfinite(count) && count == floor(count) && count >= 1 && ...
    count <= maximum_count, 'P80:GeneratorCount', ...
    'Private generator count exceeds its bound.');
state = seed;
values = zeros(1, count);
for index = 1:count
    state = mod(16807*state, 2147483647);
    values(index) = (state+0.5)/2147483647;
end
end

function values = private_normal(seed, count, maximum_count)
uniform_count = 2*ceil(count/2);
uniform_values = private_uniform(seed, uniform_count, maximum_count);
values = zeros(1, uniform_count);
for index = 1:2:uniform_count
    radius = sqrt(-2*log(uniform_values(index)));
    angle_rad = 2*pi*uniform_values(index+1);
    values(index) = radius*cos(angle_rad);
    values(index+1) = radius*sin(angle_rad);
end
values = values(1:count);
end
