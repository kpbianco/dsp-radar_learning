%% P80: Inject SAR Motion Error and Apply Autofocus
% Guiding question:
% How small a platform-position error is enough to blur a coherent image?
%
% Base MATLAB only. A visible two-way phase screen is applied to an explicit
% point-target phase history. Focusing is a coherent path-matched sum, and
% autofocus is an explicit adjacent-pulse phase-gradient integration.

close(findall(0, 'Type', 'figure', 'Tag', 'P80'));
clear p80_results;
p80_results = run_p80_experiment();

function p80_results = run_p80_experiment()

%% Visible deterministic controls and immutable resource ceilings
baseline_seed = 8001;
speed_of_light_mps = 3.0e8;
carrier_frequency_hz = 10.0e9;
scene_reference_range_m = 1000.0;
bandwidth_hz = 200.0e6;
frequency_sample_count = 129;
aperture_length_m = 30.0;
platform_spacing_m = 0.25;
image_cross_range_m = -4.0:0.02:4.0;
image_range_offset_m = -15.0:0.375:15.0;
target_cross_range_m = [-1.0 0.35 1.45];
target_range_offset_m = [-10.0 0.0 9.0];
target_voltage = [1.0 0.70 0.50];
reference_gate_index = 1;
measurement_snr_db = 35.0;
baseline_error_rms_fraction = 1/8;
baseline_random_fraction = 0.25;
error_rms_fraction_sweep = [0 1/32 1/16 1/8 1/4];
random_fraction_sweep = [0 0.25 0.50 0.75 1.0];
broken_interferer_voltage = 0.95;
display_floor_db = -45.0;

maximum_aperture_samples = 161;
maximum_image_cross_range_samples = 501;
maximum_image_range_samples = 101;
maximum_frequency_samples = 257;
maximum_targets = 4;
maximum_sweep_cases = 6;
maximum_private_values = 2048;
maximum_focus_operations = 4500000;
maximum_working_value_equivalents = 2000000;
maximum_figures = 5;
maximum_phase_increment_rad = 0.90*pi;

controls = struct( ...
    'seed', baseline_seed, 'c_mps', speed_of_light_mps, ...
    'carrier_hz', carrier_frequency_hz, ...
    'reference_range_m', scene_reference_range_m, ...
    'bandwidth_hz', bandwidth_hz, ...
    'frequency_samples', frequency_sample_count, ...
    'aperture_length_m', aperture_length_m, ...
    'platform_spacing_m', platform_spacing_m, ...
    'image_x_m', image_cross_range_m, ...
    'image_range_offset_m', image_range_offset_m, ...
    'target_x_m', target_cross_range_m, ...
    'target_range_offset_m', target_range_offset_m, ...
    'target_voltage', target_voltage, ...
    'reference_gate', reference_gate_index, ...
    'measurement_snr_db', measurement_snr_db, ...
    'baseline_error_fraction', baseline_error_rms_fraction, ...
    'baseline_random_fraction', baseline_random_fraction, ...
    'error_fraction_sweep', error_rms_fraction_sweep, ...
    'random_fraction_sweep', random_fraction_sweep, ...
    'broken_interferer_voltage', broken_interferer_voltage, ...
    'display_floor_db', display_floor_db, ...
    'max_aperture_samples', maximum_aperture_samples, ...
    'max_image_x_samples', maximum_image_cross_range_samples, ...
    'max_image_range_samples', maximum_image_range_samples, ...
    'max_frequency_samples', maximum_frequency_samples, ...
    'max_targets', maximum_targets, ...
    'max_sweep_cases', maximum_sweep_cases, ...
    'max_private_values', maximum_private_values, ...
    'max_focus_operations', maximum_focus_operations, ...
    'max_working_values', maximum_working_value_equivalents, ...
    'max_figures', maximum_figures, ...
    'max_phase_increment_rad', maximum_phase_increment_rad);
predicted_focus_operations = validate_controls(controls);

wavelength_m = speed_of_light_mps/carrier_frequency_hz;
platform_position_m = -aperture_length_m/2:platform_spacing_m: ...
    aperture_length_m/2;
aperture_sample_count = numel(platform_position_m);
target_ground_range_m = scene_reference_range_m+target_range_offset_m;

target_phase_uniform = private_uniform(baseline_seed, ...
    numel(target_voltage), maximum_private_values);
target_reflectivity = target_voltage.*exp(1j*2*pi*target_phase_uniform);
ideal_signal_history = synthesize_history(platform_position_m, ...
    target_cross_range_m, target_ground_range_m, target_reflectivity, ...
    scene_reference_range_m, wavelength_m);

noise_normal = private_normal(baseline_seed+1, ...
    2*numel(ideal_signal_history), maximum_private_values);
noise_scale = 10^(-measurement_snr_db/20)/sqrt(2);
measurement_noise = noise_scale*(reshape(noise_normal( ...
    1:numel(ideal_signal_history)), size(ideal_signal_history))+ ...
    1j*reshape(noise_normal(numel(ideal_signal_history)+1:end), ...
    size(ideal_signal_history)));
ideal_measured_history = ideal_signal_history+measurement_noise;
retained_ideal_measured_history = ideal_measured_history;

normalized_aperture = (platform_position_m-platform_position_m(1))/ ...
    (platform_position_m(end)-platform_position_m(1));
smooth_error_template = sin(2*pi*normalized_aperture+0.3)+ ...
    0.35*sin(6*pi*normalized_aperture-0.4);
smooth_error_template = normalize_zero_mean_rms(smooth_error_template);
raw_random_error = private_uniform(baseline_seed+2, ...
    aperture_sample_count, maximum_private_values)-0.5;
correlation_kernel = [1 2 3 4 3 2 1]/16;
short_correlated_error_template = conv(raw_random_error, ...
    correlation_kernel, 'same');
short_correlated_error_template = normalize_zero_mean_rms( ...
    short_correlated_error_template);

executed_focus_operations = 0;

%% Deterministic ideal baseline and baseline lambda/8 error
[ideal_focused_gates, operation_count] = focus_history( ...
    ideal_measured_history, platform_position_m, image_cross_range_m, ...
    target_ground_range_m, scene_reference_range_m, wavelength_m, ...
    maximum_focus_operations);
executed_focus_operations = executed_focus_operations+operation_count;

baseline_error_template = mix_error_templates(smooth_error_template, ...
    short_correlated_error_template, baseline_random_fraction);
baseline_path_error_m = baseline_error_rms_fraction*wavelength_m* ...
    baseline_error_template;
baseline_phase_error_rad = -4*pi*baseline_path_error_m/wavelength_m;
assert(max(abs(diff(baseline_phase_error_rad))) < ...
    maximum_phase_increment_rad, 'P80:PhaseGradientSampling', ...
    'Adjacent error phase must remain unambiguous for this lesson.');
baseline_errored_history = apply_phase_screen(ideal_signal_history, ...
    measurement_noise, baseline_phase_error_rad);
retained_errored_history = baseline_errored_history;
[blurred_focused_gates, operation_count] = focus_history( ...
    baseline_errored_history, platform_position_m, image_cross_range_m, ...
    target_ground_range_m, scene_reference_range_m, wavelength_m, ...
    maximum_focus_operations);
executed_focus_operations = executed_focus_operations+operation_count;

[baseline_phase_estimate_rad, baseline_phase_increment_rad] = ...
    estimate_phase_gradient(baseline_errored_history(:, reference_gate_index), ...
    platform_position_m, target_cross_range_m(reference_gate_index), ...
    target_ground_range_m(reference_gate_index), scene_reference_range_m, ...
    wavelength_m);
baseline_corrected_history = baseline_errored_history.* ...
    repmat(exp(-1j*baseline_phase_estimate_rad(:)), ...
    1, numel(target_voltage));
[corrected_focused_gates, operation_count] = focus_history( ...
    baseline_corrected_history, platform_position_m, image_cross_range_m, ...
    target_ground_range_m, scene_reference_range_m, wavelength_m, ...
    maximum_focus_operations);
executed_focus_operations = executed_focus_operations+operation_count;

ideal_metrics = focus_metrics(image_cross_range_m, ideal_focused_gates, ...
    ideal_focused_gates);
blurred_metrics = focus_metrics(image_cross_range_m, ...
    blurred_focused_gates, ideal_focused_gates);
corrected_metrics = focus_metrics(image_cross_range_m, ...
    corrected_focused_gates, ideal_focused_gates);
baseline_phase_rmse_rad = centered_rmse( ...
    baseline_phase_estimate_rad, baseline_phase_error_rad);

assert(blurred_metrics.mean_peak_retention < 0.65 && ...
    corrected_metrics.mean_peak_retention > 0.95 && ...
    corrected_metrics.mean_entropy < blurred_metrics.mean_entropy-0.8 && ...
    baseline_phase_rmse_rad < 0.05, 'P80:BaselineAutofocus', ...
    'The lambda/8 case must blur and materially recover.');

fprintf('\nP80 baseline: %.1f GHz carrier, wavelength %.1f mm\n', ...
    carrier_frequency_hz/1.0e9, wavelength_m*1.0e3);
fprintf('Line-of-sight error RMS %.3f mm (lambda/%.0f) -> phase RMS %.3f rad\n', ...
    root_mean_square(baseline_path_error_m)*1.0e3, ...
    1/baseline_error_rms_fraction, ...
    root_mean_square(baseline_phase_error_rad));
fprintf('Mean peak retention ideal/blurred/corrected = %.3f / %.3f / %.3f\n', ...
    ideal_metrics.mean_peak_retention, blurred_metrics.mean_peak_retention, ...
    corrected_metrics.mean_peak_retention);
fprintf(['Mean cross-range-cut entropy ideal/blurred/corrected = ' ...
    '%.3f / %.3f / %.3f nats\n'], ...
    ideal_metrics.mean_entropy, blurred_metrics.mean_entropy, ...
    corrected_metrics.mean_entropy);
fprintf('Centered autofocus phase RMSE = %.4f rad\n', ...
    baseline_phase_rmse_rad);

figure('Name', 'P80 motion error becomes aperture phase error', ...
    'Tag', 'P80', 'NumberTitle', 'off');
subplot(2, 1, 1);
plot(platform_position_m, baseline_path_error_m*1.0e3, ...
    'b-', 'LineWidth', 1.2);
grid on;
xlabel('Platform cross-range position (m)');
ylabel('Line-of-sight error (mm)');
title(sprintf('Injected path error: RMS %.2f mm = lambda/%.0f', ...
    root_mean_square(baseline_path_error_m)*1.0e3, ...
    1/baseline_error_rms_fraction));
subplot(2, 1, 2);
plot(platform_position_m, baseline_phase_error_rad, ...
    'k-', 'LineWidth', 1.2);
hold on;
plot(platform_position_m, centered(baseline_phase_estimate_rad), ...
    'r--', 'LineWidth', 1.1);
grid on;
xlabel('Platform cross-range position (m)');
ylabel('Two-way phase error (rad)');
title('Truth and phase-gradient estimate (arbitrary constant removed)');
legend('Injected phase', 'Estimated phase', 'Location', 'best');

[ideal_image, operation_count] = compose_range_cross_range_image( ...
    ideal_focused_gates, image_range_offset_m, target_range_offset_m, ...
    bandwidth_hz, frequency_sample_count, speed_of_light_mps, ...
    maximum_focus_operations);
executed_focus_operations = executed_focus_operations+operation_count;
[blurred_image, operation_count] = compose_range_cross_range_image( ...
    blurred_focused_gates, image_range_offset_m, target_range_offset_m, ...
    bandwidth_hz, frequency_sample_count, speed_of_light_mps, ...
    maximum_focus_operations);
executed_focus_operations = executed_focus_operations+operation_count;
[corrected_image, operation_count] = compose_range_cross_range_image( ...
    corrected_focused_gates, image_range_offset_m, target_range_offset_m, ...
    bandwidth_hz, frequency_sample_count, speed_of_light_mps, ...
    maximum_focus_operations);
executed_focus_operations = executed_focus_operations+operation_count;

figure('Name', 'P80 ideal blurred and autofocus-corrected images', ...
    'Tag', 'P80', 'NumberTitle', 'off');
subplot(1, 3, 1);
show_image(image_cross_range_m, image_range_offset_m, ideal_image, ...
    target_cross_range_m, target_range_offset_m, display_floor_db, ...
    'Ideal nominal-track focus');
subplot(1, 3, 2);
show_image(image_cross_range_m, image_range_offset_m, blurred_image, ...
    target_cross_range_m, target_range_offset_m, display_floor_db, ...
    sprintf('Blurred: peak %.2f, mean x-cut H %.2f', ...
    blurred_metrics.mean_peak_retention, blurred_metrics.mean_entropy));
subplot(1, 3, 3);
show_image(image_cross_range_m, image_range_offset_m, corrected_image, ...
    target_cross_range_m, target_range_offset_m, display_floor_db, ...
    sprintf('Autofocus: peak %.2f, mean x-cut H %.2f', ...
    corrected_metrics.mean_peak_retention, corrected_metrics.mean_entropy));

%% Sweep 1: error RMS in fractions of wavelength
magnitude_case_count = numel(error_rms_fraction_sweep);
magnitude_blurred_peak = zeros(1, magnitude_case_count);
magnitude_corrected_peak = zeros(1, magnitude_case_count);
magnitude_blurred_entropy = zeros(1, magnitude_case_count);
magnitude_corrected_entropy = zeros(1, magnitude_case_count);
magnitude_phase_rms_rad = zeros(1, magnitude_case_count);
magnitude_residual_phase_rmse_rad = zeros(1, magnitude_case_count);
for case_index = 1:magnitude_case_count
    case_path_error_m = error_rms_fraction_sweep(case_index)* ...
        wavelength_m*baseline_error_template;
    case_phase_error_rad = -4*pi*case_path_error_m/wavelength_m;
    assert(max(abs(diff(case_phase_error_rad))) < ...
        maximum_phase_increment_rad, 'P80:MagnitudeSweepSampling', ...
        'Magnitude sweep exceeded the phase-gradient sampling bound.');
    case_history = apply_phase_screen(ideal_signal_history, ...
        measurement_noise, case_phase_error_rad);
    [case_blurred_gates, operation_count] = focus_history( ...
        case_history, platform_position_m, image_cross_range_m, ...
        target_ground_range_m, scene_reference_range_m, wavelength_m, ...
        maximum_focus_operations);
    executed_focus_operations = executed_focus_operations+operation_count;
    case_phase_estimate_rad = estimate_phase_gradient( ...
        case_history(:, reference_gate_index), platform_position_m, ...
        target_cross_range_m(reference_gate_index), ...
        target_ground_range_m(reference_gate_index), ...
        scene_reference_range_m, wavelength_m);
    case_corrected_history = case_history.*repmat( ...
        exp(-1j*case_phase_estimate_rad(:)), 1, numel(target_voltage));
    [case_corrected_gates, operation_count] = focus_history( ...
        case_corrected_history, platform_position_m, image_cross_range_m, ...
        target_ground_range_m, scene_reference_range_m, wavelength_m, ...
        maximum_focus_operations);
    executed_focus_operations = executed_focus_operations+operation_count;
    case_blurred_metrics = focus_metrics(image_cross_range_m, ...
        case_blurred_gates, ideal_focused_gates);
    case_corrected_metrics = focus_metrics(image_cross_range_m, ...
        case_corrected_gates, ideal_focused_gates);
    magnitude_blurred_peak(case_index) = ...
        case_blurred_metrics.mean_peak_retention;
    magnitude_corrected_peak(case_index) = ...
        case_corrected_metrics.mean_peak_retention;
    magnitude_blurred_entropy(case_index) = ...
        case_blurred_metrics.mean_entropy;
    magnitude_corrected_entropy(case_index) = ...
        case_corrected_metrics.mean_entropy;
    magnitude_phase_rms_rad(case_index) = ...
        root_mean_square(case_phase_error_rad);
    magnitude_residual_phase_rmse_rad(case_index) = centered_rmse( ...
        case_phase_estimate_rad, case_phase_error_rad);
end
assert(all(diff(magnitude_blurred_peak) < 0) && ...
    magnitude_blurred_peak(end) < 0.40 && ...
    all(magnitude_corrected_peak > 0.95) && ...
    all(magnitude_residual_phase_rmse_rad < 0.05), ...
    'P80:ErrorMagnitudeSweep', ...
    'Increasing path-error RMS must degrade the uncorrected coherent peak.');

figure('Name', 'P80 wavelength-fraction error sweep', ...
    'Tag', 'P80', 'NumberTitle', 'off');
subplot(1, 2, 1);
plot(error_rms_fraction_sweep, magnitude_blurred_peak, ...
    'ro-', 'LineWidth', 1.2);
hold on;
plot(error_rms_fraction_sweep, magnitude_corrected_peak, ...
    'bs-', 'LineWidth', 1.2);
grid on;
xlabel('Line-of-sight error RMS / wavelength');
ylabel('Mean coherent peak / ideal peak');
title('Millimetres become lost coherent gain');
legend('Uncorrected', 'Autofocus corrected', 'Location', 'best');
subplot(1, 2, 2);
plot(magnitude_phase_rms_rad, magnitude_blurred_entropy, ...
    'ro-', 'LineWidth', 1.2);
hold on;
plot(magnitude_phase_rms_rad, magnitude_corrected_entropy, ...
    'bs-', 'LineWidth', 1.2);
grid on;
xlabel('Injected two-way phase RMS (rad)');
ylabel('Mean cross-range-cut entropy (nats)');
title('Defocus spreads energy; correction reconcentrates it');
legend('Uncorrected', 'Autofocus corrected', 'Location', 'best');

%% Sweep 2: smooth versus short-correlated error at fixed RMS
composition_case_count = numel(random_fraction_sweep);
composition_blurred_peak = zeros(1, composition_case_count);
composition_corrected_peak = zeros(1, composition_case_count);
composition_residual_phase_rmse_rad = zeros(1, composition_case_count);
composition_max_increment_rad = zeros(1, composition_case_count);
for case_index = 1:composition_case_count
    case_template = mix_error_templates(smooth_error_template, ...
        short_correlated_error_template, random_fraction_sweep(case_index));
    case_path_error_m = baseline_error_rms_fraction*wavelength_m* ...
        case_template;
    case_phase_error_rad = -4*pi*case_path_error_m/wavelength_m;
    composition_max_increment_rad(case_index) = ...
        max(abs(diff(case_phase_error_rad)));
    assert(composition_max_increment_rad(case_index) < ...
        maximum_phase_increment_rad, 'P80:CompositionSweepSampling', ...
        'Composition sweep exceeded the phase-gradient sampling bound.');
    case_history = apply_phase_screen(ideal_signal_history, ...
        measurement_noise, case_phase_error_rad);
    [case_blurred_gates, operation_count] = focus_history( ...
        case_history, platform_position_m, image_cross_range_m, ...
        target_ground_range_m, scene_reference_range_m, wavelength_m, ...
        maximum_focus_operations);
    executed_focus_operations = executed_focus_operations+operation_count;
    case_phase_estimate_rad = estimate_phase_gradient( ...
        case_history(:, reference_gate_index), platform_position_m, ...
        target_cross_range_m(reference_gate_index), ...
        target_ground_range_m(reference_gate_index), ...
        scene_reference_range_m, wavelength_m);
    case_corrected_history = case_history.*repmat( ...
        exp(-1j*case_phase_estimate_rad(:)), 1, numel(target_voltage));
    [case_corrected_gates, operation_count] = focus_history( ...
        case_corrected_history, platform_position_m, image_cross_range_m, ...
        target_ground_range_m, scene_reference_range_m, wavelength_m, ...
        maximum_focus_operations);
    executed_focus_operations = executed_focus_operations+operation_count;
    case_blurred_metrics = focus_metrics(image_cross_range_m, ...
        case_blurred_gates, ideal_focused_gates);
    case_corrected_metrics = focus_metrics(image_cross_range_m, ...
        case_corrected_gates, ideal_focused_gates);
    composition_blurred_peak(case_index) = ...
        case_blurred_metrics.mean_peak_retention;
    composition_corrected_peak(case_index) = ...
        case_corrected_metrics.mean_peak_retention;
    composition_residual_phase_rmse_rad(case_index) = centered_rmse( ...
        case_phase_estimate_rad, case_phase_error_rad);
end
assert(max(composition_corrected_peak-composition_blurred_peak) > 0.60 && ...
    all(composition_corrected_peak > 0.95) && ...
    all(composition_residual_phase_rmse_rad < 0.05), ...
    'P80:ErrorCompositionSweep', ...
    'Autofocus must recover both smooth and short-correlated reviewed errors.');

figure('Name', 'P80 smooth and random motion-error sweep', ...
    'Tag', 'P80', 'NumberTitle', 'off');
subplot(1, 2, 1);
plot(random_fraction_sweep, composition_blurred_peak, ...
    'ro-', 'LineWidth', 1.2);
hold on;
plot(random_fraction_sweep, composition_corrected_peak, ...
    'bs-', 'LineWidth', 1.2);
grid on;
xlabel('Short-correlated fraction at fixed lambda/8 RMS');
ylabel('Mean coherent peak / ideal peak');
title('Equal RMS does not imply equal blur shape');
legend('Uncorrected', 'Autofocus corrected', 'Location', 'best');
subplot(1, 2, 2);
plot(random_fraction_sweep, composition_max_increment_rad, ...
    'kd-', 'LineWidth', 1.2);
hold on;
plot([0 1], [maximum_phase_increment_rad maximum_phase_increment_rad], ...
    'r--', 'LineWidth', 1.0);
grid on;
xlabel('Short-correlated fraction');
ylabel('Maximum adjacent phase step (rad)');
title('Phase-gradient sampling margin');
legend('Measured', 'Reviewed bound', 'Location', 'best');

%% Intentionally broken autofocus: contaminate the reference range gate
measurement_before_failure = retained_errored_history;
broken_reference_history = retained_errored_history(:, reference_gate_index)+ ...
    broken_interferer_voltage*retained_errored_history(:, 2);
broken_phase_estimate_rad = estimate_phase_gradient( ...
    broken_reference_history, platform_position_m, ...
    target_cross_range_m(reference_gate_index), ...
    target_ground_range_m(reference_gate_index), ...
    scene_reference_range_m, wavelength_m);
broken_corrected_history = retained_errored_history.*repmat( ...
    exp(-1j*broken_phase_estimate_rad(:)), 1, numel(target_voltage));
[broken_focused_gates, operation_count] = focus_history( ...
    broken_corrected_history, platform_position_m, image_cross_range_m, ...
    target_ground_range_m, scene_reference_range_m, wavelength_m, ...
    maximum_focus_operations);
executed_focus_operations = executed_focus_operations+operation_count;
broken_metrics = focus_metrics(image_cross_range_m, broken_focused_gates, ...
    ideal_focused_gates);

% Recovery starts again from the unchanged errored measurement and the
% isolated strong range gate. It does not sharpen the broken image.
recovery_phase_estimate_rad = estimate_phase_gradient( ...
    retained_errored_history(:, reference_gate_index), ...
    platform_position_m, target_cross_range_m(reference_gate_index), ...
    target_ground_range_m(reference_gate_index), scene_reference_range_m, ...
    wavelength_m);
recovered_history = retained_errored_history.*repmat( ...
    exp(-1j*recovery_phase_estimate_rad(:)), 1, numel(target_voltage));
[recovered_focused_gates, operation_count] = focus_history( ...
    recovered_history, platform_position_m, image_cross_range_m, ...
    target_ground_range_m, scene_reference_range_m, wavelength_m, ...
    maximum_focus_operations);
executed_focus_operations = executed_focus_operations+operation_count;
recovered_metrics = focus_metrics(image_cross_range_m, ...
    recovered_focused_gates, ideal_focused_gates);
recovery_exact_match = isequaln(recovery_phase_estimate_rad, ...
    baseline_phase_estimate_rad) && isequaln(recovered_focused_gates, ...
    corrected_focused_gates);
assert(isequaln(measurement_before_failure, retained_errored_history) && ...
    broken_metrics.mean_peak_retention < ...
    recovered_metrics.mean_peak_retention-0.08 && recovery_exact_match, ...
    'P80:ContaminatedReferenceRecovery', ...
    'A contaminated reference must underperform fresh isolated-gate recovery.');

[broken_image, operation_count] = compose_range_cross_range_image( ...
    broken_focused_gates, image_range_offset_m, target_range_offset_m, ...
    bandwidth_hz, frequency_sample_count, speed_of_light_mps, ...
    maximum_focus_operations);
executed_focus_operations = executed_focus_operations+operation_count;
[recovered_image, operation_count] = compose_range_cross_range_image( ...
    recovered_focused_gates, image_range_offset_m, target_range_offset_m, ...
    bandwidth_hz, frequency_sample_count, speed_of_light_mps, ...
    maximum_focus_operations);
executed_focus_operations = executed_focus_operations+operation_count;

figure('Name', 'P80 contaminated autofocus gate and recovery', ...
    'Tag', 'P80', 'NumberTitle', 'off');
subplot(2, 2, 1);
show_image(image_cross_range_m, image_range_offset_m, broken_image, ...
    target_cross_range_m, target_range_offset_m, display_floor_db, ...
    sprintf('Broken mixed gate: peak %.2f', ...
    broken_metrics.mean_peak_retention));
subplot(2, 2, 2);
show_image(image_cross_range_m, image_range_offset_m, recovered_image, ...
    target_cross_range_m, target_range_offset_m, display_floor_db, ...
    sprintf('Recovered isolated gate: peak %.2f', ...
    recovered_metrics.mean_peak_retention));
subplot(2, 2, [3 4]);
plot(platform_position_m, centered(baseline_phase_error_rad), ...
    'k-', 'LineWidth', 1.2);
hold on;
