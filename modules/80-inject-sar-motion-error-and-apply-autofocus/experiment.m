    value = c.(vectors{index});
    assert(isnumeric(value) && isreal(value) && isrow(value) && ...
        ~isempty(value) && all(isfinite(value)), ...
        'P80:InvalidVector', '%s must be a finite real row vector.', ...
        vectors{index});
end
scalars = {'c_mps', 'carrier_hz', 'reference_range_m', 'bandwidth_hz', ...
    'frequency_samples', 'aperture_length_m', 'platform_spacing_m', ...
    'reference_gate', 'measurement_snr_db', 'baseline_error_fraction', ...
    'baseline_random_fraction', 'broken_interferer_voltage', ...
    'display_floor_db', 'max_aperture_samples', 'max_image_x_samples', ...
    'max_image_range_samples', 'max_frequency_samples', 'max_targets', ...
    'max_sweep_cases', 'max_private_values', 'max_focus_operations', ...
    'max_working_values', 'max_figures', 'max_phase_increment_rad'};
for index = 1:numel(scalars)
    value = c.(scalars{index});
    assert(isnumeric(value) && isreal(value) && isscalar(value) && ...
        isfinite(value), 'P80:InvalidScalar', ...
        '%s must be a finite real scalar.', scalars{index});
end
assert(isnumeric(c.seed) && isreal(c.seed) && isscalar(c.seed) && ...
    isfinite(c.seed) && c.seed == floor(c.seed) && c.seed >= 1 && ...
    c.seed < 2147483647, 'P80:InvalidSeed', ...
    'Seed must be an integer in the Park-Miller interval.');
positive_scalars = {'c_mps', 'carrier_hz', 'reference_range_m', ...
    'bandwidth_hz', 'frequency_samples', 'aperture_length_m', ...
    'platform_spacing_m', 'reference_gate', 'measurement_snr_db', ...
    'baseline_error_fraction', 'broken_interferer_voltage', ...
    'max_aperture_samples', 'max_image_x_samples', ...
    'max_image_range_samples', 'max_frequency_samples', 'max_targets', ...
    'max_sweep_cases', 'max_private_values', 'max_focus_operations', ...
    'max_working_values', 'max_figures', 'max_phase_increment_rad'};
for index = 1:numel(positive_scalars)
    assert(c.(positive_scalars{index}) > 0, 'P80:NonpositiveControl', ...
        '%s must be positive.', positive_scalars{index});
end
integer_scalars = {'frequency_samples', 'reference_gate', ...
    'max_aperture_samples', 'max_image_x_samples', ...
    'max_image_range_samples', 'max_frequency_samples', 'max_targets', ...
    'max_sweep_cases', 'max_private_values', 'max_focus_operations', ...
    'max_working_values', 'max_figures'};
for index = 1:numel(integer_scalars)
    assert(c.(integer_scalars{index}) == floor(c.(integer_scalars{index})), ...
        'P80:NonintegerControl', '%s must be an integer.', ...
        integer_scalars{index});
end
assert(c.frequency_samples >= 3 && mod(c.frequency_samples, 2) == 1, ...
    'P80:FrequencySamples', ...
    'Frequency count must be odd and at least three.');
assert(c.display_floor_db < 0 && c.baseline_random_fraction >= 0 && ...
    c.baseline_random_fraction <= 1, 'P80:FractionControl', ...
    'Display floor and mixture fraction are invalid.');
assert(all(diff(c.image_x_m) > 0) && ...
    all(diff(c.image_range_offset_m) > 0) && ...
    all(diff(c.error_fraction_sweep) > 0) && ...
    all(diff(c.random_fraction_sweep) > 0), 'P80:Ordering', ...
    'Axes and sweeps must be strictly increasing.');
assert(all(c.error_fraction_sweep >= 0) && ...
    c.error_fraction_sweep(1) == 0 && ...
    all(c.random_fraction_sweep >= 0) && ...
    all(c.random_fraction_sweep <= 1) && ...
    c.random_fraction_sweep(1) == 0 && ...
    c.random_fraction_sweep(end) == 1, 'P80:SweepSupport', ...
    'Sweeps must cover their reviewed nonnegative supports.');
target_count = numel(c.target_x_m);
assert(target_count == numel(c.target_range_offset_m) && ...
    target_count == numel(c.target_voltage) && ...
    all(c.target_voltage > 0), 'P80:TargetScene', ...
    'Target vectors must have equal length and positive voltage.');
assert(c.reference_gate <= target_count && ...
    c.target_voltage(c.reference_gate) == max(c.target_voltage), ...
    'P80:ReferenceGate', ...
    'Reference gate must select the strongest target.');
assert(all(c.reference_range_m+c.target_range_offset_m > 0) && ...
    all(c.target_x_m >= c.image_x_m(1)) && ...
    all(c.target_x_m <= c.image_x_m(end)) && ...
    all(c.target_range_offset_m >= c.image_range_offset_m(1)) && ...
    all(c.target_range_offset_m <= c.image_range_offset_m(end)), ...
    'P80:SceneSupport', 'Targets must lie inside positive scene support.');
aperture_ratio = c.aperture_length_m/c.platform_spacing_m;
assert(abs(aperture_ratio-round(aperture_ratio)) < 1.0e-10, ...
    'P80:OffGridAperture', ...
    'Platform spacing must include both reviewed endpoints.');
aperture_count = round(aperture_ratio)+1;
assert(aperture_count <= c.max_aperture_samples && ...
    numel(c.image_x_m) <= c.max_image_x_samples && ...
    numel(c.image_range_offset_m) <= c.max_image_range_samples && ...
    c.frequency_samples <= c.max_frequency_samples && ...
    target_count <= c.max_targets && ...
    max(numel(c.error_fraction_sweep), ...
    numel(c.random_fraction_sweep)) <= c.max_sweep_cases && ...
    2*aperture_count*target_count <= c.max_private_values, ...
    'P80:ResourceCeiling', ...
    'Sample, target, sweep, or private-generator ceiling exceeded.');
focus_count = 3+2*numel(c.error_fraction_sweep)+ ...
    2*numel(c.random_fraction_sweep)+2;
image_count = 5;
predicted_operations = focus_count*aperture_count* ...
    numel(c.image_x_m)*target_count+image_count* ...
    numel(c.image_range_offset_m)*target_count* ...
    (c.frequency_samples+numel(c.image_x_m));
assert(predicted_operations <= c.max_focus_operations, ...
    'P80:OperationCeiling', ...
    'Reviewed coherent contribution count exceeds the ceiling.');
end

function history = synthesize_history(platform_m, target_x_m, ...
    target_range_m, reflectivity, reference_range_m, wavelength_m)
history = zeros(numel(platform_m), numel(target_x_m));
for target_index = 1:numel(target_x_m)
    slant_range_m = sqrt((platform_m-target_x_m(target_index)).^2+ ...
        target_range_m(target_index)^2);
    propagation_phase_rad = -4*pi*(slant_range_m-reference_range_m)/ ...
        wavelength_m;
    history(:, target_index) = (reflectivity(target_index)* ...
        exp(1j*propagation_phase_rad)).';
end
end

function errored_history = apply_phase_screen(signal_history, noise, phase_rad)
assert(isvector(phase_rad) && numel(phase_rad) == size(signal_history, 1), ...
    'P80:PhaseScreenShape', ...
    'Phase screen must have one value per aperture sample.');
assert(isequal(size(signal_history), size(noise)) && ...
    all(isfinite(real(signal_history(:)))) && ...
    all(isfinite(imag(signal_history(:)))) && ...
    all(isfinite(real(noise(:)))) && all(isfinite(imag(noise(:)))) && ...
    all(isfinite(phase_rad)), 'P80:PhaseScreenInput', ...
    'History, noise, and phase screen must be finite and compatible.');
errored_history = signal_history.*repmat(exp(1j*phase_rad(:)), ...
    1, size(signal_history, 2))+noise;
end

function [focused_gates, operations] = focus_history(history, platform_m, ...
    candidate_x_m, target_range_m, reference_range_m, wavelength_m, ...
    operation_ceiling)
assert(size(history, 1) == numel(platform_m) && ...
    size(history, 2) == numel(target_range_m) && ...
    isrow(platform_m) && isrow(candidate_x_m) && ...
    isrow(target_range_m), 'P80:FocusShape', ...
    'Focus inputs have incompatible dimensions.');
operations = numel(history)*numel(candidate_x_m);
assert(operations <= operation_ceiling, 'P80:FocusCallCeiling', ...
    'One focus request exceeds the operation ceiling.');
focused_gates = zeros(numel(target_range_m), numel(candidate_x_m));
for target_index = 1:numel(target_range_m)
    for candidate_index = 1:numel(candidate_x_m)
        predicted_slant_range_m = sqrt((platform_m- ...
            candidate_x_m(candidate_index)).^2+target_range_m(target_index)^2);
        path_compensation = exp(1j*4*pi*(predicted_slant_range_m- ...
            reference_range_m)/wavelength_m);
        focused_gates(target_index, candidate_index) = mean( ...
            history(:, target_index).'.*path_compensation);
    end
end
end

function [phase_estimate_rad, phase_increment_rad] = ...
    estimate_phase_gradient(reference_history, platform_m, reference_x_m, ...
    reference_range_m, scene_reference_range_m, wavelength_m)
assert(isvector(reference_history) && ...
    numel(reference_history) == numel(platform_m) && ...
    all(isfinite(real(reference_history))) && ...
    all(isfinite(imag(reference_history))), 'P80:AutofocusInput', ...
    'Autofocus reference must be one finite aperture vector.');
nominal_slant_range_m = sqrt((platform_m-reference_x_m).^2+ ...
    reference_range_m^2);
nominally_deramped = reference_history(:).'.*exp(1j*4*pi* ...
    (nominal_slant_range_m-scene_reference_range_m)/wavelength_m);
assert(all(abs(nominally_deramped) > eps), 'P80:AutofocusNull', ...
    'The reference history must not contain a zero-magnitude sample.');
phase_increment_rad = angle(nominally_deramped(2:end).* ...
    conj(nominally_deramped(1:end-1)));
phase_estimate_rad = zeros(size(nominally_deramped));
phase_estimate_rad(1) = angle(nominally_deramped(1));
phase_estimate_rad(2:end) = phase_estimate_rad(1)+ ...
    cumsum(phase_increment_rad);
end

function [image, operations] = compose_range_cross_range_image( ...
    focused_gates, range_axis_m, target_range_offset_m, bandwidth_hz, ...
    frequency_count, c_mps, operation_ceiling)
assert(size(focused_gates, 1) == numel(target_range_offset_m), ...
    'P80:ImageShape', 'Each target needs one focused range gate.');
range_sum_operations = numel(range_axis_m)*frequency_count* ...
    numel(target_range_offset_m);
image_sum_operations = numel(range_axis_m)*size(focused_gates, 2)* ...
    numel(target_range_offset_m);
operations = range_sum_operations+image_sum_operations;
assert(operations <= operation_ceiling, 'P80:ImageCallCeiling', ...
    'One image composition request exceeds the operation ceiling.');
frequency_offset_hz = linspace(-bandwidth_hz/2, bandwidth_hz/2, ...
    frequency_count).';
image = zeros(numel(range_axis_m), size(focused_gates, 2));
for target_index = 1:numel(target_range_offset_m)
    range_offset_m = range_axis_m-target_range_offset_m(target_index);
    frequency_contributions = exp(1j*4*pi*frequency_offset_hz* ...
        range_offset_m/c_mps);
    range_response = mean(frequency_contributions, 1).';
    image = image+range_response*focused_gates(target_index, :);
end
end

function metrics = focus_metrics(axis_m, focused_gates, ideal_gates)
assert(isequal(size(focused_gates), size(ideal_gates)) && ...
    size(focused_gates, 2) == numel(axis_m), ...
    'P80:MetricShape', 'Focused and ideal gates must share one axis.');
target_count = size(focused_gates, 1);
peak_retention = zeros(1, target_count);
entropy_nats = zeros(1, target_count);
half_power_width_m = zeros(1, target_count);
for target_index = 1:target_count
    magnitude = abs(focused_gates(target_index, :));
    ideal_magnitude = abs(ideal_gates(target_index, :));
    peak_retention(target_index) = max(magnitude)/max(ideal_magnitude);
    intensity = magnitude.^2;
    probability = intensity/sum(intensity);
    entropy_nats(target_index) = -sum(probability.* ...
        log(max(probability, realmin)));
    half_power_width_m(target_index) = measure_half_power_width( ...
        axis_m, magnitude);
end
metrics = struct('peak_retention', peak_retention, ...
    'entropy_nats', entropy_nats, ...
    'half_power_width_m', half_power_width_m, ...
    'mean_peak_retention', mean(peak_retention), ...
    'mean_entropy', mean(entropy_nats));
end

function width_m = measure_half_power_width(axis_m, magnitude)
[peak, peak_index] = max(magnitude);
normalized = magnitude/peak;
threshold = 1/sqrt(2);
left_index = find(normalized(1:peak_index) <= threshold, 1, 'last');
right_relative = find(normalized(peak_index:end) <= threshold, 1, 'first');
assert(~isempty(left_index) && ~isempty(right_relative) && ...
    left_index < peak_index && right_relative > 1, ...
    'P80:HalfPowerSupport', ...
    'Image axis does not contain both half-power crossings.');
right_index = peak_index+right_relative-1;
left_crossing = linear_crossing(axis_m(left_index), ...
    normalized(left_index), axis_m(left_index+1), ...
    normalized(left_index+1), threshold);
right_crossing = linear_crossing(axis_m(right_index-1), ...
    normalized(right_index-1), axis_m(right_index), ...
    normalized(right_index), threshold);
width_m = right_crossing-left_crossing;
end

function crossing = linear_crossing(x1, y1, x2, y2, level)
assert(y2 ~= y1, 'P80:CrossingSlope', ...
    'Half-power interpolation needs a nonzero slope.');
crossing = x1+(level-y1)*(x2-x1)/(y2-y1);
end

