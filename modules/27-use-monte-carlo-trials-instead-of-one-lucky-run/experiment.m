results = struct();

%% Deterministic independent BPSK trials and explicit matched filter
% b_k is either -1 or +1. The unit-energy pulse p obeys sum(p.^2)=1.
% r_k = sqrt(E_b)*b_k*p + sigma*w_k
% z_k = p.'*r_k; decide +1 when z_k >= 0 and -1 otherwise.
private_stream = RandStream('mt19937ar', 'Seed', random_seed);
transmitted_symbols = 2*double(rand(private_stream, 1, symbol_count) >= 0.5)-1;
noise_unit = randn(private_stream, samples_per_symbol, symbol_count);
pulse = ones(samples_per_symbol, 1)/sqrt(samples_per_symbol);
baseline_eb_n0_linear = 10^(baseline_eb_n0_db/10);
baseline_noise_std = sqrt(bit_energy/(2*baseline_eb_n0_linear));
transmitted_waveforms = sqrt(bit_energy)*pulse*transmitted_symbols;
received_waveforms = transmitted_waveforms + baseline_noise_std*noise_unit;
matched_filter_statistic = pulse.'*received_waveforms;
detected_symbols = ones(1, symbol_count);
detected_symbols(matched_filter_statistic < 0) = -1;
error_outcomes = detected_symbols ~= transmitted_symbols;

assert(abs(sum(pulse.^2)-1) < 1e-12, ...
    'The explicit pulse must retain one normalized energy unit.');
assert(all(transmitted_symbols == -1 | transmitted_symbols == 1) && ...
    all(detected_symbols == -1 | detected_symbols == 1) && ...
    all(error_outcomes == 0 | error_outcomes == 1), ...
    'BPSK symbols and Bernoulli error outcomes must retain their domains.');

baseline_error_count = sum(error_outcomes);
baseline_empirical_ber = baseline_error_count/symbol_count;
baseline_analytic_ber = 0.5*erfc(sqrt(baseline_eb_n0_linear));

%% Running probability and explicit 95 percent Wilson interval
% For k errors in N independent Bernoulli trials, p_hat=k/N. Wilson limits:
% (p_hat+z^2/(2N) +/- z*sqrt(p_hat*(1-p_hat)/N+z^2/(4N^2)))
% divided by (1+z^2/N).
trial_index = 1:symbol_count;
running_error_count = cumsum(double(error_outcomes));
running_ber = running_error_count./trial_index;
running_denominator = 1 + confidence_z^2./trial_index;
running_center = (running_ber + confidence_z^2./(2*trial_index))./ ...
    running_denominator;
running_half_width = confidence_z./running_denominator.*sqrt( ...
    running_ber.*(1-running_ber)./trial_index + ...
    confidence_z^2./(4*trial_index.^2));
running_ci_lower = max(0, running_center-running_half_width);
running_ci_upper = min(1, running_center+running_half_width);

baseline_ci_lower = running_ci_lower(end);
baseline_ci_upper = running_ci_upper(end);
assert(baseline_error_count > 0 && baseline_error_count < symbol_count && ...
    abs(baseline_empirical_ber-baseline_analytic_ber) < 0.03, ...
    'The deterministic baseline must contain errors and approach AWGN theory.');

%% Final empirical distributions without a statistics toolbox
block_error_rates = mean(reshape(double(error_outcomes), ...
    block_length, symbol_count/block_length), 1);
decision_bin_centers = ...
    (decision_bin_edges(1:end-1)+decision_bin_edges(2:end))/2;
negative_symbol_counts = zeros(1, numel(decision_bin_centers));
positive_symbol_counts = zeros(1, numel(decision_bin_centers));
for bin_index = 1:numel(decision_bin_centers)
    if bin_index == 1
        % The first display bin absorbs the unbounded lower AWGN tail.
        in_bin = matched_filter_statistic < decision_bin_edges(bin_index+1);
    elseif bin_index < numel(decision_bin_centers)
        in_bin = matched_filter_statistic >= decision_bin_edges(bin_index) & ...
            matched_filter_statistic < decision_bin_edges(bin_index+1);
    else
        % The last display bin absorbs the unbounded upper AWGN tail.
        in_bin = matched_filter_statistic >= decision_bin_edges(bin_index);
    end
    negative_symbol_counts(bin_index) = ...
        sum(in_bin & transmitted_symbols == -1);
    positive_symbol_counts(bin_index) = ...
        sum(in_bin & transmitted_symbols == 1);
end
negative_symbol_probability = negative_symbol_counts/ ...
    sum(transmitted_symbols == -1);
positive_symbol_probability = positive_symbol_counts/ ...
    sum(transmitted_symbols == 1);
assert(sum(negative_symbol_counts) == sum(transmitted_symbols == -1) && ...
    sum(positive_symbol_counts) == sum(transmitted_symbols == 1) && ...
    abs(sum(negative_symbol_probability)-1) < 1e-12 && ...
    abs(sum(positive_symbol_probability)-1) < 1e-12, ...
    'Decision-statistic display bins must retain all empirical probability mass.');

block_ber_bin_centers = ...
    (block_ber_bin_edges(1:end-1)+block_ber_bin_edges(2:end))/2;
block_ber_counts = zeros(size(block_ber_bin_centers));
for bin_index = 1:numel(block_ber_bin_centers)
    if bin_index == 1
        in_bin = block_error_rates < block_ber_bin_edges(bin_index+1);
    elseif bin_index < numel(block_ber_bin_centers)
        in_bin = block_error_rates >= block_ber_bin_edges(bin_index) & ...
            block_error_rates < block_ber_bin_edges(bin_index+1);
    else
        in_bin = block_error_rates >= block_ber_bin_edges(bin_index);
    end
    block_ber_counts(bin_index) = sum(in_bin);
end
block_ber_probability = block_ber_counts/numel(block_error_rates);
assert(sum(block_ber_counts) == numel(block_error_rates) && ...
    abs(sum(block_ber_probability)-1) < 1e-12, ...
    'Block-BER display bins must retain all empirical probability mass.');

%% Sweep 1: change only the number of independent baseline trials
trial_sweep_empirical_ber = zeros(size(trial_count_sweep));
trial_sweep_ci_lower = zeros(size(trial_count_sweep));
trial_sweep_ci_upper = zeros(size(trial_count_sweep));
for sweep_index = 1:numel(trial_count_sweep)
    prefix_count = trial_count_sweep(sweep_index);
    prefix_errors = sum(error_outcomes(1:prefix_count));
    prefix_ber = prefix_errors/prefix_count;
    prefix_denominator = 1 + confidence_z^2/prefix_count;
    prefix_center = (prefix_ber + confidence_z^2/(2*prefix_count))/ ...
        prefix_denominator;
    prefix_half_width = confidence_z/prefix_denominator*sqrt( ...
        prefix_ber*(1-prefix_ber)/prefix_count + ...
        confidence_z^2/(4*prefix_count^2));
    trial_sweep_empirical_ber(sweep_index) = prefix_ber;
    trial_sweep_ci_lower(sweep_index) = max(0, prefix_center-prefix_half_width);
    trial_sweep_ci_upper(sweep_index) = min(1, prefix_center+prefix_half_width);
end
trial_sweep_ci_width = trial_sweep_ci_upper-trial_sweep_ci_lower;
assert(trial_sweep_ci_width(end) < trial_sweep_ci_width(1), ...
    'More independent trials should narrow this deterministic Wilson interval.');

%% Sweep 2: change only Eb/N0 on the same symbols and unit-noise samples
% Common random numbers keep the comparison paired and controlled: only the
% noise standard deviation changes between these bounded sweep cases.
snr_sweep_empirical_ber = zeros(size(eb_n0_db_sweep));
snr_sweep_analytic_ber = zeros(size(eb_n0_db_sweep));
snr_sweep_ci_lower = zeros(size(eb_n0_db_sweep));
snr_sweep_ci_upper = zeros(size(eb_n0_db_sweep));
for sweep_index = 1:numel(eb_n0_db_sweep)
    sweep_eb_n0_linear = 10^(eb_n0_db_sweep(sweep_index)/10);
    sweep_noise_std = sqrt(bit_energy/(2*sweep_eb_n0_linear));
    sweep_received = transmitted_waveforms + sweep_noise_std*noise_unit;
    sweep_statistic = pulse.'*sweep_received;
    sweep_detected = ones(1, symbol_count);
    sweep_detected(sweep_statistic < 0) = -1;
    sweep_errors = sweep_detected ~= transmitted_symbols;
    sweep_error_count = sum(sweep_errors);
    sweep_ber = sweep_error_count/symbol_count;
    sweep_denominator = 1 + confidence_z^2/symbol_count;
    sweep_center = (sweep_ber + confidence_z^2/(2*symbol_count))/ ...
        sweep_denominator;
    sweep_half_width = confidence_z/sweep_denominator*sqrt( ...
        sweep_ber*(1-sweep_ber)/symbol_count + ...
        confidence_z^2/(4*symbol_count^2));
    snr_sweep_empirical_ber(sweep_index) = sweep_ber;
    snr_sweep_analytic_ber(sweep_index) = ...
        0.5*erfc(sqrt(sweep_eb_n0_linear));
    snr_sweep_ci_lower(sweep_index) = max(0, sweep_center-sweep_half_width);
    snr_sweep_ci_upper(sweep_index) = min(1, sweep_center+sweep_half_width);
end
assert(all(diff(snr_sweep_empirical_ber) <= 0) && ...
    all(diff(snr_sweep_analytic_ber) < 0), ...
    'BER should fall across the fixed-noise Eb/N0 sweep.');

%% Intentionally broken case: call one lucky realization 4000 trials
% This is pseudo-replication. Repeating one correct waveform does not create
% independent evidence, so the binomial/Wilson interpretation is invalid.
lucky_trial_index = find(~error_outcomes, 1, 'first');
assert(~isempty(lucky_trial_index), ...
    'The deterministic record must contain a correct trial to expose reuse.');
broken_transmitted_symbols = repmat( ...
    transmitted_symbols(lucky_trial_index), 1, broken_repeat_count);
broken_received_waveforms = repmat( ...
    received_waveforms(:, lucky_trial_index), 1, broken_repeat_count);
broken_statistic = pulse.'*broken_received_waveforms;
broken_detected_symbols = ones(1, broken_repeat_count);
broken_detected_symbols(broken_statistic < 0) = -1;
broken_error_outcomes = ...
    broken_detected_symbols ~= broken_transmitted_symbols;
broken_empirical_ber = mean(double(broken_error_outcomes));
broken_unique_statistic_count = numel(unique(broken_statistic));
broken_denominator = 1 + confidence_z^2/broken_repeat_count;
broken_center = (broken_empirical_ber + ...
    confidence_z^2/(2*broken_repeat_count))/broken_denominator;
broken_half_width = confidence_z/broken_denominator*sqrt( ...
    broken_empirical_ber*(1-broken_empirical_ber)/broken_repeat_count + ...
    confidence_z^2/(4*broken_repeat_count^2));
broken_nominal_ci_lower = max(0, broken_center-broken_half_width);
broken_nominal_ci_upper = min(1, broken_center+broken_half_width);
broken_independence_valid = false;
assert(broken_empirical_ber == 0 && ...
    broken_unique_statistic_count == 1 && ...
    baseline_analytic_ber > broken_nominal_ci_upper && ...
    ~broken_independence_valid, ...
    'The broken case must expose false certainty from one reused trial.');

%% Recovery: rebuild the independent bank from a fresh private stream
recovery_stream = RandStream('mt19937ar', 'Seed', random_seed);
recovery_symbols = 2*double(rand(recovery_stream, 1, symbol_count) >= 0.5)-1;
recovery_noise_unit = randn(recovery_stream, ...
    samples_per_symbol, symbol_count);
recovery_received = sqrt(bit_energy)*pulse*recovery_symbols + ...
    baseline_noise_std*recovery_noise_unit;
recovery_statistic = pulse.'*recovery_received;
recovery_detected = ones(1, symbol_count);
recovery_detected(recovery_statistic < 0) = -1;
recovery_errors = recovery_detected ~= recovery_symbols;
recovery_exact_match = isequal(recovery_symbols, transmitted_symbols) && ...
    isequal(recovery_noise_unit, noise_unit) && ...
    isequal(recovery_statistic, matched_filter_statistic) && ...
    isequal(recovery_errors, error_outcomes);
assert(recovery_exact_match, ...
    'A clean private-seed rerun must exactly reproduce the baseline trials.');

