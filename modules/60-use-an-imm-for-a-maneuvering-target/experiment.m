%% P60 - Use an IMM for a Maneuvering Target
% How can a tracker adapt when the target alternates between straight motion
% and maneuvers? This base-MATLAB experiment exposes every interaction,
% prediction, correction, likelihood, and combination step.

clear;
clc;
close(findall(0, 'Type', 'figure', 'Tag', 'P60'));

%% Visible reviewed controls and immutable resource ceilings
baseline_seed = 6007;
number_scans = 60;
sample_interval_s = 1.0;
position_noise_sigma_m = 10.0;
maneuver_acceleration_mps2 = 2.0;
steady_acceleration_sigma_mps2 = 0.35;
maneuver_jerk_sigma_mps3 = 0.80;
mode_stay_probability = 0.94;
initial_mode_probability = [0.85; 0.15]; % [straight; maneuver]

maneuver_acceleration_sweep_mps2 = [0.8 2.0 3.2];
mode_stay_probability_sweep = [0.80 0.94 0.99];

maximum_scans = 60;
maximum_sweep_cases = 5;
maximum_model_updates = 1500;
maximum_random_values_per_scene = 120;
maximum_total_random_values = 480;
maximum_figures = 6;

controls = struct( ...
    'baseline_seed', baseline_seed, ...
    'number_scans', number_scans, ...
    'sample_interval_s', sample_interval_s, ...
    'position_noise_sigma_m', position_noise_sigma_m, ...
    'maneuver_acceleration_mps2', maneuver_acceleration_mps2, ...
    'steady_acceleration_sigma_mps2', steady_acceleration_sigma_mps2, ...
    'maneuver_jerk_sigma_mps3', maneuver_jerk_sigma_mps3, ...
    'mode_stay_probability', mode_stay_probability, ...
    'initial_mode_probability', initial_mode_probability, ...
    'maneuver_acceleration_sweep_mps2', maneuver_acceleration_sweep_mps2, ...
    'mode_stay_probability_sweep', mode_stay_probability_sweep, ...
    'maximum_scans', maximum_scans, ...
    'maximum_sweep_cases', maximum_sweep_cases, ...
    'maximum_model_updates', maximum_model_updates, ...
    'maximum_random_values_per_scene', maximum_random_values_per_scene, ...
    'maximum_total_random_values', maximum_total_random_values, ...
    'maximum_figures', maximum_figures);
validate_controls(controls);

baseline_transition_probability = [ ...
    mode_stay_probability, 1 - mode_stay_probability; ...
    1 - mode_stay_probability, mode_stay_probability];

%% Build one deterministic target record and its noisy Cartesian reports
baseline_scene = build_scene(controls, baseline_seed, ...
    maneuver_acceleration_mps2);

%% Baseline: explicit IMM against one poorly matched fixed model
baseline_imm = run_imm(baseline_scene.measurement_m, controls, ...
    baseline_transition_probability, initial_mode_probability);
baseline_fixed = run_fixed_steady_filter(baseline_scene.measurement_m, controls);

imm_metrics = score_track(baseline_imm.combined_state, baseline_scene);
fixed_metrics = score_track(baseline_fixed.state, baseline_scene);

mean_maneuver_probability = mean( ...
    baseline_imm.mode_probability(2,baseline_scene.is_maneuver));
mean_straight_probability = mean( ...
    baseline_imm.mode_probability(2,~baseline_scene.is_maneuver));

assert(mean_maneuver_probability > mean_straight_probability, ...
    'P60:ManeuverProbabilityDidNotRise');
assert(imm_metrics.position_rmse_m < fixed_metrics.position_rmse_m, ...
    'P60:IMMDidNotImproveOverallError');
assert(imm_metrics.maneuver_rmse_m < fixed_metrics.maneuver_rmse_m, ...
    'P60:IMMDidNotImproveManeuverError');
assert(max(abs(sum(baseline_imm.mode_probability,1) - 1)) < 1e-12, ...
    'P60:ModeProbabilityNormalization');

%% Sweep 1: maneuver strength, with identical normalized noise
acceleration_case_count = numel(maneuver_acceleration_sweep_mps2);
acceleration_imm_rmse_m = zeros(1, acceleration_case_count);
acceleration_fixed_rmse_m = zeros(1, acceleration_case_count);
acceleration_maneuver_probability = zeros(1, acceleration_case_count);
for case_index = 1:acceleration_case_count
    case_scene = build_scene(controls, baseline_seed, ...
        maneuver_acceleration_sweep_mps2(case_index));
    case_imm = run_imm(case_scene.measurement_m, controls, ...
        baseline_transition_probability, initial_mode_probability);
    case_fixed = run_fixed_steady_filter(case_scene.measurement_m, controls);
    case_imm_metrics = score_track(case_imm.combined_state, case_scene);
    case_fixed_metrics = score_track(case_fixed.state, case_scene);
    acceleration_imm_rmse_m(case_index) = case_imm_metrics.maneuver_rmse_m;
    acceleration_fixed_rmse_m(case_index) = case_fixed_metrics.maneuver_rmse_m;
    acceleration_maneuver_probability(case_index) = mean( ...
        case_imm.mode_probability(2,case_scene.is_maneuver));
end
assert(all(acceleration_imm_rmse_m < acceleration_fixed_rmse_m), ...
    'P60:AccelerationSweepIMMRegression');
assert(all(diff(acceleration_maneuver_probability) > 0), ...
    'P60:AccelerationSweepProbabilityDirection');

%% Sweep 2: mode persistence, changing only the transition matrix
persistence_case_count = numel(mode_stay_probability_sweep);
persistence_rmse_m = zeros(1, persistence_case_count);
persistence_switch_count = zeros(1, persistence_case_count);
persistence_maneuver_probability = zeros(1, persistence_case_count);
persistence_straight_probability = zeros(1, persistence_case_count);
for case_index = 1:persistence_case_count
    stay = mode_stay_probability_sweep(case_index);
    transition = [stay, 1 - stay; 1 - stay, stay];
    case_imm = run_imm(baseline_scene.measurement_m, controls, ...
        transition, initial_mode_probability);
    case_metrics = score_track(case_imm.combined_state, baseline_scene);
    persistence_rmse_m(case_index) = case_metrics.position_rmse_m;
    dominant_mode = 1 + (case_imm.mode_probability(2,:) > ...
        case_imm.mode_probability(1,:));
    persistence_switch_count(case_index) = sum(diff(dominant_mode) ~= 0);
    persistence_maneuver_probability(case_index) = mean( ...
        case_imm.mode_probability(2,baseline_scene.is_maneuver));
    persistence_straight_probability(case_index) = mean( ...
        case_imm.mode_probability(2,~baseline_scene.is_maneuver));
end
assert(persistence_switch_count(end) < persistence_switch_count(1), ...
    'P60:PersistenceSweepDidNotReduceModeSwitching');

%% Intentionally broken case: zero support makes one mode unreachable
broken_transition_probability = eye(2);
broken_initial_mode_probability = [1; 0];
broken_imm = run_imm(baseline_scene.measurement_m, controls, ...
    broken_transition_probability, broken_initial_mode_probability);
broken_metrics = score_track(broken_imm.combined_state, baseline_scene);
assert(max(broken_imm.mode_probability(2,:)) == 0, ...
    'P60:BrokenModeUnexpectedlyReachable');
assert(broken_metrics.position_rmse_m > imm_metrics.position_rmse_m, ...
    'P60:BrokenCaseNotVisible');

% Recovery uses the exact same measurement array; no new noise is generated.
recovered_imm = run_imm(baseline_scene.measurement_m, controls, ...
    baseline_transition_probability, initial_mode_probability);
recovery_exact = isequal(recovered_imm.combined_state, ...
    baseline_imm.combined_state) && ...
    isequal(recovered_imm.mode_probability, baseline_imm.mode_probability);
assert(recovery_exact, 'P60:RecoveryMustBeExact');

