%% Deterministic QPSK symbols and explicit pulse shapes
private_stream = RandStream('mt19937ar', 'Seed', random_seed);
qpsk_bits = double(rand(private_stream, 2, symbol_count) >= 0.5);
qpsk_i = 2*qpsk_bits(1, :) - 1;
qpsk_q = 2*qpsk_bits(2, :) - 1;
qpsk_symbols = (qpsk_i + 1j*qpsk_q)/sqrt(2);
ideal_qpsk_points = [-1-1j -1+1j 1-1j 1+1j]/sqrt(2);

upsampled_symbols = complex(zeros(1, symbol_count*samples_per_symbol));
upsampled_symbols(1:samples_per_symbol:end) = qpsk_symbols;

% A unit-energy rectangular pulse holds one symbol for one symbol interval.
rectangular_pulse = ones(1, samples_per_symbol)/sqrt(samples_per_symbol);

% Explicit root-raised-cosine equation in normalized symbol time x=t/T.
% The two branches replace removable 0/0 singularities at x=0 and
% x=+/-1/(4*rolloff); no rcosdesign or toolbox operation is hidden here.
rrc_time_symbols = ...
    (-baseline_span_symbols*samples_per_symbol/2: ...
    baseline_span_symbols*samples_per_symbol/2)/samples_per_symbol;
rrc_pulse = zeros(size(rrc_time_symbols));
for tap_index = 1:numel(rrc_time_symbols)
    x = rrc_time_symbols(tap_index);
    if abs(x) < 1e-12
        rrc_pulse(tap_index) = ...
            1 + baseline_rolloff*(4/pi - 1);
    elseif abs(abs(x) - 1/(4*baseline_rolloff)) < 1e-12
        rrc_pulse(tap_index) = baseline_rolloff/sqrt(2)*( ...
            (1 + 2/pi)*sin(pi/(4*baseline_rolloff)) + ...
            (1 - 2/pi)*cos(pi/(4*baseline_rolloff)));
    else
        rrc_pulse(tap_index) = ( ...
            sin(pi*x*(1-baseline_rolloff)) + ...
            4*baseline_rolloff*x*cos(pi*x*(1+baseline_rolloff)))/( ...
            pi*x*(1-(4*baseline_rolloff*x)^2));
    end
end
rrc_pulse = rrc_pulse/sqrt(sum(abs(rrc_pulse).^2));

% Matched filters are the conjugate time reversals of the transmit pulses.
rectangular_matched_filter = conj(fliplr(rectangular_pulse));
rrc_matched_filter = conj(fliplr(rrc_pulse));
rectangular_combined_pulse = conv(rectangular_pulse, ...
    rectangular_matched_filter);
rrc_combined_pulse = conv(rrc_pulse, rrc_matched_filter);

assert(abs(sum(abs(rectangular_pulse).^2)-1) < 1e-12 && ...
    abs(sum(abs(rrc_pulse).^2)-1) < 1e-12, ...
    'Both transmit pulses must have unit energy.');
assert(max(abs(rrc_pulse-conj(fliplr(rrc_matched_filter)))) < 1e-12, ...
    'The receiver filter must be the pulse conjugated and time reversed.');

%% Baseline: transmit, add white noise, matched-filter, and sample
rectangular_transmitted = conv(upsampled_symbols, rectangular_pulse);
rrc_transmitted = conv(upsampled_symbols, rrc_pulse);
max_waveform_samples = ...
    symbol_count*samples_per_symbol + ...
    max_span_symbols*samples_per_symbol + 1;
noise_unit = (randn(private_stream, 1, max_waveform_samples) + ...
    1j*randn(private_stream, 1, max_waveform_samples))/sqrt(2);
baseline_noise_sigma = sqrt(10^(-baseline_esn0_db/10));
rectangular_received = rectangular_transmitted + ...
    baseline_noise_sigma*noise_unit(1:numel(rectangular_transmitted));
rrc_received = rrc_transmitted + ...
    baseline_noise_sigma*noise_unit(1:numel(rrc_transmitted));

rectangular_matched_output = conv(rectangular_received, ...
    rectangular_matched_filter);
rrc_matched_output = conv(rrc_received, rrc_matched_filter);
rrc_noiseless_matched_output = conv(rrc_transmitted, rrc_matched_filter);

rectangular_total_group_delay = numel(rectangular_pulse)-1;
rrc_transmit_group_delay = (numel(rrc_pulse)-1)/2;
rrc_total_group_delay = numel(rrc_pulse)-1;
rectangular_sample_indices = 1 + rectangular_total_group_delay + ...
    (0:symbol_count-1)*samples_per_symbol;
rrc_pre_filter_sample_indices = 1 + rrc_transmit_group_delay + ...
    (0:symbol_count-1)*samples_per_symbol;
rrc_sample_indices = 1 + rrc_total_group_delay + ...
    (0:symbol_count-1)*samples_per_symbol;

rectangular_samples = ...
    rectangular_matched_output(rectangular_sample_indices);
rrc_pre_filter_samples = ...
    rrc_received(rrc_pre_filter_sample_indices)/ ...
    rrc_pulse(rrc_transmit_group_delay+1);
rrc_samples = rrc_matched_output(rrc_sample_indices);
rrc_noiseless_samples = ...
    rrc_noiseless_matched_output(rrc_sample_indices);

valid_symbol_indices = ...
    baseline_span_symbols+1:symbol_count-baseline_span_symbols;
valid_reference = qpsk_symbols(valid_symbol_indices);
rectangular_evm_pct = 100*sqrt(mean(abs( ...
    rectangular_samples(valid_symbol_indices)-valid_reference).^2));
rrc_pre_filter_evm_pct = 100*sqrt(mean(abs( ...
    rrc_pre_filter_samples(valid_symbol_indices)-valid_reference).^2));
rrc_matched_evm_pct = 100*sqrt(mean(abs( ...
    rrc_samples(valid_symbol_indices)-valid_reference).^2));
rrc_isi_only_evm_pct = 100*sqrt(mean(abs( ...
    rrc_noiseless_samples(valid_symbol_indices)-valid_reference).^2));

