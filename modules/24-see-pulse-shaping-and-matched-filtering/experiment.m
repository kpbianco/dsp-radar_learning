fprintf('  99%% BW (R_s):   %s\n', ...
    mat2str(rolloff_sweep_bandwidth_rs, 4));
fprintf('  ISI EVM (%%):    %s\n', ...
    mat2str(rolloff_sweep_isi_evm_pct, 4));

%% Sweep 2: change finite RRC span only at fixed roll-off
span_sweep_isi_evm_pct = zeros(size(span_sweep_symbols));
span_sweep_tap_counts = zeros(size(span_sweep_symbols));
for sweep_index = 1:numel(span_sweep_symbols)
    case_span_symbols = span_sweep_symbols(sweep_index);
    case_rolloff = baseline_rolloff;
    case_time_symbols = ...
        (-case_span_symbols*samples_per_symbol/2: ...
        case_span_symbols*samples_per_symbol/2)/samples_per_symbol;
    case_pulse = zeros(size(case_time_symbols));
    for tap_index = 1:numel(case_time_symbols)
        x = case_time_symbols(tap_index);
        if abs(x) < 1e-12
            case_pulse(tap_index) = 1 + case_rolloff*(4/pi - 1);
        elseif abs(abs(x)-1/(4*case_rolloff)) < 1e-12
            case_pulse(tap_index) = case_rolloff/sqrt(2)*( ...
                (1+2/pi)*sin(pi/(4*case_rolloff)) + ...
                (1-2/pi)*cos(pi/(4*case_rolloff)));
        else
            case_pulse(tap_index) = ( ...
                sin(pi*x*(1-case_rolloff)) + ...
                4*case_rolloff*x*cos(pi*x*(1+case_rolloff)))/( ...
                pi*x*(1-(4*case_rolloff*x)^2));
        end
    end
    case_pulse = case_pulse/sqrt(sum(abs(case_pulse).^2));
    case_matched_filter = conj(fliplr(case_pulse));
    case_transmitted = conv(upsampled_symbols, case_pulse);
    case_noiseless_output = conv(case_transmitted, case_matched_filter);
    case_sample_indices = 1 + numel(case_pulse)-1 + ...
        (0:symbol_count-1)*samples_per_symbol;
    case_samples = case_noiseless_output(case_sample_indices);
    case_valid_symbols = ...
        case_span_symbols+1:symbol_count-case_span_symbols;
    span_sweep_isi_evm_pct(sweep_index) = 100*sqrt(mean(abs( ...
        case_samples(case_valid_symbols)- ...
        qpsk_symbols(case_valid_symbols)).^2));
    span_sweep_tap_counts(sweep_index) = numel(case_pulse);
end
assert(span_sweep_isi_evm_pct(end) < span_sweep_isi_evm_pct(1), ...
    'The longer finite RRC should reduce truncation-driven sampled ISI.');

fprintf('\nP24 Sweep 2, span only (roll-off fixed at %.2f):\n', ...
    baseline_rolloff);
fprintf('  span (symbols):  %s\n', mat2str(span_sweep_symbols));
fprintf('  tap count:       %s\n', mat2str(span_sweep_tap_counts));
fprintf('  ISI EVM (%%):    %s\n', ...
    mat2str(span_sweep_isi_evm_pct, 4));

%% Broken case: sample half a symbol late, then recover the timing
broken_sample_indices = rrc_sample_indices + broken_timing_offset_samples;
broken_samples = ...
    rrc_noiseless_matched_output(broken_sample_indices);
broken_detected = [double(real(broken_samples) >= 0); ...
    double(imag(broken_samples) >= 0)];
broken_symbol_errors = sum(any(broken_detected ~= qpsk_bits, 1));
broken_ser = broken_symbol_errors/symbol_count;
broken_isi_evm_pct = 100*sqrt(mean(abs( ...
    broken_samples(valid_symbol_indices)-valid_reference).^2));

recovered_sample_indices = ...
    broken_sample_indices-broken_timing_offset_samples;
recovered_samples = ...
    rrc_noiseless_matched_output(recovered_sample_indices);
recovered_detected = [double(real(recovered_samples) >= 0); ...
    double(imag(recovered_samples) >= 0)];
recovered_symbol_errors = sum(any(recovered_detected ~= qpsk_bits, 1));
recovered_ser = recovered_symbol_errors/symbol_count;
recovered_isi_evm_pct = 100*sqrt(mean(abs( ...
    recovered_samples(valid_symbol_indices)-valid_reference).^2));

assert(broken_isi_evm_pct > 40 && broken_symbol_errors > 0, ...
    'A half-symbol timing error should close the eye and corrupt decisions.');
assert(abs(recovered_isi_evm_pct-rrc_isi_only_evm_pct) < 1e-12 && ...
    recovered_symbol_errors == 0, ...
    'Removing the timing offset must recover the noiseless baseline samples.');

