    double(imag(rectangular_samples) >= 0)];
rrc_detected = [double(real(rrc_samples) >= 0); ...
    double(imag(rrc_samples) >= 0)];
rectangular_symbol_errors = sum(any(rectangular_detected ~= qpsk_bits, 1));
rrc_symbol_errors = sum(any(rrc_detected ~= qpsk_bits, 1));
