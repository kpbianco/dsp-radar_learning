%% Sweep 1: scale fixed gain, phase, and position patterns together
severity_music_rmse_before_deg = zeros(size(error_scale_sweep));
severity_music_rmse_after_deg = zeros(size(error_scale_sweep));
severity_known_response_before_db = zeros(size(error_scale_sweep));
severity_known_response_after_db = zeros(size(error_scale_sweep));
for case_index = 1:numel(error_scale_sweep)
    case_scale = error_scale_sweep(case_index);
    case_positions = nominal_positions_wavelengths+case_scale* ...
        position_error_rms_wavelengths*position_error_pattern;
    case_gains = (1+case_scale*gain_error_rms_fraction*gain_error_pattern).* ...
        exp(1j*pi/180*case_scale*phase_error_rms_deg*phase_error_pattern);
    case_error_matrix = diag(case_gains)*coupling_matrix;
    [case_before, case_after, case_actual_steering, ...
        case_calibrated_steering, case_equalizer] = calibrate_case( ...
        case_error_matrix, ...
        case_positions, nominal_positions_wavelengths, source_angles_deg, ...
        source_amplitudes, source_waveforms, receiver_noise, noise_power, ...
        calibration_angle_deg, calibration_amplitude, calibration_waveform, ...
        calibration_noise, calibration_snapshots);
    case_before_covariance = form_covariance(case_before);
    case_after_covariance = form_covariance(case_after);
    [~, ~, case_before_music_db] = form_spatial_outputs( ...
        case_before_covariance, assumed_source_count, scan_steering, ...
        diagonal_loading_alpha, plot_floor_db, ideal_noise_covariance);
    [~, ~, case_after_music_db] = form_spatial_outputs( ...
        case_after_covariance, assumed_source_count, scan_steering, ...
        diagonal_loading_alpha, plot_floor_db, ...
        noise_power*case_equalizer*case_equalizer');
    severity_music_rmse_before_deg(case_index) = matched_angle_rmse( ...
        select_spatial_peaks(case_before_music_db, scan_angles_deg, ...
        assumed_source_count, minimum_peak_separation_deg), source_angles_deg);
    severity_music_rmse_after_deg(case_index) = matched_angle_rmse( ...
        select_spatial_peaks(case_after_music_db, scan_angles_deg, ...
        assumed_source_count, minimum_peak_separation_deg), source_angles_deg);
    case_before_weight = form_mvdr_weight(case_before_covariance, ...
        desired_nominal_steering, diagonal_loading_alpha);
    case_after_weight = form_mvdr_weight(case_after_covariance, ...
        desired_nominal_steering, diagonal_loading_alpha);
    severity_known_response_before_db(case_index) = 20*log10(max(abs( ...
        case_before_weight'*case_actual_steering(:, 2)), realmin));
    severity_known_response_after_db(case_index) = 20*log10(max(abs( ...
        case_after_weight'*case_calibrated_steering(:, 2)), realmin));
end
assert(all(isfinite(severity_music_rmse_before_deg)) && ...
    all(isfinite(severity_music_rmse_after_deg)) && ...
    all(isfinite(severity_known_response_before_db)) && ...
    all(isfinite(severity_known_response_after_db)), 'P67:SeveritySweep', ...
    'Every reviewed channel-error severity case must be finite.');

figure('Name', 'P67 channel-error severity sweep', 'Tag', 'P67');
