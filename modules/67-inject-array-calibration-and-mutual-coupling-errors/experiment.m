%% P67: Inject Array Calibration and Mutual-Coupling Errors
% Guiding question:
% How sensitive are beamforming and DOA results to imperfect channels?
%
% Base MATLAB only. The actual array manifold, calibration estimate,
% conventional/Bartlett scan, loaded MVDR/Capon scan, MUSIC projection, and
% direction-specific compensation are all exposed below.

close(findall(0, 'Type', 'figure', 'Tag', 'P67'));
clear p67_results;

%% Visible reviewed controls
baseline_seed = 6701;
number_elements = 10;
element_spacing_wavelengths = 0.5;
source_angles_deg = [-15 10];
interferer_inr_db = 25;
desired_snr_db = 10;
noise_power = 1.0;
number_snapshots = 512;
calibration_angle_deg = 10;
calibration_snr_db = 30;
calibration_snapshots = 256;
gain_error_rms_fraction = 0.18;
phase_error_rms_deg = 20;
position_error_rms_wavelengths = 0.05;
coupling_magnitude = 0.18;
coupling_phase_deg = 25;
next_neighbor_coupling_scale = 0.30;
diagonal_loading_alpha = 0.02;
assumed_source_count = 2;
scan_angles_deg = -40:0.1:40;
minimum_peak_separation_deg = 2.0;
error_scale_sweep = [0 0.25 0.5 0.75 1 1.25 1.5];
coupling_magnitude_sweep = [0 0.05 0.10 0.15 0.20 0.25 0.30];
plot_floor_db = -60;

maximum_elements = 16;
maximum_sources = 3;
maximum_snapshots = 512;
maximum_calibration_snapshots = 512;
maximum_scan_samples = 1001;
maximum_sweep_cases = 8;
maximum_private_values = 30000;
maximum_working_numeric_values = 1000000;
maximum_figures = 6;

controls = struct( ...
    'seed', baseline_seed, ...
    'elements', number_elements, ...
    'spacing', element_spacing_wavelengths, ...
    'source_angles', source_angles_deg, ...
    'interferer_inr_db', interferer_inr_db, ...
    'desired_snr_db', desired_snr_db, ...
    'noise_power', noise_power, ...
    'snapshots', number_snapshots, ...
    'calibration_angle', calibration_angle_deg, ...
    'calibration_snr_db', calibration_snr_db, ...
    'calibration_snapshots', calibration_snapshots, ...
    'gain_error_rms', gain_error_rms_fraction, ...
    'phase_error_rms_deg', phase_error_rms_deg, ...
    'position_error_rms', position_error_rms_wavelengths, ...
    'coupling_magnitude', coupling_magnitude, ...
    'coupling_phase_deg', coupling_phase_deg, ...
    'next_neighbor_scale', next_neighbor_coupling_scale, ...
    'loading_alpha', diagonal_loading_alpha, ...
    'assumed_sources', assumed_source_count, ...
    'scan_angles', scan_angles_deg, ...
    'minimum_peak_separation', minimum_peak_separation_deg, ...
    'error_scale_sweep', error_scale_sweep, ...
    'coupling_sweep', coupling_magnitude_sweep, ...
    'plot_floor_db', plot_floor_db, ...
    'max_elements', maximum_elements, ...
    'max_sources', maximum_sources, ...
    'max_snapshots', maximum_snapshots, ...
    'max_calibration_snapshots', maximum_calibration_snapshots, ...
    'max_scan_samples', maximum_scan_samples, ...
    'max_sweep_cases', maximum_sweep_cases, ...
    'max_private_values', maximum_private_values, ...
    'max_working_values', maximum_working_numeric_values, ...
    'max_figures', maximum_figures);
validate_controls(controls);

preflight_working_value_bound = ...
    16*number_elements*max(number_snapshots, calibration_snapshots)+ ...
    12*number_elements*numel(scan_angles_deg)+ ...
    24*numel(scan_angles_deg)+20*number_elements^2+ ...
    40*maximum_sweep_cases;
assert(preflight_working_value_bound <= maximum_working_numeric_values, ...
    'P67:PreflightWorkingBound', ...
    'Conservative simultaneous working-value estimate exceeds the ceiling.');

%% Freeze one random array and one operational record
nominal_positions_wavelengths = (0:number_elements-1).'* ...
    element_spacing_wavelengths;
error_uniforms = private_uniform(baseline_seed, 3*number_elements, ...
    maximum_private_values);
gain_error_pattern = unit_rms_pattern( ...
    2*error_uniforms(1:number_elements)-1);
phase_error_pattern = unit_rms_pattern( ...
    2*error_uniforms(number_elements+1:2*number_elements)-1);
position_error_pattern = unit_rms_pattern( ...
    2*error_uniforms(2*number_elements+1:3*number_elements)-1);

actual_positions_wavelengths = nominal_positions_wavelengths+ ...
    position_error_rms_wavelengths*position_error_pattern;
assert(all(diff(actual_positions_wavelengths) > 0), ...
    'P67:ElementOrdering', ...
    'Position errors must not reorder neighboring physical elements.');
channel_gains = (1+gain_error_rms_fraction*gain_error_pattern).* ...
    exp(1j*pi/180*phase_error_rms_deg*phase_error_pattern);
coupling_matrix = form_coupling_matrix(number_elements, coupling_magnitude, ...
    coupling_phase_deg, next_neighbor_coupling_scale);
array_error_matrix = diag(channel_gains)*coupling_matrix;

number_sources = numel(source_angles_deg);
source_waveforms = zeros(number_sources, number_snapshots);
for source_index = 1:number_sources
    phase_uniforms = private_uniform(baseline_seed+source_index, ...
        number_snapshots, maximum_private_values);
    source_waveforms(source_index, :) = exp(1j*2*pi*phase_uniforms);
end
receiver_noise = private_complex_noise(baseline_seed+3, number_elements, ...
    number_snapshots, maximum_private_values);
source_powers = noise_power*10.^([interferer_inr_db desired_snr_db]/10);
source_amplitudes = sqrt(source_powers).';

nominal_source_steering = steering_matrix(source_angles_deg, ...
    nominal_positions_wavelengths);
actual_source_steering = array_error_matrix*steering_matrix( ...
    source_angles_deg, actual_positions_wavelengths);
ideal_sensor_data = nominal_source_steering* ...
    (source_amplitudes.*source_waveforms)+sqrt(noise_power)*receiver_noise;
impaired_sensor_data = actual_source_steering* ...
    (source_amplitudes.*source_waveforms)+sqrt(noise_power)*receiver_noise;

%% Estimate a composite per-channel response from one known source
calibration_waveform = exp(1j*2*pi*private_uniform(baseline_seed+4, ...
    calibration_snapshots, maximum_private_values));
calibration_noise = private_complex_noise(baseline_seed+5, number_elements, ...
    calibration_snapshots, maximum_private_values);
nominal_calibration_steering = steering_matrix(calibration_angle_deg, ...
    nominal_positions_wavelengths);
actual_calibration_steering = array_error_matrix*steering_matrix( ...
    calibration_angle_deg, actual_positions_wavelengths);
calibration_amplitude = sqrt(noise_power*10^(calibration_snr_db/10));
calibration_sensor_data = actual_calibration_steering* ...
    (calibration_amplitude*calibration_waveform)+ ...
    sqrt(noise_power)*calibration_noise;
measured_calibration_response = calibration_sensor_data* ...
    calibration_waveform'/calibration_snapshots/calibration_amplitude;
estimated_channel_response = measured_calibration_response./ ...
    nominal_calibration_steering;
assert(all(abs(estimated_channel_response) > 0.10), ...
    'P67:CalibrationInvertibility', ...
    'Every estimated composite channel response must stay safely invertible.');
calibration_equalizer = diag(1./estimated_channel_response);
calibrated_sensor_data = calibration_equalizer*impaired_sensor_data;
calibrated_source_steering = calibration_equalizer*actual_source_steering;
ideal_noise_covariance = noise_power*eye(number_elements);
calibrated_noise_covariance = noise_power*calibration_equalizer* ...
    calibration_equalizer';

%% Compare conventional, MVDR/Capon, and MUSIC outputs
scan_steering = steering_matrix(scan_angles_deg, ...
    nominal_positions_wavelengths);
ideal_covariance = form_covariance(ideal_sensor_data);
impaired_covariance = form_covariance(impaired_sensor_data);
calibrated_covariance = form_covariance(calibrated_sensor_data);
[ideal_bartlett_db, ideal_capon_db, ideal_music_db] = form_spatial_outputs( ...
    ideal_covariance, assumed_source_count, scan_steering, ...
    diagonal_loading_alpha, plot_floor_db, ideal_noise_covariance);
[impaired_bartlett_db, impaired_capon_db, impaired_music_db] = ...
    form_spatial_outputs(impaired_covariance, assumed_source_count, ...
    scan_steering, diagonal_loading_alpha, plot_floor_db, ...
    ideal_noise_covariance);
[calibrated_bartlett_db, calibrated_capon_db, calibrated_music_db] = ...
    form_spatial_outputs(calibrated_covariance, assumed_source_count, ...
    scan_steering, diagonal_loading_alpha, plot_floor_db, ...
    calibrated_noise_covariance);

ideal_music_peaks_deg = select_spatial_peaks(ideal_music_db, ...
    scan_angles_deg, assumed_source_count, minimum_peak_separation_deg);
impaired_music_peaks_deg = select_spatial_peaks(impaired_music_db, ...
    scan_angles_deg, assumed_source_count, minimum_peak_separation_deg);
calibrated_music_peaks_deg = select_spatial_peaks(calibrated_music_db, ...
    scan_angles_deg, assumed_source_count, minimum_peak_separation_deg);
ideal_music_rmse_deg = matched_angle_rmse(ideal_music_peaks_deg, ...
    source_angles_deg);
impaired_music_rmse_deg = matched_angle_rmse(impaired_music_peaks_deg, ...
    source_angles_deg);
calibrated_music_rmse_deg = matched_angle_rmse(calibrated_music_peaks_deg, ...
    source_angles_deg);

desired_nominal_steering = nominal_calibration_steering;
conventional_weight = desired_nominal_steering/number_elements;
ideal_mvdr_weight = form_mvdr_weight(ideal_covariance, ...
    desired_nominal_steering, diagonal_loading_alpha);
impaired_mvdr_weight = form_mvdr_weight(impaired_covariance, ...
    desired_nominal_steering, diagonal_loading_alpha);
calibrated_mvdr_weight = form_mvdr_weight(calibrated_covariance, ...
    desired_nominal_steering, diagonal_loading_alpha);
ideal_mvdr_metrics = component_metrics(ideal_mvdr_weight, ...
    nominal_source_steering, source_powers, ideal_noise_covariance);
impaired_mvdr_metrics = component_metrics(impaired_mvdr_weight, ...
    actual_source_steering, source_powers, ideal_noise_covariance);
calibrated_mvdr_metrics = component_metrics(calibrated_mvdr_weight, ...
    calibrated_source_steering, source_powers, calibrated_noise_covariance);

known_response_before_db = 20*log10(max(abs( ...
    impaired_mvdr_weight'*actual_calibration_steering), realmin));
known_response_after_db = 20*log10(max(abs( ...
    calibrated_mvdr_weight'*(calibration_equalizer* ...
    actual_calibration_steering)), realmin));
calibration_manifold_error_before_db = relative_error_db( ...
    actual_calibration_steering, nominal_calibration_steering);
calibration_manifold_error_after_db = relative_error_db( ...
    calibration_equalizer*actual_calibration_steering, ...
    nominal_calibration_steering);

assert(ideal_music_rmse_deg < 0.25 && calibrated_music_rmse_deg < 0.5, ...
    'P67:DOARecovery', 'Ideal and calibrated MUSIC must recover the scene.');
assert(known_response_after_db > known_response_before_db+8, ...
    'P67:BeamRecovery', ...
    'Calibration must materially restore response at the known source.');
assert(calibration_manifold_error_after_db < ...
    calibration_manifold_error_before_db-20, 'P67:ManifoldRecovery', ...
    'Known-direction manifold error must fall materially after calibration.');

