%% Local transparent helpers
function steering = steering_matrix(angles_deg, positions_wavelengths)
    steering = exp(1j*2*pi*positions_wavelengths(:)*sind(angles_deg(:).'));
end

function pattern = unit_rms_pattern(values)
    pattern = values(:)-mean(values(:));
    pattern_rms = sqrt(mean(pattern.^2));
    assert(isfinite(pattern_rms) && pattern_rms > 0, 'P67:ErrorPattern', ...
        'Random error pattern must have finite nonzero RMS.');
    pattern = pattern/pattern_rms;
end

function coupling = form_coupling_matrix(elements, magnitude, phase_deg, ...
        next_neighbor_scale)
    coupling = eye(elements);
    nearest = magnitude*exp(1j*pi/180*phase_deg);
    next_nearest = next_neighbor_scale*nearest^2;
    for sensor_index = 1:elements-1
        coupling(sensor_index, sensor_index+1) = nearest;
        coupling(sensor_index+1, sensor_index) = nearest;
    end
    for sensor_index = 1:elements-2
        coupling(sensor_index, sensor_index+2) = next_nearest;
        coupling(sensor_index+2, sensor_index) = next_nearest;
    end
    assert(rcond(coupling) > 0.05, 'P67:CouplingCondition', ...
        'Reviewed coupling matrix must remain safely invertible.');
end

function covariance_matrix = form_covariance(sensor_data)
    snapshots = size(sensor_data, 2);
    covariance_matrix = sensor_data*sensor_data'/snapshots;
    covariance_matrix = (covariance_matrix+covariance_matrix')/2;
end

function [bartlett_db, capon_db, music_db] = form_spatial_outputs( ...
        covariance_matrix, source_count, scan_steering, loading_alpha, ...
        plot_floor_db, noise_covariance)
    elements = size(covariance_matrix, 1);
    bartlett_power = real(sum(conj(scan_steering).* ...
        (covariance_matrix*scan_steering), 1))/elements^2;
    loading_power = loading_alpha*real(trace(covariance_matrix))/elements;
    loaded_covariance = covariance_matrix+loading_power*eye(elements);
    loaded_covariance = (loaded_covariance+loaded_covariance')/2;
    assert(rcond(loaded_covariance) > 1e-12, 'P67:CaponCondition', ...
        'Loaded covariance must support a finite Capon solve.');
    capon_solutions = loaded_covariance\scan_steering;
    capon_denominator = real(sum(conj(scan_steering).*capon_solutions, 1));
    capon_power = 1./max(capon_denominator, realmin);
    noise_covariance = (noise_covariance+noise_covariance')/2;
    [noise_vectors, noise_value_matrix] = eig(noise_covariance);
    noise_values = real(diag(noise_value_matrix));
    assert(all(isfinite(noise_values)) && all(noise_values > realmin), ...
        'P67:NoiseWhitening', ...
        'Known receiver-noise covariance must be positive definite.');
    noise_whitener = noise_vectors*diag(1./sqrt(noise_values))*noise_vectors';
    whitened_covariance = noise_whitener*covariance_matrix*noise_whitener';
    whitened_covariance = (whitened_covariance+whitened_covariance')/2;
    whitened_scan_steering = noise_whitener*scan_steering;
    [eigenvectors, eigenvalue_matrix] = eig(whitened_covariance);
    [~, eigenvalue_order] = sort(real(diag(eigenvalue_matrix)), 'descend');
    eigenvectors = eigenvectors(:, eigenvalue_order);
    noise_subspace = eigenvectors(:, source_count+1:end);
    music_denominator = sum(abs(noise_subspace'* ...
        whitened_scan_steering).^2, 1);
    music_power = 1./max(music_denominator, realmin);
    floor_linear = 10^(plot_floor_db/10);
    bartlett_db = 10*log10(max(bartlett_power/max(bartlett_power), ...
        floor_linear));
    capon_db = 10*log10(max(capon_power/max(capon_power), floor_linear));
    music_db = 10*log10(max(music_power/max(music_power), floor_linear));
end

function weight = form_mvdr_weight(covariance_matrix, look_steering, alpha)
    elements = size(covariance_matrix, 1);
    loading_power = alpha*real(trace(covariance_matrix))/elements;
    loaded_covariance = covariance_matrix+loading_power*eye(elements);
    loaded_covariance = (loaded_covariance+loaded_covariance')/2;
    assert(rcond(loaded_covariance) > 1e-12, 'P67:MVDRCondition', ...
        'Loaded covariance must support a finite MVDR solve.');
    numerator = loaded_covariance\look_steering;
    denominator = look_steering'*numerator;
    assert(isfinite(real(denominator)) && isfinite(imag(denominator)) && ...
        abs(denominator) > realmin, 'P67:MVDRNormalization', ...
        'MVDR normalization must be finite and nonzero.');
    weight = numerator/denominator;
end

function metrics = component_metrics(weight, source_steering, ...
        source_powers, noise_covariance)
    responses = abs(weight'*source_steering).^2;
    interference_power = source_powers(1)*responses(1);
    desired_power = source_powers(2)*responses(2);
    output_noise_power = real(weight'*noise_covariance*weight);
    output_sinr = desired_power/(interference_power+output_noise_power);
    metrics = struct( ...
        'desired_response_db', 10*log10(max(responses(2), realmin)), ...
        'interferer_response_db', 10*log10(max(responses(1), realmin)), ...
        'desired_power', desired_power, ...
        'interference_power', interference_power, ...
        'noise_power', output_noise_power, ...
        'output_sinr_db', 10*log10(max(output_sinr, realmin)));
end

function peaks_deg = select_spatial_peaks(spectrum_db, scan_angles_deg, ...
        peak_count, minimum_separation_deg)
    candidate_indices = find(spectrum_db(2:end-1) > spectrum_db(1:end-2) & ...
        spectrum_db(2:end-1) >= spectrum_db(3:end))+1;
    [~, order] = sort(spectrum_db(candidate_indices), 'descend');
    candidate_indices = candidate_indices(order);
    selected_indices = zeros(1, peak_count);
    selected_count = 0;
    for candidate_index = candidate_indices(:).'
        if selected_count == 0 || all(abs(scan_angles_deg(candidate_index)- ...
                scan_angles_deg(selected_indices(1:selected_count))) >= ...
                minimum_separation_deg)
            selected_count = selected_count+1;
            selected_indices(selected_count) = candidate_index;
            if selected_count == peak_count
                break;
            end
        end
    end
    assert(selected_count == peak_count, 'P67:PeakCount', ...
        'Reviewed scan must contain the requested separated local peaks.');
    peaks_deg = sort(scan_angles_deg(selected_indices));
end

function rmse_deg = matched_angle_rmse(estimated_deg, truth_deg)
    assert(numel(estimated_deg) == numel(truth_deg), 'P67:AngleCount', ...
        'Estimated and true angle counts must match.');
    rmse_deg = sqrt(mean((sort(estimated_deg)-sort(truth_deg)).^2));
end

function value_db = relative_error_db(actual, reference)
    value_db = 20*log10(max(norm(actual-reference)/norm(reference), realmin));
end

function [before_data, after_data, actual_source_steering, ...
        calibrated_source_steering, equalizer] = calibrate_case(error_matrix, ...
        actual_positions, nominal_positions, source_angles, ...
        source_amplitudes, source_waveforms, receiver_noise, noise_power, ...
        calibration_angle, calibration_amplitude, calibration_waveform, ...
        calibration_noise, calibration_snapshots)
    assert(all(diff(actual_positions) > 0), 'P67:SweepElementOrdering', ...
        'Sweep position errors must not reorder neighboring elements.');
    actual_source_steering = error_matrix*steering_matrix( ...
        source_angles, actual_positions);
    before_data = actual_source_steering* ...
        (source_amplitudes.*source_waveforms)+sqrt(noise_power)*receiver_noise;
    actual_calibration = error_matrix*steering_matrix( ...
        calibration_angle, actual_positions);
    nominal_calibration = steering_matrix(calibration_angle, nominal_positions);
    calibration_data = actual_calibration* ...
        (calibration_amplitude*calibration_waveform)+ ...
        sqrt(noise_power)*calibration_noise;
    measured_response = calibration_data*calibration_waveform'/ ...
        calibration_snapshots/calibration_amplitude;
    estimated_response = measured_response./nominal_calibration;
    assert(all(abs(estimated_response) > 0.10), ...
        'P67:SweepCalibrationInvertibility', ...
        'Sweep calibration estimate must remain safely invertible.');
    equalizer = diag(1./estimated_response);
    after_data = equalizer*before_data;
    calibrated_source_steering = equalizer*actual_source_steering;
end

function uniforms = private_uniform(seed, count, maximum_private_values)
    assert(isnumeric(seed) && ~islogical(seed) && isreal(seed) && ...
        isscalar(seed) && isfinite(seed) && seed == floor(seed) && ...
        seed >= 1 && seed < 2147483647, 'P67:Seed', ...
        'Seed must be one valid positive integer.');
    assert(isnumeric(count) && ~islogical(count) && isreal(count) && ...
        isscalar(count) && isfinite(count) && count == floor(count) && ...
        count >= 1 && count <= maximum_private_values, 'P67:PrivateBound', ...
        'Private generator request exceeds the reviewed ceiling.');
    state = double(seed);
    uniforms = zeros(1, count);
    for sample_index = 1:count
        state = mod(16807*state, 2147483647);
        uniforms(sample_index) = state/2147483647;
    end
end

function noise = private_complex_noise(seed, number_rows, number_columns, ...
        maximum_private_values)
    sample_count = number_rows*number_columns;
    uniforms = private_uniform(seed, 2*sample_count, maximum_private_values);
    first = max(uniforms(1:sample_count), realmin);
    second = uniforms(sample_count+1:2*sample_count);
    samples = sqrt(-2*log(first)).*exp(1j*2*pi*second)/sqrt(2);
    noise = reshape(samples, number_rows, number_columns);
end

function validate_controls(c)
    scalar_names = {'seed', 'elements', 'spacing', 'interferer_inr_db', ...
        'desired_snr_db', 'noise_power', 'snapshots', 'calibration_angle', ...
        'calibration_snr_db', 'calibration_snapshots', 'gain_error_rms', ...
        'phase_error_rms_deg', 'position_error_rms', 'coupling_magnitude', ...
        'coupling_phase_deg', 'next_neighbor_scale', 'loading_alpha', ...
        'assumed_sources', 'minimum_peak_separation', 'plot_floor_db', ...
        'max_elements', 'max_sources', 'max_snapshots', ...
        'max_calibration_snapshots', 'max_scan_samples', 'max_sweep_cases', ...
        'max_private_values', 'max_working_values', 'max_figures'};
    for name_index = 1:numel(scalar_names)
        value = c.(scalar_names{name_index});
        assert(isnumeric(value) && ~islogical(value) && isreal(value) && ...
            isscalar(value) && isfinite(value), 'P67:FiniteControls', ...
            '%s must be one finite real numeric scalar.', ...
            scalar_names{name_index});
    end
    integers = [c.seed c.elements c.snapshots c.calibration_snapshots ...
        c.assumed_sources c.max_elements c.max_sources c.max_snapshots ...
        c.max_calibration_snapshots c.max_scan_samples c.max_sweep_cases ...
        c.max_private_values c.max_working_values c.max_figures];
    assert(all(integers == floor(integers)) && all(integers > 0), ...
        'P67:IntegerControls', 'Reviewed count controls must be positive integers.');
    assert(isnumeric(c.source_angles) && ~islogical(c.source_angles) && ...
        isreal(c.source_angles) && isrow(c.source_angles) && ...
        numel(c.source_angles) == c.assumed_sources && ...
        numel(c.source_angles) <= c.max_sources && ...
        all(isfinite(c.source_angles)) && all(abs(c.source_angles) < 90) && ...
        all(diff(c.source_angles) > 0), 'P67:SourceAngles', ...
        'Source angles must be finite, ordered, distinct, and visible.');
    assert(isnumeric(c.scan_angles) && ~islogical(c.scan_angles) && ...
        isreal(c.scan_angles) && isrow(c.scan_angles) && ...
        numel(c.scan_angles) >= 2*c.assumed_sources+1 && ...
        numel(c.scan_angles) <= ...
        c.max_scan_samples && all(isfinite(c.scan_angles)) && ...
        all(abs(c.scan_angles) < 90) && all(diff(c.scan_angles) > 0) && ...
        c.scan_angles(1) < c.source_angles(1) && ...
        c.scan_angles(end) > c.source_angles(end), 'P67:ScanGrid', ...
        ['Scan grid must be ordered and place both source angles strictly ' ...
        'inside enough samples for separated local-peak selection.']);
    validate_sweep(c.error_scale_sweep, c.max_sweep_cases, 0, 2);
    validate_sweep(c.coupling_sweep, c.max_sweep_cases, 0, 0.35);
    assert(c.elements <= c.max_elements && c.assumed_sources == 2 && ...
        c.assumed_sources < c.elements && ...
        c.snapshots <= c.max_snapshots && ...
        c.calibration_snapshots <= c.max_calibration_snapshots && ...
        c.spacing > 0 && c.spacing <= 0.5 && c.noise_power > 0 && ...
        c.noise_power <= 1e6 && c.gain_error_rms >= 0 && ...
        c.gain_error_rms <= 0.30 && c.phase_error_rms_deg >= 0 && ...
        c.phase_error_rms_deg <= 45 && c.position_error_rms >= 0 && ...
        c.position_error_rms <= 0.10 && c.coupling_magnitude >= 0 && ...
        c.coupling_magnitude <= 0.35 && c.next_neighbor_scale >= 0 && ...
        c.next_neighbor_scale <= 0.5 && c.loading_alpha > 0 && ...
        c.loading_alpha <= 1 && abs(c.interferer_inr_db) <= 60 && ...
        abs(c.desired_snr_db) <= 60 && abs(c.calibration_snr_db) <= 80 && ...
        c.calibration_angle == c.source_angles(2) && ...
        c.minimum_peak_separation > 0 && c.minimum_peak_separation <= 10 && ...
        c.plot_floor_db >= -200 && c.plot_floor_db <= -10, ...
        'P67:PhysicalControls', ...
        'Reviewed physical controls violate bounded model assumptions.');
    assert(c.max_elements == 16 && c.max_sources == 3 && ...
        c.max_snapshots == 512 && c.max_calibration_snapshots == 512 && ...
        c.max_scan_samples == 1001 && c.max_sweep_cases == 8 && ...
        c.max_private_values == 30000 && c.max_working_values == 1000000 && ...
        c.max_figures == 6 && c.seed <= 2147483641 && ...
        2*c.elements*max(c.snapshots, c.calibration_snapshots) <= ...
        c.max_private_values, 'P67:ResourceBounds', ...
        'Immutable resource ceilings or private allocation are inconsistent.');
end

function validate_sweep(values, maximum_cases, minimum_value, maximum_value)
    assert(isnumeric(values) && ~islogical(values) && isreal(values) && ...
        isrow(values) && numel(values) >= 3 && numel(values) <= ...
        maximum_cases && all(isfinite(values)) && all(diff(values) > 0) && ...
        values(1) >= minimum_value && values(end) <= maximum_value, ...
        'P67:SweepControls', ...
        'Sweep must be finite, ordered, distinct, and inside reviewed bounds.');
end
