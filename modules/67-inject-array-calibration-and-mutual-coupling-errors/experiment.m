%% Sweep 2: change only mutual-coupling magnitude
coupling_music_rmse_before_deg = zeros(size(coupling_magnitude_sweep));
coupling_music_rmse_after_deg = zeros(size(coupling_magnitude_sweep));
coupling_off_angle_error_after_db = zeros(size(coupling_magnitude_sweep));
for case_index = 1:numel(coupling_magnitude_sweep)
    case_coupling = form_coupling_matrix(number_elements, ...
        coupling_magnitude_sweep(case_index), coupling_phase_deg, ...
        next_neighbor_coupling_scale);
    case_error_matrix = diag(channel_gains)*case_coupling;
    [case_before, case_after, case_actual_steering, ...
        case_calibrated_steering, case_equalizer] = calibrate_case( ...
        case_error_matrix, ...
        actual_positions_wavelengths, nominal_positions_wavelengths, ...
        source_angles_deg, source_amplitudes, source_waveforms, ...
        receiver_noise, noise_power, calibration_angle_deg, ...
        calibration_amplitude, calibration_waveform, calibration_noise, ...
        calibration_snapshots);
    [~, ~, case_before_music_db] = form_spatial_outputs( ...
        form_covariance(case_before), assumed_source_count, scan_steering, ...
        diagonal_loading_alpha, plot_floor_db, ideal_noise_covariance);
    [~, ~, case_after_music_db] = form_spatial_outputs( ...
        form_covariance(case_after), assumed_source_count, scan_steering, ...
        diagonal_loading_alpha, plot_floor_db, ...
        noise_power*case_equalizer*case_equalizer');
    coupling_music_rmse_before_deg(case_index) = matched_angle_rmse( ...
