%% Broken case: forget to remove the known source steering phase
wrong_reference_equalizer = diag(1./measured_calibration_response);
wrong_reference_sensor_data = wrong_reference_equalizer*impaired_sensor_data;
[wrong_bartlett_db, wrong_capon_db, wrong_music_db] = form_spatial_outputs( ...
    form_covariance(wrong_reference_sensor_data), assumed_source_count, ...
    scan_steering, diagonal_loading_alpha, plot_floor_db, ...
    noise_power*wrong_reference_equalizer*wrong_reference_equalizer');
wrong_music_peaks_deg = select_spatial_peaks(wrong_music_db, scan_angles_deg, ...
    assumed_source_count, minimum_peak_separation_deg);
wrong_music_rmse_deg = matched_angle_rmse(wrong_music_peaks_deg, ...
    source_angles_deg);
wrong_known_manifold = wrong_reference_equalizer*actual_calibration_steering;
wrong_known_scan_response = abs(wrong_known_manifold'*scan_steering);
[~, wrong_known_peak_index] = max(wrong_known_scan_response);
wrong_known_peak_deg = scan_angles_deg(wrong_known_peak_index);
assert(wrong_music_rmse_deg > 5 && abs(wrong_known_peak_deg) < 0.11, ...
    'P67:BrokenReference', ...
    'The reviewed wrong-reference case must corrupt DOA despite known truth.');
assert(norm(wrong_known_manifold-ones(number_elements, 1))/ ...
    sqrt(number_elements) < 0.05, 'P67:BrokenFlattening', ...
    'Wrong calibration must visibly flatten the known source phase slope.');

figure('Name', 'P67 broken calibration and recovery', 'Tag', 'P67');
subplot(2, 1, 1);
plot(1:number_elements, unwrap(angle(nominal_calibration_steering)), 'o-', ...
