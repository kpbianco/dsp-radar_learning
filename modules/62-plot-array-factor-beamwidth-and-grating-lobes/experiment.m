%% Local helpers: explicit repeated coherent sum, metrics, and validation
function response = array_factor(number_elements, spacing_wavelengths, ...
    steering_angle_deg, observation_angle_deg, weights)
    element_index = (0:number_elements-1).';
    direction_offset = sind(observation_angle_deg)-sind(steering_angle_deg);
    phase_rad = 2*pi*spacing_wavelengths*element_index*direction_offset;
    element_contributions = weights(:).*exp(1j*phase_rad);
    response = abs(sum(element_contributions, 1))/sum(abs(weights));
end

function metrics = pattern_metrics(angle_grid_deg, response, ...
    expected_peak_angle_deg)
    assert(isrow(angle_grid_deg) && isrow(response) && ...
        numel(angle_grid_deg) == numel(response) && ...
        all(isfinite(angle_grid_deg)) && all(isfinite(response)) && ...
        all(diff(angle_grid_deg) > 0) && all(response >= 0), ...
        'P62:BadMetricInput', 'Pattern metrics need finite ordered row vectors.');
    [~, expected_index] = min(abs(angle_grid_deg-expected_peak_angle_deg));
    search_half_width = max(1, round(5/median(diff(angle_grid_deg))));
    search_indices = max(1, expected_index-search_half_width): ...
        min(numel(response), expected_index+search_half_width);
    [peak_value, local_peak_offset] = max(response(search_indices));
    peak_index = search_indices(local_peak_offset);
    normalized = response/peak_value;

    half_power = 1/sqrt(2);
    left_below = find(normalized(1:peak_index) <= half_power, 1, 'last');
    right_relative = find(normalized(peak_index:end) <= half_power, 1, 'first');
    assert(~isempty(left_below) && ~isempty(right_relative) && ...
        left_below < peak_index && right_relative > 1, ...
        'P62:MissingHalfPowerCrossing', ...
        'The main lobe must contain two half-power crossings.');
    right_below = peak_index+right_relative-1;
    left_half_power_deg = interpolate_crossing( ...
        angle_grid_deg(left_below), normalized(left_below), ...
        angle_grid_deg(left_below+1), normalized(left_below+1), half_power);
    right_half_power_deg = interpolate_crossing( ...
        angle_grid_deg(right_below-1), normalized(right_below-1), ...
        angle_grid_deg(right_below), normalized(right_below), half_power);

    local_minimum = false(size(normalized));
    local_minimum(2:end-1) = normalized(2:end-1) <= normalized(1:end-2) & ...
        normalized(2:end-1) < normalized(3:end);
    left_null_index = find(local_minimum(1:peak_index-1), 1, 'last');
    right_relative = find(local_minimum(peak_index+1:end), 1, 'first');
    assert(~isempty(left_null_index) && ~isempty(right_relative), ...
        'P62:MissingFirstNull', ...
        'The reviewed pattern must have a local minimum on both sides.');
    right_null_index = peak_index+right_relative;
    sidelobe_samples = [normalized(1:left_null_index) ...
        normalized(right_null_index:end)];
    peak_sidelobe_level_db = 20*log10(max(sidelobe_samples));

    metrics = struct( ...
        'peak_angle_deg', angle_grid_deg(peak_index), ...
        'peak_value', peak_value, ...
        'left_half_power_deg', left_half_power_deg, ...
        'right_half_power_deg', right_half_power_deg, ...
        'half_power_beamwidth_deg', ...
            right_half_power_deg-left_half_power_deg, ...
        'left_null_deg', angle_grid_deg(left_null_index), ...
        'right_null_deg', angle_grid_deg(right_null_index), ...
        'first_null_beamwidth_deg', ...
            angle_grid_deg(right_null_index)-angle_grid_deg(left_null_index), ...
        'peak_sidelobe_level_db', peak_sidelobe_level_db);
end

function crossing_x = interpolate_crossing(x1, y1, x2, y2, target_y)
    assert(isfinite(x1) && isfinite(y1) && isfinite(x2) && isfinite(y2) && ...
        isfinite(target_y) && x2 > x1 && y2 ~= y1 && ...
        target_y >= min(y1, y2) && target_y <= max(y1, y2), ...
        'P62:BadCrossingBracket', ...
        'A crossing needs an ordered finite bracket around the target.');
    crossing_x = x1+(target_y-y1)*(x2-x1)/(y2-y1);
end

function grating_angles_deg = visible_grating_angles( ...
    spacing_wavelengths, steering_angle_deg)
    direction_steer = sind(steering_angle_deg);
    candidate_orders = -ceil(2*spacing_wavelengths): ...
        ceil(2*spacing_wavelengths);
    grating_angles_deg = [];
    for order = candidate_orders
        if order == 0
            continue;
        end
        candidate_direction = direction_steer+order/spacing_wavelengths;
        if abs(candidate_direction) <= 1
            grating_angles_deg(end+1) = asind(candidate_direction); %#ok<AGROW>
        end
    end
    grating_angles_deg = sort(grating_angles_deg);
end

function values = private_uniform(seed, count, maximum_count)
    modulus = 2147483647;
    multiplier = 16807;
    assert(isnumeric(seed) && isreal(seed) && isscalar(seed) && ...
        isfinite(seed) && seed == floor(seed) && seed >= 1 && seed < modulus, ...
        'P62:BadPrivateSeed', 'Private seed must be an integer in range.');
    assert(isnumeric(count) && isreal(count) && isscalar(count) && ...
        isfinite(count) && count == floor(count) && count >= 1 && ...
        count <= maximum_count, 'P62:BadPrivateCount', ...
        'Private sample count exceeds its immutable ceiling.');
    values = zeros(1, count);
    state = seed;
    for sample_index = 1:count
        state = mod(multiplier*state, modulus);
        values(sample_index) = (state+0.5)/modulus;
    end
end

function validate_controls(c)
    scalar_names = {'baseline_seed', 'number_elements', ...
        'element_spacing_wavelengths', 'steering_angle_deg', ...
        'plot_floor_db', 'broken_steering_angle_deg', ...
        'broken_spacing_wavelengths', 'broken_grating_angle_deg', ...
        'recovered_spacing_wavelengths', 'maximum_elements', ...
        'maximum_angle_samples', 'maximum_sweep_cases', ...
        'maximum_probe_angles', 'maximum_stored_numeric_values', ...
        'maximum_figures', 'comparison_tolerance'};
    for name_index = 1:numel(scalar_names)
        value = c.(scalar_names{name_index});
        assert(isnumeric(value) && ~islogical(value) && isreal(value) && ...
            isscalar(value) && isfinite(value), 'P62:BadScalarControl', ...
            '%s must be one finite real numeric scalar.', ...
            scalar_names{name_index});
    end
    integer_names = {'baseline_seed', 'number_elements', 'maximum_elements', ...
        'maximum_angle_samples', 'maximum_sweep_cases', ...
        'maximum_probe_angles', 'maximum_stored_numeric_values', ...
        'maximum_figures'};
    for name_index = 1:numel(integer_names)
        value = c.(integer_names{name_index});
        assert(value == floor(value), 'P62:BadIntegerControl', ...
            '%s must be integer-valued.', integer_names{name_index});
    end
    assert(c.baseline_seed == 6201 && c.baseline_seed >= 1 && ...
        c.baseline_seed < 2147483647, 'P62:BadSeed', ...
        'The reviewed private seed is 6201.');
    assert(c.number_elements == 8 && c.number_elements >= 2 && ...
        c.number_elements <= c.maximum_elements && c.maximum_elements == 32, ...
        'P62:BadElementCount', 'The reviewed element count or ceiling changed.');
    assert(c.element_spacing_wavelengths == 0.5 && ...
        c.element_spacing_wavelengths > 0, 'P62:BadBaselineSpacing', ...
        'The reviewed baseline uses half-wavelength spacing.');
    assert(c.steering_angle_deg == 0 && ...
        abs(c.steering_angle_deg) < 90, 'P62:BadBaselineSteering', ...
        'The reviewed baseline steering angle is broadside.');
    assert(isnumeric(c.angle_grid_deg) && ~islogical(c.angle_grid_deg) && ...
        isreal(c.angle_grid_deg) && isrow(c.angle_grid_deg) && ...
        all(isfinite(c.angle_grid_deg)) && ...
        numel(c.angle_grid_deg) <= c.maximum_angle_samples && ...
        c.maximum_angle_samples == 10001 && c.angle_grid_deg(1) == -90 && ...
        c.angle_grid_deg(end) == 90 && all(diff(c.angle_grid_deg) > 0) && ...
        max(abs(diff(c.angle_grid_deg)-0.025)) < 1e-12, ...
        'P62:BadAngleGrid', 'The reviewed angle grid is bounded and ordered.');
    validate_sweep(c.element_count_sweep, c.maximum_sweep_cases, ...
        'P62:BadElementSweep');
    assert(all(c.element_count_sweep == floor(c.element_count_sweep)) && ...
        isequal(c.element_count_sweep, [4 8 16]) && ...
        max(c.element_count_sweep) <= c.maximum_elements, ...
        'P62:BadElementSweep', 'The reviewed element-count sweep changed.');
    validate_sweep(c.spacing_sweep_wavelengths, c.maximum_sweep_cases, ...
        'P62:BadSpacingSweep');
    assert(isequal(c.spacing_sweep_wavelengths, [0.5 0.75 1.0]), ...
        'P62:BadSpacingSweep', 'The reviewed spacing sweep changed.');
    assert(c.broken_steering_angle_deg == 30 && ...
        c.broken_spacing_wavelengths == 1.0 && ...
        c.broken_grating_angle_deg == -30 && ...
        c.recovered_spacing_wavelengths == 0.5, ...
        'P62:BadBrokenFixture', ...
        'The exact broken and recovered grating-lobe fixture changed.');
    assert(c.plot_floor_db == -60 && c.comparison_tolerance == 1e-10, ...
        'P62:BadDisplayControl', 'Reviewed floor or tolerance changed.');
    assert(c.maximum_sweep_cases == 5 && c.maximum_probe_angles == 8 && ...
        c.maximum_stored_numeric_values == 250000 && ...
        c.maximum_figures == 5, 'P62:BadResourceCeiling', ...
        'Immutable resource ceilings changed.');
    estimated_values = numel(c.angle_grid_deg)*( ...
        4+numel(c.element_count_sweep)+numel(c.spacing_sweep_wavelengths)+ ...
        c.number_elements)+100*c.maximum_elements;
    assert(estimated_values <= c.maximum_stored_numeric_values, ...
        'P62:StoredValueCeiling', ...
        'Reviewed numeric arrays exceed the immutable resource ceiling.');
end

function validate_sweep(values, maximum_cases, error_id)
    assert(isnumeric(values) && ~islogical(values) && isreal(values) && ...
        isrow(values) && ~isempty(values) && all(isfinite(values)) && ...
        all(values > 0) && numel(values) <= maximum_cases && ...
        all(diff(values) > 0), error_id, ...
        'Sweep must be a positive, finite, strictly increasing bounded row.');
end
