%% Broken case: unknown right-channel gain creates a false boresight angle
broken_steering = exp(1j*2*pi*element_spacing_wavelengths*element_index* ...
    sind(broken_target_angle_deg));
broken_data = broken_steering*exp(1j*target_phase_rad);
broken_left = (left_weight'*broken_data)*left_phase_correction;
ideal_right = (right_weight'*broken_data)*right_phase_correction;
broken_right = broken_right_gain*ideal_right;
broken_sum = (broken_right+broken_left)/2;
broken_difference = (broken_right-broken_left)/2;
broken_ratio = real(broken_difference/broken_sum);
broken_estimate_deg = ratio_to_angle(broken_ratio, ...
    calibration_ratio, calibration_angles_deg);

% Recovery changes only the known receiver calibration, not the scene data.
recovered_right = broken_right/broken_right_gain;
recovered_sum = (recovered_right+broken_left)/2;
recovered_difference = (recovered_right-broken_left)/2;
recovered_ratio = real(recovered_difference/recovered_sum);
recovered_estimate_deg = ratio_to_angle(recovered_ratio, ...
    calibration_ratio, calibration_angles_deg);
assert(abs(broken_estimate_deg) > 0.3, 'P64:BrokenBias', ...
    'Reviewed gain mismatch must create a visible false angle.');
assert(abs(recovered_estimate_deg-broken_target_angle_deg) < ...
    comparison_tolerance, 'P64:Recovery', ...
    'Known inverse gain calibration must restore boresight on unchanged data.');

broken_right_pattern = broken_right_gain*right_pattern;
broken_ratio_curve = real((broken_right_pattern-left_pattern)./ ...
    (broken_right_pattern+left_pattern));
recovered_ratio_curve = real((broken_right_pattern/broken_right_gain- ...
    left_pattern)./(broken_right_pattern/broken_right_gain+left_pattern));
assert(max(abs(recovered_ratio_curve-normalized_ratio)) < ...
    comparison_tolerance, 'P64:RecoveryCurve', ...
    'Recovery must restore the ideal ratio curve exactly.');

