title(sprintf('Coherent estimate %.3f deg; snapshot RMSE %.3f deg', ...
    baseline_estimate_deg, baseline_snapshot_rmse_deg));
legend('Single-snapshot estimates', 'True angle', ...
    'Coherently averaged estimate', 'Location', 'best');

%% Sweep 1: beam squint changes comparator slope and sum-channel strength
number_squint_cases = numel(squint_sweep_deg);
squint_ratio_curves = zeros(number_squint_cases, numel(pattern_angles_deg));
squint_slopes_per_deg = zeros(1, number_squint_cases);
squint_boresight_sum = zeros(1, number_squint_cases);
for case_index = 1:number_squint_cases
    current_squint_deg = squint_sweep_deg(case_index);
    [current_left, current_right] = aligned_beam_patterns(number_elements, ...
        element_spacing_wavelengths, current_squint_deg, pattern_angles_deg);
    current_sum = (current_right+current_left)/2;
    current_difference = (current_right-current_left)/2;
    squint_ratio_curves(case_index, :) = real(current_difference./current_sum);
    minus_index = find(abs(pattern_angles_deg+1) < comparison_tolerance, 1);
    plus_index = find(abs(pattern_angles_deg-1) < comparison_tolerance, 1);
    zero_index = find(abs(pattern_angles_deg) < comparison_tolerance, 1);
    squint_slopes_per_deg(case_index) = ...
        (squint_ratio_curves(case_index, plus_index)- ...
        squint_ratio_curves(case_index, minus_index))/2;
    squint_boresight_sum(case_index) = abs(current_sum(zero_index));
end
assert(all(diff(squint_slopes_per_deg) > 0), 'P64:SquintSlopeSweep', ...
    'Reviewed larger squints must steepen the local comparator slope.');
assert(all(diff(squint_boresight_sum) < 0), 'P64:SquintSumSweep', ...
    'Reviewed larger squints must reduce boresight sum response.');

figure('Name', 'P64 beam-squint sweep', 'Tag', 'P64');
subplot(2, 1, 1);
plot(pattern_angles_deg, squint_ratio_curves, 'LineWidth', 1.5);
grid on;
