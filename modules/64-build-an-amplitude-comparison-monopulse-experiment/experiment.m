%% Local functions: validation, explicit channel formation, and private noise
function validate_controls(controls)
    require_finite_integer(controls.baseline_seed, 'baseline_seed');
    require_finite_integer(controls.number_elements, 'number_elements');
    require_finite_integer(controls.number_snapshots, 'number_snapshots');
    require_finite_integer(controls.maximum_elements, 'maximum_elements');
    require_finite_integer(controls.maximum_snapshots, 'maximum_snapshots');
    require_finite_integer(controls.maximum_angle_samples, 'maximum_angle_samples');
    require_finite_integer(controls.maximum_sweep_cases, 'maximum_sweep_cases');
    require_finite_integer(controls.maximum_private_values, 'maximum_private_values');
    require_finite_integer(controls.maximum_working_numeric_values, ...
        'maximum_working_numeric_values');
    require_finite_integer(controls.maximum_figures, 'maximum_figures');
    finite_scalars = [controls.element_spacing_wavelengths, ...
        controls.beam_squint_deg, controls.target_angle_deg, ...
        controls.target_phase_rad, controls.receiver_snr_db, ...
        controls.calibration_limit_deg, controls.sum_guard, ...
        controls.broken_right_gain, controls.broken_target_angle_deg, ...
        controls.comparison_tolerance];
    assert(all(isfinite(finite_scalars)), 'P64:MalformedControl', ...
        'Scalar controls must be finite.');
    assert(controls.baseline_seed == 6401, 'P64:SeedContract', ...
        'The reviewed deterministic seed is 6401.');
    assert(controls.number_elements == 12 && ...
        controls.number_elements <= controls.maximum_elements && ...
        controls.maximum_elements == 16, 'P64:ElementBound', ...
        'Reviewed element count or ceiling changed.');
    assert(controls.number_snapshots == 256 && ...
        controls.number_snapshots <= controls.maximum_snapshots && ...
        controls.maximum_snapshots == 512, 'P64:SnapshotBound', ...
        'Reviewed snapshot count or ceiling changed.');
    assert(controls.element_spacing_wavelengths == 0.5 && ...
        controls.beam_squint_deg == 3.0 && ...
        controls.target_angle_deg == 2.0 && ...
        controls.receiver_snr_db == 15.0, 'P64:BaselineContract', ...
        'Reviewed geometry or baseline scene changed.');
    assert(isrow(controls.pattern_angles_deg) && ...
        ~isempty(controls.pattern_angles_deg) && ...
        numel(controls.pattern_angles_deg) <= controls.maximum_angle_samples && ...
        all(isfinite(controls.pattern_angles_deg)) && ...
        all(diff(controls.pattern_angles_deg) > 0) && ...
        abs(controls.pattern_angles_deg(1)+10) < controls.comparison_tolerance && ...
        abs(controls.pattern_angles_deg(end)-10) < controls.comparison_tolerance && ...
        max(abs(diff(controls.pattern_angles_deg)-0.05)) < ...
        controls.comparison_tolerance, 'P64:AngleGrid', ...
        'Pattern angle grid must be ordered -10:0.05:10 degrees.');
    assert(controls.calibration_limit_deg == 4.0 && ...
        controls.sum_guard == 0.15 && controls.comparison_tolerance == 1e-10, ...
        'P64:CalibrationContract', 'Reviewed calibration limits changed.');
    assert(isequal(controls.squint_sweep_deg, [1.5 3.0 5.0]) && ...
        numel(controls.squint_sweep_deg) <= controls.maximum_sweep_cases && ...
        all(diff(controls.squint_sweep_deg) > 0), 'P64:SquintSweep', ...
        'Reviewed squint sweep changed or is malformed.');
    assert(isequal(controls.snr_sweep_db, [-5 5 15 25]) && ...
        numel(controls.snr_sweep_db) <= controls.maximum_sweep_cases && ...
        all(diff(controls.snr_sweep_db) > 0), 'P64:SNRSweepControl', ...
        'Reviewed SNR sweep changed or is malformed.');
    assert(controls.broken_right_gain == 1.12 && ...
        controls.broken_target_angle_deg == 0.0, 'P64:BrokenContract', ...
        'Reviewed broken mismatch changed.');
    assert(controls.maximum_private_values == 20000 && ...
        controls.maximum_working_numeric_values == 500000 && ...
        controls.maximum_figures == 5 && controls.maximum_sweep_cases == 5, ...
        'P64:ResourceContract', 'Immutable resource ceilings changed.');
    private_request = 2*controls.maximum_elements*controls.number_snapshots;
    working_request = controls.number_elements*controls.number_snapshots+ ...
        8*numel(controls.pattern_angles_deg)+ ...
        controls.maximum_sweep_cases*numel(controls.pattern_angles_deg);
    assert(private_request <= controls.maximum_private_values && ...
        working_request <= controls.maximum_working_numeric_values, ...
        'P64:ResourceBound', 'Reviewed allocations exceed immutable ceilings.');
end

function [left_pattern, right_pattern] = aligned_beam_patterns( ...
        number_elements, spacing_wavelengths, squint_deg, angles_deg)
    element_index = (0:number_elements-1).';
    steering = exp(1j*2*pi*spacing_wavelengths*element_index*sind(angles_deg));
    left_weight = exp(1j*2*pi*spacing_wavelengths*element_index* ...
        sind(-squint_deg))/number_elements;
    right_weight = exp(1j*2*pi*spacing_wavelengths*element_index* ...
        sind(squint_deg))/number_elements;
    left_phase = exp(-1j*angle(left_weight'*ones(number_elements, 1)));
    right_phase = exp(-1j*angle(right_weight'*ones(number_elements, 1)));
    left_pattern = (left_weight'*steering)*left_phase;
    right_pattern = (right_weight'*steering)*right_phase;
end

function [left_channel, right_channel] = monopulse_channels(sensor_data, ...
        number_elements, spacing_wavelengths, squint_deg)
    assert(isnumeric(sensor_data) && ismatrix(sensor_data) && ...
        size(sensor_data, 1) == number_elements && ...
        ~isempty(sensor_data) && all(isfinite(real(sensor_data(:)))) && ...
        all(isfinite(imag(sensor_data(:)))), 'P64:MalformedSensorData', ...
        'Sensor data must be a finite M-by-L complex matrix.');
    element_index = (0:number_elements-1).';
    left_weight = exp(1j*2*pi*spacing_wavelengths*element_index* ...
        sind(-squint_deg))/number_elements;
    right_weight = exp(1j*2*pi*spacing_wavelengths*element_index* ...
        sind(squint_deg))/number_elements;
    left_phase = exp(-1j*angle(left_weight'*ones(number_elements, 1)));
    right_phase = exp(-1j*angle(right_weight'*ones(number_elements, 1)));
    left_channel = (left_weight'*sensor_data)*left_phase;
    right_channel = (right_weight'*sensor_data)*right_phase;
end

function estimates_deg = ratio_to_angle(ratios, calibration_ratio, ...
        calibration_angles_deg)
    assert(isnumeric(ratios) && ~isempty(ratios) && ...
        all(isfinite(ratios(:))) && isreal(ratios), ...
        'P64:MalformedRatio', 'Ratios must be finite real values.');
    assert(isrow(calibration_ratio) && isrow(calibration_angles_deg) && ...
        numel(calibration_ratio) == numel(calibration_angles_deg) && ...
        numel(calibration_ratio) >= 2 && all(isfinite(calibration_ratio)) && ...
        all(isfinite(calibration_angles_deg)) && ...
        all(diff(calibration_ratio) > 0) && ...
        all(diff(calibration_angles_deg) > 0), 'P64:MalformedCalibration', ...
        'Calibration must be paired, finite, ordered row vectors.');
    ratio_shape = size(ratios);
    flat_ratios = ratios(:).';
    clipped = min(max(flat_ratios, calibration_ratio(1)), ...
        calibration_ratio(end));
    flat_estimates = zeros(size(clipped));
    for sample_index = 1:numel(clipped)
        upper_index = find(calibration_ratio >= clipped(sample_index), 1);
        if upper_index == 1
            flat_estimates(sample_index) = calibration_angles_deg(1);
        else
            lower_index = upper_index-1;
            fraction = (clipped(sample_index)-calibration_ratio(lower_index))/ ...
                (calibration_ratio(upper_index)-calibration_ratio(lower_index));
            flat_estimates(sample_index) = calibration_angles_deg(lower_index)+ ...
                fraction*(calibration_angles_deg(upper_index)- ...
                calibration_angles_deg(lower_index));
        end
    end
    estimates_deg = reshape(flat_estimates, ratio_shape);
end

function noise = private_complex_noise(seed, number_rows, number_columns, ...
        maximum_values)
    require_finite_integer(number_rows, 'number_rows');
    require_finite_integer(number_columns, 'number_columns');
    assert(number_rows >= 1 && number_columns >= 1, 'P64:NoiseShape', ...
        'Noise dimensions must be positive.');
    uniforms = private_uniform(seed, 2*number_rows*number_columns, ...
        maximum_values);
    first = uniforms(1:2:end);
    second = uniforms(2:2:end);
    samples = sqrt(-2*log(first)).*exp(1j*2*pi*second)/sqrt(2);
    noise = reshape(samples, number_rows, number_columns);
end

function values = private_uniform(seed, count, maximum_values)
    modulus = 2147483647;
    multiplier = 16807;
    require_finite_integer(seed, 'seed');
    require_finite_integer(count, 'count');
    require_finite_integer(maximum_values, 'maximum_values');
    assert(seed >= 1 && seed < modulus, 'P64:SeedRange', ...
        'Seed must be inside the Park-Miller state range.');
    assert(count >= 1 && count <= maximum_values, 'P64:PrivateBound', ...
        'Private generator request exceeds its immutable ceiling.');
    state = double(seed);
    values = zeros(1, count);
    for sample_index = 1:count
        state = mod(multiplier*state, modulus);
        values(sample_index) = (state+0.5)/modulus;
    end
end

function require_finite_integer(value, name)
    assert(isnumeric(value) && isscalar(value) && isreal(value) && ...
        isfinite(value) && value == floor(value), 'P64:MalformedInteger', ...
        '%s must be a finite integer scalar.', name);
end
