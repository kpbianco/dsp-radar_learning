%% P64 - Build an Amplitude-Comparison Monopulse Experiment
% How can sum and difference beams estimate small angle error around boresight?
% Convention: elements m=0,...,M-1 lie on +x, angle is measured from
% broadside, and a_m(theta)=exp(j*2*pi*m*(d/lambda)*sin(theta)).

clearvars;
clc;
close(findall(0, 'Type', 'figure', 'Tag', 'P64'));

%% Visible deterministic controls and immutable resource ceilings
baseline_seed = 6401;
number_elements = 12;
element_spacing_wavelengths = 0.5;
beam_squint_deg = 3.0;
target_angle_deg = 2.0;
target_phase_rad = 0.4;
receiver_snr_db = 15.0;
number_snapshots = 256;
pattern_angles_deg = -10:0.05:10;
calibration_limit_deg = 4.0;
sum_guard = 0.15;

squint_sweep_deg = [1.5 3.0 5.0];
snr_sweep_db = [-5 5 15 25];
broken_right_gain = 1.12;
broken_target_angle_deg = 0.0;

maximum_elements = 16;
maximum_snapshots = 512;
maximum_angle_samples = 1001;
maximum_sweep_cases = 5;
maximum_private_values = 20000;
maximum_working_numeric_values = 500000;
maximum_figures = 5;
comparison_tolerance = 1e-10;

controls = struct( ...
    'baseline_seed', baseline_seed, ...
    'number_elements', number_elements, ...
    'element_spacing_wavelengths', element_spacing_wavelengths, ...
    'beam_squint_deg', beam_squint_deg, ...
    'target_angle_deg', target_angle_deg, ...
    'target_phase_rad', target_phase_rad, ...
    'receiver_snr_db', receiver_snr_db, ...
    'number_snapshots', number_snapshots, ...
    'pattern_angles_deg', pattern_angles_deg, ...
    'calibration_limit_deg', calibration_limit_deg, ...
    'sum_guard', sum_guard, ...
    'squint_sweep_deg', squint_sweep_deg, ...
    'snr_sweep_db', snr_sweep_db, ...
    'broken_right_gain', broken_right_gain, ...
    'broken_target_angle_deg', broken_target_angle_deg, ...
    'maximum_elements', maximum_elements, ...
    'maximum_snapshots', maximum_snapshots, ...
    'maximum_angle_samples', maximum_angle_samples, ...
    'maximum_sweep_cases', maximum_sweep_cases, ...
    'maximum_private_values', maximum_private_values, ...
    'maximum_working_numeric_values', maximum_working_numeric_values, ...
    'maximum_figures', maximum_figures, ...
    'comparison_tolerance', comparison_tolerance);
validate_controls(controls);

%% Build left/right beams, then expose the sum and difference hybrid
element_index = (0:number_elements-1).';
steering = exp(1j*2*pi*element_spacing_wavelengths*element_index* ...
    sind(pattern_angles_deg));
left_steering = exp(1j*2*pi*element_spacing_wavelengths*element_index* ...
    sind(-beam_squint_deg));
right_steering = exp(1j*2*pi*element_spacing_wavelengths*element_index* ...
    sind(beam_squint_deg));
left_weight = left_steering/number_elements;
right_weight = right_steering/number_elements;

boresight_steering = ones(number_elements, 1);
left_boresight_voltage = left_weight'*boresight_steering;
right_boresight_voltage = right_weight'*boresight_steering;
left_phase_correction = exp(-1j*angle(left_boresight_voltage));
right_phase_correction = exp(-1j*angle(right_boresight_voltage));

left_pattern = (left_weight'*steering)*left_phase_correction;
right_pattern = (right_weight'*steering)*right_phase_correction;
sum_pattern = (right_pattern+left_pattern)/2;
difference_pattern = (right_pattern-left_pattern)/2;
normalized_ratio = real(difference_pattern./sum_pattern);

calibration_mask = abs(pattern_angles_deg) <= calibration_limit_deg;
calibration_angles_deg = pattern_angles_deg(calibration_mask);
calibration_ratio = normalized_ratio(calibration_mask);
assert(all(diff(calibration_ratio) > 0), 'P64:CalibrationMonotonic', ...
    'Reviewed Delta/Sigma calibration must be strictly increasing.');
assert(min(abs(sum_pattern(calibration_mask))) > sum_guard, ...
    'P64:CalibrationSumGuard', ...
    'Sum response is too small inside the reviewed calibration sector.');

figure('Name', 'P64 beam and comparator patterns', 'Tag', 'P64');
subplot(2, 1, 1);
plot(pattern_angles_deg, abs(left_pattern), 'LineWidth', 1.4);
hold on;
plot(pattern_angles_deg, abs(right_pattern), 'LineWidth', 1.4);
plot(pattern_angles_deg, abs(sum_pattern), 'k-', 'LineWidth', 1.4);
plot(pattern_angles_deg, abs(difference_pattern), 'm--', 'LineWidth', 1.4);
grid on;
xlabel('Angle from boresight (deg)');
ylabel('Normalized voltage magnitude');
title('Overlapping beams and explicit Sigma/Delta hybrid');
legend('|L|', '|R|', '|Sigma|', '|Delta|', 'Location', 'best');
subplot(2, 1, 2);
plot(pattern_angles_deg, normalized_ratio, 'b-', 'LineWidth', 1.5);
hold on;
plot(calibration_angles_deg, calibration_ratio, 'r-', 'LineWidth', 2.2);
line([-calibration_limit_deg calibration_limit_deg], [0 0], ...
    'Color', [0.3 0.3 0.3], 'LineStyle', ':');
grid on;
xlabel('Angle from boresight (deg)');
ylabel('Re\{Delta/Sigma\} (unitless)');
title('Signed local error ratio; red is the calibrated interval');
legend('Full plotted ratio', 'Monotonic calibration', 'Zero error', ...
    'Location', 'best');

%% Baseline: one coherent target plus private deterministic receiver noise
target_steering = exp(1j*2*pi*element_spacing_wavelengths*element_index* ...
    sind(target_angle_deg));
target_voltage = exp(1j*target_phase_rad)*ones(1, number_snapshots);
baseline_noise = private_complex_noise(baseline_seed, maximum_elements, ...
    number_snapshots, maximum_private_values);
noise_scale = 10^(-receiver_snr_db/20);
baseline_sensor_data = target_steering*target_voltage+ ...
    noise_scale*baseline_noise(1:number_elements, :);

% The essential operation is visible: steer, phase-align, hybrid, normalize.
baseline_left = (left_weight'*baseline_sensor_data)*left_phase_correction;
baseline_right = (right_weight'*baseline_sensor_data)*right_phase_correction;
baseline_sum = (baseline_right+baseline_left)/2;
baseline_difference = (baseline_right-baseline_left)/2;
baseline_ratio_samples = real(baseline_difference./baseline_sum);
baseline_valid_samples = abs(baseline_sum) >= sum_guard;
assert(any(baseline_valid_samples), 'P64:NoValidBaseline', ...
    'No baseline snapshots have a safe sum-channel denominator.');
baseline_ratio_mean = real(mean(baseline_difference)/mean(baseline_sum));
assert(abs(mean(baseline_sum)) >= sum_guard, 'P64:MeanSumGuard', ...
    'Coherently averaged baseline sum channel is too weak.');
baseline_estimate_samples_deg = nan(size(baseline_ratio_samples));
baseline_estimate_samples_deg(baseline_valid_samples) = ratio_to_angle( ...
    baseline_ratio_samples(baseline_valid_samples), calibration_ratio, ...
    calibration_angles_deg);
baseline_estimate_deg = ratio_to_angle(baseline_ratio_mean, ...
    calibration_ratio, calibration_angles_deg);
baseline_snapshot_rmse_deg = sqrt(mean( ...
    (baseline_estimate_samples_deg(baseline_valid_samples)-target_angle_deg).^2));
assert(abs(baseline_estimate_deg-target_angle_deg) < 0.15, ...
    'P64:BaselineEstimate', ...
    'Deterministic coherent baseline must estimate the reviewed target.');

figure('Name', 'P64 noisy baseline estimate', 'Tag', 'P64');
subplot(2, 1, 1);
plot(1:number_snapshots, baseline_ratio_samples, '.', ...
    'Color', [0.25 0.45 0.8]);
hold on;
line([1 number_snapshots], [baseline_ratio_mean baseline_ratio_mean], ...
    'Color', [0.85 0.2 0.2], 'LineWidth', 1.6);
grid on;
xlabel('Snapshot index');
ylabel('Re\{Delta/Sigma\} (unitless)');
title(sprintf('Noisy ratio samples: target %.1f deg, SNR %.1f dB', ...
    target_angle_deg, receiver_snr_db));
legend('Single-snapshot ratio', 'Ratio after coherent channel averaging', ...
    'Location', 'best');
subplot(2, 1, 2);
plot(1:number_snapshots, baseline_estimate_samples_deg, '.', ...
    'Color', [0.3 0.6 0.35]);
hold on;
line([1 number_snapshots], [target_angle_deg target_angle_deg], ...
    'Color', 'k', 'LineStyle', '--', 'LineWidth', 1.4);
line([1 number_snapshots], [baseline_estimate_deg baseline_estimate_deg], ...
    'Color', [0.85 0.2 0.2], 'LineWidth', 1.6);
grid on;
