legend('1.5 deg squint', '3.0 deg squint', '5.0 deg squint', ...
    'Location', 'best');
subplot(2, 1, 2);
plot(squint_sweep_deg, squint_slopes_per_deg, 'o-', 'LineWidth', 1.5);
hold on;
plot(squint_sweep_deg, squint_boresight_sum, 's--', 'LineWidth', 1.5);
grid on;
xlabel('Left/right beam squint magnitude (deg)');
ylabel('Slope (1/deg) or |Sigma(0)| (normalized voltage)');
title('A steeper comparator trades against boresight sum strength');
legend('Local ratio slope', 'Boresight |Sigma|', 'Location', 'best');

%% Sweep 2: SNR changes random angle error, not the calibration curve
number_snr_cases = numel(snr_sweep_db);
snr_sweep_rmse_deg = zeros(1, number_snr_cases);
snr_sweep_coherent_estimate_deg = zeros(1, number_snr_cases);
snr_sweep_rejected_snapshots = zeros(1, number_snr_cases);
shared_noise = private_complex_noise(baseline_seed+1, maximum_elements, ...
    number_snapshots, maximum_private_values);
for case_index = 1:number_snr_cases
    current_snr_db = snr_sweep_db(case_index);
    current_data = target_steering*target_voltage+ ...
        10^(-current_snr_db/20)*shared_noise(1:number_elements, :);
    [current_left, current_right] = monopulse_channels(current_data, ...
        number_elements, element_spacing_wavelengths, beam_squint_deg);
    current_sum = (current_right+current_left)/2;
    current_difference = (current_right-current_left)/2;
    current_ratio = real(current_difference./current_sum);
    current_valid = abs(current_sum) >= sum_guard;
    assert(any(current_valid), 'P64:NoValidSweepSamples', ...
        'An SNR sweep case has no safe sum-channel samples.');
    current_estimates_deg = ratio_to_angle(current_ratio(current_valid), ...
        calibration_ratio, calibration_angles_deg);
    snr_sweep_rmse_deg(case_index) = sqrt(mean( ...
        (current_estimates_deg-target_angle_deg).^2));
    snr_sweep_rejected_snapshots(case_index) = sum(~current_valid);
    current_coherent_ratio = real(mean(current_difference)/mean(current_sum));
    assert(abs(mean(current_sum)) >= sum_guard, 'P64:SweepMeanSumGuard', ...
        'An averaged SNR sweep sum channel is too weak.');
    snr_sweep_coherent_estimate_deg(case_index) = ratio_to_angle( ...
        current_coherent_ratio, calibration_ratio, calibration_angles_deg);
end
assert(all(diff(snr_sweep_rmse_deg) < 0), 'P64:SNRSweep', ...
    'Reviewed snapshot angle RMSE must fall as SNR rises.');

