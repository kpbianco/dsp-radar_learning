%% Deterministic amplitude- and phase-varying real bandpass signal
time_s = (0:record_sample_count-1)/fs_hz;
private_stream = RandStream('mt19937ar', 'Seed', random_seed);
baseline_noise_v = noise_rms_v*randn(private_stream, 1, record_sample_count);
broken_noise_v = broken_noise_rms_v*randn(private_stream, 1, record_sample_count);

designed_envelope_v = 1 + baseline_envelope_depth* ...
    cos(2*pi*envelope_modulation_frequency_hz*time_s);
designed_phase_rad = 2*pi*carrier_frequency_hz*time_s + carrier_phase_rad + ...
    baseline_phase_deviation_rad* ...
    sin(2*pi*phase_modulation_frequency_hz*time_s);
designed_instantaneous_frequency_hz = carrier_frequency_hz + ...
    baseline_phase_deviation_rad*phase_modulation_frequency_hz* ...
    cos(2*pi*phase_modulation_frequency_hz*time_s);
real_bandpass_v = designed_envelope_v.*cos(designed_phase_rad) + baseline_noise_v;

%% Form the analytic signal explicitly: keep DC/Nyquist, double +f, zero -f
% For even N, Z[k] = X[k]H[k], with H = [1, 2...2, 1, 0...0].
real_spectrum_v = fft(real_bandpass_v);
analytic_fft_mask = zeros(1, record_sample_count);
analytic_fft_mask(1) = 1;
analytic_fft_mask(2:record_sample_count/2) = 2;
analytic_fft_mask(record_sample_count/2 + 1) = 1;
analytic_signal_v = ifft(real_spectrum_v.*analytic_fft_mask);

recovered_envelope_v = abs(analytic_signal_v);
recovered_phase_rad = unwrap(angle(analytic_signal_v));
recovered_instantaneous_frequency_hz = [NaN ...
    diff(recovered_phase_rad)*fs_hz/(2*pi)];
analytic_spectrum_v = fft(analytic_signal_v);
frequency_hz = (-record_sample_count/2:record_sample_count/2-1)* ...
    fs_hz/record_sample_count;

evaluation_mask = false(1, record_sample_count);
evaluation_mask(edge_guard_sample_count+1: ...
    record_sample_count-edge_guard_sample_count) = true;
frequency_evaluation_mask = evaluation_mask;
frequency_evaluation_mask(1) = false;
envelope_rmse_v = sqrt(mean((recovered_envelope_v(evaluation_mask) - ...
    designed_envelope_v(evaluation_mask)).^2));
instantaneous_frequency_rmse_hz = sqrt(mean(( ...
    recovered_instantaneous_frequency_hz(frequency_evaluation_mask) - ...
    designed_instantaneous_frequency_hz(frequency_evaluation_mask)).^2));
real_reconstruction_max_error_v = max(abs(real(analytic_signal_v) - ...
    real_bandpass_v));
positive_frequency_energy_v2 = sum(abs(analytic_spectrum_v( ...
    2:record_sample_count/2)).^2);
negative_frequency_energy_v2 = sum(abs(analytic_spectrum_v( ...
    record_sample_count/2+2:end)).^2);
negative_frequency_suppression_db = 10*log10( ...
    max(positive_frequency_energy_v2, eps)/ ...
    max(negative_frequency_energy_v2, eps));

fprintf('\nP16 baseline: analytic signal from an explicit FFT mask\n');
fprintf('  envelope RMSE away from edges: %.6f V\n', envelope_rmse_v);
fprintf('  instantaneous-frequency RMSE away from edges: %.3f Hz\n', ...
    instantaneous_frequency_rmse_hz);
fprintf('  max real-part reconstruction error: %.3e V\n', ...
    real_reconstruction_max_error_v);
fprintf('  positive/negative analytic energy ratio: %.1f dB\n', ...
    negative_frequency_suppression_db);

