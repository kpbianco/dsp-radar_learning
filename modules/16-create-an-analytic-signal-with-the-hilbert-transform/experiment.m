%% Broken case: envelope approaches zero, so phase and its derivative explode
broken_envelope_v = 1 - (1-broken_minimum_envelope_v)*exp(-0.5*( ...
    (time_s-broken_notch_center_s)/broken_notch_width_s).^2);
broken_real_v = broken_envelope_v.*cos(designed_phase_rad) + broken_noise_v;
broken_spectrum_v = fft(broken_real_v);
broken_analytic_v = ifft(broken_spectrum_v.*analytic_fft_mask);
broken_recovered_envelope_v = abs(broken_analytic_v);
broken_recovered_phase_rad = unwrap(angle(broken_analytic_v));
broken_raw_frequency_hz = [NaN ...
    diff(broken_recovered_phase_rad)*fs_hz/(2*pi)];
broken_magnitude_reliable_mask = ...
    broken_recovered_envelope_v >= reliability_threshold_v;
% f[n] uses phase[n] and phase[n-1], so both endpoint magnitudes must support
% a stable angle. This also rejects the first transition out of the notch.
broken_reliable_mask = broken_magnitude_reliable_mask & ...
    [false broken_magnitude_reliable_mask(1:end-1)] & evaluation_mask;
broken_recovered_frequency_hz = broken_raw_frequency_hz;
broken_recovered_frequency_hz(~broken_reliable_mask) = NaN;
broken_unreliable_sample_count = sum(~broken_reliable_mask & evaluation_mask);
broken_valid_frequency_rmse_hz = sqrt(mean(( ...
    broken_raw_frequency_hz(broken_reliable_mask) - ...
    designed_instantaneous_frequency_hz(broken_reliable_mask)).^2));
broken_low_amplitude_mask = broken_recovered_envelope_v < ...
    reliability_threshold_v & frequency_evaluation_mask;
assert(any(broken_low_amplitude_mask) && any(broken_reliable_mask), ...
    ['The broken case must contain both rejected low-amplitude samples and ' ...
