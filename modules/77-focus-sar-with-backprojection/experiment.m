%% Local transparent helpers
function predicted_backprojection_operations = validate_controls(controls)
vector_names = {'target_cross_range_m', 'target_ground_range_m', ...
    'target_voltage', 'target_initial_phase_rad', ...
    'image_cross_range_m', 'image_ground_range_m', ...
