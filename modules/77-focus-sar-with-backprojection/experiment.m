        'Every target property vector must have the same length.');
end
scalar_names = {'seed', 'c_mps', 'carrier_hz', ...
    'range_gate_start_m', 'range_gate_end_m', 'range_spacing_m', ...
    'range_resolution_m', 'aperture_length_m', 'platform_spacing_m', ...
    'noise_rms_voltage', 'max_aperture_samples', 'max_range_samples', ...
    'max_image_pixels', 'max_targets', 'max_sweep_cases', ...
    'max_private_values', 'max_backprojection_operations', ...
    'max_working_values', 'max_figures', 'max_phase_step_rad', ...
    'min_input_coherence', 'min_recovered_coherence', ...
    'max_broken_coherence', 'max_cross_range_error_m', ...
    'max_ground_range_error_m'};
for scalar_index = 1:numel(scalar_names)
    name = scalar_names{scalar_index};
    value = controls.(name);
    if ~isnumeric(value) || ~isreal(value) || numel(value) ~= 1 || ...
            ~isfinite(value)
        error('P77:ControlScalar', '%s must be a finite real scalar.', name);
    end
end
if controls.seed ~= floor(controls.seed) || controls.seed < 1 || ...
        controls.seed >= 2147483647
    error('P77:Seed', 'Seed must be an integer in [1, 2147483646].');
end
positive_names = {'c_mps', 'carrier_hz', 'range_gate_start_m', ...
    'range_gate_end_m', 'range_spacing_m', 'range_resolution_m', ...
    'aperture_length_m', 'platform_spacing_m', ...
    'max_aperture_samples', 'max_range_samples', 'max_image_pixels', ...
    'max_targets', 'max_sweep_cases', 'max_private_values', ...
    'max_backprojection_operations', 'max_working_values', ...
    'max_figures', 'max_phase_step_rad', 'min_input_coherence', ...
    'min_recovered_coherence', 'max_broken_coherence', ...
    'max_cross_range_error_m', 'max_ground_range_error_m'};
for scalar_index = 1:numel(positive_names)
    if controls.(positive_names{scalar_index}) <= 0
        error('P77:PositiveControl', '%s must be positive.', ...
            positive_names{scalar_index});
    end
end
if controls.noise_rms_voltage < 0
    error('P77:NoiseScale', 'Noise RMS must be nonnegative.');
end
if controls.range_gate_end_m <= controls.range_gate_start_m || ...
        controls.range_resolution_m < controls.range_spacing_m
    error('P77:RangeControls', ...
        'Range gate and compressed-response scales are inconsistent.');
end
if any(controls.target_ground_range_m <= 0) || ...
        any(controls.target_voltage <= 0) || ...
        any(controls.path_error_sweep_m < 0)
    error('P77:PositiveVectors', ...
        'Target ranges/voltages must be positive and path errors nonnegative.');
end
if any(diff(controls.image_cross_range_m) <= 0) || ...
        any(diff(controls.image_ground_range_m) <= 0) || ...
        any(diff(controls.partial_counts) <= 0) || ...
        any(diff(controls.path_error_sweep_m) <= 0)
    error('P77:SweepOrder', ...
        'Image axes and reviewed sweep cases must increase strictly.');
end
if controls.path_error_sweep_m(1) ~= 0 || ...
        numel(controls.path_error_sweep_m) ~= 3 || ...
        numel(controls.partial_counts) ~= 3
    error('P77:SweepCount', ...
        'Both reviewed sweeps require exactly three cases and zero-error first.');
end
if controls.max_phase_step_rad >= pi || ...
        controls.min_input_coherence >= 1 || ...
        controls.min_recovered_coherence >= 1 || ...
        controls.max_broken_coherence >= controls.min_recovered_coherence
    error('P77:MetricLimits', ...
        'Phase, coherence, or localization limits are inconsistent.');
end
if controls.max_figures ~= 6
    error('P77:FigureCeiling', ...
        'The immutable figure count must equal six reviewed figure groups.');
end
if abs(controls.aperture_length_m/(2*controls.platform_spacing_m)- ...
        round(controls.aperture_length_m/(2*controls.platform_spacing_m))) ...
        > 1.0e-9
    error('P77:ApertureGrid', ...
        'Half-aperture must land exactly on the platform grid.');
end
range_span_samples = (controls.range_gate_end_m- ...
    controls.range_gate_start_m)/controls.range_spacing_m;
if abs(range_span_samples-round(range_span_samples)) > 1.0e-9
    error('P77:RangeGrid', ...
        'Range-gate endpoints must land exactly on the range grid.');
end
image_x_step = diff(controls.image_cross_range_m);
image_y_step = diff(controls.image_ground_range_m);
if numel(controls.image_cross_range_m) < 3 || ...
        numel(controls.image_ground_range_m) < 3
    error('P77:ImageGrid', ...
        'Image axes need at least three samples for supported response cuts.');
end
if max(abs(image_x_step-image_x_step(1))) > 1.0e-12 || ...
        max(abs(image_y_step-image_y_step(1))) > 1.0e-12
    error('P77:ImageGrid', 'Image axes must be uniformly spaced.');
end
for target_index = 1:target_count
    if min(abs(controls.image_cross_range_m- ...
            controls.target_cross_range_m(target_index))) > 1.0e-9 || ...
            min(abs(controls.image_ground_range_m- ...
            controls.target_ground_range_m(target_index))) > 1.0e-9
        error('P77:TargetImageGrid', ...
            'Every target coordinate must lie on the reviewed image grid.');
    end
end

aperture_samples = round(controls.aperture_length_m/ ...
    controls.platform_spacing_m)+1;
range_samples = round(range_span_samples)+1;
image_pixels = numel(controls.image_cross_range_m)* ...
    numel(controls.image_ground_range_m);
if aperture_samples > controls.max_aperture_samples || ...
        range_samples > controls.max_range_samples || ...
        image_pixels > controls.max_image_pixels || ...
        target_count > controls.max_targets
    error('P77:ResourceCeilings', ...
        'Aperture, range, image, or target count exceeds its ceiling.');
end
if numel(controls.partial_counts) > controls.max_sweep_cases || ...
        numel(controls.path_error_sweep_m) > controls.max_sweep_cases
    error('P77:SweepCeiling', 'A sweep exceeds its immutable case ceiling.');
end
if any(controls.partial_counts <= 0) || ...
        any(controls.partial_counts ~= floor(controls.partial_counts)) || ...
        any(mod(controls.partial_counts, 2) ~= 1) || ...
        controls.partial_counts(end) ~= aperture_samples || ...
        any(controls.partial_counts > aperture_samples)
    error('P77:PartialApertureCounts', ...
        'Partial look counts must be increasing odd counts ending at full aperture.');
end
if 2*aperture_samples*range_samples > controls.max_private_values
    error('P77:PrivateCeiling', ...
        'The private noise request exceeds its immutable ceiling.');
end
nonzero_path_case_count = numel(controls.path_error_sweep_m)-1;
recovery_case_count = 1;
predicted_backprojection_operations = image_pixels*( ...
    sum(controls.partial_counts)+aperture_samples*( ...
    nonzero_path_case_count+recovery_case_count));
if predicted_backprojection_operations > ...
        controls.max_backprojection_operations
    error('P77:BackprojectionPreflight', ...
        'Predicted pixel-look work exceeds its immutable ceiling.');
end
predicted_working_values = 30*image_pixels*( ...
    numel(controls.partial_counts)+numel(controls.path_error_sweep_m))+ ...
    20*aperture_samples*range_samples;
if predicted_working_values > controls.max_working_values
    error('P77:WorkingPreflight', ...
        'Conservative working-storage prediction exceeds its ceiling.');
end

platform_position_m = -controls.aperture_length_m/2: ...
    controls.platform_spacing_m:controls.aperture_length_m/2;
wavelength_m = controls.c_mps/controls.carrier_hz;
for target_index = 1:target_count
    slant_range_m = hypot(platform_position_m- ...
        controls.target_cross_range_m(target_index), ...
        controls.target_ground_range_m(target_index));
    phase_rad = -4*pi*(slant_range_m-controls.range_gate_start_m)/ ...
        wavelength_m;
    if max(abs(diff(phase_rad))) >= controls.max_phase_step_rad
        error('P77:SpatialAliasing', ...
            'A target exceeds the adjacent aperture phase-step limit.');
    end
    if min(slant_range_m) <= controls.range_gate_start_m+ ...
            controls.range_spacing_m || ...
            max(slant_range_m) >= controls.range_gate_end_m- ...
            controls.range_spacing_m
        error('P77:TargetRangeSupport', ...
            'The range grid does not contain every target ridge for interpolation.');
    end
end
[image_x_grid_m, image_y_grid_m] = meshgrid( ...
    controls.image_cross_range_m, controls.image_ground_range_m);
maximum_path_error_m = max(controls.path_error_sweep_m);
for aperture_index = 1:aperture_samples
    minimum_hypothesized_range_m = min(min(hypot( ...
        platform_position_m(aperture_index)-image_x_grid_m, ...
        image_y_grid_m-maximum_path_error_m)));
    maximum_hypothesized_range_m = max(max(hypot( ...
        platform_position_m(aperture_index)-image_x_grid_m, ...
        image_y_grid_m+maximum_path_error_m)));
    if minimum_hypothesized_range_m <= controls.range_gate_start_m || ...
            maximum_hypothesized_range_m >= controls.range_gate_end_m
        error('P77:ImageRangeSupport', ...
            'The range grid does not support every reviewed image hypothesis.');
    end
end
end

