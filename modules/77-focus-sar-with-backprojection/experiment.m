function [image_complex, operation_count] = backproject_image(range_history, ...
        platform_position_m, selected_indices, range_axis_m, ...
        image_cross_range_m, image_ground_range_m, wavelength_m, ...
        range_reference_m, assumed_path_error_m, maximum_operations)
if ~isnumeric(range_history) || isempty(range_history) || ...
        any(~isfinite(real(range_history(:)))) || ...
        any(~isfinite(imag(range_history(:))))
    error('P77:BackprojectionData', ...
        'Range history must be a finite nonempty numeric matrix.');
end
if ~isnumeric(platform_position_m) || ~isreal(platform_position_m) || ...
        isempty(platform_position_m) || size(platform_position_m, 1) ~= 1 || ...
        any(~isfinite(platform_position_m)) || ...
        ~isnumeric(assumed_path_error_m) || ...
        ~isreal(assumed_path_error_m) || ...
        size(assumed_path_error_m, 1) ~= 1 || ...
        any(~isfinite(assumed_path_error_m))
    error('P77:BackprojectionPlatform', ...
        'Platform and assumed path error must be finite real row vectors.');
end
if size(range_history, 1) ~= numel(platform_position_m) || ...
        size(range_history, 2) ~= numel(range_axis_m) || ...
        numel(assumed_path_error_m) ~= numel(platform_position_m)
    error('P77:BackprojectionShape', ...
        'Data, platform, range, and path-error dimensions must agree.');
end
if ~isnumeric(selected_indices) || ~isreal(selected_indices) || ...
        size(selected_indices, 1) ~= 1 || any(~isfinite(selected_indices)) || ...
        isempty(selected_indices) || ...
        any(selected_indices ~= floor(selected_indices)) || ...
        any(selected_indices < 1) || ...
        any(selected_indices > numel(platform_position_m)) || ...
        any(diff(selected_indices) <= 0)
    error('P77:SelectedLooks', ...
        'Selected aperture indices must be unique increasing valid integers.');
end
if ~isnumeric(range_axis_m) || ~isreal(range_axis_m) || ...
        size(range_axis_m, 1) ~= 1 || any(~isfinite(range_axis_m)) || ...
        any(diff(range_axis_m) <= 0) || numel(range_axis_m) < 2 || ...
        max(abs(diff(range_axis_m)-diff(range_axis_m(1:2)))) > 1.0e-12
    error('P77:BackprojectionRangeAxis', ...
        'Range axis must be a uniformly increasing vector.');
end
if ~isnumeric(image_cross_range_m) || ~isreal(image_cross_range_m) || ...
        isempty(image_cross_range_m) || size(image_cross_range_m, 1) ~= 1 || ...
        any(~isfinite(image_cross_range_m)) || ...
        any(diff(image_cross_range_m) <= 0) || ...
        ~isnumeric(image_ground_range_m) || ~isreal(image_ground_range_m) || ...
        isempty(image_ground_range_m) || size(image_ground_range_m, 1) ~= 1 || ...
        any(~isfinite(image_ground_range_m)) || ...
        any(diff(image_ground_range_m) <= 0)
    error('P77:BackprojectionImageAxes', ...
        'Image axes must be finite real increasing row vectors.');
end
if ~isscalar(wavelength_m) || ~isfinite(wavelength_m) || ...
        wavelength_m <= 0 || ~isscalar(range_reference_m) || ...
        ~isfinite(range_reference_m)
    error('P77:BackprojectionPhaseControls', ...
        'Wavelength and range reference must be valid finite scalars.');
end
if ~isnumeric(maximum_operations) || ~isreal(maximum_operations) || ...
        ~isscalar(maximum_operations) || ~isfinite(maximum_operations) || ...
        maximum_operations <= 0
    error('P77:BackprojectionOperationBound', ...
        'The pixel-look operation ceiling must be a positive finite scalar.');
end
[image_x_grid_m, image_y_grid_m] = meshgrid( ...
    image_cross_range_m, image_ground_range_m);
operation_count = numel(image_x_grid_m)*numel(selected_indices);
if operation_count > maximum_operations
    error('P77:BackprojectionOperationBound', ...
        'Requested backprojection exceeds its pixel-look operation ceiling.');
end

range_spacing_m = range_axis_m(2)-range_axis_m(1);
image_complex = zeros(size(image_x_grid_m));
for selected_index = 1:numel(selected_indices)
    aperture_index = selected_indices(selected_index);
    hypothesized_range_m = hypot( ...
        platform_position_m(aperture_index)-image_x_grid_m, ...
        image_y_grid_m+assumed_path_error_m(aperture_index));

    % Explicit linear interpolation of this complex range-compressed row.
    fractional_index = (hypothesized_range_m-range_axis_m(1))/ ...
        range_spacing_m+1;
    left_index = floor(fractional_index);
    right_weight = fractional_index-left_index;
    valid = left_index >= 1 & left_index < numel(range_axis_m);
    sampled_complex_value = zeros(size(hypothesized_range_m));
    valid_linear_index = find(valid);
    valid_left_index = left_index(valid_linear_index);
    valid_right_weight = right_weight(valid_linear_index);
    aperture_row = range_history(aperture_index, :);
    left_value = reshape(aperture_row(valid_left_index), ...
        size(valid_left_index));
    right_value = reshape(aperture_row(valid_left_index+1), ...
        size(valid_left_index));
    sampled_complex_value(valid_linear_index) = ...
        (1-valid_right_weight).*left_value+ ...
        valid_right_weight.*right_value;

    % The positive phase cancels negative monostatic propagation phase.
    phase_compensation = exp(1j*4*pi*(hypothesized_range_m- ...
        range_reference_m)/wavelength_m);
    image_complex = image_complex+sampled_complex_value.* ...
        phase_compensation;
end
end

function terms = pixel_backprojection_terms(range_history, ...
        platform_position_m, selected_indices, range_axis_m, ...
        pixel_cross_range_m, pixel_ground_range_m, wavelength_m, ...
        range_reference_m, assumed_path_error_m)
if ~isnumeric(range_history) || isempty(range_history) || ...
        any(~isfinite(real(range_history(:)))) || ...
        any(~isfinite(imag(range_history(:)))) || ...
        ~isnumeric(platform_position_m) || ~isreal(platform_position_m) || ...
        size(platform_position_m, 1) ~= 1 || ...
        any(~isfinite(platform_position_m)) || ...
        ~isnumeric(assumed_path_error_m) || ...
        ~isreal(assumed_path_error_m) || ...
        size(assumed_path_error_m, 1) ~= 1 || ...
        any(~isfinite(assumed_path_error_m)) || ...
        size(range_history, 1) ~= numel(platform_position_m) || ...
        size(range_history, 2) ~= numel(range_axis_m) || ...
        numel(assumed_path_error_m) ~= numel(platform_position_m)
    error('P77:PixelTermShape', ...
        'Pixel-term data, platform, range, and path-error shapes must agree.');
end
if ~isnumeric(selected_indices) || ~isreal(selected_indices) || ...
        isempty(selected_indices) || size(selected_indices, 1) ~= 1 || ...
        any(~isfinite(selected_indices)) || ...
        any(selected_indices ~= floor(selected_indices)) || ...
        any(selected_indices < 1) || ...
        any(selected_indices > numel(platform_position_m))
    error('P77:PixelTermShape', ...
        'Pixel-term platform, indices, and path-error dimensions must agree.');
end
if ~isnumeric(range_axis_m) || ~isreal(range_axis_m) || ...
        size(range_axis_m, 1) ~= 1 || numel(range_axis_m) < 2 || ...
        any(~isfinite(range_axis_m)) || any(diff(range_axis_m) <= 0) || ...
        max(abs(diff(range_axis_m)-diff(range_axis_m(1:2)))) > 1.0e-12 || ...
        ~isnumeric(pixel_cross_range_m) || ~isreal(pixel_cross_range_m) || ...
        ~isscalar(pixel_cross_range_m) || ~isfinite(pixel_cross_range_m) || ...
        ~isnumeric(pixel_ground_range_m) || ~isreal(pixel_ground_range_m) || ...
        ~isscalar(pixel_ground_range_m) || ~isfinite(pixel_ground_range_m) || ...
        ~isnumeric(wavelength_m) || ~isreal(wavelength_m) || ...
        ~isscalar(wavelength_m) || ~isfinite(wavelength_m) || ...
        wavelength_m <= 0 || ~isnumeric(range_reference_m) || ...
        ~isreal(range_reference_m) || ~isscalar(range_reference_m) || ...
        ~isfinite(range_reference_m)
    error('P77:PixelTermControls', ...
        'Pixel-term axes, coordinate, and phase controls must be finite.');
end
range_spacing_m = range_axis_m(2)-range_axis_m(1);
terms = zeros(numel(selected_indices), 1);
for selected_index = 1:numel(selected_indices)
    aperture_index = selected_indices(selected_index);
    hypothesized_range_m = hypot( ...
        platform_position_m(aperture_index)-pixel_cross_range_m, ...
        pixel_ground_range_m+assumed_path_error_m(aperture_index));
    fractional_index = (hypothesized_range_m-range_axis_m(1))/ ...
        range_spacing_m+1;
    left_index = floor(fractional_index);
    if left_index < 1 || left_index >= numel(range_axis_m)
        error('P77:PixelTermRange', ...
            'Pixel hypothesis falls outside interpolation support.');
    end
    right_weight = fractional_index-left_index;
    sampled_value = (1-right_weight)*range_history(aperture_index, ...
        left_index)+right_weight*range_history(aperture_index, ...
        left_index+1);
    terms(selected_index) = sampled_value*exp(1j*4*pi*( ...
        hypothesized_range_m-range_reference_m)/wavelength_m);
end
end

function width_m = half_power_width(magnitude, coordinate_m)
magnitude = magnitude(:).';
coordinate_m = coordinate_m(:).';
if numel(magnitude) ~= numel(coordinate_m) || numel(magnitude) < 3 || ...
        any(~isfinite(magnitude)) || any(~isfinite(coordinate_m)) || ...
        any(diff(coordinate_m) <= 0) || max(magnitude) <= 0
    error('P77:WidthInput', ...
        'Width inputs must be finite, ordered, and nonzero.');
end
[peak, peak_index] = max(magnitude);
threshold = peak/sqrt(2);
left_index = peak_index;
while left_index > 1 && magnitude(left_index) >= threshold
    left_index = left_index-1;
end
right_index = peak_index;
while right_index < numel(magnitude) && magnitude(right_index) >= threshold
    right_index = right_index+1;
end
if magnitude(left_index) >= threshold || ...
        magnitude(right_index) >= threshold
    error('P77:WidthSupport', ...
        'Half-power crossings require support on both sides.');
end
left_coordinate_m = coordinate_m(left_index)+(threshold- ...
    magnitude(left_index))*(coordinate_m(left_index+1)- ...
    coordinate_m(left_index))/(magnitude(left_index+1)- ...
    magnitude(left_index));
right_coordinate_m = coordinate_m(right_index-1)+(threshold- ...
    magnitude(right_index-1))*(coordinate_m(right_index)- ...
    coordinate_m(right_index-1))/(magnitude(right_index)- ...
    magnitude(right_index-1));
width_m = right_coordinate_m-left_coordinate_m;
end

function values = private_complex_noise(seed, count, maximum_count)
if ~isscalar(seed) || ~isfinite(seed) || seed ~= floor(seed) || ...
        seed < 1 || seed >= 2147483647
    error('P77:PrivateSeed', 'Private seed is outside the supported range.');
end
if ~isscalar(count) || ~isfinite(count) || count ~= floor(count) || ...
        count < 1 || 2*count > maximum_count
    error('P77:PrivateCount', ...
        'Private generator request exceeds its ceiling.');
end
uniforms = zeros(1, 2*count);
state = seed;
for sample_index = 1:2*count
    state = mod(16807*state, 2147483647);
    uniforms(sample_index) = state/2147483647;
end
radius = sqrt(-2*log(max(uniforms(1:2:end), realmin)));
angle_rad = 2*pi*uniforms(2:2:end);
values = radius.*exp(1j*angle_rad)/sqrt(2);
end
