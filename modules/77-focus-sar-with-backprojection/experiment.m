%% P77: Focus SAR with Backprojection
% Guiding question:
% How does compensating the correct path length focus a point in an image?
%
% Base MATLAB only. This script constructs a seeded range-compressed complex
% phase history, then explicitly predicts slant range, linearly interpolates
% each aperture row, applies two-way carrier phase compensation, and sums.

close(findall(0, 'Type', 'figure', 'Tag', 'P77'));
clear p77_results;
p77_results = run_p77_experiment();

function p77_results = run_p77_experiment()

%% Visible deterministic controls and immutable resource ceilings
baseline_seed = 7701;
speed_of_light_mps = 3.0e8;
carrier_frequency_hz = 5.0e9;
range_gate_start_m = 990.0;
range_gate_end_m = 1035.0;
range_sample_spacing_m = 0.5;
range_resolution_m = 2.5;
aperture_length_m = 30.0;
platform_spacing_m = 0.25;
target_cross_range_m = [-6.0 7.0];
target_ground_range_m = [1002.0 1020.0];
target_voltage = [1.0 0.75];
target_initial_phase_rad = [0.0 0.7];
noise_rms_voltage = 0.015;
image_cross_range_m = -15.0:0.25:15.0;
image_ground_range_m = 995.0:0.5:1027.0;
partial_aperture_counts = [21 61 121];
path_error_sweep_m = [0.0 0.005 0.010];

maximum_aperture_samples = 201;
maximum_range_samples = 121;
maximum_image_pixels = 10000;
maximum_targets = 4;
maximum_sweep_cases = 5;
maximum_private_values = 30000;
maximum_backprojection_operations = 5000000;
maximum_working_value_equivalents = 5000000;
maximum_figures = 6;
maximum_adjacent_phase_step_rad = 0.90*pi;
minimum_input_phase_coherence = 0.99;
minimum_recovered_coherence = 0.98;
maximum_broken_coherence = 0.35;
maximum_cross_range_error_m = 0.25;
maximum_ground_range_error_m = 0.5;

controls = struct( ...
    'seed', baseline_seed, 'c_mps', speed_of_light_mps, ...
    'carrier_hz', carrier_frequency_hz, ...
    'range_gate_start_m', range_gate_start_m, ...
    'range_gate_end_m', range_gate_end_m, ...
    'range_spacing_m', range_sample_spacing_m, ...
    'range_resolution_m', range_resolution_m, ...
    'aperture_length_m', aperture_length_m, ...
    'platform_spacing_m', platform_spacing_m, ...
    'target_cross_range_m', target_cross_range_m, ...
    'target_ground_range_m', target_ground_range_m, ...
    'target_voltage', target_voltage, ...
    'target_initial_phase_rad', target_initial_phase_rad, ...
    'noise_rms_voltage', noise_rms_voltage, ...
    'image_cross_range_m', image_cross_range_m, ...
    'image_ground_range_m', image_ground_range_m, ...
    'partial_counts', partial_aperture_counts, ...
    'path_error_sweep_m', path_error_sweep_m, ...
    'max_aperture_samples', maximum_aperture_samples, ...
    'max_range_samples', maximum_range_samples, ...
    'max_image_pixels', maximum_image_pixels, ...
    'max_targets', maximum_targets, ...
    'max_sweep_cases', maximum_sweep_cases, ...
    'max_private_values', maximum_private_values, ...
    'max_backprojection_operations', ...
    maximum_backprojection_operations, ...
    'max_working_values', maximum_working_value_equivalents, ...
    'max_figures', maximum_figures, ...
    'max_phase_step_rad', maximum_adjacent_phase_step_rad, ...
    'min_input_coherence', minimum_input_phase_coherence, ...
    'min_recovered_coherence', minimum_recovered_coherence, ...
    'max_broken_coherence', maximum_broken_coherence, ...
    'max_cross_range_error_m', maximum_cross_range_error_m, ...
    'max_ground_range_error_m', maximum_ground_range_error_m);
predicted_backprojection_operations = validate_controls(controls);

wavelength_m = speed_of_light_mps/carrier_frequency_hz;
platform_position_m = -aperture_length_m/2:platform_spacing_m: ...
    aperture_length_m/2;
range_axis_m = range_gate_start_m:range_sample_spacing_m:range_gate_end_m;
aperture_sample_count = numel(platform_position_m);
range_sample_count = numel(range_axis_m);
[image_cross_range_grid_m, image_ground_range_grid_m] = meshgrid( ...
    image_cross_range_m, image_ground_range_m);
image_pixel_count = numel(image_cross_range_grid_m);

%% Deterministic range-compressed complex phase history
% One fixed reference is used in both synthesis and image formation.
range_reference_m = range_gate_start_m;
clean_range_history = zeros(aperture_sample_count, range_sample_count);
target_slant_range_m = zeros(aperture_sample_count, numel(target_voltage));
target_phase_rad = zeros(aperture_sample_count, numel(target_voltage));

for target_index = 1:numel(target_voltage)
    target_slant_range_m(:, target_index) = hypot( ...
        platform_position_m(:)-target_cross_range_m(target_index), ...
        target_ground_range_m(target_index));
    target_phase_rad(:, target_index) = ...
        target_initial_phase_rad(target_index)-4*pi*( ...
        target_slant_range_m(:, target_index)-range_reference_m)/ ...
        wavelength_m;
    for aperture_index = 1:aperture_sample_count
        normalized_range_offset = (range_axis_m- ...
            target_slant_range_m(aperture_index, target_index))/ ...
            range_resolution_m;
        compressed_point_response = explicit_sinc( ...
            normalized_range_offset);
        clean_range_history(aperture_index, :) = ...
            clean_range_history(aperture_index, :)+ ...
            target_voltage(target_index)*compressed_point_response* ...
            exp(1j*target_phase_rad(aperture_index, target_index));
    end
end

private_noise = private_complex_noise(baseline_seed, ...
    numel(clean_range_history), maximum_private_values);
additive_noise = noise_rms_voltage*reshape(private_noise, ...
    size(clean_range_history));
range_compressed_history = clean_range_history+additive_noise;
retained_complex_range_history = range_compressed_history;

% Interpolate target 1's measured ridge to verify the input phase contract.
input_ridge = zeros(aperture_sample_count, 1);
for aperture_index = 1:aperture_sample_count
    fractional_index = (target_slant_range_m(aperture_index, 1)- ...
        range_gate_start_m)/range_sample_spacing_m+1;
    left_index = floor(fractional_index);
    right_weight = fractional_index-left_index;
    input_ridge(aperture_index) = ...
        (1-right_weight)*range_compressed_history(aperture_index, ...
        left_index)+right_weight*range_compressed_history( ...
        aperture_index, left_index+1);
end
expected_input_phasor = exp(1j*target_phase_rad(:, 1));
input_unit_phasor = input_ridge./max(abs(input_ridge), eps);
input_phase_coherence = abs(mean(input_unit_phasor.* ...
    conj(expected_input_phasor)));
measured_relative_phase_rad = unwrap(angle(input_ridge));
measured_relative_phase_rad = measured_relative_phase_rad- ...
    measured_relative_phase_rad(1);
expected_relative_phase_rad = target_phase_rad(:, 1)- ...
    target_phase_rad(1, 1);
assert(input_phase_coherence > minimum_input_phase_coherence, ...
    'P77:InputPhaseCoherence', ...
    'Range-compressed input must preserve the modeled aperture phase.');

fprintf('\nP77 baseline: %d aperture looks, %d range samples, %d image pixels\n', ...
    aperture_sample_count, range_sample_count, image_pixel_count);
fprintf('Carrier %.1f GHz; wavelength %.1f mm; range grid %.2f m\n', ...
    carrier_frequency_hz/1.0e9, wavelength_m*1.0e3, ...
    range_sample_spacing_m);
fprintf('Input target-1 ridge phase coherence = %.5f\n', ...
    input_phase_coherence);

figure('Name', 'P77 input geometry and range-compressed phase history', ...
    'Tag', 'P77', 'NumberTitle', 'off');
subplot(3, 1, 1);
plot(platform_position_m, zeros(size(platform_position_m)), 'b.-');
hold on;
plot(target_cross_range_m, target_ground_range_m, 'rx', ...
    'MarkerSize', 10, 'LineWidth', 1.5);
grid on;
xlabel('Cross-range x (m)');
ylabel('Ground-range y (m)');
title('One antenna visits known positions and observes two point targets');
legend('Platform positions', 'Point targets', 'Location', 'best');
ylim([-50 1070]);
subplot(3, 1, 2);
history_magnitude_db = 20*log10(max(abs(range_compressed_history)/ ...
    max(abs(range_compressed_history(:))), 1.0e-5));
imagesc(range_axis_m, platform_position_m, history_magnitude_db);
axis xy;
xlabel('Monostatic slant range (m)');
ylabel('Platform cross-range position (m)');
title('Input magnitude: range-compressed ridges, not a ground image');
colorbar;
caxis([-45 0]);
subplot(3, 1, 3);
plot(platform_position_m, measured_relative_phase_rad, 'b-', ...
    'LineWidth', 1.0);
hold on;
plot(platform_position_m, expected_relative_phase_rad, 'r--', ...
    'LineWidth', 1.0);
grid on;
xlabel('Platform cross-range position (m)');
ylabel('Unwrapped ridge phase (rad)');
title('Complex ridge phase follows the two-way slant-range path');
legend('Interpolated measurement', 'Expected path phase', ...
    'Location', 'best');

%% Sweep 1: accumulate only the centered aperture look count
partial_case_count = numel(partial_aperture_counts);
partial_images = cell(1, partial_case_count);
partial_selected_indices = cell(1, partial_case_count);
partial_cross_range_width_m = zeros(1, partial_case_count);
partial_true_pixel_voltage = zeros(1, partial_case_count);
zero_path_error_m = zeros(1, aperture_sample_count);
executed_backprojection_operations = 0;
target_one_x_index = find(abs(image_cross_range_m- ...
    target_cross_range_m(1)) < 1.0e-12, 1);
target_one_y_index = find(abs(image_ground_range_m- ...
    target_ground_range_m(1)) < 1.0e-12, 1);

for case_index = 1:partial_case_count
    look_count = partial_aperture_counts(case_index);
    first_index = (aperture_sample_count-look_count)/2+1;
    selected_indices = first_index:(first_index+look_count-1);
    partial_selected_indices{case_index} = selected_indices;
    [partial_images{case_index}, case_operation_count] = backproject_image( ...
        range_compressed_history, platform_position_m, selected_indices, ...
        range_axis_m, image_cross_range_m, image_ground_range_m, ...
        wavelength_m, range_reference_m, zero_path_error_m, ...
        maximum_backprojection_operations);
    executed_backprojection_operations = ...
        executed_backprojection_operations+case_operation_count;
    target_cut = abs(partial_images{case_index}( ...
        target_one_y_index, :));
    partial_cross_range_width_m(case_index) = half_power_width( ...
        target_cut, image_cross_range_m);
    partial_true_pixel_voltage(case_index) = abs(partial_images{case_index}( ...
        target_one_y_index, target_one_x_index));
end

assert(all(diff(partial_cross_range_width_m) < 0), ...
    'P77:PartialApertureWidth', ...
    'Cross-range width must narrow as correct aperture looks accumulate.');
assert(all(diff(partial_true_pixel_voltage) > 0), ...
    'P77:PartialApertureGain', ...
    'Unnormalized true-pixel voltage must grow with coherent look count.');

fprintf('\nPartial aperture look counts: %s\n', ...
    mat2str(partial_aperture_counts));
fprintf('Target-1 full -3 dB cross-range widths (m): %s\n', ...
    mat2str(partial_cross_range_width_m, 5));
fprintf('Target-1 unnormalized coherent voltages: %s\n', ...
    mat2str(partial_true_pixel_voltage, 5));

figure('Name', 'P77 partial-aperture accumulation', ...
    'Tag', 'P77', 'NumberTitle', 'off');
for case_index = 1:partial_case_count
    subplot(1, partial_case_count, case_index);
    display_magnitude = abs(partial_images{case_index})/ ...
        partial_aperture_counts(case_index);
    display_db = 20*log10(max(display_magnitude/ ...
        max(display_magnitude(:)), 1.0e-4));
    imagesc(image_cross_range_m, image_ground_range_m, display_db);
    axis xy;
    xlabel('Target cross-range x (m)');
    ylabel('Target ground-range y (m)');
    title(sprintf('%d centered looks; width %.2f m', ...
        partial_aperture_counts(case_index), ...
        partial_cross_range_width_m(case_index)));
    caxis([-40 0]);
    colorbar;
end

%% Correct full-aperture image, localization metrics, and response cuts
correct_image = partial_images{end};
correct_magnitude = abs(correct_image);
focused_cross_range_m = zeros(1, numel(target_voltage));
focused_ground_range_m = zeros(1, numel(target_voltage));
cross_range_error_m = zeros(1, numel(target_voltage));
ground_range_error_m = zeros(1, numel(target_voltage));

for target_index = 1:numel(target_voltage)
    local_mask = abs(image_cross_range_grid_m- ...
        target_cross_range_m(target_index)) <= 3.0 & ...
        abs(image_ground_range_grid_m- ...
        target_ground_range_m(target_index)) <= 4.0;
    local_magnitude = correct_magnitude;
    local_magnitude(~local_mask) = -Inf;
    [~, local_linear_index] = max(local_magnitude(:));
    [local_y_index, local_x_index] = ind2sub(size(local_magnitude), ...
        local_linear_index);
    focused_cross_range_m(target_index) = ...
        image_cross_range_m(local_x_index);
    focused_ground_range_m(target_index) = ...
        image_ground_range_m(local_y_index);
    cross_range_error_m(target_index) = abs( ...
        focused_cross_range_m(target_index)- ...
        target_cross_range_m(target_index));
    ground_range_error_m(target_index) = abs( ...
        focused_ground_range_m(target_index)- ...
        target_ground_range_m(target_index));
end
assert(all(cross_range_error_m <= maximum_cross_range_error_m) && ...
    all(ground_range_error_m <= maximum_ground_range_error_m), ...
    'P77:Localization', ...
    'Each target must focus within one reviewed image-grid step.');

target_one_range_cut = correct_magnitude(:, target_one_x_index).';
target_one_cross_range_cut = correct_magnitude(target_one_y_index, :);
target_one_range_width_m = half_power_width(target_one_range_cut, ...
    image_ground_range_m);
target_one_cross_range_width_m = half_power_width( ...
    target_one_cross_range_cut, image_cross_range_m);

fprintf('\nCorrect-image focused x coordinates (m): %s\n', ...
    mat2str(focused_cross_range_m));
fprintf('Correct-image focused y coordinates (m): %s\n', ...
    mat2str(focused_ground_range_m));
fprintf('Target-1 full -3 dB range/cross-range widths: %.3f / %.3f m\n', ...
    target_one_range_width_m, target_one_cross_range_width_m);

figure('Name', 'P77 correctly focused backprojection image', ...
    'Tag', 'P77', 'NumberTitle', 'off');
correct_image_db = 20*log10(max(correct_magnitude/ ...
    max(correct_magnitude(:)), 1.0e-4));
imagesc(image_cross_range_m, image_ground_range_m, correct_image_db);
axis xy;
hold on;
plot(target_cross_range_m, target_ground_range_m, 'wx', ...
    'MarkerSize', 10, 'LineWidth', 1.5);
xlabel('Target cross-range x (m)');
ylabel('Target ground-range y (m)');
title('Correct geometry: range interpolation and phase compensation focus targets');
colorbar;
caxis([-40 0]);

figure('Name', 'P77 focused point-target response cuts', ...
    'Tag', 'P77', 'NumberTitle', 'off');
subplot(2, 1, 1);
plot(image_ground_range_m, 20*log10(max(target_one_range_cut/ ...
    max(target_one_range_cut), 1.0e-4)), 'b-', 'LineWidth', 1.1);
grid on;
xlabel('Target ground-range y (m)');
ylabel('Normalized magnitude (dB)');
title(sprintf('Target 1 range cut: full -3 dB width %.2f m', ...
    target_one_range_width_m));
ylim([-40 2]);
subplot(2, 1, 2);
plot(image_cross_range_m, 20*log10(max(target_one_cross_range_cut/ ...
    max(target_one_cross_range_cut), 1.0e-4)), 'b-', ...
    'LineWidth', 1.1);
grid on;
xlabel('Target cross-range x (m)');
ylabel('Normalized magnitude (dB)');
title(sprintf('Target 1 cross-range cut: full -3 dB width %.2f m', ...
    target_one_cross_range_width_m));
ylim([-40 2]);

%% Sweep 2: wrong assumed path only, unchanged complex measurement
path_case_count = numel(path_error_sweep_m);
path_error_images = cell(1, path_case_count);
path_error_profiles_m = cell(1, path_case_count);
true_pixel_gain_ratio = zeros(1, path_case_count);
all_aperture_indices = 1:aperture_sample_count;

for case_index = 1:path_case_count
    case_error_amplitude_m = path_error_sweep_m(case_index);
    case_path_error_m = case_error_amplitude_m*sin(2*pi* ...
        (0:aperture_sample_count-1)/(aperture_sample_count-1));
    path_error_profiles_m{case_index} = case_path_error_m;
    if case_index == 1
        % The full-aperture baseline is already the reviewed zero-error case.
        path_error_images{case_index} = correct_image;
    else
        [path_error_images{case_index}, case_operation_count] = ...
            backproject_image( ...
            retained_complex_range_history, platform_position_m, ...
            all_aperture_indices, range_axis_m, image_cross_range_m, ...
            image_ground_range_m, wavelength_m, range_reference_m, ...
            case_path_error_m, maximum_backprojection_operations);
        executed_backprojection_operations = ...
            executed_backprojection_operations+case_operation_count;
    end
    true_pixel_gain_ratio(case_index) = abs(path_error_images{case_index}( ...
        target_one_y_index, target_one_x_index))/ ...
        abs(correct_image(target_one_y_index, target_one_x_index));
end

assert(isequaln(path_error_images{1}, correct_image), ...
    'P77:ZeroErrorCrosscheck', ...
    'The zero-path-error sweep image must equal the baseline image exactly.');
assert(all(diff(true_pixel_gain_ratio) < 0) && ...
    true_pixel_gain_ratio(end) < maximum_broken_coherence, ...
    'P77:PathErrorSweep', ...
    'Increasing reviewed non-rigid path error must reduce true-pixel gain.');

fprintf('\nAssumed sinusoidal path-error amplitudes (mm): %s\n', ...
    mat2str(1.0e3*path_error_sweep_m));
fprintf('Target-1 true-pixel coherent gain ratios: %s\n', ...
    mat2str(true_pixel_gain_ratio, 5));

figure('Name', 'P77 assumed-path-error sweep', ...
    'Tag', 'P77', 'NumberTitle', 'off');
correct_peak = max(correct_magnitude(:));
for case_index = 1:path_case_count
    subplot(1, path_case_count, case_index);
    case_db = 20*log10(max(abs(path_error_images{case_index})/ ...
        correct_peak, 1.0e-4));
    imagesc(image_cross_range_m, image_ground_range_m, case_db);
    axis xy;
    xlabel('Target cross-range x (m)');
    ylabel('Target ground-range y (m)');
    title(sprintf('Assumed path error %.0f mm; true-pixel gain %.2f', ...
        1.0e3*path_error_sweep_m(case_index), ...
        true_pixel_gain_ratio(case_index)));
    caxis([-40 0]);
    colorbar;
end

%% Intentionally broken 10 mm path and exact same-data recovery
measurement_before_failure = retained_complex_range_history;
broken_image = path_error_images{end};
broken_path_error_m = path_error_profiles_m{end};
broken_target_terms = pixel_backprojection_terms( ...
    retained_complex_range_history, platform_position_m, ...
    all_aperture_indices, range_axis_m, target_cross_range_m(1), ...
    target_ground_range_m(1), wavelength_m, range_reference_m, ...
    broken_path_error_m);
recovered_target_terms = pixel_backprojection_terms( ...
    retained_complex_range_history, platform_position_m, ...
    all_aperture_indices, range_axis_m, target_cross_range_m(1), ...
    target_ground_range_m(1), wavelength_m, range_reference_m, ...
    zero_path_error_m);
broken_phase_coherence = abs(sum(broken_target_terms))/ ...
    sum(abs(broken_target_terms));
recovered_phase_coherence = abs(sum(recovered_target_terms))/ ...
    sum(abs(recovered_target_terms));

recovered_complex_range_history = retained_complex_range_history;
[recovered_image, recovery_operation_count] = backproject_image( ...
    recovered_complex_range_history, platform_position_m, ...
    all_aperture_indices, range_axis_m, image_cross_range_m, ...
    image_ground_range_m, wavelength_m, range_reference_m, ...
    zero_path_error_m, maximum_backprojection_operations);
executed_backprojection_operations = ...
    executed_backprojection_operations+recovery_operation_count;
measurement_exact_match = isequaln(recovered_complex_range_history, ...
    measurement_before_failure);
recovery_exact_match = isequaln(recovered_image, correct_image);
assert(broken_phase_coherence < maximum_broken_coherence, ...
    'P77:BrokenPathDefocus', ...
    'The 10 mm non-rigid path error must break true-pixel coherence.');
assert(measurement_exact_match && recovery_exact_match && ...
    recovered_phase_coherence > minimum_recovered_coherence, ...
    'P77:SameDataRecovery', ...
    'Correct geometry must recover the exact baseline from unchanged data.');

fprintf('\nBroken/recovered target-1 phase coherence: %.4f / %.4f\n', ...
    broken_phase_coherence, recovered_phase_coherence);
fprintf('Measurement/image exact recovery matches: %d / %d\n', ...
    measurement_exact_match, recovery_exact_match);

figure('Name', 'P77 broken path and same-data recovery', ...
    'Tag', 'P77', 'NumberTitle', 'off');
subplot(2, 1, 1);
plot(platform_position_m, unwrap(angle(broken_target_terms)), 'r-', ...
    'LineWidth', 1.0);
hold on;
plot(platform_position_m, unwrap(angle(recovered_target_terms)), 'b--', ...
    'LineWidth', 1.0);
grid on;
xlabel('Platform cross-range position (m)');
ylabel('Compensated target-1 term phase (rad)');
title('Broken path leaves aperture-dependent residual phase');
legend('10 mm wrong path', 'Correct path', 'Location', 'best');
subplot(2, 1, 2);
broken_cross_range_cut = abs(broken_image(target_one_y_index, :));
recovered_cross_range_cut = abs(recovered_image(target_one_y_index, :));
plot(image_cross_range_m, 20*log10(max(broken_cross_range_cut/ ...
    max(recovered_cross_range_cut), 1.0e-4)), 'r-', ...
    'LineWidth', 1.0);
hold on;
plot(image_cross_range_m, 20*log10(max(recovered_cross_range_cut/ ...
    max(recovered_cross_range_cut), 1.0e-4)), 'b--', ...
    'LineWidth', 1.0);
grid on;
xlabel('Target cross-range x (m)');
ylabel('Magnitude relative to recovered peak (dB)');
title('Same complex data: wrong-path defocus and correct-path recovery');
legend('Broken path', 'Recovered correct path', 'Location', 'best');
ylim([-40 2]);

%% Retained results and final boundedness checks
pre_results_workspace_inventory = whos;
pre_results_storage_bytes = sum([pre_results_workspace_inventory.bytes]);
pre_results_value_equivalents = ceil(pre_results_storage_bytes/8);
assert(pre_results_value_equivalents <= ...
    maximum_working_value_equivalents, 'P77:WorkingBound', ...
    'The pre-results live workspace exceeds its immutable storage ceiling.');
assert(all(isfinite([input_phase_coherence ...
    partial_cross_range_width_m partial_true_pixel_voltage ...
    focused_cross_range_m focused_ground_range_m ...
    target_one_range_width_m target_one_cross_range_width_m ...
    true_pixel_gain_ratio broken_phase_coherence ...
    recovered_phase_coherence])), 'P77:FiniteMetrics', ...
    'Every retained metric must be finite.');
assert(numel(findall(0, 'Type', 'figure', 'Tag', 'P77')) == ...
    maximum_figures, 'P77:FigureBound', ...
    'The reviewed experiment must create exactly six tagged figure groups.');
assert(executed_backprojection_operations == ...
    predicted_backprojection_operations && ...
    executed_backprojection_operations <= maximum_backprojection_operations, ...
    'P77:BackprojectionOperationAccounting', ...
