%% Downconvert paired upper/lower RF sides with complex and real mixers
upper_rf_iq_v = tone_amplitude_v*exp(1j*( ...
    2*pi*(lo_frequency_hz+tone_frequency_hz)*time_s + tone_phase_rad));
lower_rf_iq_v = tone_amplitude_v*exp(1j*( ...
    2*pi*(lo_frequency_hz-tone_frequency_hz)*time_s - tone_phase_rad));
complex_lo = exp(-1j*2*pi*lo_frequency_hz*time_s);
upper_complex_baseband_v = upper_rf_iq_v.*complex_lo;
lower_complex_baseband_v = lower_rf_iq_v.*complex_lo;

% A 2*cos(2*pi*fLO*t) real mixer creates a desired difference cosine with
% amplitude A plus a sum term. Build the channel low-pass explicitly.
filter_half_length = (lowpass_tap_count-1)/2;
centered_tap_index = -filter_half_length:filter_half_length;
ideal_fir = zeros(1, lowpass_tap_count);
for tap_index = 1:lowpass_tap_count
    centered_index = centered_tap_index(tap_index);
    if centered_index == 0
        ideal_fir(tap_index) = 2*lowpass_cutoff_hz/fs_hz;
    else
        ideal_fir(tap_index) = sin(2*pi*lowpass_cutoff_hz* ...
            centered_index/fs_hz)/(pi*centered_index);
    end
end
hamming_window = 0.54 - 0.46*cos(2*pi*(0:lowpass_tap_count-1)/ ...
    (lowpass_tap_count-1));
lowpass_fir = ideal_fir.*hamming_window;
lowpass_fir = lowpass_fir/sum(lowpass_fir);

real_lo = 2*cos(2*pi*lo_frequency_hz*time_s);
upper_real_mixed_v = real(upper_rf_iq_v).*real_lo;
lower_real_mixed_v = real(lower_rf_iq_v).*real_lo;
upper_real_full_v = conv(upper_real_mixed_v, lowpass_fir, 'full');
lower_real_full_v = conv(lower_real_mixed_v, lowpass_fir, 'full');
upper_real_baseband_v = upper_real_full_v(filter_half_length+1: ...
    filter_half_length+record_sample_count);
lower_real_baseband_v = lower_real_full_v(filter_half_length+1: ...
    filter_half_length+record_sample_count);

evaluation_mask = false(1, record_sample_count);
evaluation_mask(evaluation_guard_sample_count+1: ...
    record_sample_count-evaluation_guard_sample_count) = true;
real_mixer_collapse_rmse_v = sqrt(mean(( ...
    upper_real_baseband_v(evaluation_mask) - ...
    lower_real_baseband_v(evaluation_mask)).^2));
upper_complex_frequency_hz = angle(sum(conj( ...
    upper_complex_baseband_v(1:end-1)).* ...
    upper_complex_baseband_v(2:end)))*fs_hz/(2*pi);
lower_complex_frequency_hz = angle(sum(conj( ...
    lower_complex_baseband_v(1:end-1)).* ...
    lower_complex_baseband_v(2:end)))*fs_hz/(2*pi);

