%% Baseline: paired complex tones and their identical real projections
time_s = (0:record_sample_count-1)/fs_hz;
private_stream = RandStream('mt19937ar', 'Seed', random_seed);
complex_noise_v = noise_rms_v/sqrt(2)*( ...
    randn(private_stream, 1, record_sample_count) + ...
    1j*randn(private_stream, 1, record_sample_count));

positive_iq_clean_v = tone_amplitude_v*exp(1j*( ...
    2*pi*tone_frequency_hz*time_s + tone_phase_rad));
negative_iq_clean_v = tone_amplitude_v*exp(-1j*( ...
    2*pi*tone_frequency_hz*time_s + tone_phase_rad));
positive_iq_v = positive_iq_clean_v + complex_noise_v;
negative_iq_v = conj(positive_iq_v);
positive_real_v = real(positive_iq_v);
negative_real_v = real(negative_iq_v);

positive_phase_step_rad = angle(sum(conj(positive_iq_v(1:end-1)).* ...
    positive_iq_v(2:end)));
negative_phase_step_rad = angle(sum(conj(negative_iq_v(1:end-1)).* ...
    negative_iq_v(2:end)));
positive_estimated_frequency_hz = positive_phase_step_rad*fs_hz/(2*pi);
negative_estimated_frequency_hz = negative_phase_step_rad*fs_hz/(2*pi);
real_projection_rmse_v = sqrt(mean((positive_real_v-negative_real_v).^2));

frequency_hz = (-record_sample_count/2:record_sample_count/2-1)* ...
    fs_hz/record_sample_count;
positive_spectrum_v = abs(fftshift(fft(positive_iq_v)))/record_sample_count;
negative_spectrum_v = abs(fftshift(fft(negative_iq_v)))/record_sample_count;
real_spectrum_complex_v = fftshift(fft(positive_real_v))/record_sample_count;
real_spectrum_v = abs(real_spectrum_complex_v);
[~, positive_peak_index] = max(positive_spectrum_v);
[~, negative_peak_index] = max(negative_spectrum_v);
positive_peak_frequency_hz = frequency_hz(positive_peak_index);
negative_peak_frequency_hz = frequency_hz(negative_peak_index);
real_spectrum_symmetry_error_v = max(abs(real_spectrum_complex_v - ...
    conj(circshift(fliplr(real_spectrum_complex_v), [0 1]))));

