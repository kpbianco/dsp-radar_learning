%% P52: Validate CFAR Pfa by Monte Carlo
% Guiding question:
% Does the implemented detector actually achieve the requested false-alarm
% probability?
% One trial is one valid noise-only CUT plus N complete reference cells.

close(findall(groot, 'Type', 'figure', 'Tag', 'P52'));
clearvars;
clc;

%% Visible deterministic controls and immutable resource ceilings
random_seed = 5201;
trial_count = 200000;
block_trial_count = 2000;
design_false_alarm_probability = 1e-3;
baseline_training_cell_count = 24;
false_alarm_probability_sweep = [1e-2 3e-3 1e-3];
training_cell_count_sweep = [8 16 24 32 64];
correlation_coefficient = 0.65;
texture_log_standard_deviation = 0.90;
confidence_z_score = 1.96;
running_trial_counts = [200 500 1000 2000 5000 10000 20000 ...
    50000 100000 200000];
display_trial_count = 240;
probability_tolerance_sigma = 5;

max_trial_count = 250000;
max_block_trial_count = 5000;
max_training_cell_count = 64;
max_sweep_case_count = 6;
max_running_checkpoint_count = 12;
max_generated_random_real_values = 55000000;
max_peak_stored_numeric_values = 1000000;
max_threshold_comparisons = 3000000;
max_figure_groups = 5;

%% Reject malformed, ambiguous, or unbounded controls before allocation
if max_trial_count ~= 250000 || max_block_trial_count ~= 5000 || ...
        max_training_cell_count ~= 64 || max_sweep_case_count ~= 6 || ...
        max_running_checkpoint_count ~= 12 || ...
        max_generated_random_real_values ~= 55000000 || ...
        max_peak_stored_numeric_values ~= 1000000 || ...
        max_threshold_comparisons ~= 3000000 || max_figure_groups ~= 5
    error('P52:CeilingControls', ...
        'Reviewed resource ceilings must remain fixed.');
end

integer_controls = {random_seed trial_count block_trial_count ...
    baseline_training_cell_count display_trial_count max_trial_count ...
    max_block_trial_count max_training_cell_count max_sweep_case_count ...
    max_running_checkpoint_count max_generated_random_real_values ...
    max_peak_stored_numeric_values max_threshold_comparisons ...
    max_figure_groups};
for control_index = 1:numel(integer_controls)
    control_value = integer_controls{control_index};
    if ~isscalar(control_value) || ~isnumeric(control_value) || ...
            islogical(control_value) || ~isreal(control_value) || ...
            ~isfinite(control_value) || control_value ~= fix(control_value)
        error('P52:IntegerControls', ...
            'Integer controls must be finite real integer scalars.');
    end
end

real_controls = {design_false_alarm_probability correlation_coefficient ...
    texture_log_standard_deviation confidence_z_score ...
    probability_tolerance_sigma};
for control_index = 1:numel(real_controls)
    control_value = real_controls{control_index};
    if ~isscalar(control_value) || ~isnumeric(control_value) || ...
            islogical(control_value) || ~isreal(control_value) || ...
            ~isfinite(control_value)
        error('P52:RealControls', ...
            'Physical controls must be finite real scalars.');
    end
end

if random_seed ~= 5201 || trial_count < 10000 || ...
        trial_count > max_trial_count
    error('P52:DeterminismOrTrials', ...
        'Keep the reviewed seed and a bounded informative trial count.');
end
if block_trial_count < 100 || block_trial_count > max_block_trial_count || ...
        mod(trial_count, block_trial_count) ~= 0
    error('P52:BlockSize', ...
        'Block size must divide the trial count within reviewed bounds.');
end
if design_false_alarm_probability < 1e-5 || ...
        design_false_alarm_probability >= 0.1
    error('P52:DesignPfa', ...
        'Design Pfa must lie from 1e-5 inclusive to 0.1 exclusive.');
end
if ~isnumeric(false_alarm_probability_sweep) || ...
        islogical(false_alarm_probability_sweep) || ...
        ~isreal(false_alarm_probability_sweep) || ...
        ~isrow(false_alarm_probability_sweep) || ...
        any(~isfinite(false_alarm_probability_sweep)) || ...
        numel(false_alarm_probability_sweep) < 3 || ...
        numel(false_alarm_probability_sweep) > max_sweep_case_count || ...
        any(false_alarm_probability_sweep < 1e-5) || ...
        any(false_alarm_probability_sweep >= 0.1) || ...
        any(diff(false_alarm_probability_sweep) >= 0) || ...
        ~any(false_alarm_probability_sweep == ...
        design_false_alarm_probability)
    error('P52:PfaSweep', ...
        'Pfa sweep must be bounded, decreasing, and include the design value.');
end
if ~isnumeric(training_cell_count_sweep) || ...
        islogical(training_cell_count_sweep) || ...
        ~isreal(training_cell_count_sweep) || ...
        ~isrow(training_cell_count_sweep) || ...
        any(~isfinite(training_cell_count_sweep)) || ...
        any(training_cell_count_sweep ~= fix(training_cell_count_sweep)) || ...
        numel(training_cell_count_sweep) < 3 || ...
        numel(training_cell_count_sweep) > max_sweep_case_count || ...
        any(training_cell_count_sweep < 4) || ...
        any(training_cell_count_sweep > max_training_cell_count) || ...
        any(diff(training_cell_count_sweep) <= 0) || ...
        ~any(training_cell_count_sweep == baseline_training_cell_count)
    error('P52:TrainingSweep', ...
        'Training counts must be increasing bounded integers including N.');
end
if correlation_coefficient <= 0 || correlation_coefficient >= 1
    error('P52:Correlation', ...
        'Correlation coefficient must lie strictly between zero and one.');
end
if texture_log_standard_deviation <= 0 || ...
        texture_log_standard_deviation > 1.5
    error('P52:Texture', ...
        'Log-texture standard deviation must lie in (0, 1.5].');
end
if confidence_z_score < 1 || confidence_z_score > 4 || ...
        probability_tolerance_sigma < 3 || probability_tolerance_sigma > 8
    error('P52:Uncertainty', ...
        'Confidence and deterministic tolerance controls are out of bounds.');
end
if ~isnumeric(running_trial_counts) || islogical(running_trial_counts) || ...
        ~isreal(running_trial_counts) || ~isrow(running_trial_counts) || ...
        any(~isfinite(running_trial_counts)) || ...
        any(running_trial_counts ~= fix(running_trial_counts)) || ...
        numel(running_trial_counts) < 4 || ...
        numel(running_trial_counts) > max_running_checkpoint_count || ...
        any(diff(running_trial_counts) <= 0) || running_trial_counts(1) < 100 || ...
        running_trial_counts(end) ~= trial_count
    error('P52:RunningCheckpoints', ...
        'Running checkpoints must increase to the complete trial count.');
end
if display_trial_count < 50 || display_trial_count > block_trial_count
    error('P52:DisplayTrials', ...
        'Displayed trials must fit in the first generated block.');
end

pfa_case_count = numel(false_alarm_probability_sweep);
training_case_count = numel(training_cell_count_sweep);
largest_training_cell_count = max(training_cell_count_sweep);
estimated_generated_random_real_values = ...
    2*trial_count*(largest_training_cell_count+1) + ...
    2*trial_count*(baseline_training_cell_count+2) + ...
    3*trial_count*(baseline_training_cell_count+1);
estimated_peak_stored_numeric_values = trial_count + ...
    block_trial_count*(2*(largest_training_cell_count+1) + ...
    5*(baseline_training_cell_count+1)) + 10000;
estimated_threshold_comparisons = trial_count*(pfa_case_count + ...
    training_case_count + 4);
if estimated_generated_random_real_values > ...
        max_generated_random_real_values || ...
        estimated_peak_stored_numeric_values > ...
        max_peak_stored_numeric_values || ...
        estimated_threshold_comparisons > max_threshold_comparisons
    error('P52:ResourceBudget', ...
        'Reviewed random, storage, or comparison budget was exceeded.');
end
is_reviewed_default_run = trial_count == 200000 && ...
    block_trial_count == 2000 && ...
    baseline_training_cell_count == 24 && ...
    design_false_alarm_probability == 1e-3 && ...
    correlation_coefficient == 0.65 && ...
    texture_log_standard_deviation == 0.90;

%% Homogeneous baseline: explicit square law, training mean, and comparison
private_stream = RandStream('mt19937ar', 'Seed', random_seed);
pfa_alarm_counts = zeros(1, pfa_case_count);
training_alarm_counts = zeros(1, training_case_count);
baseline_alarm_indicator = false(trial_count, 1);
broken_alarm_count = 0;
example_cut_power = zeros(display_trial_count, 1);
example_threshold_power = zeros(display_trial_count, 1);

for block_first_trial = 1:block_trial_count:trial_count
    block_last_trial = block_first_trial+block_trial_count-1;
    block_rows = block_first_trial:block_last_trial;
    independent_noise = (randn(private_stream, block_trial_count, ...
        largest_training_cell_count+1)+1i*randn(private_stream, ...
        block_trial_count, largest_training_cell_count+1))/sqrt(2);
    independent_power = abs(independent_noise).^2;
    cut_power = independent_power(:, 1);
    training_power_cumulative = cumsum(independent_power(:, 2:end), 2);
    baseline_training_mean_power = ...
        training_power_cumulative(:, baseline_training_cell_count)/...
        baseline_training_cell_count;

    for pfa_index = 1:pfa_case_count
        requested_pfa = false_alarm_probability_sweep(pfa_index);
        cfar_scale_factor = baseline_training_cell_count*(...
            requested_pfa^(-1/baseline_training_cell_count)-1);
        pfa_alarm_counts(pfa_index) = pfa_alarm_counts(pfa_index) + ...
            sum(cut_power > cfar_scale_factor*...
            baseline_training_mean_power);
    end

    for training_index = 1:training_case_count
        training_cell_count = training_cell_count_sweep(training_index);
        training_mean_power = training_power_cumulative(:, ...
            training_cell_count)/training_cell_count;
        cfar_scale_factor = training_cell_count*(...
            design_false_alarm_probability^(-1/training_cell_count)-1);
        training_alarm_counts(training_index) = ...
            training_alarm_counts(training_index) + ...
            sum(cut_power > cfar_scale_factor*training_mean_power);
    end

    baseline_scale_factor = baseline_training_cell_count*(...
        design_false_alarm_probability^...
        (-1/baseline_training_cell_count)-1);
    baseline_threshold_power = baseline_scale_factor*...
        baseline_training_mean_power;
    baseline_alarm_indicator(block_rows) = ...
        cut_power > baseline_threshold_power;
    known_noise_scale_factor = -log(design_false_alarm_probability);
    broken_alarm_count = broken_alarm_count + sum(cut_power > ...
        known_noise_scale_factor*baseline_training_mean_power);

    if block_first_trial == 1
        example_cut_power = cut_power(1:display_trial_count);
        example_threshold_power = ...
            baseline_threshold_power(1:display_trial_count);
    end
end
clear independent_noise independent_power cut_power ...
    training_power_cumulative baseline_training_mean_power ...
    training_mean_power baseline_threshold_power block_rows;

%% Measured rates, exact iid theory, and explicit Wilson intervals
confidence_level_percent = 100*erf(confidence_z_score/sqrt(2));
confidence_interval_label = sprintf('%.1f%% Wilson interval', ...
    confidence_level_percent);
pfa_measured = pfa_alarm_counts/trial_count;
pfa_scale_factor = baseline_training_cell_count*(...
    false_alarm_probability_sweep.^...
    (-1/baseline_training_cell_count)-1);
pfa_theory = (1+pfa_scale_factor/baseline_training_cell_count).^...
    (-baseline_training_cell_count);

training_measured = training_alarm_counts/trial_count;
training_scale_factor = training_cell_count_sweep.*(...
    design_false_alarm_probability.^(-1./training_cell_count_sweep)-1);
training_theory = (1+training_scale_factor./training_cell_count_sweep).^...
    (-training_cell_count_sweep);

wilson_denominator = 1+confidence_z_score^2/trial_count;
pfa_wilson_center = (pfa_measured+confidence_z_score^2/(2*trial_count))/...
    wilson_denominator;
pfa_wilson_half_width = confidence_z_score/wilson_denominator*sqrt(...
    pfa_measured.*(1-pfa_measured)/trial_count + ...
    confidence_z_score^2/(4*trial_count^2));
pfa_wilson_lower = max(0, pfa_wilson_center-pfa_wilson_half_width);
pfa_wilson_upper = min(1, pfa_wilson_center+pfa_wilson_half_width);

training_wilson_center = (training_measured+...
    confidence_z_score^2/(2*trial_count))/wilson_denominator;
training_wilson_half_width = confidence_z_score/wilson_denominator*sqrt(...
    training_measured.*(1-training_measured)/trial_count + ...
    confidence_z_score^2/(4*trial_count^2));
training_wilson_lower = max(0, ...
    training_wilson_center-training_wilson_half_width);
training_wilson_upper = min(1, ...
    training_wilson_center+training_wilson_half_width);

if max(abs(pfa_theory-false_alarm_probability_sweep)) > 1e-12 || ...
        max(abs(training_theory-design_false_alarm_probability)) > 1e-12
    error('P52:AnalyticCalibration', ...
        'Finite-N homogeneous calibration must equal the requested Pfa.');
end
pfa_sampling_tolerance = probability_tolerance_sigma*sqrt(...
    false_alarm_probability_sweep.*...
    (1-false_alarm_probability_sweep)/trial_count) + 2/trial_count;
training_sampling_tolerance = probability_tolerance_sigma*sqrt(...
    design_false_alarm_probability*...
    (1-design_false_alarm_probability)/trial_count) + 2/trial_count;
if any(abs(pfa_measured-pfa_theory) > pfa_sampling_tolerance) || ...
        any(abs(training_measured-training_theory) > ...
        training_sampling_tolerance)
    error('P52:HomogeneousOracle', ...
        'Homogeneous Monte Carlo rate departed beyond its sampling bound.');
end

baseline_pfa_index = find(false_alarm_probability_sweep == ...
    design_false_alarm_probability, 1);
baseline_training_index = find(training_cell_count_sweep == ...
    baseline_training_cell_count, 1);
baseline_alarm_count = pfa_alarm_counts(baseline_pfa_index);
baseline_measured_pfa = pfa_measured(baseline_pfa_index);
if baseline_alarm_count ~= training_alarm_counts(baseline_training_index)
    error('P52:BaselinePairing', ...
        'The shared N and Pfa baseline must produce one paired alarm count.');
end

if sum(baseline_alarm_indicator) ~= baseline_alarm_count
    error('P52:BaselineAccounting', ...
        'Every baseline alarm must be counted exactly once.');
end

running_alarm_count = cumsum(double(baseline_alarm_indicator));
running_measured_pfa = running_alarm_count(running_trial_counts)./...
    running_trial_counts;
running_denominator = 1+confidence_z_score^2./running_trial_counts;
running_wilson_center = (running_measured_pfa+...
    confidence_z_score^2./(2*running_trial_counts))./running_denominator;
running_wilson_half_width = confidence_z_score./running_denominator.*sqrt(...
    running_measured_pfa.*(1-running_measured_pfa)./running_trial_counts + ...
    confidence_z_score^2./(4*running_trial_counts.^2));
running_wilson_lower = max(0, ...
    running_wilson_center-running_wilson_half_width);
running_wilson_upper = min(1, ...
    running_wilson_center+running_wilson_half_width);
if running_wilson_upper(end)-running_wilson_lower(end) >= ...
        running_wilson_upper(1)-running_wilson_lower(1)
    error('P52:ConfidenceNarrowing', ...
        'The retained Monte Carlo interval should narrow with trial count.');
end
clear running_alarm_count;

%% Sweep 3: change only the noise model at fixed N and requested Pfa
correlated_alarm_count = 0;
textured_alarm_count = 0;
for block_first_trial = 1:block_trial_count:trial_count
    common_noise = (randn(private_stream, block_trial_count, 1)+...
        1i*randn(private_stream, block_trial_count, 1))/sqrt(2);
    independent_innovation = (randn(private_stream, block_trial_count, ...
        baseline_training_cell_count+1)+1i*randn(private_stream, ...
        block_trial_count, baseline_training_cell_count+1))/sqrt(2);
    correlated_noise = sqrt(correlation_coefficient)*common_noise + ...
        sqrt(1-correlation_coefficient)*independent_innovation;
    correlated_power = abs(correlated_noise).^2;
    correlated_cut_power = correlated_power(:, 1);
    correlated_training_mean_power = mean(correlated_power(:, 2:end), 2);
    correlated_alarm_count = correlated_alarm_count + ...
        sum(correlated_cut_power > baseline_scale_factor*...
        correlated_training_mean_power);

    texture_carrier_noise = (randn(private_stream, block_trial_count, ...
        baseline_training_cell_count+1)+1i*randn(private_stream, ...
        block_trial_count, baseline_training_cell_count+1))/sqrt(2);
    log_texture_driver = randn(private_stream, block_trial_count, ...
        baseline_training_cell_count+1);
    unit_mean_texture = exp(texture_log_standard_deviation*...
        log_texture_driver - 0.5*texture_log_standard_deviation^2);
    textured_power = abs(texture_carrier_noise).^2.*unit_mean_texture;
    textured_cut_power = textured_power(:, 1);
    textured_training_mean_power = mean(textured_power(:, 2:end), 2);
    textured_alarm_count = textured_alarm_count + sum(textured_cut_power > ...
        baseline_scale_factor*textured_training_mean_power);
end
clear common_noise independent_innovation correlated_noise ...
    correlated_power correlated_cut_power correlated_training_mean_power ...
    texture_carrier_noise log_texture_driver unit_mean_texture ...
    textured_power textured_cut_power textured_training_mean_power;

model_names = {'iid exponential', 'correlated Gaussian', ...
    'compound lognormal'};
model_alarm_counts = [baseline_alarm_count correlated_alarm_count ...
    textured_alarm_count];
model_measured_pfa = model_alarm_counts/trial_count;
model_wilson_center = (model_measured_pfa+...
    confidence_z_score^2/(2*trial_count))/wilson_denominator;
model_wilson_half_width = confidence_z_score/wilson_denominator*sqrt(...
    model_measured_pfa.*(1-model_measured_pfa)/trial_count + ...
    confidence_z_score^2/(4*trial_count^2));
model_wilson_lower = max(0, ...
    model_wilson_center-model_wilson_half_width);
model_wilson_upper = min(1, ...
    model_wilson_center+model_wilson_half_width);
if is_reviewed_default_run
    if model_measured_pfa(2) >= 0.6*design_false_alarm_probability || ...
            model_measured_pfa(3) <= 8*design_false_alarm_probability
        error('P52:ModelMismatch', ...
            'Reviewed mismatch cases must depart in opposite directions.');
    end
end

%% Intentionally broken case and exact finite-N recovery
broken_measured_pfa = broken_alarm_count/trial_count;
broken_theoretical_pfa = (1+known_noise_scale_factor/...
    baseline_training_cell_count)^(-baseline_training_cell_count);
recovered_scale_factor = baseline_training_cell_count*(...
    design_false_alarm_probability^...
    (-1/baseline_training_cell_count)-1);
recovered_measured_pfa = sum(baseline_alarm_indicator)/trial_count;
recovered_theoretical_pfa = (1+recovered_scale_factor/...
    baseline_training_cell_count)^(-baseline_training_cell_count);
if broken_theoretical_pfa <= design_false_alarm_probability || ...
        abs(recovered_theoretical_pfa-design_false_alarm_probability) > 1e-12 || ...
        recovered_scale_factor ~= baseline_scale_factor
    error('P52:BrokenRecovery', ...
        'Broken scaling must overspend Pfa and finite-N recovery must restore it.');
end
if is_reviewed_default_run && ...
        broken_measured_pfa <= 1.5*design_false_alarm_probability
    error('P52:BrokenEmpiricalOracle', ...
        'The reviewed broken run must visibly overspend measured Pfa.');
end

%% Figure 1: one complete CUT/reference decision and convergence by trial count
figure('Name', 'P52 homogeneous baseline', 'Tag', 'P52');
subplot(2, 1, 1);
semilogy(1:display_trial_count, example_cut_power, 'k.', ...
    'DisplayName', 'Noise-only CUT power');
hold on;
semilogy(1:display_trial_count, example_threshold_power, 'b-', ...
    'LineWidth', 1.2, 'DisplayName', 'Finite-N CA threshold');
example_alarms = example_cut_power > example_threshold_power;
semilogy(find(example_alarms), example_cut_power(example_alarms), 'ro', ...
    'MarkerSize', 6, 'LineWidth', 1.2, 'DisplayName', 'False alarm');
grid on;
xlabel('Independent noise-only trial index');
ylabel('Normalized square-law power');
title(sprintf('One valid CUT and N=%d complete references per trial', ...
    baseline_training_cell_count));
legend('Location', 'best');

subplot(2, 1, 2);
semilogx(running_trial_counts, running_measured_pfa, 'ko-', ...
    'LineWidth', 1.3, 'DisplayName', 'Measured P_{FA}');
hold on;
semilogx(running_trial_counts, running_wilson_lower, 'b--', ...
    'LineWidth', 1.1, 'DisplayName', confidence_interval_label);
semilogx(running_trial_counts, running_wilson_upper, 'b--', ...
    'LineWidth', 1.1, 'HandleVisibility', 'off');
yline(design_false_alarm_probability, 'r:', 'LineWidth', 1.4, ...
    'DisplayName', 'Requested P_{FA}');
grid on;
xlabel('Independent tested CUT count');
ylabel('False-alarm probability (alarms / tested CUTs)');
title('More independent trials narrow uncertainty');
legend('Location', 'best');

%% Figure 2: requested-Pfa sweep with measured confidence intervals
figure('Name', 'P52 requested Pfa sweep', 'Tag', 'P52');
errorbar(false_alarm_probability_sweep, pfa_measured, ...
    pfa_measured-pfa_wilson_lower, pfa_wilson_upper-pfa_measured, ...
    'ko', 'LineWidth', 1.3, 'MarkerFaceColor', 'k');
hold on;
plot(false_alarm_probability_sweep, pfa_theory, 'b-', 'LineWidth', 1.4);
set(gca, 'XScale', 'log', 'YScale', 'log', 'XDir', 'reverse');
grid on;
xlabel('Requested false-alarm probability');
ylabel('Measured false-alarm probability (alarms / tested CUTs)');
title(sprintf('Sweep 1: requested P_{FA}, fixed N=%d and iid model', ...
    baseline_training_cell_count));
legend(['Measured with ' confidence_interval_label], 'Exact iid theory', ...
    'Location', 'best');

%% Figure 3: total training-count sweep at fixed requested Pfa
figure('Name', 'P52 training count sweep', 'Tag', 'P52');
errorbar(training_cell_count_sweep, training_measured, ...
    training_measured-training_wilson_lower, ...
    training_wilson_upper-training_measured, 'ko-', ...
    'LineWidth', 1.3, 'MarkerFaceColor', 'k');
hold on;
yline(design_false_alarm_probability, 'b--', 'LineWidth', 1.4);
set(gca, 'YScale', 'log');
grid on;
xlabel('Total independent training-cell count N');
ylabel('Measured false-alarm probability (alarms / tested CUTs)');
title(sprintf('Sweep 2: N changes; alpha(N,P_{FA}) is recalibrated at %.0e', ...
    design_false_alarm_probability));
legend(['Measured with ' confidence_interval_label], 'Requested P_{FA}', ...
    'Location', 'best');

%% Figure 4: noise-model sweep at fixed detector settings
figure('Name', 'P52 noise model mismatch', 'Tag', 'P52');
bar(1:3, model_measured_pfa, 0.65, 'FaceColor', [0.35 0.55 0.75]);
hold on;
errorbar(1:3, model_measured_pfa, ...
    model_measured_pfa-model_wilson_lower, ...
    model_wilson_upper-model_measured_pfa, 'k.', 'LineWidth', 1.3);
yline(design_false_alarm_probability, 'r--', 'LineWidth', 1.4);
set(gca, 'YScale', 'log', 'XTick', 1:3, 'XTickLabel', model_names);
grid on;
ylabel('Measured false-alarm probability (alarms / tested CUTs)');
title(sprintf(['Sweep 3: fixed N=%d and alpha; only the H0 model changes'], ...
    baseline_training_cell_count));
legend('Measured P_{FA}', confidence_interval_label, 'Requested P_{FA}', ...
    'Location', 'best');

%% Figure 5: broken infinite-training multiplier and finite-N recovery
figure('Name', 'P52 broken scaling and recovery', 'Tag', 'P52');
comparison_measured = [broken_measured_pfa recovered_measured_pfa];
comparison_theory = [broken_theoretical_pfa recovered_theoretical_pfa];
bar(1:2, [comparison_measured(:) comparison_theory(:)], 'grouped');
hold on;
yline(design_false_alarm_probability, 'k--', 'LineWidth', 1.4);
set(gca, 'YScale', 'log', 'XTick', 1:2, ...
    'XTickLabel', {'Broken -log(Pfa)', 'Recovered finite-N alpha'});
