    values = c.(vector_fields{field_index});
    assert(isnumeric(values) && isreal(values) && isrow(values) && ...
        ~isempty(values) && all(isfinite(values)), 'P72:ControlVector', ...
        'Every sweep and multi-target control must be finite and numeric.');
