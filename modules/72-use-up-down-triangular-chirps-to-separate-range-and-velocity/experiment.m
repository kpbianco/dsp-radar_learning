%% P72: Use Up/Down Triangular Chirps to Separate Range and Velocity
% Guiding question:
% How can opposite chirp slopes disentangle delay and Doppler?
%
% Base MATLAB only. The two quadratic-phase chirp legs, delayed moving
% echoes, tx.*conj(rx) mixer, signed beat estimates, two-equation solve,
% three one-variable sweeps, multi-target wrong pairing, and same-data
% association recovery are explicit.

close(findall(0, 'Type', 'figure', 'Tag', 'P72'));
clear p72_results;

%% Visible reviewed controls
baseline_seed = 7201;
speed_of_light_mps = 3.0e8;
carrier_frequency_hz = 77.0e9;
sample_rate_hz = 80.0e6;
chirp_duration_s = 40.0e-6;
chirp_bandwidth_hz = 20.0e6;
target_range_m = 45.0;
target_velocity_mps = 20.0;
target_voltage = 1.0;
target_initial_phase_rad = 0.35;
noise_rms = 0.002;
range_sweep_m = [15 30 45 60 75];
velocity_sweep_mps = [-30 -15 0 15 30];
noise_sweep_rms = [0 0.002 0.01 0.03 0.08];
multi_target_range_m = [30 65];
multi_target_velocity_mps = [15 -10];
multi_target_voltage = [1.0 0.8];
multi_target_phase_rad = [0.2 -0.6];
minimum_peak_separation_hz = 60.0e3;
plot_floor_db = -80;

maximum_samples = 5000;
maximum_sweep_cases = 7;
maximum_targets = 3;
maximum_private_values = 20000;
maximum_working_numeric_values = 350000;
maximum_figures = 7;

controls = struct( ...
    'seed', baseline_seed, 'c_mps', speed_of_light_mps, ...
    'carrier_hz', carrier_frequency_hz, 'fs_hz', sample_rate_hz, ...
    'chirp_duration_s', chirp_duration_s, ...
    'bandwidth_hz', chirp_bandwidth_hz, ...
    'target_range_m', target_range_m, ...
    'target_velocity_mps', target_velocity_mps, ...
    'target_voltage', target_voltage, ...
    'target_phase_rad', target_initial_phase_rad, ...
    'noise_rms', noise_rms, 'range_sweep_m', range_sweep_m, ...
    'velocity_sweep_mps', velocity_sweep_mps, ...
    'noise_sweep_rms', noise_sweep_rms, ...
    'multi_range_m', multi_target_range_m, ...
    'multi_velocity_mps', multi_target_velocity_mps, ...
    'multi_voltage', multi_target_voltage, ...
    'multi_phase_rad', multi_target_phase_rad, ...
    'min_peak_separation_hz', minimum_peak_separation_hz, ...
    'plot_floor_db', plot_floor_db, ...
    'max_samples', maximum_samples, ...
    'max_sweep_cases', maximum_sweep_cases, ...
    'max_targets', maximum_targets, ...
    'max_private_values', maximum_private_values, ...
    'max_working_values', maximum_working_numeric_values, ...
    'max_figures', maximum_figures);
validate_controls(controls);

sample_count = round(sample_rate_hz*chirp_duration_s);
time_s = (0:sample_count-1).'/sample_rate_hz;
wavelength_m = speed_of_light_mps/carrier_frequency_hz;
chirp_slope_hz_per_s = chirp_bandwidth_hz/chirp_duration_s;
round_trip_delay_s = 2*target_range_m/speed_of_light_mps;
doppler_frequency_hz = 2*target_velocity_mps/wavelength_m;
delay_beat_frequency_hz = chirp_slope_hz_per_s*round_trip_delay_s;
ideal_up_beat_frequency_hz = delay_beat_frequency_hz- ...
    doppler_frequency_hz;
ideal_down_beat_frequency_hz = -delay_beat_frequency_hz- ...
    doppler_frequency_hz;
overlap_mask = time_s >= round_trip_delay_s;
overlap_start_index = find(overlap_mask, 1, 'first');
overlap_count = sum(overlap_mask);
target_motion_over_triangle_m = target_velocity_mps*2*chirp_duration_s;

preflight_working_value_bound = 80*sample_count + ...
    40*(numel(range_sweep_m)+numel(velocity_sweep_mps)+ ...
    numel(noise_sweep_rms)+numel(multi_target_range_m));
assert(preflight_working_value_bound <= maximum_working_numeric_values, ...
    'P72:PreflightWorkingBound', ...
    'Conservative simultaneous working-value estimate exceeds the ceiling.');

%% Baseline: generate one up leg and one down leg explicitly
% Positive velocity means approaching and f_d = 2*v/lambda is positive.
% With tx.*conj(rx), the signed triangular-leg equations are
% f_up = S*tau - f_d and f_down = -S*tau - f_d.
up_transmit_phase_rad = pi*chirp_slope_hz_per_s* ...
    (time_s-chirp_duration_s/2).^2;
down_transmit_phase_rad = -pi*chirp_slope_hz_per_s* ...
    (time_s-chirp_duration_s/2).^2;
up_transmit_chirp = exp(1j*up_transmit_phase_rad);
down_transmit_chirp = exp(1j*down_transmit_phase_rad);

up_echo_phase_rad = pi*chirp_slope_hz_per_s* ...
    (time_s-round_trip_delay_s-chirp_duration_s/2).^2 + ...
    2*pi*doppler_frequency_hz*time_s + target_initial_phase_rad;
down_echo_phase_rad = -pi*chirp_slope_hz_per_s* ...
    (time_s-round_trip_delay_s-chirp_duration_s/2).^2 + ...
    2*pi*doppler_frequency_hz*time_s + target_initial_phase_rad;
up_received_echo = zeros(sample_count, 1);
down_received_echo = zeros(sample_count, 1);
up_received_echo(overlap_mask) = target_voltage* ...
    exp(1j*up_echo_phase_rad(overlap_mask));
down_received_echo(overlap_mask) = target_voltage* ...
    exp(1j*down_echo_phase_rad(overlap_mask));

up_private_noise = noise_rms*private_complex_noise( ...
    baseline_seed, sample_count, maximum_private_values);
down_private_noise = noise_rms*private_complex_noise( ...
    baseline_seed+1, sample_count, maximum_private_values);
up_dechirped_beat = up_transmit_chirp.*conj(up_received_echo);
down_dechirped_beat = down_transmit_chirp.*conj(down_received_echo);
up_dechirped_beat(overlap_mask) = ...
    up_dechirped_beat(overlap_mask)+up_private_noise(overlap_mask);
down_dechirped_beat(overlap_mask) = ...
    down_dechirped_beat(overlap_mask)+down_private_noise(overlap_mask);

measured_up_beat_frequency_hz = estimate_signed_tone_frequency( ...
    up_dechirped_beat(overlap_mask), sample_rate_hz);
measured_down_beat_frequency_hz = estimate_signed_tone_frequency( ...
    down_dechirped_beat(overlap_mask), sample_rate_hz);

% Difference cancels Doppler; sum cancels delay. These are the two
% operations that make the triangular waveform informative.
measured_delay_beat_frequency_hz = ...
    (measured_up_beat_frequency_hz-measured_down_beat_frequency_hz)/2;
measured_doppler_frequency_hz = ...
    -(measured_up_beat_frequency_hz+measured_down_beat_frequency_hz)/2;
estimated_range_m = speed_of_light_mps* ...
    measured_delay_beat_frequency_hz/(2*chirp_slope_hz_per_s);
estimated_velocity_mps = wavelength_m*measured_doppler_frequency_hz/2;
range_error_m = estimated_range_m-target_range_m;
velocity_error_mps = estimated_velocity_mps-target_velocity_mps;

assert(abs(measured_up_beat_frequency_hz- ...
    ideal_up_beat_frequency_hz) < 250, 'P72:UpBeatEstimate', ...
    'Measured signed up beat moved outside the reviewed tolerance.');
assert(abs(measured_down_beat_frequency_hz- ...
    ideal_down_beat_frequency_hz) < 250, 'P72:DownBeatEstimate', ...
    'Measured signed down beat moved outside the reviewed tolerance.');
assert(abs(range_error_m) < 0.08 && abs(velocity_error_mps) < 0.08, ...
    'P72:BaselineSolve', ...
    'Opposite-slope solve must recover reviewed range and velocity.');

%% Figure 1: see delay and Doppler on both chirp slopes
up_transmit_frequency_hz = chirp_slope_hz_per_s* ...
    (time_s-chirp_duration_s/2);
down_transmit_frequency_hz = -chirp_slope_hz_per_s* ...
