integer_fields = {'seed', 'max_samples', 'max_sweep_cases', ...
    'max_targets', 'max_private_values', 'max_working_values', ...
    'max_figures'};
for field_index = 1:numel(integer_fields)
    value = c.(integer_fields{field_index});
    assert(value > 0 && value == floor(value), 'P72:ControlInteger', ...
        'Integer controls and ceilings must be positive integers.');
