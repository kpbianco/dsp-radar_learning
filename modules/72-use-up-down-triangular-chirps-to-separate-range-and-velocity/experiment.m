    numel(c.range_sweep_m) <= c.max_sweep_cases && ...
    all(c.range_sweep_m > 0) && all(diff(c.range_sweep_m) > 0) && ...
    any(c.range_sweep_m == c.target_range_m), 'P72:RangeSweepControls', ...
