function [up_beat, down_beat, overlap_mask] = simulate_chirp_pair( ...
    c, range_m, velocity_mps, case_noise_rms, seed)
% Repeat both visible baseline leg equations for one controlled case.
validateattributes(range_m, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
validateattributes(velocity_mps, {'numeric'}, ...
    {'scalar', 'real', 'finite'});
validateattributes(case_noise_rms, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'nonnegative', '<=', 0.2});
validateattributes(seed, {'numeric'}, ...
    {'scalar', 'integer', '>=', 1, '<', 2147483646});
sample_count_local = round(c.fs_hz*c.chirp_duration_s);
time_local_s = (0:sample_count_local-1).'/c.fs_hz;
slope_local = c.bandwidth_hz/c.chirp_duration_s;
delay_local_s = 2*range_m/c.c_mps;
doppler_local_hz = 2*velocity_mps/(c.c_mps/c.carrier_hz);
overlap_mask = time_local_s >= delay_local_s;
up_tx = exp(1j*pi*slope_local* ...
    (time_local_s-c.chirp_duration_s/2).^2);
down_tx = exp(-1j*pi*slope_local* ...
    (time_local_s-c.chirp_duration_s/2).^2);
up_echo = zeros(sample_count_local, 1);
down_echo = zeros(sample_count_local, 1);
up_echo_phase = pi*slope_local* ...
    (time_local_s-delay_local_s-c.chirp_duration_s/2).^2 + ...
    2*pi*doppler_local_hz*time_local_s + c.target_phase_rad;
down_echo_phase = -pi*slope_local* ...
    (time_local_s-delay_local_s-c.chirp_duration_s/2).^2 + ...
    2*pi*doppler_local_hz*time_local_s + c.target_phase_rad;
up_echo(overlap_mask) = c.target_voltage* ...
    exp(1j*up_echo_phase(overlap_mask));
down_echo(overlap_mask) = c.target_voltage* ...
    exp(1j*down_echo_phase(overlap_mask));
up_noise = case_noise_rms*private_complex_noise( ...
    seed, sample_count_local, c.max_private_values);
down_noise = case_noise_rms*private_complex_noise( ...
    seed+1, sample_count_local, c.max_private_values);
up_beat = up_tx.*conj(up_echo);
down_beat = down_tx.*conj(down_echo);
up_beat(overlap_mask) = up_beat(overlap_mask)+up_noise(overlap_mask);
down_beat(overlap_mask) = ...
    down_beat(overlap_mask)+down_noise(overlap_mask);
end

function [range_m, velocity_mps] = solve_pair(up_hz, down_hz, c)
% Solve the explicit 2-by-2 physical system; no estimator is hidden here.
validateattributes(up_hz, {'numeric'}, {'real', 'finite'});
validateattributes(down_hz, {'numeric'}, ...
    {'real', 'finite', 'size', size(up_hz)});
delay_beat_hz = (up_hz-down_hz)/2;
doppler_hz = -(up_hz+down_hz)/2;
slope_hz_per_s = c.bandwidth_hz/c.chirp_duration_s;
range_m = c.c_mps*delay_beat_hz/(2*slope_hz_per_s);
velocity_mps = (c.c_mps/c.carrier_hz)*doppler_hz/2;
end

function frequency_hz = estimate_signed_tone_frequency(samples, fs_hz)
validateattributes(samples, {'numeric'}, {'vector', 'nonempty', 'finite'});
validateattributes(fs_hz, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
assert(numel(samples) >= 2, 'P72:ToneLength', ...
    'Signed tone estimation requires at least two samples.');
lag_one_product = sum(conj(samples(1:end-1)).*samples(2:end));
assert(abs(lag_one_product) > 100*eps, 'P72:ToneEnergy', ...
    'Signed tone estimate requires nonzero coherent energy.');
frequency_hz = angle(lag_one_product)*fs_hz/(2*pi);
end

function [frequency_axis_hz, spectrum_db] = signed_spectrum( ...
    samples, fs_hz, floor_db)
validateattributes(samples, {'numeric'}, {'vector', 'nonempty', 'finite'});
sample_count_local = numel(samples);
assert(sample_count_local >= 2, 'P72:SpectrumLength', ...
    'A signed spectrum needs at least two samples.');
window = 0.5-0.5*cos(2*pi*(0:sample_count_local-1).' / ...
    (sample_count_local-1));
fft_count = 4*2^nextpow2(sample_count_local);
frequency_axis_hz = (-fft_count/2:fft_count/2-1).'*fs_hz/fft_count;
spectrum = fftshift(fft(samples(:).*window, fft_count))/sum(window);
normalized = abs(spectrum)/max(abs(spectrum));
spectrum_db = 20*log10(max(normalized, 10^(floor_db/20)));
end

function [frequencies_hz, frequency_axis_hz, spectrum_db] = ...
    estimate_separated_tones(samples, fs_hz, tone_count, ...
    minimum_separation_hz, floor_db)
% Find strongest separated local spectral peaks, then interpolate each peak.
validateattributes(samples, {'numeric'}, {'vector', 'nonempty', 'finite'});
validateattributes(tone_count, {'numeric'}, ...
    {'scalar', 'integer', '>=', 1, '<=', 3});
sample_count_local = numel(samples);
assert(sample_count_local >= 2, 'P72:PeakLength', ...
    'Peak estimation needs at least two samples.');
window = 0.5-0.5*cos(2*pi*(0:sample_count_local-1).' / ...
    (sample_count_local-1));
fft_count = 8*2^nextpow2(sample_count_local);
frequency_axis_hz = (-fft_count/2:fft_count/2-1).'*fs_hz/fft_count;
spectrum = fftshift(fft(samples(:).*window, fft_count))/sum(window);
magnitude = abs(spectrum);
spectrum_db = 20*log10(max(magnitude/max(magnitude), 10^(floor_db/20)));
search_magnitude = magnitude;
blank_half_width = max(1, ceil(minimum_separation_hz / ...
    (fs_hz/fft_count)));
frequencies_hz = zeros(1, tone_count);
for tone_index = 1:tone_count
    [peak_value, peak_index] = max(search_magnitude);
    assert(peak_value > 100*eps && peak_index > 1 && ...
        peak_index < fft_count, 'P72:PeakEnergy', ...
        'Separated-tone estimation requires interior nonzero peaks.');
    left_value = magnitude(peak_index-1);
    center_value = magnitude(peak_index);
    right_value = magnitude(peak_index+1);
    denominator = left_value-2*center_value+right_value;
    offset = 0;
    if abs(denominator) > 100*eps
        offset = 0.5*(left_value-right_value)/denominator;
        offset = max(-0.5, min(0.5, offset));
    end
    frequencies_hz(tone_index) = frequency_axis_hz(peak_index) + ...
        offset*(fs_hz/fft_count);
    blank_start = max(1, peak_index-blank_half_width);
    blank_stop = min(fft_count, peak_index+blank_half_width);
    search_magnitude(blank_start:blank_stop) = 0;
end
frequencies_hz = sort(frequencies_hz);
end

function noise = private_complex_noise(seed, count, maximum_values)
validateattributes(seed, {'numeric'}, ...
    {'scalar', 'integer', '>=', 1, '<', 2147483647});
validateattributes(count, {'numeric'}, ...
    {'scalar', 'integer', 'positive'});
validateattributes(maximum_values, {'numeric'}, ...
    {'scalar', 'integer', 'positive'});
assert(2*count <= maximum_values, 'P72:PrivateNoiseBound', ...
    'Private generator request exceeds the reviewed ceiling.');
uniform_values = private_uniform(seed, 2*count, maximum_values);
first = max(uniform_values(1:count), realmin);
second = uniform_values(count+1:end);
noise = sqrt(-2*log(first)).*exp(1j*2*pi*second)/sqrt(2);
end

function values = private_uniform(seed, count, maximum_values)
validateattributes(seed, {'numeric'}, ...
    {'scalar', 'integer', '>=', 1, '<', 2147483647});
validateattributes(count, {'numeric'}, ...
    {'scalar', 'integer', '>=', 1, '<=', maximum_values});
state = seed;
values = zeros(count, 1);
for value_index = 1:count
    state = mod(16807*state, 2147483647);
    values(value_index) = state/2147483647;
end
end

