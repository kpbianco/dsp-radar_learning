%% Intentionally broken case: pair beats from different targets
% The composite up and down records contain two tones each. Sorting both
% signed lists the same way pairs target 1's up beat with target 2's down
% beat and creates two plausible but false range/velocity reports.
multi_count = numel(multi_target_range_m);
multi_up_echo = zeros(sample_count, 1);
multi_down_echo = zeros(sample_count, 1);
multi_overlap_mask = time_s >= ...
    max(2*multi_target_range_m/speed_of_light_mps);
for target_index = 1:multi_count
    target_delay_s = 2*multi_target_range_m(target_index)/ ...
        speed_of_light_mps;
    target_doppler_hz = 2*multi_target_velocity_mps(target_index)/ ...
        wavelength_m;
    target_mask = time_s >= target_delay_s;
    target_up_phase = pi*chirp_slope_hz_per_s* ...
        (time_s-target_delay_s-chirp_duration_s/2).^2 + ...
        2*pi*target_doppler_hz*time_s + ...
        multi_target_phase_rad(target_index);
    target_down_phase = -pi*chirp_slope_hz_per_s* ...
        (time_s-target_delay_s-chirp_duration_s/2).^2 + ...
        2*pi*target_doppler_hz*time_s + ...
        multi_target_phase_rad(target_index);
    multi_up_echo(target_mask) = multi_up_echo(target_mask) + ...
        multi_target_voltage(target_index)*exp( ...
        1j*target_up_phase(target_mask));
    multi_down_echo(target_mask) = multi_down_echo(target_mask) + ...
        multi_target_voltage(target_index)*exp( ...
        1j*target_down_phase(target_mask));
end
multi_up_beat = up_transmit_chirp.*conj(multi_up_echo);
multi_down_beat = down_transmit_chirp.*conj(multi_down_echo);
multi_up_noise = noise_rms*private_complex_noise( ...
    baseline_seed+500, sample_count, maximum_private_values);
multi_down_noise = noise_rms*private_complex_noise( ...
    baseline_seed+501, sample_count, maximum_private_values);
multi_up_beat(multi_overlap_mask) = multi_up_beat(multi_overlap_mask) + ...
    multi_up_noise(multi_overlap_mask);
multi_down_beat(multi_overlap_mask) = ...
    multi_down_beat(multi_overlap_mask) + ...
    multi_down_noise(multi_overlap_mask);

[detected_up_hz, multi_frequency_axis_hz, multi_up_spectrum_db] = ...
    estimate_separated_tones(multi_up_beat(multi_overlap_mask), ...
    sample_rate_hz, multi_count, minimum_peak_separation_hz, plot_floor_db);
[detected_down_hz, ~, multi_down_spectrum_db] = ...
    estimate_separated_tones(multi_down_beat(multi_overlap_mask), ...
    sample_rate_hz, multi_count, minimum_peak_separation_hz, plot_floor_db);

wrong_paired_down_hz = detected_down_hz;
correct_paired_down_hz = fliplr(detected_down_hz);
[ghost_range_m, ghost_velocity_mps] = solve_pair( ...
    detected_up_hz, wrong_paired_down_hz, controls);
[recovered_range_m, recovered_velocity_mps] = solve_pair( ...
    detected_up_hz, correct_paired_down_hz, controls);

assert(max(abs(recovered_range_m-multi_target_range_m)) < 0.8 && ...
    max(abs(recovered_velocity_mps-multi_target_velocity_mps)) < 1.5, ...
    'P72:PairingRecovery', ...
    'Correct association must recover both reviewed target reports.');
assert(min(abs(ghost_range_m(1)-multi_target_range_m)) > 5 && ...
    min(abs(ghost_range_m(2)-multi_target_range_m)) > 5, ...
    'P72:WrongPairingFailure', ...
    'Wrong cross-target pairing must create reviewed ghost ranges.');
assert(isequal(wrong_paired_down_hz, detected_down_hz) && ...
    isequal(fliplr(correct_paired_down_hz), detected_down_hz), ...
    'P72:SameDetectionRecovery', ...
    'Association recovery must reuse the unchanged detected beat lists.');

figure('Name', 'P72 multi-target pairing failure and recovery', 'Tag', 'P72');
