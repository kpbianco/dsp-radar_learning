    numel(c.noise_sweep_rms) <= c.max_sweep_cases && ...
    all(c.noise_sweep_rms >= 0) && all(diff(c.noise_sweep_rms) > 0) && ...
    c.noise_sweep_rms(1) == 0 && ...
    any(c.noise_sweep_rms == c.noise_rms) && ...
    c.noise_sweep_rms(end) <= 0.2, 'P72:NoiseSweepControls', ...
    'Noise sweep must be bounded, ordered, and include zero and baseline.');
