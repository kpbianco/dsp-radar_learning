seed_signature = randn(random_stream, 1, 4);
unit_noise = randn(random_stream, 1, record_sample_count);
noise_v = noise_sigma_v*unit_noise;
clean_hidden_v = zeros(1, record_sample_count);
hidden_record_indices = hidden_delay_samples + (1:reference_sample_count);
clean_hidden_v(hidden_record_indices) = hidden_amplitude_v*reference;
received_v = clean_hidden_v + noise_v;
record_n = 0:record_sample_count-1;
record_time_ms = 1000*record_n/fs;
reference_n = 0:reference_sample_count-1;
