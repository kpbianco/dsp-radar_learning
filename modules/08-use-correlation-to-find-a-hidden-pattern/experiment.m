    hidden_amplitude_v*sqrt(reference_energy)/noise_sigma_v;
matched_output_power_snr_linear = ...
    matched_output_peak_to_noise_rms_ratio^2;

aligned_products_v = received_v(hidden_record_indices).*reference;
