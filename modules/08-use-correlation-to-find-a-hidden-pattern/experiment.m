%% Correlate explicitly over relative delay, then cross-check with conv
% The convention is r_xs[lag] = sum_m x[lag+m]*s[m], using zero outside the
% record. A positive lag means the reference starts later in the record.
explicit_correlation_v = zeros(1, correlation_sample_count);
for lag_index = 1:correlation_sample_count
    lag_samples = correlation_lags_samples(lag_index);
    for reference_index = 1:reference_sample_count
        received_index = lag_samples + (reference_index-1);
        if received_index >= 0 && received_index < record_sample_count
            explicit_correlation_v(lag_index) = ...
                explicit_correlation_v(lag_index) + ...
                received_v(received_index+1)*reference(reference_index);
        end
    end
end

conv_correlation_v = conv(received_v, fliplr(reference));
explicit_vs_conv_max_error_v = max(abs(...
    explicit_correlation_v-conv_correlation_v));
assert(explicit_vs_conv_max_error_v < comparison_tolerance_v, ...
    'The explicit correlation must match conv(x,fliplr(s)).');

[correlation_peak_v, correlation_peak_index] = max(explicit_correlation_v);
estimated_delay_samples = correlation_lags_samples(correlation_peak_index);
estimated_delay_ms = 1000*estimated_delay_samples/fs;
delay_error_samples = estimated_delay_samples-hidden_delay_samples;
delay_error_us = 1e6*delay_error_samples/fs;
assert(estimated_delay_samples == hidden_delay_samples, ...
    'The deterministic baseline must locate the configured hidden delay.');

peak_exclusion_half_width_samples = samples_per_chip;
sidelobe_mask = abs(correlation_lags_samples-estimated_delay_samples) > ...
    peak_exclusion_half_width_samples;
largest_outside_peak_v = max(abs(explicit_correlation_v(sidelobe_mask)));
peak_to_outside_ratio_db = 20*log10(abs(correlation_peak_v)/ ...
    largest_outside_peak_v);
expected_noise_output_rms_v = noise_sigma_v*sqrt(reference_energy);
