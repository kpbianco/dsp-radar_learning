%% Build the known dimensionless coded pulse
% Repeat each signed chip explicitly, remove its small DC mean, and normalize
% to unit RMS. This keeps code energy and output units visible.
reference_sample_count = numel(reference_chips)*samples_per_chip;
reference = zeros(1, reference_sample_count);
for chip_index = 1:numel(reference_chips)
    first_reference_index = (chip_index-1)*samples_per_chip + 1;
    last_reference_index = chip_index*samples_per_chip;
    reference(first_reference_index:last_reference_index) = ...
        reference_chips(chip_index);
end
reference = reference - mean(reference);
reference_rms = sqrt(sum(reference.^2)/reference_sample_count);
reference = reference/reference_rms;
final_reference_rms = sqrt(sum(reference.^2)/reference_sample_count);
reference_energy = sum(reference.^2);
correlation_sample_count = record_sample_count + reference_sample_count - 1;
correlation_lags_samples = -(reference_sample_count-1):(record_sample_count-1);

assert(reference_sample_count <= max_reference_samples, ...
    'reference_sample_count exceeds the reviewed resource ceiling.');
assert(correlation_sample_count <= max_correlation_samples, ...
    'correlation_sample_count exceeds the reviewed resource ceiling.');
assert(abs(mean(reference)) < comparison_tolerance_v && ...
    abs(final_reference_rms-1) < comparison_tolerance_v, ...
    'The final reference must be zero mean and unit RMS.');
assert(abs(sum(reference.^2)-reference_sample_count) < ...
    comparison_tolerance_v, 'Unit-RMS reference energy must equal its length.');
assert(hidden_delay_samples + reference_sample_count <= record_sample_count, ...
    'The baseline reference must fit completely inside the record.');
assert(hidden_delay_samples + max(second_separation_sweep_samples) + ...
    reference_sample_count <= record_sample_count, ...
    'Every second-copy sweep case must fit completely inside the record.');

%% Deterministic noisy record with one hidden copy
% A private stream makes the noise repeatable without changing MATLAB's global
% random stream. The exact clean insertion remains explicit.
