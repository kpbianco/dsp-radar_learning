%% Sweep 1: change only guard cells and expose target self-masking
guard_case_count = numel(guard_cell_sweep);
guard_sweep_threshold_power = nan(guard_case_count, cell_count);
guard_sweep_detection_mask = false(guard_case_count, cell_count);
guard_sweep_strong_target_margin = zeros(1, guard_case_count);
guard_sweep_reference_target_power = zeros(1, guard_case_count);
guard_sweep_window_span_m = zeros(1, guard_case_count);
guard_sweep_excluded_edge_count = zeros(1, guard_case_count);
for guard_index = 1:guard_case_count
    guard_cells_per_side = guard_cell_sweep(guard_index);
    sweep_first_cell = baseline_training_cells_per_side+...
        guard_cells_per_side+1;
    sweep_last_cell = cell_count-baseline_training_cells_per_side-...
        guard_cells_per_side;
    for cut_cell = sweep_first_cell:sweep_last_cell
        leading_training_cells = cut_cell-guard_cells_per_side-...
            baseline_training_cells_per_side:cut_cell-guard_cells_per_side-1;
        lagging_training_cells = cut_cell+guard_cells_per_side+1:...
            cut_cell+guard_cells_per_side+baseline_training_cells_per_side;
        training_cells = [leading_training_cells lagging_training_cells];
        local_noise_estimate_power = mean(profile_power(training_cells));
        guard_sweep_threshold_power(guard_index, cut_cell) = ...
            cfar_scale_factor*local_noise_estimate_power;
        guard_sweep_detection_mask(guard_index, cut_cell) = ...
            profile_power(cut_cell) > ...
            guard_sweep_threshold_power(guard_index, cut_cell);
    end
    strong_leading_references = strong_target_cell-guard_cells_per_side-...
        baseline_training_cells_per_side:strong_target_cell-...
        guard_cells_per_side-1;
    strong_lagging_references = strong_target_cell+guard_cells_per_side+1:...
        strong_target_cell+guard_cells_per_side+...
        baseline_training_cells_per_side;
    strong_references = [strong_leading_references strong_lagging_references];
    guard_sweep_reference_target_power(guard_index) = ...
        mean(target_only_power(strong_references));
    guard_sweep_strong_target_margin(guard_index) = ...
        profile_power(strong_target_cell)/...
        guard_sweep_threshold_power(guard_index, strong_target_cell);
    guard_sweep_window_span_m(guard_index) = ...
        (2*(baseline_training_cells_per_side+guard_cells_per_side)+1)*...
        range_resolution_m;
    guard_sweep_excluded_edge_count(guard_index) = ...
        2*(baseline_training_cells_per_side+guard_cells_per_side);
end
