%% Sweep 2: change only training cells and separate variance from locality
training_case_count = numel(training_cell_sweep);
training_sweep_scale_factor = zeros(1, training_case_count);
training_sweep_noise_estimate_power = nan(training_case_count, cell_count);
training_sweep_expected_estimate_power = nan(training_case_count, cell_count);
training_sweep_threshold_power = nan(training_case_count, cell_count);
training_sweep_roughness = zeros(1, training_case_count);
training_sweep_locality_error = zeros(1, training_case_count);
training_sweep_window_span_m = zeros(1, training_case_count);
training_sweep_excluded_edge_count = zeros(1, training_case_count);
for training_index = 1:training_case_count
    training_cells_per_side = training_cell_sweep(training_index);
    sweep_training_count = 2*training_cells_per_side;
    training_sweep_scale_factor(training_index) = sweep_training_count*(...
        design_false_alarm_probability^(-1/sweep_training_count)-1);
    sweep_first_cell = training_cells_per_side+...
        training_sweep_guard_cells_per_side+1;
    sweep_last_cell = cell_count-training_cells_per_side-...
        training_sweep_guard_cells_per_side;
    for cut_cell = sweep_first_cell:sweep_last_cell
        leading_training_cells = cut_cell-...
            training_sweep_guard_cells_per_side-training_cells_per_side:...
            cut_cell-training_sweep_guard_cells_per_side-1;
        lagging_training_cells = cut_cell+...
            training_sweep_guard_cells_per_side+1:cut_cell+...
            training_sweep_guard_cells_per_side+training_cells_per_side;
        training_cells = [leading_training_cells lagging_training_cells];
        training_sweep_noise_estimate_power(training_index, cut_cell) = ...
            mean(background_only_power(training_cells));
        training_sweep_expected_estimate_power(training_index, cut_cell) = ...
            mean(background_mean_power(training_cells));
        training_sweep_threshold_power(training_index, cut_cell) = ...
            training_sweep_scale_factor(training_index)*...
            training_sweep_noise_estimate_power(training_index, cut_cell);
    end
    quiet_estimate = training_sweep_noise_estimate_power(...
        training_index, quiet_region_cells);
    training_sweep_roughness(training_index) = mean(abs(diff(quiet_estimate)))/...
        mean(background_mean_power(quiet_region_cells));
    expected_transition_estimate = training_sweep_expected_estimate_power(...
        training_index, transition_region_cells);
    training_sweep_locality_error(training_index) = mean(abs(...
        expected_transition_estimate-...
        background_mean_power(transition_region_cells))./...
        background_mean_power(transition_region_cells));
    training_sweep_window_span_m(training_index) = ...
        (2*(training_cells_per_side+...
        training_sweep_guard_cells_per_side)+1)*range_resolution_m;
    training_sweep_excluded_edge_count(training_index) = ...
        2*(training_cells_per_side+training_sweep_guard_cells_per_side);
end
