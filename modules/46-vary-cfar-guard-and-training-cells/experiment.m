    contaminating_target_complex_amplitude;
contaminated_profile_power = abs(contaminated_received).^2;
assert(contaminated_profile_power(weak_target_cell) == ...
    profile_power(weak_target_cell));

broken_noise_estimate_power = nan(1, cell_count);
broken_threshold_power = nan(1, cell_count);
broken_detection_mask = false(1, cell_count);
for cut_cell = valid_first_cell:valid_last_cell
    leading_training_cells = cut_cell-baseline_guard_cells_per_side-...
        baseline_training_cells_per_side:...
        cut_cell-baseline_guard_cells_per_side-1;
    lagging_training_cells = cut_cell+baseline_guard_cells_per_side+1:...
        cut_cell+baseline_guard_cells_per_side+...
        baseline_training_cells_per_side;
    training_cells = [leading_training_cells lagging_training_cells];
    broken_noise_estimate_power(cut_cell) = ...
        mean(contaminated_profile_power(training_cells));
    broken_threshold_power(cut_cell) = ...
        cfar_scale_factor*broken_noise_estimate_power(cut_cell);
    broken_detection_mask(cut_cell) = contaminated_profile_power(cut_cell) > ...
        broken_threshold_power(cut_cell);
end
broken_weak_leading_references = weak_target_cell-...
    baseline_guard_cells_per_side-baseline_training_cells_per_side:...
    weak_target_cell-baseline_guard_cells_per_side-1;
broken_weak_lagging_references = weak_target_cell+...
    baseline_guard_cells_per_side+1:weak_target_cell+...
    baseline_guard_cells_per_side+baseline_training_cells_per_side;
broken_weak_references = [broken_weak_leading_references ...
    broken_weak_lagging_references];
broken_reference_contains_contaminator = any(...
    broken_weak_references == contaminating_target_cell);
broken_claim_is_valid = false;

recovery_first_cell = baseline_training_cells_per_side+...
    recovery_guard_cells_per_side+1;
recovery_last_cell = cell_count-baseline_training_cells_per_side-...
    recovery_guard_cells_per_side;
recovery_noise_estimate_power = nan(1, cell_count);
recovery_threshold_power = nan(1, cell_count);
recovery_detection_mask = false(1, cell_count);
for cut_cell = recovery_first_cell:recovery_last_cell
    leading_training_cells = cut_cell-recovery_guard_cells_per_side-...
        baseline_training_cells_per_side:...
        cut_cell-recovery_guard_cells_per_side-1;
    lagging_training_cells = cut_cell+recovery_guard_cells_per_side+1:...
        cut_cell+recovery_guard_cells_per_side+...
        baseline_training_cells_per_side;
    training_cells = [leading_training_cells lagging_training_cells];
    recovery_noise_estimate_power(cut_cell) = ...
        mean(contaminated_profile_power(training_cells));
    recovery_threshold_power(cut_cell) = ...
        cfar_scale_factor*recovery_noise_estimate_power(cut_cell);
    recovery_detection_mask(cut_cell) = ...
        contaminated_profile_power(cut_cell) > ...
        recovery_threshold_power(cut_cell);
end
recovery_weak_leading_references = weak_target_cell-...
    recovery_guard_cells_per_side-baseline_training_cells_per_side:...
    weak_target_cell-recovery_guard_cells_per_side-1;
recovery_weak_lagging_references = weak_target_cell+...
    recovery_guard_cells_per_side+1:weak_target_cell+...
    recovery_guard_cells_per_side+baseline_training_cells_per_side;
recovery_weak_references = [recovery_weak_leading_references ...
    recovery_weak_lagging_references];
recovery_reference_excludes_contaminator = ~any(...
    recovery_weak_references == contaminating_target_cell);
recovery_geometry_valid = recovery_reference_excludes_contaminator && ...
    abs(weak_target_cell-contaminating_target_cell) <= ...
    recovery_guard_cells_per_side;
assert(broken_reference_contains_contaminator);
assert(~broken_detection_mask(weak_target_cell));
assert(recovery_geometry_valid);
assert(recovery_detection_mask(weak_target_cell));
assert(recovery_threshold_power(weak_target_cell) < ...
    broken_threshold_power(weak_target_cell));

