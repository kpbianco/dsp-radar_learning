%% Build one gradual background and a target with a visible sampled-sinc response
cell_index = 1:cell_count;
range_axis_m = (cell_index-1)*range_resolution_m;
background_mean_power = 0.75+0.003*cell_index+...
    2.8./(1+exp(-(cell_index-background_transition_cell)/5.5));
assert(all(isfinite(background_mean_power)) && ...
    all(background_mean_power > 0) && all(diff(background_mean_power) > 0));

private_stream = RandStream('mt19937ar', 'Seed', random_seed);
unit_noise_i = randn(private_stream, 1, cell_count);
unit_noise_q = randn(private_stream, 1, cell_count);
unit_complex_noise = (unit_noise_i+1i*unit_noise_q)/sqrt(2);
background_only_received = sqrt(background_mean_power).*unit_complex_noise;
background_only_power = abs(background_only_received).^2;
received = background_only_received;

response_offsets = -target_response_half_span_cells:...
    target_response_half_span_cells;
response_argument = response_offsets/target_response_width_cells;
target_response_amplitude = ones(size(response_argument));
nonzero_response = response_offsets ~= 0;
target_response_amplitude(nonzero_response) = ...
    sin(pi*response_argument(nonzero_response))./...
    (pi*response_argument(nonzero_response));
target_response_amplitude = target_response_amplitude/...
    max(abs(target_response_amplitude));
strong_response_cells = strong_target_cell+response_offsets;
strong_target_complex_amplitude = sqrt(...
    background_mean_power(strong_target_cell)*...
    10^(strong_target_snr_db/10))*exp(1i*strong_target_phase_rad);
strong_target_response = strong_target_complex_amplitude*...
    target_response_amplitude;
received(strong_response_cells) = received(strong_response_cells)+...
    strong_target_response;

weak_target_complex_amplitude = sqrt(background_mean_power(weak_target_cell)*...
    10^(weak_target_snr_db/10))*exp(1i*weak_target_phase_rad);
received(weak_target_cell) = received(weak_target_cell)+...
    weak_target_complex_amplitude;
profile_power = abs(received).^2;
assert(all(isfinite(profile_power)) && all(profile_power >= 0));

