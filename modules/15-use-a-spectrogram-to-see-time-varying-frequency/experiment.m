%% Deterministic record and visible component tracks
sample_index = 0:(record_sample_count - 1);
time_s = sample_index/fs_hz;
steady_v = steady_amplitude_v*cos(2*pi*steady_frequency_hz*time_s + ...
    steady_phase_rad);

chirp_gate = zeros(1, record_sample_count);
chirp_active_index = chirp_start_sample + (1:chirp_sample_count);
chirp_gate(chirp_active_index) = 1;
chirp_taper = sin(linspace(0, pi/2, chirp_taper_sample_count)).^2;
chirp_gate(chirp_active_index(1:chirp_taper_sample_count)) = chirp_taper;
chirp_gate(chirp_active_index((end - chirp_taper_sample_count + 1):end)) = ...
    fliplr(chirp_taper);
chirp_rate_hz_per_s = ...
    (chirp_stop_frequency_hz - chirp_start_frequency_hz)/ ...
    (chirp_stop_s - chirp_start_s);
chirp_time_from_start_s = time_s - chirp_start_s;
chirp_phase_track_rad = 2*pi*(chirp_start_frequency_hz* ...
    chirp_time_from_start_s + 0.5*chirp_rate_hz_per_s* ...
    chirp_time_from_start_s.^2) + chirp_phase_rad;
chirp_v = chirp_amplitude_v*chirp_gate.*cos(chirp_phase_track_rad);

burst_gate = zeros(1, record_sample_count);
burst_active_index = burst_start_sample + (1:burst_sample_count);
burst_gate(burst_active_index) = 0.5 - 0.5*cos(2*pi* ...
    (0:(burst_sample_count - 1))/(burst_sample_count - 1));
burst_v = burst_amplitude_v*burst_gate.*cos(2*pi*burst_frequency_hz*time_s + ...
    burst_phase_rad);
burst_center_s = ...
    (burst_start_sample + (burst_sample_count - 1)/2)/fs_hz;

hop_frequency_track_hz = hop_frequency_before_hz*ones(1, record_sample_count);
hop_frequency_track_hz((hop_sample + 1):end) = hop_frequency_after_hz;
% Integrating instantaneous frequency keeps phase continuous at the hop.
hop_phase_track_rad = hop_phase_rad + 2*pi*[0 cumsum( ...
    hop_frequency_track_hz(1:(end - 1)))]/fs_hz;
hop_v = hop_amplitude_v*cos(hop_phase_track_rad);

stream = RandStream('mt19937ar', 'Seed', random_seed);
raw_noise_v = randn(stream, 1, record_sample_count);
noise_v = noise_rms_v*raw_noise_v/sqrt(mean(raw_noise_v.^2));
record_v = steady_v + chirp_v + burst_v + hop_v + noise_v;

%% Baseline: explicit 128-sample, 50%-overlapped STFT
% For frame r, X_r[k] = sum_m x[rH+m]w[m]exp(-j*2*pi*k*m/M).
% PSD is |X_r[k]|^2/(fs*sum(w.^2)) in V^2/Hz. Retain DC through
% Nyquist and double only interior bins. Timestamp each frame at its center.
baseline_window = 0.5 - 0.5*cos(2*pi* ...
    (0:(baseline_window_length - 1))/(baseline_window_length - 1));
baseline_window_energy = sum(baseline_window.^2);
baseline_frame_start = 1:baseline_hop_samples: ...
    (record_sample_count - baseline_window_length + 1);
baseline_time_s = ((baseline_frame_start - 1) + ...
    (baseline_window_length - 1)/2)/fs_hz;
baseline_frequency_hz = ...
    (0:(baseline_window_length/2))*fs_hz/baseline_window_length;
baseline_psd_v2_per_hz = zeros(numel(baseline_frequency_hz), ...
    baseline_frame_count);
for frame_index = 1:baseline_frame_count
    frame_sample_index = baseline_frame_start(frame_index) + ...
        (0:(baseline_window_length - 1));
    windowed_frame_v = record_v(frame_sample_index).*baseline_window;
    frame_fft_v = fft(windowed_frame_v, baseline_window_length);
    frame_two_sided_psd_v2_per_hz = ...
        abs(frame_fft_v).^2/(fs_hz*baseline_window_energy);
    frame_one_sided_psd_v2_per_hz = ...
        frame_two_sided_psd_v2_per_hz(1:(baseline_window_length/2 + 1));
    frame_one_sided_psd_v2_per_hz(2:end-1) = ...
        2*frame_one_sided_psd_v2_per_hz(2:end-1);
    baseline_psd_v2_per_hz(:, frame_index) = ...
        frame_one_sided_psd_v2_per_hz(:);
end
baseline_display_db = 10*log10(max(baseline_psd_v2_per_hz, ...
    10^(display_floor_db/10)));
baseline_window_duration_ms = 1000*baseline_window_length/fs_hz;
baseline_time_step_ms = 1000*baseline_hop_samples/fs_hz;
baseline_bin_spacing_hz = fs_hz/baseline_window_length;
baseline_hann_main_lobe_width_hz = 4*fs_hz/baseline_window_length;

[~, baseline_burst_bin] = min(abs(baseline_frequency_hz - burst_frequency_hz));
[baseline_burst_peak_psd_v2_per_hz, baseline_burst_peak_frame] = ...
    max(baseline_psd_v2_per_hz(baseline_burst_bin, :));
baseline_burst_peak_time_s = baseline_time_s(baseline_burst_peak_frame);
baseline_burst_peak_time_error_ms = ...
    1000*abs(baseline_burst_peak_time_s - burst_center_s);

chirp_frame_mask = baseline_time_s >= ...
    chirp_start_s + chirp_taper_sample_count/fs_hz & ...
    baseline_time_s <= chirp_stop_s - chirp_taper_sample_count/fs_hz;
chirp_frequency_mask = baseline_frequency_hz >= ...
    chirp_start_frequency_hz - 16 & baseline_frequency_hz <= ...
    chirp_stop_frequency_hz + 16;
chirp_search_psd = baseline_psd_v2_per_hz(chirp_frequency_mask, chirp_frame_mask);
chirp_search_frequency_hz = baseline_frequency_hz(chirp_frequency_mask);
[~, chirp_ridge_local_index] = max(chirp_search_psd, [], 1);
chirp_ridge_frequency_hz = chirp_search_frequency_hz(chirp_ridge_local_index);
chirp_expected_frequency_hz = chirp_start_frequency_hz + ...
    chirp_rate_hz_per_s*(baseline_time_s(chirp_frame_mask) - chirp_start_s);
baseline_chirp_ridge_mae_hz = ...
    mean(abs(chirp_ridge_frequency_hz - chirp_expected_frequency_hz));

%% Sweep 1: change only window duration at matched 50% overlap
window_psd_v2_per_hz = cell(1, numel(window_length_sweep));
window_frequency_hz = cell(1, numel(window_length_sweep));
window_time_s = cell(1, numel(window_length_sweep));
window_display_db = cell(1, numel(window_length_sweep));
window_duration_ms = 1000*window_length_sweep/fs_hz;
window_time_step_ms = 1000*window_hop_samples/fs_hz;
window_bin_spacing_hz = fs_hz./window_length_sweep;
window_resolution_ratio = ...
    hop_frequency_separation_hz./window_hann_main_lobe_width_hz;
window_burst_peak_time_error_ms = zeros(1, numel(window_length_sweep));

for sweep_index = 1:numel(window_length_sweep)
    sweep_window_length = window_length_sweep(sweep_index);
    sweep_hop_samples = window_hop_samples(sweep_index);
    sweep_window = 0.5 - 0.5*cos(2*pi* ...
        (0:(sweep_window_length - 1))/(sweep_window_length - 1));
    sweep_window_energy = sum(sweep_window.^2);
    sweep_frame_start = 1:sweep_hop_samples: ...
        (record_sample_count - sweep_window_length + 1);
    sweep_time_s = ((sweep_frame_start - 1) + ...
        (sweep_window_length - 1)/2)/fs_hz;
    sweep_frequency_hz = ...
        (0:(sweep_window_length/2))*fs_hz/sweep_window_length;
    sweep_psd_v2_per_hz = zeros(numel(sweep_frequency_hz), ...
        window_frame_count(sweep_index));
    for frame_index = 1:window_frame_count(sweep_index)
        frame_sample_index = sweep_frame_start(frame_index) + ...
            (0:(sweep_window_length - 1));
        windowed_frame_v = record_v(frame_sample_index).*sweep_window;
        frame_fft_v = fft(windowed_frame_v, sweep_window_length);
        frame_two_sided_psd_v2_per_hz = ...
            abs(frame_fft_v).^2/(fs_hz*sweep_window_energy);
        frame_one_sided_psd_v2_per_hz = ...
            frame_two_sided_psd_v2_per_hz(1:(sweep_window_length/2 + 1));
        frame_one_sided_psd_v2_per_hz(2:end-1) = ...
            2*frame_one_sided_psd_v2_per_hz(2:end-1);
        sweep_psd_v2_per_hz(:, frame_index) = ...
            frame_one_sided_psd_v2_per_hz(:);
    end
    window_psd_v2_per_hz{sweep_index} = sweep_psd_v2_per_hz;
    window_frequency_hz{sweep_index} = sweep_frequency_hz;
    window_time_s{sweep_index} = sweep_time_s;
    window_display_db{sweep_index} = 10*log10(max(sweep_psd_v2_per_hz, ...
        10^(display_floor_db/10)));
    [~, sweep_burst_bin] = min(abs(sweep_frequency_hz - burst_frequency_hz));
    [~, sweep_burst_peak_frame] = max(sweep_psd_v2_per_hz(sweep_burst_bin, :));
    window_burst_peak_time_error_ms(sweep_index) = 1000*abs( ...
        sweep_time_s(sweep_burst_peak_frame) - burst_center_s);
end

%% Sweep 2: change only overlap at fixed 128-sample window
overlap_psd_v2_per_hz = cell(1, numel(overlap_fraction_sweep));
overlap_time_s = cell(1, numel(overlap_fraction_sweep));
overlap_display_db = cell(1, numel(overlap_fraction_sweep));
overlap_time_step_ms = 1000*overlap_sweep_hop_samples/fs_hz;
overlap_bin_spacing_hz = baseline_bin_spacing_hz* ...
    ones(size(overlap_fraction_sweep));
overlap_hann_main_lobe_width_hz = baseline_hann_main_lobe_width_hz* ...
    ones(size(overlap_fraction_sweep));
overlap_burst_peak_psd_v2_per_hz = zeros(size(overlap_fraction_sweep));
overlap_burst_peak_time_error_ms = zeros(size(overlap_fraction_sweep));

for sweep_index = 1:numel(overlap_fraction_sweep)
    sweep_overlap_samples = overlap_sweep_samples(sweep_index);
    sweep_hop_samples = baseline_window_length - sweep_overlap_samples;
    sweep_frame_start = 1:sweep_hop_samples: ...
        (record_sample_count - baseline_window_length + 1);
    sweep_time_s = ((sweep_frame_start - 1) + ...
        (baseline_window_length - 1)/2)/fs_hz;
    sweep_psd_v2_per_hz = zeros(numel(baseline_frequency_hz), ...
        overlap_frame_count(sweep_index));
    for frame_index = 1:overlap_frame_count(sweep_index)
        frame_sample_index = sweep_frame_start(frame_index) + ...
            (0:(baseline_window_length - 1));
        windowed_frame_v = record_v(frame_sample_index).*baseline_window;
        frame_fft_v = fft(windowed_frame_v, baseline_window_length);
        frame_two_sided_psd_v2_per_hz = ...
            abs(frame_fft_v).^2/(fs_hz*baseline_window_energy);
        frame_one_sided_psd_v2_per_hz = ...
            frame_two_sided_psd_v2_per_hz(1:(baseline_window_length/2 + 1));
        frame_one_sided_psd_v2_per_hz(2:end-1) = ...
            2*frame_one_sided_psd_v2_per_hz(2:end-1);
        sweep_psd_v2_per_hz(:, frame_index) = ...
            frame_one_sided_psd_v2_per_hz(:);
    end
    overlap_psd_v2_per_hz{sweep_index} = sweep_psd_v2_per_hz;
    overlap_time_s{sweep_index} = sweep_time_s;
    overlap_display_db{sweep_index} = 10*log10(max(sweep_psd_v2_per_hz, ...
        10^(display_floor_db/10)));
    [overlap_burst_peak_psd_v2_per_hz(sweep_index), burst_peak_frame] = ...
        max(sweep_psd_v2_per_hz(baseline_burst_bin, :));
    overlap_burst_peak_time_error_ms(sweep_index) = 1000*abs( ...
        sweep_time_s(burst_peak_frame) - burst_center_s);
end
overlap_burst_capture_gain_db = 10*log10( ...
    overlap_burst_peak_psd_v2_per_hz(end)/ ...
    overlap_burst_peak_psd_v2_per_hz(1));

%% Broken case: zero-padding a short frame is not physical resolution
% Broken claim: 512 FFT points create 2 Hz resolution from only 64 samples.
% The recovered interpretation keeps display spacing separate from the
% 4*fs/M Hann response width and compares against an actually long window.
broken_hop_samples = broken_window_length*(1 - matched_overlap_fraction);
broken_frame_start = 1:broken_hop_samples: ...
    (record_sample_count - broken_window_length + 1);
broken_frame_count = numel(broken_frame_start);
broken_time_s = ((broken_frame_start - 1) + ...
    (broken_window_length - 1)/2)/fs_hz;
broken_frequency_hz = (0:(broken_fft_length/2))*fs_hz/broken_fft_length;
broken_window = 0.5 - 0.5*cos(2*pi* ...
    (0:(broken_window_length - 1))/(broken_window_length - 1));
broken_window_energy = sum(broken_window.^2);
broken_psd_v2_per_hz = zeros(numel(broken_frequency_hz), broken_frame_count);
for frame_index = 1:broken_frame_count
    frame_sample_index = broken_frame_start(frame_index) + ...
        (0:(broken_window_length - 1));
    windowed_frame_v = record_v(frame_sample_index).*broken_window;
    frame_fft_v = fft(windowed_frame_v, broken_fft_length);
    frame_two_sided_psd_v2_per_hz = ...
        abs(frame_fft_v).^2/(fs_hz*broken_window_energy);
    frame_one_sided_psd_v2_per_hz = ...
        frame_two_sided_psd_v2_per_hz(1:(broken_fft_length/2 + 1));
    frame_one_sided_psd_v2_per_hz(2:end-1) = ...
        2*frame_one_sided_psd_v2_per_hz(2:end-1);
    broken_psd_v2_per_hz(:, frame_index) = ...
        frame_one_sided_psd_v2_per_hz(:);
end
broken_display_bin_spacing_hz = fs_hz/broken_fft_length;
broken_true_main_lobe_width_hz = 4*fs_hz/broken_window_length;
recovered_window_length = window_length_sweep(1);
recovered_display_bin_spacing_hz = fs_hz/recovered_window_length;
recovered_true_main_lobe_width_hz = 4*fs_hz/recovered_window_length;
[~, broken_hop_frame] = min(abs(broken_time_s - hop_time_s));
[~, recovered_hop_frame] = min(abs(window_time_s{1} - hop_time_s));

