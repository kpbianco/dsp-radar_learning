%% P81: Form an ISAR Image from a Rotating Target
% How does target rotation create synthetic aperture when the radar is stationary?
% Base MATLAB R2016b+; no toolbox, file, network, worker, timer, or GPU use.

old_p81_figures = findall(0, 'Type', 'figure', 'Tag', 'P81');
if ~isempty(old_p81_figures)
    close(old_p81_figures);
end
clear old_p81_figures p81_results
p81_results = run_p81_experiment();

function p81_results = run_p81_experiment()
%% Visible deterministic controls and immutable resource ceilings
baseline_seed = 8101;
speed_of_light_mps = 3.0e8;
carrier_hz = 10.0e9;
bandwidth_hz = 600.0e6;
frequency_samples = 129;
look_count = 65;
baseline_aperture_deg = 6;
baseline_rotation_rate_deg_s = 6;
translation_velocity_mps = 2.0;
aperture_sweep_deg = [2 4 6 8];
rotation_rate_sweep_deg_s = [3 6 12];
display_floor_db = -35;
target_cross_range_m = [0 0 0 0 -2 -1 1 2 -0.75 0.75];
target_down_range_m = [-1.5 -0.5 0.5 1.5 0 0 0 0 -1.25 -1.25];
target_voltage = [1.00 0.75 0.85 0.90 0.80 0.65 0.65 0.80 0.55 0.55];
maximum_frequency_samples = 257;
maximum_look_count = 129;
maximum_target_count = 16;
maximum_sweep_cases = 6;
maximum_private_values = 64;
maximum_coherent_contributions = 900000;
maximum_working_value_equivalents = 2500000;
expected_figure_count = 5;

wavelength_m = speed_of_light_mps/carrier_hz;
frequency_offset_hz = linspace(-bandwidth_hz/2, bandwidth_hz/2, ...
    frequency_samples);
frequency_hz = carrier_hz+frequency_offset_hz;
target_phase_rad = 2*pi*private_uniform(baseline_seed, ...
    numel(target_voltage), maximum_private_values);
target_reflectivity = target_voltage.*exp(1j*target_phase_rad);
controls = struct('seed', baseline_seed, 'c_mps', speed_of_light_mps, ...
    'carrier_hz', carrier_hz, 'bandwidth_hz', bandwidth_hz, ...
    'frequency_hz', frequency_hz, 'frequency_samples', frequency_samples, ...
    'look_count', look_count, 'baseline_aperture_deg', ...
    baseline_aperture_deg, 'baseline_rate_deg_s', ...
    baseline_rotation_rate_deg_s, 'translation_velocity_mps', ...
    translation_velocity_mps, 'aperture_sweep_deg', aperture_sweep_deg, ...
    'rate_sweep_deg_s', rotation_rate_sweep_deg_s, ...
    'target_x_m', target_cross_range_m, 'target_y_m', ...
    target_down_range_m, 'target_reflectivity', target_reflectivity, ...
    'display_floor_db', display_floor_db, ...
    'max_frequency_samples', maximum_frequency_samples, ...
    'max_look_count', maximum_look_count, ...
    'max_target_count', maximum_target_count, ...
    'max_sweep_cases', maximum_sweep_cases, ...
    'max_private_values', maximum_private_values, ...
    'max_contributions', maximum_coherent_contributions, ...
    'max_working_values', maximum_working_value_equivalents, ...
    'expected_figures', expected_figure_count);
predicted_contributions = validate_controls(controls);
executed_contributions = 0;

%% Deterministic baseline: rotate, range-compress, align, and focus
aspect_angle_rad = linspace(-baseline_aperture_deg/2, ...
    baseline_aperture_deg/2, look_count)*pi/180;
rotation_rate_rad_s = baseline_rotation_rate_deg_s*pi/180;
slow_time_s = aspect_angle_rad/rotation_rate_rad_s;
translation_m = translation_velocity_mps*slow_time_s;
[raw_history, operation_count] = synthesize_history(frequency_hz, ...
    aspect_angle_rad, translation_m, target_cross_range_m, ...
    target_down_range_m, target_reflectivity, speed_of_light_mps, ...
    maximum_coherent_contributions);
executed_contributions = executed_contributions+operation_count;
retained_raw_history = raw_history;

[raw_profiles, baseline_range_axis_m] = range_compress(raw_history, frequency_offset_hz, ...
    speed_of_light_mps);
aligned_history = align_translation(raw_history, frequency_hz, ...
    translation_m, speed_of_light_mps);
aligned_profiles = range_compress(aligned_history, frequency_offset_hz, ...
    speed_of_light_mps);
[baseline_image, image_range_m, image_cross_range_m] = form_isar_image( ...
    aligned_profiles, baseline_range_axis_m, aspect_angle_rad, wavelength_m);
retained_aligned_history = aligned_history;
retained_baseline_image = baseline_image;

baseline_metrics = image_metrics(baseline_image, image_range_m, ...
    image_cross_range_m, target_down_range_m, target_cross_range_m, []);
theoretical_range_resolution_m = speed_of_light_mps/(2*bandwidth_hz);
theoretical_cross_range_resolution_m = wavelength_m/(2* ...
    (max(aspect_angle_rad)-min(aspect_angle_rad)));
cross_range_unambiguous_m = wavelength_m/(4*mean(diff(aspect_angle_rad)));
assert(baseline_metrics.truth_capture > 0.30 && ...
    baseline_metrics.truth_peak_ratio > 5.0, 'P81:BaselineRecognition', ...
    'The aligned baseline must concentrate energy around the target layout.');

fprintf('\nP81 baseline: %.1f GHz carrier, %.0f MHz stepped bandwidth\n', ...
    carrier_hz/1e9, bandwidth_hz/1e6);
fprintf('Aspect %.1f deg at %.1f deg/s -> CPI %.3f s; centroid drift %.3f m\n', ...
    baseline_aperture_deg, baseline_rotation_rate_deg_s, ...
    max(slow_time_s)-min(slow_time_s), max(translation_m)-min(translation_m));
fprintf('Nominal range/cross-range resolutions = %.3f m / %.3f m\n', ...
    theoretical_range_resolution_m, theoretical_cross_range_resolution_m);
fprintf('Aligned truth capture %.3f; truth/background peak ratio %.2f\n', ...
    baseline_metrics.truth_capture, baseline_metrics.truth_peak_ratio);

figure('Name', 'P81 range compression and translational alignment', ...
    'Tag', 'P81', 'Color', 'w');
subplot(1, 2, 1);
show_profiles(image_range_m, aspect_angle_rad*180/pi, raw_profiles, ...
    display_floor_db, 'Raw range profiles: centroid migration');
subplot(1, 2, 2);
show_profiles(image_range_m, aspect_angle_rad*180/pi, aligned_profiles, ...
    display_floor_db, 'After envelope and carrier-phase alignment');

figure('Name', 'P81 focused rotating-target image', ...
    'Tag', 'P81', 'Color', 'w');
show_image(image_cross_range_m, image_range_m, baseline_image, ...
    target_cross_range_m, target_down_range_m, display_floor_db, ...
    sprintf('Aligned ISAR image: truth capture %.2f', ...
    baseline_metrics.truth_capture));

%% Sweep 1: aperture angle controls cross-range resolution
aperture_case_count = numel(aperture_sweep_deg);
aperture_resolution_m = zeros(1, aperture_case_count);
aperture_truth_capture = zeros(1, aperture_case_count);
aperture_correlation = zeros(1, aperture_case_count);
aperture_images = cell(1, aperture_case_count);
for case_index = 1:aperture_case_count
    case_angle_rad = linspace(-aperture_sweep_deg(case_index)/2, ...
        aperture_sweep_deg(case_index)/2, look_count)*pi/180;
    case_time_s = case_angle_rad/rotation_rate_rad_s;
    case_translation_m = translation_velocity_mps*case_time_s;
    [case_raw, operation_count] = synthesize_history(frequency_hz, ...
        case_angle_rad, case_translation_m, target_cross_range_m, ...
        target_down_range_m, target_reflectivity, speed_of_light_mps, ...
        maximum_coherent_contributions-executed_contributions);
    executed_contributions = executed_contributions+operation_count;
    case_aligned = align_translation(case_raw, frequency_hz, ...
        case_translation_m, speed_of_light_mps);
    [case_profiles, case_range_axis_m] = range_compress(case_aligned, frequency_offset_hz, ...
        speed_of_light_mps);
    [case_image, case_range_m, case_cross_range_m] = form_isar_image( ...
        case_profiles, case_range_axis_m, case_angle_rad, wavelength_m);
    aperture_images{case_index} = struct('image', case_image, ...
        'range_m', case_range_m, 'cross_range_m', case_cross_range_m);
    case_metrics = image_metrics(case_image, case_range_m, ...
        case_cross_range_m, target_down_range_m, target_cross_range_m, []);
    aperture_resolution_m(case_index) = wavelength_m/(2* ...
        (max(case_angle_rad)-min(case_angle_rad)));
    aperture_truth_capture(case_index) = case_metrics.truth_capture;
    aperture_correlation(case_index) = truth_map_correlation(case_image, ...
        case_range_m, case_cross_range_m, target_down_range_m, ...
        target_cross_range_m);
end
assert(all(diff(aperture_resolution_m) < 0) && ...
    aperture_correlation(end) > aperture_correlation(1)+0.05, ...
    'P81:ApertureSweep', ...
    'Larger reviewed angle must improve nominal resolution and layout correlation.');

figure('Name', 'P81 angular-aperture sweep', 'Tag', 'P81', 'Color', 'w');
subplot(1, 2, 1);
plot(aperture_sweep_deg, aperture_resolution_m, 'o-', 'LineWidth', 1.5);
grid on;
xlabel('Total aspect aperture (deg)');
ylabel('Nominal cross-range resolution (m)');
title('Angular support sharpens cross-range');
subplot(1, 2, 2);
plot(aperture_sweep_deg, aperture_correlation, 's-', 'LineWidth', 1.5);
hold on;
plot(aperture_sweep_deg, aperture_truth_capture, 'd--', 'LineWidth', 1.2);
grid on;
xlabel('Total aspect aperture (deg)');
ylabel('Dimensionless image metric');
legend('Truth-map correlation', 'Truth-neighborhood power', ...
    'Location', 'best');
title('Same target, wider angular diversity');

%% Sweep 2: rate changes CPI and Doppler hertz, not the angle-domain image
rate_case_count = numel(rotation_rate_sweep_deg_s);
rate_cpi_s = zeros(1, rate_case_count);
rate_doppler_span_hz = zeros(1, rate_case_count);
rate_prf_hz = zeros(1, rate_case_count);
rate_image_correlation = zeros(1, rate_case_count);
rate_images = cell(1, rate_case_count);
for case_index = 1:rate_case_count
    case_rate_rad_s = rotation_rate_sweep_deg_s(case_index)*pi/180;
    case_time_s = aspect_angle_rad/case_rate_rad_s;
    case_translation_m = translation_velocity_mps*case_time_s;
    [case_raw, operation_count] = synthesize_history(frequency_hz, ...
        aspect_angle_rad, case_translation_m, target_cross_range_m, ...
        target_down_range_m, target_reflectivity, speed_of_light_mps, ...
        maximum_coherent_contributions-executed_contributions);
    executed_contributions = executed_contributions+operation_count;
    case_aligned = align_translation(case_raw, frequency_hz, ...
        case_translation_m, speed_of_light_mps);
    [case_profiles, case_range_axis_m] = range_compress(case_aligned, frequency_offset_hz, ...
        speed_of_light_mps);
    [case_image, case_range_m, case_cross_range_m] = form_isar_image( ...
        case_profiles, case_range_axis_m, aspect_angle_rad, wavelength_m);
    rate_images{case_index} = case_image;
    rate_cpi_s(case_index) = max(case_time_s)-min(case_time_s);
    rate_doppler_span_hz(case_index) = 2* ...
        max(abs(target_cross_range_m))*case_rate_rad_s/wavelength_m;
    rate_prf_hz(case_index) = 1/mean(diff(case_time_s));
    rate_image_correlation(case_index) = magnitude_correlation( ...
        baseline_image, case_image);
end
assert(all(diff(rate_cpi_s) < 0) && ...
    all(diff(rate_doppler_span_hz) > 0) && ...
    all(2*rate_doppler_span_hz < rate_prf_hz) && ...
    all(rate_image_correlation > 1-1.0e-10), 'P81:RateSweep', ...
    'Fixed aspect support must preserve focus with sampled rotational Doppler.');
fprintf('Rate sweep PRF (Hz) =');
fprintf(' %.1f', rate_prf_hz);
fprintf('; rotational Doppler max (Hz) =');
fprintf(' %.1f', rate_doppler_span_hz);
fprintf('\n');

figure('Name', 'P81 rotation-rate sweep', 'Tag', 'P81', 'Color', 'w');
subplot(1, 2, 1);
plot(rotation_rate_sweep_deg_s, rate_cpi_s, 'o-', 'LineWidth', 1.5);
grid on;
xlabel('Rotation rate (deg/s)');
ylabel('CPI for fixed 6 deg aperture (s)');
title('Faster rotation collects the angle sooner');
subplot(1, 2, 2);
yyaxis left;
plot(rotation_rate_sweep_deg_s, rate_doppler_span_hz, 's-', ...
    'LineWidth', 1.5);
hold on;
plot(rotation_rate_sweep_deg_s, rate_prf_hz/2, '^-', ...
    'LineWidth', 1.2);
ylabel('Rotational Doppler / Nyquist frequency (Hz)');
yyaxis right;
plot(rotation_rate_sweep_deg_s, rate_image_correlation, 'd--', ...
    'LineWidth', 1.2);
ylabel('Correlation with baseline magnitude');
ylim([0.95 1.005]);
grid on;
xlabel('Rotation rate (deg/s)');
legend('Maximum rotational Doppler', 'Slow-time Nyquist', ...
    'Image correlation', 'Location', 'best');
title('Hertz scale changes; angle-domain image does not');

%% Intentionally broken case: omit translational range/phase alignment
measurement_before_failure = retained_raw_history;
[broken_image, broken_range_m, broken_cross_range_m] = form_isar_image( ...
    raw_profiles, baseline_range_axis_m, aspect_angle_rad, wavelength_m);
broken_metrics = image_metrics(broken_image, broken_range_m, ...
    broken_cross_range_m, target_down_range_m, target_cross_range_m, ...
    retained_baseline_image);

% Recovery starts from the unchanged raw history, not the broken image.
recovered_history = align_translation(retained_raw_history, frequency_hz, ...
    translation_m, speed_of_light_mps);
[recovered_profiles, recovered_range_axis_m] = range_compress(recovered_history, frequency_offset_hz, ...
    speed_of_light_mps);
[recovered_image, recovered_range_m, recovered_cross_range_m] = ...
    form_isar_image(recovered_profiles, recovered_range_axis_m, ...
    aspect_angle_rad, wavelength_m);
recovered_metrics = image_metrics(recovered_image, recovered_range_m, ...
    recovered_cross_range_m, target_down_range_m, target_cross_range_m, ...
    retained_baseline_image);
recovery_exact_match = isequaln(recovered_history, ...
    retained_aligned_history) && isequaln(recovered_image, ...
    retained_baseline_image);
assert(isequaln(measurement_before_failure, retained_raw_history) && ...
    broken_metrics.reference_correlation < 0.65 && ...
    recovered_metrics.reference_correlation > 1-1.0e-12 && ...
    recovery_exact_match, 'P81:BrokenRecovery', ...
    'Unaligned translation must smear; fresh alignment must recover exactly.');

figure('Name', 'P81 uncompensated translation and recovery', ...
    'Tag', 'P81', 'Color', 'w');
subplot(1, 2, 1);
show_image(broken_cross_range_m, broken_range_m, broken_image, ...
    target_cross_range_m, target_down_range_m, display_floor_db, ...
    sprintf('Broken: no translation alignment, corr %.2f', ...
    broken_metrics.reference_correlation));
subplot(1, 2, 2);
show_image(recovered_cross_range_m, recovered_range_m, recovered_image, ...
    target_cross_range_m, target_down_range_m, display_floor_db, ...
    sprintf('Recovered from raw history, corr %.2f', ...
    recovered_metrics.reference_correlation));
fprintf('Broken/recovered image correlation = %.3f / %.3f\n', ...
    broken_metrics.reference_correlation, ...
    recovered_metrics.reference_correlation);

%% Bounded completion and public retained results
assert(executed_contributions == predicted_contributions && ...
    executed_contributions <= maximum_coherent_contributions, ...
    'P81:ContributionAccounting', ...
    'Coherent contribution accounting or ceiling mismatch.');
assert(numel(findall(0, 'Type', 'figure', 'Tag', 'P81')) == ...
    expected_figure_count, 'P81:FigureCount', ...
    'The experiment must create exactly five P81 figure groups.');
assert(isequaln(retained_raw_history, measurement_before_failure), ...
    'P81:MeasurementMutation', ...
    'Failure and recovery must not mutate the retained raw measurement.');
workspace_inventory = whos;
working_value_equivalents = sum([workspace_inventory.bytes])/8;
assert(working_value_equivalents <= maximum_working_value_equivalents, ...
    'P81:WorkingStorage', 'Retained workspace inventory ceiling exceeded.');

p81_results = struct('seed', baseline_seed, 'wavelength_m', wavelength_m, ...
    'frequency_hz', frequency_hz, 'aspect_angle_rad', aspect_angle_rad, ...
    'slow_time_s', slow_time_s, 'translation_m', translation_m, ...
    'target_cross_range_m', target_cross_range_m, ...
    'target_down_range_m', target_down_range_m, ...
    'target_reflectivity', target_reflectivity, ...
    'raw_history', retained_raw_history, ...
    'aligned_history', retained_aligned_history, ...
    'raw_profiles', raw_profiles, 'aligned_profiles', aligned_profiles, ...
    'baseline_image', retained_baseline_image, ...
    'image_range_m', image_range_m, ...
    'image_cross_range_m', image_cross_range_m, ...
    'baseline_metrics', baseline_metrics, ...
    'range_resolution_m', theoretical_range_resolution_m, ...
    'cross_range_resolution_m', theoretical_cross_range_resolution_m, ...
    'cross_range_unambiguous_m', cross_range_unambiguous_m, ...
    'aperture_sweep_deg', aperture_sweep_deg, ...
    'aperture_resolution_m', aperture_resolution_m, ...
    'aperture_truth_capture', aperture_truth_capture, ...
    'aperture_correlation', aperture_correlation, ...
    'aperture_images', {aperture_images}, ...
    'rate_sweep_deg_s', rotation_rate_sweep_deg_s, ...
    'rate_cpi_s', rate_cpi_s, ...
    'rate_doppler_span_hz', rate_doppler_span_hz, ...
    'rate_prf_hz', rate_prf_hz, ...
    'rate_image_correlation', rate_image_correlation, ...
    'rate_images', {rate_images}, ...
    'broken_image', broken_image, 'broken_metrics', broken_metrics, ...
    'recovered_image', recovered_image, ...
    'recovered_metrics', recovered_metrics, ...
    'recovery_exact_match', recovery_exact_match, ...
    'executed_contributions', executed_contributions, ...
    'predicted_contributions', predicted_contributions, ...
    'working_value_equivalents', working_value_equivalents);
end

function predicted = validate_controls(c)
row_vectors = {'frequency_hz', 'aperture_sweep_deg', 'rate_sweep_deg_s', ...
    'target_x_m', 'target_y_m', 'target_reflectivity'};
for index = 1:numel(row_vectors)
    value = c.(row_vectors{index});
    assert(isnumeric(value) && isrow(value) && ~isempty(value) && ...
        all(isfinite(real(value))) && all(isfinite(imag(value))), ...
        'P81:MalformedVector', 'Controls must contain finite numeric rows.');
end
real_scalars = {'seed', 'c_mps', 'carrier_hz', 'bandwidth_hz', ...
    'frequency_samples', 'look_count', 'baseline_aperture_deg', ...
    'baseline_rate_deg_s', 'translation_velocity_mps', 'display_floor_db', ...
    'max_frequency_samples', 'max_look_count', 'max_target_count', ...
    'max_sweep_cases', 'max_private_values', 'max_contributions', ...
    'max_working_values', 'expected_figures'};
for index = 1:numel(real_scalars)
    value = c.(real_scalars{index});
    assert(isnumeric(value) && isreal(value) && isscalar(value) && ...
        isfinite(value), 'P81:MalformedScalar', ...
        'Scalar controls must be finite and real.');
end
positive_scalars = {'c_mps', 'carrier_hz', 'bandwidth_hz', ...
    'frequency_samples', 'look_count', 'baseline_aperture_deg', ...
    'baseline_rate_deg_s', 'translation_velocity_mps', ...
    'max_frequency_samples', 'max_look_count', 'max_target_count', ...
    'max_sweep_cases', 'max_private_values', 'max_contributions', ...
    'max_working_values', 'expected_figures'};
for index = 1:numel(positive_scalars)
    assert(c.(positive_scalars{index}) > 0, 'P81:NonpositiveControl', ...
        'Physical controls and resource ceilings must be positive.');
end
integer_scalars = {'seed', 'frequency_samples', 'look_count', ...
    'max_frequency_samples', 'max_look_count', 'max_target_count', ...
    'max_sweep_cases', 'max_private_values', 'max_contributions', ...
    'max_working_values', 'expected_figures'};
for index = 1:numel(integer_scalars)
    assert(c.(integer_scalars{index}) == floor(c.(integer_scalars{index})), ...
        'P81:IntegerControl', 'Counts and seed must be integers.');
end
assert(c.seed > 0 && c.seed < 2147483647, 'P81:SeedRange', ...
    'Seed must be inside the Park-Miller state range.');
assert(c.frequency_samples >= 5 && mod(c.frequency_samples, 2) == 1 && ...
    c.look_count >= 5 && mod(c.look_count, 2) == 1, ...
    'P81:OddSampleCounts', 'Frequency and look counts must be odd and >= 5.');
assert(c.display_floor_db < 0 && ...
    all(diff(c.frequency_hz) > 0) && ...
    all(diff(c.aperture_sweep_deg) > 0) && ...
    all(diff(c.rate_sweep_deg_s) > 0), 'P81:Ordering', ...
    'Axes/sweeps must increase and display floor must be negative.');
assert(all(c.aperture_sweep_deg > 0) && all(c.rate_sweep_deg_s > 0), ...
    'P81:PositiveSweep', 'Aperture and rotation-rate sweeps must be positive.');
frequency_step_hz = mean(diff(c.frequency_hz));
assert(max(abs(diff(c.frequency_hz)-frequency_step_hz)) < ...
    1.0e-10*frequency_step_hz && ...
    abs(mean(c.frequency_hz)-c.carrier_hz) < 1.0e-10*c.carrier_hz && ...
    abs((max(c.frequency_hz)-min(c.frequency_hz))-c.bandwidth_hz) < ...
    1.0e-10*c.bandwidth_hz, 'P81:FrequencyGrid', ...
    'Frequency samples must be uniform and bind the carrier/span controls.');
target_count = numel(c.target_x_m);
assert(target_count == numel(c.target_y_m) && ...
    target_count == numel(c.target_reflectivity) && ...
    all(abs(c.target_reflectivity) > 0), 'P81:TargetShape', ...
    'Target coordinate and reflectivity rows must agree and be nonzero.');
assert(numel(c.frequency_hz) == c.frequency_samples && ...
    max(abs(c.target_x_m)) < c.c_mps/c.carrier_hz/(4* ...
    (max(c.aperture_sweep_deg)*pi/180/(c.look_count-1))) && ...
    max(abs(c.target_y_m)) < c.c_mps/(4*mean(diff(c.frequency_hz))), ...
    'P81:UnambiguousSupport', ...
    'Scene must stay inside reviewed range and cross-range support.');
maximum_time_s = max(max(c.aperture_sweep_deg)/(2*c.baseline_rate_deg_s), ...
    c.baseline_aperture_deg/(2*min(c.rate_sweep_deg_s)));
maximum_projected_range_m = c.translation_velocity_mps*maximum_time_s+ ...
    max(sqrt(c.target_x_m.^2+c.target_y_m.^2));
assert(maximum_projected_range_m < c.c_mps/(4*frequency_step_hz), ...
    'P81:CompleteRangeSupport', ...
    'Translation plus target projection must stay inside periodic range support.');
for rate_index = 1:numel(c.rate_sweep_deg_s)
    case_rate_rad_s = c.rate_sweep_deg_s(rate_index)*pi/180;
    case_prf_hz = (c.look_count-1)*c.rate_sweep_deg_s(rate_index)/ ...
        c.baseline_aperture_deg;
    maximum_rotational_doppler_hz = 2*max(abs(c.target_x_m))* ...
        case_rate_rad_s/(c.c_mps/c.carrier_hz);
    assert(2*maximum_rotational_doppler_hz < case_prf_hz, ...
        'P81:RotationalNyquist', ...
        'Reviewed rotational Doppler must remain inside slow-time Nyquist.');
end
assert(c.frequency_samples <= c.max_frequency_samples && ...
    c.look_count <= c.max_look_count && ...
    target_count <= c.max_target_count && ...
    max(numel(c.aperture_sweep_deg), numel(c.rate_sweep_deg_s)) <= ...
    c.max_sweep_cases && target_count <= c.max_private_values, ...
    'P81:ResourceCeiling', 'Sample, target, sweep, or generator bound exceeded.');
history_count = 1+numel(c.aperture_sweep_deg)+ ...
    numel(c.rate_sweep_deg_s);
predicted = history_count*c.look_count*c.frequency_samples*target_count;
assert(predicted <= c.max_contributions, 'P81:ContributionCeiling', ...
    'Predicted coherent contributions exceed the immutable ceiling.');
end

function [history, operations] = synthesize_history(frequency_hz, ...
    angle_rad, translation_m, target_x_m, target_y_m, reflectivity, c_mps, ...
    operation_ceiling)
look_count = numel(angle_rad);
frequency_count = numel(frequency_hz);
target_count = numel(reflectivity);
assert(isrow(frequency_hz) && isrow(angle_rad) && ...
    isrow(translation_m) && numel(translation_m) == look_count, ...
    'P81:HistoryAxes', 'History axes must be compatible rows.');
operations = look_count*frequency_count*target_count;
assert(operations <= operation_ceiling, 'P81:HistoryCallCeiling', ...
    'One history synthesis exceeds its remaining contribution budget.');
history = complex(zeros(look_count, frequency_count));
for look_index = 1:look_count
    projected_range_m = translation_m(look_index)+ ...
        target_x_m*sin(angle_rad(look_index))+ ...
        target_y_m*cos(angle_rad(look_index));
    for target_index = 1:target_count
        history(look_index, :) = history(look_index, :)+ ...
            reflectivity(target_index)*exp(-1j*4*pi*frequency_hz* ...
            projected_range_m(target_index)/c_mps);
    end
end
end

function aligned = align_translation(history, frequency_hz, ...
    translation_m, c_mps)
assert(size(history, 1) == numel(translation_m) && ...
    size(history, 2) == numel(frequency_hz), 'P81:AlignmentShape', ...
    'Translation, frequency, and history dimensions must agree.');
correction = exp(1j*4*pi*(translation_m(:)*frequency_hz)/c_mps);
aligned = history.*correction;
end

function [profiles, range_axis_m] = range_compress(history, ...
    frequency_offset_hz, c_mps)
assert(size(history, 2) == numel(frequency_offset_hz) && ...
    all(diff(frequency_offset_hz) > 0), 'P81:RangeCompressionInput', ...
    'Frequency samples must match increasing history columns.');
frequency_step_hz = mean(diff(frequency_offset_hz));
frequency_count = numel(frequency_offset_hz);
profiles = fftshift(ifft(ifftshift(history, 2), [], 2), 2);
range_axis_m = (-floor(frequency_count/2):floor(frequency_count/2))* ...
    c_mps/(2*frequency_count*frequency_step_hz);
end

function [image, range_axis_m, cross_range_axis_m] = form_isar_image( ...
    range_profiles, range_axis_m, angle_rad, wavelength_m)
look_count = numel(angle_rad);
assert(size(range_profiles, 1) == look_count && ...
    size(range_profiles, 2) == numel(range_axis_m) && look_count >= 5 && ...
    all(diff(angle_rad) > 0) && all(diff(range_axis_m) > 0), 'P81:FocusInput', ...
    'Angle samples must match increasing profile rows.');
angle_step_rad = mean(diff(angle_rad));
assert(max(abs(diff(angle_rad)-angle_step_rad)) < 1.0e-12, ...
    'P81:NonuniformAngle', ...
    'The transparent angle FFT requires uniform aspect samples.');
angle_spectrum = fftshift(fft(ifftshift(range_profiles, 1), [], 1), 1)/ ...
    look_count;
angle_frequency_cycles_per_rad = ...
    (-floor(look_count/2):floor(look_count/2))/(look_count*angle_step_rad);
raw_cross_range_m = -wavelength_m*angle_frequency_cycles_per_rad/2;
[cross_range_axis_m, order] = sort(raw_cross_range_m);
image = angle_spectrum(order, :).';
end

function metrics = image_metrics(image, range_axis_m, cross_range_axis_m, ...
    truth_range_m, truth_cross_range_m, reference_image)
assert(size(image, 1) == numel(range_axis_m) && ...
    size(image, 2) == numel(cross_range_axis_m), 'P81:MetricShape', ...
    'Image dimensions and axes must agree.');
power_image = abs(image).^2;
truth_mask = false(size(power_image));
for target_index = 1:numel(truth_range_m)
    [~, range_index] = min(abs(range_axis_m-truth_range_m(target_index)));
    [~, cross_index] = min(abs(cross_range_axis_m- ...
        truth_cross_range_m(target_index)));
    range_indices = max(1, range_index-1):min(size(image, 1), range_index+1);
    cross_indices = max(1, cross_index-1):min(size(image, 2), cross_index+1);
    truth_mask(range_indices, cross_indices) = true;
end
truth_power = sum(power_image(truth_mask));
total_power = sum(power_image(:));
background = power_image(~truth_mask);
metrics = struct('truth_capture', truth_power/max(total_power, eps), ...
    'truth_peak_ratio', max(power_image(truth_mask))/max(median(background), eps), ...
    'reference_correlation', NaN);
if ~isempty(reference_image)
    metrics.reference_correlation = magnitude_correlation(image, reference_image);
end
end

function value = truth_map_correlation(image, range_axis_m, ...
    cross_range_axis_m, truth_range_m, truth_cross_range_m)
truth_map = zeros(size(image));
for target_index = 1:numel(truth_range_m)
    [~, range_index] = min(abs(range_axis_m-truth_range_m(target_index)));
    [~, cross_index] = min(abs(cross_range_axis_m- ...
        truth_cross_range_m(target_index)));
    truth_map(range_index, cross_index) = truth_map(range_index, cross_index)+1;
end
kernel = [1 2 1; 2 4 2; 1 2 1];
truth_map = conv2(truth_map, kernel/sum(kernel(:)), 'same');
value = vector_correlation(abs(image(:)), truth_map(:));
end

function value = magnitude_correlation(first, second)
assert(isequal(size(first), size(second)), 'P81:CorrelationShape', ...
    'Compared images must have equal size.');
value = vector_correlation(abs(first(:)), abs(second(:)));
end

function value = vector_correlation(first, second)
first = first-mean(first);
second = second-mean(second);
denominator = sqrt(sum(first.^2)*sum(second.^2));
assert(denominator > eps, 'P81:CorrelationNull', ...
    'Correlation inputs must contain nonconstant energy.');
value = real(sum(first.*second)/denominator);
end

