function values_db = normalized_db(values, floor_db)
peak = max(values(:));
assert(isfinite(peak) && peak > 0, 'P81:DecibelInput', ...
    'Displayed magnitude must have finite nonzero peak.');
values_db = 20*log10(max(values/peak, 10^(floor_db/20)));
end

function values = private_uniform(seed, count, maximum_count)
assert(isnumeric(seed) && isreal(seed) && isscalar(seed) && ...
    isfinite(seed) && seed == floor(seed) && seed > 0 && ...
    seed < 2147483647, 'P81:PrivateSeed', ...
    'Private generator seed must be an integer in (0, 2147483647).');
assert(isnumeric(count) && isreal(count) && isscalar(count) && ...
    isfinite(count) && count == floor(count) && count >= 1 && ...
    count <= maximum_count, 'P81:PrivateCount', ...
    'Private generator count must be a positive bounded integer.');
state = seed;
values = zeros(1, count);
for index = 1:count
    state = mod(16807*state, 2147483647);
    values(index) = state/2147483647;
end
end
