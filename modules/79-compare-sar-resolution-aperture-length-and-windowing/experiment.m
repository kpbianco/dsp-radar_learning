%% P79: Compare SAR Resolution, Aperture Length, and Windowing
% Guiding question:
% What controls range and cross-range resolution and sidelobes?
%
% Base MATLAB only. Range focus is an explicit coherent sum over waveform
% frequency. Cross-range focus is an explicit coherent sum of exact two-way
% slant-range phase over platform positions. No SAR or window toolbox call is
% used.

close(findall(0, 'Type', 'figure', 'Tag', 'P79'));
clear p79_results;
p79_results = run_p79_experiment();

function p79_results = run_p79_experiment()

%% Visible deterministic controls and immutable resource ceilings
baseline_seed = 7901;
speed_of_light_mps = 3.0e8;
carrier_frequency_hz = 10.0e9;
scene_center_ground_range_m = 1000.0;
baseline_bandwidth_hz = 200.0e6;
frequency_sample_count = 257;
baseline_aperture_length_m = 30.0;
dense_platform_spacing_m = 0.25;
bandwidth_sweep_hz = [100.0e6 200.0e6 400.0e6];
aperture_length_sweep_m = [10.0 20.0 30.0];
platform_spacing_sweep_m = [0.25 1.0 5.0];
range_offset_axis_m = -6.0:0.005:6.0;
cross_range_offset_axis_m = -8.0:0.005:8.0;
image_cross_range_m = -5.0:0.05:5.0;
image_ground_range_offset_m = -2.0:0.05:2.0;
target_cross_range_m = [0.0 0.80 0.0];
target_ground_range_offset_m = [0.0 0.0 1.20];
target_voltage = [1.0 0.65 0.55];
display_floor_db = -50.0;

maximum_frequency_samples = 513;
maximum_aperture_samples = 201;
maximum_response_samples = 4001;
maximum_image_pixels = 20000;
maximum_targets = 4;
maximum_sweep_cases = 4;
maximum_private_values = 32;
maximum_response_operations = 6000000;
maximum_working_value_equivalents = 2000000;
maximum_figures = 5;
maximum_dense_phase_step_rad = 0.90*pi;

controls = struct( ...
    'seed', baseline_seed, 'c_mps', speed_of_light_mps, ...
    'carrier_hz', carrier_frequency_hz, ...
    'scene_range_m', scene_center_ground_range_m, ...
    'bandwidth_hz', baseline_bandwidth_hz, ...
    'frequency_samples', frequency_sample_count, ...
    'aperture_length_m', baseline_aperture_length_m, ...
    'dense_spacing_m', dense_platform_spacing_m, ...
    'bandwidth_sweep_hz', bandwidth_sweep_hz, ...
    'aperture_sweep_m', aperture_length_sweep_m, ...
    'spacing_sweep_m', platform_spacing_sweep_m, ...
    'range_axis_m', range_offset_axis_m, ...
    'cross_range_axis_m', cross_range_offset_axis_m, ...
    'image_x_m', image_cross_range_m, ...
    'image_range_offset_m', image_ground_range_offset_m, ...
    'target_x_m', target_cross_range_m, ...
    'target_range_offset_m', target_ground_range_offset_m, ...
    'target_voltage', target_voltage, ...
    'display_floor_db', display_floor_db, ...
    'max_frequency_samples', maximum_frequency_samples, ...
    'max_aperture_samples', maximum_aperture_samples, ...
    'max_response_samples', maximum_response_samples, ...
    'max_image_pixels', maximum_image_pixels, ...
    'max_targets', maximum_targets, ...
    'max_sweep_cases', maximum_sweep_cases, ...
    'max_private_values', maximum_private_values, ...
    'max_response_operations', maximum_response_operations, ...
    'max_working_values', maximum_working_value_equivalents, ...
    'max_figures', maximum_figures, ...
    'max_dense_phase_step_rad', maximum_dense_phase_step_rad);
predicted_response_operations = validate_controls(controls);

wavelength_m = speed_of_light_mps/carrier_frequency_hz;
nominal_range_resolution_m = speed_of_light_mps/(2*baseline_bandwidth_hz);
nominal_cross_range_resolution_m = wavelength_m* ...
    scene_center_ground_range_m/(2*baseline_aperture_length_m);

dense_platform_position_m = -baseline_aperture_length_m/2: ...
    dense_platform_spacing_m:baseline_aperture_length_m/2;
uniform_aperture_weights = ones(size(dense_platform_position_m));
sample_index = 0:numel(dense_platform_position_m)-1;
hamming_aperture_weights = 0.54-0.46*cos(2*pi*sample_index/ ...
    (numel(dense_platform_position_m)-1));

% A private generator seeds only the complex point reflectivities. It does
% not change the caller's global random stream.
target_phase_uniform = private_uniform(baseline_seed, ...
    numel(target_voltage), maximum_private_values);
target_complex_reflectivity = target_voltage.*exp( ...
    1j*2*pi*target_phase_uniform);
retained_target_scene = target_complex_reflectivity;

executed_response_operations = 0;

%% Baseline isolated point-spread functions
[baseline_range_complex, operation_count] = coherent_range_response( ...
    range_offset_axis_m, baseline_bandwidth_hz, frequency_sample_count, ...
    speed_of_light_mps, maximum_response_operations);
executed_response_operations = executed_response_operations+operation_count;
[baseline_cross_range_complex, operation_count] = ...
    coherent_aperture_response(cross_range_offset_axis_m, 0.0, ...
    scene_center_ground_range_m, dense_platform_position_m, ...
    uniform_aperture_weights, carrier_frequency_hz, ...
    speed_of_light_mps, maximum_response_operations);
executed_response_operations = executed_response_operations+operation_count;

baseline_range_magnitude = abs(baseline_range_complex);
baseline_cross_range_magnitude = abs(baseline_cross_range_complex);
baseline_range_metrics = response_metrics(range_offset_axis_m, ...
    baseline_range_magnitude);
baseline_cross_range_metrics = response_metrics( ...
    cross_range_offset_axis_m, baseline_cross_range_magnitude);

assert(abs(abs(baseline_range_metrics.left_null_m)- ...
    nominal_range_resolution_m) < 0.02, ...
    'P79:RangeResolutionAgreement', ...
    'Range first null must agree with c/(2B).');
assert(abs(abs(baseline_cross_range_metrics.left_null_m)- ...
    nominal_cross_range_resolution_m) < 0.03, ...
    'P79:CrossRangeResolutionAgreement', ...
    'Cross-range first null must agree with lambda*R/(2L).');

[baseline_image_complex, operation_count] = form_separable_image( ...
    image_cross_range_m, image_ground_range_offset_m, ...
    target_cross_range_m, target_ground_range_offset_m, ...
    target_complex_reflectivity, baseline_bandwidth_hz, ...
    frequency_sample_count, dense_platform_position_m, ...
    uniform_aperture_weights, scene_center_ground_range_m, ...
    carrier_frequency_hz, speed_of_light_mps, ...
    maximum_response_operations);
executed_response_operations = executed_response_operations+operation_count;
baseline_image_db = normalized_db(baseline_image_complex, display_floor_db);

fprintf('\nP79 baseline: %.1f GHz carrier, %.0f MHz bandwidth\n', ...
    carrier_frequency_hz/1.0e9, baseline_bandwidth_hz/1.0e6);
fprintf('Wavelength %.1f mm; aperture %.1f m; dense spacing %.2f m\n', ...
    wavelength_m*1.0e3, baseline_aperture_length_m, ...
    dense_platform_spacing_m);
fprintf('Nominal first-null scales: range %.3f m, cross-range %.3f m\n', ...
    nominal_range_resolution_m, nominal_cross_range_resolution_m);
fprintf('Measured HPBW: range %.3f m, cross-range %.3f m\n', ...
    baseline_range_metrics.half_power_width_m, ...
    baseline_cross_range_metrics.half_power_width_m);
fprintf('Measured PSL: range %.2f dB, cross-range %.2f dB\n', ...
    baseline_range_metrics.peak_sidelobe_db, ...
    baseline_cross_range_metrics.peak_sidelobe_db);

figure('Name', 'P79 baseline SAR point-spread function', ...
    'Tag', 'P79', 'NumberTitle', 'off');
subplot(2, 2, 1);
plot(range_offset_axis_m, normalized_db(baseline_range_magnitude, ...
    display_floor_db), 'b-', 'LineWidth', 1.1);
grid on;
xlabel('Range offset (m)');
ylabel('Normalized magnitude (dB)');
title(sprintf('Range cut: HPBW %.3f m, PSL %.1f dB', ...
    baseline_range_metrics.half_power_width_m, ...
    baseline_range_metrics.peak_sidelobe_db));
ylim([display_floor_db 1]);
subplot(2, 2, 2);
plot(cross_range_offset_axis_m, normalized_db( ...
    baseline_cross_range_magnitude, display_floor_db), ...
    'r-', 'LineWidth', 1.1);
grid on;
xlabel('Cross-range offset (m)');
ylabel('Normalized magnitude (dB)');
title(sprintf('Cross-range cut: HPBW %.3f m, PSL %.1f dB', ...
    baseline_cross_range_metrics.half_power_width_m, ...
    baseline_cross_range_metrics.peak_sidelobe_db));
ylim([display_floor_db 1]);
subplot(2, 2, [3 4]);
imagesc(image_cross_range_m, image_ground_range_offset_m, baseline_image_db);
axis xy;
hold on;
plot(target_cross_range_m, target_ground_range_offset_m, ...
    'wx', 'MarkerSize', 9, 'LineWidth', 1.5);
xlabel('Cross-range x (m)');
ylabel('Ground-range offset from 1000 m (m)');
title('Three ideal points convolved with the separable focused response');
colorbar;
caxis([display_floor_db 0]);

%% Sweep 1: bandwidth changes only the range point-spread width
bandwidth_range_response = zeros(numel(bandwidth_sweep_hz), ...
    numel(range_offset_axis_m));
bandwidth_half_power_width_m = zeros(size(bandwidth_sweep_hz));
bandwidth_first_null_m = zeros(size(bandwidth_sweep_hz));
bandwidth_peak_sidelobe_db = zeros(size(bandwidth_sweep_hz));
for case_index = 1:numel(bandwidth_sweep_hz)
    [case_response, operation_count] = coherent_range_response( ...
        range_offset_axis_m, bandwidth_sweep_hz(case_index), ...
        frequency_sample_count, speed_of_light_mps, ...
        maximum_response_operations);
    executed_response_operations = executed_response_operations+operation_count;
    bandwidth_range_response(case_index, :) = abs(case_response);
    case_metrics = response_metrics(range_offset_axis_m, abs(case_response));
    bandwidth_half_power_width_m(case_index) = ...
        case_metrics.half_power_width_m;
    bandwidth_first_null_m(case_index) = abs(case_metrics.right_null_m);
    bandwidth_peak_sidelobe_db(case_index) = ...
        case_metrics.peak_sidelobe_db;
end
assert(all(diff(bandwidth_half_power_width_m) < 0) && ...
    max(abs(bandwidth_first_null_m-speed_of_light_mps./ ...
    (2*bandwidth_sweep_hz))) < 0.02, 'P79:BandwidthSweep', ...
    'Increasing only bandwidth must narrow the range response.');

figure('Name', 'P79 bandwidth controls range resolution', ...
    'Tag', 'P79', 'NumberTitle', 'off');
subplot(1, 2, 1);
hold on;
for case_index = 1:numel(bandwidth_sweep_hz)
    plot(range_offset_axis_m, normalized_db( ...
        bandwidth_range_response(case_index, :), display_floor_db), ...
        'LineWidth', 1.1);
end
grid on;
xlabel('Range offset (m)');
ylabel('Normalized magnitude (dB)');
title('Only transmitted bandwidth changes');
legend('100 MHz', '200 MHz', '400 MHz', 'Location', 'best');
ylim([display_floor_db 1]);
subplot(1, 2, 2);
plot(bandwidth_sweep_hz/1.0e6, bandwidth_half_power_width_m, ...
    'bo-', 'LineWidth', 1.2);
hold on;
plot(bandwidth_sweep_hz/1.0e6, bandwidth_first_null_m, ...
    'rs-', 'LineWidth', 1.2);
grid on;
xlabel('Transmitted bandwidth (MHz)');
ylabel('Measured width or one-sided first null (m)');
title('Range width falls approximately as 1/B');
legend('Half-power width', 'First-null resolution', 'Location', 'best');

%% Sweep 2: aperture length changes only the cross-range width
aperture_cross_range_response = zeros(numel(aperture_length_sweep_m), ...
    numel(cross_range_offset_axis_m));
aperture_half_power_width_m = zeros(size(aperture_length_sweep_m));
aperture_first_null_m = zeros(size(aperture_length_sweep_m));
aperture_peak_sidelobe_db = zeros(size(aperture_length_sweep_m));
for case_index = 1:numel(aperture_length_sweep_m)
    case_positions_m = -aperture_length_sweep_m(case_index)/2: ...
        dense_platform_spacing_m:aperture_length_sweep_m(case_index)/2;
    case_weights = ones(size(case_positions_m));
    [case_response, operation_count] = coherent_aperture_response( ...
        cross_range_offset_axis_m, 0.0, scene_center_ground_range_m, ...
        case_positions_m, case_weights, carrier_frequency_hz, ...
        speed_of_light_mps, maximum_response_operations);
    executed_response_operations = executed_response_operations+operation_count;
    aperture_cross_range_response(case_index, :) = abs(case_response);
    case_metrics = response_metrics(cross_range_offset_axis_m, ...
        abs(case_response));
    aperture_half_power_width_m(case_index) = ...
        case_metrics.half_power_width_m;
    aperture_first_null_m(case_index) = abs(case_metrics.right_null_m);
    aperture_peak_sidelobe_db(case_index) = ...
        case_metrics.peak_sidelobe_db;
end
assert(all(diff(aperture_half_power_width_m) < 0) && ...
    max(abs(aperture_first_null_m-wavelength_m* ...
    scene_center_ground_range_m./(2*aperture_length_sweep_m))) < 0.06, ...
    'P79:ApertureSweep', ...
    'Increasing only aperture length must narrow cross-range response.');

figure('Name', 'P79 aperture controls cross-range resolution', ...
    'Tag', 'P79', 'NumberTitle', 'off');
subplot(1, 2, 1);
hold on;
for case_index = 1:numel(aperture_length_sweep_m)
    plot(cross_range_offset_axis_m, normalized_db( ...
        aperture_cross_range_response(case_index, :), display_floor_db), ...
        'LineWidth', 1.1);
end
grid on;
xlabel('Cross-range offset (m)');
ylabel('Normalized magnitude (dB)');
title('Only synthetic-aperture length changes');
legend('10 m', '20 m', '30 m', 'Location', 'best');
ylim([display_floor_db 1]);
subplot(1, 2, 2);
plot(aperture_length_sweep_m, aperture_half_power_width_m, ...
    'bo-', 'LineWidth', 1.2);
hold on;
plot(aperture_length_sweep_m, aperture_first_null_m, ...
    'rs-', 'LineWidth', 1.2);
grid on;
xlabel('Synthetic-aperture length L (m)');
ylabel('Measured width or one-sided first null (m)');
title('Cross-range width falls approximately as 1/L');
legend('Half-power width', 'First-null resolution', 'Location', 'best');

%% Aperture window comparison: sidelobes fall while the mainlobe widens
[hamming_cross_range_complex, operation_count] = ...
    coherent_aperture_response(cross_range_offset_axis_m, 0.0, ...
    scene_center_ground_range_m, dense_platform_position_m, ...
    hamming_aperture_weights, carrier_frequency_hz, ...
    speed_of_light_mps, maximum_response_operations);
executed_response_operations = executed_response_operations+operation_count;
hamming_cross_range_metrics = response_metrics(cross_range_offset_axis_m, ...
    abs(hamming_cross_range_complex));
taper_coherent_gain_db = 20*log10(sum(hamming_aperture_weights)/ ...
    numel(hamming_aperture_weights));
taper_snr_efficiency_db = 10*log10(sum(hamming_aperture_weights)^2/( ...
    numel(hamming_aperture_weights)*sum(hamming_aperture_weights.^2)));
assert(hamming_cross_range_metrics.peak_sidelobe_db < ...
    baseline_cross_range_metrics.peak_sidelobe_db-20 && ...
    hamming_cross_range_metrics.half_power_width_m > ...
    1.3*baseline_cross_range_metrics.half_power_width_m && ...
    taper_snr_efficiency_db < -1.0 && taper_snr_efficiency_db > -2.0, ...
    'P79:TaperTradeoff', ...
    'Hamming aperture weights must lower PSL and widen the mainlobe.');

fprintf('\nUniform/Hamming cross-range HPBW = %.3f / %.3f m\n', ...
    baseline_cross_range_metrics.half_power_width_m, ...
    hamming_cross_range_metrics.half_power_width_m);
fprintf('Uniform/Hamming cross-range PSL = %.2f / %.2f dB\n', ...
    baseline_cross_range_metrics.peak_sidelobe_db, ...
    hamming_cross_range_metrics.peak_sidelobe_db);
fprintf('Hamming coherent peak gain before normalization = %.2f dB\n', ...
    taper_coherent_gain_db);
fprintf('Hamming white-noise SNR efficiency = %.2f dB\n', ...
    taper_snr_efficiency_db);

figure('Name', 'P79 aperture window tradeoff', ...
    'Tag', 'P79', 'NumberTitle', 'off');
subplot(1, 2, 1);
plot(dense_platform_position_m, uniform_aperture_weights, ...
    'b-', 'LineWidth', 1.1);
hold on;
plot(dense_platform_position_m, hamming_aperture_weights, ...
    'r-', 'LineWidth', 1.1);
grid on;
xlabel('Platform cross-range position (m)');
ylabel('Aperture weight (linear)');
title('Hamming taper reduces edge contributions');
legend('Uniform', 'Hamming', 'Location', 'best');
subplot(1, 2, 2);
plot(cross_range_offset_axis_m, normalized_db( ...
    baseline_cross_range_magnitude, display_floor_db), ...
    'b-', 'LineWidth', 1.1);
hold on;
plot(cross_range_offset_axis_m, normalized_db( ...
    abs(hamming_cross_range_complex), display_floor_db), ...
    'r-', 'LineWidth', 1.1);
grid on;
xlabel('Cross-range offset (m)');
ylabel('Normalized magnitude (dB)');
title('Lower sidelobes cost mainlobe width');
legend('Uniform', 'Hamming', 'Location', 'best');
ylim([display_floor_db 1]);

%% Intentionally broken case: sparse platform spacing aliases cross-range
spacing_cross_range_response = zeros(numel(platform_spacing_sweep_m), ...
    numel(cross_range_offset_axis_m));
spacing_aperture_sample_count = zeros(size(platform_spacing_sweep_m));
spacing_far_peak_linear = zeros(size(platform_spacing_sweep_m));
far_region = abs(cross_range_offset_axis_m) > 1.5;
for case_index = 1:numel(platform_spacing_sweep_m)
    case_positions_m = -baseline_aperture_length_m/2: ...
        platform_spacing_sweep_m(case_index):baseline_aperture_length_m/2;
    case_weights = ones(size(case_positions_m));
    [case_response, operation_count] = coherent_aperture_response( ...
        cross_range_offset_axis_m, 0.0, scene_center_ground_range_m, ...
        case_positions_m, case_weights, carrier_frequency_hz, ...
        speed_of_light_mps, maximum_response_operations);
    executed_response_operations = executed_response_operations+operation_count;
    spacing_cross_range_response(case_index, :) = abs(case_response);
    spacing_aperture_sample_count(case_index) = numel(case_positions_m);
    far_values = abs(case_response(far_region));
    spacing_far_peak_linear(case_index) = max(far_values);
end
broken_spacing_m = platform_spacing_sweep_m(end);
broken_platform_position_m = -baseline_aperture_length_m/2: ...
    broken_spacing_m:baseline_aperture_length_m/2;
predicted_alias_spacing_m = wavelength_m*scene_center_ground_range_m/ ...
    (2*broken_spacing_m);
assert(spacing_far_peak_linear(end) > 0.95 && ...
    spacing_far_peak_linear(1) < 0.15 && ...
    abs(predicted_alias_spacing_m-3.0) < 1.0e-12, ...
    'P79:SparseApertureAliases', ...
    'The sparse aperture must create a near-unity false cross-range copy.');

[broken_image_complex, operation_count] = form_separable_image( ...
    image_cross_range_m, image_ground_range_offset_m, ...
    target_cross_range_m, target_ground_range_offset_m, ...
    retained_target_scene, baseline_bandwidth_hz, frequency_sample_count, ...
    broken_platform_position_m, ones(size(broken_platform_position_m)), ...
    scene_center_ground_range_m, carrier_frequency_hz, ...
    speed_of_light_mps, maximum_response_operations);
executed_response_operations = executed_response_operations+operation_count;

% Recovery is a fresh focus from the byte-for-byte unchanged scene. It does
% not filter or invert the already aliased image.
measurement_before_failure = retained_target_scene;
[recovered_cross_range_complex, operation_count] = ...
    coherent_aperture_response(cross_range_offset_axis_m, 0.0, ...
    scene_center_ground_range_m, dense_platform_position_m, ...
    uniform_aperture_weights, carrier_frequency_hz, ...
    speed_of_light_mps, maximum_response_operations);
executed_response_operations = executed_response_operations+operation_count;
[recovered_image_complex, operation_count] = form_separable_image( ...
    image_cross_range_m, image_ground_range_offset_m, ...
    target_cross_range_m, target_ground_range_offset_m, ...
    retained_target_scene, baseline_bandwidth_hz, frequency_sample_count, ...
    dense_platform_position_m, uniform_aperture_weights, ...
    scene_center_ground_range_m, carrier_frequency_hz, ...
    speed_of_light_mps, maximum_response_operations);
executed_response_operations = executed_response_operations+operation_count;
recovery_exact_match = isequaln(recovered_cross_range_complex, ...
    baseline_cross_range_complex) && isequaln(recovered_image_complex, ...
    baseline_image_complex);
assert(isequaln(measurement_before_failure, retained_target_scene) && ...
    recovery_exact_match, 'P79:SameSceneRecovery', ...
    'Dense recovery must start from the unchanged scene and match baseline.');

fprintf('\nPlatform spacing sweep (m): %s\n', ...
    mat2str(platform_spacing_sweep_m, 4));
fprintf('Aperture look counts: %s\n', ...
    mat2str(spacing_aperture_sample_count));
fprintf('Largest |x|>1.5 m response: %s\n', ...
    mat2str(spacing_far_peak_linear, 5));
fprintf('Broken paraxial alias spacing = %.3f m; fresh recovery exact = %d\n', ...
    predicted_alias_spacing_m, recovery_exact_match);

figure('Name', 'P79 sparse-aperture failure and recovery', ...
    'Tag', 'P79', 'NumberTitle', 'off');
subplot(2, 2, 1);
hold on;
for case_index = 1:numel(platform_spacing_sweep_m)
    plot(cross_range_offset_axis_m, normalized_db( ...
        spacing_cross_range_response(case_index, :), display_floor_db), ...
        'LineWidth', 1.1);
end
grid on;
xlabel('Cross-range offset (m)');
ylabel('Normalized magnitude (dB)');
title('Only platform-sample spacing changes');
legend('0.25 m', '1 m', '5 m (broken)', 'Location', 'best');
ylim([display_floor_db 1]);
subplot(2, 2, 2);
stem(broken_platform_position_m, ones(size(broken_platform_position_m)), ...
    'filled');
grid on;
xlabel('Platform cross-range position (m)');
ylabel('Retained look');
title(sprintf('Broken: only %d looks, alias period about %.1f m', ...
    numel(broken_platform_position_m), predicted_alias_spacing_m));
subplot(2, 2, 3);
imagesc(image_cross_range_m, image_ground_range_offset_m, ...
    normalized_db(broken_image_complex, display_floor_db));
axis xy;
hold on;
plot(target_cross_range_m, target_ground_range_offset_m, ...
    'wx', 'MarkerSize', 8, 'LineWidth', 1.4);
xlabel('Cross-range x (m)');
ylabel('Ground-range offset (m)');
title('Broken sparse image: repeated false targets');
colorbar;
caxis([display_floor_db 0]);
subplot(2, 2, 4);
imagesc(image_cross_range_m, image_ground_range_offset_m, ...
    normalized_db(recovered_image_complex, display_floor_db));
axis xy;
hold on;
plot(target_cross_range_m, target_ground_range_offset_m, ...
    'wx', 'MarkerSize', 8, 'LineWidth', 1.4);
xlabel('Cross-range x (m)');
ylabel('Ground-range offset (m)');
title('Recovered: dense sampling of the unchanged scene');
colorbar;
caxis([display_floor_db 0]);

%% Operation, storage, and public-result contract
assert(executed_response_operations == predicted_response_operations && ...
    executed_response_operations <= maximum_response_operations, ...
    'P79:OperationAccounting', ...
    'Executed coherent contributions must match the bounded prediction.');
pre_results_workspace_inventory = whos;
