%% Local helpers: explicit coherent sums, metrics, generator, and validation
function [response, operation_count] = coherent_range_response( ...
    range_offset_m, bandwidth_hz, frequency_sample_count, c_mps, ...
    maximum_operations)
assert(isnumeric(range_offset_m) && isreal(range_offset_m) && ...
    isrow(range_offset_m) && ~isempty(range_offset_m) && ...
    all(isfinite(range_offset_m)) && all(diff(range_offset_m) > 0), ...
    'P79:BadRangeAxis', 'Range offsets must be a finite increasing row.');
assert(isnumeric(bandwidth_hz) && isreal(bandwidth_hz) && ...
    isscalar(bandwidth_hz) && isfinite(bandwidth_hz) && ...
    bandwidth_hz > 0 && isnumeric(frequency_sample_count) && ...
    isreal(frequency_sample_count) && isscalar(frequency_sample_count) && ...
    isfinite(frequency_sample_count) && ...
    frequency_sample_count == floor(frequency_sample_count) && ...
    frequency_sample_count >= 3 && mod(frequency_sample_count, 2) == 1 && ...
    isnumeric(c_mps) && isreal(c_mps) && isscalar(c_mps) && ...
    isfinite(c_mps) && c_mps > 0, 'P79:BadRangeModel', ...
    'Range focus needs positive finite physics and an odd sample count.');
operation_count = numel(range_offset_m)*frequency_sample_count;
assert(operation_count <= maximum_operations, 'P79:RangeOperationCeiling', ...
    'Requested range-response work exceeds its ceiling.');
frequency_offset_hz = linspace(-bandwidth_hz/2, bandwidth_hz/2, ...
    frequency_sample_count).';
response = complex(zeros(size(range_offset_m)));
for range_index = 1:numel(range_offset_m)
    % A monostatic range offset DeltaR changes round-trip phase by
    % 4*pi*f*DeltaR/c. Adding all baseband frequency samples forms the
    % range-compressed point response.
    frequency_contributions = exp(1j*4*pi*frequency_offset_hz* ...
        range_offset_m(range_index)/c_mps);
    response(range_index) = sum(frequency_contributions)/ ...
        frequency_sample_count;
end
end

function [response, operation_count] = coherent_aperture_response( ...
    candidate_cross_range_m, target_cross_range_m, target_ground_range_m, ...
    platform_position_m, aperture_weights, carrier_hz, c_mps, ...
    maximum_operations)
assert(isnumeric(candidate_cross_range_m) && ...
    isreal(candidate_cross_range_m) && isrow(candidate_cross_range_m) && ...
    ~isempty(candidate_cross_range_m) && ...
    all(isfinite(candidate_cross_range_m)) && ...
    all(diff(candidate_cross_range_m) > 0), 'P79:BadCrossRangeAxis', ...
    'Candidate cross-range positions must be a finite increasing row.');
assert(isnumeric(platform_position_m) && isreal(platform_position_m) && ...
    isrow(platform_position_m) && numel(platform_position_m) >= 3 && ...
    all(isfinite(platform_position_m)) && ...
    all(diff(platform_position_m) > 0) && ...
    isnumeric(aperture_weights) && isreal(aperture_weights) && ...
    isrow(aperture_weights) && ...
    numel(aperture_weights) == numel(platform_position_m) && ...
    all(isfinite(aperture_weights)) && all(aperture_weights >= 0) && ...
    sum(aperture_weights) > 0, 'P79:BadAperture', ...
    'Aperture positions and weights must be finite compatible rows.');
assert(isnumeric(target_cross_range_m) && isreal(target_cross_range_m) && ...
    isscalar(target_cross_range_m) && isfinite(target_cross_range_m) && ...
    isnumeric(target_ground_range_m) && isreal(target_ground_range_m) && ...
    isscalar(target_ground_range_m) && isfinite(target_ground_range_m) && ...
    target_ground_range_m > 0 && isnumeric(carrier_hz) && ...
    isreal(carrier_hz) && isscalar(carrier_hz) && ...
    isfinite(carrier_hz) && carrier_hz > 0 && isnumeric(c_mps) && ...
    isreal(c_mps) && isscalar(c_mps) && isfinite(c_mps) && c_mps > 0, ...
    'P79:BadApertureModel', ...
    'Aperture focus needs finite target geometry and positive physics.');
operation_count = numel(candidate_cross_range_m)* ...
    numel(platform_position_m);
assert(operation_count <= maximum_operations, ...
    'P79:ApertureOperationCeiling', ...
    'Requested aperture-response work exceeds its ceiling.');
target_slant_range_m = hypot(platform_position_m-target_cross_range_m, ...
    target_ground_range_m);
response = complex(zeros(size(candidate_cross_range_m)));
for candidate_index = 1:numel(candidate_cross_range_m)
    predicted_slant_range_m = hypot(platform_position_m- ...
        candidate_cross_range_m(candidate_index), target_ground_range_m);
    residual_phase_rad = 4*pi*carrier_hz*( ...
        predicted_slant_range_m-target_slant_range_m)/c_mps;
    aperture_contributions = aperture_weights.*exp(1j*residual_phase_rad);
    response(candidate_index) = sum(aperture_contributions)/ ...
        sum(aperture_weights);
end
end

function [image_complex, operation_count] = form_separable_image( ...
    image_x_m, image_range_offset_m, target_x_m, target_range_offset_m, ...
    target_reflectivity, bandwidth_hz, frequency_sample_count, ...
    platform_position_m, aperture_weights, scene_center_range_m, ...
    carrier_hz, c_mps, maximum_operations)
assert(isrow(image_x_m) && isrow(image_range_offset_m) && ...
    all(isfinite(image_x_m)) && all(isfinite(image_range_offset_m)) && ...
    all(diff(image_x_m) > 0) && all(diff(image_range_offset_m) > 0) && ...
    isrow(target_x_m) && isrow(target_range_offset_m) && ...
    isrow(target_reflectivity) && numel(target_x_m) >= 1 && ...
    numel(target_x_m) == numel(target_range_offset_m) && ...
    numel(target_x_m) == numel(target_reflectivity) && ...
    all(isfinite(target_x_m)) && all(isfinite(target_range_offset_m)) && ...
    all(isfinite(target_reflectivity)), 'P79:BadImageModel', ...
    'Image and target coordinates must be finite compatible rows.');
operation_count = numel(target_x_m)*( ...
    numel(image_range_offset_m)*frequency_sample_count+ ...
    numel(image_x_m)*numel(platform_position_m));
assert(operation_count <= maximum_operations, 'P79:ImageOperationCeiling', ...
    'Requested separable-image work exceeds its ceiling.');
image_complex = complex(zeros(numel(image_range_offset_m), ...
    numel(image_x_m)));
for target_index = 1:numel(target_x_m)
    [range_response, ~] = coherent_range_response( ...
        image_range_offset_m-target_range_offset_m(target_index), ...
        bandwidth_hz, frequency_sample_count, c_mps, maximum_operations);
    [cross_range_response, ~] = coherent_aperture_response( ...
        image_x_m, target_x_m(target_index), ...
        scene_center_range_m+target_range_offset_m(target_index), ...
        platform_position_m, aperture_weights, carrier_hz, c_mps, ...
        maximum_operations);
    image_complex = image_complex+target_reflectivity(target_index).* ...
        (range_response.'*cross_range_response);
end
end

function metrics = response_metrics(coordinate_m, magnitude)
assert(isnumeric(coordinate_m) && isreal(coordinate_m) && ...
    isrow(coordinate_m) && isnumeric(magnitude) && isreal(magnitude) && ...
    isrow(magnitude) && numel(coordinate_m) == numel(magnitude) && ...
    numel(coordinate_m) >= 9 && all(isfinite(coordinate_m)) && ...
    all(isfinite(magnitude)) && all(diff(coordinate_m) > 0) && ...
    all(magnitude >= 0), 'P79:BadMetricInput', ...
    'Metrics need finite ordered coordinate and magnitude rows.');
[peak_value, peak_index] = max(magnitude);
assert(peak_value > 0 && peak_index > 2 && ...
    peak_index < numel(magnitude)-1, 'P79:BadMetricPeak', ...
    'Response must have an interior positive peak.');
normalized = magnitude/peak_value;
half_power_amplitude = 1/sqrt(2);
left_below = find(normalized(1:peak_index) <= ...
    half_power_amplitude, 1, 'last');
right_relative = find(normalized(peak_index:end) <= ...
    half_power_amplitude, 1, 'first');
assert(~isempty(left_below) && ~isempty(right_relative) && ...
    left_below < peak_index && right_relative > 1, ...
    'P79:MissingHalfPowerCrossing', ...
    'Mainlobe must have two half-power crossings.');
right_below = peak_index+right_relative-1;
left_half_power_m = interpolate_crossing( ...
    coordinate_m(left_below), normalized(left_below), ...
    coordinate_m(left_below+1), normalized(left_below+1), ...
    half_power_amplitude);
right_half_power_m = interpolate_crossing( ...
    coordinate_m(right_below-1), normalized(right_below-1), ...
    coordinate_m(right_below), normalized(right_below), ...
    half_power_amplitude);

local_minimum = false(size(normalized));
local_minimum(2:end-1) = normalized(2:end-1) <= normalized(1:end-2) & ...
    normalized(2:end-1) < normalized(3:end);
left_null_index = find(local_minimum(1:peak_index-1), 1, 'last');
right_relative = find(local_minimum(peak_index+1:end), 1, 'first');
assert(~isempty(left_null_index) && ~isempty(right_relative), ...
    'P79:MissingFirstNull', ...
    'Response must have a local minimum on both sides of the peak.');
right_null_index = peak_index+right_relative;
sidelobe_samples = [normalized(1:left_null_index) ...
    normalized(right_null_index:end)];
peak_sidelobe_db = 20*log10(max(sidelobe_samples));
metrics = struct( ...
    'peak_coordinate_m', coordinate_m(peak_index), ...
    'peak_value', peak_value, ...
    'left_half_power_m', left_half_power_m, ...
    'right_half_power_m', right_half_power_m, ...
    'half_power_width_m', right_half_power_m-left_half_power_m, ...
    'left_null_m', coordinate_m(left_null_index), ...
    'right_null_m', coordinate_m(right_null_index), ...
    'first_null_width_m', coordinate_m(right_null_index)- ...
        coordinate_m(left_null_index), ...
    'peak_sidelobe_db', peak_sidelobe_db);
end

function crossing_x = interpolate_crossing(x1, y1, x2, y2, target_y)
assert(all(isfinite([x1 y1 x2 y2 target_y])) && x2 > x1 && ...
    y2 ~= y1 && target_y >= min(y1, y2) && ...
    target_y <= max(y1, y2), 'P79:BadCrossingBracket', ...
    'A crossing needs an ordered finite bracket around the target.');
crossing_x = x1+(target_y-y1)*(x2-x1)/(y2-y1);
end

function output_db = normalized_db(values, display_floor_db)
magnitude = abs(values);
peak_value = max(magnitude(:));
assert(isfinite(peak_value) && peak_value > 0 && ...
    isfinite(display_floor_db) && display_floor_db < 0, ...
    'P79:BadDisplayInput', ...
    'dB display needs a positive peak and a finite negative floor.');
output_db = 20*log10(max(magnitude/peak_value, ...
    10^(display_floor_db/20)));
end

function values = private_uniform(seed, count, maximum_count)
modulus = 2147483647;
multiplier = 16807;
assert(isnumeric(seed) && isreal(seed) && isscalar(seed) && ...
    isfinite(seed) && seed == floor(seed) && seed >= 1 && seed < modulus, ...
    'P79:BadPrivateSeed', 'Private seed must be an integer in range.');
assert(isnumeric(count) && isreal(count) && isscalar(count) && ...
    isfinite(count) && count == floor(count) && count >= 1 && ...
    count <= maximum_count, 'P79:BadPrivateCount', ...
    'Private sample count exceeds its immutable ceiling.');
values = zeros(1, count);
state = seed;
for sample_index = 1:count
    state = mod(multiplier*state, modulus);
    values(sample_index) = (state+0.5)/modulus;
end
end

