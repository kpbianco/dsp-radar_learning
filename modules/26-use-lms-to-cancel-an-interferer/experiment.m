%% Deterministic desired signal, reference, and changing unknown FIR path
private_stream = RandStream('mt19937ar', 'Seed', random_seed);
reference_signal = randn(private_stream, 1, sample_count);
reference_signal = reference_signal/sqrt(mean(reference_signal.^2));
independent_reference_noise = randn(private_stream, 1, sample_count);
independent_reference_noise = independent_reference_noise/ ...
    sqrt(mean(independent_reference_noise.^2));
receiver_noise_unit = randn(private_stream, 1, sample_count);
receiver_noise_unit = receiver_noise_unit/sqrt(mean(receiver_noise_unit.^2));

sample_index_zero = 0:sample_count-1;
time_seconds = sample_index_zero/sampling_rate_hz;
desired_clean_signal = ...
    desired_amplitudes(1)*sin(2*pi*desired_frequencies_hz(1)*time_seconds + ...
        desired_phase_rad(1)) + ...
    desired_amplitudes(2)*sin(2*pi*desired_frequencies_hz(2)*time_seconds + ...
        desired_phase_rad(2));
desired_signal = desired_clean_signal + receiver_noise_std*receiver_noise_unit;

coupled_before_full = conv(reference_signal, path_before);
coupled_after_full = conv(reference_signal, path_after);
true_interference = coupled_before_full(1:sample_count);
true_interference(path_change_sample:end) = ...
    coupled_after_full(path_change_sample:sample_count);
primary_signal = desired_signal + true_interference;
reference_power = mean(reference_signal.^2);
conservative_step_limit = 0.1/(filter_tap_count*reference_power);
white_gaussian_mean_square_step_limit = ...
    2/((filter_tap_count+2)*reference_power);

assert(abs(reference_power-1) < 1e-12, ...
    'The cancellation reference must have unit mean-square power.');
assert(baseline_step_size <= conservative_step_limit && ...
    max(step_size_sweep) <= conservative_step_limit, ...
    'Stable study step sizes must stay within the conservative bound.');
