    'The broken step size must be visibly beyond the conservative bound.');
assert(broken_step_size > white_gaussian_mean_square_step_limit, ...
    ['The broken step size must exceed the ideal white-Gaussian ', ...
     'mean-square stability reference bound.']);

%% Baseline LMS: estimate the coupled interference one sample at a time
% x_n = [x(n), x(n-1), ..., x(n-L+1)]^T
% y_hat(n) = w(n)^T x_n
% e(n) = d(n) - y_hat(n)
% w(n+1) = w(n) + mu e(n) x_n
baseline_weights = zeros(filter_tap_count, 1);
baseline_weight_history = zeros(filter_tap_count, sample_count);
baseline_estimated_interference = zeros(1, sample_count);
baseline_error = zeros(1, sample_count);
baseline_residual_interference = zeros(1, sample_count);
baseline_path_mismatch = zeros(1, sample_count);

for sample_index = 1:sample_count
    reference_vector = zeros(filter_tap_count, 1);
    available_taps = min(filter_tap_count, sample_index);
    reference_vector(1:available_taps) = ...
        reference_signal(sample_index:-1:sample_index-available_taps+1).';
    estimated_interference = baseline_weights.'*reference_vector;
    error_sample = primary_signal(sample_index) - estimated_interference;
    baseline_weights = baseline_weights + ...
        baseline_step_size*error_sample*reference_vector;

    baseline_estimated_interference(sample_index) = estimated_interference;
    baseline_error(sample_index) = error_sample;
    baseline_residual_interference(sample_index) = ...
        true_interference(sample_index) - estimated_interference;
    baseline_weight_history(:, sample_index) = baseline_weights;
    if sample_index < path_change_sample
        active_path = path_before.';
    else
        active_path = path_after.';
    end
    baseline_path_mismatch(sample_index) = ...
        sqrt(mean((baseline_weights-active_path).^2));
end

pre_settled_indices = ...
    path_change_sample-spectrum_segment_length:path_change_sample-1;
post_settled_indices = sample_count-spectrum_segment_length+1:sample_count;
baseline_pre_interference_power = ...
    mean(true_interference(pre_settled_indices).^2);
baseline_post_interference_power = ...
    mean(true_interference(post_settled_indices).^2);
baseline_pre_residual_power = ...
    mean(baseline_residual_interference(pre_settled_indices).^2);
baseline_post_residual_power = ...
    mean(baseline_residual_interference(post_settled_indices).^2);
baseline_pre_error_power = mean(baseline_error(pre_settled_indices).^2);
baseline_post_error_power = mean(baseline_error(post_settled_indices).^2);
baseline_pre_desired_gain = sum( ...
    baseline_error(pre_settled_indices).* ...
    desired_clean_signal(pre_settled_indices))/sum( ...
    desired_clean_signal(pre_settled_indices).^2);
baseline_post_desired_gain = sum( ...
    baseline_error(post_settled_indices).* ...
    desired_clean_signal(post_settled_indices))/sum( ...
    desired_clean_signal(post_settled_indices).^2);
baseline_pre_suppression_db = 10*log10( ...
    baseline_pre_interference_power/baseline_pre_residual_power);
baseline_post_suppression_db = 10*log10( ...
    baseline_post_interference_power/baseline_post_residual_power);

post_change_below_threshold = ...
    baseline_path_mismatch(path_change_sample:end) < ...
    reacquisition_mismatch_threshold;
post_change_streak = conv(double(post_change_below_threshold), ...
    ones(1, reacquisition_hold_samples), 'valid');
baseline_streak_index = find( ...
    post_change_streak >= reacquisition_hold_samples, 1, 'first');
assert(~isempty(baseline_streak_index), ...
    'Baseline LMS must reacquire the changed path.');
baseline_reacquisition_samples = ...
    baseline_streak_index + reacquisition_hold_samples - 1;

assert(baseline_pre_residual_power < 0.05*baseline_pre_interference_power && ...
    baseline_post_residual_power < 0.05*baseline_post_interference_power, ...
    'Baseline LMS should suppress correlated interference in both epochs.');
assert(abs(baseline_pre_desired_gain-1) < 0.05 && ...
    abs(baseline_post_desired_gain-1) < 0.05, ...
    'Settled canceller output must preserve the clean desired waveform gain.');
assert(baseline_path_mismatch(path_change_sample-1) < ...
    reacquisition_mismatch_threshold && ...
    baseline_path_mismatch(end) < reacquisition_mismatch_threshold, ...
    'Baseline learned taps should approach both unknown paths.');

baseline_moving_error_power = conv(baseline_error.^2, ...
    ones(1, moving_average_length)/moving_average_length, 'same');
baseline_moving_residual_power = conv(baseline_residual_interference.^2, ...
    ones(1, moving_average_length)/moving_average_length, 'same');

%% Sweep 1: change only LMS step size on the same signals and paths
step_sweep_pre_error_power = zeros(size(step_size_sweep));
step_sweep_post_error_power = zeros(size(step_size_sweep));
step_sweep_final_path_mismatch = zeros(size(step_size_sweep));
step_sweep_reacquisition_samples = NaN(size(step_size_sweep));

for sweep_index = 1:numel(step_size_sweep)
    sweep_step_size = step_size_sweep(sweep_index);
    sweep_weights = zeros(filter_tap_count, 1);
    sweep_error = zeros(1, sample_count);
    sweep_path_mismatch = zeros(1, sample_count);
    for sample_index = 1:sample_count
        reference_vector = zeros(filter_tap_count, 1);
        available_taps = min(filter_tap_count, sample_index);
        reference_vector(1:available_taps) = ...
            reference_signal(sample_index:-1:sample_index-available_taps+1).';
        estimated_interference = sweep_weights.'*reference_vector;
        error_sample = primary_signal(sample_index) - estimated_interference;
        sweep_weights = sweep_weights + ...
            sweep_step_size*error_sample*reference_vector;
        sweep_error(sample_index) = error_sample;
        if sample_index < path_change_sample
            active_path = path_before.';
        else
            active_path = path_after.';
        end
        sweep_path_mismatch(sample_index) = ...
            sqrt(mean((sweep_weights-active_path).^2));
    end
    step_sweep_pre_error_power(sweep_index) = ...
        mean(sweep_error(pre_settled_indices).^2);
    step_sweep_post_error_power(sweep_index) = ...
        mean(sweep_error(post_settled_indices).^2);
    step_sweep_final_path_mismatch(sweep_index) = sweep_path_mismatch(end);
    below_threshold = sweep_path_mismatch(path_change_sample:end) < ...
        reacquisition_mismatch_threshold;
    threshold_streak = conv(double(below_threshold), ...
        ones(1, reacquisition_hold_samples), 'valid');
    streak_index = find(threshold_streak >= reacquisition_hold_samples, ...
        1, 'first');
    if ~isempty(streak_index)
        step_sweep_reacquisition_samples(sweep_index) = ...
            streak_index + reacquisition_hold_samples - 1;
    end
end

baseline_sweep_index = find(step_size_sweep == baseline_step_size, 1, 'first');
assert(~isempty(baseline_sweep_index) && ...
    abs(step_sweep_post_error_power(baseline_sweep_index) - ...
