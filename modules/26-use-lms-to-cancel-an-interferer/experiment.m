%% Sweep 2: change only reference correlation; keep the primary fixed
reference_sweep_suppression_db = zeros(size(reference_correlation_sweep));
reference_sweep_post_error_power = zeros(size(reference_correlation_sweep));

for sweep_index = 1:numel(reference_correlation_sweep)
    reference_correlation = reference_correlation_sweep(sweep_index);
    candidate_reference = reference_correlation*reference_signal + ...
        sqrt(1-reference_correlation^2)*independent_reference_noise;
    candidate_reference = candidate_reference/ ...
        sqrt(mean(candidate_reference.^2));
    sweep_weights = zeros(filter_tap_count, 1);
    sweep_error = zeros(1, sample_count);
    sweep_residual_interference = zeros(1, sample_count);
    for sample_index = 1:sample_count
        reference_vector = zeros(filter_tap_count, 1);
        available_taps = min(filter_tap_count, sample_index);
        reference_vector(1:available_taps) = ...
            candidate_reference( ...
                sample_index:-1:sample_index-available_taps+1).';
        estimated_interference = sweep_weights.'*reference_vector;
        error_sample = primary_signal(sample_index) - estimated_interference;
        sweep_weights = sweep_weights + ...
            baseline_step_size*error_sample*reference_vector;
        sweep_error(sample_index) = error_sample;
        sweep_residual_interference(sample_index) = ...
            true_interference(sample_index) - estimated_interference;
    end
    residual_power = mean( ...
        sweep_residual_interference(post_settled_indices).^2);
    reference_sweep_suppression_db(sweep_index) = 10*log10( ...
        baseline_post_interference_power/residual_power);
    reference_sweep_post_error_power(sweep_index) = ...
        mean(sweep_error(post_settled_indices).^2);
end

assert(reference_sweep_suppression_db(1) > ...
    reference_sweep_suppression_db(end) + 10 && ...
    reference_sweep_suppression_db(end) < 3, ...
    'An uncorrelated reference must fail to reproduce the coupled interferer.');

%% Intentionally broken case: oversized step, bounded guard, then recovery
broken_weights = zeros(filter_tap_count, 1);
broken_error = NaN(1, sample_count);
broken_weight_norm = NaN(1, sample_count);
broken_guard_triggered = false;
broken_stop_sample = sample_count + 1;

for sample_index = 1:sample_count
    reference_vector = zeros(filter_tap_count, 1);
    available_taps = min(filter_tap_count, sample_index);
    reference_vector(1:available_taps) = ...
        reference_signal(sample_index:-1:sample_index-available_taps+1).';
    estimated_interference = broken_weights.'*reference_vector;
    error_sample = primary_signal(sample_index) - estimated_interference;
    candidate_weights = broken_weights + ...
        broken_step_size*error_sample*reference_vector;
    if ~isfinite(error_sample) || any(~isfinite(candidate_weights)) || ...
            norm(candidate_weights) > broken_weight_norm_limit || ...
            abs(error_sample) > broken_error_limit
        broken_guard_triggered = true;
        broken_stop_sample = sample_index;
        break;
    end
    broken_weights = candidate_weights;
    broken_error(sample_index) = error_sample;
    broken_weight_norm(sample_index) = norm(broken_weights);
end

assert(broken_guard_triggered && broken_stop_sample <= sample_count, ...
    'The intentionally oversized step must trigger the bounded failure guard.');

% Recovery is operationally explicit: discard broken weights, keep the same
% deterministic input, and rerun from zero with the baseline step size.
recovery_weights = zeros(filter_tap_count, 1);
recovery_error = zeros(1, sample_count);
for sample_index = 1:sample_count
    reference_vector = zeros(filter_tap_count, 1);
    available_taps = min(filter_tap_count, sample_index);
    reference_vector(1:available_taps) = ...
        reference_signal(sample_index:-1:sample_index-available_taps+1).';
    estimated_interference = recovery_weights.'*reference_vector;
    error_sample = primary_signal(sample_index) - estimated_interference;
    recovery_weights = recovery_weights + ...
        baseline_step_size*error_sample*reference_vector;
    recovery_error(sample_index) = error_sample;
end
assert(max(abs(recovery_error-baseline_error)) < 1e-12 && ...
    max(abs(recovery_weights-baseline_weights)) < 1e-12, ...
    'A clean stable rerun must reproduce the deterministic baseline.');

