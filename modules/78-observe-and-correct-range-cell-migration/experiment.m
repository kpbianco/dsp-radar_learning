%% P78: Observe and Correct Range-Cell Migration
% Guiding question:
% Why does a target move through range bins during a long synthetic aperture?
%
% Base MATLAB only. The script creates one seeded range-compressed point
% target, exposes its curved slant-range history, explicitly shifts each row
% with linear interpolation, and compares fixed-bin image formation with
% path-following backprojection on the same complex measurement.

close(findall(0, 'Type', 'figure', 'Tag', 'P78'));
clear p78_results;
p78_results = run_p78_experiment();

function p78_results = run_p78_experiment()

%% Visible deterministic controls and immutable resource ceilings
baseline_seed = 7801;
speed_of_light_mps = 3.0e8;
carrier_frequency_hz = 1.0e9;
range_gate_start_m = 955.0;
range_gate_end_m = 1075.0;
range_sample_spacing_m = 0.5;
range_resolution_m = 2.0;
aperture_length_m = 400.0;
platform_spacing_m = 0.25;
target_cross_range_m = 60.0;
target_ground_range_m = 1000.0;
target_voltage = 1.0;
target_initial_phase_rad = 0.3;
noise_rms_voltage = 0.02;
aperture_length_sweep_m = [100.0 200.0 400.0];
squint_offset_sweep_m = [0.0 60.0 80.0];
image_cross_range_m = -40.0:2.0:160.0;
image_ground_range_m = 995.0:1.0:1005.0;

maximum_aperture_samples = 2001;
maximum_range_samples = 251;
maximum_image_pixels = 1500;
maximum_sweep_cases = 5;
maximum_private_values = 800000;
maximum_interpolation_operations = 1200000;
maximum_image_operations = 4000000;
maximum_total_operations = 5200000;
maximum_working_value_equivalents = 12000000;
maximum_figures = 6;
maximum_adjacent_phase_step_rad = 0.90*pi;
minimum_visible_migration_bins = 40.0;
maximum_corrected_ridge_span_m = 1.0;
minimum_profile_peak_gain = 3.0;
minimum_concentration_gain = 1.4;
maximum_fixed_true_pixel_ratio = 0.40;
minimum_image_concentration_gain = 1.8;

controls = struct( ...
    'seed', baseline_seed, 'c_mps', speed_of_light_mps, ...
    'carrier_hz', carrier_frequency_hz, ...
    'range_gate_start_m', range_gate_start_m, ...
    'range_gate_end_m', range_gate_end_m, ...
    'range_spacing_m', range_sample_spacing_m, ...
    'range_resolution_m', range_resolution_m, ...
    'aperture_length_m', aperture_length_m, ...
    'platform_spacing_m', platform_spacing_m, ...
    'target_cross_range_m', target_cross_range_m, ...
    'target_ground_range_m', target_ground_range_m, ...
    'target_voltage', target_voltage, ...
    'target_initial_phase_rad', target_initial_phase_rad, ...
    'noise_rms_voltage', noise_rms_voltage, ...
    'aperture_length_sweep_m', aperture_length_sweep_m, ...
    'squint_offset_sweep_m', squint_offset_sweep_m, ...
    'image_cross_range_m', image_cross_range_m, ...
    'image_ground_range_m', image_ground_range_m, ...
    'max_aperture_samples', maximum_aperture_samples, ...
    'max_range_samples', maximum_range_samples, ...
    'max_image_pixels', maximum_image_pixels, ...
    'max_sweep_cases', maximum_sweep_cases, ...
    'max_private_values', maximum_private_values, ...
    'max_interpolation_operations', maximum_interpolation_operations, ...
    'max_image_operations', maximum_image_operations, ...
    'max_total_operations', maximum_total_operations, ...
    'max_working_values', maximum_working_value_equivalents, ...
    'max_figures', maximum_figures, ...
    'max_phase_step_rad', maximum_adjacent_phase_step_rad);
predicted_operations = validate_controls(controls);

wavelength_m = speed_of_light_mps/carrier_frequency_hz;
platform_position_m = -aperture_length_m/2:platform_spacing_m: ...
    aperture_length_m/2;
range_axis_m = range_gate_start_m:range_sample_spacing_m:range_gate_end_m;
aperture_sample_count = numel(platform_position_m);
range_sample_count = numel(range_axis_m);

%% Deterministic range-compressed complex target history
% The monostatic two-way phase is -4*pi*R/lambda. A fixed range reference
% removes only a harmless common phase from the simulated samples.
target_slant_range_m = hypot(platform_position_m-target_cross_range_m, ...
    target_ground_range_m);
range_reference_m = range_gate_start_m;
target_phase_rad = target_initial_phase_rad-4*pi*( ...
    target_slant_range_m-range_reference_m)/wavelength_m;
clean_range_history = zeros(aperture_sample_count, range_sample_count);
for aperture_index = 1:aperture_sample_count
    normalized_range_offset = (range_axis_m- ...
        target_slant_range_m(aperture_index))/range_resolution_m;
    clean_range_history(aperture_index, :) = target_voltage* ...
        explicit_sinc(normalized_range_offset)* ...
        exp(1j*target_phase_rad(aperture_index));
end
private_noise = private_complex_noise(baseline_seed, ...
    numel(clean_range_history), maximum_private_values);
additive_noise = noise_rms_voltage*reshape(private_noise, ...
    size(clean_range_history));
range_compressed_history = clean_range_history+additive_noise;
retained_complex_range_history = range_compressed_history;

[~, measured_peak_index] = max(abs(range_compressed_history), [], 2);
measured_ridge_range_m = range_axis_m(measured_peak_index);
true_migration_span_m = max(target_slant_range_m)- ...
    min(target_slant_range_m);
measured_migration_span_m = max(measured_ridge_range_m)- ...
    min(measured_ridge_range_m);
measured_migration_bins = measured_migration_span_m/ ...
    range_sample_spacing_m;
assert(measured_migration_bins > minimum_visible_migration_bins, ...
    'P78:VisibleMigration', ...
    'The baseline must visibly cross many sampled range bins.');

fprintf('\nP78 baseline: %d aperture positions, %d range samples\n', ...
    aperture_sample_count, range_sample_count);
fprintf('Carrier %.1f GHz; wavelength %.1f mm; range spacing %.2f m\n', ...
    carrier_frequency_hz/1.0e9, wavelength_m*1.0e3, ...
    range_sample_spacing_m);
fprintf('True/measured migration span = %.3f / %.3f m (%.1f bins)\n', ...
    true_migration_span_m, measured_migration_span_m, ...
    measured_migration_bins);

figure('Name', 'P78 geometry and observed range-cell migration', ...
    'Tag', 'P78', 'NumberTitle', 'off');
subplot(2, 1, 1);
plot(platform_position_m, zeros(size(platform_position_m)), 'b.-');
hold on;
plot(target_cross_range_m, target_ground_range_m, 'rx', ...
    'MarkerSize', 10, 'LineWidth', 1.5);
grid on;
xlabel('Platform cross-range position x_p (m)');
ylabel('Ground-range y (m)');
title('A long track views one squinted point target from changing slant range');
legend('Platform positions', 'Point target', 'Location', 'best');
subplot(2, 1, 2);
history_db = 20*log10(max(abs(range_compressed_history)/ ...
    max(abs(range_compressed_history(:))), 1.0e-5));
imagesc(range_axis_m, platform_position_m, history_db);
axis xy;
hold on;
plot(target_slant_range_m, platform_position_m, 'w--', 'LineWidth', 1.2);
xlabel('Monostatic slant range (m)');
ylabel('Platform cross-range position x_p (m)');
title(sprintf('Range-compressed ridge migrates %.1f sampled bins', ...
    measured_migration_bins));
colorbar;
caxis([-40 0]);

%% Correct range-cell migration with explicit row-wise linear interpolation
% Let DeltaR(p) = R(p)-R_ref. The corrected output at range r samples the
% original row at r+DeltaR(p):
% y_corrected(p,r) = y_measured(p,r+DeltaR(p)).
center_aperture_index = (aperture_sample_count+1)/2;
alignment_reference_range_m = ...
    target_slant_range_m(center_aperture_index);
migration_offset_m = target_slant_range_m-alignment_reference_range_m;
[corrected_range_history, correct_interpolation_operations] = ...
    shift_range_history(retained_complex_range_history, range_axis_m, ...
    migration_offset_m, +1, maximum_interpolation_operations);
[~, corrected_peak_index] = max(abs(corrected_range_history), [], 2);
corrected_ridge_range_m = range_axis_m(corrected_peak_index);
corrected_ridge_span_m = max(corrected_ridge_range_m)- ...
    min(corrected_ridge_range_m);
assert(corrected_ridge_span_m <= maximum_corrected_ridge_span_m, ...
    'P78:CorrectedRidgeAlignment', ...
    'Correct-sign interpolation must align the migrating ridge.');

% Both profiles use the same two-way phase compensation. The only changed
% operation is whether each aperture row is shifted to follow the range path.
two_way_phase_compensation = exp(1j*4*pi*( ...
    target_slant_range_m-range_reference_m)/wavelength_m).';
fixed_bin_profile = sum(range_compressed_history.* ...
    two_way_phase_compensation, 1);
corrected_profile = sum(corrected_range_history.* ...
    two_way_phase_compensation, 1);
fixed_profile_power = abs(fixed_bin_profile).^2;
corrected_profile_power = abs(corrected_profile).^2;
fixed_profile_concentration = max(fixed_profile_power)/ ...
    sum(fixed_profile_power);
corrected_profile_concentration = max(corrected_profile_power)/ ...
    sum(corrected_profile_power);
profile_peak_gain = max(abs(corrected_profile))/ ...
    max(abs(fixed_bin_profile));
profile_concentration_gain = corrected_profile_concentration/ ...
    fixed_profile_concentration;
assert(profile_peak_gain > minimum_profile_peak_gain && ...
    profile_concentration_gain > minimum_concentration_gain, ...
    'P78:CorrectedProfileConcentration', ...
    'Following the range path must concentrate more coherent energy.');

fprintf('\nCorrected ridge span = %.3f m\n', corrected_ridge_span_m);
fprintf('Corrected/fixed coherent peak gain = %.3f\n', profile_peak_gain);
fprintf('Corrected/fixed power-concentration gain = %.3f\n', ...
    profile_concentration_gain);

figure('Name', 'P78 before and after range migration correction', ...
    'Tag', 'P78', 'NumberTitle', 'off');
subplot(1, 2, 1);
imagesc(range_axis_m, platform_position_m, history_db);
axis xy;
xlabel('Monostatic slant range (m)');
ylabel('Platform cross-range position x_p (m)');
title(sprintf('Before: ridge span %.1f m', measured_migration_span_m));
colorbar;
caxis([-40 0]);
subplot(1, 2, 2);
corrected_history_db = 20*log10(max(abs(corrected_range_history)/ ...
    max(abs(corrected_range_history(:))), 1.0e-5));
imagesc(range_axis_m, platform_position_m, corrected_history_db);
axis xy;
xlabel('Reference-aligned slant range (m)');
ylabel('Platform cross-range position x_p (m)');
title(sprintf('After: ridge span %.1f m', corrected_ridge_span_m));
colorbar;
caxis([-40 0]);

figure('Name', 'P78 fixed-bin versus path-following range profile', ...
    'Tag', 'P78', 'NumberTitle', 'off');
plot(range_axis_m, 20*log10(max(abs(fixed_bin_profile)/ ...
    max(abs(corrected_profile)), 1.0e-5)), 'r--', 'LineWidth', 1.1);
hold on;
plot(range_axis_m, 20*log10(max(abs(corrected_profile)/ ...
    max(abs(corrected_profile)), 1.0e-5)), 'b-', 'LineWidth', 1.2);
grid on;
xlabel('Reference-aligned slant range (m)');
ylabel('Coherent profile relative to corrected peak (dB)');
title('Same phase compensation: only the range sampling path changes');
legend('Fixed range bins', 'Follow curved range path', 'Location', 'best');
xlim([alignment_reference_range_m-45 alignment_reference_range_m+45]);
ylim([-45 2]);

%% Sweep 1: aperture length only
aperture_case_count = numel(aperture_length_sweep_m);
aperture_migration_span_m = zeros(1, aperture_case_count);
aperture_migration_bins = zeros(1, aperture_case_count);
aperture_range_histories_m = cell(1, aperture_case_count);
aperture_positions_m = cell(1, aperture_case_count);
for case_index = 1:aperture_case_count
    case_length_m = aperture_length_sweep_m(case_index);
    case_positions_m = -case_length_m/2:platform_spacing_m:case_length_m/2;
    case_ranges_m = hypot(case_positions_m-target_cross_range_m, ...
        target_ground_range_m);
    aperture_positions_m{case_index} = case_positions_m;
    aperture_range_histories_m{case_index} = case_ranges_m;
    aperture_migration_span_m(case_index) = max(case_ranges_m)- ...
        min(case_ranges_m);
    aperture_migration_bins(case_index) = ...
        aperture_migration_span_m(case_index)/range_sample_spacing_m;
end
assert(all(diff(aperture_migration_span_m) > 0), ...
    'P78:ApertureLengthSweep', ...
    'Longer reviewed apertures must cross more range cells.');

%% Sweep 2: squint offset only
squint_case_count = numel(squint_offset_sweep_m);
squint_migration_span_m = zeros(1, squint_case_count);
squint_migration_bins = zeros(1, squint_case_count);
squint_range_histories_m = zeros(squint_case_count, ...
    aperture_sample_count);
for case_index = 1:squint_case_count
    case_target_cross_range_m = squint_offset_sweep_m(case_index);
    case_ranges_m = hypot(platform_position_m-case_target_cross_range_m, ...
        target_ground_range_m);
    squint_range_histories_m(case_index, :) = case_ranges_m;
    squint_migration_span_m(case_index) = max(case_ranges_m)- ...
        min(case_ranges_m);
    squint_migration_bins(case_index) = ...
        squint_migration_span_m(case_index)/range_sample_spacing_m;
end
assert(all(diff(squint_migration_span_m) > 0), ...
    'P78:SquintOffsetSweep', ...
    'Larger reviewed squint offsets must increase migration and asymmetry.');

fprintf('\nAperture-length sweep (m): %s\n', ...
    mat2str(aperture_length_sweep_m));
fprintf('Migration spans (m): %s; sampled bins: %s\n', ...
    mat2str(aperture_migration_span_m, 5), ...
    mat2str(aperture_migration_bins, 5));
fprintf('Squint-offset sweep (m): %s\n', ...
    mat2str(squint_offset_sweep_m));
fprintf('Migration spans (m): %s; sampled bins: %s\n', ...
    mat2str(squint_migration_span_m, 5), ...
    mat2str(squint_migration_bins, 5));

figure('Name', 'P78 aperture-length and squint sweeps', ...
    'Tag', 'P78', 'NumberTitle', 'off');
subplot(1, 2, 1);
hold on;
for case_index = 1:aperture_case_count
    case_ranges_m = aperture_range_histories_m{case_index};
    plot(aperture_positions_m{case_index}, case_ranges_m- ...
        case_ranges_m(ceil(numel(case_ranges_m)/2)), 'LineWidth', 1.0);
end
grid on;
xlabel('Platform cross-range position x_p (m)');
ylabel('Range change from center look (m)');
title('Only aperture length changes');
legend('100 m', '200 m', '400 m', 'Location', 'best');
subplot(1, 2, 2);
hold on;
for case_index = 1:squint_case_count
    plot(platform_position_m, squint_range_histories_m(case_index, :)- ...
        squint_range_histories_m(case_index, center_aperture_index), ...
        'LineWidth', 1.0);
end
grid on;
xlabel('Platform cross-range position x_p (m)');
ylabel('Range change from center look (m)');
title('Only target squint offset changes');
legend('0 m', '60 m', '80 m', 'Location', 'best');

%% Fixed-bin image versus path-following backprojection
% Each pixel gets the same predicted phase compensation. The fixed-bin image
% repeatedly samples only that pixel's center-look range. The corrected image
% linearly samples every aperture row at the pixel's changing slant range.
[fixed_bin_image, fixed_image_operations] = form_range_cross_range_image( ...
    retained_complex_range_history, platform_position_m, range_axis_m, ...
    image_cross_range_m, image_ground_range_m, wavelength_m, ...
    range_reference_m, false, maximum_image_operations);
[path_following_image, corrected_image_operations] = ...
    form_range_cross_range_image(retained_complex_range_history, ...
    platform_position_m, range_axis_m, image_cross_range_m, ...
    image_ground_range_m, wavelength_m, range_reference_m, true, ...
    maximum_image_operations);

target_x_index = find(abs(image_cross_range_m-target_cross_range_m) < ...
    1.0e-12, 1);
target_y_index = find(abs(image_ground_range_m-target_ground_range_m) < ...
    1.0e-12, 1);
correct_true_pixel_voltage = abs(path_following_image( ...
    target_y_index, target_x_index));
fixed_true_pixel_voltage = abs(fixed_bin_image( ...
    target_y_index, target_x_index));
fixed_true_pixel_ratio = fixed_true_pixel_voltage/correct_true_pixel_voltage;
fixed_image_power = abs(fixed_bin_image).^2;
corrected_image_power = abs(path_following_image).^2;
fixed_image_concentration = max(fixed_image_power(:))/ ...
    sum(fixed_image_power(:));
corrected_image_concentration = max(corrected_image_power(:))/ ...
    sum(corrected_image_power(:));
image_concentration_gain = corrected_image_concentration/ ...
    fixed_image_concentration;
[~, corrected_peak_linear_index] = max(corrected_image_power(:));
[corrected_peak_y_index, corrected_peak_x_index] = ind2sub( ...
    size(corrected_image_power), corrected_peak_linear_index);
focused_cross_range_m = image_cross_range_m(corrected_peak_x_index);
focused_ground_range_m = image_ground_range_m(corrected_peak_y_index);
assert(fixed_true_pixel_ratio < maximum_fixed_true_pixel_ratio && ...
    image_concentration_gain > minimum_image_concentration_gain, ...
    'P78:FixedBinSmear', ...
    'Fixed-bin processing must lose target energy and concentration.');
assert(abs(focused_cross_range_m-target_cross_range_m) <= 2.0 && ...
    abs(focused_ground_range_m-target_ground_range_m) <= 1.0, ...
    'P78:CorrectedImageLocalization', ...
    'Path-following interpolation must focus at the modeled target.');

fprintf('\nFixed/corrected true-pixel voltage = %.3f / %.3f (ratio %.3f)\n', ...
    fixed_true_pixel_voltage, correct_true_pixel_voltage, ...
    fixed_true_pixel_ratio);
fprintf('Corrected/fixed image concentration gain = %.3f\n', ...
    image_concentration_gain);
fprintf('Corrected image peak = (%.1f m cross-range, %.1f m ground-range)\n', ...
    focused_cross_range_m, focused_ground_range_m);

figure('Name', 'P78 fixed-bin smear and corrected image', ...
    'Tag', 'P78', 'NumberTitle', 'off');
subplot(1, 2, 1);
fixed_display_db = 20*log10(max(abs(fixed_bin_image)/ ...
    max(abs(path_following_image(:))), 1.0e-4));
imagesc(image_cross_range_m, image_ground_range_m, fixed_display_db);
axis xy;
hold on;
plot(target_cross_range_m, target_ground_range_m, 'wx', ...
    'MarkerSize', 9, 'LineWidth', 1.5);
xlabel('Target cross-range (m)');
ylabel('Target ground-range (m)');
title('Broken assumption: one fixed range bin per pixel');
colorbar;
caxis([-40 0]);
subplot(1, 2, 2);
corrected_display_db = 20*log10(max(abs(path_following_image)/ ...
    max(abs(path_following_image(:))), 1.0e-4));
imagesc(image_cross_range_m, image_ground_range_m, corrected_display_db);
axis xy;
hold on;
plot(target_cross_range_m, target_ground_range_m, 'wx', ...
    'MarkerSize', 9, 'LineWidth', 1.5);
xlabel('Target cross-range (m)');
ylabel('Target ground-range (m)');
title('Corrected: interpolate along every hypothesized curved path');
colorbar;
caxis([-40 0]);

%% Intentionally broken case: use the opposite interpolation sign
measurement_before_failure = retained_complex_range_history;
[wrong_sign_range_history, wrong_interpolation_operations] = ...
    shift_range_history(retained_complex_range_history, range_axis_m, ...
    migration_offset_m, -1, maximum_interpolation_operations);
[~, wrong_peak_index] = max(abs(wrong_sign_range_history), [], 2);
wrong_ridge_range_m = range_axis_m(wrong_peak_index);
wrong_ridge_span_m = max(wrong_ridge_range_m)-min(wrong_ridge_range_m);
wrong_sign_profile = sum(wrong_sign_range_history.* ...
    two_way_phase_compensation, 1);
measurement_exact_match = isequaln(retained_complex_range_history, ...
    measurement_before_failure);

% Recovery is a fresh correct-sign interpolation from the unchanged input.
[recovered_range_history, recovery_interpolation_operations] = ...
    shift_range_history(measurement_before_failure, range_axis_m, ...
    migration_offset_m, +1, maximum_interpolation_operations);
recovery_exact_match = isequaln(recovered_range_history, ...
    corrected_range_history);
recovered_profile = sum(recovered_range_history.* ...
    two_way_phase_compensation, 1);
profile_recovery_exact_match = isequaln(recovered_profile, corrected_profile);
assert(wrong_ridge_span_m > 1.8*measured_migration_span_m, ...
    'P78:WrongSignDoublesMigration', ...
    'Opposite-sign interpolation must make migration substantially worse.');
assert(measurement_exact_match && recovery_exact_match && ...
    profile_recovery_exact_match, 'P78:SameDataRecovery', ...
    'Recovery must rerun correct interpolation from unchanged complex data.');

executed_interpolation_operations = correct_interpolation_operations+ ...
    wrong_interpolation_operations+recovery_interpolation_operations;
executed_image_operations = fixed_image_operations+ ...
    corrected_image_operations;
executed_total_operations = executed_interpolation_operations+ ...
    executed_image_operations;
assert(executed_interpolation_operations == ...
    predicted_operations.interpolation && executed_image_operations == ...
    predicted_operations.image && executed_total_operations == ...
    predicted_operations.total, 'P78:OperationAccounting', ...
    'Executed correction, failure, recovery, and image work must match preflight.');

fprintf('\nWrong-sign ridge span = %.3f m (uncorrected %.3f m)\n', ...
    wrong_ridge_span_m, measured_migration_span_m);
fprintf('Same-data / correction / profile recovery exact = %d / %d / %d\n', ...
    measurement_exact_match, recovery_exact_match, ...
    profile_recovery_exact_match);
fprintf('Executed interpolation/image/total operations = %d / %d / %d\n', ...
    executed_interpolation_operations, executed_image_operations, ...
    executed_total_operations);

figure('Name', 'P78 wrong-sign failure and same-data recovery', ...
    'Tag', 'P78', 'NumberTitle', 'off');
subplot(2, 1, 1);
plot(platform_position_m, measured_ridge_range_m, 'Color', [0.5 0.5 0.5]);
hold on;
plot(platform_position_m, wrong_ridge_range_m, 'r--', 'LineWidth', 1.0);
plot(platform_position_m, corrected_ridge_range_m, 'b-', 'LineWidth', 1.1);
grid on;
xlabel('Platform cross-range position x_p (m)');
ylabel('Measured ridge range (m)');
title('Wrong sign doubles the motion; correct sign aligns the ridge');
legend('Uncorrected', 'Wrong-sign shift', 'Recovered correct shift', ...
    'Location', 'best');
subplot(2, 1, 2);
plot(range_axis_m, 20*log10(max(abs(wrong_sign_profile)/ ...
    max(abs(recovered_profile)), 1.0e-5)), 'r--', 'LineWidth', 1.0);
hold on;
plot(range_axis_m, 20*log10(max(abs(recovered_profile)/ ...
    max(abs(recovered_profile)), 1.0e-5)), 'b-', 'LineWidth', 1.1);
grid on;
xlabel('Reference-aligned slant range (m)');
ylabel('Coherent profile relative to recovered peak (dB)');
title('Recovery reuses the unchanged complex range history');
legend('Wrong-sign interpolation', 'Recovered correct interpolation', ...
    'Location', 'best');
xlim([alignment_reference_range_m-45 alignment_reference_range_m+45]);
ylim([-45 2]);

%% Retained bounded results
pre_results_workspace_inventory = whos;
pre_results_storage_bytes = sum([pre_results_workspace_inventory.bytes]);
pre_results_value_equivalents = ceil(pre_results_storage_bytes/8);
assert(pre_results_value_equivalents <= maximum_working_value_equivalents, ...
    'P78:WorkingStorageBound', ...
    'Live local workspace exceeded the reviewed eight-byte value ceiling.');
assert(numel(findall(0, 'Type', 'figure', 'Tag', 'P78')) == ...
    maximum_figures, 'P78:FigureCount', ...
    'The experiment must retain exactly six purposeful P78 figure groups.');

p78_results = struct( ...
    'controls', controls, ...
    'target_slant_range_m', target_slant_range_m, ...
