function noise = private_complex_noise(seed, count, maximum_values)
assert(isnumeric(seed) && isreal(seed) && isscalar(seed) && ...
    isfinite(seed) && seed == floor(seed) && seed >= 1 && ...
    seed < 2147483647, 'P78:NoiseSeed', ...
    'Private noise seed is outside the supported integer domain.');
assert(isnumeric(count) && isreal(count) && isscalar(count) && ...
    isfinite(count) && count == floor(count) && count >= 1 && ...
    2*count <= maximum_values, 'P78:NoiseCount', ...
    'Private noise request exceeds the reviewed bound.');
uniforms = zeros(1, 2*count);
state = seed;
for value_index = 1:(2*count)
    state = mod(16807*state, 2147483647);
    uniforms(value_index) = state/2147483647;
end
radius = sqrt(-2*log(max(uniforms(1:2:end), realmin)));
angle_rad = 2*pi*uniforms(2:2:end);
noise = radius.*exp(1j*angle_rad)/sqrt(2);
end

function [shifted_history, operation_count] = shift_range_history( ...
    range_history, range_axis_m, migration_offset_m, direction_sign, ...
    operation_ceiling)
assert(isnumeric(range_history) && ismatrix(range_history) && ...
    all(isfinite(range_history(:))), 'P78:ShiftHistory', ...
    'Range history must be a finite numeric matrix.');
assert(isnumeric(range_axis_m) && isreal(range_axis_m) && ...
    isrow(range_axis_m) && numel(range_axis_m) == size(range_history, 2) && ...
    all(isfinite(range_axis_m)) && numel(range_axis_m) >= 2, ...
    'P78:ShiftRangeAxis', 'Range axis does not match the history.');
assert(isnumeric(migration_offset_m) && isreal(migration_offset_m) && ...
    isrow(migration_offset_m) && ...
    numel(migration_offset_m) == size(range_history, 1) && ...
    all(isfinite(migration_offset_m)), 'P78:ShiftPath', ...
    'Migration path must supply one finite offset per aperture row.');
assert(isscalar(direction_sign) && any(direction_sign == [-1 1]), ...
    'P78:ShiftDirection', 'Interpolation direction must be +1 or -1.');
range_spacing_m = range_axis_m(2)-range_axis_m(1);
assert(range_spacing_m > 0 && max(abs(diff(range_axis_m)- ...
    range_spacing_m)) < 1.0e-9, 'P78:ShiftUniformGrid', ...
    'Explicit interpolation requires a uniform increasing range axis.');
operation_count = numel(range_history);
assert(operation_count <= operation_ceiling, 'P78:ShiftOperationBound', ...
    'One interpolation call exceeds its operation ceiling.');

shifted_history = zeros(size(range_history));
for aperture_index = 1:size(range_history, 1)
    requested_range_m = range_axis_m+ ...
        direction_sign*migration_offset_m(aperture_index);
    fractional_index = (requested_range_m-range_axis_m(1))/ ...
        range_spacing_m+1;
    left_index = floor(fractional_index);
    right_weight = fractional_index-left_index;
    valid = left_index >= 1 & left_index < numel(range_axis_m);
    valid_output_index = find(valid);
    valid_left_index = left_index(valid);
    shifted_history(aperture_index, valid_output_index) = ...
        (1-right_weight(valid)).*range_history(aperture_index, ...
        valid_left_index)+right_weight(valid).*range_history( ...
        aperture_index, valid_left_index+1);
end
end

function [image_complex, operation_count] = form_range_cross_range_image( ...
    range_history, platform_position_m, range_axis_m, image_cross_range_m, ...
    image_ground_range_m, wavelength_m, range_reference_m, follow_path, ...
    operation_ceiling)
assert(isnumeric(range_history) && ismatrix(range_history) && ...
    all(isfinite(range_history(:))), 'P78:ImageHistory', ...
    'Image formation needs a finite numeric range history.');
assert(isnumeric(platform_position_m) && isreal(platform_position_m) && ...
    isrow(platform_position_m) && numel(platform_position_m) == ...
    size(range_history, 1) && all(isfinite(platform_position_m)), ...
    'P78:ImagePlatform', ...
    'Platform positions must match the aperture rows.');
assert(isnumeric(range_axis_m) && isreal(range_axis_m) && ...
    isrow(range_axis_m) && numel(range_axis_m) == size(range_history, 2) && ...
    numel(range_axis_m) >= 2 && all(isfinite(range_axis_m)), ...
    'P78:ImageRangeAxis', 'Range axis must match the history columns.');
assert(isnumeric(image_cross_range_m) && isreal(image_cross_range_m) && ...
    isrow(image_cross_range_m) && numel(image_cross_range_m) >= 3 && ...
    all(isfinite(image_cross_range_m)) && ...
    all(diff(image_cross_range_m) > 0), 'P78:ImageCrossRangeAxis', ...
    'Cross-range image axis is malformed.');
assert(isnumeric(image_ground_range_m) && isreal(image_ground_range_m) && ...
    isrow(image_ground_range_m) && numel(image_ground_range_m) >= 3 && ...
    all(isfinite(image_ground_range_m)) && ...
    all(diff(image_ground_range_m) > 0), 'P78:ImageGroundRangeAxis', ...
    'Ground-range image axis is malformed.');
assert(isnumeric(wavelength_m) && isreal(wavelength_m) && ...
    isscalar(wavelength_m) && isfinite(wavelength_m) && wavelength_m > 0 && ...
    isnumeric(range_reference_m) && isreal(range_reference_m) && ...
    isscalar(range_reference_m) && isfinite(range_reference_m), ...
    'P78:ImagePhysicalControls', ...
    'Wavelength and phase reference must be finite scalars.');
assert(islogical(follow_path) && isscalar(follow_path), ...
    'P78:ImageMode', 'Path-following mode must be one logical scalar.');

[image_x_grid_m, image_y_grid_m] = meshgrid(image_cross_range_m, ...
    image_ground_range_m);
operation_count = numel(image_x_grid_m)*numel(platform_position_m);
assert(operation_count <= operation_ceiling, 'P78:ImageOperationBound', ...
    'One image-formation call exceeds its operation ceiling.');
range_spacing_m = range_axis_m(2)-range_axis_m(1);
assert(range_spacing_m > 0 && max(abs(diff(range_axis_m)- ...
    range_spacing_m)) < 1.0e-9, 'P78:ImageUniformRangeGrid', ...
    'Image interpolation requires a uniform increasing range axis.');
reference_platform_m = 0;
fixed_requested_range_m = hypot(reference_platform_m-image_x_grid_m, ...
    image_y_grid_m);
image_complex = zeros(size(image_x_grid_m));
for aperture_index = 1:numel(platform_position_m)
    predicted_range_m = hypot(platform_position_m(aperture_index)- ...
        image_x_grid_m, image_y_grid_m);
    if follow_path
        requested_range_m = predicted_range_m;
    else
        requested_range_m = fixed_requested_range_m;
    end
    fractional_index = (requested_range_m-range_axis_m(1))/ ...
        range_spacing_m+1;
    left_index = floor(fractional_index);
    right_weight = fractional_index-left_index;
    valid = left_index >= 1 & left_index < numel(range_axis_m);
    assert(all(valid(:)), 'P78:ImageInterpolationSupport', ...
        'An image hypothesis left the retained range gate.');
    row = range_history(aperture_index, :);
    sampled_complex_value = (1-right_weight).*row(left_index)+ ...
        right_weight.*row(left_index+1);
    phase_compensation = exp(1j*4*pi*(predicted_range_m- ...
        range_reference_m)/wavelength_m);
    image_complex = image_complex+sampled_complex_value.* ...
        phase_compensation;
end
