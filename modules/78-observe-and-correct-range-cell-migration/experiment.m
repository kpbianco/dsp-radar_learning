function predicted = validate_controls(controls)
required_scalars = {'seed', 'c_mps', 'carrier_hz', ...
    'range_gate_start_m', 'range_gate_end_m', 'range_spacing_m', ...
    'range_resolution_m', 'aperture_length_m', 'platform_spacing_m', ...
    'target_cross_range_m', 'target_ground_range_m', 'target_voltage', ...
    'target_initial_phase_rad', 'noise_rms_voltage', ...
    'max_aperture_samples', 'max_range_samples', 'max_image_pixels', ...
    'max_sweep_cases', 'max_private_values', ...
    'max_interpolation_operations', 'max_image_operations', ...
    'max_total_operations', 'max_working_values', 'max_figures', ...
    'max_phase_step_rad'};
for field_index = 1:numel(required_scalars)
    value = controls.(required_scalars{field_index});
    assert(isnumeric(value) && isreal(value) && isscalar(value) && ...
        isfinite(value), 'P78:MalformedScalar', ...
        'Every scalar control must be finite, real, numeric, and scalar.');
end
required_vectors = {'aperture_length_sweep_m', ...
    'squint_offset_sweep_m', 'image_cross_range_m', ...
    'image_ground_range_m'};
for field_index = 1:numel(required_vectors)
    value = controls.(required_vectors{field_index});
    assert(isnumeric(value) && isreal(value) && isrow(value) && ...
        ~isempty(value) && all(isfinite(value)), 'P78:MalformedVector', ...
        'Sweep and image axes must be finite real numeric row vectors.');
end
assert(controls.seed == floor(controls.seed) && controls.seed >= 1 && ...
    controls.seed < 2147483647, 'P78:Seed', ...
    'The private deterministic seed must be an integer in the LCG domain.');
positive_scalars = {'c_mps', 'carrier_hz', 'range_spacing_m', ...
    'range_resolution_m', 'aperture_length_m', 'platform_spacing_m', ...
    'target_ground_range_m', 'target_voltage', 'max_aperture_samples', ...
    'max_range_samples', 'max_image_pixels', 'max_sweep_cases', ...
    'max_private_values', 'max_interpolation_operations', ...
    'max_image_operations', 'max_total_operations', ...
    'max_working_values', 'max_figures', 'max_phase_step_rad'};
for field_index = 1:numel(positive_scalars)
    assert(controls.(positive_scalars{field_index}) > 0, ...
        'P78:NonpositiveControl', ...
        'Physical values and resource ceilings must be positive.');
end
assert(controls.noise_rms_voltage >= 0 && ...
    controls.range_gate_end_m > controls.range_gate_start_m && ...
    controls.range_resolution_m >= controls.range_spacing_m, ...
    'P78:RangeNoiseContract', ...
    'Noise and range-grid controls are inconsistent.');
assert(all(diff(controls.aperture_length_sweep_m) > 0) && ...
    all(diff(controls.squint_offset_sweep_m) > 0) && ...
    all(diff(controls.image_cross_range_m) > 0) && ...
    all(diff(controls.image_ground_range_m) > 0), ...
    'P78:OrderedControls', ...
    'Sweep and image vectors must be strictly increasing.');
assert(numel(controls.aperture_length_sweep_m) == 3 && ...
    numel(controls.squint_offset_sweep_m) == 3 && ...
    controls.aperture_length_sweep_m(end) == controls.aperture_length_m && ...
    controls.squint_offset_sweep_m(2) == controls.target_cross_range_m, ...
    'P78:SweepContract', ...
    'Each sweep needs three cases and must contain the baseline.');
assert(numel(controls.image_cross_range_m) >= 3 && ...
    numel(controls.image_ground_range_m) >= 3 && ...
    any(abs(controls.image_cross_range_m- ...
    controls.target_cross_range_m) < 1.0e-12) && ...
    any(abs(controls.image_ground_range_m- ...
    controls.target_ground_range_m) < 1.0e-12), ...
    'P78:ImageGrid', ...
    'The image grid must have support and contain the target coordinates.');

aperture_steps = controls.aperture_length_m/controls.platform_spacing_m;
range_steps = (controls.range_gate_end_m-controls.range_gate_start_m)/ ...
    controls.range_spacing_m;
assert(abs(aperture_steps-round(aperture_steps)) < 1.0e-9 && ...
    abs(range_steps-round(range_steps)) < 1.0e-9, 'P78:GridEndpoints', ...
    'Aperture and range endpoints must land exactly on their grids.');
aperture_sample_count = round(aperture_steps)+1;
range_sample_count = round(range_steps)+1;
image_pixel_count = numel(controls.image_cross_range_m)* ...
    numel(controls.image_ground_range_m);
assert(aperture_sample_count <= controls.max_aperture_samples && ...
    range_sample_count <= controls.max_range_samples && ...
    image_pixel_count <= controls.max_image_pixels && ...
    max(numel(controls.aperture_length_sweep_m), ...
    numel(controls.squint_offset_sweep_m)) <= controls.max_sweep_cases, ...
    'P78:SampleCeilings', ...
    'A sample, pixel, or sweep ceiling would be exceeded.');
assert(2*aperture_sample_count*range_sample_count <= ...
    controls.max_private_values, 'P78:PrivateNoiseBound', ...
    'Private complex noise needs two bounded uniforms per value.');

wavelength_m = controls.c_mps/controls.carrier_hz;
platform_position_m = -controls.aperture_length_m/2: ...
    controls.platform_spacing_m:controls.aperture_length_m/2;
target_slant_range_m = hypot(platform_position_m- ...
    controls.target_cross_range_m, controls.target_ground_range_m);
target_phase_rad = -4*pi*target_slant_range_m/wavelength_m;
assert(max(abs(diff(target_phase_rad))) < controls.max_phase_step_rad, ...
    'P78:SpatialPhaseSampling', ...
    'Platform spacing aliases the modeled two-way aperture phase.');
for case_index = 1:numel(controls.squint_offset_sweep_m)
    case_slant_range_m = hypot(platform_position_m- ...
        controls.squint_offset_sweep_m(case_index), ...
        controls.target_ground_range_m);
    case_phase_rad = -4*pi*case_slant_range_m/wavelength_m;
    assert(max(abs(diff(case_phase_rad))) < controls.max_phase_step_rad, ...
        'P78:SweepSpatialPhaseSampling', ...
        'A squint sweep case aliases the modeled two-way aperture phase.');
end
maximum_range_offset_m = max(target_slant_range_m)- ...
    min(target_slant_range_m);
wrong_sign_minimum_m = min(target_slant_range_m)-maximum_range_offset_m- ...
    2*controls.range_resolution_m;
wrong_sign_maximum_m = max(target_slant_range_m)+maximum_range_offset_m+ ...
    2*controls.range_resolution_m;
assert(wrong_sign_minimum_m > controls.range_gate_start_m && ...
    wrong_sign_maximum_m < controls.range_gate_end_m, ...
    'P78:RangeSupport', ...
    'The gate must retain baseline and wrong-sign migrated responses.');

reference_platform_m = 0;
[image_x_grid_m, image_y_grid_m] = meshgrid( ...
    controls.image_cross_range_m, controls.image_ground_range_m);
reference_image_range_m = hypot(reference_platform_m-image_x_grid_m, ...
    image_y_grid_m);
minimum_image_range_m = inf;
maximum_image_range_m = -inf;
for aperture_index = 1:aperture_sample_count
    predicted_range_m = hypot(platform_position_m(aperture_index)- ...
        image_x_grid_m, image_y_grid_m);
    minimum_image_range_m = min(minimum_image_range_m, ...
        min(predicted_range_m(:)));
    maximum_image_range_m = max(maximum_image_range_m, ...
        max(predicted_range_m(:)));
end
minimum_image_range_m = min(minimum_image_range_m, ...
    min(reference_image_range_m(:)));
maximum_image_range_m = max(maximum_image_range_m, ...
    max(reference_image_range_m(:)));
assert(minimum_image_range_m > controls.range_gate_start_m+ ...
    controls.range_spacing_m && maximum_image_range_m < ...
    controls.range_gate_end_m-controls.range_spacing_m, ...
    'P78:ImageRangeSupport', ...
    'Every fixed and path-following image sample needs interpolation support.');

interpolation_operations = 3*aperture_sample_count*range_sample_count;
image_operations = 2*aperture_sample_count*image_pixel_count;
total_operations = interpolation_operations+image_operations;
predicted_working_value_equivalents = ...
    24*aperture_sample_count*range_sample_count+20*image_pixel_count;
assert(interpolation_operations <= controls.max_interpolation_operations && ...
    image_operations <= controls.max_image_operations && ...
    total_operations <= controls.max_total_operations, ...
    'P78:OperationPreflight', ...
    'Correction, failure, recovery, or image work exceeds its ceiling.');
assert(predicted_working_value_equivalents <= controls.max_working_values, ...
    'P78:WorkingPreflight', ...
    'Predicted live workspace exceeds its eight-byte value ceiling.');
assert(controls.max_figures == 6, 'P78:FigureCeiling', ...
    'The reviewed experiment retains exactly six figure groups.');
predicted = struct('interpolation', interpolation_operations, ...
    'image', image_operations, 'total', total_operations, ...
    'working_values', predicted_working_value_equivalents);
end

