%% Local functions keep the essential nonlinear operation visible
function track = run_range_bearing_ekf(measurement, sample_interval_s, ...
        process_acceleration_std_mps2, range_std_m, bearing_std_deg, ...
        initial_state, initial_covariance, minimum_range_m, wrap_innovation)
    validate_filter_inputs(measurement, sample_interval_s, ...
        process_acceleration_std_mps2, range_std_m, bearing_std_deg, ...
        initial_state, initial_covariance, minimum_range_m, wrap_innovation);

    sample_count = size(measurement, 2);
    F_local = [1 sample_interval_s 0 0; 0 1 0 0; ...
        0 0 1 sample_interval_s; 0 0 0 1];
    G_local = [0.5*sample_interval_s^2 0; sample_interval_s 0; ...
        0 0.5*sample_interval_s^2; 0 sample_interval_s];
    Q_local = process_acceleration_std_mps2^2*(G_local*G_local');
    bearing_std_rad = bearing_std_deg*pi/180;
    R_local = diag([range_std_m^2 bearing_std_rad^2]);
    identity_state = eye(4);

    state_prediction = zeros(4, sample_count);
    state_estimate = zeros(4, sample_count);
    posterior_covariance = zeros(4, 4, sample_count);
    posterior_variance = zeros(4, sample_count);
    predicted_measurement = NaN(2, sample_count);
    innovation = NaN(2, sample_count);
    innovation_covariance = NaN(2, 2, sample_count);
    kalman_gain = NaN(4, 2, sample_count);
    nis = NaN(1, sample_count);

    state_prediction(:, 1) = initial_state;
    state_estimate(:, 1) = initial_state;
    covariance_estimate = initial_covariance;
    posterior_covariance(:, :, 1) = covariance_estimate;
    posterior_variance(:, 1) = diag(covariance_estimate);

    for sample_index = 2:sample_count
        state_prediction(:, sample_index) = ...
            F_local*state_estimate(:, sample_index-1);
        covariance_prediction = ...
            F_local*covariance_estimate*F_local' + Q_local;

        predicted_x_m = state_prediction(1, sample_index);
        predicted_y_m = state_prediction(3, sample_index);
        predicted_range_squared_m2 = predicted_x_m^2 + predicted_y_m^2;
        if predicted_range_squared_m2 <= minimum_range_m^2
            error('P56:LinearizationSingularity', ...
                'Predicted position is too close to the radar for this EKF Jacobian.');
        end
        predicted_range_m = sqrt(predicted_range_squared_m2);
        predicted_measurement(:, sample_index) = [predicted_range_m; ...
            atan2(predicted_y_m, predicted_x_m)];

        H_local = [predicted_x_m/predicted_range_m 0 ...
            predicted_y_m/predicted_range_m 0; ...
            -predicted_y_m/predicted_range_squared_m2 0 ...
            predicted_x_m/predicted_range_squared_m2 0];
        innovation(:, sample_index) = measurement(:, sample_index) - ...
            predicted_measurement(:, sample_index);
        if wrap_innovation
            innovation(2, sample_index) = atan2( ...
                sin(innovation(2, sample_index)), ...
                cos(innovation(2, sample_index)));
        end
        innovation_covariance(:, :, sample_index) = ...
            H_local*covariance_prediction*H_local' + R_local;
        current_innovation_covariance = ...
            innovation_covariance(:, :, sample_index);
        if any(~isfinite(current_innovation_covariance(:))) || ...
                current_innovation_covariance(1, 1) <= 0 || ...
                current_innovation_covariance(2, 2) <= 0 || ...
                det(current_innovation_covariance) <= 0
            error('P56:InvalidInnovationCovariance', ...
                'Innovation covariance must remain finite and positive definite.');
        end
        kalman_gain(:, :, sample_index) = ...
            (covariance_prediction*H_local')/ ...
            innovation_covariance(:, :, sample_index);

        state_estimate(:, sample_index) = state_prediction(:, sample_index) + ...
            kalman_gain(:, :, sample_index)*innovation(:, sample_index);
        if any(~isfinite(state_estimate(:, sample_index)))
            error('P56:InvalidPosteriorState', ...
                'Posterior state must remain finite after correction.');
        end
        joseph_factor = identity_state - kalman_gain(:, :, sample_index)*H_local;
        covariance_estimate = joseph_factor*covariance_prediction*joseph_factor' + ...
            kalman_gain(:, :, sample_index)*R_local* ...
            kalman_gain(:, :, sample_index)';
        covariance_estimate = 0.5*(covariance_estimate + covariance_estimate');
        if any(~isfinite(covariance_estimate(:))) || ...
                any(eig(covariance_estimate) < -1e-8)
            error('P56:InvalidPosteriorCovariance', ...
                'Posterior covariance must remain finite and positive semidefinite.');
        end
        posterior_covariance(:, :, sample_index) = covariance_estimate;
        posterior_variance(:, sample_index) = diag(covariance_estimate);
        nis(sample_index) = innovation(:, sample_index)'/ ...
            innovation_covariance(:, :, sample_index)*innovation(:, sample_index);
        if ~isfinite(nis(sample_index)) || nis(sample_index) < 0
            error('P56:InvalidNIS', ...
                'Normalized innovation squared must remain finite and nonnegative.');
        end
    end

    track = struct();
    track.state_prediction = state_prediction;
    track.state_estimate = state_estimate;
    track.posterior_covariance = posterior_covariance;
    track.posterior_variance = posterior_variance;
    track.predicted_measurement = predicted_measurement;
    track.innovation = innovation;
    track.innovation_covariance = innovation_covariance;
    track.kalman_gain = kalman_gain;
    track.nis = nis;
end

function validate_filter_inputs(measurement, sample_interval_s, ...
        process_acceleration_std_mps2, range_std_m, bearing_std_deg, ...
        initial_state, initial_covariance, minimum_range_m, wrap_innovation)
    maximum_supported_range_m = 1e7;
    maximum_supported_state_magnitude = 1e7;
    maximum_supported_covariance_magnitude = 1e14;
    maximum_supported_standard_deviation = 1e6;
    if ~isnumeric(measurement) || ~isa(measurement, 'double') || ...
            ~isreal(measurement) || ...
            islogical(measurement) || size(measurement, 1) ~= 2 || ...
            size(measurement, 2) < 2 || any(~isfinite(measurement(:))) || ...
            any(measurement(1, :) <= 0) || ...
            any(measurement(1, :) > maximum_supported_range_m) || ...
            any(measurement(2, :) < -pi | measurement(2, :) > pi)
        error('P56:InvalidMeasurement', ...
            'Measurement must be a finite 2-by-N [positive range; bearing in +/-pi] matrix.');
    end
    if ~isa(sample_interval_s, 'double') || ...
            ~isa(process_acceleration_std_mps2, 'double') || ...
            ~isa(range_std_m, 'double') || ~isa(bearing_std_deg, 'double') || ...
            ~isa(minimum_range_m, 'double')
        error('P56:InvalidNumericClass', ...
            'Filter interval, noise scales, and range guard must use double precision.');
    end
    scalar_inputs = [sample_interval_s process_acceleration_std_mps2 ...
        range_std_m bearing_std_deg minimum_range_m];
    if ~isscalar(sample_interval_s) || ...
            ~isscalar(process_acceleration_std_mps2) || ...
            ~isscalar(range_std_m) || ~isscalar(bearing_std_deg) || ...
            ~isscalar(minimum_range_m) || islogical(sample_interval_s) || ...
            islogical(process_acceleration_std_mps2) || islogical(range_std_m) || ...
            islogical(bearing_std_deg) || islogical(minimum_range_m) || ...
            ~isreal(scalar_inputs) || any(~isfinite(scalar_inputs)) || ...
            sample_interval_s <= 0 || process_acceleration_std_mps2 < 0 || ...
            range_std_m <= 0 || bearing_std_deg <= 0 || minimum_range_m <= 0 || ...
            process_acceleration_std_mps2 > maximum_supported_standard_deviation || ...
            range_std_m > maximum_supported_standard_deviation || ...
            bearing_std_deg > 180 || ...
            minimum_range_m > maximum_supported_range_m
        error('P56:InvalidNoiseModel', ...
            'Interval, process scale, measurement scales, and minimum range have invalid domains.');
    end
    if ~isnumeric(initial_state) || ~isa(initial_state, 'double') || ...
            ~isreal(initial_state) || ...
            islogical(initial_state) || ~isequal(size(initial_state), [4 1]) || ...
            any(~isfinite(initial_state)) || ...
            any(abs(initial_state) > maximum_supported_state_magnitude) || ...
            hypot(initial_state(1), initial_state(3)) <= minimum_range_m
        error('P56:InvalidInitialState', ...
            'Initial state must be finite, real, 4-by-1, and outside minimum range.');
    end
    if ~isnumeric(initial_covariance) || ~isa(initial_covariance, 'double') || ...
            ~isreal(initial_covariance) || ...
            islogical(initial_covariance) || ...
            ~isequal(size(initial_covariance), [4 4]) || ...
            any(~isfinite(initial_covariance(:))) || ...
            any(abs(initial_covariance(:)) > maximum_supported_covariance_magnitude) || ...
            max(max(abs(initial_covariance - initial_covariance'))) > 1e-10 || ...
            any(eig(initial_covariance) < -1e-10)
        error('P56:InvalidInitialCovariance', ...
            'Initial covariance must be finite, real, symmetric, and positive semidefinite.');
    end
    if ~islogical(wrap_innovation) || ~isscalar(wrap_innovation)
        error('P56:InvalidWrapControl', ...
            'Angle-wrap control must be a logical scalar.');
    end
end

function wrapped = wrap_angle(angle_rad)
    if ~isnumeric(angle_rad) || ~isreal(angle_rad) || islogical(angle_rad) || ...
            any(~isfinite(angle_rad(:)))
        error('P56:InvalidAngle', 'Angle input must be finite, real, and numeric.');
    end
    wrapped = atan2(sin(angle_rad), cos(angle_rad));
end

function validate_positive_sweep(values, baseline, maximum_cases, label)
    if ~isnumeric(values) || ~isreal(values) || islogical(values) || ...
            ~isrow(values) || numel(values) < 3 || ...
            numel(values) > maximum_cases || any(~isfinite(values)) || ...
            any(values <= 0) || any(diff(values) <= 0) || ...
            ~any(values == baseline) || ~ischar(label)
        error('P56:InvalidSweep', ...
            'Each sweep must be a finite positive increasing row with its baseline.');
    end
end

function ellipse_xy = covariance_ellipse(center_xy, covariance_xy, scale, point_count)
    if ~isnumeric(center_xy) || ~isreal(center_xy) || islogical(center_xy) || ...
            ~isequal(size(center_xy), [2 1]) || any(~isfinite(center_xy)) || ...
            ~isnumeric(covariance_xy) || ~isreal(covariance_xy) || ...
            islogical(covariance_xy) || ~isequal(size(covariance_xy), [2 2]) || ...
            any(~isfinite(covariance_xy(:))) || ...
            max(max(abs(covariance_xy-covariance_xy'))) > 1e-10 || ...
            any(eig(covariance_xy) < -1e-10) || ~isscalar(scale) || ...
            ~isnumeric(scale) || ~isreal(scale) || islogical(scale) || ...
            ~isfinite(scale) || scale <= 0 || ~isscalar(point_count) || ...
            ~isnumeric(point_count) || ~isreal(point_count) || ...
            islogical(point_count) || ~isfinite(point_count) || ...
            point_count ~= floor(point_count) || point_count < 5 || point_count > 73
        error('P56:InvalidEllipseInput', ...
            'Ellipse inputs must be finite, bounded, and covariance-consistent.');
    end
    [eigenvectors, eigenvalues] = eig(0.5*(covariance_xy+covariance_xy'));
    angles = linspace(0, 2*pi, point_count);
    unit_circle = [cos(angles); sin(angles)];
    ellipse_xy = center_xy + scale*eigenvectors* ...
        diag(sqrt(max(diag(eigenvalues), 0)))*unit_circle;
end

function value = root_mean_square(samples)
    if isempty(samples) || ~isnumeric(samples) || ~isreal(samples) || ...
            islogical(samples) || any(~isfinite(samples(:)))
        error('P56:InvalidMetricInput', ...
            'RMS input must be nonempty, finite, real, and numeric.');
    end
    value = sqrt(mean(samples(:).^2));
end
