%% P56: Use an EKF for Range-Bearing Measurements
% Guiding question: How can nonlinear radar measurements update Cartesian target state?
% Dependency: P55 supplies constant-velocity covariance prediction and correction.
% P56 assumes one range-bearing report is already associated to one track.
% This script uses base MATLAB only.

clear;
clc;

%% Visible controls and fixed resource ceilings
random_seed = 5601;
number_scans = 101;
scan_interval_s = 1;
initial_true_x_m = -1600;
initial_true_vx_mps = 4;
initial_true_y_m = 600;
initial_true_vy_mps = -12;
actual_process_acceleration_std_mps2 = 0.25;
actual_range_std_m = 18;
actual_bearing_std_deg = 0.8;
initial_velocity_std_mps = 20;
warmup_scans = 15;

assumed_process_acceleration_std_mps2 = 0.25;
assumed_range_std_m = 18;
assumed_bearing_std_deg = 0.8;
bearing_std_sweep_deg = [0.2 0.8 3.2];
geometry_range_sweep_m = [500 1500 3000];
minimum_linearization_range_m = 25;
ellipse_probability_scale = sqrt(5.991);

maximum_number_scans = 200;
maximum_sweep_cases = 5;
maximum_figure_count = 5;
maximum_filter_updates = 700;
maximum_ellipse_points = 73;
ellipse_point_count = 73;

integer_controls = [random_seed number_scans warmup_scans ...
    maximum_number_scans maximum_sweep_cases maximum_figure_count ...
    maximum_filter_updates maximum_ellipse_points ellipse_point_count];
if ~isscalar(random_seed) || ~isscalar(number_scans) || ...
        ~isscalar(warmup_scans) || ~isscalar(maximum_number_scans) || ...
        ~isscalar(maximum_sweep_cases) || ~isscalar(maximum_figure_count) || ...
        ~isscalar(maximum_filter_updates) || ~isscalar(maximum_ellipse_points) || ...
        ~isscalar(ellipse_point_count) || islogical(random_seed) || ...
        islogical(number_scans) || islogical(warmup_scans) || ...
        islogical(maximum_number_scans) || islogical(maximum_sweep_cases) || ...
        islogical(maximum_figure_count) || islogical(maximum_filter_updates) || ...
        islogical(maximum_ellipse_points) || islogical(ellipse_point_count) || ...
        ~isreal(integer_controls) || any(~isfinite(integer_controls)) || ...
        any(integer_controls ~= floor(integer_controls))
    error('P56:InvalidIntegerControl', ...
        'Seed, counts, and resource ceilings must be finite nonlogical integers.');
end
if random_seed ~= 5601 || number_scans ~= 101 || ...
        number_scans > maximum_number_scans
    error('P56:ReviewedScene', ...
        'The reviewed deterministic scene requires seed 5601 and 101 scans within its bound.');
end
if maximum_number_scans ~= 200 || maximum_sweep_cases ~= 5 || ...
        maximum_figure_count ~= 5 || maximum_filter_updates ~= 700 || ...
        maximum_ellipse_points ~= 73 || ellipse_point_count ~= 73
    error('P56:CeilingDrift', 'Fixed resource ceilings must not be changed.');
end
if warmup_scans < 1 || warmup_scans >= number_scans - 2
    error('P56:InvalidWarmup', 'Warm-up must leave at least three evaluation scans.');
end

real_controls = [scan_interval_s initial_true_x_m initial_true_vx_mps ...
    initial_true_y_m initial_true_vy_mps ...
    actual_process_acceleration_std_mps2 actual_range_std_m ...
    actual_bearing_std_deg initial_velocity_std_mps ...
    assumed_process_acceleration_std_mps2 assumed_range_std_m ...
    assumed_bearing_std_deg minimum_linearization_range_m ...
    ellipse_probability_scale];
if ~isscalar(scan_interval_s) || ~isscalar(initial_true_x_m) || ...
        ~isscalar(initial_true_vx_mps) || ~isscalar(initial_true_y_m) || ...
        ~isscalar(initial_true_vy_mps) || ...
        ~isscalar(actual_process_acceleration_std_mps2) || ...
        ~isscalar(actual_range_std_m) || ~isscalar(actual_bearing_std_deg) || ...
        ~isscalar(initial_velocity_std_mps) || ...
        ~isscalar(assumed_process_acceleration_std_mps2) || ...
        ~isscalar(assumed_range_std_m) || ...
        ~isscalar(assumed_bearing_std_deg) || ...
        ~isscalar(minimum_linearization_range_m) || ...
        ~isscalar(ellipse_probability_scale) || islogical(scan_interval_s) || ...
        islogical(initial_true_x_m) || islogical(initial_true_vx_mps) || ...
        islogical(initial_true_y_m) || islogical(initial_true_vy_mps) || ...
        islogical(actual_process_acceleration_std_mps2) || ...
        islogical(actual_range_std_m) || islogical(actual_bearing_std_deg) || ...
        islogical(initial_velocity_std_mps) || ...
        islogical(assumed_process_acceleration_std_mps2) || ...
        islogical(assumed_range_std_m) || ...
        islogical(assumed_bearing_std_deg) || ...
        islogical(minimum_linearization_range_m) || ...
        islogical(ellipse_probability_scale) || ~isreal(real_controls) || ...
        any(~isfinite(real_controls))
    error('P56:InvalidRealControl', ...
        'Physical, uncertainty, and tuning controls must be finite real nonlogical scalars.');
end
if scan_interval_s ~= 1 || scan_interval_s <= 0 || ...
        actual_process_acceleration_std_mps2 < 0 || actual_range_std_m <= 0 || ...
        actual_bearing_std_deg <= 0 || initial_velocity_std_mps <= 0 || ...
        assumed_process_acceleration_std_mps2 < 0 || assumed_range_std_m <= 0 || ...
        assumed_bearing_std_deg <= 0 || minimum_linearization_range_m <= 0 || ...
        ellipse_probability_scale <= 0
    error('P56:InvalidPhysicalControl', ...
        'Intervals, ranges, scales, and standard deviations must have valid domains.');
end
if initial_true_x_m ~= -1600 || initial_true_vx_mps ~= 4 || ...
        initial_true_y_m ~= 600 || initial_true_vy_mps ~= -12 || ...
        actual_process_acceleration_std_mps2 ~= 0.25 || actual_range_std_m ~= 18 || ...
        actual_bearing_std_deg ~= 0.8 || ...
        assumed_process_acceleration_std_mps2 ~= 0.25 || ...
        assumed_range_std_m ~= 18 || assumed_bearing_std_deg ~= 0.8 || ...
        minimum_linearization_range_m ~= 25 || ...
        abs(ellipse_probability_scale - sqrt(5.991)) > 1e-12
    error('P56:TuningDrift', ...
        'Restore the reviewed truth, measurement, EKF, and ellipse controls.');
end
validate_positive_sweep(bearing_std_sweep_deg, assumed_bearing_std_deg, ...
    maximum_sweep_cases, 'bearing standard deviation');
validate_positive_sweep(geometry_range_sweep_m, 1500, ...
    maximum_sweep_cases, 'geometry range');

filter_run_count = 1 + numel(bearing_std_sweep_deg) + 1 + 1;
reviewed_filter_updates = filter_run_count*(number_scans - 1);
if reviewed_filter_updates > maximum_filter_updates
    error('P56:FilterUpdateBound', ...
        'Baseline, sweep, failure, and recovery exceed the filter-update ceiling.');
end

% Validation above precedes random work, state-history allocation, and figures.
close(findobj(groot, 'Type', 'figure', 'Tag', 'P56'));

%% Deterministic target and noisy polar measurements
% Cartesian state: x = [px; vx; py; vy]. Radar measurement:
% h(x) = [sqrt(px^2+py^2); atan2(py,px)].
F = [1 scan_interval_s 0 0; 0 1 0 0; ...
    0 0 1 scan_interval_s; 0 0 0 1];
G = [0.5*scan_interval_s^2 0; scan_interval_s 0; ...
    0 0.5*scan_interval_s^2; 0 scan_interval_s];
time_s = (0:number_scans-1)*scan_interval_s;
true_state = zeros(4, number_scans);
true_state(:, 1) = [initial_true_x_m; initial_true_vx_mps; ...
    initial_true_y_m; initial_true_vy_mps];

private_stream = RandStream('mt19937ar', 'Seed', random_seed);
actual_acceleration_mps2 = actual_process_acceleration_std_mps2* ...
    randn(private_stream, 2, number_scans-1);
for scan_index = 2:number_scans
    true_state(:, scan_index) = F*true_state(:, scan_index-1) + ...
        G*actual_acceleration_mps2(:, scan_index-1);
end
true_range_m = hypot(true_state(1, :), true_state(3, :));
true_bearing_rad = atan2(true_state(3, :), true_state(1, :));
range_noise_m = actual_range_std_m*randn(private_stream, 1, number_scans);
bearing_noise_rad = actual_bearing_std_deg*pi/180* ...
    randn(private_stream, 1, number_scans);
measurement_range_m = true_range_m + range_noise_m;
measurement_bearing_rad = wrap_angle(true_bearing_rad + bearing_noise_rad);
polar_measurement = [measurement_range_m; measurement_bearing_rad];
raw_cartesian_x_m = measurement_range_m.*cos(measurement_bearing_rad);
raw_cartesian_y_m = measurement_range_m.*sin(measurement_bearing_rad);

figure('Name', 'P56 Figure 1: polar measurements and Cartesian conversion', 'Tag', 'P56');
subplot(2, 2, [1 3]);
plot(true_state(1, :), true_state(3, :), 'k-', 'LineWidth', 1.7); hold on;
plot(raw_cartesian_x_m, raw_cartesian_y_m, '.', 'Color', [0.25 0.55 0.9]);
plot(0, 0, 'rp', 'MarkerSize', 11, 'MarkerFaceColor', 'r');
axis equal; grid on;
xlabel('Cartesian x (m)'); ylabel('Cartesian y (m)');
title('The radar reports polar samples, not Cartesian position');
legend('Truth', 'Raw polar-to-Cartesian report', 'Radar', 'Location', 'best');
subplot(2, 2, 2);
plot(time_s, true_range_m, 'k-', 'LineWidth', 1.3); hold on;
plot(time_s, measurement_range_m, '.', 'Color', [0.25 0.55 0.9]);
xlabel('Time (s)'); ylabel('Range (m)');
title('Noisy range reports'); legend('Truth', 'Report', 'Location', 'best'); grid on;
subplot(2, 2, 4);
plot(time_s, true_bearing_rad*180/pi, 'k-', 'LineWidth', 1.3); hold on;
plot(time_s, measurement_bearing_rad*180/pi, '.', 'Color', [0.8 0.3 0.15]);
xlabel('Time (s)'); ylabel('Bearing (deg)');
title('The same direction wraps at +/-180 degrees');
legend('Truth', 'Report', 'Location', 'best'); grid on;

%% Initialize Cartesian state and covariance from the first polar report
assumed_bearing_std_rad = assumed_bearing_std_deg*pi/180;
initial_polar_to_cartesian_jacobian = [ ...
    cos(measurement_bearing_rad(1)) -measurement_range_m(1)*sin(measurement_bearing_rad(1)); ...
    sin(measurement_bearing_rad(1)) measurement_range_m(1)*cos(measurement_bearing_rad(1))];
initial_polar_covariance = diag([assumed_range_std_m^2 assumed_bearing_std_rad^2]);
initial_cartesian_position_covariance = initial_polar_to_cartesian_jacobian* ...
    initial_polar_covariance*initial_polar_to_cartesian_jacobian';
initial_state_estimate = [raw_cartesian_x_m(1); 0; raw_cartesian_y_m(1); 0];
initial_covariance = zeros(4, 4);
initial_covariance([1 3], [1 3]) = initial_cartesian_position_covariance;
initial_covariance(2, 2) = initial_velocity_std_mps^2;
initial_covariance(4, 4) = initial_velocity_std_mps^2;

baseline = run_range_bearing_ekf(polar_measurement, scan_interval_s, ...
    assumed_process_acceleration_std_mps2, assumed_range_std_m, ...
    assumed_bearing_std_deg, initial_state_estimate, initial_covariance, ...
    minimum_linearization_range_m, true);

%% Baseline Cartesian track and changing covariance shape
evaluation_indices = warmup_scans+1:number_scans;
baseline_x_error_m = baseline.state_estimate(1, :) - true_state(1, :);
baseline_y_error_m = baseline.state_estimate(3, :) - true_state(3, :);
baseline_position_error_m = hypot(baseline_x_error_m, baseline_y_error_m);
raw_position_error_m = hypot(raw_cartesian_x_m - true_state(1, :), ...
    raw_cartesian_y_m - true_state(3, :));
raw_position_rmse_m = root_mean_square(raw_position_error_m(evaluation_indices));
baseline_position_rmse_m = root_mean_square( ...
    baseline_position_error_m(evaluation_indices));

baseline_position_ellipse_coverage = zeros(1, numel(evaluation_indices));
baseline_radial_sigma_m = zeros(1, numel(evaluation_indices));
baseline_tangential_sigma_m = zeros(1, numel(evaluation_indices));
for metric_index = 1:numel(evaluation_indices)
    scan_index = evaluation_indices(metric_index);
    position_covariance = baseline.posterior_covariance([1 3], [1 3], scan_index);
    position_error = [baseline_x_error_m(scan_index); baseline_y_error_m(scan_index)];
    squared_position_distance = position_error'/position_covariance*position_error;
    baseline_position_ellipse_coverage(metric_index) = ...
        squared_position_distance <= ellipse_probability_scale^2;
    radial_unit = true_state([1 3], scan_index)/true_range_m(scan_index);
    tangential_unit = [-radial_unit(2); radial_unit(1)];
    baseline_radial_sigma_m(metric_index) = sqrt( ...
        radial_unit'*position_covariance*radial_unit);
    baseline_tangential_sigma_m(metric_index) = sqrt( ...
        tangential_unit'*position_covariance*tangential_unit);
end
baseline_position_coverage = mean(baseline_position_ellipse_coverage);

figure('Name', 'P56 Figure 2: EKF trajectory and covariance ellipses', 'Tag', 'P56');
subplot(2, 1, 1);
truth_handle = plot(true_state(1, :), true_state(3, :), ...
    'k-', 'LineWidth', 1.7); hold on;
raw_handle = plot(raw_cartesian_x_m, raw_cartesian_y_m, ...
    '.', 'Color', [0.75 0.82 0.92]);
ekf_handle = plot(baseline.state_estimate(1, :), baseline.state_estimate(3, :), ...
    'b-', 'LineWidth', 1.4);
ellipse_scans = [1 21 41 61 81 101];
for ellipse_index = 1:numel(ellipse_scans)
    scan_index = ellipse_scans(ellipse_index);
    ellipse_xy = covariance_ellipse( ...
        baseline.state_estimate([1 3], scan_index), ...
        baseline.posterior_covariance([1 3], [1 3], scan_index), ...
        ellipse_probability_scale, ellipse_point_count);
    if ellipse_index == 1
        ellipse_handle = plot(ellipse_xy(1, :), ellipse_xy(2, :), ...
            'Color', [0.1 0.55 0.25]);
    else
        plot(ellipse_xy(1, :), ellipse_xy(2, :), ...
            'Color', [0.1 0.55 0.25], 'HandleVisibility', 'off');
    end
end
radar_handle = plot(0, 0, 'rp', 'MarkerSize', 11, 'MarkerFaceColor', 'r');
axis equal; grid on;
xlabel('Cartesian x (m)'); ylabel('Cartesian y (m)');
title('EKF trajectory with selected 95% position covariance ellipses');
legend([truth_handle raw_handle ekf_handle ellipse_handle radar_handle], ...
    {'Truth', 'Raw conversion', 'EKF', '95% covariance ellipse', 'Radar'}, ...
    'Location', 'best');
subplot(2, 1, 2);
plot(time_s, raw_position_error_m, 'Color', [0.65 0.7 0.78]); hold on;
plot(time_s, baseline_position_error_m, 'b-', 'LineWidth', 1.3);
xlabel('Time (s)'); ylabel('Cartesian position error (m)');
title('Prediction plus nonlinear update smooths the raw converted reports');
legend('Raw conversion error', 'EKF error', 'Location', 'best'); grid on;

%% Innovations: compare different units with their own covariance
baseline_range_innovation_sigma_m = sqrt(baseline.innovation_covariance(1, 1, :));
baseline_range_innovation_sigma_m = reshape(baseline_range_innovation_sigma_m, 1, []);
baseline_bearing_innovation_sigma_deg = ...
    reshape(sqrt(baseline.innovation_covariance(2, 2, :)), 1, [])*180/pi;
baseline_bearing_innovation_deg = baseline.innovation(2, :)*180/pi;
baseline_mean_nis = mean(baseline.nis(evaluation_indices));
baseline_innovation_coverage = mean( ...
    baseline.nis(evaluation_indices) <= ellipse_probability_scale^2);

figure('Name', 'P56 Figure 3: wrapped innovations and consistency', 'Tag', 'P56');
subplot(3, 1, 1);
plot(time_s, baseline.innovation(1, :), 'Color', [0.45 0.1 0.65]); hold on;
plot(time_s, 2*baseline_range_innovation_sigma_m, 'k--');
plot(time_s, -2*baseline_range_innovation_sigma_m, 'k--');
xlabel('Time (s)'); ylabel('Range innovation (m)');
title('Range report minus nonlinear predicted range');
legend('Innovation', '+/- 2 sqrt(S_{rr})', 'Location', 'best'); grid on;
subplot(3, 1, 2);
plot(time_s, baseline_bearing_innovation_deg, 'Color', [0.8 0.3 0.15]); hold on;
plot(time_s, 2*baseline_bearing_innovation_sigma_deg, 'k--');
plot(time_s, -2*baseline_bearing_innovation_sigma_deg, 'k--');
xlabel('Time (s)'); ylabel('Wrapped bearing innovation (deg)');
title('atan2(sin(delta),cos(delta)) keeps the angular residual local');
legend('Innovation', '+/- 2 sqrt(S_{theta theta})', 'Location', 'best'); grid on;
subplot(3, 1, 3);
plot(time_s, baseline.nis, 'b-'); hold on;
plot(time_s, ellipse_probability_scale^2*ones(size(time_s)), 'r--');
xlabel('Time (s)'); ylabel('NIS (dimensionless)');
title('Joint range-bearing innovation against the 95% two-dimensional threshold');
legend('Innovation'' S^{-1} innovation', '95% chi-square threshold', ...
    'Location', 'best'); grid on;

%% Sweep 1: change only assumed bearing noise on the same polar reports
bearing_sweep_tracks = cell(1, numel(bearing_std_sweep_deg));
bearing_sweep_position_rmse_m = zeros(1, numel(bearing_std_sweep_deg));
bearing_sweep_mean_nis = zeros(1, numel(bearing_std_sweep_deg));
bearing_sweep_mean_tangential_sigma_m = zeros(1, numel(bearing_std_sweep_deg));
for sweep_index = 1:numel(bearing_std_sweep_deg)
    bearing_sweep_tracks{sweep_index} = run_range_bearing_ekf( ...
        polar_measurement, scan_interval_s, ...
        assumed_process_acceleration_std_mps2, assumed_range_std_m, ...
        bearing_std_sweep_deg(sweep_index), initial_state_estimate, ...
        initial_covariance, minimum_linearization_range_m, true);
    track = bearing_sweep_tracks{sweep_index};
    sweep_position_error_m = hypot( ...
        track.state_estimate(1, :) - true_state(1, :), ...
        track.state_estimate(3, :) - true_state(3, :));
    bearing_sweep_position_rmse_m(sweep_index) = root_mean_square( ...
        sweep_position_error_m(evaluation_indices));
    bearing_sweep_mean_nis(sweep_index) = mean(track.nis(evaluation_indices));
    sweep_tangential_sigma_m = zeros(1, numel(evaluation_indices));
    for metric_index = 1:numel(evaluation_indices)
        scan_index = evaluation_indices(metric_index);
        radial_unit = true_state([1 3], scan_index)/true_range_m(scan_index);
        tangential_unit = [-radial_unit(2); radial_unit(1)];
        position_covariance = track.posterior_covariance([1 3], [1 3], scan_index);
        sweep_tangential_sigma_m(metric_index) = sqrt( ...
            tangential_unit'*position_covariance*tangential_unit);
    end
    bearing_sweep_mean_tangential_sigma_m(sweep_index) = ...
        mean(sweep_tangential_sigma_m);
end

%% Sweep 2: hold angular accuracy fixed and move the same ray farther away
geometry_bearing_std_rad = assumed_bearing_std_deg*pi/180;
geometry_radial_sigma_m = assumed_range_std_m*ones(size(geometry_range_sweep_m));
geometry_tangential_sigma_m = geometry_range_sweep_m*geometry_bearing_std_rad;
geometry_major_sigma_m = zeros(size(geometry_range_sweep_m));
geometry_bearing_rad = 35*pi/180;
for sweep_index = 1:numel(geometry_range_sweep_m)
    range_value_m = geometry_range_sweep_m(sweep_index);
    conversion_jacobian = [cos(geometry_bearing_rad) -range_value_m*sin(geometry_bearing_rad); ...
        sin(geometry_bearing_rad) range_value_m*cos(geometry_bearing_rad)];
    cartesian_measurement_covariance = conversion_jacobian* ...
        diag([assumed_range_std_m^2 geometry_bearing_std_rad^2])* ...
        conversion_jacobian';
    geometry_major_sigma_m(sweep_index) = sqrt(max(eig( ...
        cartesian_measurement_covariance)));
end

figure('Name', 'P56 Figure 4: bearing-noise and geometry sweeps', 'Tag', 'P56');
subplot(2, 3, 1);
plot(bearing_std_sweep_deg, bearing_sweep_position_rmse_m, 'o-', 'LineWidth', 1.3);
xlabel('Assumed bearing std (deg)'); ylabel('Position RMSE (m)');
title('Sweep 1: same reports, different bearing trust'); grid on;
subplot(2, 3, 2);
plot(bearing_std_sweep_deg, bearing_sweep_mean_tangential_sigma_m, 's-', ...
    'LineWidth', 1.3);
xlabel('Assumed bearing std (deg)'); ylabel('Tangential sigma (m)');
title('Declared bearing noise changes cross-range uncertainty'); grid on;
subplot(2, 3, 3);
plot(bearing_std_sweep_deg, bearing_sweep_mean_nis, 'o-', 'LineWidth', 1.3);
xlabel('Assumed bearing std (deg)'); ylabel('Mean NIS (dimensionless)');
title('NIS exposes inconsistent bearing confidence'); grid on;
subplot(2, 3, [4 5 6]);
plot(geometry_range_sweep_m, geometry_radial_sigma_m, 'o-', 'LineWidth', 1.3); hold on;
plot(geometry_range_sweep_m, geometry_tangential_sigma_m, 's-', 'LineWidth', 1.3);
plot(geometry_range_sweep_m, geometry_major_sigma_m, 'd--', 'LineWidth', 1.1);
xlabel('Target range (m)'); ylabel('Local Cartesian 1-sigma uncertainty (m)');
title(sprintf('Sweep 2: %.1f deg bearing error grows with range', ...
    assumed_bearing_std_deg));
legend('Radial', 'Small-angle tangential r sigma_theta', ...
    'Jacobian-mapped major axis', 'Location', 'northwest'); grid on;

%% Broken case: subtract branch-cut angles without wrapping; then recover
broken_unwrapped = run_range_bearing_ekf(polar_measurement, scan_interval_s, ...
    assumed_process_acceleration_std_mps2, assumed_range_std_m, ...
    assumed_bearing_std_deg, initial_state_estimate, initial_covariance, ...
    minimum_linearization_range_m, false);
recovered = run_range_bearing_ekf(polar_measurement, scan_interval_s, ...
    assumed_process_acceleration_std_mps2, assumed_range_std_m, ...
    assumed_bearing_std_deg, initial_state_estimate, initial_covariance, ...
    minimum_linearization_range_m, true);
broken_position_error_m = hypot( ...
    broken_unwrapped.state_estimate(1, :) - true_state(1, :), ...
    broken_unwrapped.state_estimate(3, :) - true_state(3, :));
broken_position_rmse_m = root_mean_square( ...
    broken_position_error_m(evaluation_indices));
broken_max_bearing_innovation_deg = max(abs( ...
    broken_unwrapped.innovation(2, evaluation_indices)))*180/pi;

figure('Name', 'P56 Figure 5: broken angle residual and recovery', 'Tag', 'P56');
subplot(2, 2, [1 3]);
plot(true_state(1, :), true_state(3, :), 'k-', 'LineWidth', 1.7); hold on;
plot(baseline.state_estimate(1, :), baseline.state_estimate(3, :), ...
    'b-', 'LineWidth', 1.3);
plot(broken_unwrapped.state_estimate(1, :), ...
    broken_unwrapped.state_estimate(3, :), 'r--', 'LineWidth', 1.2);
plot(0, 0, 'rp', 'MarkerSize', 11, 'MarkerFaceColor', 'r');
axis equal; grid on;
xlabel('Cartesian x (m)'); ylabel('Cartesian y (m)');
title('A branch-cut residual can pull the track the long way around');
legend('Truth', 'Recovered wrapped EKF', 'Broken unwrapped EKF', 'Radar', ...
    'Location', 'best');
subplot(2, 2, 2);
plot(time_s, baseline_bearing_innovation_deg, 'b-'); hold on;
plot(time_s, broken_unwrapped.innovation(2, :)*180/pi, 'r--');
xlabel('Time (s)'); ylabel('Bearing innovation (deg)');
title('Local wrapped residual versus nearly 360-degree subtraction');
legend('Recovered', 'Broken', 'Location', 'best'); grid on;
subplot(2, 2, 4);
plot(time_s, baseline_position_error_m, 'b-'); hold on;
plot(time_s, broken_position_error_m, 'r--');
xlabel('Time (s)'); ylabel('Position error (m)');
title('Recovery reruns the same data with angle wrapping restored');
