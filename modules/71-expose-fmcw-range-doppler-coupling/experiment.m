grid on; xlabel('Time after echo overlap begins (us)');
ylabel('Real dechirped voltage (V/V)');
title('One complex beat contains both physical contributions');
subplot(2, 1, 2);
plot(signed_frequency_axis_hz/1e3, beat_spectrum_db, ...
    'LineWidth', 1.2); hold on;
plot(delay_beat_frequency_hz/1e3*[1 1], [plot_floor_db 0], 'k--');
plot(coupled_beat_frequency_hz/1e3*[1 1], [plot_floor_db 0], 'r--');
plot(measured_beat_frequency_hz/1e3, 0, 'ro', 'LineWidth', 1.3);
hold off; grid on; xlim([-50 220]); ylim([plot_floor_db 3]);
xlabel('Signed dechirped frequency (kHz)');
ylabel('Normalized magnitude (dB)');
legend('Measured spectrum', 'Delay-only contribution', ...
