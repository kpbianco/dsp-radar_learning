title('Delay and approaching Doppler both move the echo frequency');

%% Figure 2: preserve and display signed dechirped frequency
valid_time_s = time_s(overlap_mask)-time_s(overlap_start_index);
valid_beat = dechirped_beat(overlap_mask);
valid_window = 0.5-0.5*cos(2*pi*(0:overlap_count-1).' / ...
    (overlap_count-1));
spectrum_fft_count = 4*2^nextpow2(overlap_count);
signed_frequency_axis_hz = (-spectrum_fft_count/2: ...
    spectrum_fft_count/2-1).'*sample_rate_hz/spectrum_fft_count;
beat_spectrum = fftshift(fft(valid_beat.*valid_window, ...
    spectrum_fft_count))/sum(valid_window);
beat_spectrum_db = 20*log10(max(abs(beat_spectrum)/ ...
    max(abs(beat_spectrum)), 10^(plot_floor_db/20)));

figure('Name', 'P71 signed dechirped beat', 'Tag', 'P71');
subplot(2, 1, 1);
plot(valid_time_s(1:min(overlap_count, 600))*1e6, ...
