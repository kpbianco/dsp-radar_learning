transmit_instantaneous_frequency_hz = chirp_slope_hz_per_s* ...
    (time_s-chirp_duration_s/2);
echo_instantaneous_frequency_hz = chirp_slope_hz_per_s* ...
    (time_s-round_trip_delay_s-chirp_duration_s/2) + ...
    doppler_frequency_hz;
figure('Name', 'P71 transmitted and moving echo chirp', 'Tag', 'P71');
plot(time_s*1e6, transmit_instantaneous_frequency_hz/1e6, ...
