plot(time_s(overlap_mask)*1e6, ...
    echo_instantaneous_frequency_hz(overlap_mask)/1e6, ...
    'LineWidth', 1.3);
plot(round_trip_delay_s*1e6*[1 1], ...
    [-chirp_bandwidth_hz chirp_bandwidth_hz]/2e6, 'k--');
hold off; grid on;
xlabel('Fast time within up-chirp (us)');
ylabel('Instantaneous frequency relative to carrier (MHz)');
legend('Transmitted up-chirp', 'Delayed moving echo', ...
