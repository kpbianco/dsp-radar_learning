%% P71: Expose FMCW Range-Doppler Coupling
% Guiding question:
% Why can target motion bias the range estimated from one chirp?
%
% Base MATLAB only. The up-chirp, delayed Doppler-shifted echo, declared
% tx.*conj(rx) mixer, signed beat estimate, two one-variable sweeps,
% deliberately wrong correction, and same-measurement recovery are explicit.

close(findall(0, 'Type', 'figure', 'Tag', 'P71'));
clear p71_results;

%% Visible reviewed controls
baseline_seed = 7101;
speed_of_light_mps = 3.0e8;
carrier_frequency_hz = 77.0e9;
sample_rate_hz = 80.0e6;
chirp_duration_s = 40.0e-6;
chirp_bandwidth_hz = 20.0e6;
target_range_m = 45.0;
target_velocity_mps = 20.0;
target_voltage = 1.0;
target_initial_phase_rad = 0.35;
noise_rms = 0.002;
velocity_sweep_mps = [-30 -15 0 15 30];
bandwidth_sweep_hz = [10 15 20 25 30]*1.0e6;
plot_floor_db = -80;

maximum_samples = 5000;
maximum_sweep_cases = 7;
maximum_private_values = 20000;
maximum_working_numeric_values = 250000;
maximum_figures = 6;

controls = struct( ...
    'seed', baseline_seed, 'c_mps', speed_of_light_mps, ...
    'carrier_hz', carrier_frequency_hz, 'fs_hz', sample_rate_hz, ...
    'chirp_duration_s', chirp_duration_s, ...
    'bandwidth_hz', chirp_bandwidth_hz, ...
    'target_range_m', target_range_m, ...
    'target_velocity_mps', target_velocity_mps, ...
    'target_voltage', target_voltage, ...
    'target_phase_rad', target_initial_phase_rad, ...
    'noise_rms', noise_rms, ...
    'velocity_sweep_mps', velocity_sweep_mps, ...
    'bandwidth_sweep_hz', bandwidth_sweep_hz, ...
    'plot_floor_db', plot_floor_db, ...
    'max_samples', maximum_samples, ...
    'max_sweep_cases', maximum_sweep_cases, ...
    'max_private_values', maximum_private_values, ...
    'max_working_values', maximum_working_numeric_values, ...
    'max_figures', maximum_figures);
validate_controls(controls);

sample_count = round(sample_rate_hz*chirp_duration_s);
time_s = (0:sample_count-1).'/sample_rate_hz;
wavelength_m = speed_of_light_mps/carrier_frequency_hz;
chirp_slope_hz_per_s = chirp_bandwidth_hz/chirp_duration_s;
round_trip_delay_s = 2*target_range_m/speed_of_light_mps;
doppler_frequency_hz = 2*target_velocity_mps/wavelength_m;
delay_beat_frequency_hz = chirp_slope_hz_per_s*round_trip_delay_s;
coupled_beat_frequency_hz = delay_beat_frequency_hz-doppler_frequency_hz;
overlap_mask = time_s >= round_trip_delay_s;
overlap_start_index = find(overlap_mask, 1, 'first');
overlap_count = sum(overlap_mask);
target_motion_during_chirp_m = target_velocity_mps*chirp_duration_s;

preflight_working_value_bound = 45*sample_count + ...
    20*max(numel(velocity_sweep_mps), numel(bandwidth_sweep_hz));
assert(preflight_working_value_bound <= maximum_working_numeric_values, ...
    'P71:PreflightWorkingBound', ...
    'Conservative simultaneous working-value estimate exceeds the ceiling.');

%% Baseline: generate one up-chirp and its moving delayed echo explicitly
% Positive velocity means approaching. The echo has positive carrier
% Doppler f_d = 2*v/lambda. With tx.*conj(rx), the signed up-chirp beat is
% f_beat = S*tau - f_d. Delay is frozen within this first-order model.
transmit_phase_rad = pi*chirp_slope_hz_per_s* ...
    (time_s-chirp_duration_s/2).^2;
transmit_chirp = exp(1j*transmit_phase_rad);
echo_phase_rad = pi*chirp_slope_hz_per_s* ...
    (time_s-round_trip_delay_s-chirp_duration_s/2).^2 + ...
    2*pi*doppler_frequency_hz*time_s + target_initial_phase_rad;
received_echo = zeros(sample_count, 1);
received_echo(overlap_mask) = target_voltage* ...
    exp(1j*echo_phase_rad(overlap_mask));

private_noise = noise_rms*private_complex_noise( ...
    baseline_seed, sample_count, maximum_private_values);
dechirped_beat = transmit_chirp.*conj(received_echo);
dechirped_beat(overlap_mask) = dechirped_beat(overlap_mask) + ...
    private_noise(overlap_mask);

measured_beat_frequency_hz = estimate_signed_tone_frequency( ...
    dechirped_beat(overlap_mask), sample_rate_hz);
beat_frequency_error_hz = measured_beat_frequency_hz- ...
    coupled_beat_frequency_hz;
stationary_range_estimate_m = speed_of_light_mps* ...
    measured_beat_frequency_hz/(2*chirp_slope_hz_per_s);
stationary_range_bias_m = stationary_range_estimate_m-target_range_m;
ideal_range_bias_m = -carrier_frequency_hz*target_velocity_mps / ...
    chirp_slope_hz_per_s;

% Velocity is independently supplied; it is not estimated from this beat.
corrected_range_estimate_m = speed_of_light_mps* ...
    (measured_beat_frequency_hz+doppler_frequency_hz) / ...
    (2*chirp_slope_hz_per_s);
corrected_range_error_m = corrected_range_estimate_m-target_range_m;

assert(abs(beat_frequency_error_hz) < 250, 'P71:BeatEstimate', ...
    'Measured signed beat moved outside the reviewed tolerance.');
assert(stationary_range_bias_m < 0 && ...
    abs(stationary_range_bias_m-ideal_range_bias_m) < 0.08, ...
    'P71:ApproachingBias', ...
    'Approaching motion must create the reviewed negative range bias.');
assert(abs(corrected_range_error_m) < 0.08, 'P71:CorrectedRange', ...
    'Independent signed-Doppler correction must recover true range.');

