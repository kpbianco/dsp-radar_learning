%% Local functions
function beat = simulate_dechirped_beat(c, range_m, velocity_mps, ...
    bandwidth_hz, seed)
% Repeat the visible baseline equation for a one-variable sweep case.
validateattributes(range_m, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
validateattributes(velocity_mps, {'numeric'}, ...
    {'scalar', 'real', 'finite'});
validateattributes(bandwidth_hz, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
validateattributes(seed, {'numeric'}, ...
    {'scalar', 'integer', '>=', 1, '<', 2147483647});
sample_count_local = round(c.fs_hz*c.chirp_duration_s);
time_local_s = (0:sample_count_local-1).'/c.fs_hz;
slope_local = bandwidth_hz/c.chirp_duration_s;
delay_local_s = 2*range_m/c.c_mps;
wavelength_local_m = c.c_mps/c.carrier_hz;
doppler_local_hz = 2*velocity_mps/wavelength_local_m;
mask_local = time_local_s >= delay_local_s;
tx_phase_local = pi*slope_local* ...
    (time_local_s-c.chirp_duration_s/2).^2;
echo_phase_local = pi*slope_local* ...
    (time_local_s-delay_local_s-c.chirp_duration_s/2).^2 + ...
    2*pi*doppler_local_hz*time_local_s + c.target_phase_rad;
tx_local = exp(1j*tx_phase_local);
echo_local = zeros(sample_count_local, 1);
echo_local(mask_local) = c.target_voltage* ...
    exp(1j*echo_phase_local(mask_local));
noise_local = c.noise_rms*private_complex_noise( ...
    seed, sample_count_local, c.max_private_values);
beat = tx_local.*conj(echo_local);
beat(mask_local) = beat(mask_local)+noise_local(mask_local);
end

function frequency_hz = estimate_signed_tone_frequency(samples, fs_hz)
validateattributes(samples, {'numeric'}, {'vector', 'nonempty', 'finite'});
validateattributes(fs_hz, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
assert(numel(samples) >= 2, 'P71:ToneLength', ...
    'Signed tone estimation requires at least two samples.');
lag_one_product = sum(conj(samples(1:end-1)).*samples(2:end));
assert(abs(lag_one_product) > 100*eps, 'P71:ToneEnergy', ...
    'Signed tone estimate requires nonzero coherent energy.');
frequency_hz = angle(lag_one_product)*fs_hz/(2*pi);
end

function noise = private_complex_noise(seed, count, maximum_values)
validateattributes(seed, {'numeric'}, ...
    {'scalar', 'integer', '>=', 1, '<', 2147483647});
validateattributes(count, {'numeric'}, ...
    {'scalar', 'integer', 'positive'});
validateattributes(maximum_values, {'numeric'}, ...
    {'scalar', 'integer', 'positive'});
assert(2*count <= maximum_values, 'P71:PrivateNoiseBound', ...
    'Private generator request exceeds the reviewed ceiling.');
uniform_values = private_uniform(seed, 2*count, maximum_values);
first = max(uniform_values(1:count), realmin);
second = uniform_values(count+1:end);
noise = sqrt(-2*log(first)).*exp(1j*2*pi*second)/sqrt(2);
end

function values = private_uniform(seed, count, maximum_values)
validateattributes(seed, {'numeric'}, ...
    {'scalar', 'integer', '>=', 1, '<', 2147483647});
validateattributes(count, {'numeric'}, ...
    {'scalar', 'integer', '>=', 1, '<=', maximum_values});
state = seed;
values = zeros(count, 1);
for value_index = 1:count
    state = mod(16807*state, 2147483647);
    values(value_index) = state/2147483647;
end
end

function validate_controls(c)
assert(isstruct(c) && isscalar(c), 'P71:ControlsType', ...
    'Controls must be one scalar struct.');
required_fields = {'seed', 'c_mps', 'carrier_hz', 'fs_hz', ...
    'chirp_duration_s', 'bandwidth_hz', 'target_range_m', ...
    'target_velocity_mps', 'target_voltage', 'target_phase_rad', ...
    'noise_rms', 'velocity_sweep_mps', 'bandwidth_sweep_hz', ...
    'plot_floor_db', 'max_samples', 'max_sweep_cases', ...
    'max_private_values', 'max_working_values', 'max_figures'};
assert(isequal(sort(fieldnames(c)), sort(required_fields.')), ...
    'P71:ControlFields', 'Controls have missing or unexpected fields.');
scalar_fields = {'seed', 'c_mps', 'carrier_hz', 'fs_hz', ...
    'chirp_duration_s', 'bandwidth_hz', 'target_range_m', ...
    'target_velocity_mps', 'target_voltage', 'target_phase_rad', ...
    'noise_rms', 'plot_floor_db', 'max_samples', ...
    'max_sweep_cases', 'max_private_values', 'max_working_values', ...
    'max_figures'};
for field_index = 1:numel(scalar_fields)
    value = c.(scalar_fields{field_index});
    assert(isnumeric(value) && isreal(value) && isscalar(value) && ...
        isfinite(value), 'P71:ControlScalar', ...
        'Every scalar control must be finite, real, numeric, and scalar.');
end
vector_fields = {'velocity_sweep_mps', 'bandwidth_sweep_hz'};
for field_index = 1:numel(vector_fields)
    values = c.(vector_fields{field_index});
    assert(isnumeric(values) && isreal(values) && isvector(values) && ...
        all(isfinite(values)), 'P71:ControlVector', ...
        'Every sweep must be finite, real, and numeric.');
end
integer_fields = {'seed', 'max_samples', 'max_sweep_cases', ...
    'max_private_values', 'max_working_values', 'max_figures'};
for field_index = 1:numel(integer_fields)
    value = c.(integer_fields{field_index});
    assert(value > 0 && value == floor(value), 'P71:ControlInteger', ...
        'Integer controls and ceilings must be positive integers.');
end
sample_count_local = round(c.fs_hz*c.chirp_duration_s);
assert(c.c_mps > 0 && c.carrier_hz > 0 && c.fs_hz > 0 && ...
    c.chirp_duration_s > 0 && c.bandwidth_hz > 0 && ...
    c.bandwidth_hz < c.fs_hz && ...
    abs(sample_count_local-c.fs_hz*c.chirp_duration_s) <= ...
    100*eps(sample_count_local) && ...
    sample_count_local >= 256 && sample_count_local <= c.max_samples && ...
    c.target_range_m > 0 && c.target_voltage > 0 && ...
    c.target_voltage <= 2 && c.noise_rms >= 0 && c.noise_rms <= 0.2 && ...
    c.plot_floor_db >= -200 && c.plot_floor_db <= -20, ...
    'P71:PhysicalControls', ...
    'Controls violate waveform, target, noise, or display bounds.');
assert(numel(c.velocity_sweep_mps) >= 3 && ...
    numel(c.velocity_sweep_mps) <= c.max_sweep_cases && ...
    all(diff(c.velocity_sweep_mps) > 0) && ...
    any(c.velocity_sweep_mps < 0) && any(c.velocity_sweep_mps == 0) && ...
    any(c.velocity_sweep_mps > 0), 'P71:VelocitySweep', ...
    'Velocity sweep must be bounded, ordered, and cross zero.');
assert(numel(c.bandwidth_sweep_hz) >= 3 && ...
    numel(c.bandwidth_sweep_hz) <= c.max_sweep_cases && ...
    all(c.bandwidth_sweep_hz > 0) && ...
    all(diff(c.bandwidth_sweep_hz) > 0) && ...
    all(c.bandwidth_sweep_hz < c.fs_hz), 'P71:BandwidthSweep', ...
    'Bandwidth sweep must be bounded, positive, ordered, and sampled.');
assert(any(c.bandwidth_sweep_hz == c.bandwidth_hz), ...
    'P71:BaselineInSweep', ...
    'Slope sweep must contain the reviewed baseline bandwidth.');
delay_local_s = 2*c.target_range_m/c.c_mps;
overlap_count_local = sum((0:sample_count_local-1)/c.fs_hz >= ...
    delay_local_s);
wavelength_local_m = c.c_mps/c.carrier_hz;
all_doppler_hz = 2*[c.target_velocity_mps c.velocity_sweep_mps] / ...
    wavelength_local_m;
all_slopes = [c.bandwidth_hz c.bandwidth_sweep_hz]/ ...
    c.chirp_duration_s;
all_beats_hz = [];
for slope_index = 1:numel(all_slopes)
    all_beats_hz = [all_beats_hz ...
        all_slopes(slope_index)*delay_local_s-all_doppler_hz];
end
assert(delay_local_s > 0 && delay_local_s < c.chirp_duration_s && ...
    overlap_count_local >= 2 && ...
    all(abs(all_beats_hz) < c.fs_hz/2), 'P71:OverlapNyquist', ...
    ['Every reviewed echo needs at least two overlap samples and every ' ...
    'signed beat must be in band.']);
assert(c.max_samples == 5000 && c.max_sweep_cases == 7 && ...
    c.max_private_values == 20000 && ...
    c.max_working_values == 250000 && c.max_figures == 6, ...
    'P71:ImmutableCeilings', 'Reviewed resource ceilings changed.');
assert(2*sample_count_local <= c.max_private_values, ...
    'P71:NoiseCeiling', ...
    'Baseline private-noise request exceeds its reviewed ceiling.');
assert(c.seed <= 2147483540, 'P71:SeedRange', ...
    'Seed must leave room for deterministic sweep streams.');
end
