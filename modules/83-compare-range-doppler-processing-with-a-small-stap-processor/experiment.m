%% Local transparent operations
function validate_controls(c)
required_fields = {'seed','elements','pulses','range_cells', ...
    'target_range_cell','guard_cells','training_indices','spacing', ...
    'wavelength_m','prf_hz','platform_speed_mps','clutter_angles', ...
    'clutter_power_db','noise_power','target_power_db','assumed_angle', ...
    'actual_angle','assumed_doppler','actual_doppler','doppler_grid', ...
    'loading_alpha','ridge_sweep','support_sweep', ...
    'contamination_fraction','contamination_power_db','display_floor_db', ...
    'display_ceiling_db','max_elements','max_pulses','max_dimension', ...
    'max_range_cells','max_patches','max_doppler_cells','max_training', ...
    'max_sweeps','max_maps','max_solves','max_macs','max_private', ...
    'max_working','max_figures'};
assert(isstruct(c) && isscalar(c) && ...
    isequal(sort(fieldnames(c)), sort(required_fields(:))), ...
    'P83:ControlFields', 'Control structure fields changed.');

vector_fields = {'training_indices','clutter_angles','doppler_grid', ...
    'ridge_sweep','support_sweep'};
all_fields = fieldnames(c);
for field_index = 1:numel(all_fields)
    name = all_fields{field_index};
    value = c.(name);
    assert(isnumeric(value) && isreal(value) && ~isempty(value) && ...
        all(isfinite(value(:))), 'P83:FiniteControl', ...
        'Every control must be finite, real, numeric, and nonempty.');
    if ~any(strcmp(name, vector_fields))
        assert(isscalar(value), 'P83:ScalarControl', ...
            'Reviewed scalar control became nonscalar.');
    else
        assert(isrow(value), 'P83:RowControl', ...
            'Reviewed vector controls must be rows.');
    end
end

integer_fields = {'seed','elements','pulses','range_cells', ...
    'target_range_cell','guard_cells','training_indices','support_sweep', ...
    'max_elements','max_pulses','max_dimension','max_range_cells', ...
    'max_patches','max_doppler_cells','max_training','max_sweeps', ...
    'max_maps','max_solves','max_macs','max_private','max_working', ...
    'max_figures'};
for field_index = 1:numel(integer_fields)
    value = c.(integer_fields{field_index});
    assert(all(value(:) == floor(value(:))) && all(value(:) >= 0), ...
        'P83:IntegerControl', ...
        'Count, index, seed, and ceiling controls must be nonnegative integers.');
end

dimension = c.elements*c.pulses;
slope = 2*c.platform_speed_mps/(c.wavelength_m*c.prf_hz);
assert(c.seed >= 1 && c.seed <= 2147483644, 'P83:SeedRange', ...
    'Seed and derived private streams must fit Park-Miller state.');
assert(c.elements >= 2 && c.elements <= c.max_elements && ...
    c.pulses >= 2 && c.pulses <= c.max_pulses && ...
    dimension <= c.max_dimension, 'P83:DimensionBound', ...
    'Space-time dimensions exceed reviewed bounds.');
assert(c.range_cells <= c.max_range_cells && c.target_range_cell >= 1 && ...
    c.target_range_cell <= c.range_cells && c.guard_cells >= 1, ...
    'P83:RangeBound', 'Range geometry exceeds reviewed bounds.');
assert(numel(c.clutter_angles) >= 5 && ...
    numel(c.clutter_angles) <= c.max_patches && ...
    all(diff(c.clutter_angles) > 0) && ...
    all(abs(c.clutter_angles) < 90), 'P83:ClutterGrid', ...
    'Clutter angle grid is malformed or out of bounds.');
assert(numel(c.doppler_grid) >= 5 && ...
    numel(c.doppler_grid) <= c.max_doppler_cells && ...
    all(diff(c.doppler_grid) > 0) && ...
    c.doppler_grid(1) > -0.5 && c.doppler_grid(end) < 0.5 && ...
    any(abs(c.doppler_grid-c.assumed_doppler) < 1e-12), ...
    'P83:DopplerGrid', 'Doppler grid is malformed, aliased, or misses target.');
assert(c.spacing > 0 && c.spacing <= 0.5 && c.wavelength_m > 0 && ...
    c.prf_hz > 0 && c.platform_speed_mps > 0 && slope > 0 && slope < 0.5, ...
    'P83:PhysicalControls', 'Sampling or moving-platform controls are invalid.');
assert(c.noise_power > 0 && c.noise_power <= 1e6 && ...
    abs(c.clutter_power_db) <= 80 && abs(c.target_power_db) <= 80 && ...
    c.contamination_power_db >= c.target_power_db && ...
    c.contamination_power_db <= 80, 'P83:PowerControls', ...
    'Reviewed component powers are invalid.');
assert(abs(c.assumed_angle) < 90 && abs(c.actual_angle) < 90 && ...
    abs(c.actual_angle-c.assumed_angle) <= 2 && ...
    c.actual_doppler > c.doppler_grid(1) && ...
    c.actual_doppler < c.doppler_grid(end) && ...
    abs(c.actual_doppler-c.assumed_doppler) <= 0.02, ...
    'P83:TargetControls', 'Target steering or mismatch is outside reviewed bounds.');
assert(c.loading_alpha > 0 && c.loading_alpha <= 1, ...
    'P83:LoadingControl', 'Diagonal loading must lie in (0,1].');
assert(numel(c.training_indices) >= dimension && ...
    numel(c.training_indices) <= c.max_training && ...
    all(diff(c.training_indices) > 0) && ...
    c.training_indices(1) >= 1 && ...
    c.training_indices(end) <= c.range_cells && ...
    ~any(abs(c.training_indices-c.target_range_cell) <= c.guard_cells), ...
    'P83:TrainingControls', 'Training geometry or support is invalid.');
assert(numel(c.ridge_sweep) >= 3 && ...
    numel(c.ridge_sweep) <= c.max_sweeps && ...
    all(diff(c.ridge_sweep) > 0) && all(c.ridge_sweep > 0) && ...
    slope*sind(c.actual_angle)+c.ridge_sweep(end) < 0.5, ...
    'P83:RidgeSweepControls', 'Ridge-offset sweep is malformed or aliased.');
assert(numel(c.support_sweep) >= 3 && ...
    numel(c.support_sweep) <= c.max_sweeps && ...
    all(diff(c.support_sweep) > 0) && c.support_sweep(1) >= 2 && ...
    c.support_sweep(end) == numel(c.training_indices), ...
    'P83:SupportSweepControls', 'Training-support sweep is malformed.');
assert(c.contamination_fraction > 0 && c.contamination_fraction <= 0.5 && ...
    round(c.contamination_fraction*numel(c.training_indices)) >= 1, ...
    'P83:ContaminationControl', 'Contamination fraction is invalid.');
assert(c.display_floor_db < 0 && c.display_ceiling_db > 0 && ...
    c.display_ceiling_db > c.display_floor_db, 'P83:DisplayControls', ...
    'Display limits are invalid.');
assert(c.max_maps == 4 && c.max_solves == 200 && c.max_macs == 8000000 && ...
    c.max_private == 100000 && c.max_working == 250000 && ...
    c.max_figures == 5, 'P83:ImmutableCeilings', ...
    'Reviewed resource ceilings changed.');
private_count = 2*max(numel(c.clutter_angles)*c.range_cells, ...
    dimension*c.range_cells);
assert(private_count <= c.max_private, 'P83:PrivateBound', ...
    'Private deterministic generator request exceeds the ceiling.');
end

function steering = space_time_steering(angle_deg, normalized_doppler, ...
    number_elements, number_pulses, spacing_wavelengths)
space = exp(1j*2*pi*spacing_wavelengths*(0:number_elements-1).'* ...
    sind(angle_deg));
slow_time = exp(1j*2*pi*(0:number_pulses-1).'*normalized_doppler);
steering = kron(slow_time, space);
end

function [solution, weight] = loaded_solution(covariance_matrix, ...
    steering_vector, alpha)
dimension = numel(steering_vector);
loading = alpha*real(trace(covariance_matrix))/dimension;
assert(isfinite(loading) && loading > 0, 'P83:PositiveLoading', ...
    'Covariance loading must be finite and positive.');
loaded_covariance = covariance_matrix + loading*eye(dimension);
solution = loaded_covariance\steering_vector;
denominator = steering_vector'*solution;
assert(isfinite(real(denominator)) && real(denominator) > 0 && ...
    abs(imag(denominator)) < 1e-7*real(denominator), ...
    'P83:AdaptiveDenominator', ...
    'Loaded covariance produced an invalid adaptive normalization.');
weight = solution/denominator;
end

function [value_db, target_output_power, interference_output_power] = ...
    output_scnr_db(weight, actual_target_steering, ...
    target_power, interference_covariance)
target_output_power = target_power*abs(weight'*actual_target_steering)^2;
interference_output_power = real(weight'*interference_covariance*weight);
assert(target_output_power > 0 && interference_output_power > 0, ...
    'P83:OutputPower', 'Known simulated output powers must be positive.');
value_db = 10*log10(target_output_power/interference_output_power);
end

function noise = private_complex_noise(seed, number_rows, number_columns, ...
    maximum_values)
assert(isscalar(seed) && isfinite(seed) && seed == floor(seed) && ...
    seed >= 1 && seed < 2147483647, 'P83:PrivateSeed', ...
    'Private generator seed is invalid.');
assert(isscalar(number_rows) && isscalar(number_columns) && ...
    number_rows == floor(number_rows) && number_columns == floor(number_columns) && ...
    number_rows >= 1 && number_columns >= 1, 'P83:PrivateShape', ...
    'Private generator shape is invalid.');
number_values = number_rows*number_columns;
assert(2*number_values <= maximum_values, 'P83:PrivateRequest', ...
    'Private generator request exceeds the reviewed ceiling.');
uniforms = zeros(1, 2*number_values);
state = seed;
for sample_index = 1:2*number_values
    state = mod(16807*state, 2147483647);
    uniforms(sample_index) = state/2147483647;
end
first = max(uniforms(1:number_values), realmin);
second = uniforms(number_values+1:end);
samples = sqrt(-2*log(first)).*exp(1j*2*pi*second)/sqrt(2);
noise = reshape(samples, number_rows, number_columns);
end
