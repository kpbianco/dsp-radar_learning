%% P83: Compare Range-Doppler Processing with a Small STAP Processor
% Guiding question:
% When is Doppler filtering alone insufficient against clutter?
%
% Base MATLAB R2016b+ only. The moving-platform ridge, fixed spatial beam,
% Doppler bank, sample covariance, diagonal loading, joint solve, output SCNR,
% sweeps, contaminated training, and recovery are explicit below.

close(findall(0, 'Type', 'figure', 'Tag', 'P83'));
clear p83_results;

%% Visible reviewed controls
baseline_seed = 8301;
number_elements = 4;
number_pulses = 8;
number_range_cells = 48;
target_range_cell = 25;
guard_cells_each_side = 2;
training_indices = [5:22 28:45];
element_spacing_wavelengths = 0.5;
wavelength_m = 0.03;
prf_hz = 20000;
platform_speed_mps = 90;
clutter_angles_deg = -60:3:60;
clutter_total_power_db = 32;
noise_power = 1.0;
target_power_db = 18;
assumed_target_angle_deg = 12.0;
actual_target_angle_deg = 12.5;
assumed_target_normalized_doppler = 0.120;
actual_target_normalized_doppler = 0.125;
doppler_grid = -0.25:0.01:0.25;
diagonal_loading_alpha = 0.05;
ridge_offset_sweep = [0.01 0.03 0.06 0.10];
training_support_sweep = [8 16 24 36];
contaminated_training_fraction = 0.25;
contamination_power_db = 30;
display_floor_db = -20;
display_ceiling_db = 35;

maximum_elements = 6;
maximum_pulses = 12;
maximum_space_time_dimension = 72;
maximum_range_cells = 64;
maximum_clutter_patches = 61;
maximum_doppler_cells = 81;
maximum_training_cells = 48;
maximum_sweep_cases = 5;
maximum_map_evaluations = 4;
maximum_linear_solves = 200;
maximum_multiply_accumulates = 8000000;
maximum_private_values = 100000;
maximum_working_numeric_values = 250000;
maximum_figures = 5;

controls = struct( ...
    'seed', baseline_seed, 'elements', number_elements, ...
    'pulses', number_pulses, 'range_cells', number_range_cells, ...
    'target_range_cell', target_range_cell, 'guard_cells', guard_cells_each_side, ...
    'training_indices', training_indices, ...
    'spacing', element_spacing_wavelengths, ...
    'wavelength_m', wavelength_m, 'prf_hz', prf_hz, ...
    'platform_speed_mps', platform_speed_mps, ...
    'clutter_angles', clutter_angles_deg, ...
    'clutter_power_db', clutter_total_power_db, ...
    'noise_power', noise_power, 'target_power_db', target_power_db, ...
    'assumed_angle', assumed_target_angle_deg, ...
    'actual_angle', actual_target_angle_deg, ...
    'assumed_doppler', assumed_target_normalized_doppler, ...
    'actual_doppler', actual_target_normalized_doppler, ...
    'doppler_grid', doppler_grid, 'loading_alpha', diagonal_loading_alpha, ...
    'ridge_sweep', ridge_offset_sweep, ...
    'support_sweep', training_support_sweep, ...
    'contamination_fraction', contaminated_training_fraction, ...
    'contamination_power_db', contamination_power_db, ...
    'display_floor_db', display_floor_db, ...
    'display_ceiling_db', display_ceiling_db, ...
    'max_elements', maximum_elements, 'max_pulses', maximum_pulses, ...
    'max_dimension', maximum_space_time_dimension, ...
    'max_range_cells', maximum_range_cells, ...
    'max_patches', maximum_clutter_patches, ...
    'max_doppler_cells', maximum_doppler_cells, ...
    'max_training', maximum_training_cells, ...
    'max_sweeps', maximum_sweep_cases, ...
    'max_maps', maximum_map_evaluations, ...
    'max_solves', maximum_linear_solves, ...
    'max_macs', maximum_multiply_accumulates, ...
    'max_private', maximum_private_values, ...
    'max_working', maximum_working_numeric_values, ...
    'max_figures', maximum_figures);
validate_controls(controls);

space_time_dimension = number_elements*number_pulses;
number_clutter_patches = numel(clutter_angles_deg);
number_training_cells = numel(training_indices);
number_doppler_cells = numel(doppler_grid);
target_doppler_index = find(abs(doppler_grid- ...
    assumed_target_normalized_doppler) < 1e-12, 1);
executed_map_count = 4;
executed_linear_solve_count = 3*number_doppler_cells + ...
    numel(ridge_offset_sweep) + numel(training_support_sweep);
predicted_multiply_accumulates = ...
    executed_linear_solve_count*space_time_dimension^3 + ...
    executed_map_count*number_doppler_cells*number_range_cells* ...
    space_time_dimension + ...
    4*space_time_dimension^2*number_training_cells + ...
    space_time_dimension*number_clutter_patches*number_range_cells;
predicted_working_numeric_values = ...
    2*space_time_dimension*number_clutter_patches + ...
    6*space_time_dimension*number_range_cells + ...
    8*space_time_dimension^2 + ...
    executed_map_count*number_doppler_cells*number_range_cells + ...
    1000;
assert(executed_map_count <= maximum_map_evaluations, ...
    'P83:MapBound', 'Planned map count exceeds the reviewed ceiling.');
assert(executed_linear_solve_count <= maximum_linear_solves, ...
    'P83:SolveBound', 'Planned linear solves exceed the reviewed ceiling.');
assert(predicted_multiply_accumulates <= maximum_multiply_accumulates, ...
    'P83:MacBound', 'Planned multiply-accumulates exceed the reviewed ceiling.');
assert(predicted_working_numeric_values <= maximum_working_numeric_values, ...
    'P83:WorkingBound', 'Conservative working-value estimate exceeds the ceiling.');

%% Build the moving-platform angle-Doppler clutter ridge explicitly
normalized_clutter_slope = ...
    2*platform_speed_mps/(wavelength_m*prf_hz);
clutter_normalized_doppler = ...
    normalized_clutter_slope*sind(clutter_angles_deg);
clutter_shape = cosd(clutter_angles_deg).^2;
clutter_total_power = noise_power*10^(clutter_total_power_db/10);
clutter_patch_powers = clutter_total_power*clutter_shape/sum(clutter_shape);

clutter_steering = complex(zeros(space_time_dimension, number_clutter_patches));
for patch_index = 1:number_clutter_patches
    clutter_steering(:, patch_index) = space_time_steering( ...
        clutter_angles_deg(patch_index), ...
        clutter_normalized_doppler(patch_index), number_elements, ...
        number_pulses, element_spacing_wavelengths);
end
weighted_clutter_steering = bsxfun(@times, clutter_steering, ...
    reshape(sqrt(clutter_patch_powers), 1, []));
known_interference_covariance = weighted_clutter_steering* ...
    weighted_clutter_steering' + noise_power*eye(space_time_dimension);

%% Generate one immutable range record and neighboring training snapshots
clutter_coefficients = private_complex_noise(baseline_seed, ...
    number_clutter_patches, number_range_cells, maximum_private_values);
thermal_noise = private_complex_noise(baseline_seed+1, ...
    space_time_dimension, number_range_cells, maximum_private_values);
clean_background = weighted_clutter_steering*clutter_coefficients + ...
    sqrt(noise_power)*thermal_noise;
clean_training_data = clean_background(:, training_indices);
clean_sample_covariance = clean_training_data*clean_training_data'/ ...
    number_training_cells;
clean_loading = diagonal_loading_alpha*real(trace(clean_sample_covariance))/ ...
    space_time_dimension;
clean_loaded_covariance = clean_sample_covariance + ...
    clean_loading*eye(space_time_dimension);

actual_target_steering = space_time_steering(actual_target_angle_deg, ...
    actual_target_normalized_doppler, number_elements, number_pulses, ...
    element_spacing_wavelengths);
assumed_target_steering = space_time_steering(assumed_target_angle_deg, ...
    assumed_target_normalized_doppler, number_elements, number_pulses, ...
    element_spacing_wavelengths);
target_power = noise_power*10^(target_power_db/10);
measurement = clean_background;
measurement(:, target_range_cell) = measurement(:, target_range_cell) + ...
    sqrt(target_power)*actual_target_steering;
measurement_before_failure = measurement;

assert(~any(abs(training_indices-target_range_cell) <= guard_cells_each_side), ...
    'P83:TrainingGuard', 'Training cells overlap the guarded CUT.');
assert(rank(clean_sample_covariance) == space_time_dimension, ...
    'P83:TrainingRank', 'Reviewed clean training covariance must be full rank.');

%% Conventional fixed-beam range-Doppler map and joint adaptive map
range_doppler_power = zeros(number_doppler_cells, number_range_cells);
stap_power = zeros(number_doppler_cells, number_range_cells);
baseline_stap_weight = complex(zeros(space_time_dimension, 1));
for doppler_index = 1:number_doppler_cells
    trial_steering = space_time_steering(assumed_target_angle_deg, ...
        doppler_grid(doppler_index), number_elements, number_pulses, ...
        element_spacing_wavelengths);

    % A fixed spatial beam followed by a Doppler matched filter is the
    % separable conventional reference: w_RD = s/(s^H s).
    range_doppler_weight = trial_steering/(trial_steering'*trial_steering);
    range_doppler_normalization = real(range_doppler_weight'* ...
        clean_loaded_covariance*range_doppler_weight);
    range_doppler_power(doppler_index, :) = ...
        abs(range_doppler_weight'*measurement).^2/ ...
        range_doppler_normalization;

    % The small STAP/AMF map whitens the same steering vector with the
    % neighboring-range covariance. Diagonal loading is explicit.
    [adaptive_solution, adaptive_weight] = loaded_solution( ...
        clean_sample_covariance, trial_steering, diagonal_loading_alpha);
    adaptive_normalization = real(trial_steering'*adaptive_solution);
    stap_power(doppler_index, :) = ...
        abs(adaptive_solution'*measurement).^2/adaptive_normalization;
    if doppler_index == target_doppler_index
        baseline_stap_weight = adaptive_weight;
    end
end

baseline_range_doppler_weight = assumed_target_steering/ ...
    (assumed_target_steering'*assumed_target_steering);
range_doppler_scnr_db = output_scnr_db(baseline_range_doppler_weight, ...
    actual_target_steering, target_power, known_interference_covariance);
[stap_scnr_db, stap_target_output_power, ...
    stap_interference_output_power] = output_scnr_db( ...
    baseline_stap_weight, actual_target_steering, target_power, ...
    known_interference_covariance);

background_mask = true(size(range_doppler_power));
doppler_guard = max(1, target_doppler_index-1): ...
    min(number_doppler_cells, target_doppler_index+1);
range_guard = (target_range_cell-guard_cells_each_side): ...
    (target_range_cell+guard_cells_each_side);
background_mask(doppler_guard, range_guard) = false;
range_doppler_background = median(range_doppler_power(background_mask));
stap_background = median(stap_power(background_mask));
range_doppler_contrast_db = 10*log10( ...
    range_doppler_power(target_doppler_index, target_range_cell)/ ...
    range_doppler_background);
stap_contrast_db = 10*log10( ...
    stap_power(target_doppler_index, target_range_cell)/stap_background);

[~, range_doppler_peak_linear] = max(range_doppler_power(:));
[range_doppler_peak_doppler_index, range_doppler_peak_range_cell] = ...
    ind2sub(size(range_doppler_power), range_doppler_peak_linear);
[~, stap_peak_linear] = max(stap_power(:));
[stap_peak_doppler_index, stap_peak_range_cell] = ...
    ind2sub(size(stap_power), stap_peak_linear);

assert(stap_scnr_db > range_doppler_scnr_db+20, ...
    'P83:JointScnrImprovement', ...
    'Reviewed STAP weight must materially improve known-component SCNR.');
assert(stap_contrast_db > range_doppler_contrast_db+15, ...
    'P83:JointMapImprovement', ...
    'Adaptive map must materially improve target-to-background contrast.');
assert(stap_peak_range_cell == target_range_cell && ...
    stap_peak_doppler_index == target_doppler_index, ...
    'P83:AdaptiveLocalization', ...
    'Target must own the reviewed adaptive map at its assumed grid cell.');
assert(range_doppler_peak_range_cell ~= target_range_cell || ...
    range_doppler_peak_doppler_index ~= target_doppler_index, ...
    'P83:ConventionalFailure', ...
    'Conventional map is intended to be clutter-dominated in the baseline.');

%% Sweep 1: move the target away from its local clutter-ridge Doppler
local_ridge_doppler = normalized_clutter_slope*sind(actual_target_angle_deg);
ridge_sweep_range_doppler_scnr_db = zeros(size(ridge_offset_sweep));
ridge_sweep_stap_scnr_db = zeros(size(ridge_offset_sweep));
for case_index = 1:numel(ridge_offset_sweep)
    case_doppler = local_ridge_doppler + ridge_offset_sweep(case_index);
    case_steering = space_time_steering(actual_target_angle_deg, ...
        case_doppler, number_elements, number_pulses, ...
        element_spacing_wavelengths);
    case_range_doppler_weight = case_steering/(case_steering'*case_steering);
    [~, case_stap_weight] = loaded_solution(clean_sample_covariance, ...
        case_steering, diagonal_loading_alpha);
    ridge_sweep_range_doppler_scnr_db(case_index) = output_scnr_db( ...
        case_range_doppler_weight, case_steering, target_power, ...
        known_interference_covariance);
    ridge_sweep_stap_scnr_db(case_index) = output_scnr_db( ...
        case_stap_weight, case_steering, target_power, ...
        known_interference_covariance);
end
assert(ridge_sweep_stap_scnr_db(end) > ...
    ridge_sweep_stap_scnr_db(1)+20, ...
    'P83:RidgeSweep', ...
    'Moving away from the ridge must materially improve reviewed STAP SCNR.');

%% Sweep 2: prefixes of one unchanged clean training record
support_scnr_db = zeros(size(training_support_sweep));
support_loaded_condition = zeros(size(training_support_sweep));
support_sample_rank = zeros(size(training_support_sweep));
for case_index = 1:numel(training_support_sweep)
    support = training_support_sweep(case_index);
    case_training = clean_training_data(:, 1:support);
    case_covariance = case_training*case_training'/support;
    [~, case_weight] = loaded_solution(case_covariance, ...
        assumed_target_steering, diagonal_loading_alpha);
    support_scnr_db(case_index) = output_scnr_db(case_weight, ...
        actual_target_steering, target_power, known_interference_covariance);
    loading = diagonal_loading_alpha*real(trace(case_covariance))/ ...
        space_time_dimension;
    support_loaded_condition(case_index) = cond(case_covariance + ...
        loading*eye(space_time_dimension));
    support_sample_rank(case_index) = rank(case_covariance, ...
        max(abs(eig(case_covariance)))*1e-8);
end
assert(support_scnr_db(end) > support_scnr_db(1)+10, ...
    'P83:SupportSweep', ...
    'Reviewed clean support increase must materially improve output SCNR.');

%% Intentionally broken case: target-like training contamination
contamination_cell_count = round(contaminated_training_fraction* ...
    number_training_cells);
contamination_waveform = private_complex_noise(baseline_seed+2, 1, ...
    number_training_cells, maximum_private_values);
contamination_power = noise_power*10^(contamination_power_db/10);
contaminated_training_data = clean_training_data;
contaminated_training_data(:, 1:contamination_cell_count) = ...
    contaminated_training_data(:, 1:contamination_cell_count) + ...
    sqrt(contamination_power)*actual_target_steering* ...
    contamination_waveform(1, 1:contamination_cell_count);
broken_covariance = contaminated_training_data* ...
    contaminated_training_data'/number_training_cells;

broken_stap_power = zeros(number_doppler_cells, number_range_cells);
broken_stap_weight = complex(zeros(space_time_dimension, 1));
for doppler_index = 1:number_doppler_cells
    trial_steering = space_time_steering(assumed_target_angle_deg, ...
        doppler_grid(doppler_index), number_elements, number_pulses, ...
        element_spacing_wavelengths);
    [broken_solution, broken_weight] = loaded_solution(broken_covariance, ...
        trial_steering, diagonal_loading_alpha);
    broken_normalization = real(trial_steering'*broken_solution);
    broken_stap_power(doppler_index, :) = ...
        abs(broken_solution'*measurement).^2/broken_normalization;
    if doppler_index == target_doppler_index
        broken_stap_weight = broken_weight;
    end
end
[broken_scnr_db, broken_target_output_power, ...
    broken_interference_output_power] = output_scnr_db( ...
    broken_stap_weight, actual_target_steering, target_power, ...
    known_interference_covariance);
broken_target_output_change_db = 10*log10( ...
    broken_target_output_power/stap_target_output_power);
broken_interference_output_increase_db = 10*log10( ...
    broken_interference_output_power/stap_interference_output_power);
clean_assumed_response = baseline_stap_weight'*assumed_target_steering;
broken_assumed_response = broken_stap_weight'*assumed_target_steering;
broken_background = median(broken_stap_power(background_mask));
broken_contrast_db = 10*log10( ...
    broken_stap_power(target_doppler_index, target_range_cell)/ ...
    broken_background);

% Recovery starts from the retained clean training data and unchanged CUT.
recovered_covariance = clean_training_data*clean_training_data'/ ...
    number_training_cells;
recovered_stap_power = zeros(number_doppler_cells, number_range_cells);
recovered_stap_weight = complex(zeros(space_time_dimension, 1));
for doppler_index = 1:number_doppler_cells
    trial_steering = space_time_steering(assumed_target_angle_deg, ...
        doppler_grid(doppler_index), number_elements, number_pulses, ...
        element_spacing_wavelengths);
    [recovered_solution, recovered_weight] = loaded_solution( ...
        recovered_covariance, trial_steering, diagonal_loading_alpha);
    recovered_normalization = real(trial_steering'*recovered_solution);
    recovered_stap_power(doppler_index, :) = ...
        abs(recovered_solution'*measurement).^2/recovered_normalization;
    if doppler_index == target_doppler_index
        recovered_stap_weight = recovered_weight;
    end
end
recovered_scnr_db = output_scnr_db(recovered_stap_weight, ...
    actual_target_steering, target_power, known_interference_covariance);
recovery_exact_match = isequaln(recovered_stap_power, stap_power) && ...
    isequaln(recovered_covariance, clean_sample_covariance) && ...
    isequaln(recovered_stap_weight, baseline_stap_weight) && ...
    isequaln(measurement, measurement_before_failure);
assert(recovered_scnr_db > broken_scnr_db+20, ...
    'P83:TrainingRecovery', ...
    'Clean same-record recovery must materially restore output SCNR.');
assert(broken_contrast_db < 2, ...
    'P83:BrokenVisibility', ...
    'Contaminated training is intended to erase reviewed target contrast.');
assert(abs(clean_assumed_response-1) < 1e-10 && ...
    abs(broken_assumed_response-1) < 1e-10 && ...
    broken_target_output_change_db > -3 && ...
    broken_interference_output_increase_db > 20, ...
    'P83:ContaminationMechanism', ...
    ['The reviewed failure must preserve the assumed look and lose SCNR ' ...
    'through interference growth rather than a desired-signal null.']);
assert(recovery_exact_match, 'P83:ExactRecovery', ...
    'Recovery must exactly reproduce the clean adaptive map and inputs.');

