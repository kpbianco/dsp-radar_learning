range_doppler_map_db = 10*log10(max(range_doppler_power, realmin));
stap_map_db = 10*log10(max(stap_power, realmin));
broken_map_db = 10*log10(max(broken_stap_power, realmin));
recovered_map_db = stap_map_db;

