%% P30: Measure Range from Echo Delay
% Guiding question: How does round-trip delay become target range?
% Base MATLAB only. Fractional-delay echo insertion, explicit correlation,
% sample-rate and fractional-delay sweeps, two-target separation, the
% one-way-ranging failure, and clean recovery are visible below.

%% Visible controls and fixed resource bounds
random_seed = 3001;
speed_of_light_mps = 299792458;
sample_rate_hz = 20e6;
pulse_duration_s = 1e-6;
true_round_trip_delay_s = 6.0175e-6;
echo_amplitude = 1;
noise_sigma = 0.03;
capture_duration_s = 16e-6;
sample_rate_sweep_hz = [10e6 20e6 40e6];
fractional_delay_integer_samples = 120;
fractional_delay_sweep_samples = [0 0.25 0.5 0.75];
second_echo_amplitude = 0.65;
second_target_separation_s = [0.5e-6 1e-6 1.5e-6];

max_record_samples = 640;
max_pulse_samples = 40;
max_correlation_samples = 640;
max_sweep_cases = 4;
max_figure_groups = 6;
max_stored_numeric_values = 50000;
comparison_tolerance = 1e-10;

assert(isscalar(random_seed) && isnumeric(random_seed) && ...
    ~islogical(random_seed) && isreal(random_seed) && ...
    isfinite(random_seed) && random_seed == fix(random_seed) && ...
    random_seed == 3001, ...
    'random_seed must be the canonical integer 3001.');
positive_scalar_controls = {speed_of_light_mps, sample_rate_hz, ...
    pulse_duration_s, true_round_trip_delay_s, echo_amplitude, ...
    capture_duration_s, second_echo_amplitude, comparison_tolerance};
for validation_index = 1:numel(positive_scalar_controls)
    control_value = positive_scalar_controls{validation_index};
    assert(isscalar(control_value) && isnumeric(control_value) && ...
        ~islogical(control_value) && isreal(control_value) && ...
        isfinite(control_value) && control_value > 0, ...
        'Physical scalar controls must be numeric, real, finite, and positive.');
end
assert(isscalar(noise_sigma) && isnumeric(noise_sigma) && ...
    ~islogical(noise_sigma) && isreal(noise_sigma) && ...
    isfinite(noise_sigma) && noise_sigma >= 0, ...
    'noise_sigma must be numeric, real, finite, and nonnegative.');
assert(isnumeric(sample_rate_sweep_hz) && ...
    ~islogical(sample_rate_sweep_hz) && isreal(sample_rate_sweep_hz) && ...
    all(isfinite(sample_rate_sweep_hz)) && ...
    isequal(sample_rate_sweep_hz, [10e6 20e6 40e6]) && ...
    all(diff(sample_rate_sweep_hz) > 0), ...
    'sample_rate_sweep_hz must equal the reviewed increasing grid.');
assert(isscalar(fractional_delay_integer_samples) && ...
    isnumeric(fractional_delay_integer_samples) && ...
    ~islogical(fractional_delay_integer_samples) && ...
    isreal(fractional_delay_integer_samples) && ...
    isfinite(fractional_delay_integer_samples) && ...
    fractional_delay_integer_samples == fix(fractional_delay_integer_samples) && ...
    fractional_delay_integer_samples >= 0, ...
    'fractional_delay_integer_samples must be a nonnegative integer.');
assert(isnumeric(fractional_delay_sweep_samples) && ...
    ~islogical(fractional_delay_sweep_samples) && ...
    isreal(fractional_delay_sweep_samples) && ...
    all(isfinite(fractional_delay_sweep_samples)) && ...
    isequal(fractional_delay_sweep_samples, [0 0.25 0.5 0.75]) && ...
    all(fractional_delay_sweep_samples >= 0) && ...
    all(fractional_delay_sweep_samples < 1), ...
    'fractional_delay_sweep_samples must equal the reviewed fractional grid.');
assert(isnumeric(second_target_separation_s) && ...
    ~islogical(second_target_separation_s) && ...
    isreal(second_target_separation_s) && ...
    all(isfinite(second_target_separation_s)) && ...
    isequal(second_target_separation_s, [0.5e-6 1e-6 1.5e-6]) && ...
    all(diff(second_target_separation_s) > 0), ...
    'second_target_separation_s must equal the reviewed increasing grid.');
assert(max_record_samples == 640 && max_pulse_samples == 40 && ...
    max_correlation_samples == 640 && max_sweep_cases == 4 && ...
    max_figure_groups == 6 && max_stored_numeric_values == 50000, ...
    'Resource ceilings are fixed by the P30 deterministic contract.');

largest_sample_rate_hz = max([sample_rate_hz sample_rate_sweep_hz]);
estimated_max_record_samples = round(capture_duration_s*largest_sample_rate_hz);
estimated_max_pulse_samples = round(pulse_duration_s*largest_sample_rate_hz);
baseline_record_sample_count = round(capture_duration_s*sample_rate_hz);
baseline_pulse_sample_count = round(pulse_duration_s*sample_rate_hz);
reviewed_pulse_sample_counts = round(pulse_duration_s* ...
    [sample_rate_hz sample_rate_sweep_hz]);
estimated_stored_numeric_values = 40*estimated_max_record_samples + ...
    20*max_sweep_cases*estimated_max_pulse_samples;
assert(numel(sample_rate_sweep_hz) <= max_sweep_cases && ...
    numel(fractional_delay_sweep_samples) <= max_sweep_cases && ...
    numel(second_target_separation_s) <= max_sweep_cases && ...
    estimated_max_record_samples <= max_record_samples && ...
    estimated_max_pulse_samples <= max_pulse_samples && ...
    estimated_max_record_samples <= max_correlation_samples && ...
    estimated_stored_numeric_values <= max_stored_numeric_values, ...
    'P30 arrays would exceed their fixed resource ceilings.');
assert(all(reviewed_pulse_sample_counts >= 1), ...
    'Every reviewed rate must represent the finite pulse with at least one sample.');
fractional_minimum_delay_samples = fractional_delay_integer_samples + ...
    min(fractional_delay_sweep_samples);
fractional_maximum_delay_samples = fractional_delay_integer_samples + ...
    max(fractional_delay_sweep_samples);
assert(fractional_minimum_delay_samples >= 1 && ...
    fractional_maximum_delay_samples + baseline_pulse_sample_count + 1 <= ...
    baseline_record_sample_count, ...
    ['Fractional-delay cases must keep the complete pulse and a two-sided ' ...
    'correlation-peak neighborhood inside the capture.']);
assert(true_round_trip_delay_s + pulse_duration_s + ...
    max(second_target_separation_s) < capture_duration_s, ...
    'Every delayed pulse must fit completely inside the capture.');
% Validation succeeded: allocation, private random generation, bounded loops,
% P30-only figure cleanup, and plotting begin below.
results = struct();

%% Build the finite transmitted pulse and fractional delayed echo
% The pulse is one volt for pulse_duration_s and zero elsewhere. Echo samples
% evaluate a zero-extended, piecewise-linear version at n-delay_samples.
% This represents a fractional delay before the receiver samples the echo;
% rounding delay here would erase the fractional-delay experiment.
record_sample_count = round(capture_duration_s*sample_rate_hz);
pulse_sample_count = round(pulse_duration_s*sample_rate_hz);
transmit_pulse = ones(1, pulse_sample_count);
record_time_s = (0:record_sample_count-1)/sample_rate_hz;
true_delay_samples = true_round_trip_delay_s*sample_rate_hz;
true_range_m = speed_of_light_mps*true_round_trip_delay_s/2;
clean_echo = zeros(1, record_sample_count);
for record_index = 1:record_sample_count
    source_position = (record_index-1)-true_delay_samples;
    source_left = floor(source_position);
    source_fraction = source_position-source_left;
    left_value = 0;
    right_value = 0;
    if source_left >= 0 && source_left < pulse_sample_count
        left_value = transmit_pulse(source_left+1);
    end
    if source_left+1 >= 0 && source_left+1 < pulse_sample_count
        right_value = transmit_pulse(source_left+2);
    end
    clean_echo(record_index) = echo_amplitude*((1-source_fraction)* ...
        left_value + source_fraction*right_value);
end
assert(abs(sum(clean_echo)-echo_amplitude*pulse_sample_count) < ...
    comparison_tolerance, ...
    'Zero-extended linear interpolation must preserve pulse area.');

% A private stream makes noise repeatable without advancing the caller's
% global random stream.
private_stream = RandStream('mt19937ar', 'Seed', random_seed);
unit_noise = randn(private_stream, 1, record_sample_count);
received_signal = clean_echo + noise_sigma*unit_noise;

%% Correlate explicitly over nonnegative echo lag
% r_xs[ell] = sum_m x[ell+m]*conj(s[m]). A positive ell means the echo
% starts after transmission. This is linear correlation, not circular shift.
correlation_lags_samples = 0:record_sample_count-pulse_sample_count;
explicit_correlation = zeros(size(correlation_lags_samples));
for lag_index = 1:numel(correlation_lags_samples)
    lag_samples = correlation_lags_samples(lag_index);
    aligned_sum = 0;
    for pulse_index = 1:pulse_sample_count
        received_index = lag_samples+pulse_index;
        aligned_sum = aligned_sum + received_signal(received_index)* ...
            conj(transmit_pulse(pulse_index));
    end
    explicit_correlation(lag_index) = aligned_sum;
end
convolution_crosscheck = conv(received_signal, fliplr(conj(transmit_pulse)));
convolution_valid_lags = convolution_crosscheck(pulse_sample_count:record_sample_count);
assert(max(abs(explicit_correlation-convolution_valid_lags)) < ...
    comparison_tolerance, ...
    'Explicit valid-lag correlation must match reversed conjugate convolution.');

correlation_magnitude = abs(explicit_correlation);
[correlation_peak, peak_index] = max(correlation_magnitude);
integer_delay_samples = correlation_lags_samples(peak_index);
assert(peak_index > 1 && peak_index < numel(correlation_magnitude), ...
    'The baseline correlation peak must have two neighbors.');
peak_left = correlation_magnitude(peak_index-1);
peak_center = correlation_magnitude(peak_index);
peak_right = correlation_magnitude(peak_index+1);
parabolic_denominator = peak_left-2*peak_center+peak_right;
assert(abs(parabolic_denominator) > comparison_tolerance, ...
    'The baseline correlation peak must have usable local curvature.');
parabolic_offset_samples = 0.5*(peak_left-peak_right)/parabolic_denominator;
assert(abs(parabolic_offset_samples) <= 0.5, ...
    'Parabolic peak refinement must remain inside the selected sample bin.');
refined_delay_samples = integer_delay_samples+parabolic_offset_samples;
integer_delay_s = integer_delay_samples/sample_rate_hz;
refined_delay_s = refined_delay_samples/sample_rate_hz;
integer_range_m = speed_of_light_mps*integer_delay_s/2;
refined_range_m = speed_of_light_mps*refined_delay_s/2;
range_bin_spacing_m = speed_of_light_mps/(2*sample_rate_hz);
integer_range_error_m = integer_range_m-true_range_m;
refined_range_error_m = refined_range_m-true_range_m;
assert(abs(integer_range_error_m) <= range_bin_spacing_m/2 + ...
    comparison_tolerance && abs(refined_range_error_m) < ...
    abs(integer_range_error_m), ...
    'Baseline integer ranging must meet its bin bound and refinement must help.');

%% Sweep 1: sample rate, with physical delay and pulse duration fixed
sample_rate_integer_range_m = zeros(size(sample_rate_sweep_hz));
sample_rate_refined_range_m = zeros(size(sample_rate_sweep_hz));
sample_rate_bin_spacing_m = zeros(size(sample_rate_sweep_hz));
sample_rate_integer_error_m = zeros(size(sample_rate_sweep_hz));
sample_rate_refined_error_m = zeros(size(sample_rate_sweep_hz));
for rate_index = 1:numel(sample_rate_sweep_hz)
    sweep_rate_hz = sample_rate_sweep_hz(rate_index);
    sweep_record_count = round(capture_duration_s*sweep_rate_hz);
    sweep_pulse_count = round(pulse_duration_s*sweep_rate_hz);
    sweep_delay_samples = true_round_trip_delay_s*sweep_rate_hz;
    sweep_pulse = ones(1, sweep_pulse_count);
    sweep_echo = zeros(1, sweep_record_count);
    for record_index = 1:sweep_record_count
        source_position = (record_index-1)-sweep_delay_samples;
        source_left = floor(source_position);
        source_fraction = source_position-source_left;
        left_value = 0;
        right_value = 0;
        if source_left >= 0 && source_left < sweep_pulse_count
            left_value = sweep_pulse(source_left+1);
        end
        if source_left+1 >= 0 && source_left+1 < sweep_pulse_count
            right_value = sweep_pulse(source_left+2);
        end
        sweep_echo(record_index) = (1-source_fraction)*left_value + ...
            source_fraction*right_value;
    end
    sweep_lags = 0:sweep_record_count-sweep_pulse_count;
    sweep_correlation = zeros(size(sweep_lags));
    for lag_index = 1:numel(sweep_lags)
        lag_samples = sweep_lags(lag_index);
        aligned_sum = 0;
        for pulse_index = 1:sweep_pulse_count
            aligned_sum = aligned_sum + sweep_echo(lag_samples+pulse_index)* ...
                conj(sweep_pulse(pulse_index));
        end
        sweep_correlation(lag_index) = aligned_sum;
    end
    [~, sweep_peak_index] = max(abs(sweep_correlation));
    sweep_integer_delay = sweep_lags(sweep_peak_index);
    sweep_magnitude = abs(sweep_correlation);
    sweep_left = sweep_magnitude(sweep_peak_index-1);
    sweep_center = sweep_magnitude(sweep_peak_index);
    sweep_right = sweep_magnitude(sweep_peak_index+1);
    sweep_denominator = sweep_left-2*sweep_center+sweep_right;
    sweep_offset = 0.5*(sweep_left-sweep_right)/sweep_denominator;
    sweep_refined_delay = sweep_integer_delay+sweep_offset;
    sample_rate_integer_range_m(rate_index) = ...
        speed_of_light_mps*sweep_integer_delay/(2*sweep_rate_hz);
    sample_rate_refined_range_m(rate_index) = ...
        speed_of_light_mps*sweep_refined_delay/(2*sweep_rate_hz);
    sample_rate_bin_spacing_m(rate_index) = ...
        speed_of_light_mps/(2*sweep_rate_hz);
    sample_rate_integer_error_m(rate_index) = ...
        sample_rate_integer_range_m(rate_index)-true_range_m;
    sample_rate_refined_error_m(rate_index) = ...
        sample_rate_refined_range_m(rate_index)-true_range_m;
end
assert(all(abs(sample_rate_integer_error_m) <= ...
    sample_rate_bin_spacing_m/2+comparison_tolerance) && ...
    all(diff(sample_rate_bin_spacing_m) < 0), ...
    'Higher sample rate must shrink bins and integer error must stay bounded.');

%% Sweep 2: fractional-sample delay exposes the integer-lag staircase
fractional_true_delay_samples = fractional_delay_integer_samples + ...
    fractional_delay_sweep_samples;
fractional_integer_estimate_samples = zeros(size(fractional_true_delay_samples));
fractional_refined_estimate_samples = zeros(size(fractional_true_delay_samples));
fractional_integer_error_samples = zeros(size(fractional_true_delay_samples));
fractional_refined_error_samples = zeros(size(fractional_true_delay_samples));
for fraction_index = 1:numel(fractional_true_delay_samples)
    case_delay_samples = fractional_true_delay_samples(fraction_index);
    case_echo = zeros(1, record_sample_count);
    for record_index = 1:record_sample_count
        source_position = (record_index-1)-case_delay_samples;
        source_left = floor(source_position);
        source_fraction = source_position-source_left;
        left_value = 0;
        right_value = 0;
        if source_left >= 0 && source_left < pulse_sample_count
            left_value = transmit_pulse(source_left+1);
        end
        if source_left+1 >= 0 && source_left+1 < pulse_sample_count
            right_value = transmit_pulse(source_left+2);
        end
        case_echo(record_index) = (1-source_fraction)*left_value + ...
            source_fraction*right_value;
    end
    case_correlation = zeros(size(correlation_lags_samples));
    for lag_index = 1:numel(correlation_lags_samples)
        lag_samples = correlation_lags_samples(lag_index);
        aligned_sum = 0;
        for pulse_index = 1:pulse_sample_count
            aligned_sum = aligned_sum + case_echo(lag_samples+pulse_index)* ...
                conj(transmit_pulse(pulse_index));
        end
        case_correlation(lag_index) = aligned_sum;
    end
    [~, case_peak_index] = max(abs(case_correlation));
    case_integer_delay = correlation_lags_samples(case_peak_index);
    case_magnitude = abs(case_correlation);
    case_left = case_magnitude(case_peak_index-1);
    case_center = case_magnitude(case_peak_index);
    case_right = case_magnitude(case_peak_index+1);
    case_denominator = case_left-2*case_center+case_right;
    case_offset = 0.5*(case_left-case_right)/case_denominator;
    case_refined_delay = case_integer_delay+case_offset;
    fractional_integer_estimate_samples(fraction_index) = case_integer_delay;
    fractional_refined_estimate_samples(fraction_index) = case_refined_delay;
    fractional_integer_error_samples(fraction_index) = ...
        case_integer_delay-case_delay_samples;
    fractional_refined_error_samples(fraction_index) = ...
        case_refined_delay-case_delay_samples;
end
assert(all(abs(fractional_integer_error_samples) <= 0.5) && ...
    max(abs(fractional_refined_error_samples)) < ...
    max(abs(fractional_integer_error_samples)), ...
    'Refinement must reduce the reviewed fractional-delay staircase error.');

%% Sweep 3: second-target separation versus finite-pulse correlation width
two_target_correlation = zeros(numel(second_target_separation_s), ...
    numel(correlation_lags_samples));
two_target_peak_count = zeros(size(second_target_separation_s));
two_target_separation_m = speed_of_light_mps*second_target_separation_s/2;
for separation_index = 1:numel(second_target_separation_s)
    second_delay_samples = true_delay_samples + ...
        second_target_separation_s(separation_index)*sample_rate_hz;
    second_echo = zeros(1, record_sample_count);
    for record_index = 1:record_sample_count
        source_position = (record_index-1)-second_delay_samples;
        source_left = floor(source_position);
        source_fraction = source_position-source_left;
        left_value = 0;
        right_value = 0;
        if source_left >= 0 && source_left < pulse_sample_count
            left_value = transmit_pulse(source_left+1);
        end
        if source_left+1 >= 0 && source_left+1 < pulse_sample_count
            right_value = transmit_pulse(source_left+2);
        end
        second_echo(record_index) = second_echo_amplitude* ...
            ((1-source_fraction)*left_value + source_fraction*right_value);
    end
    two_echo_record = clean_echo+second_echo;
    for lag_index = 1:numel(correlation_lags_samples)
        lag_samples = correlation_lags_samples(lag_index);
        aligned_sum = 0;
        for pulse_index = 1:pulse_sample_count
            aligned_sum = aligned_sum + two_echo_record(lag_samples+pulse_index)* ...
                conj(transmit_pulse(pulse_index));
        end
        two_target_correlation(separation_index, lag_index) = aligned_sum;
    end
    case_magnitude = abs(two_target_correlation(separation_index, :));
    local_threshold = 0.25*max(case_magnitude);
    local_peak_count = 0;
    for lag_index = 2:numel(case_magnitude)-1
        if case_magnitude(lag_index) > case_magnitude(lag_index-1) && ...
                case_magnitude(lag_index) >= case_magnitude(lag_index+1) && ...
                case_magnitude(lag_index) > local_threshold
            local_peak_count = local_peak_count+1;
        end
    end
    two_target_peak_count(separation_index) = local_peak_count;
end
assert(isequal(two_target_peak_count, [1 1 2]), ...
    'Reviewed separations must progress from merged to two visible peaks.');

%% Intentionally broken case: forget that measured delay is round trip
% The incorrect one-way conversion uses R_broken = c*tau. It doubles every
% reported target range even though correlation found the same echo lag.
broken_range_m = speed_of_light_mps*refined_delay_s;
broken_factor_of_two_error = broken_range_m/refined_range_m;
broken_model_valid = false;
assert(abs(broken_factor_of_two_error-2) < comparison_tolerance && ...
    ~broken_model_valid, ...
    'The broken one-way formula must produce exactly twice the measured range.');

%% Recovery: restore c*tau/2 and reproduce the baseline private stream
recovered_range_m = speed_of_light_mps*refined_delay_s/2;
recovery_stream = RandStream('mt19937ar', 'Seed', random_seed);
recovery_unit_noise = randn(recovery_stream, 1, record_sample_count);
recovered_received_signal = clean_echo+noise_sigma*recovery_unit_noise;
recovery_correlation = zeros(size(correlation_lags_samples));
for lag_index = 1:numel(correlation_lags_samples)
    lag_samples = correlation_lags_samples(lag_index);
    aligned_sum = 0;
    for pulse_index = 1:pulse_sample_count
        aligned_sum = aligned_sum + ...
            recovered_received_signal(lag_samples+pulse_index)* ...
            conj(transmit_pulse(pulse_index));
    end
    recovery_correlation(lag_index) = aligned_sum;
end
recovery_exact_match = isequal(recovery_unit_noise, unit_noise) && ...
    isequal(recovered_received_signal, received_signal) && ...
    isequal(recovery_correlation, explicit_correlation) && ...
    recovered_range_m == refined_range_m;
assert(recovery_exact_match, ...
    'Clean recovery must restore the two-way formula and exact seeded result.');

