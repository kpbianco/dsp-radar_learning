    display_floor_db <= -40 && display_floor_db >= -160, ...
    'display_floor_db must lie from -160 through -40 dB.');
assert(isnumeric(comparison_tolerance) && isscalar(comparison_tolerance) && ...
    isreal(comparison_tolerance) && ~islogical(comparison_tolerance) && ...
