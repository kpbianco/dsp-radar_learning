%% P13: Prove Zero-Padding Does Not Improve True Resolution
% Guiding question: Why does a smoother FFT plot not necessarily contain more information?
% Learning dependencies: P11 FFT grids and P12 finite-record/window response.
% Base MATLAB only. The finite-record sum is evaluated explicitly at one
% dense-grid frequency before fft is used for the bounded display sweeps.

