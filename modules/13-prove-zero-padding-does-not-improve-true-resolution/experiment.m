assert(isnumeric(probe_frequency_hz) && isscalar(probe_frequency_hz) && ...
    isreal(probe_frequency_hz) && ~islogical(probe_frequency_hz) && ...
    isfinite(probe_frequency_hz), ...
    'probe_frequency_hz must be finite and real.');
assert(isnumeric(display_floor_db) && isscalar(display_floor_db) && ...
    isreal(display_floor_db) && ~islogical(display_floor_db) && ...
