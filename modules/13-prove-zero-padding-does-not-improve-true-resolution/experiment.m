long_sample_count = short_sample_count*long_observation_multiplier;
padding_fft_count = short_sample_count*padding_factors;
observation_sample_count = short_sample_count*observation_multiplier_sweep;
tone_frequency_hz = tone_center_hz + [-0.5 0.5]*tone_separation_hz;
short_rayleigh_hz = fs_hz/short_sample_count;
long_rayleigh_hz = fs_hz/long_sample_count;
comparison_spacing_hz = fs_hz/comparison_fft_count;

assert(long_sample_count <= max_record_samples && ...
    all(observation_sample_count <= max_record_samples), ...
    'An observation length exceeds the P13 sample ceiling.');
assert(max(padding_factors) <= max_padding_factor && ...
    all(padding_fft_count <= max_fft_count) && ...
    comparison_fft_count <= max_fft_count, ...
    'A P13 FFT or padding factor exceeds its resource ceiling.');
assert(numel(padding_factors) <= max_sweep_cases && ...
    numel(observation_multiplier_sweep) <= max_sweep_cases, ...
    'A P13 sweep exceeds the case ceiling.');
assert(short_sample_count <= max_explicit_dft_terms, ...
    'The explicit finite DFT probe exceeds its term ceiling.');
assert(all(mod(comparison_fft_count, observation_sample_count) == 0) && ...
    all(mod(comparison_fft_count, padding_fft_count) == 0), ...
    'FFT grids must be integer refinements of every measured record.');
assert(all(tone_frequency_hz > 0) && all(tone_frequency_hz < fs_hz/2) && ...
    probe_frequency_hz > 0 && probe_frequency_hz < fs_hz/2, ...
    'Tone and probe frequencies must lie strictly between DC and Nyquist.');
assert(tone_separation_hz < short_rayleigh_hz && ...
    tone_separation_hz > long_rayleigh_hz, ...
    'Tone separation must be below the short and above the long Rayleigh interval.');
assert(all(abs(tone_frequency_hz/comparison_spacing_hz - ...
    round(tone_frequency_hz/comparison_spacing_hz)) < comparison_tolerance) && ...
    abs(tone_center_hz/comparison_spacing_hz - ...
    round(tone_center_hz/comparison_spacing_hz)) < comparison_tolerance, ...
    'Tone frequencies must align with the comparison display grid.');
assert(abs(probe_frequency_hz/(fs_hz/padding_fft_count(end)) - ...
    round(probe_frequency_hz/(fs_hz/padding_fft_count(end)))) < ...
    comparison_tolerance, ...
    'Probe frequency must align with the densest padding grid.');

%% Deterministic longest record and short-record baseline
max_sample_index = 0:(long_sample_count - 1);
max_time_s = max_sample_index/fs_hz;
tone_1_v = tone_amplitude_v*exp(1j*( ...
    2*pi*tone_frequency_hz(1)*max_time_s + tone_phase_rad(1)));
tone_2_v = tone_amplitude_v*exp(1j*( ...
    2*pi*tone_frequency_hz(2)*max_time_s + tone_phase_rad(2)));
stream = RandStream('mt19937ar', 'Seed', random_seed);
raw_complex_noise_v = 1/sqrt(2)*( ...
    randn(stream, 1, long_sample_count) + ...
    1j*randn(stream, 1, long_sample_count));
if noise_rms_v > 0
    complex_noise_v = noise_rms_v*raw_complex_noise_v/ ...
        sqrt(mean(abs(raw_complex_noise_v).^2));
else
    complex_noise_v = complex(zeros(1, long_sample_count));
end
rectangular_window = ones(1, long_sample_count);
long_record_v = (tone_1_v + tone_2_v + complex_noise_v).*rectangular_window;
short_record_v = long_record_v(1:short_sample_count);
short_sample_index = 0:(short_sample_count - 1);
short_time_s = short_sample_index/fs_hz;
short_duration_s = short_sample_count/fs_hz;
long_duration_s = long_sample_count/fs_hz;

%% Sweep 1: change only zero-padding factor for the same short samples
padding_case_count = numel(padding_factors);
padding_frequency_axis_hz = cell(1, padding_case_count);
padding_spectrum_v = cell(1, padding_case_count);
padding_display_spacing_hz = zeros(1, padding_case_count);
padding_rayleigh_hz = short_rayleigh_hz*ones(1, padding_case_count);
padding_main_lobe_null_to_null_hz = ...
    2*short_rayleigh_hz*ones(1, padding_case_count);
padding_measured_sample_count = short_sample_count*ones(1, padding_case_count);
padding_appended_zero_count = zeros(1, padding_case_count);
original_grid_error_v = zeros(1, padding_case_count);

base_projection_v = fft(short_record_v)/short_sample_count;
for sweep_index = 1:padding_case_count
    padding_factor = padding_factors(sweep_index);
    sweep_fft_count = padding_fft_count(sweep_index);
    % X[k] = sum_{n=0}^{N-1} x[n] exp(-j*2*pi*k*n/Nfft).
    % fft(x,Nfft) appends zeros after the same N measured samples.
    sweep_projection_v = fft(short_record_v, sweep_fft_count)/short_sample_count;
    padding_spectrum_v{sweep_index} = abs(sweep_projection_v);
    padding_frequency_axis_hz{sweep_index} = ...
        (0:(sweep_fft_count - 1))*fs_hz/sweep_fft_count;
    padding_display_spacing_hz(sweep_index) = fs_hz/sweep_fft_count;
    padding_appended_zero_count(sweep_index) = ...
        sweep_fft_count - short_sample_count;
    original_grid_projection_v = sweep_projection_v(1:padding_factor:end);
    original_grid_error_v(sweep_index) = ...
        max(abs(original_grid_projection_v - base_projection_v));
end

% Evaluate one dense point directly before trusting the FFT convenience.
explicit_probe_v = sum(short_record_v.*exp( ...
    -1j*2*pi*probe_frequency_hz*short_time_s))/short_sample_count;
dense_padding_spacing_hz = padding_display_spacing_hz(end);
probe_fft_index = round(probe_frequency_hz/dense_padding_spacing_hz) + 1;
dense_probe_v = fft(short_record_v, padding_fft_count(end))/short_sample_count;
dense_probe_v = dense_probe_v(probe_fft_index);
explicit_probe_error_v = abs(explicit_probe_v - dense_probe_v);

assert(max(original_grid_error_v) < comparison_tolerance, ...
    'Zero-padding must preserve every original N-point DFT value.');
assert(explicit_probe_error_v < comparison_tolerance, ...
    'Explicit finite-record projection and dense FFT point must agree.');
assert(all(padding_measured_sample_count == short_sample_count) && ...
    all(padding_rayleigh_hz == short_rayleigh_hz), ...
    'Padding must not change measured samples or the Rayleigh interval.');
assert(all(diff(padding_display_spacing_hz) < 0), ...
    'Larger padding factors must make only the display grid denser.');

%% Sweep 2: change only measured observation length using shared prefixes
observation_case_count = numel(observation_multiplier_sweep);
comparison_frequency_axis_hz = ...
    (0:(comparison_fft_count - 1))*comparison_spacing_hz;
observation_spectrum_v = cell(1, observation_case_count);
observation_duration_s = zeros(1, observation_case_count);
observation_rayleigh_hz = zeros(1, observation_case_count);
observation_main_lobe_null_to_null_hz = zeros(1, observation_case_count);
observation_noise_rms_realized_v = zeros(1, observation_case_count);
separation_rayleigh_ratio = zeros(1, observation_case_count);
midpoint_to_tone_level_db = zeros(1, observation_case_count);
dominant_peak_count = zeros(1, observation_case_count);

tone_1_grid_index = round(tone_frequency_hz(1)/comparison_spacing_hz) + 1;
tone_2_grid_index = round(tone_frequency_hz(2)/comparison_spacing_hz) + 1;
midpoint_grid_index = round(tone_center_hz/comparison_spacing_hz) + 1;

for sweep_index = 1:observation_case_count
    sweep_sample_count = observation_sample_count(sweep_index);
    sweep_record_v = long_record_v(1:sweep_sample_count);
    sweep_projection_v = fft(sweep_record_v, comparison_fft_count)/ ...
        sweep_sample_count;
    sweep_magnitude_v = abs(sweep_projection_v);
    observation_spectrum_v{sweep_index} = sweep_magnitude_v;
    observation_duration_s(sweep_index) = sweep_sample_count/fs_hz;
    observation_rayleigh_hz(sweep_index) = fs_hz/sweep_sample_count;
    observation_main_lobe_null_to_null_hz(sweep_index) = ...
        2*observation_rayleigh_hz(sweep_index);
    observation_noise_rms_realized_v(sweep_index) = sqrt(mean(abs( ...
        complex_noise_v(1:sweep_sample_count)).^2));
    separation_rayleigh_ratio(sweep_index) = ...
        tone_separation_hz/observation_rayleigh_hz(sweep_index);

    tone_reference_v = sqrt(sweep_magnitude_v(tone_1_grid_index)* ...
        sweep_magnitude_v(tone_2_grid_index));
    midpoint_to_tone_level_db(sweep_index) = 20*log10(max( ...
        sweep_magnitude_v(midpoint_grid_index)/tone_reference_v, ...
        10^(display_floor_db/20)));

    search_mask = (comparison_frequency_axis_hz >= ...
        tone_frequency_hz(1) - short_rayleigh_hz) & ...
        (comparison_frequency_axis_hz <= ...
        tone_frequency_hz(2) + short_rayleigh_hz);
    search_magnitude_v = sweep_magnitude_v(search_mask);
    dominant_threshold_v = 0.5*max(search_magnitude_v);
    local_peak_mask = search_magnitude_v(2:end-1) > ...
        search_magnitude_v(1:end-2) & ...
        search_magnitude_v(2:end-1) >= search_magnitude_v(3:end) & ...
        search_magnitude_v(2:end-1) >= dominant_threshold_v;
    dominant_peak_count(sweep_index) = sum(local_peak_mask);
end

assert(all(diff(observation_duration_s) > 0) && ...
    all(diff(observation_rayleigh_hz) < 0), ...
    'More measured time must reduce the Rayleigh interval.');
assert(midpoint_to_tone_level_db(1) > 0 && ...
    midpoint_to_tone_level_db(end) < -20, ...
    'The short pair must blend while the longest record separates it deeply.');
assert(dominant_peak_count(1) == 1 && dominant_peak_count(end) == 2, ...
    'The short record must have one dominant peak and the long record two.');

%% Broken case: call the 16x display spacing true resolution
broken_claimed_resolution_hz = padding_display_spacing_hz(end);
broken_claimed_separation_cells = ...
    tone_separation_hz/broken_claimed_resolution_hz;
recovered_short_resolution_hz = short_rayleigh_hz;
recovered_long_resolution_hz = long_rayleigh_hz;
recovered_short_separation_ratio = ...
    tone_separation_hz/recovered_short_resolution_hz;
recovered_long_separation_ratio = ...
    tone_separation_hz/recovered_long_resolution_hz;

assert(broken_claimed_resolution_hz < tone_separation_hz && ...
    recovered_short_resolution_hz > tone_separation_hz, ...
    'The broken grid-spacing claim must contradict the short-record response.');
assert(recovered_long_resolution_hz < recovered_short_resolution_hz && ...
    recovered_long_separation_ratio > 1, ...
    'Recovery must improve resolution with measured time, not zeros.');

