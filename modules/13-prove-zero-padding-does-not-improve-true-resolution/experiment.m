    all(isfinite(observation_multiplier_sweep)) && ...
    all(observation_multiplier_sweep == floor(observation_multiplier_sweep)) && ...
    all(diff(observation_multiplier_sweep) > 0) && ...
    isequal(observation_multiplier_sweep, [1 2 4]) && ...
    observation_multiplier_sweep(end) == long_observation_multiplier, ...
    'observation_multiplier_sweep must be exactly [1 2 4].');
assert(isnumeric(comparison_fft_count) && isscalar(comparison_fft_count) && ...
    isreal(comparison_fft_count) && ~islogical(comparison_fft_count) && ...
    isfinite(comparison_fft_count) && comparison_fft_count >= short_sample_count && ...
