assert(isnumeric(lowpass_tap_count) && isscalar(lowpass_tap_count) && ...
    isreal(lowpass_tap_count) && ~islogical(lowpass_tap_count) && ...
    isfinite(lowpass_tap_count), ...
    'lowpass_tap_count must be a finite real nonlogical scalar.');
assert(lo_frequency_hz == carrier_frequency_hz && ...
    lo_frequency_hz < fs_hz/2 && ...
    lowpass_cutoff_hz > 0 && lowpass_cutoff_hz < fs_hz/2 && ...
    lowpass_tap_count == 129 && lowpass_tap_count == floor(lowpass_tap_count) && ...
    mod(lowpass_tap_count, 2) == 1, ...
    ['The baseline LO must exactly match the carrier, and the canonical ' ...
    'odd 129-tap low-pass FIR must remain valid.']);

assert(isnumeric(lo_frequency_sweep_hz) && isvector(lo_frequency_sweep_hz) && ...
    isreal(lo_frequency_sweep_hz) && ~islogical(lo_frequency_sweep_hz) && ...
    all(isfinite(lo_frequency_sweep_hz)) && ...
    isequal(lo_frequency_sweep_hz, [204 240 276]), ...
    'lo_frequency_sweep_hz must be exactly [204 240 276].');
assert(isnumeric(lo_phase_sweep_rad) && isvector(lo_phase_sweep_rad) && ...
    isreal(lo_phase_sweep_rad) && ~islogical(lo_phase_sweep_rad) && ...
    all(isfinite(lo_phase_sweep_rad)) && ...
    isequal(lo_phase_sweep_rad, [0 pi/2 pi]), ...
    'lo_phase_sweep_rad must be exactly [0 pi/2 pi].');
assert(isnumeric(broken_lo_frequency_hz) && ...
    isscalar(broken_lo_frequency_hz) && isreal(broken_lo_frequency_hz) && ...
    ~islogical(broken_lo_frequency_hz) && ...
    isfinite(broken_lo_frequency_hz) && broken_lo_frequency_hz == 216, ...
    'broken_lo_frequency_hz must be the canonical 216 Hz case.');

all_lo_frequencies_hz = [lo_frequency_hz lo_frequency_sweep_hz ...
    broken_lo_frequency_hz];
desired_sweep_frequencies_hz = carrier_frequency_hz - lo_frequency_sweep_hz;
minimum_sum_image_frequency_hz = carrier_frequency_hz + ...
    min(all_lo_frequencies_hz);
assert(all(all_lo_frequencies_hz > 0) && ...
    all(all_lo_frequencies_hz < fs_hz/2) && ...
    carrier_frequency_hz + max(all_lo_frequencies_hz) < fs_hz/2 && ...
    max(abs(desired_sweep_frequencies_hz)) < lowpass_cutoff_hz && ...
    lowpass_cutoff_hz < minimum_sum_image_frequency_hz/3, ...
    ['The low-pass must retain every desired signed beat and remain far ' ...
    'below every sum-frequency image.']);
record_duration_s = record_sample_count/fs_hz;
coherent_frequencies_hz = [carrier_frequency_hz all_lo_frequencies_hz];
assert(all(coherent_frequencies_hz*record_duration_s == ...
    floor(coherent_frequencies_hz*record_duration_s)), ...
    'Carrier and LO controls must complete integer cycles in the record.');

assert(isnumeric(evaluation_guard_sample_count) && ...
    isscalar(evaluation_guard_sample_count) && ...
    isreal(evaluation_guard_sample_count) && ...
    ~islogical(evaluation_guard_sample_count) && ...
    isfinite(evaluation_guard_sample_count) && ...
    evaluation_guard_sample_count == 192 && ...
    evaluation_guard_sample_count == floor(evaluation_guard_sample_count), ...
    'evaluation_guard_sample_count must be the canonical 192 samples.');
assert(max_record_samples == 4096 && max_fft_length == 4096 && ...
    max_filter_taps == 129 && max_sweep_cases == 3 && ...
    max_stored_numeric_values == 180000 && max_figure_groups == 5, ...
    'P17 resource ceilings must remain fixed.');
actual_sweep_case_count = numel(lo_frequency_sweep_hz) + ...
    numel(lo_phase_sweep_rad);
actual_figure_group_count = 5;
estimated_stored_numeric_values = record_sample_count*(24 + ...
    3*numel(lo_frequency_sweep_hz) + 3*numel(lo_phase_sweep_rad));
assert(record_sample_count <= max_record_samples && ...
    record_sample_count <= max_fft_length && ...
    lowpass_tap_count <= max_filter_taps && ...
    numel(lo_frequency_sweep_hz) <= max_sweep_cases && ...
    numel(lo_phase_sweep_rad) <= max_sweep_cases && ...
    actual_sweep_case_count <= 2*max_sweep_cases && ...
    estimated_stored_numeric_values <= max_stored_numeric_values && ...
    actual_figure_group_count <= max_figure_groups && ...
    evaluation_guard_sample_count > lowpass_tap_count && ...
    2*evaluation_guard_sample_count < record_sample_count, ...
    'A P17 record, FFT, FIR, sweep, storage, guard, or figure ceiling was exceeded.');

%% Deterministic real passband input and explicit complex oscillator
time_s = (0:record_sample_count-1)/fs_hz;
private_stream = RandStream('mt19937ar', 'Seed', random_seed);
noise_v = noise_rms_v*randn(private_stream, 1, record_sample_count);
real_passband_v = carrier_amplitude_v*cos(2*pi*carrier_frequency_hz*time_s + ...
    carrier_phase_rad) + noise_v;
complex_oscillator = exp(-1j*(2*pi*lo_frequency_hz*time_s + lo_phase_rad));
mixed_signal_v = real_passband_v.*complex_oscillator;

%% Build the base-MATLAB low-pass FIR by hand and remove its group delay
% h_ideal[n] = 2*fc/fs at n=0 and sin(2*pi*fc*n/fs)/(pi*n) otherwise.
filter_half_length = (lowpass_tap_count-1)/2;
centered_tap_index = -filter_half_length:filter_half_length;
ideal_fir = zeros(1, lowpass_tap_count);
for tap_index = 1:lowpass_tap_count
    centered_index = centered_tap_index(tap_index);
    if centered_index == 0
        ideal_fir(tap_index) = 2*lowpass_cutoff_hz/fs_hz;
    else
        ideal_fir(tap_index) = sin(2*pi*lowpass_cutoff_hz* ...
            centered_index/fs_hz)/(pi*centered_index);
    end
end
hamming_window = 0.54 - 0.46*cos(2*pi*(0:lowpass_tap_count-1)/ ...
    (lowpass_tap_count-1));
lowpass_fir = ideal_fir.*hamming_window;
lowpass_fir = lowpass_fir/sum(lowpass_fir);

mixed_full_v = conv(mixed_signal_v, lowpass_fir, 'full');
filtered_mixer_v = mixed_full_v(filter_half_length+1: ...
    filter_half_length+record_sample_count);
% A real cosine divides equally between +fc and -fc, so the retained desired
% term has half the RF peak amplitude. This explicit 2x calibration restores it.
baseband_iq_v = 2*filtered_mixer_v;

expected_baseband_frequency_hz = carrier_frequency_hz - lo_frequency_hz;
expected_baseband_iq_v = carrier_amplitude_v*exp(1j*( ...
    2*pi*expected_baseband_frequency_hz*time_s + ...
    carrier_phase_rad - lo_phase_rad));
image_frequency_hz = -(carrier_frequency_hz + lo_frequency_hz);
evaluation_mask = false(1, record_sample_count);
evaluation_mask(evaluation_guard_sample_count+1: ...
    record_sample_count-evaluation_guard_sample_count) = true;
evaluation_time_s = time_s(evaluation_mask);
evaluation_count = sum(evaluation_mask);

desired_projection = sum(baseband_iq_v(evaluation_mask).*exp(-1j*2*pi* ...
    expected_baseband_frequency_hz*evaluation_time_s))/evaluation_count;
estimated_baseband_amplitude_v = abs(desired_projection);
estimated_baseband_phase_rad = angle(desired_projection);
baseband_rmse_v = sqrt(mean(abs(baseband_iq_v(evaluation_mask) - ...
    expected_baseband_iq_v(evaluation_mask)).^2));
unscaled_mixer_gain = abs(sum(filtered_mixer_v(evaluation_mask).* ...
    exp(-1j*2*pi*expected_baseband_frequency_hz*evaluation_time_s))/ ...
    evaluation_count)/carrier_amplitude_v;
pre_filter_image_amplitude_v = abs(sum(mixed_signal_v(evaluation_mask).* ...
    exp(-1j*2*pi*image_frequency_hz*evaluation_time_s))/evaluation_count);
post_filter_image_amplitude_v = abs(sum(filtered_mixer_v(evaluation_mask).* ...
    exp(-1j*2*pi*image_frequency_hz*evaluation_time_s))/evaluation_count);
image_suppression_db = 20*log10(max(pre_filter_image_amplitude_v, eps)/ ...
    max(post_filter_image_amplitude_v, eps));

fprintf('\nP17 baseline: real passband multiplied by exp(-j2*pi*fLO*t)\n');
fprintf('  expected signed baseband frequency: %+.1f Hz\n', ...
    expected_baseband_frequency_hz);
fprintf('  unscaled real-input mixer gain: %.4f (ideal 0.5)\n', ...
    unscaled_mixer_gain);
fprintf('  calibrated baseband amplitude: %.4f V\n', ...
    estimated_baseband_amplitude_v);
fprintf('  calibrated baseband phase: %+.4f rad\n', ...
    estimated_baseband_phase_rad);
fprintf('  sum-frequency image suppression: %.1f dB\n', ...
    image_suppression_db);

