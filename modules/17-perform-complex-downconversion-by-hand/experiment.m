    isfinite(carrier_phase_rad), ...
    'carrier_phase_rad must be a finite real nonlogical scalar.');
assert(isnumeric(noise_rms_v) && isscalar(noise_rms_v) && ...
    isreal(noise_rms_v) && ~islogical(noise_rms_v) && ...
    isfinite(noise_rms_v), ...
    'noise_rms_v must be a finite real nonlogical scalar.');
assert(carrier_frequency_hz == 240 && carrier_frequency_hz < fs_hz/2 && ...
    carrier_amplitude_v > 0 && carrier_amplitude_v <= 2 && ...
    noise_rms_v >= 0 && noise_rms_v <= 0.01, ...
    ['The canonical 240 Hz carrier and the amplitude/noise bounds must ' ...
    'remain fixed for the labeled sweeps.']);

assert(isnumeric(lo_frequency_hz) && isscalar(lo_frequency_hz) && ...
