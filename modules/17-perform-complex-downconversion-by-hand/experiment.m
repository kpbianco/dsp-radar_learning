end

%% Broken case: use the opposite oscillator sign and select the wrong RF side
% With a real input, +j mixing does not produce nothing. It selects the
% negative-frequency conjugate and reverses the intended signed baseband.
broken_expected_frequency_hz = carrier_frequency_hz - ...
    broken_lo_frequency_hz;
wrong_side_oscillator = exp(+1j*2*pi*broken_lo_frequency_hz*time_s);
wrong_side_mixed_v = real_passband_v.*wrong_side_oscillator;
wrong_side_full_v = conv(wrong_side_mixed_v, lowpass_fir, 'full');
wrong_side_baseband_v = 2*wrong_side_full_v(filter_half_length+1: ...
    filter_half_length+record_sample_count);
wrong_side_phase_rad = unwrap(angle(wrong_side_baseband_v(evaluation_mask)));
wrong_side_estimated_frequency_hz = mean(diff(wrong_side_phase_rad))* ...
    fs_hz/(2*pi);

recovery_oscillator = exp(-1j*2*pi*broken_lo_frequency_hz*time_s);
recovery_mixed_v = real_passband_v.*recovery_oscillator;
recovery_full_v = conv(recovery_mixed_v, lowpass_fir, 'full');
recovery_baseband_v = 2*recovery_full_v(filter_half_length+1: ...
    filter_half_length+record_sample_count);
recovery_phase_rad = unwrap(angle(recovery_baseband_v(evaluation_mask)));
recovery_estimated_frequency_hz = mean(diff(recovery_phase_rad))*fs_hz/(2*pi);

figure('Name', 'P17 broken side selection and recovery', 'Tag', 'P17', ...
    'Color', 'w', 'Position', [190 110 1100 480]);
subplot(1, 2, 1);
plot(real(wrong_side_baseband_v(trajectory_indices)), ...
    imag(wrong_side_baseband_v(trajectory_indices)), '-', ...
    'Color', [0.85 0.25 0.15]);
grid on; axis equal; xlim([-1.15 1.15]); ylim([-1.15 1.15]);
xlabel('I (V)'); ylabel('Q (V)');
title(sprintf('Broken +j LO: %+.2f Hz (conjugate side)', ...
    wrong_side_estimated_frequency_hz));

subplot(1, 2, 2);
plot(real(recovery_baseband_v(trajectory_indices)), ...
    imag(recovery_baseband_v(trajectory_indices)), '-', ...
    'Color', [0.20 0.55 0.35]);
grid on; axis equal; xlim([-1.15 1.15]); ylim([-1.15 1.15]);
xlabel('I (V)'); ylabel('Q (V)');
title(sprintf('Recovered -j LO: %+.2f Hz (expected %+.0f Hz)', ...
    recovery_estimated_frequency_hz, broken_expected_frequency_hz));

fprintf('\nP17 wrong-side case at LO %.0f Hz\n', broken_lo_frequency_hz);
fprintf('  intended -j LO signed frequency: %+.1f Hz\n', ...
    broken_expected_frequency_hz);
fprintf('  broken +j LO estimated frequency: %+.2f Hz\n', ...
    wrong_side_estimated_frequency_hz);
fprintf('  recovered -j LO estimated frequency: %+.2f Hz\n', ...
