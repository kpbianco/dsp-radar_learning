fs_hz = 2048;
record_sample_count = 4096;
carrier_frequency_hz = 240;
carrier_amplitude_v = 1.00;
carrier_phase_rad = 0.35;
noise_rms_v = 0.002;

lo_frequency_hz = 240;
lo_phase_rad = 0;
lowpass_cutoff_hz = 80;
lowpass_tap_count = 129;

lo_frequency_sweep_hz = [204 240 276];
lo_phase_sweep_rad = [0 pi/2 pi];

broken_lo_frequency_hz = 216;
evaluation_guard_sample_count = 192;

