%% P17: Perform Complex Downconversion by Hand
% Guiding question: How does multiplying by a complex oscillator move an RF/IF signal to baseband?
% Learning dependencies: P11 signed FFT bins, P12 mirrored real spectra,
% and P16 analytic/IQ phase. Base MATLAB only: mixing, the windowed-sinc
% low-pass FIR, convolution, signed-frequency metrics, and I/Q are explicit.

