title(sprintf('After explicit LPF: image suppression %.1f dB', ...
    image_suppression_db));

%% Sweep 1: change only LO frequency to expose signed translation
lo_sweep_expected_frequency_hz = carrier_frequency_hz - ...
    lo_frequency_sweep_hz;
lo_sweep_estimated_frequency_hz = zeros(size(lo_frequency_sweep_hz));
lo_sweep_amplitude_v = zeros(size(lo_frequency_sweep_hz));
lo_sweep_baseband_iq_v = zeros(numel(lo_frequency_sweep_hz), ...
    record_sample_count);
rotation_labels = {'counterclockwise', 'stationary', 'clockwise'};

figure('Name', 'P17 LO-frequency sweep', 'Tag', 'P17', ...
    'Color', 'w', 'Position', [130 70 1100 780]);
for case_index = 1:numel(lo_frequency_sweep_hz)
    case_lo_frequency_hz = lo_frequency_sweep_hz(case_index);
    case_oscillator = exp(-1j*(2*pi*case_lo_frequency_hz*time_s + ...
        lo_phase_rad));
    case_mixed_v = real_passband_v.*case_oscillator;
    case_full_v = conv(case_mixed_v, lowpass_fir, 'full');
    case_baseband_v = 2*case_full_v(filter_half_length+1: ...
        filter_half_length+record_sample_count);
    case_phase_rad = unwrap(angle(case_baseband_v(evaluation_mask)));
    case_expected_frequency_hz = carrier_frequency_hz - case_lo_frequency_hz;
    case_projection = sum(case_baseband_v(evaluation_mask).*exp(-1j*2*pi* ...
        case_expected_frequency_hz*evaluation_time_s))/evaluation_count;

    lo_sweep_baseband_iq_v(case_index, :) = case_baseband_v;
    lo_sweep_estimated_frequency_hz(case_index) = ...
        mean(diff(case_phase_rad))*fs_hz/(2*pi);
    lo_sweep_amplitude_v(case_index) = abs(case_projection);

    subplot(numel(lo_frequency_sweep_hz), 1, case_index);
    plot(real(case_baseband_v(trajectory_indices)), ...
        imag(case_baseband_v(trajectory_indices)), '-', ...
        'Color', [0.45 0.20 0.70]);
    grid on; axis equal; xlim([-1.15 1.15]); ylim([-1.15 1.15]);
    xlabel('I (V)'); ylabel('Q (V)');
    title(sprintf(['LO %.0f Hz -> expected %+.0f Hz, estimated %+.2f Hz ' ...
        '(%s rotation)'], case_lo_frequency_hz, case_expected_frequency_hz, ...
        lo_sweep_estimated_frequency_hz(case_index), ...
        rotation_labels{case_index}));
end

%% Sweep 2: change only LO phase; frequency and magnitude stay fixed
phase_sweep_estimated_phase_rad = zeros(size(lo_phase_sweep_rad));
phase_sweep_amplitude_v = zeros(size(lo_phase_sweep_rad));
phase_sweep_baseband_iq_v = zeros(numel(lo_phase_sweep_rad), ...
    record_sample_count);

figure('Name', 'P17 LO-phase sweep', 'Tag', 'P17', ...
    'Color', 'w', 'Position', [160 90 1100 760]);
for case_index = 1:numel(lo_phase_sweep_rad)
    case_lo_phase_rad = lo_phase_sweep_rad(case_index);
