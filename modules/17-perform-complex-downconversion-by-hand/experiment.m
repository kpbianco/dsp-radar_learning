        filter_half_length+record_sample_count);
    case_projection = sum(case_baseband_v(evaluation_mask))/evaluation_count;

    phase_sweep_baseband_iq_v(case_index, :) = case_baseband_v;
    phase_sweep_estimated_phase_rad(case_index) = angle(case_projection);
    phase_sweep_amplitude_v(case_index) = abs(case_projection);

    subplot(1, numel(lo_phase_sweep_rad), case_index);
    plot(real(case_baseband_v(trajectory_indices)), ...
