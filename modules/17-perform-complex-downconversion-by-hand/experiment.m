grid on; axis equal;
xlabel('I (V)'); ylabel('Q (V)');
title('Exact LO: the baseband phasor is stationary');

%% Signed spectra before mixing, after mixing, and after filtering
frequency_hz = (-record_sample_count/2:record_sample_count/2-1)* ...
    fs_hz/record_sample_count;
passband_spectrum_v = abs(fftshift(fft(real_passband_v)))/record_sample_count;
mixed_spectrum_v = abs(fftshift(fft(mixed_signal_v)))/record_sample_count;
filtered_spectrum_v = abs(fftshift(fft(filtered_mixer_v)))/record_sample_count;
plot_floor_v = 1e-8;

figure('Name', 'P17 spectra through downconversion', 'Tag', 'P17', ...
