recovery_observed_frequency_hz = [recovery_intended_frequency_hz(1) ...
    recovery_fs_hz*diff(unwrap(angle(recovery_phasor_v)))/(2*pi)];
recovery_frequency_error_hz = max(abs(recovery_observed_frequency_hz(2:end)- ...
    recovery_intended_frequency_hz(2:end)));
recovery_phase_slope_margin_hz = recovery_fs_hz/2 - ...
    max(recovery_intended_frequency_hz);
recovery_frequency_spacing_hz = recovery_fs_hz/recovery_sample_count;
recovery_rf_v = real(recovery_phasor_v);
recovery_spectrum_v = fft(recovery_rf_v);
recovery_amplitude_v = 2*abs( ...
    recovery_spectrum_v(1:recovery_sample_count/2+1))/recovery_sample_count;
recovery_amplitude_v([1 end]) = recovery_amplitude_v([1 end])/2;
recovery_maximum_order = floor(min(broken_carrier_frequency_hz, ...
    recovery_fs_hz/2-broken_carrier_frequency_hz)/message_frequency_hz);
recovery_orders = -recovery_maximum_order:recovery_maximum_order;
recovery_line_frequencies_hz = broken_carrier_frequency_hz + ...
    recovery_orders*message_frequency_hz;
recovery_line_indices = round( ...
    recovery_line_frequencies_hz/recovery_frequency_spacing_hz) + 1;
recovery_line_power_v2 = recovery_amplitude_v(recovery_line_indices).^2;
recovery_total_line_power_v2 = sum(recovery_line_power_v2);
recovery_occupied_sideband_order = recovery_maximum_order;
for candidate_order = 0:recovery_maximum_order
    inside = abs(recovery_orders) <= candidate_order;
    if sum(recovery_line_power_v2(inside))/recovery_total_line_power_v2 >= ...
            occupied_power_fraction
        recovery_occupied_sideband_order = candidate_order;
        break;
    end
end
recovery_occupied_bandwidth_hz = 2*recovery_occupied_sideband_order* ...
    message_frequency_hz;
recovery_occupied_upper_frequency_hz = broken_carrier_frequency_hz + ...
    recovery_occupied_bandwidth_hz/2;
recovery_occupied_margin_hz = recovery_fs_hz/2 - ...
    recovery_occupied_upper_frequency_hz;
assert(broken_nyquist_margin_hz < 0 && ...
    broken_alias_sample_fraction > 0.15 && ...
    recovery_fs_hz >= minimum_recovery_fs_hz && ...
    recovery_phase_slope_margin_hz >= recovery_guard_hz && ...
    recovery_occupied_sideband_order == 51 && ...
    recovery_occupied_bandwidth_hz == broken_carson_bandwidth_hz && ...
    recovery_occupied_margin_hz >= recovery_guard_hz && ...
    recovery_frequency_error_hz < 55, ...
    ['The failure must wrap phase increments, while recovery must preserve ' ...
    'the documented 98% occupied-band target with guard.']);

broken_signed_frequency_hz = (-sample_count/2:sample_count/2-1)* ...
    frequency_spacing_hz;
broken_spectrum_v = fftshift(fft(broken_phasor_v));
broken_amplitude_v = abs(broken_spectrum_v)/sample_count;
