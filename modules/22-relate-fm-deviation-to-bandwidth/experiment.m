%% Deterministic baseline: frequency motion writes phase modulation
private_stream = RandStream('mt19937ar', 'Seed', random_seed);
time_s = (0:sample_count-1)/fs_hz;
frequency_spacing_hz = fs_hz/sample_count;
frequency_axis_hz = (0:sample_count/2)*frequency_spacing_hz;
time_view_count = round(time_view_duration_s*fs_hz);
time_view = 1:time_view_count;

message = cos(2*pi*message_frequency_hz*time_s);
modulation_index = frequency_deviation_hz/message_frequency_hz;
instantaneous_phase_rad = 2*pi*carrier_frequency_hz*time_s + ...
    modulation_index*sin(2*pi*message_frequency_hz*time_s);
instantaneous_frequency_hz = carrier_frequency_hz + ...
    frequency_deviation_hz*message;
fm_phasor_v = carrier_amplitude_v*exp(1j*instantaneous_phase_rad);
clean_rf_v = real(fm_phasor_v);
receiver_noise_v = receiver_noise_rms_v* ...
    randn(private_stream, 1, sample_count);
received_rf_v = clean_rf_v + receiver_noise_v;
measured_frequency_hz = [instantaneous_frequency_hz(1) ...
    fs_hz*diff(unwrap(angle(fm_phasor_v)))/(2*pi)];

clean_spectrum_v = fft(clean_rf_v);
received_spectrum_v = fft(received_rf_v);
clean_amplitude_v = 2*abs(clean_spectrum_v(1:sample_count/2+1))/ ...
    sample_count;
received_amplitude_v = 2*abs( ...
    received_spectrum_v(1:sample_count/2+1))/sample_count;
clean_amplitude_v([1 end]) = clean_amplitude_v([1 end])/2;
received_amplitude_v([1 end]) = received_amplitude_v([1 end])/2;

maximum_line_order = floor(min(carrier_frequency_hz, ...
    fs_hz/2-carrier_frequency_hz)/message_frequency_hz);
line_orders = -maximum_line_order:maximum_line_order;
line_frequencies_hz = carrier_frequency_hz + ...
    line_orders*message_frequency_hz;
line_indices = round(line_frequencies_hz/frequency_spacing_hz) + 1;
line_power_v2 = clean_amplitude_v(line_indices).^2;
total_line_power_v2 = sum(line_power_v2);
occupied_sideband_order = maximum_line_order;
for candidate_order = 0:maximum_line_order
    inside = abs(line_orders) <= candidate_order;
    if sum(line_power_v2(inside))/total_line_power_v2 >= ...
            occupied_power_fraction
        occupied_sideband_order = candidate_order;
        break;
    end
end
occupied_bandwidth_hz = 2*occupied_sideband_order*message_frequency_hz;
carson_bandwidth_hz = 2*(frequency_deviation_hz+message_frequency_hz);
phasor_magnitude_error_v = max(abs(abs(fm_phasor_v)-carrier_amplitude_v));
frequency_motion_error_hz = max(abs( ...
    measured_frequency_hz(2:end)-instantaneous_frequency_hz(2:end)));

assert(phasor_magnitude_error_v < 1e-12 && frequency_motion_error_hz < 6, ...
    'The baseline must preserve amplitude and its phase slope must follow f_i.');
assert(occupied_sideband_order >= 4 && occupied_sideband_order <= 6, ...
    'The beta=4 baseline should need several Bessel-like sideband pairs.');

