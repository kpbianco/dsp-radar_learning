%% Deterministic baseline: one message tone makes two RF sidebands
private_stream = RandStream('mt19937ar', 'Seed', random_seed);
time_s = (0:sample_count-1)/fs_hz;
frequency_spacing_hz = fs_hz/sample_count;
frequency_axis_hz = (0:sample_count/2)*frequency_spacing_hz;
signed_frequency_axis_hz = [0:sample_count/2 ...
    -sample_count/2+1:-1]*frequency_spacing_hz;
analytic_mask = zeros(1, sample_count);
analytic_mask(1) = 1;
analytic_mask(2:sample_count/2) = 2;
analytic_mask(sample_count/2+1) = 1;
lowpass_mask = abs(signed_frequency_axis_hz) <= ...
    recovery_lowpass_cutoff_hz;
time_view_count = round(time_view_duration_s*fs_hz);
time_view = 1:time_view_count;

message = cos(2*pi*message_frequency_hz*time_s);
signed_envelope_v = carrier_amplitude_v*( ...
    1 + baseline_modulation_depth*message);
carrier = cos(2*pi*carrier_frequency_hz*time_s);
clean_rf_v = signed_envelope_v.*carrier;
receiver_noise_v = receiver_noise_rms_v* ...
    randn(private_stream, 1, sample_count);
received_rf_v = clean_rf_v + receiver_noise_v;

received_spectrum_v = fft(received_rf_v);
one_sided_amplitude_v = 2*abs(received_spectrum_v(1:sample_count/2+1))/ ...
    sample_count;
one_sided_amplitude_v([1 end]) = ...
    one_sided_amplitude_v([1 end])/2;
carrier_index = round(carrier_frequency_hz/frequency_spacing_hz) + 1;
lower_sideband_index = round((carrier_frequency_hz-message_frequency_hz)/ ...
    frequency_spacing_hz) + 1;
upper_sideband_index = round((carrier_frequency_hz+message_frequency_hz)/ ...
    frequency_spacing_hz) + 1;
expected_sideband_amplitude_v = ...
    carrier_amplitude_v*baseline_modulation_depth/2;
measured_carrier_amplitude_v = one_sided_amplitude_v(carrier_index);
measured_sideband_amplitudes_v = one_sided_amplitude_v( ...
    [lower_sideband_index upper_sideband_index]);

analytic_received_v = ifft(received_spectrum_v.*analytic_mask);
detected_envelope_v = abs(analytic_received_v);
envelope_recovered_message = (detected_envelope_v/carrier_amplitude_v-1)/ ...
    baseline_modulation_depth;
mixed_to_baseband_v = 2*received_rf_v.*carrier;
coherent_baseband_v = real(ifft(fft(mixed_to_baseband_v).*lowpass_mask));
coherent_recovered_message = (coherent_baseband_v/carrier_amplitude_v-1)/ ...
    baseline_modulation_depth;
baseline_envelope_rmse = sqrt(mean(( ...
    envelope_recovered_message-message).^2));
baseline_coherent_rmse = sqrt(mean(( ...
    coherent_recovered_message-message).^2));

assert(max(abs(measured_sideband_amplitudes_v- ...
    expected_sideband_amplitude_v)) < 0.01 && ...
    abs(measured_carrier_amplitude_v-carrier_amplitude_v) < 0.01, ...
    'The seeded baseline must retain its carrier and symmetric sidebands.');

fprintf('\nP21 baseline: single-tone conventional AM\n');
fprintf('  carrier %.0f Hz, message %.0f Hz, depth %.2f, noise %.4f V RMS\n', ...
    carrier_frequency_hz, message_frequency_hz, ...
    baseline_modulation_depth, receiver_noise_rms_v);
fprintf('  predicted lines: %.0f, %.0f, %.0f Hz\n', ...
