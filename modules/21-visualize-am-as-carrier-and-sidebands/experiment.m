%% Broken case: over-modulation folds a magnitude envelope detector
broken_signed_envelope_v = carrier_amplitude_v*( ...
    1+broken_modulation_depth*message);
broken_clean_rf_v = broken_signed_envelope_v.*carrier;
broken_spectrum_v = fft(broken_clean_rf_v);
broken_analytic_v = ifft(broken_spectrum_v.*analytic_mask);
broken_detected_envelope_v = abs(broken_analytic_v);
broken_envelope_recovered = ( ...
    broken_detected_envelope_v/carrier_amplitude_v-1)/ ...
    broken_modulation_depth;
broken_mixed_v = 2*broken_clean_rf_v.*carrier;
broken_coherent_baseband_v = real(ifft( ...
    fft(broken_mixed_v).*lowpass_mask));
broken_coherent_recovered = ( ...
    broken_coherent_baseband_v/carrier_amplitude_v-1)/ ...
    broken_modulation_depth;
broken_envelope_rmse = sqrt(mean((broken_envelope_recovered-message).^2));
broken_coherent_rmse = sqrt(mean((broken_coherent_recovered-message).^2));
inverted_sample_fraction = mean(broken_signed_envelope_v < 0);
assert(min(broken_signed_envelope_v) < 0 && inverted_sample_fraction > 0 && ...
    broken_envelope_rmse > 0.1 && broken_coherent_rmse < 1e-10, ...
    'The intentionally broken case must invert and separate the detectors.');

