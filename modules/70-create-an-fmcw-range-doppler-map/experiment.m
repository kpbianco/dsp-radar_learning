%% P70: Create an FMCW Range-Doppler Map
% Guiding question:
% How do fast-time beat frequency and chirp-to-chirp phase separate range and velocity?
%
% Base MATLAB only. The dechirped target model, fast-time range FFT,
% slow-time Doppler FFT, observation-length sweeps, broken phase-discarding
% path, and same-data recovery are explicit below.

close(findall(0, 'Type', 'figure', 'Tag', 'P70'));
clear p70_results;

%% Visible reviewed controls
baseline_seed = 7001;
speed_of_light_mps = 3.0e8;
carrier_frequency_hz = 77.0e9;
sample_rate_hz = 12.8e6;
chirp_duration_s = 40.0e-6;
chirp_bandwidth_hz = 150.0e6;
chirp_repetition_interval_s = 50.0e-6;
sample_count = 512;
chirp_count = 64;
target_ranges_m = [20 20 23];
target_velocity_bin_offsets = [-3 3 3];
target_voltage = [1.00 0.82 0.68];
target_initial_phase_rad = [0.10 0.75 -0.55];
noise_rms = 0.01;
sample_count_sweep = [128 256 512];
chirp_count_sweep = [16 32 64];
plot_floor_db = -70;

maximum_samples = 1024;
maximum_chirps = 128;
maximum_targets = 8;
maximum_sweep_cases = 6;
maximum_private_values = 100000;
maximum_working_numeric_values = 2000000;
maximum_figures = 7;

controls = struct( ...
    'seed', baseline_seed, 'c_mps', speed_of_light_mps, ...
    'carrier_hz', carrier_frequency_hz, 'fs_hz', sample_rate_hz, ...
    'chirp_duration_s', chirp_duration_s, ...
    'bandwidth_hz', chirp_bandwidth_hz, ...
    'chirp_interval_s', chirp_repetition_interval_s, ...
    'sample_count', sample_count, 'chirp_count', chirp_count, ...
    'target_ranges_m', target_ranges_m, ...
    'target_velocity_bin_offsets', target_velocity_bin_offsets, ...
    'target_voltage', target_voltage, ...
    'target_initial_phase_rad', target_initial_phase_rad, ...
    'noise_rms', noise_rms, ...
    'sample_count_sweep', sample_count_sweep, ...
    'chirp_count_sweep', chirp_count_sweep, ...
    'plot_floor_db', plot_floor_db, ...
    'max_samples', maximum_samples, 'max_chirps', maximum_chirps, ...
    'max_targets', maximum_targets, ...
    'max_sweep_cases', maximum_sweep_cases, ...
    'max_private_values', maximum_private_values, ...
    'max_working_values', maximum_working_numeric_values, ...
    'max_figures', maximum_figures);
validate_controls(controls);

wavelength_m = speed_of_light_mps/carrier_frequency_hz;
chirp_slope_hz_per_s = chirp_bandwidth_hz/chirp_duration_s;
chirp_repetition_frequency_hz = 1/chirp_repetition_interval_s;
fast_time_s = (0:sample_count-1).'/sample_rate_hz;
chirp_time_s = (0:chirp_count-1)*chirp_repetition_interval_s;
range_frequency_hz = (0:sample_count/2).'*sample_rate_hz/sample_count;
range_axis_m = speed_of_light_mps*range_frequency_hz / ...
    (2*chirp_slope_hz_per_s);
doppler_frequency_hz = (-chirp_count/2:chirp_count/2-1)* ...
    chirp_repetition_frequency_hz/chirp_count;
% With P69's tx.*conj(rx) mixer, positive approaching velocity produces
% negative dechirped slow-time frequency. Reverse that FFT-frequency sign
% when labeling the physical velocity axis.
velocity_axis_mps = -wavelength_m*doppler_frequency_hz/2;
range_bin_spacing_m = speed_of_light_mps*sample_rate_hz / ...
    (2*chirp_slope_hz_per_s*sample_count);
velocity_bin_spacing_mps = wavelength_m* ...
    chirp_repetition_frequency_hz/(2*chirp_count);
target_beat_frequency_hz = 2*chirp_slope_hz_per_s* ...
    target_ranges_m/speed_of_light_mps;
target_radial_doppler_frequency_hz = target_velocity_bin_offsets* ...
    chirp_repetition_frequency_hz/chirp_count;
target_dechirped_slow_frequency_hz = ...
    -target_radial_doppler_frequency_hz;
target_velocities_mps = wavelength_m* ...
    target_radial_doppler_frequency_hz/2;
nominal_range_resolution_m = speed_of_light_mps/(2*chirp_bandwidth_hz);
unambiguous_range_m = speed_of_light_mps*(sample_rate_hz/2) / ...
    (2*chirp_slope_hz_per_s);
unambiguous_velocity_mps = wavelength_m* ...
    chirp_repetition_frequency_hz/4;

preflight_working_value_bound = 40*sample_count*chirp_count + ...
    12*sample_count + 12*chirp_count;
assert(preflight_working_value_bound <= maximum_working_numeric_values, ...
    'P70:PreflightWorkingBound', ...
    'Conservative simultaneous working-value estimate exceeds the ceiling.');

%% Baseline: build fast-time rows by chirp columns explicitly
% The reviewed stop-and-hop model is
% z_q[n,m] = a_q exp(j*2*pi*(f_b,q*n/fs - f_d,q*m*T_r) + j*phi_q).
% It preserves range in fast-time beat frequency and velocity in slow-time
% phase under P69's tx.*conj(rx) sign while reserving within-chirp Doppler
% coupling for P71. Here f_d = 2*v/lambda is positive for approaching.
target_count = numel(target_ranges_m);
dechirped_targets = complex(zeros(sample_count, chirp_count));
target_slow_phase_rad = zeros(target_count, chirp_count);
for target_index = 1:target_count
    fast_phase_rad = 2*pi*target_beat_frequency_hz(target_index)* ...
        fast_time_s;
    slow_phase_rad = 2*pi* ...
        target_dechirped_slow_frequency_hz(target_index)* ...
        chirp_time_s + target_initial_phase_rad(target_index);
    target_slow_phase_rad(target_index, :) = slow_phase_rad;
    target_contribution = target_voltage(target_index)* ...
        exp(1j*(fast_phase_rad + slow_phase_rad));
    dechirped_targets = dechirped_targets + target_contribution;
end
private_noise = noise_rms*private_complex_noise( ...
    baseline_seed, sample_count, chirp_count, maximum_private_values);
dechirped_data = dechirped_targets + private_noise;

assert(isequal(size(dechirped_data), [sample_count chirp_count]), ...
    'P70:MatrixShape', ...
    'Dechirped data must retain fast-time rows and chirp columns.');

%% Stage 1: FFT down fast-time rows to obtain range for every chirp
fast_time_window = 0.5-0.5*cos(2*pi*(0:sample_count-1).' / ...
    (sample_count-1));
windowed_fast_time_data = dechirped_data.*fast_time_window;
range_spectrum_full = fft(windowed_fast_time_data, sample_count, 1) / ...
    sum(fast_time_window);
range_data = range_spectrum_full(1:sample_count/2+1, :);

assert(isequal(size(range_data), [sample_count/2+1 chirp_count]), ...
    'P70:RangeMatrixShape', ...
    'Range FFT must transform rows while retaining every chirp column.');

%% Stage 2: FFT across coherent chirp columns to obtain signed Doppler
slow_time_window = 0.5-0.5*cos(2*pi*(0:chirp_count-1) / ...
    (chirp_count-1));
windowed_slow_time_data = range_data.*slow_time_window;
range_doppler_complex = fftshift(fft(windowed_slow_time_data, ...
    chirp_count, 2), 2)/sum(slow_time_window);
map_reference = max(abs(range_doppler_complex(:)));
range_doppler_db = 20*log10(max(abs(range_doppler_complex)/ ...
    map_reference, 10^(plot_floor_db/20)));

expected_range_indices = round(target_ranges_m/range_bin_spacing_m)+1;
expected_doppler_indices = -target_velocity_bin_offsets+chirp_count/2+1;
measured_target_ranges_m = zeros(1, target_count);
measured_target_velocities_mps = zeros(1, target_count);
measured_target_peak_indices = zeros(target_count, 2);
target_peak_magnitude = zeros(1, target_count);
for target_index = 1:target_count
    range_indices = max(1, expected_range_indices(target_index)-1): ...
        min(numel(range_axis_m), expected_range_indices(target_index)+1);
    doppler_indices = max(1, expected_doppler_indices(target_index)-1): ...
        min(chirp_count, expected_doppler_indices(target_index)+1);
    local_map = abs(range_doppler_complex(range_indices, doppler_indices));
    [target_peak_magnitude(target_index), local_linear_index] = ...
        max(local_map(:));
    [local_range_index, local_doppler_index] = ind2sub( ...
        size(local_map), local_linear_index);
    measured_target_ranges_m(target_index) = ...
        range_axis_m(range_indices(local_range_index));
    measured_target_velocities_mps(target_index) = ...
        velocity_axis_mps(doppler_indices(local_doppler_index));
    measured_target_peak_indices(target_index, :) = ...
        [range_indices(local_range_index) ...
        doppler_indices(local_doppler_index)];
end
map_median_magnitude = median(abs(range_doppler_complex(:)));
target_peak_to_median_db = 20*log10(target_peak_magnitude / ...
    max(map_median_magnitude, eps));

assert(all(abs(measured_target_ranges_m-target_ranges_m) <= ...
    range_bin_spacing_m+100*eps), 'P70:TargetRange', ...
    'A target moved outside its reviewed range neighborhood.');
assert(all(abs(measured_target_velocities_mps-target_velocities_mps) <= ...
    velocity_bin_spacing_mps+100*eps), 'P70:TargetVelocity', ...
    'A target moved outside its reviewed velocity neighborhood.');
assert(size(unique(measured_target_peak_indices, 'rows'), 1) == ...
    target_count, 'P70:DistinctTargets', ...
    'The three reviewed targets must occupy distinct map cells.');
assert(all(target_peak_to_median_db > 20), 'P70:TargetContrast', ...
    'A reviewed target no longer rises clearly above the map median.');

%% Figure 1: expose the two clocks before processing
figure('Name', 'P70 dechirped fast-time by chirp matrix', 'Tag', 'P70');
subplot(2, 1, 1);
imagesc(0:chirp_count-1, fast_time_s*1e6, real(dechirped_data));
axis xy; colorbar;
xlabel('Chirp index (slow time)'); ylabel('Fast time within chirp (us)');
title('Real dechirped matrix: samples are rows, chirps are columns');
subplot(2, 1, 2);
plot(fast_time_s*1e6, real(dechirped_data(:, 1)), 'LineWidth', 1.0);
grid on; xlabel('Fast time within chirp (us)');
ylabel('Real dechirped voltage (V/V)');
title('One column contains range-dependent beat tones');

%% Figure 2: range FFT keeps slow-time columns intact
range_matrix_db = 20*log10(max(abs(range_data)/ ...
    max(abs(range_data(:))), 10^(plot_floor_db/20)));
first_chirp_range_db = range_matrix_db(:, 1);
figure('Name', 'P70 fast-time range FFT', 'Tag', 'P70');
subplot(2, 1, 1);
plot(range_axis_m, first_chirp_range_db, 'LineWidth', 1.2); hold on;
plot(target_ranges_m, plot_floor_db/10*ones(size(target_ranges_m)), ...
    'ko', 'LineWidth', 1.0); hold off; grid on;
xlim([0 45]); ylim([plot_floor_db 3]);
xlabel('Range from beat frequency (m)'); ylabel('Normalized magnitude (dB)');
title('One chirp: equal-range targets still share one range neighborhood');
subplot(2, 1, 2);
imagesc(0:chirp_count-1, range_axis_m, range_matrix_db);
axis xy; colorbar; caxis([plot_floor_db 0]); ylim([0 45]);
xlabel('Chirp index retained for Doppler'); ylabel('Range (m)');
title('Range FFT acts down rows and preserves complex chirp history');

%% Figure 3: chirp-to-chirp phase becomes signed Doppler
shared_range_index = expected_range_indices(1);
shared_range_trace = range_data(shared_range_index, :);
shared_range_doppler = fftshift(fft(shared_range_trace.* ...
    slow_time_window, chirp_count))/sum(slow_time_window);
shared_range_db = 20*log10(max(abs(shared_range_doppler)/ ...
    max(abs(shared_range_doppler)), 10^(plot_floor_db/20)));
figure('Name', 'P70 slow-time phase and Doppler', 'Tag', 'P70');
subplot(2, 1, 1);
plot(0:chirp_count-1, unwrap(target_slow_phase_rad(1, :)), ...
    'LineWidth', 1.2); hold on;
plot(0:chirp_count-1, unwrap(target_slow_phase_rad(2, :)), ...
    'LineWidth', 1.2); hold off; grid on;
xlabel('Chirp index (slow time)'); ylabel('Unwrapped target phase (rad)');
legend('Shared range, negative velocity', ...
    'Shared range, positive velocity', 'Location', 'best');
title('Opposite phase slopes carry velocity sign');
subplot(2, 1, 2);
plot(velocity_axis_mps, shared_range_db, 'LineWidth', 1.2); grid on;
xlabel('Radial velocity (m/s, positive approaching)');
ylabel('Normalized magnitude (dB)'); ylim([plot_floor_db 3]);
title('Slow-time FFT separates the equal-range pair');

%% Figure 4: the complete range-Doppler map
figure('Name', 'P70 FMCW range-Doppler map', 'Tag', 'P70');
imagesc(velocity_axis_mps, range_axis_m, range_doppler_db);
axis xy; colorbar; caxis([plot_floor_db 0]); ylim([0 45]); hold on;
plot(target_velocities_mps, target_ranges_m, 'wo', ...
    'MarkerSize', 8, 'LineWidth', 1.4); hold off;
xlabel('Radial velocity (m/s, positive approaching)');
ylabel('Range from fast-time beat (m)');
title('Fast-time FFT then slow-time FFT separates all three targets');

%% Sweep 1: vary only coherent chirp count
chirp_sweep_velocity_spacing_mps = zeros(size(chirp_count_sweep));
chirp_sweep_cpi_s = zeros(size(chirp_count_sweep));
figure('Name', 'P70 coherent chirp-count sweep', 'Tag', 'P70');
for case_index = 1:numel(chirp_count_sweep)
    case_chirp_count = chirp_count_sweep(case_index);
    case_window = 0.5-0.5*cos(2*pi*(0:case_chirp_count-1) / ...
        (case_chirp_count-1));
    case_trace = shared_range_trace(1:case_chirp_count);
    case_spectrum = fftshift(fft(case_trace.*case_window, ...
        case_chirp_count))/sum(case_window);
    case_velocity_axis_mps = -(-case_chirp_count/2: ...
        case_chirp_count/2-1)*chirp_repetition_frequency_hz / ...
        case_chirp_count*wavelength_m/2;
    case_db = 20*log10(max(abs(case_spectrum)/max(abs(case_spectrum)), ...
        10^(plot_floor_db/20)));
    chirp_sweep_velocity_spacing_mps(case_index) = wavelength_m* ...
        chirp_repetition_frequency_hz/(2*case_chirp_count);
    chirp_sweep_cpi_s(case_index) = case_chirp_count* ...
        chirp_repetition_interval_s;
    subplot(numel(chirp_count_sweep), 1, case_index);
    plot(case_velocity_axis_mps, case_db, 'LineWidth', 1.2); grid on;
    xlabel('Radial velocity (m/s)'); ylabel('Magnitude (dB)');
    ylim([plot_floor_db 3]);
    title(sprintf('%d chirps: CPI %.2f ms, bins %.3f m/s', ...
        case_chirp_count, 1e3*chirp_sweep_cpi_s(case_index), ...
        chirp_sweep_velocity_spacing_mps(case_index)));
end
assert(all(diff(chirp_sweep_velocity_spacing_mps) < 0) && ...
    all(diff(chirp_sweep_cpi_s) > 0), 'P70:ChirpSweep', ...
    'Longer coherent chirp records must tighten the Doppler grid.');

%% Sweep 2: vary only the retained fast-time sample count
sample_sweep_range_spacing_m = zeros(size(sample_count_sweep));
sample_sweep_effective_bandwidth_hz = zeros(size(sample_count_sweep));
positive_velocity_index = expected_doppler_indices(2);
figure('Name', 'P70 retained sample-count sweep', 'Tag', 'P70');
for case_index = 1:numel(sample_count_sweep)
    case_sample_count = sample_count_sweep(case_index);
    case_window = 0.5-0.5*cos(2*pi*(0:case_sample_count-1).' / ...
        (case_sample_count-1));
    case_range_spectrum = fft(dechirped_data(1:case_sample_count, :).* ...
        case_window, case_sample_count, 1)/sum(case_window);
    case_range_data = case_range_spectrum(1:case_sample_count/2+1, :);
    case_map = fftshift(fft(case_range_data.*slow_time_window, ...
        chirp_count, 2), 2)/sum(slow_time_window);
    case_range_frequency_hz = (0:case_sample_count/2).'* ...
        sample_rate_hz/case_sample_count;
    case_range_axis_m = speed_of_light_mps*case_range_frequency_hz / ...
        (2*chirp_slope_hz_per_s);
    case_cut = abs(case_map(:, positive_velocity_index));
    case_db = 20*log10(max(case_cut/max(case_cut), ...
        10^(plot_floor_db/20)));
    case_observation_s = case_sample_count/sample_rate_hz;
    sample_sweep_effective_bandwidth_hz(case_index) = ...
        chirp_slope_hz_per_s*case_observation_s;
    sample_sweep_range_spacing_m(case_index) = speed_of_light_mps / ...
        (2*sample_sweep_effective_bandwidth_hz(case_index));
    subplot(numel(sample_count_sweep), 1, case_index);
    plot(case_range_axis_m, case_db, 'LineWidth', 1.2); grid on;
    xlim([14 30]); ylim([plot_floor_db 3]);
    xlabel('Range from beat frequency (m)'); ylabel('Magnitude (dB)');
    title(sprintf('%d samples: observed sweep %.1f MHz, bins %.2f m', ...
        case_sample_count, ...
        sample_sweep_effective_bandwidth_hz(case_index)/1e6, ...
        sample_sweep_range_spacing_m(case_index)));
end
assert(all(diff(sample_sweep_effective_bandwidth_hz) > 0) && ...
    all(diff(sample_sweep_range_spacing_m) < 0), 'P70:SampleSweep', ...
    'Longer fast-time records must observe more sweep and tighten range bins.');

%% Intentionally broken case: discard phase before the Doppler FFT
% abs(.) retains range magnitudes but destroys signed chirp-to-chirp phase.
broken_noncoherent_range_data = abs(range_data);
broken_range_doppler_complex = fftshift(fft( ...
    broken_noncoherent_range_data.*slow_time_window, ...
    chirp_count, 2), 2)/sum(slow_time_window);
isolated_range_index = expected_range_indices(3);
[~, broken_peak_index] = max(abs( ...
    broken_range_doppler_complex(isolated_range_index, :)));
broken_peak_velocity_mps = velocity_axis_mps(broken_peak_index);
broken_velocity_sign_preserved = abs(broken_peak_velocity_mps- ...
    target_velocities_mps(3)) <= velocity_bin_spacing_mps;

% Recovery reuses the unchanged complex range data and correct dimension.
recovered_range_doppler_complex = fftshift(fft( ...
    range_data.*slow_time_window, chirp_count, 2), 2) / ...
    sum(slow_time_window);
recovery_error = max(abs(recovered_range_doppler_complex(:)- ...
    range_doppler_complex(:)));
[~, recovered_peak_index] = max(abs( ...
    recovered_range_doppler_complex(isolated_range_index, :)));
recovered_peak_velocity_mps = velocity_axis_mps(recovered_peak_index);
recovered_velocity_sign_preserved = abs(recovered_peak_velocity_mps- ...
    target_velocities_mps(3)) <= velocity_bin_spacing_mps;
assert(abs(broken_peak_velocity_mps) <= velocity_bin_spacing_mps, ...
    'P70:BrokenPhaseLoss', ...
    'Phase-discarding should collapse the isolated target near zero velocity.');
assert(~broken_velocity_sign_preserved && ...
    recovered_velocity_sign_preserved, 'P70:VelocitySignRecovery', ...
    'Broken and recovered paths must measure the expected sign behavior.');
assert(recovery_error <= 100*eps(map_reference), ...
    'P70:SameDataRecovery', ...
    'Recovery must reproduce the baseline map from unchanged complex data.');

broken_reference = max(abs(broken_range_doppler_complex(:)));
broken_db = 20*log10(max(abs(broken_range_doppler_complex)/ ...
    broken_reference, 10^(plot_floor_db/20)));
recovered_db = 20*log10(max(abs(recovered_range_doppler_complex)/ ...
    map_reference, 10^(plot_floor_db/20)));
figure('Name', 'P70 broken phase loss and recovery', 'Tag', 'P70');
subplot(1, 2, 1);
imagesc(velocity_axis_mps, range_axis_m, broken_db);
axis xy; colorbar; caxis([plot_floor_db 0]); ylim([0 45]);
xlabel('Apparent velocity (m/s)'); ylabel('Range (m)');
title('Broken: magnitude before Doppler FFT');
subplot(1, 2, 2);
imagesc(velocity_axis_mps, range_axis_m, recovered_db);
axis xy; colorbar; caxis([plot_floor_db 0]); ylim([0 45]);
xlabel('Recovered velocity (m/s)'); ylabel('Range (m)');
title('Recovered: unchanged complex chirp history');

%% Retain compact metrics and report reviewed units
working_value_count = numel(dechirped_targets) + numel(private_noise) + ...
    numel(dechirped_data) + numel(windowed_fast_time_data) + ...
    numel(range_spectrum_full) + numel(range_data) + ...
    numel(windowed_slow_time_data) + numel(range_doppler_complex) + ...
    numel(broken_range_doppler_complex) + ...
    numel(recovered_range_doppler_complex);
assert(working_value_count <= maximum_working_numeric_values, ...
    'P70:WorkingBound', 'Retained working arrays exceed the reviewed ceiling.');
assert(all(isfinite([measured_target_ranges_m ...
    measured_target_velocities_mps target_peak_to_median_db ...
    chirp_sweep_velocity_spacing_mps sample_sweep_range_spacing_m ...
    broken_peak_velocity_mps recovered_peak_velocity_mps ...
    recovery_error])), 'P70:FiniteMetrics', ...
    'A retained range-Doppler metric is nonfinite.');

p70_results = struct( ...
    'controls', controls, 'wavelength_m', wavelength_m, ...
    'chirp_slope_hz_per_s', chirp_slope_hz_per_s, ...
    'target_beat_frequency_hz', target_beat_frequency_hz, ...
    'target_radial_doppler_frequency_hz', ...
    target_radial_doppler_frequency_hz, ...
    'target_dechirped_slow_frequency_hz', ...
    target_dechirped_slow_frequency_hz, ...
    'target_velocities_mps', target_velocities_mps, ...
    'range_axis_m', range_axis_m, 'velocity_axis_mps', velocity_axis_mps, ...
    'range_bin_spacing_m', range_bin_spacing_m, ...
    'velocity_bin_spacing_mps', velocity_bin_spacing_mps, ...
    'nominal_range_resolution_m', nominal_range_resolution_m, ...
    'unambiguous_range_m', unambiguous_range_m, ...
    'unambiguous_velocity_mps', unambiguous_velocity_mps, ...
    'measured_target_ranges_m', measured_target_ranges_m, ...
    'measured_target_velocities_mps', measured_target_velocities_mps, ...
    'target_peak_to_median_db', target_peak_to_median_db, ...
    'chirp_sweep_velocity_spacing_mps', ...
    chirp_sweep_velocity_spacing_mps, ...
    'sample_sweep_effective_bandwidth_hz', ...
    sample_sweep_effective_bandwidth_hz, ...
    'sample_sweep_range_spacing_m', sample_sweep_range_spacing_m, ...
    'broken_peak_velocity_mps', broken_peak_velocity_mps, ...
    'broken_velocity_sign_preserved', broken_velocity_sign_preserved, ...
    'recovered_peak_velocity_mps', recovered_peak_velocity_mps, ...
    'recovered_velocity_sign_preserved', ...
    recovered_velocity_sign_preserved, ...
    'recovery_error', recovery_error, ...
    'working_value_count', working_value_count);

fprintf('\nP70 deterministic baseline (seed %d)\n', baseline_seed);
fprintf('  matrix: %d fast-time samples x %d coherent chirps\n', ...
    sample_count, chirp_count);
fprintf('  range / velocity bin spacing: %.3f m / %.3f m/s\n', ...
    range_bin_spacing_m, velocity_bin_spacing_mps);
fprintf('  known target ranges (m): %.3f %.3f %.3f\n', target_ranges_m);
fprintf('  measured target ranges (m): %.3f %.3f %.3f\n', ...
    measured_target_ranges_m);
fprintf('  known target velocities (m/s): %.3f %.3f %.3f\n', ...
    target_velocities_mps);
