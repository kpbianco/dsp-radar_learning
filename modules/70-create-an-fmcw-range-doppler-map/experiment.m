function noise = private_complex_noise(seed, number_rows, number_columns, maximum_values)
validateattributes(seed, {'numeric'}, ...
    {'scalar', 'integer', '>=', 1, '<', 2147483647});
validateattributes(number_rows, {'numeric'}, ...
    {'scalar', 'integer', 'positive'});
validateattributes(number_columns, {'numeric'}, ...
    {'scalar', 'integer', 'positive'});
validateattributes(maximum_values, {'numeric'}, ...
    {'scalar', 'integer', 'positive'});
sample_total = number_rows*number_columns;
assert(2*sample_total <= maximum_values, 'P70:PrivateNoiseBound', ...
    'Private generator request exceeds the reviewed ceiling.');
uniform_values = private_uniform(seed, 2*sample_total, maximum_values);
first = max(uniform_values(1:sample_total), realmin);
second = uniform_values(sample_total+1:end);
samples = sqrt(-2*log(first)).*exp(1j*2*pi*second)/sqrt(2);
noise = reshape(samples, number_rows, number_columns);
end

function values = private_uniform(seed, count, maximum_values)
validateattributes(seed, {'numeric'}, ...
    {'scalar', 'integer', '>=', 1, '<', 2147483647});
validateattributes(count, {'numeric'}, ...
    {'scalar', 'integer', '>=', 1, '<=', maximum_values});
state = seed;
values = zeros(count, 1);
for value_index = 1:count
    state = mod(16807*state, 2147483647);
    values(value_index) = state/2147483647;
end
end

function validate_controls(c)
assert(isstruct(c) && isscalar(c), 'P70:ControlsType', ...
    'Controls must be one scalar struct.');
required_fields = {'seed', 'c_mps', 'carrier_hz', 'fs_hz', ...
    'chirp_duration_s', 'bandwidth_hz', 'chirp_interval_s', ...
    'sample_count', 'chirp_count', 'target_ranges_m', ...
    'target_velocity_bin_offsets', 'target_voltage', ...
    'target_initial_phase_rad', 'noise_rms', 'sample_count_sweep', ...
    'chirp_count_sweep', 'plot_floor_db', 'max_samples', ...
    'max_chirps', 'max_targets', 'max_sweep_cases', ...
    'max_private_values', 'max_working_values', 'max_figures'};
assert(isequal(sort(fieldnames(c)), sort(required_fields.')), ...
    'P70:ControlFields', 'Controls have missing or unexpected fields.');
scalar_fields = {'seed', 'c_mps', 'carrier_hz', 'fs_hz', ...
    'chirp_duration_s', 'bandwidth_hz', 'chirp_interval_s', ...
    'sample_count', 'chirp_count', 'noise_rms', 'plot_floor_db', ...
    'max_samples', 'max_chirps', 'max_targets', 'max_sweep_cases', ...
    'max_private_values', 'max_working_values', 'max_figures'};
for field_index = 1:numel(scalar_fields)
    value = c.(scalar_fields{field_index});
    assert(isnumeric(value) && isreal(value) && isscalar(value) && ...
        isfinite(value), 'P70:ControlScalar', ...
        'Every scalar control must be finite, real, numeric, and scalar.');
end
vector_fields = {'target_ranges_m', 'target_velocity_bin_offsets', ...
    'target_voltage', 'target_initial_phase_rad', ...
    'sample_count_sweep', 'chirp_count_sweep'};
for field_index = 1:numel(vector_fields)
    values = c.(vector_fields{field_index});
    assert(isnumeric(values) && isreal(values) && isvector(values) && ...
        all(isfinite(values)), 'P70:ControlVector', ...
        'Every vector control must be finite, real, and numeric.');
end
target_count_local = numel(c.target_ranges_m);
assert(target_count_local >= 3 && target_count_local <= c.max_targets && ...
    numel(c.target_velocity_bin_offsets) == target_count_local && ...
    numel(c.target_voltage) == target_count_local && ...
    numel(c.target_initial_phase_rad) == target_count_local, ...
    'P70:TargetVectors', ...
    'Target vectors must have one bounded entry per target.');
assert(numel(c.sample_count_sweep) >= 3 && ...
    numel(c.sample_count_sweep) <= c.max_sweep_cases && ...
    all(diff(c.sample_count_sweep) > 0) && ...
    numel(c.chirp_count_sweep) >= 3 && ...
    numel(c.chirp_count_sweep) <= c.max_sweep_cases && ...
    all(diff(c.chirp_count_sweep) > 0), 'P70:SweepVectors', ...
    'Sweeps must be bounded, finite, and strictly increasing.');
integer_fields = {'seed', 'sample_count', 'chirp_count', ...
    'max_samples', 'max_chirps', 'max_targets', 'max_sweep_cases', ...
    'max_private_values', 'max_working_values', 'max_figures'};
for field_index = 1:numel(integer_fields)
    value = c.(integer_fields{field_index});
    assert(value > 0 && value == floor(value), 'P70:ControlInteger', ...
        'Integer controls and ceilings must be positive integers.');
end
assert(all(c.sample_count_sweep == floor(c.sample_count_sweep)) && ...
    all(c.chirp_count_sweep == floor(c.chirp_count_sweep)) && ...
    all(c.target_velocity_bin_offsets == ...
    floor(c.target_velocity_bin_offsets)), 'P70:VectorIntegers', ...
    'Sample counts, chirp counts, and reviewed bin offsets must be integers.');
assert(all(2.^nextpow2(c.sample_count_sweep) == c.sample_count_sweep) && ...
    all(2.^nextpow2(c.chirp_count_sweep) == c.chirp_count_sweep), ...
    'P70:RadixTwoSweeps', ...
    'Reviewed FFT observation counts must be powers of two.');
assert(c.c_mps > 0 && c.carrier_hz > 0 && c.fs_hz > 0 && ...
    c.chirp_duration_s > 0 && c.bandwidth_hz > 0 && ...
    c.chirp_interval_s >= c.chirp_duration_s && ...
    c.sample_count == round(c.fs_hz*c.chirp_duration_s) && ...
    c.sample_count >= 128 && c.sample_count <= c.max_samples && ...
    c.chirp_count >= 16 && c.chirp_count <= c.max_chirps && ...
    c.sample_count_sweep(end) == c.sample_count && ...
    c.chirp_count_sweep(end) == c.chirp_count && ...
    all(c.sample_count_sweep >= 64) && ...
    all(c.chirp_count_sweep >= 8) && ...
    c.noise_rms >= 0 && c.noise_rms <= 1 && ...
    c.plot_floor_db >= -200 && c.plot_floor_db <= -20, ...
    'P70:PhysicalControls', ...
    'Controls violate sampling, timing, observation, or display bounds.');
assert(all(c.target_ranges_m > 0) && ...
    all(c.target_voltage > 0) && all(c.target_voltage <= 2) && ...
    all(abs(c.target_velocity_bin_offsets) < c.chirp_count/2) && ...
    size(unique([c.target_ranges_m(:) ...
    c.target_velocity_bin_offsets(:)], 'rows'), 1) == target_count_local, ...
    'P70:TargetControls', ...
    'Targets need valid amplitudes and unique in-band range/velocity pairs.');
maximum_beat_hz = max(2*(c.bandwidth_hz/c.chirp_duration_s)* ...
    c.target_ranges_m/c.c_mps);
assert(maximum_beat_hz < c.fs_hz/2, 'P70:BeatNyquist', ...
    'Every dechirped target beat must remain below Nyquist.');
assert(c.max_samples == 1024 && c.max_chirps == 128 && ...
    c.max_targets == 8 && c.max_sweep_cases == 6 && ...
    c.max_private_values == 100000 && ...
    c.max_working_values == 2000000 && c.max_figures == 7, ...
    'P70:ImmutableCeilings', 'Reviewed resource ceilings changed.');
assert(2*c.sample_count*c.chirp_count <= c.max_private_values, ...
    'P70:NoiseCeiling', ...
    'Baseline private-noise request exceeds its reviewed ceiling.');
assert(c.seed <= 2147483642, 'P70:SeedRange', ...
    'Seed must leave room for deterministic companion streams.');
end
