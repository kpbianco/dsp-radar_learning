%% P69: Derive FMCW Range from Beat Frequency
% Guiding question:
% Why does a delayed chirp produce a nearly constant beat frequency?
%
% Base MATLAB only. Chirp phase, physical delay, valid overlap, dechirp
% multiplication, FFT peak, range conversion, sweeps, failure, and recovery
% are exposed below.

close(findall(0, 'Type', 'figure', 'Tag', 'P69'));
clear p69_results;

%% Visible reviewed controls
baseline_seed = 6901;
speed_of_light_mps = 3.0e8;
sample_rate_hz = 80.0e6;
chirp_duration_s = 40.0e-6;
chirp_bandwidth_hz = 20.0e6;
target_range_m = 45.0;
echo_voltage = 0.70;
noise_rms = 0.01;
fft_length = 65536;
range_sweep_m = [15 30 45 60 75];
slope_bandwidth_sweep_hz = [10 15 20 25 30]*1.0e6;
plot_floor_db = -80;

maximum_samples = 4096;
maximum_fft_length = 131072;
maximum_sweep_cases = 8;
maximum_private_values = 100000;
maximum_working_numeric_values = 1000000;
maximum_figures = 6;

controls = struct( ...
    'seed', baseline_seed, 'c_mps', speed_of_light_mps, ...
    'fs_hz', sample_rate_hz, 'duration_s', chirp_duration_s, ...
    'bandwidth_hz', chirp_bandwidth_hz, 'range_m', target_range_m, ...
    'echo_voltage', echo_voltage, 'noise_rms', noise_rms, ...
    'fft_length', fft_length, 'range_sweep_m', range_sweep_m, ...
    'bandwidth_sweep_hz', slope_bandwidth_sweep_hz, ...
    'plot_floor_db', plot_floor_db, 'max_samples', maximum_samples, ...
    'max_fft_length', maximum_fft_length, ...
    'max_sweep_cases', maximum_sweep_cases, ...
    'max_private_values', maximum_private_values, ...
    'max_working_values', maximum_working_numeric_values, ...
    'max_figures', maximum_figures);
validate_controls(controls);

number_samples = round(sample_rate_hz*chirp_duration_s);
time_s = (0:number_samples-1).'/sample_rate_hz;
chirp_slope_hz_per_s = chirp_bandwidth_hz/chirp_duration_s;
round_trip_delay_s = 2*target_range_m/speed_of_light_mps;
valid_overlap = time_s >= round_trip_delay_s & time_s < chirp_duration_s;
valid_time_s = time_s(valid_overlap);

preflight_working_value_bound = ...
    24*number_samples + 8*fft_length + ...
    8*maximum_sweep_cases*number_samples;
assert(preflight_working_value_bound <= maximum_working_numeric_values, ...
    'P69:PreflightWorkingBound', ...
    'Conservative simultaneous working-value estimate exceeds the ceiling.');

%% Baseline: form one chirp and one physically delayed echo
% The centered complex-baseband phase keeps the swept band at +/-B/2.
transmit_phase_rad = pi*chirp_slope_hz_per_s* ...
    (time_s-chirp_duration_s/2).^2;
transmitted_chirp = exp(1j*transmit_phase_rad);

delayed_time_s = time_s-round_trip_delay_s;
received_chirp = complex(zeros(number_samples, 1));
received_chirp(valid_overlap) = echo_voltage*exp(1j*pi* ...
    chirp_slope_hz_per_s* ...
    (delayed_time_s(valid_overlap)-chirp_duration_s/2).^2);
received_noise = noise_rms*private_complex_noise( ...
    baseline_seed, number_samples, 1, maximum_private_values);
received_chirp(valid_overlap) = received_chirp(valid_overlap) + ...
    received_noise(valid_overlap);

transmit_instantaneous_frequency_hz = ...
    chirp_slope_hz_per_s*(time_s-chirp_duration_s/2);
received_instantaneous_frequency_hz = nan(number_samples, 1);
received_instantaneous_frequency_hz(valid_overlap) = ...
    chirp_slope_hz_per_s* ...
    (delayed_time_s(valid_overlap)-chirp_duration_s/2);
theoretical_beat_frequency_hz = ...
    chirp_slope_hz_per_s*round_trip_delay_s;

%% Dechirp over valid transmit/receive overlap and expose the FFT
% This order gives +S*tau for an up-chirp: tx .* conj(rx).
dechirped_beat = transmitted_chirp(valid_overlap).* ...
    conj(received_chirp(valid_overlap));
number_valid_samples = numel(dechirped_beat);
analysis_window = 0.5-0.5*cos(2*pi*(0:number_valid_samples-1).' / ...
    (number_valid_samples-1));
windowed_beat = dechirped_beat.*analysis_window;
beat_spectrum = fft(windowed_beat, fft_length);
positive_frequency_hz = (0:fft_length/2).'*sample_rate_hz/fft_length;
positive_power = abs(beat_spectrum(1:fft_length/2+1)).^2;
[~, baseline_peak_index] = max(positive_power(2:end));
baseline_peak_index = baseline_peak_index+1;
baseline_offset_bins = parabolic_peak_offset( ...
    positive_power, baseline_peak_index);
estimated_beat_frequency_hz = ...
    (baseline_peak_index-1+baseline_offset_bins)* ...
    sample_rate_hz/fft_length;
estimated_range_m = speed_of_light_mps*estimated_beat_frequency_hz / ...
    (2*chirp_slope_hz_per_s);

phase_increment = sum(conj(dechirped_beat(1:end-1)).* ...
    dechirped_beat(2:end));
phase_beat_frequency_hz = angle(phase_increment)*sample_rate_hz/(2*pi);
phase_range_m = speed_of_light_mps*phase_beat_frequency_hz / ...
    (2*chirp_slope_hz_per_s);

assert(phase_beat_frequency_hz > 0 && ...
    abs(phase_beat_frequency_hz-theoretical_beat_frequency_hz) < ...
    2*sample_rate_hz/fft_length, 'P69:MixerSign', ...
    'Signed phase increments must confirm the reviewed positive beat.');
assert(abs(estimated_beat_frequency_hz-theoretical_beat_frequency_hz) < ...
    2*sample_rate_hz/fft_length, 'P69:BaselineBeat', ...
    'Baseline FFT beat estimate moved outside the reviewed tolerance.');

%% Sweep 1: vary only target range while slope and noise stay fixed
range_sweep_beat_hz = zeros(size(range_sweep_m));
range_sweep_estimate_m = zeros(size(range_sweep_m));
range_sweep_theory_hz = zeros(size(range_sweep_m));
for case_index = 1:numel(range_sweep_m)
    case_range_m = range_sweep_m(case_index);
    case_delay_s = 2*case_range_m/speed_of_light_mps;
    case_valid = time_s >= case_delay_s & time_s < chirp_duration_s;
    case_delayed_time_s = time_s(case_valid)-case_delay_s;
    case_echo = echo_voltage*exp(1j*pi*chirp_slope_hz_per_s* ...
        (case_delayed_time_s-chirp_duration_s/2).^2) + ...
        received_noise(case_valid);
    case_beat = transmitted_chirp(case_valid).*conj(case_echo);
    case_window = 0.5-0.5*cos(2*pi*(0:numel(case_beat)-1).' / ...
        (numel(case_beat)-1));
    case_spectrum = fft(case_beat.*case_window, fft_length);
    case_power = abs(case_spectrum(1:fft_length/2+1)).^2;
    [~, case_peak_index] = max(case_power(2:end));
    case_peak_index = case_peak_index+1;
    case_offset_bins = parabolic_peak_offset(case_power, case_peak_index);
    range_sweep_beat_hz(case_index) = ...
        (case_peak_index-1+case_offset_bins)*sample_rate_hz/fft_length;
    range_sweep_estimate_m(case_index) = speed_of_light_mps* ...
        range_sweep_beat_hz(case_index)/(2*chirp_slope_hz_per_s);
    range_sweep_theory_hz(case_index) = chirp_slope_hz_per_s*case_delay_s;
end
assert(max(abs(range_sweep_estimate_m-range_sweep_m)) < 1.0, ...
    'P69:RangeSweep', ...
    'Range-sweep estimates moved outside the reviewed one-metre bound.');

%% Sweep 2: vary only chirp slope while target range stays fixed
slope_sweep_hz_per_s = slope_bandwidth_sweep_hz/chirp_duration_s;
slope_sweep_beat_hz = zeros(size(slope_sweep_hz_per_s));
slope_sweep_estimate_m = zeros(size(slope_sweep_hz_per_s));
slope_sweep_theory_hz = slope_sweep_hz_per_s*round_trip_delay_s;
for case_index = 1:numel(slope_sweep_hz_per_s)
    case_slope = slope_sweep_hz_per_s(case_index);
    case_transmit = exp(1j*pi*case_slope* ...
        (time_s-chirp_duration_s/2).^2);
    case_echo = echo_voltage*exp(1j*pi*case_slope* ...
        (delayed_time_s(valid_overlap)-chirp_duration_s/2).^2) + ...
        received_noise(valid_overlap);
    case_beat = case_transmit(valid_overlap).*conj(case_echo);
    case_window = 0.5-0.5*cos(2*pi*(0:numel(case_beat)-1).' / ...
        (numel(case_beat)-1));
    case_spectrum = fft(case_beat.*case_window, fft_length);
    case_power = abs(case_spectrum(1:fft_length/2+1)).^2;
    [~, case_peak_index] = max(case_power(2:end));
    case_peak_index = case_peak_index+1;
    case_offset_bins = parabolic_peak_offset(case_power, case_peak_index);
    slope_sweep_beat_hz(case_index) = ...
        (case_peak_index-1+case_offset_bins)*sample_rate_hz/fft_length;
    slope_sweep_estimate_m(case_index) = speed_of_light_mps* ...
        slope_sweep_beat_hz(case_index)/(2*case_slope);
end
assert(max(abs(slope_sweep_estimate_m-target_range_m)) < 1.0, ...
    'P69:SlopeSweep', ...
    'Slope-sweep range estimates moved outside the reviewed one-metre bound.');

%% Intentionally broken case and same-measurement recovery
% Wrong: treating monostatic round-trip delay as one-way propagation.
broken_one_way_range_m = speed_of_light_mps*estimated_beat_frequency_hz / ...
    chirp_slope_hz_per_s;
recovered_monostatic_range_m = speed_of_light_mps* ...
    estimated_beat_frequency_hz/(2*chirp_slope_hz_per_s);
assert(abs(broken_one_way_range_m-2*estimated_range_m) < 1e-12, ...
    'P69:BrokenFactor', 'Broken conversion must double the same estimate.');
assert(abs(recovered_monostatic_range_m-estimated_range_m) < 1e-12, ...
    'P69:SameMeasurementRecovery', ...
    'Recovery must reuse the baseline beat and restore the monostatic factor.');

