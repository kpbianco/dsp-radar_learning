%% Local functions
function offset = parabolic_peak_offset(power_values, peak_index)
validateattributes(power_values, {'numeric'}, ...
    {'vector', 'real', 'finite', 'nonnegative', 'nonempty'});
validateattributes(peak_index, {'numeric'}, ...
    {'scalar', 'integer', '>=', 2, '<=', numel(power_values)-1});
log_power = log(max(power_values(peak_index-1:peak_index+1), realmin));
denominator = log_power(1)-2*log_power(2)+log_power(3);
if abs(denominator) <= 100*eps(max(abs(log_power)))
    offset = 0;
else
    offset = 0.5*(log_power(1)-log_power(3))/denominator;
end
offset = max(-0.5, min(0.5, offset));
end

function noise = private_complex_noise(seed, number_rows, number_columns, maximum_values)
validateattributes(seed, {'numeric'}, ...
    {'scalar', 'integer', '>=', 1, '<', 2147483647});
validateattributes(number_rows, {'numeric'}, ...
    {'scalar', 'integer', 'positive'});
validateattributes(number_columns, {'numeric'}, ...
    {'scalar', 'integer', 'positive'});
validateattributes(maximum_values, {'numeric'}, ...
    {'scalar', 'integer', 'positive'});
sample_count = number_rows*number_columns;
assert(2*sample_count <= maximum_values, 'P69:PrivateNoiseBound', ...
    'Private generator request exceeds the reviewed ceiling.');
uniform_values = private_uniform(seed, 2*sample_count, maximum_values);
first = max(uniform_values(1:sample_count), realmin);
second = uniform_values(sample_count+1:end);
samples = sqrt(-2*log(first)).*exp(1j*2*pi*second)/sqrt(2);
noise = reshape(samples, number_rows, number_columns);
end

function values = private_uniform(seed, count, maximum_values)
validateattributes(seed, {'numeric'}, ...
    {'scalar', 'integer', '>=', 1, '<', 2147483647});
validateattributes(count, {'numeric'}, ...
    {'scalar', 'integer', '>=', 1, '<=', maximum_values});
state = seed;
values = zeros(count, 1);
for value_index = 1:count
    state = mod(16807*state, 2147483647);
    values(value_index) = state/2147483647;
end
end

function validate_controls(c)
assert(isstruct(c) && isscalar(c), 'P69:ControlsType', ...
    'Controls must be one scalar struct.');
required_fields = {'seed', 'c_mps', 'fs_hz', 'duration_s', ...
    'bandwidth_hz', 'range_m', 'echo_voltage', 'noise_rms', ...
    'fft_length', 'range_sweep_m', 'bandwidth_sweep_hz', ...
    'plot_floor_db', 'max_samples', 'max_fft_length', ...
    'max_sweep_cases', 'max_private_values', 'max_working_values', ...
    'max_figures'};
assert(isequal(sort(fieldnames(c)), sort(required_fields.')), ...
    'P69:ControlFields', 'Controls have missing or unexpected fields.');
scalar_fields = {'seed', 'c_mps', 'fs_hz', 'duration_s', ...
    'bandwidth_hz', 'range_m', 'echo_voltage', 'noise_rms', ...
    'fft_length', 'plot_floor_db', 'max_samples', 'max_fft_length', ...
    'max_sweep_cases', 'max_private_values', 'max_working_values', ...
    'max_figures'};
for field_index = 1:numel(scalar_fields)
    value = c.(scalar_fields{field_index});
    assert(isnumeric(value) && isreal(value) && isscalar(value) && ...
        isfinite(value), 'P69:ControlScalar', ...
        'Every scalar control must be finite, real, numeric, and scalar.');
end
vector_fields = {'range_sweep_m', 'bandwidth_sweep_hz'};
for field_index = 1:numel(vector_fields)
    values = c.(vector_fields{field_index});
    assert(isnumeric(values) && isreal(values) && isvector(values) && ...
        numel(values) >= 3 && numel(values) <= c.max_sweep_cases && ...
        all(isfinite(values)) && all(diff(values) > 0), ...
        'P69:ControlVector', ...
        'Sweep controls must be finite, strictly increasing vectors.');
end
integer_fields = {'seed', 'fft_length', 'max_samples', ...
    'max_fft_length', 'max_sweep_cases', 'max_private_values', ...
    'max_working_values', 'max_figures'};
for field_index = 1:numel(integer_fields)
    value = c.(integer_fields{field_index});
    assert(value > 0 && value == floor(value), 'P69:ControlInteger', ...
        'Integer controls and ceilings must be positive integers.');
end
sample_count = c.fs_hz*c.duration_s;
maximum_range_m = max([c.range_m c.range_sweep_m(:).']);
maximum_delay_s = 2*maximum_range_m/c.c_mps;
maximum_bandwidth_hz = max([c.bandwidth_hz c.bandwidth_sweep_hz(:).']);
maximum_slope = maximum_bandwidth_hz/c.duration_s;
maximum_beat_hz = maximum_slope*maximum_delay_s;
assert(c.c_mps > 0 && c.fs_hz > 0 && c.duration_s > 0 && ...
    c.bandwidth_hz > 0 && c.range_m > 0 && c.echo_voltage > 0 && ...
    c.echo_voltage <= 1 && c.noise_rms >= 0 && c.noise_rms <= 1 && ...
    abs(sample_count-round(sample_count)) < 1e-9 && ...
    sample_count >= 128 && sample_count <= c.max_samples && ...
    maximum_bandwidth_hz < c.fs_hz && maximum_beat_hz < c.fs_hz/2 && ...
    maximum_delay_s < c.duration_s && ...
    round(sample_count-c.fs_hz*maximum_delay_s) >= 128 && ...
    c.fft_length >= sample_count && c.fft_length <= c.max_fft_length && ...
    2^nextpow2(c.fft_length) == c.fft_length && ...
    c.plot_floor_db >= -200 && c.plot_floor_db <= -20, ...
    'P69:PhysicalControls', ...
    'Controls violate sampling, overlap, FFT, or physical bounds.');
assert(c.max_samples == 4096 && c.max_fft_length == 131072 && ...
    c.max_sweep_cases == 8 && c.max_private_values == 100000 && ...
    c.max_working_values == 1000000 && c.max_figures == 6, ...
    'P69:ImmutableCeilings', 'Reviewed resource ceilings changed.');
assert(c.seed <= 2147483642, 'P69:SeedRange', ...
    'Seed must leave room for deterministic companion streams.');
end
