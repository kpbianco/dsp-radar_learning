%% One isolated target: integer bin versus sub-bin peak location
baseline_received_single = baseline_first_echo+ ...
    high_noise_sigma*unit_noise_resolution;
[baseline_single_response, baseline_single_lags] = ...
    explicit_matched_response(baseline_received_single, baseline_pulse);
baseline_single_magnitude = abs(baseline_single_response);
accuracy_gate = abs(speed_of_light_mps*baseline_single_lags/ ...
    (2*sample_rate_hz)-single_target_range_m) <= accuracy_gate_half_width_m;
accuracy_gate_indices = find(accuracy_gate);
[~, gated_peak_offset] = max(baseline_single_magnitude(accuracy_gate_indices));
baseline_integer_peak_index = accuracy_gate_indices(gated_peak_offset);
[baseline_integer_lag_samples, baseline_refined_lag_samples] = ...
    refine_parabolic_peak(baseline_single_magnitude, baseline_single_lags, ...
    baseline_integer_peak_index, comparison_tolerance);
baseline_integer_range_m = speed_of_light_mps*baseline_integer_lag_samples/ ...
    (2*sample_rate_hz);
baseline_refined_range_m = speed_of_light_mps*baseline_refined_lag_samples/ ...
    (2*sample_rate_hz);
baseline_integer_error_m = baseline_integer_range_m-single_target_range_m;
baseline_refined_error_m = baseline_refined_range_m-single_target_range_m;
assert(abs(baseline_integer_error_m) <= range_bin_spacing_m/2+ ...
    comparison_tolerance && ...
    abs(baseline_refined_error_m) < abs(baseline_integer_error_m) && ...
    abs(baseline_refined_error_m) < baseline_response_width_m/20, ...
    'Single-target refinement must improve error far below response width.');

%% Sweep 3: SNR changes estimator error, not waveform response width
% The pulse, target, range gate, estimator, and underlying unit-noise bank
% stay fixed. Only noise scale changes. Bias, standard deviation, and RMSE
% are distinct metrics; response width is copied from the same clean pulse.
accuracy_unit_noise = randn(private_stream, accuracy_trial_count, ...
    record_sample_count);
accuracy_bias_m = zeros(size(accuracy_snr_db_sweep));
accuracy_standard_deviation_m = zeros(size(accuracy_snr_db_sweep));
accuracy_rmse_m = zeros(size(accuracy_snr_db_sweep));
accuracy_response_width_m = baseline_response_width_m* ...
    ones(size(accuracy_snr_db_sweep));
accuracy_all_estimates_m = zeros(numel(accuracy_snr_db_sweep), ...
    accuracy_trial_count);
for snr_index = 1:numel(accuracy_snr_db_sweep)
    case_noise_sigma = baseline_clean_peak/ ...
        10^(accuracy_snr_db_sweep(snr_index)/20);
    for trial_index = 1:accuracy_trial_count
        case_received = baseline_first_echo+case_noise_sigma* ...
            accuracy_unit_noise(trial_index, :);
        [case_response, case_lags] = ...
            explicit_matched_response(case_received, baseline_pulse);
        case_magnitude = abs(case_response);
        case_range_axis_m = speed_of_light_mps*case_lags/ ...
            (2*sample_rate_hz);
        case_gate_indices = find(abs(case_range_axis_m- ...
            single_target_range_m) <= accuracy_gate_half_width_m);
        [~, case_gated_peak_offset] = max(case_magnitude(case_gate_indices));
        case_peak_index = case_gate_indices(case_gated_peak_offset);
        [~, case_refined_lag] = refine_parabolic_peak( ...
            case_magnitude, case_lags, case_peak_index, comparison_tolerance);
        accuracy_all_estimates_m(snr_index, trial_index) = ...
            speed_of_light_mps*case_refined_lag/(2*sample_rate_hz);
    end
    case_errors_m = accuracy_all_estimates_m(snr_index, :)- ...
        single_target_range_m;
    accuracy_bias_m(snr_index) = mean(case_errors_m);
    accuracy_standard_deviation_m(snr_index) = std(case_errors_m, 0);
    accuracy_rmse_m(snr_index) = sqrt(mean(case_errors_m.^2));
end
assert(accuracy_rmse_m(end) < accuracy_rmse_m(1)/5 && ...
    accuracy_standard_deviation_m(end) < ...
    accuracy_standard_deviation_m(1)/5 && ...
    accuracy_rmse_m(end) < baseline_response_width_m/20 && ...
    all(accuracy_response_width_m == baseline_response_width_m), ...
    'Higher SNR must improve single-target estimation without changing width.');

%% Intentionally broken case: call two dense display samples two targets
% Linear interpolation only redraws the same unresolved 4 MHz response.
% The broken rule sorts samples by height and reports the largest two even
% when they are adjacent points on one physical maximum.
fine_range_axis_m = baseline_range_axis_m(1): ...
    range_bin_spacing_m/fine_grid_factor:baseline_range_axis_m(end);
fine_pair_magnitude = interp1(baseline_range_axis_m, ...
    baseline_pair_magnitude, fine_range_axis_m, 'linear');
broken_gate = fine_range_axis_m >= single_target_range_m- ...
    accuracy_gate_half_width_m & fine_range_axis_m <= ...
    second_target_range_m+accuracy_gate_half_width_m;
broken_gate_indices = find(broken_gate);
[~, broken_sort_order] = sort(fine_pair_magnitude(broken_gate_indices), ...
    'descend');
broken_selected_indices = broken_gate_indices(broken_sort_order(1:2));
broken_reported_ranges_m = sort(fine_range_axis_m(broken_selected_indices));
broken_reported_separation_m = diff(broken_reported_ranges_m);
broken_claimed_target_count = 2;
broken_physical_peak_count = baseline_pair_peak_count;
broken_model_valid = false;
assert(broken_claimed_target_count == 2 && ...
    broken_physical_peak_count == 1 && ...
    broken_reported_separation_m <= 2*range_bin_spacing_m/fine_grid_factor && ...
    abs(broken_reported_separation_m-two_target_separation_m) > ...
    baseline_response_width_m/4 && ~broken_model_valid, ...
    'The broken dense-grid rule must expose two samples on one blended crest.');

%% Recovery: restore physical peak counting and change actual bandwidth
