%% Baseline: one sampled pulse and one unresolved two-target response
% The declared B is the two-sided -3 dB bandwidth of the untruncated
% Gaussian spectrum. sigma_t=sqrt(log(2))/(pi*B). The sampled finite pulse
% is energy normalized, and its actual matched-response width is measured.
[baseline_pulse, baseline_pulse_time_s, baseline_time_sigma_s] = ...
    build_gaussian_pulse(baseline_bandwidth_hz, sample_rate_hz, ...
    pulse_truncation_sigma);
baseline_pulse_sample_count = numel(baseline_pulse);
first_delay_s = 2*single_target_range_m/speed_of_light_mps;
second_target_range_m = single_target_range_m+two_target_separation_m;
second_delay_s = 2*second_target_range_m/speed_of_light_mps;
first_delay_samples = first_delay_s*sample_rate_hz;
second_delay_samples = second_delay_s*sample_rate_hz;
baseline_first_echo = insert_fractional_echo(baseline_pulse, ...
    record_sample_count, first_delay_samples, echo_amplitude);
baseline_second_echo = insert_fractional_echo(baseline_pulse, ...
    record_sample_count, second_delay_samples, echo_amplitude);

% Unit-energy pulse => matched-filter output-noise standard deviation equals
% receiver sample-noise sigma. Scale from the sampled fractional-delay echo's
% clean peak, so the reference target realizes the labeled matched-filter SNR.
baseline_clean_single_response = explicit_matched_response( ...
    baseline_first_echo, baseline_pulse);
baseline_clean_peak = max(abs(baseline_clean_single_response));
high_noise_sigma = baseline_clean_peak/10^(high_matched_snr_db/20);
private_stream = RandStream('mt19937ar', 'Seed', random_seed);
unit_noise_resolution = randn(private_stream, 1, record_sample_count);
baseline_received_pair = baseline_first_echo+baseline_second_echo+ ...
    high_noise_sigma*unit_noise_resolution;
[baseline_pair_response, baseline_lags_samples] = ...
    explicit_matched_response(baseline_received_pair, baseline_pulse);
baseline_range_axis_m = speed_of_light_mps*baseline_lags_samples/ ...
    (2*sample_rate_hz);
baseline_pair_magnitude = abs(baseline_pair_response);
baseline_pair_peak_indices = visible_local_maxima( ...
    baseline_pair_magnitude, visible_peak_threshold_ratio);
baseline_pair_peak_count = numel(baseline_pair_peak_indices);

baseline_response_width_m = full_half_power_width( ...
    abs(baseline_clean_single_response), range_bin_spacing_m);
assert(baseline_pair_peak_count == 1, ...
    'The canonical 4 MHz, 22 m pair must produce one blended maximum.');
assert(baseline_response_width_m > range_bin_spacing_m && ...
    baseline_response_width_m < 2*baseline_nominal_resolution_m, ...
    'Measured response width must be finite and physically consistent.');

%% Sweep 1: bandwidth only, fixed targets and fixed high SNR
bandwidth_nominal_resolution_m = zeros(size(bandwidth_sweep_hz));
bandwidth_measured_width_m = zeros(size(bandwidth_sweep_hz));
bandwidth_peak_count = zeros(size(bandwidth_sweep_hz));
bandwidth_pair_magnitude = cell(size(bandwidth_sweep_hz));
bandwidth_range_axis_m = cell(size(bandwidth_sweep_hz));
bandwidth_received_pair = cell(size(bandwidth_sweep_hz));
for bandwidth_index = 1:numel(bandwidth_sweep_hz)
    case_bandwidth_hz = bandwidth_sweep_hz(bandwidth_index);
    case_pulse = build_gaussian_pulse(case_bandwidth_hz, sample_rate_hz, ...
        pulse_truncation_sigma);
    case_first_echo = insert_fractional_echo(case_pulse, ...
        record_sample_count, first_delay_samples, echo_amplitude);
    case_second_echo = insert_fractional_echo(case_pulse, ...
        record_sample_count, second_delay_samples, echo_amplitude);
    case_clean_response = explicit_matched_response(case_first_echo, case_pulse);
    case_clean_peak = max(abs(case_clean_response));
    case_high_noise_sigma = case_clean_peak/10^(high_matched_snr_db/20);
    case_received = case_first_echo+case_second_echo+ ...
        case_high_noise_sigma*unit_noise_resolution;
    [case_response, case_lags] = ...
        explicit_matched_response(case_received, case_pulse);
    case_magnitude = abs(case_response);
    bandwidth_nominal_resolution_m(bandwidth_index) = ...
        speed_of_light_mps/(2*case_bandwidth_hz);
    bandwidth_measured_width_m(bandwidth_index) = ...
        full_half_power_width(abs(case_clean_response), range_bin_spacing_m);
    bandwidth_peak_count(bandwidth_index) = numel( ...
        visible_local_maxima(case_magnitude, visible_peak_threshold_ratio));
    bandwidth_pair_magnitude{bandwidth_index} = case_magnitude;
    bandwidth_range_axis_m{bandwidth_index} = ...
        speed_of_light_mps*case_lags/(2*sample_rate_hz);
    bandwidth_received_pair{bandwidth_index} = case_received;
end
assert(all(diff(bandwidth_nominal_resolution_m) < 0) && ...
    all(diff(bandwidth_measured_width_m) < 0) && ...
    isequal(bandwidth_peak_count, [1 1 2]), ...
    'Increasing bandwidth must narrow width and reveal the canonical pair.');

%% Sweep 2: target spacing only, fixed 4 MHz waveform and fixed high SNR
