%% Local transparent operations
function [pulse, pulse_time_s, time_sigma_s] = build_gaussian_pulse( ...
    bandwidth_hz, sample_rate_hz, truncation_sigma)
% B is the two-sided -3 dB bandwidth of the ideal Gaussian spectrum.
% The pulse is sampled through +/- truncation_sigma*sigma_t and unit-energy
% normalized so matched-filter SNR has an explicit scale.
time_sigma_s = sqrt(log(2))/(pi*bandwidth_hz);
half_span_samples = ceil(truncation_sigma*time_sigma_s*sample_rate_hz);
pulse_time_s = (-half_span_samples:half_span_samples)/sample_rate_hz;
pulse = exp(-0.5*(pulse_time_s/time_sigma_s).^2);
pulse = pulse/sqrt(sum(abs(pulse).^2));
end

function echo = insert_fractional_echo(pulse, record_sample_count, ...
    delay_samples, amplitude)
% Evaluate a zero-extended, piecewise-linear pulse at n-delay_samples.
% Nothing wraps around the record; fractional delay exists before sampling.
echo = zeros(1, record_sample_count);
for record_index = 1:record_sample_count
    source_position = (record_index-1)-delay_samples;
    source_left = floor(source_position);
    source_fraction = source_position-source_left;
    left_value = 0;
    right_value = 0;
    if source_left >= 0 && source_left < numel(pulse)
        left_value = pulse(source_left+1);
    end
    if source_left+1 >= 0 && source_left+1 < numel(pulse)
        right_value = pulse(source_left+2);
    end
    echo(record_index) = amplitude*((1-source_fraction)*left_value+ ...
        source_fraction*right_value);
end
end

function [response, lags_samples] = explicit_matched_response( ...
    received_signal, pulse)
% y[ell] = sum_m x[ell+m]*conj(s[m]) over valid nonnegative echo lags.
lags_samples = 0:numel(received_signal)-numel(pulse);
response = zeros(size(lags_samples));
for lag_index = 1:numel(lags_samples)
    lag_samples = lags_samples(lag_index);
    aligned_sum = 0;
    for pulse_index = 1:numel(pulse)
        received_index = lag_samples+pulse_index;
        aligned_sum = aligned_sum+received_signal(received_index)* ...
            conj(pulse(pulse_index));
    end
    response(lag_index) = aligned_sum;
end
end

function peak_indices = visible_local_maxima(magnitude, threshold_ratio)
% Count strict local maxima above a declared fraction of the strongest peak.
% This deliberately differs from selecting the two largest samples.
threshold = threshold_ratio*max(magnitude);
peak_indices = find(magnitude(2:end-1) > magnitude(1:end-2) & ...
    magnitude(2:end-1) >= magnitude(3:end) & ...
    magnitude(2:end-1) >= threshold)+1;
end

function width_units = full_half_power_width(magnitude, unit_spacing)
% Full width of the sampled response above max/sqrt(2), since magnitude
% squared is power and -3 dB is one half of peak power.
above_half_power = find(magnitude >= max(magnitude)/sqrt(2));
assert(numel(above_half_power) >= 2, ...
    'The matched response must span at least two half-power samples.');
width_units = (above_half_power(end)-above_half_power(1))*unit_spacing;
end

function [integer_lag, refined_lag] = refine_parabolic_peak( ...
    magnitude, lags_samples, peak_index, tolerance)
% Fit a parabola through one maximum and its two neighbors. This refines
% one peak location; it neither adds bandwidth nor creates another maximum.
assert(peak_index > 1 && peak_index < numel(magnitude), ...
    'Peak refinement requires a two-sided sample neighborhood.');
left = magnitude(peak_index-1);
center = magnitude(peak_index);
right = magnitude(peak_index+1);
denominator = left-2*center+right;
if denominator < -tolerance
    offset = 0.5*(left-right)/denominator;
    % A noisy gated maximum can sit at a gate boundary or have an asymmetric
    % three-point neighborhood. Falling back inside the selected bin keeps the
    % estimator bounded without turning numerical curvature into a fake peak.
    offset = max(-0.5, min(0.5, offset));
else
    offset = 0;
end
integer_lag = lags_samples(peak_index);
refined_lag = integer_lag+offset;
end
