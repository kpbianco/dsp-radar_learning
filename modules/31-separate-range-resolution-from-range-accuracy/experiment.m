        record_sample_count, case_second_delay_samples, echo_amplitude);
    case_received = baseline_first_echo+case_second_echo+ ...
        high_noise_sigma*unit_noise_resolution;
    case_response = explicit_matched_response(case_received, baseline_pulse);
    case_magnitude = abs(case_response);
    separation_peak_count(separation_index) = numel( ...
        visible_local_maxima(case_magnitude, visible_peak_threshold_ratio));
    separation_pair_magnitude{separation_index} = case_magnitude;
end
assert(isequal(separation_peak_count, [1 1 2]), ...
