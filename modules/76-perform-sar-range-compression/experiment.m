%% Local transparent helpers
function validate_controls(controls)
vector_names = {'target_cross_range_m', 'target_perpendicular_range_m', ...
    'target_voltage', 'target_initial_phase_rad', ...
    'bandwidth_sweep_hz', 'spacing_sweep_m'};
for vector_index = 1:numel(vector_names)
    name = vector_names{vector_index};
    value = controls.(name);
    if ~isnumeric(value) || ~isreal(value) || isempty(value) || ...
            size(value, 1) ~= 1 || any(~isfinite(value))
        error('P76:ControlShape', ...
            '%s must be a finite real nonempty row vector.', name);
    end
end
target_count = numel(controls.target_cross_range_m);
if numel(controls.target_perpendicular_range_m) ~= target_count || ...
        numel(controls.target_voltage) ~= target_count || ...
        numel(controls.target_initial_phase_rad) ~= target_count
    error('P76:TargetLengths', ...
        'Every target property vector must have the same length.');
end
scalar_names = {'seed', 'c_mps', 'carrier_hz', 'sample_rate_hz', ...
    'pulse_duration_s', 'baseline_bandwidth_hz', ...
    'range_gate_start_m', 'range_gate_end_m', 'aperture_length_m', ...
    'platform_spacing_m', 'noise_rms_voltage', ...
    'max_aperture_samples', 'max_fast_time_samples', ...
    'max_compressed_samples', 'max_targets', 'max_sweep_cases', ...
    'max_private_values', 'max_working_values', 'max_figures', ...
    'max_phase_step_rad', 'min_phase_coherence', ...
    'max_broken_phase_coherence'};
for scalar_index = 1:numel(scalar_names)
    name = scalar_names{scalar_index};
    value = controls.(name);
    if ~isnumeric(value) || ~isreal(value) || numel(value) ~= 1 || ...
            ~isfinite(value)
        error('P76:ControlScalar', '%s must be a finite real scalar.', name);
    end
end
if controls.seed ~= floor(controls.seed) || controls.seed < 1 || ...
        controls.seed >= 2147483647
    error('P76:Seed', 'Seed must be an integer in [1, 2147483646].');
end
positive_names = {'c_mps', 'carrier_hz', 'sample_rate_hz', ...
    'pulse_duration_s', 'baseline_bandwidth_hz', ...
    'range_gate_start_m', 'range_gate_end_m', 'aperture_length_m', ...
    'platform_spacing_m', 'max_aperture_samples', ...
    'max_fast_time_samples', 'max_compressed_samples', 'max_targets', ...
    'max_sweep_cases', 'max_private_values', 'max_working_values', ...
    'max_figures', 'max_phase_step_rad', 'min_phase_coherence', ...
    'max_broken_phase_coherence'};
for scalar_index = 1:numel(positive_names)
    if controls.(positive_names{scalar_index}) <= 0
        error('P76:PositiveControl', '%s must be positive.', ...
            positive_names{scalar_index});
    end
end
if controls.noise_rms_voltage < 0
    error('P76:NoiseScale', 'Noise RMS must be nonnegative.');
end
if controls.range_gate_end_m <= controls.range_gate_start_m
    error('P76:RangeGate', 'Range-gate limits must be ordered.');
end
if any(controls.target_perpendicular_range_m <= 0) || ...
        any(controls.target_voltage <= 0) || ...
        any(controls.bandwidth_sweep_hz <= 0) || ...
        any(controls.spacing_sweep_m <= 0)
    error('P76:PositiveVectors', ...
        'Target ranges, voltages, bandwidths, and spacings must be positive.');
end
if any(diff(controls.bandwidth_sweep_hz) <= 0) || ...
        any(diff(controls.spacing_sweep_m) <= 0)
    error('P76:SweepOrder', ...
        'Bandwidth and spacing sweep cases must increase strictly.');
end
if controls.baseline_bandwidth_hz >= controls.sample_rate_hz/2 || ...
        max(controls.bandwidth_sweep_hz) >= controls.sample_rate_hz/2
    error('P76:NyquistMargin', ...
        'Every reviewed two-sided baseband chirp must stay below Fs/2.');
end
if abs(controls.sample_rate_hz*controls.pulse_duration_s- ...
        round(controls.sample_rate_hz*controls.pulse_duration_s)) > 1.0e-9
    error('P76:PulseGrid', 'Pulse duration must contain an integer sample count.');
end
if abs(controls.aperture_length_m/(2*controls.platform_spacing_m)- ...
        round(controls.aperture_length_m/(2*controls.platform_spacing_m))) ...
        > 1.0e-9
    error('P76:ApertureGrid', ...
        'Half-aperture must land exactly on the platform grid.');
end
range_spacing_m = controls.c_mps/(2*controls.sample_rate_hz);
if abs((controls.range_gate_end_m-controls.range_gate_start_m)/ ...
        range_spacing_m-round((controls.range_gate_end_m- ...
        controls.range_gate_start_m)/range_spacing_m)) > 1.0e-9
    error('P76:FastTimeGrid', ...
        'Range-gate endpoints must land exactly on the fast-time grid.');
end
if controls.max_phase_step_rad >= pi || ...
        controls.min_phase_coherence >= 1 || ...
        controls.max_broken_phase_coherence >= controls.min_phase_coherence
    error('P76:MetricLimits', 'Phase and coherence limits are inconsistent.');
end
if controls.max_figures < 6
    error('P76:FigureCeiling', ...
        'The immutable figure ceiling must allow six reviewed figure groups.');
end

aperture_samples = round(controls.aperture_length_m/ ...
    controls.platform_spacing_m)+1;
fast_time_samples = round((controls.range_gate_end_m- ...
    controls.range_gate_start_m)/range_spacing_m)+1;
pulse_samples = round(controls.sample_rate_hz*controls.pulse_duration_s);
compressed_samples = fast_time_samples+pulse_samples-1;
if aperture_samples > controls.max_aperture_samples || ...
        fast_time_samples > controls.max_fast_time_samples || ...
        compressed_samples > controls.max_compressed_samples || ...
        target_count > controls.max_targets
    error('P76:ResourceCeilings', ...
        'Aperture, fast-time, compressed, or target count exceeds its ceiling.');
end
if numel(controls.bandwidth_sweep_hz) > controls.max_sweep_cases || ...
        numel(controls.spacing_sweep_m) > controls.max_sweep_cases
    error('P76:SweepCeiling', 'A sweep exceeds its immutable case ceiling.');
end
if numel(controls.bandwidth_sweep_hz) ~= 3 || ...
        numel(controls.spacing_sweep_m) ~= 3
    error('P76:SweepCount', ...
        'The reviewed plots and assertions require exactly three sweep cases.');
end
spacing_grid_ratio = controls.spacing_sweep_m/range_spacing_m;
if any(abs(spacing_grid_ratio-round(spacing_grid_ratio)) > 1.0e-9)
    error('P76:SpacingGrid', ...
        'Every spacing case must land exactly on the fast-time range grid.');
end
largest_pair_delay = round((1000.0+max(controls.spacing_sweep_m)- ...
    controls.range_gate_start_m)/range_spacing_m);
if largest_pair_delay < 0 || largest_pair_delay+pulse_samples > ...
        fast_time_samples
    error('P76:SpacingSupport', ...
        'The range gate does not contain the largest reviewed target pair.');
end
if 2*aperture_samples*fast_time_samples > controls.max_private_values
    error('P76:PrivateCeiling', ...
        'The private noise request exceeds its immutable ceiling.');
end
predicted_working_values = ...
    18*aperture_samples*compressed_samples + ...
    12*aperture_samples*fast_time_samples + ...
    20*target_count*aperture_samples + ...
    20*compressed_samples*(numel(controls.bandwidth_sweep_hz)+ ...
    numel(controls.spacing_sweep_m));
if predicted_working_values > controls.max_working_values
    error('P76:WorkingPreflight', ...
        'Conservative working-storage prediction exceeds its ceiling.');
end

platform_position_m = -controls.aperture_length_m/2: ...
    controls.platform_spacing_m:controls.aperture_length_m/2;
wavelength_m = controls.c_mps/controls.carrier_hz;
for target_index = 1:target_count
    slant_range_m = sqrt(controls.target_perpendicular_range_m(target_index)^2 + ...
        (platform_position_m-controls.target_cross_range_m(target_index)).^2);
    phase_rad = controls.target_initial_phase_rad(target_index)- ...
        4*pi*(slant_range_m-controls.target_perpendicular_range_m(target_index))/ ...
        wavelength_m;
    if max(abs(diff(phase_rad))) >= controls.max_phase_step_rad
        error('P76:SpatialAliasing', ...
            'A target exceeds the adjacent aperture phase-step limit.');
    end
    delay_samples = round((slant_range_m-controls.range_gate_start_m)/ ...
        range_spacing_m);
    if any(delay_samples < 0) || any(delay_samples+pulse_samples > ...
            fast_time_samples)
        error('P76:EchoSupport', ...
            'The range gate does not contain every reviewed LFM echo.');
    end
end
end

function [waveform, pulse_time_s, instantaneous_frequency_hz] = ...
        build_lfm(bandwidth_hz, duration_s, sample_rate_hz)
if ~isscalar(bandwidth_hz) || ~isscalar(duration_s) || ...
        ~isscalar(sample_rate_hz) || any(~isfinite( ...
        [bandwidth_hz duration_s sample_rate_hz])) || ...
        bandwidth_hz <= 0 || duration_s <= 0 || sample_rate_hz <= 0 || ...
        bandwidth_hz >= sample_rate_hz/2
    error('P76:LfmControls', ...
        'LFM bandwidth, duration, and sample rate are invalid.');
end
sample_count = round(duration_s*sample_rate_hz);
if sample_count < 8 || abs(sample_count-duration_s*sample_rate_hz) > 1.0e-9
    error('P76:LfmSamples', ...
        'LFM duration must contain at least eight integer samples.');
end
pulse_time_s = (0:sample_count-1)/sample_rate_hz - ...
    (sample_count-1)/(2*sample_rate_hz);
chirp_rate_hz_per_s = bandwidth_hz/duration_s;
instantaneous_frequency_hz = chirp_rate_hz_per_s*pulse_time_s;
waveform = exp(1j*pi*chirp_rate_hz_per_s*pulse_time_s.^2);
end

function [received, clean, noise, slant_range_m, delay_index, phase_rad] = ...
        simulate_scene(seed, platform_position_m, raw_range_axis_m, waveform, ...
        target_cross_range_m, target_perpendicular_range_m, target_voltage, ...
        target_initial_phase_rad, range_gate_start_m, range_spacing_m, ...
        wavelength_m, noise_rms_voltage, maximum_private_values)
aperture_count = numel(platform_position_m);
fast_time_count = numel(raw_range_axis_m);
target_count = numel(target_voltage);
clean = zeros(aperture_count, fast_time_count);
slant_range_m = zeros(aperture_count, target_count);
delay_index = zeros(aperture_count, target_count);
phase_rad = zeros(aperture_count, target_count);
for target_index = 1:target_count
    slant_range_m(:, target_index) = sqrt( ...
        target_perpendicular_range_m(target_index)^2 + ...
        (platform_position_m(:)-target_cross_range_m(target_index)).^2);
    delay_index(:, target_index) = round((slant_range_m(:, target_index)- ...
        range_gate_start_m)/range_spacing_m)+1;
    phase_rad(:, target_index) = target_initial_phase_rad(target_index)- ...
        4*pi*(slant_range_m(:, target_index)- ...
        target_perpendicular_range_m(target_index))/wavelength_m;
    for aperture_index = 1:aperture_count
        echo_indices = delay_index(aperture_index, target_index)+ ...
            (0:numel(waveform)-1);
        clean(aperture_index, echo_indices) = ...
            clean(aperture_index, echo_indices)+ ...
            target_voltage(target_index)* ...
            exp(1j*phase_rad(aperture_index, target_index))*waveform;
    end
end
unit_noise = private_complex_noise(seed, numel(clean), ...
    maximum_private_values);
noise = noise_rms_voltage*reshape(unit_noise, size(clean));
received = clean+noise;
end

function width_m = half_power_width(magnitude, range_axis_m)
magnitude = magnitude(:).';
range_axis_m = range_axis_m(:).';
if numel(magnitude) ~= numel(range_axis_m) || numel(magnitude) < 3 || ...
        any(~isfinite(magnitude)) || any(~isfinite(range_axis_m)) || ...
        any(diff(range_axis_m) <= 0) || max(magnitude) <= 0
    error('P76:WidthInput', 'Width inputs must be finite, ordered, and nonzero.');
end
[peak, peak_index] = max(magnitude);
threshold = peak/sqrt(2);
left_index = peak_index;
while left_index > 1 && magnitude(left_index) >= threshold
    left_index = left_index-1;
end
right_index = peak_index;
while right_index < numel(magnitude) && magnitude(right_index) >= threshold
    right_index = right_index+1;
end
if left_index == 1 || right_index == numel(magnitude)
    error('P76:WidthSupport', 'Half-power crossings require support on both sides.');
end
left_range_m = range_axis_m(left_index)+(threshold-magnitude(left_index))* ...
    (range_axis_m(left_index+1)-range_axis_m(left_index))/ ...
    (magnitude(left_index+1)-magnitude(left_index));
right_range_m = range_axis_m(right_index-1)+(threshold- ...
    magnitude(right_index-1))*(range_axis_m(right_index)- ...
    range_axis_m(right_index-1))/(magnitude(right_index)- ...
    magnitude(right_index-1));
width_m = right_range_m-left_range_m;
end

function values = private_complex_noise(seed, count, maximum_count)
if ~isscalar(seed) || ~isfinite(seed) || seed ~= floor(seed) || ...
        seed < 1 || seed >= 2147483647
    error('P76:PrivateSeed', 'Private seed is outside the supported range.');
end
if ~isscalar(count) || ~isfinite(count) || count ~= floor(count) || ...
        count < 1 || 2*count > maximum_count
    error('P76:PrivateCount', 'Private generator request exceeds its ceiling.');
end
uniforms = zeros(1, 2*count);
state = seed;
for sample_index = 1:2*count
    state = mod(16807*state, 2147483647);
    uniforms(sample_index) = state/2147483647;
end
radius = sqrt(-2*log(max(uniforms(1:2:end), realmin)));
angle_rad = 2*pi*uniforms(2:2:end);
values = radius.*exp(1j*angle_rad)/sqrt(2);
end
