grid on;
xlabel('Platform cross-range position (m)');
ylabel('Unwrapped ridge phase (rad)');
title('Broken: magnitude preserves the ridge but replaces its phase by zero');
legend('Magnitude-only data', 'Expected path phase', 'Location', 'best');
subplot(2, 1, 2);
plot(platform_position_m, unwrap(angle(recovered_ridge)), 'b-', ...
    'LineWidth', 1.0);
hold on;
plot(platform_position_m, unwrap(angle(expected_failure_phasor)), ...
    'r--', 'LineWidth', 1.0);
grid on;
xlabel('Platform cross-range position (m)');
ylabel('Unwrapped ridge phase (rad)');
title('Recovered: unchanged complex range data retains the aperture phase');
legend('Recovered complex data', 'Expected path phase', 'Location', 'best');

