%% P76: Perform SAR Range Compression
% Guiding question:
% What information is created before azimuth focusing begins?
%
% Base MATLAB only. LFM generation, zero-extended echo insertion, private
% noise, row-wise matched filtering, range-axis correction, and phase metrics
% are explicit. The aperture dimension is preserved, not focused.

close(findall(0, 'Type', 'figure', 'Tag', 'P76'));
clear p76_results;

%% Visible deterministic controls and immutable resource ceilings
baseline_seed = 7601;
speed_of_light_mps = 3.0e8;
carrier_frequency_hz = 5.0e9;
sample_rate_hz = 120.0e6;
pulse_duration_s = 2.0e-6;
baseline_bandwidth_hz = 20.0e6;
range_gate_start_m = 950.0;
range_gate_end_m = 1400.0;
aperture_length_m = 80.0;
platform_spacing_m = 0.2;
target_cross_range_m = [-15.0 0.0 18.0];
target_perpendicular_range_m = [1000.0 1025.0 1070.0];
target_voltage = [1.0 0.80 0.60];
target_initial_phase_rad = [0.0 0.6 -0.9];
noise_rms_voltage = 0.20;
bandwidth_sweep_hz = [10.0e6 20.0e6 40.0e6];
spacing_sweep_m = [3.75 10.0 15.0];

maximum_aperture_samples = 501;
maximum_fast_time_samples = 401;
maximum_compressed_samples = 701;
maximum_targets = 5;
maximum_sweep_cases = 5;
maximum_private_values = 400000;
maximum_working_value_equivalents = 12000000;
maximum_figures = 6;
maximum_adjacent_phase_step_rad = 0.90*pi;
minimum_phase_coherence = 0.98;
maximum_broken_phase_coherence = 0.20;

controls = struct( ...
    'seed', baseline_seed, 'c_mps', speed_of_light_mps, ...
    'carrier_hz', carrier_frequency_hz, 'sample_rate_hz', sample_rate_hz, ...
    'pulse_duration_s', pulse_duration_s, ...
    'baseline_bandwidth_hz', baseline_bandwidth_hz, ...
    'range_gate_start_m', range_gate_start_m, ...
    'range_gate_end_m', range_gate_end_m, ...
    'aperture_length_m', aperture_length_m, ...
    'platform_spacing_m', platform_spacing_m, ...
    'target_cross_range_m', target_cross_range_m, ...
    'target_perpendicular_range_m', target_perpendicular_range_m, ...
    'target_voltage', target_voltage, ...
    'target_initial_phase_rad', target_initial_phase_rad, ...
    'noise_rms_voltage', noise_rms_voltage, ...
    'bandwidth_sweep_hz', bandwidth_sweep_hz, ...
    'spacing_sweep_m', spacing_sweep_m, ...
    'max_aperture_samples', maximum_aperture_samples, ...
    'max_fast_time_samples', maximum_fast_time_samples, ...
    'max_compressed_samples', maximum_compressed_samples, ...
    'max_targets', maximum_targets, ...
    'max_sweep_cases', maximum_sweep_cases, ...
    'max_private_values', maximum_private_values, ...
    'max_working_values', maximum_working_value_equivalents, ...
    'max_figures', maximum_figures, ...
    'max_phase_step_rad', maximum_adjacent_phase_step_rad, ...
    'min_phase_coherence', minimum_phase_coherence, ...
    'max_broken_phase_coherence', maximum_broken_phase_coherence);
validate_controls(controls);

wavelength_m = speed_of_light_mps/carrier_frequency_hz;
range_sample_spacing_m = speed_of_light_mps/(2*sample_rate_hz);
platform_position_m = -aperture_length_m/2:platform_spacing_m: ...
    aperture_length_m/2;
raw_range_axis_m = range_gate_start_m:range_sample_spacing_m: ...
    range_gate_end_m;
aperture_sample_count = numel(platform_position_m);
fast_time_sample_count = numel(raw_range_axis_m);

%% Baseline transmit pulse and raw complex phase history
[transmit_chirp, pulse_time_s, instantaneous_frequency_hz] = ...
    build_lfm(baseline_bandwidth_hz, pulse_duration_s, sample_rate_hz);
matched_filter = fliplr(conj(transmit_chirp));
matched_filter_energy = sum(abs(transmit_chirp).^2);

[raw_phase_history, clean_phase_history, additive_noise, ...
    target_slant_range_m, target_delay_index, target_phase_rad] = ...
    simulate_scene(baseline_seed, platform_position_m, ...
    raw_range_axis_m, transmit_chirp, target_cross_range_m, ...
    target_perpendicular_range_m, target_voltage, ...
    target_initial_phase_rad, range_gate_start_m, ...
    range_sample_spacing_m, wavelength_m, noise_rms_voltage, ...
    maximum_private_values);

%% Explicit range compression: independent linear matched filter per aperture row
compressed_sample_count = fast_time_sample_count+numel(transmit_chirp)-1;
range_compressed_history = zeros(aperture_sample_count, ...
    compressed_sample_count);
for aperture_index = 1:aperture_sample_count
    for output_index = 1:compressed_sample_count
        aligned_sum = 0;
        input_min = max(1, output_index-numel(matched_filter)+1);
        input_max = min(fast_time_sample_count, output_index);
        for input_index = input_min:input_max
            filter_index = output_index-input_index+1;
            aligned_sum = aligned_sum + ...
                raw_phase_history(aperture_index, input_index)* ...
                matched_filter(filter_index);
        end
        range_compressed_history(aperture_index, output_index) = ...
            aligned_sum/matched_filter_energy;
    end
end

filter_delay_samples = numel(transmit_chirp)-1;
compressed_range_axis_m = range_gate_start_m + ...
    (((1:compressed_sample_count)-1)-filter_delay_samples)* ...
    range_sample_spacing_m;
assert(abs(compressed_range_axis_m(filter_delay_samples+1)- ...
    range_gate_start_m) < 1.0e-12, 'P76:FilterDelayAxis', ...
    'The matched-filter delay must map back to the range-gate start.');

center_aperture_index = (aperture_sample_count+1)/2;
center_convolution_crosscheck = conv( ...
    raw_phase_history(center_aperture_index, :), matched_filter)/ ...
    matched_filter_energy;
convolution_crosscheck_error = max(abs(center_convolution_crosscheck- ...
    range_compressed_history(center_aperture_index, :)));
assert(convolution_crosscheck_error < 1.0e-10, ...
    'P76:ConvolutionCrosscheck', ...
    'Explicit matched filtering must agree with linear convolution.');

nominal_range_resolution_m = speed_of_light_mps/(2*baseline_bandwidth_hz);
maximum_delay_quantization_m = range_sample_spacing_m/2;
range_quantization_error_m = abs(target_slant_range_m- ...
    (range_gate_start_m+(target_delay_index-1)*range_sample_spacing_m));
assert(max(range_quantization_error_m(:)) <= ...
    maximum_delay_quantization_m+1.0e-9, 'P76:RangeQuantization', ...
    'Integer delay must stay within half a range sample of true slant range.');

fprintf('\nP76 baseline: range compression preserves %d aperture rows\n', ...
    aperture_sample_count);
fprintf('Pulse: %.1f us, %.1f MHz, B*T = %.1f, %d samples\n', ...
    1.0e6*pulse_duration_s, baseline_bandwidth_hz/1.0e6, ...
    baseline_bandwidth_hz*pulse_duration_s, numel(transmit_chirp));
fprintf('Range sample spacing = %.3f m; nominal resolution = %.3f m\n', ...
    range_sample_spacing_m, nominal_range_resolution_m);
fprintf('Raw/compressed matrix sizes: %d x %d / %d x %d\n', ...
    size(raw_phase_history, 1), size(raw_phase_history, 2), ...
    size(range_compressed_history, 1), size(range_compressed_history, 2));
fprintf('Explicit-versus-conv cross-check error = %.3g\n', ...
    convolution_crosscheck_error);

figure('Name', 'P76 waveform and center-look compression', ...
    'Tag', 'P76', 'NumberTitle', 'off');
subplot(3, 1, 1);
plot(1.0e6*pulse_time_s, real(transmit_chirp), 'b-', ...
    1.0e6*pulse_time_s, imag(transmit_chirp), 'r-');
grid on;
xlabel('Pulse time (microseconds)');
ylabel('Complex amplitude');
title('Transmit LFM: one energetic pulse used at every aperture position');
legend('I', 'Q', 'Location', 'best');
subplot(3, 1, 2);
plot(1.0e6*pulse_time_s, instantaneous_frequency_hz/1.0e6, 'k-');
grid on;
xlabel('Pulse time (microseconds)');
ylabel('Instantaneous frequency (MHz)');
title('Linear sweep bandwidth controls range resolution');
subplot(3, 1, 3);
plot(raw_range_axis_m, abs(raw_phase_history(center_aperture_index, :)), ...
    'Color', [0.65 0.65 0.65]);
hold on;
plot(compressed_range_axis_m, ...
    abs(range_compressed_history(center_aperture_index, :)), 'b-', ...
    'LineWidth', 1.1);
grid on;
xlabel('Apparent monostatic slant range (m)');
ylabel('Magnitude (normalized voltage)');
title('One center look: long echoes become localized range responses');
legend('Raw fast time', 'Range compressed', 'Location', 'best');
xlim([range_gate_start_m range_gate_end_m]);

figure('Name', 'P76 raw aperture fast-time data', ...
    'Tag', 'P76', 'NumberTitle', 'off');
imagesc(raw_range_axis_m, platform_position_m, abs(raw_phase_history));
axis xy;
xlabel('Apparent monostatic slant range (m)');
ylabel('Platform cross-range position (m)');
title('Before compression: each long LFM echo occupies many fast-time samples');
colorbar;

compressed_magnitude_db = 20*log10(max( ...
    abs(range_compressed_history)/max(abs(range_compressed_history(:))), ...
    1.0e-6));
figure('Name', 'P76 complex range-compressed phase history', ...
    'Tag', 'P76', 'NumberTitle', 'off');
subplot(2, 1, 1);
imagesc(compressed_range_axis_m, platform_position_m, ...
    compressed_magnitude_db);
axis xy;
xlabel('Filter-delay-corrected slant range (m)');
ylabel('Platform cross-range position (m)');
title('After compression: localized range ridges, but no azimuth focus');
colorbar;
caxis([-45 0]);

target_ridge_measurement = zeros(aperture_sample_count, numel(target_voltage));
target_phase_coherence = zeros(1, numel(target_voltage));
for target_index = 1:numel(target_voltage)
    target_peak_index = target_delay_index(:, target_index)+ ...
        filter_delay_samples;
    for aperture_index = 1:aperture_sample_count
        target_ridge_measurement(aperture_index, target_index) = ...
            range_compressed_history(aperture_index, ...
            target_peak_index(aperture_index));
    end
    expected_phasor = exp(1j*target_phase_rad(:, target_index));
    observed_unit_phasor = target_ridge_measurement(:, target_index)./ ...
        max(abs(target_ridge_measurement(:, target_index)), eps);
    target_phase_coherence(target_index) = abs(mean( ...
        observed_unit_phasor.*conj(expected_phasor)));
end
assert(all(target_phase_coherence > minimum_phase_coherence), ...
    'P76:PhasePreserved', ...
    'Range-compressed target ridges must preserve expected aperture phase.');
subplot(2, 1, 2);
plot(platform_position_m, unwrap(angle( ...
    target_ridge_measurement(:, 3))), 'b-', 'LineWidth', 1.0);
hold on;
plot(platform_position_m, unwrap(target_phase_rad(:, 3)), 'r--', ...
    'LineWidth', 1.0);
grid on;
xlabel('Platform cross-range position (m)');
ylabel('Unwrapped ridge phase (rad)');
title('The complex ridge retains the target path-dependent aperture phase');
legend('Compressed data', 'Expected two-way phase', 'Location', 'best');
fprintf('Target ridge phase coherences: %s\n', ...
    mat2str(target_phase_coherence, 5));

%% Sweep 1: bandwidth only, fixed duration, scene, aperture, and noise seed
bandwidth_case_count = numel(bandwidth_sweep_hz);
bandwidth_measured_width_m = zeros(1, bandwidth_case_count);
bandwidth_nominal_resolution_m = speed_of_light_mps./ ...
    (2*bandwidth_sweep_hz);
bandwidth_profiles = cell(1, bandwidth_case_count);
bandwidth_range_axes_m = cell(1, bandwidth_case_count);
isolated_delay_samples = round((target_perpendicular_range_m(1)- ...
    range_gate_start_m)/range_sample_spacing_m);

for case_index = 1:bandwidth_case_count
    case_bandwidth_hz = bandwidth_sweep_hz(case_index);
    case_chirp = build_lfm(case_bandwidth_hz, pulse_duration_s, ...
        sample_rate_hz);
    case_raw_echo = zeros(1, fast_time_sample_count);
    case_indices = isolated_delay_samples+(1:numel(case_chirp));
    case_raw_echo(case_indices) = case_chirp;
    case_matched_filter = fliplr(conj(case_chirp));
    case_profile = conv(case_raw_echo, case_matched_filter)/ ...
        sum(abs(case_chirp).^2);
    case_range_axis_m = range_gate_start_m + ...
        (((1:numel(case_profile))-1)-(numel(case_chirp)-1))* ...
        range_sample_spacing_m;
    bandwidth_profiles{case_index} = case_profile;
    bandwidth_range_axes_m{case_index} = case_range_axis_m;
    bandwidth_measured_width_m(case_index) = half_power_width( ...
        abs(case_profile), case_range_axis_m);
end
assert(all(diff(bandwidth_measured_width_m) < 0) && ...
    all(diff(bandwidth_nominal_resolution_m) < 0), ...
    'P76:BandwidthSweep', ...
    'Increasing bandwidth must narrow measured and nominal range response.');

fprintf('\nBandwidth sweep (MHz): %s\n', ...
    mat2str(bandwidth_sweep_hz/1.0e6));
fprintf('Measured full -3 dB widths (m): %s\n', ...
    mat2str(bandwidth_measured_width_m, 5));
fprintf('Nominal c/(2B) scales (m): %s\n', ...
    mat2str(bandwidth_nominal_resolution_m, 5));

figure('Name', 'P76 bandwidth-only sweep', ...
    'Tag', 'P76', 'NumberTitle', 'off');
subplot(2, 1, 1);
hold on;
for case_index = 1:bandwidth_case_count
    profile_db = 20*log10(max(abs(bandwidth_profiles{case_index})/ ...
