%% Sweep 2: target range spacing only, fixed waveform and equal amplitudes
spacing_case_count = numel(spacing_sweep_m);
spacing_profiles = cell(1, spacing_case_count);
spacing_range_axis_m = cell(1, spacing_case_count);
spacing_valley_ratio = zeros(1, spacing_case_count);
spacing_resolved = false(1, spacing_case_count);
pair_base_range_m = 1000.0;

for case_index = 1:spacing_case_count
    case_spacing_m = spacing_sweep_m(case_index);
    pair_range_m = [pair_base_range_m pair_base_range_m+case_spacing_m];
    pair_delay_samples = round((pair_range_m-range_gate_start_m)/ ...
        range_sample_spacing_m);
    pair_raw_echo = zeros(1, fast_time_sample_count);
    for pair_index = 1:2
        pair_indices = pair_delay_samples(pair_index)+ ...
            (1:numel(transmit_chirp));
        pair_raw_echo(pair_indices) = pair_raw_echo(pair_indices)+ ...
            transmit_chirp;
    end
    pair_profile = conv(pair_raw_echo, matched_filter)/matched_filter_energy;
    pair_range_axis = range_gate_start_m + ...
        (((1:numel(pair_profile))-1)-filter_delay_samples)* ...
        range_sample_spacing_m;
    peak_indices = pair_delay_samples+filter_delay_samples+1;
    search_half_width = max(1, round(0.25*nominal_range_resolution_m/ ...
        range_sample_spacing_m));
    pair_peak = zeros(1, 2);
    for pair_index = 1:2
        search_indices = peak_indices(pair_index)+ ...
            (-search_half_width:search_half_width);
        pair_peak(pair_index) = max(abs(pair_profile(search_indices)));
    end
    between_indices = peak_indices(1):peak_indices(2);
    valley = min(abs(pair_profile(between_indices)));
    spacing_valley_ratio(case_index) = valley/min(pair_peak);
    spacing_resolved(case_index) = spacing_valley_ratio(case_index) < ...
        1/sqrt(2);
    spacing_profiles{case_index} = pair_profile;
    spacing_range_axis_m{case_index} = pair_range_axis;
end
assert(~spacing_resolved(1) && ~spacing_resolved(2) && ...
    spacing_resolved(3), 'P76:SpacingSweep', ...
    'Reviewed spacing cases must progress from merged to clearly separated.');

fprintf('\nEqual-target spacing sweep (m): %s\n', ...
    mat2str(spacing_sweep_m));
fprintf('Valley / weaker-peak ratios: %s; resolved at -3 dB: %s\n', ...
    mat2str(spacing_valley_ratio, 5), mat2str(spacing_resolved));

figure('Name', 'P76 target-range-spacing sweep', ...
    'Tag', 'P76', 'NumberTitle', 'off');
for case_index = 1:spacing_case_count
    subplot(spacing_case_count, 1, case_index);
    profile_db = 20*log10(max(abs(spacing_profiles{case_index})/ ...
        max(abs(spacing_profiles{case_index})), 1.0e-5));
    plot(spacing_range_axis_m{case_index}, profile_db, 'b-', ...
        'LineWidth', 1.0);
    grid on;
    xlabel('Filter-delay-corrected slant range (m)');
    ylabel('Normalized output (dB)');
    title(sprintf('Only target spacing changes: %.2f m, resolved = %d', ...
        spacing_sweep_m(case_index), spacing_resolved(case_index)));
    xlim([pair_base_range_m-25 pair_base_range_m+45]);
    ylim([-45 2]);
end

%% Intentionally broken case: discard complex phase after range compression
retained_complex_range_history = range_compressed_history;
magnitude_only_range_history = abs(retained_complex_range_history);
measurement_before_recovery = retained_complex_range_history;
recovered_complex_range_history = retained_complex_range_history;
recovery_exact_match = isequaln(recovered_complex_range_history, ...
    measurement_before_recovery);

failure_target_index = 3;
failure_peak_index = target_delay_index(:, failure_target_index)+ ...
    filter_delay_samples;
broken_ridge = zeros(aperture_sample_count, 1);
recovered_ridge = zeros(aperture_sample_count, 1);
for aperture_index = 1:aperture_sample_count
    broken_ridge(aperture_index) = magnitude_only_range_history( ...
        aperture_index, failure_peak_index(aperture_index));
    recovered_ridge(aperture_index) = recovered_complex_range_history( ...
        aperture_index, failure_peak_index(aperture_index));
end
expected_failure_phasor = exp(1j*target_phase_rad(:, failure_target_index));
broken_unit_phasor = broken_ridge./max(abs(broken_ridge), eps);
recovered_unit_phasor = recovered_ridge./max(abs(recovered_ridge), eps);
broken_phase_coherence = abs(mean( ...
    broken_unit_phasor.*conj(expected_failure_phasor)));
recovered_phase_coherence = abs(mean( ...
    recovered_unit_phasor.*conj(expected_failure_phasor)));
magnitude_ridge_exact_match = isequal( ...
    abs(recovered_complex_range_history), magnitude_only_range_history);

assert(magnitude_ridge_exact_match && ...
    broken_phase_coherence < maximum_broken_phase_coherence, ...
    'P76:MagnitudeOnlyFailure', ...
    'Magnitude-only data must retain ridges while losing aperture phase.');
assert(recovery_exact_match && ...
    recovered_phase_coherence > minimum_phase_coherence, ...
    'P76:SameDataRecovery', ...
    'Recovery must use unchanged complex data and restore phase coherence.');

fprintf('\nMagnitude-only failure: ridge magnitude exact = %d\n', ...
    magnitude_ridge_exact_match);
fprintf('Broken/recovered phase coherence: %.4f / %.4f\n', ...
    broken_phase_coherence, recovered_phase_coherence);
fprintf('Same-data recovery exact match: %d\n', recovery_exact_match);

figure('Name', 'P76 magnitude-only failure and recovery', ...
    'Tag', 'P76', 'NumberTitle', 'off');
subplot(2, 1, 1);
plot(platform_position_m, unwrap(angle(broken_ridge)), 'k-', ...
