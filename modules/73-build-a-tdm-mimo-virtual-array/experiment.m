function [positions_lambda, tx_slot_by_virtual] = ...
    construct_virtual_positions(tx_positions_lambda, rx_positions_lambda)
    number_tx_local = numel(tx_positions_lambda);
    number_rx_local = numel(rx_positions_lambda);
    positions_lambda = zeros(1, number_tx_local*number_rx_local);
    tx_slot_by_virtual = zeros(1, number_tx_local*number_rx_local);
    output_index = 0;
    for tx_index_local = 1:number_tx_local
        for rx_index_local = 1:number_rx_local
            output_index = output_index+1;
            positions_lambda(output_index) = ...
                tx_positions_lambda(tx_index_local)+ ...
                rx_positions_lambda(rx_index_local);
            tx_slot_by_virtual(output_index) = tx_index_local-1;
        end
    end
end

function power = array_response_power(positions_lambda, scan_angles_deg, ...
    source_angles_deg)
    number_channels_local = numel(positions_lambda);
    scan_steering = exp(-1j*2*pi*positions_lambda(:)* ...
        sind(scan_angles_deg));
    power = zeros(1, numel(scan_angles_deg));
    for source_index = 1:numel(source_angles_deg)
        source_steering = exp(-1j*2*pi*positions_lambda(:)* ...
            sind(source_angles_deg(source_index)));
        coherent_output = scan_steering'*source_steering/ ...
            number_channels_local;
        power = power+abs(coherent_output.').^2;
    end
end

function power = scan_power(data, positions_lambda, scan_angles_deg)
    number_channels_local = numel(positions_lambda);
    assert(size(data, 1) == number_channels_local, ...
        'P73:ScanDimensions', ...
        'Data rows must match the number of virtual positions.');
    scan_steering = exp(-1j*2*pi*positions_lambda(:)* ...
        sind(scan_angles_deg));
    weights = scan_steering/number_channels_local;
    beam_outputs = weights'*data;
    power = mean(abs(beam_outputs).^2, 2).';
end

function width_deg = half_power_beamwidth(scan_angles_deg, power)
    [peak_power, peak_index] = max(power);
    left_index = peak_index;
    while left_index > 1 && power(left_index) >= peak_power/2
        left_index = left_index-1;
    end
    right_index = peak_index;
    while right_index < numel(power) && power(right_index) >= peak_power/2
        right_index = right_index+1;
    end
    assert(left_index > 1 && right_index < numel(power), ...
        'P73:BeamwidthBounds', ...
        'The reviewed scan must contain both half-power crossings.');
    left_angle = interp1(power(left_index:left_index+1), ...
        scan_angles_deg(left_index:left_index+1), peak_power/2);
    right_angle = interp1(power(right_index-1:right_index), ...
        scan_angles_deg(right_index-1:right_index), peak_power/2);
    width_deg = right_angle-left_angle;
end

function [dip_db, is_resolved, peak_angles_deg] = ...
    pair_resolution_metrics(scan_angles_deg, power, threshold_db)
    [~, center_index] = min(abs(scan_angles_deg));
    [left_peak, left_relative_index] = max(power(1:center_index));
    left_index = left_relative_index;
    [right_peak, right_relative_index] = max(power(center_index:end));
    right_index = center_index+right_relative_index-1;
    midpoint_power = power(center_index);
    smaller_peak = min(left_peak, right_peak);
    dip_db = max(0, 10*log10(smaller_peak/max(midpoint_power, eps)));
    peak_angles_deg = [scan_angles_deg(left_index) ...
        scan_angles_deg(right_index)];
    is_resolved = dip_db >= threshold_db && ...
        peak_angles_deg(1) < -0.25 && peak_angles_deg(2) > 0.25;
end

function [data, noise] = simulate_tdm_record(seed, positions_lambda, ...
    tx_slot_by_virtual, target_angle_deg, target_velocity_mps, ...
    wavelength_m, tx_slot_s, number_cycles, snr_db, maximum_private_values)
    number_channels_local = numel(positions_lambda);
    cycle_spacing_s = (max(tx_slot_by_virtual)+1)*tx_slot_s;
    doppler_hz = 2*target_velocity_mps/wavelength_m;
    cycle_time_s = (0:number_cycles-1)*cycle_spacing_s;
    noise = private_complex_noise(seed, number_channels_local, ...
        number_cycles, maximum_private_values);
    noise_rms = 10^(-snr_db/20);
    data = zeros(number_channels_local, number_cycles);
    for channel_index = 1:number_channels_local
        spatial_phase_rad = -2*pi*positions_lambda(channel_index)* ...
            sind(target_angle_deg);
        sample_time_s = cycle_time_s+ ...
            tx_slot_by_virtual(channel_index)*tx_slot_s;
        data(channel_index, :) = exp(1j*spatial_phase_rad).* ...
            exp(-1j*2*pi*doppler_hz*sample_time_s)+ ...
            noise_rms*noise(channel_index, :);
    end
end

function doppler_hz = estimate_same_tx_doppler(data, cycle_spacing_s)
    assert(size(data, 2) >= 2, 'P73:DopplerLength', ...
        'Same-TX Doppler estimation requires at least two TDM cycles.');
    lag_one_products = conj(data(:, 1:end-1)).*data(:, 2:end);
    coherent_product = sum(lag_one_products(:));
    assert(abs(coherent_product) > 100*eps, 'P73:DopplerEnergy', ...
        'Same-TX lag-one phase is undefined at zero coherent energy.');
    doppler_hz = -angle(coherent_product)/(2*pi*cycle_spacing_s);
end

function compensated = compensate_tdm_slots(data, tx_slot_by_virtual, ...
    tx_slot_s, doppler_hz)
    compensated = data;
    for channel_index = 1:size(data, 1)
        slot_time_s = tx_slot_by_virtual(channel_index)*tx_slot_s;
        compensated(channel_index, :) = data(channel_index, :)* ...
            exp(1j*2*pi*doppler_hz*slot_time_s);
    end
end

function angle_deg = peak_angle(scan_angles_deg, power)
    [~, index] = max(power);
    angle_deg = scan_angles_deg(index);
end

function relative_db = power_to_relative_db(power, floor_db)
    normalized = power/max(power);
    relative_db = max(10*log10(max(normalized, 10^(floor_db/10))), ...
        floor_db);
end

function noise = private_complex_noise(seed, number_rows, number_columns, ...
    maximum_values)
    count = number_rows*number_columns;
    assert(2*count <= maximum_values, 'P73:PrivateNoiseBound', ...
        'Private noise request exceeds the immutable ceiling.');
    uniform_values = private_uniform(seed, 2*count, maximum_values);
    radius = sqrt(-2*log(max(uniform_values(1:2:end), realmin)));
    phase = 2*pi*uniform_values(2:2:end);
    normal_1 = radius.*cos(phase);
    normal_2 = radius.*sin(phase);
    noise = reshape((normal_1+1j*normal_2)/sqrt(2), ...
        number_rows, number_columns);
end

function values = private_uniform(seed, count, maximum_values)
    validateattributes(seed, {'numeric'}, ...
        {'real', 'scalar', 'integer', '>=', 1, '<', 2147483647});
    validateattributes(count, {'numeric'}, ...
        {'real', 'scalar', 'integer', '>=', 1, '<=', maximum_values});
    state = double(seed);
    values = zeros(1, count);
    for value_index = 1:count
        state = mod(16807*state, 2147483647);
        values(value_index) = state/2147483647;
    end
end

function validate_controls(c)
    assert(isstruct(c) && isscalar(c), 'P73:ControlsType', ...
        'Controls must be one scalar structure.');
    required_fields = {'seed', 'c_mps', 'carrier_hz', ...
        'rx_positions_lambda', 'tx_positions_lambda', ...
        'target_angle_deg', 'target_velocity_mps', 'tdm_cycles', ...
        'tx_slot_s', 'snr_db', 'scan_angles_deg', ...
        'separation_sweep_deg', 'velocity_sweep_mps', ...
        'broken_velocity_mps', 'resolution_dip_db', 'plot_floor_db', ...
        'max_virtual_channels', 'max_tdm_cycles', 'max_scan_samples', ...
        'max_sweep_cases', 'max_private_values', 'max_working_values', ...
        'max_figures'};
    assert(isequal(sort(fieldnames(c)), sort(required_fields.')), ...
        'P73:ControlFields', 'Control fields are missing or unexpected.');

    scalar_fields = {'seed', 'c_mps', 'carrier_hz', ...
        'target_angle_deg', 'target_velocity_mps', 'tdm_cycles', ...
        'tx_slot_s', 'snr_db', 'broken_velocity_mps', ...
        'resolution_dip_db', 'plot_floor_db', 'max_virtual_channels', ...
        'max_tdm_cycles', 'max_scan_samples', 'max_sweep_cases', ...
        'max_private_values', 'max_working_values', 'max_figures'};
    for field_index = 1:numel(scalar_fields)
        value = c.(scalar_fields{field_index});
        assert(isnumeric(value) && isreal(value) && isscalar(value) && ...
            isfinite(value), 'P73:ControlScalar', ...
            'Scalar controls must be finite real numeric values.');
    end
    vector_fields = {'rx_positions_lambda', 'tx_positions_lambda', ...
        'scan_angles_deg', 'separation_sweep_deg', 'velocity_sweep_mps'};
    for field_index = 1:numel(vector_fields)
        values = c.(vector_fields{field_index});
        assert(isnumeric(values) && isreal(values) && isrow(values) && ...
            ~isempty(values) && all(isfinite(values)), ...
            'P73:ControlVector', ...
            'Vector controls must be finite nonempty numeric rows.');
    end
    integer_fields = {'seed', 'tdm_cycles', 'max_virtual_channels', ...
        'max_tdm_cycles', 'max_scan_samples', 'max_sweep_cases', ...
        'max_private_values', 'max_working_values', 'max_figures'};
    for field_index = 1:numel(integer_fields)
        value = c.(integer_fields{field_index});
        assert(value >= 1 && value == floor(value), 'P73:ControlInteger', ...
            'Integer controls and ceilings must be positive integers.');
    end

    assert(c.seed == 7301 && c.seed < 2147483000, 'P73:SeedRange', ...
        'The reviewed private deterministic seed changed or is unsafe.');
    assert(c.c_mps == 3.0e8 && c.carrier_hz == 77.0e9 && ...
        c.tx_slot_s == 40.0e-6 && c.c_mps > 0 && c.carrier_hz > 0, ...
        'P73:PhysicalControls', ...
        'Reviewed propagation, carrier, or TDM timing controls changed.');
    assert(isequal(c.rx_positions_lambda, [0 0.5 1.0 1.5]) && ...
        isequal(c.tx_positions_lambda, [0 2.0]) && ...
        all(diff(c.rx_positions_lambda) > 0) && ...
        all(diff(c.tx_positions_lambda) > 0), 'P73:GeometryControls', ...
        'Reviewed physical positions changed or are not strictly ordered.');
    assert(c.target_angle_deg == 18 && c.target_velocity_mps == 0 && ...
        c.tdm_cycles == 64 && c.tdm_cycles <= c.max_tdm_cycles && ...
        c.snr_db == 20, 'P73:BaselineControls', ...
        'Reviewed target or acquisition controls changed.');
    assert(numel(c.scan_angles_deg) >= 3 && ...
        numel(c.scan_angles_deg) <= c.max_scan_samples && ...
        all(diff(c.scan_angles_deg) > 0) && c.scan_angles_deg(1) == -60 && ...
        c.scan_angles_deg(end) == 60 && ...
        any(c.scan_angles_deg == c.target_angle_deg), ...
        'P73:ScanGrid', 'Reviewed scan grid changed or is malformed.');
    assert(isequal(c.separation_sweep_deg, [8 16 28]) && ...
        numel(c.separation_sweep_deg) <= c.max_sweep_cases && ...
        all(diff(c.separation_sweep_deg) > 0), ...
        'P73:SeparationSweep', ...
        'Reviewed separation sweep changed or is malformed.');
    assert(isequal(c.velocity_sweep_mps, [-10 -5 0 5 10]) && ...
        numel(c.velocity_sweep_mps) <= c.max_sweep_cases && ...
        all(diff(c.velocity_sweep_mps) > 0) && ...
        c.broken_velocity_mps == 10 && ...
        any(c.velocity_sweep_mps == c.broken_velocity_mps), ...
        'P73:VelocitySweep', ...
        'Reviewed velocity sweep or broken case changed.');
    wavelength_local_m = c.c_mps/c.carrier_hz;
    cycle_spacing_local_s = numel(c.tx_positions_lambda)*c.tx_slot_s;
    maximum_doppler_hz = 2*max(abs([c.velocity_sweep_mps ...
        c.broken_velocity_mps]))/wavelength_local_m;
    assert(maximum_doppler_hz < 1/(2*cycle_spacing_local_s), ...
        'P73:DopplerNyquist', ...
        'Reviewed same-TX Doppler would alias across TDM cycles.');
    assert(c.resolution_dip_db == 0.25 && c.plot_floor_db == -50, ...
        'P73:DisplayControls', 'Reviewed resolution/display controls changed.');
    assert(c.max_virtual_channels == 32 && c.max_tdm_cycles == 128 && ...
        c.max_scan_samples == 2001 && c.max_sweep_cases == 7 && ...
        c.max_private_values == 20000 && ...
        c.max_working_values == 500000 && c.max_figures == 5, ...
        'P73:ResourceCeilings', 'Immutable resource ceilings changed.');
    number_virtual_local = numel(c.rx_positions_lambda)* ...
        numel(c.tx_positions_lambda);
    assert(number_virtual_local <= c.max_virtual_channels && ...
        2*number_virtual_local*c.tdm_cycles <= c.max_private_values, ...
        'P73:ResourceBound', ...
        'Reviewed geometry or noise request exceeds a fixed ceiling.');
end
