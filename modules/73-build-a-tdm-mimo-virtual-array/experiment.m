    pair_angles_deg = [-separation_deg/2 separation_deg/2];
    rx_separation_power(case_index, :) = array_response_power( ...
        rx_positions_wavelengths, scan_angles_deg, pair_angles_deg);
    virtual_separation_power(case_index, :) = array_response_power( ...
        virtual_positions_wavelengths, scan_angles_deg, pair_angles_deg);
    [rx_midpoint_dip_db(case_index), rx_pair_resolved(case_index), ...
        rx_pair_peak_angles_deg(case_index, :)] = pair_resolution_metrics( ...
        scan_angles_deg, rx_separation_power(case_index, :), ...
        resolution_dip_threshold_db);
    [virtual_midpoint_dip_db(case_index), ...
        virtual_pair_resolved(case_index), ...
        virtual_pair_peak_angles_deg(case_index, :)] = ...
        pair_resolution_metrics(scan_angles_deg, ...
        virtual_separation_power(case_index, :), ...
        resolution_dip_threshold_db);
end

