%% Sweep 2: change only velocity and expose TDM angle coupling
velocity_case_count = numel(velocity_sweep_mps);
true_doppler_sweep_hz = 2*velocity_sweep_mps/wavelength_m;
estimated_doppler_sweep_hz = zeros(1, velocity_case_count);
inter_tx_phase_sweep_rad = -2*pi*true_doppler_sweep_hz* ...
    tx_slot_spacing_s;
naive_angle_sweep_deg = zeros(1, velocity_case_count);
compensated_angle_sweep_deg = zeros(1, velocity_case_count);
motion_data_by_case = cell(1, velocity_case_count);

for case_index = 1:velocity_case_count
    case_velocity_mps = velocity_sweep_mps(case_index);
    case_data = simulate_tdm_record(baseline_seed+100, ...
        virtual_positions_wavelengths, tx_slot_by_virtual, ...
        target_angle_deg, case_velocity_mps, wavelength_m, ...
        tx_slot_spacing_s, number_tdm_cycles, input_snr_db, ...
        maximum_private_values);
    motion_data_by_case{case_index} = case_data;
    estimated_doppler_sweep_hz(case_index) = estimate_same_tx_doppler( ...
        case_data, 2*tx_slot_spacing_s);
    naive_case_power = scan_power(case_data, ...
        virtual_positions_wavelengths, scan_angles_deg);
    compensated_case_data = compensate_tdm_slots(case_data, ...
        tx_slot_by_virtual, tx_slot_spacing_s, ...
        estimated_doppler_sweep_hz(case_index));
    compensated_case_power = scan_power(compensated_case_data, ...
        virtual_positions_wavelengths, scan_angles_deg);
    naive_angle_sweep_deg(case_index) = peak_angle(scan_angles_deg, ...
        naive_case_power);
    compensated_angle_sweep_deg(case_index) = peak_angle( ...
        scan_angles_deg, compensated_case_power);
end

