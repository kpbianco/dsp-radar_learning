%% Deterministic baseline: map bits, rotate, add noise, and decide
private_stream = RandStream('mt19937ar', 'Seed', random_seed);
bpsk_bits = double(rand(private_stream, 1, symbol_count) >= 0.5);
qpsk_bits = double(rand(private_stream, 2, symbol_count) >= 0.5);
bpsk_noise_unit = randn(private_stream, 1, symbol_count) + ...
    1j*randn(private_stream, 1, symbol_count);
qpsk_noise_unit = randn(private_stream, 1, symbol_count) + ...
    1j*randn(private_stream, 1, symbol_count);

% Explicit symbol maps. QPSK is Gray-like around the unit circle because each
% quadrant boundary changes only the bit carried by that coordinate.
bpsk_symbols = 2*bpsk_bits - 1;
qpsk_i = 2*qpsk_bits(1, :) - 1;
qpsk_q = 2*qpsk_bits(2, :) - 1;
qpsk_symbols = (qpsk_i + 1j*qpsk_q)/sqrt(2);

baseline_ebn0_linear = 10^(baseline_ebn0_db/10);
baseline_rotation = exp(1j*pi*baseline_phase_error_deg/180);
bpsk_noise_sigma = sqrt(1/(2*baseline_ebn0_linear));
qpsk_noise_sigma = sqrt(1/(4*baseline_ebn0_linear));
bpsk_received = bpsk_symbols*baseline_rotation + ...
    bpsk_noise_sigma*bpsk_noise_unit;
qpsk_received = qpsk_symbols*baseline_rotation + ...
    qpsk_noise_sigma*qpsk_noise_unit;

% Hard decisions are the visible decision regions: I=0 for BPSK, and I=0
% plus Q=0 for QPSK.
bpsk_detected_bits = double(real(bpsk_received) >= 0);
qpsk_detected_bits = [double(real(qpsk_received) >= 0); ...
    double(imag(qpsk_received) >= 0)];
bpsk_error_mask = bpsk_detected_bits ~= bpsk_bits;
qpsk_error_mask = qpsk_detected_bits ~= qpsk_bits;
bpsk_bit_errors = sum(bpsk_error_mask);
qpsk_bit_errors = sum(qpsk_error_mask(:));
bpsk_ber = bpsk_bit_errors/symbol_count;
qpsk_ber = qpsk_bit_errors/(2*symbol_count);

ideal_bpsk_points = [-1 1];
ideal_qpsk_points = [-1-1j -1+1j 1-1j 1+1j]/sqrt(2);
bpsk_symbol_energy = mean(abs(bpsk_symbols).^2);
qpsk_symbol_energy = mean(abs(qpsk_symbols).^2);
minimum_qpsk_signed_margin = min([qpsk_i.*real(qpsk_received) ...
    qpsk_q.*imag(qpsk_received)]);

assert(bpsk_symbol_energy == 1 && abs(qpsk_symbol_energy-1) < 1e-12, ...
    'Both ideal constellations must have unit mean symbol energy.');
assert(all(ismember(bpsk_symbols, ideal_bpsk_points)) && ...
    all(ismember(qpsk_symbols, ideal_qpsk_points)), ...
    'The explicit bit maps must emit only the canonical ideal points.');
assert(bpsk_ber >= 0 && bpsk_ber < 0.08 && ...
    qpsk_ber >= 0 && qpsk_ber < 0.08, ...
    'The seeded baseline should retain clear, mostly correct clusters.');

