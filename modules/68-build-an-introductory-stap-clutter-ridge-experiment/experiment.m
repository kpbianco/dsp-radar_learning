%% Local transparent operations
function vector = space_steering(angle_deg, number_elements, spacing)
    element_index = (0:number_elements-1).';
    vector = exp(1j*2*pi*spacing*element_index*sind(angle_deg));
end

function vector = doppler_steering(normalized_doppler, number_pulses)
    pulse_index = (0:number_pulses-1).';
    vector = exp(1j*2*pi*pulse_index*normalized_doppler);
end

function vector = space_time_steering(angle_deg, normalized_doppler, ...
        number_elements, number_pulses, spacing)
    spatial = space_steering(angle_deg, number_elements, spacing);
    slow_time = doppler_steering(normalized_doppler, number_pulses);
    vector = kron(slow_time, spatial);
end

function weight = loaded_mvdr(covariance_matrix, steering_vector, alpha)
    dimension = size(covariance_matrix, 1);
    loading = alpha*real(trace(covariance_matrix))/dimension;
    loaded_covariance = covariance_matrix + loading*eye(dimension);
    solution = loaded_covariance\steering_vector;
    denominator = steering_vector'*solution;
    assert(isfinite(real(denominator)) && isfinite(imag(denominator)) && ...
        abs(denominator) > 1e-12, 'P68:WeightNormalization', ...
        'Loaded constrained solve has an invalid normalization.');
    weight = solution/denominator;
end

function metrics = output_metrics(weight, actual_target_steering, ...
        target_power, interference_covariance)
    target_response = weight'*actual_target_steering;
    target_output_power = target_power*abs(target_response)^2;
    interference_output_power = real(weight'*interference_covariance*weight);
    assert(interference_output_power > 0 && isfinite(interference_output_power), ...
        'P68:OutputPower', 'Interference output power must be positive.');
    metrics = struct( ...
        'target_response_db', 20*log10(max(abs(target_response), realmin)), ...
        'target_output_power_db', 10*log10(max(target_output_power, realmin)), ...
        'interference_output_power_db', 10*log10(interference_output_power), ...
        'scnr_db', 10*log10(target_output_power/interference_output_power));
end

function power_surface = covariance_power_surface(covariance_matrix, ...
        angles_deg, normalized_doppler, number_elements, number_pulses, spacing)
    dimension = number_elements*number_pulses;
    power_surface = zeros(numel(normalized_doppler), numel(angles_deg));
    for doppler_index = 1:numel(normalized_doppler)
        for angle_index = 1:numel(angles_deg)
            steering = space_time_steering(angles_deg(angle_index), ...
                normalized_doppler(doppler_index), number_elements, ...
                number_pulses, spacing);
            power_surface(doppler_index, angle_index) = max(real( ...
                steering'*covariance_matrix*steering)/dimension^2, realmin);
        end
    end
end

function power_surface = weight_power_surface(weight, angles_deg, ...
        normalized_doppler, number_elements, number_pulses, spacing)
    power_surface = zeros(numel(normalized_doppler), numel(angles_deg));
    for doppler_index = 1:numel(normalized_doppler)
        for angle_index = 1:numel(angles_deg)
            steering = space_time_steering(angles_deg(angle_index), ...
                normalized_doppler(doppler_index), number_elements, ...
                number_pulses, spacing);
            power_surface(doppler_index, angle_index) = abs(weight'*steering)^2;
        end
    end
end

function values_db = normalize_power_db(values, floor_db)
    values_db = 10*log10(max(values, realmin));
    values_db = values_db-max(values_db(:));
    values_db = max(values_db, floor_db);
end

function validate_controls(c)
    scalar_names = {'seed', 'elements', 'pulses', 'spacing', 'wavelength_m', ...
        'prf_hz', 'platform_speed_mps', 'clutter_power_db', 'noise_power', ...
        'target_power_db', 'assumed_target_angle', 'actual_target_angle', ...
        'assumed_target_doppler', 'actual_target_doppler', 'training_cells', ...
        'loading_alpha', 'contamination_power_db', 'plot_floor_db', ...
        'max_elements', 'max_pulses', 'max_dimension', 'max_patches', ...
        'max_training', 'max_map_samples', 'max_sweep_cases', ...
        'max_private_values', 'max_working_values', 'max_figures'};
    for index = 1:numel(scalar_names)
        value = c.(scalar_names{index});
        assert(isnumeric(value) && isreal(value) && isscalar(value) && ...
            isfinite(value), 'P68:InvalidScalar', ...
            'Every scalar control must be one finite real numeric value.');
    end
    integer_names = {'seed', 'elements', 'pulses', 'training_cells', ...
        'max_elements', 'max_pulses', 'max_dimension', 'max_patches', ...
        'max_training', 'max_map_samples', 'max_sweep_cases', ...
        'max_private_values', 'max_working_values', 'max_figures'};
    for index = 1:numel(integer_names)
        value = c.(integer_names{index});
        assert(value >= 1 && value == floor(value), 'P68:InvalidInteger', ...
            'Count, seed, and ceiling controls must be positive integers.');
    end
    vector_names = {'clutter_angles', 'support_sweep', ...
        'contamination_sweep', 'map_angles', 'map_doppler'};
    for index = 1:numel(vector_names)
        value = c.(vector_names{index});
        assert(isnumeric(value) && isreal(value) && isvector(value) && ...
            ~isempty(value) && all(isfinite(value)), 'P68:InvalidVector', ...
            'Every grid and sweep must be finite nonempty real values.');
        assert(all(diff(value) > 0), 'P68:UnorderedVector', ...
            'Every grid and sweep must be strictly increasing.');
    end
    dimension = c.elements*c.pulses;
    slope = 2*c.platform_speed_mps/(c.wavelength_m*c.prf_hz);
    assert(c.elements <= c.max_elements && c.pulses <= c.max_pulses && ...
        dimension <= c.max_dimension, 'P68:DimensionBound', ...
        'Space-time dimension exceeds the reviewed ceiling.');
    assert(numel(c.clutter_angles) >= 5 && ...
        numel(c.clutter_angles) <= c.max_patches, 'P68:PatchBound', ...
        'Clutter patch count is outside the reviewed range.');
    assert(c.training_cells <= c.max_training && ...
        numel(c.map_angles)*numel(c.map_doppler) <= c.max_map_samples, ...
        'P68:GridBound', 'Training or response grid exceeds its ceiling.');
    assert(numel(c.support_sweep) >= 3 && ...
        numel(c.support_sweep) <= c.max_sweep_cases && ...
        all(c.support_sweep == floor(c.support_sweep)) && ...
        c.support_sweep(1) >= 2 && c.support_sweep(end) == c.training_cells, ...
        'P68:SupportSweep', ...
        'Support sweep must use integer prefixes ending at the full record.');
    assert(numel(c.contamination_sweep) >= 3 && ...
        numel(c.contamination_sweep) <= c.max_sweep_cases && ...
        c.contamination_sweep(1) == 0 && ...
        c.contamination_sweep(end) <= 0.5, 'P68:ContaminationSweep', ...
        'Contamination sweep must begin clean and remain at or below 50 percent.');
    assert(c.spacing > 0 && c.spacing <= 0.5 && c.wavelength_m > 0 && ...
        c.prf_hz > 0 && c.platform_speed_mps > 0 && slope < 0.5, ...
        'P68:PhysicalControls', 'Geometry must stay inside the unaliased model.');
    assert(c.noise_power > 0 && c.noise_power <= 1e6 && ...
        abs(c.clutter_power_db) <= 80 && abs(c.target_power_db) <= 80 && ...
        c.contamination_power_db >= c.target_power_db && ...
        c.contamination_power_db <= 60 && c.loading_alpha > 0 && ...
        c.loading_alpha <= 1 && c.plot_floor_db >= -200 && ...
        c.plot_floor_db <= -10, 'P68:PowerControls', ...
        'Power, loading, or plot controls are outside reviewed limits.');
    assert(all(abs(c.clutter_angles) < 90) && all(abs(c.map_angles) < 90) && ...
        c.map_angles(1) <= c.clutter_angles(1) && ...
        c.map_angles(end) >= c.clutter_angles(end), 'P68:AngleGrid', ...
        'Angle grids must cover broadside-referenced clutter.');
    assert(c.map_doppler(1) > -0.5 && c.map_doppler(end) < 0.5 && ...
        min(slope*sind(c.clutter_angles)) >= c.map_doppler(1) && ...
        max(slope*sind(c.clutter_angles)) <= c.map_doppler(end), ...
        'P68:DopplerGrid', 'Doppler map must cover the clutter ridge.');
    assert(c.actual_target_angle > c.map_angles(1) && ...
        c.actual_target_angle < c.map_angles(end) && ...
        c.assumed_target_angle > c.map_angles(1) && ...
        c.assumed_target_angle < c.map_angles(end) && ...
        c.actual_target_doppler > c.map_doppler(1) && ...
        c.actual_target_doppler < c.map_doppler(end) && ...
        c.assumed_target_doppler > c.map_doppler(1) && ...
        c.assumed_target_doppler < c.map_doppler(end), ...
        'P68:TargetGrid', 'Assumed and actual targets must be inside the map.');
    assert(abs(c.actual_target_angle-c.assumed_target_angle) <= 2 && ...
        abs(c.actual_target_doppler-c.assumed_target_doppler) <= 0.02 && ...
        abs(c.actual_target_doppler-slope*sind(c.actual_target_angle)) >= 0.05, ...
        'P68:TargetModel', ...
        'Mismatch must be small and the actual target must remain off ridge.');
    assert(c.max_elements == 10 && c.max_pulses == 10 && ...
        c.max_dimension == 100 && c.max_patches == 61 && ...
        c.max_training == 256 && c.max_map_samples == 5000 && ...
        c.max_sweep_cases == 8 && c.max_private_values == 100000 && ...
        c.max_working_values == 1000000 && c.max_figures == 6 && ...
        c.seed <= 2147483642, 'P68:ImmutableCeilings', ...
        'Reviewed resource ceilings or derived seed range changed.');
end

function values = private_uniform(seed, count, maximum_count)
    assert(isnumeric(seed) && isreal(seed) && isscalar(seed) && ...
        isfinite(seed) && seed == floor(seed) && seed >= 1 && ...
        seed < 2147483647, 'P68:PrivateSeed', ...
        'Private seed must be an integer in the Park-Miller range.');
    assert(isnumeric(count) && isreal(count) && isscalar(count) && ...
        isfinite(count) && count == floor(count) && count >= 1 && ...
        count <= maximum_count, 'P68:PrivateCount', ...
        'Private generator count exceeds the reviewed ceiling.');
    state = double(seed); values = zeros(1, count);
    for index = 1:count
        state = mod(16807*state, 2147483647);
        values(index) = state/2147483647;
    end
end

function noise = private_complex_noise(seed, number_rows, number_columns, ...
        maximum_values)
    count = number_rows*number_columns;
    assert(number_rows >= 1 && number_rows == floor(number_rows) && ...
        number_columns >= 1 && number_columns == floor(number_columns) && ...
        2*count <= maximum_values, 'P68:PrivateShape', ...
        'Complex-noise request exceeds the private-value ceiling.');
    values = private_uniform(seed, 2*count, maximum_values);
    first = max(values(1:count), realmin); second = values(count+1:end);
    samples = sqrt(-2*log(first)).*exp(1j*2*pi*second)/sqrt(2);
    noise = reshape(samples, number_rows, number_columns);
end
