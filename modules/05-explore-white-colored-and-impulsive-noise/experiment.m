grid on;
set(gca, 'XTick', 1:noise_type_count, 'XTickLabel', noise_names);
ylabel('Target phasor error (V)');
title('These errors cannot be attributed to type while powers differ');

fprintf('P05 deliberately broken unequal-RMS comparison\n');
for noise_index = 1:noise_type_count
    fprintf('  %-24s raw RMS = %.6f V, tone error = %.6f V\n', ...
        noise_names{noise_index}, raw_rms_v(noise_index), ...
