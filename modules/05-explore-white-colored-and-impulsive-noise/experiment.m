%% P05 - Explore White, Colored, and Impulsive Noise
% Guiding question:
% What does the word noise hide about time behavior and spectrum?
%
% Dependency contract: P04 and base MATLAB only. No toolbox is required.
% Do not wholesale-clear the learner workspace or command window. Preserve
% unrelated figures and the global random stream; a rerun replaces only prior
% P05 figures. As a script, this file still creates or replaces its named
% working variables in the current workspace, including results.
p05_figure_tag = 'P05NoiseLab';
prior_p05_figures = findall(groot, 'Type', 'figure', 'Tag', p05_figure_tag);
if ~isempty(prior_p05_figures)
    close(prior_p05_figures);
end
random_seed = 505;
random_stream = RandStream('mt19937ar', 'Seed', random_seed);

%% Baseline controls - change one of these at a time
fs = 4096;                       % sample rate (samples/s)
duration = 1.0;                 % record duration (s)
tone_amplitude = 0.18;          % target-tone peak amplitude (V)
tone_frequency_hz = 512;        % coherent target-tone frequency (Hz)
tone_phase_rad = pi/9;          % target-tone phase (rad)
noise_rms_target = 0.25;        % RMS of every normalized noise record (V RMS)
colored_alpha = 0.92;           % one-pole memory coefficient (unitless)
impulse_probability = 0.01;     % probability of an outlier at each sample
max_lag_samples = 96;           % largest displayed correlation lag (samples)
histogram_bin_count = 80;       % common histogram resolution (bins)
max_samples = 16384;            % resource ceiling for any record (samples)
max_sweep_cases = 8;            % resource ceiling for an edited sweep
noise_type_count = 4;           % white, colored, narrowband, impulsive

% Fail before record allocation if an edited control is malformed.
assert(isscalar(fs) && isnumeric(fs) && ~islogical(fs) && isreal(fs) && ...
    isfinite(fs) && fs > 0, ...
    'fs must be one finite positive real sample rate.');
assert(isscalar(duration) && isnumeric(duration) && ~islogical(duration) && ...
    isreal(duration) && isfinite(duration) && duration > 0, ...
    'duration must be one finite positive real time in seconds.');
assert(isscalar(tone_amplitude) && isnumeric(tone_amplitude) && ...
    ~islogical(tone_amplitude) && isreal(tone_amplitude) && ...
    isfinite(tone_amplitude) && tone_amplitude > 0, ...
    'tone_amplitude must be one finite positive real voltage.');
assert(isscalar(tone_frequency_hz) && isnumeric(tone_frequency_hz) && ...
    ~islogical(tone_frequency_hz) && isreal(tone_frequency_hz) && ...
    isfinite(tone_frequency_hz) && tone_frequency_hz > 0 && ...
    tone_frequency_hz < fs/2, ...
    'tone_frequency_hz must be finite, positive, and below Nyquist.');
assert(isscalar(tone_phase_rad) && isnumeric(tone_phase_rad) && ...
    ~islogical(tone_phase_rad) && isreal(tone_phase_rad) && ...
    isfinite(tone_phase_rad), ...
    'tone_phase_rad must be one finite real phase in radians.');
assert(isscalar(noise_rms_target) && isnumeric(noise_rms_target) && ...
    ~islogical(noise_rms_target) && isreal(noise_rms_target) && ...
    isfinite(noise_rms_target) && noise_rms_target > 0, ...
    'noise_rms_target must be one finite positive real voltage.');
assert(isscalar(colored_alpha) && isnumeric(colored_alpha) && ...
    ~islogical(colored_alpha) && isreal(colored_alpha) && ...
    isfinite(colored_alpha) && colored_alpha >= 0 && colored_alpha < 1, ...
    'colored_alpha must be a finite real coefficient in [0,1).');
assert(isscalar(impulse_probability) && isnumeric(impulse_probability) && ...
    ~islogical(impulse_probability) && isreal(impulse_probability) && ...
    isfinite(impulse_probability) && impulse_probability > 0 && ...
    impulse_probability < 0.25, ...
    'impulse_probability must be finite and between 0 and 0.25.');
assert(isscalar(max_lag_samples) && isnumeric(max_lag_samples) && ...
    ~islogical(max_lag_samples) && isreal(max_lag_samples) && ...
    isfinite(max_lag_samples) && max_lag_samples == floor(max_lag_samples) && ...
    max_lag_samples >= 1 && max_lag_samples <= 256, ...
    'max_lag_samples must be an integer from 1 through 256.');
assert(isscalar(histogram_bin_count) && isnumeric(histogram_bin_count) && ...
    ~islogical(histogram_bin_count) && isreal(histogram_bin_count) && ...
    isfinite(histogram_bin_count) && ...
    histogram_bin_count == floor(histogram_bin_count) && ...
    histogram_bin_count >= 16 && histogram_bin_count <= 128, ...
    'histogram_bin_count must be an integer from 16 through 128.');
assert(isscalar(max_samples) && isnumeric(max_samples) && ...
    ~islogical(max_samples) && isreal(max_samples) && isfinite(max_samples) && ...
    max_samples == floor(max_samples) && max_samples == 16384, ...
    'max_samples is a fixed safety ceiling of 16384 samples.');
assert(isscalar(max_sweep_cases) && isnumeric(max_sweep_cases) && ...
    ~islogical(max_sweep_cases) && isreal(max_sweep_cases) && ...
    isfinite(max_sweep_cases) && ...
    max_sweep_cases == floor(max_sweep_cases) && max_sweep_cases == 8, ...
    'max_sweep_cases is a fixed safety ceiling of eight cases.');
assert(isscalar(noise_type_count) && isnumeric(noise_type_count) && ...
    ~islogical(noise_type_count) && isreal(noise_type_count) && ...
    isfinite(noise_type_count) && noise_type_count == 4, ...
    'noise_type_count is fixed at the four canonical baseline types.');

sample_count = round(duration*fs);
assert(sample_count >= 256 && ...
    abs(sample_count-duration*fs) < 10*eps(max(1, duration*fs)), ...
    'duration*fs must be an integer record of at least 256 samples.');
assert(sample_count <= max_samples, ...
    'A record is limited to 16384 samples; reduce fs or duration.');
assert(mod(sample_count, 2) == 0, ...
    'Use an even sample count so the one-sided PSD includes Nyquist.');
assert(max_lag_samples < sample_count, ...
    'max_lag_samples must be smaller than the record.');
assert(abs(tone_frequency_hz*duration-round(tone_frequency_hz*duration)) < ...
    10*eps(max(1, tone_frequency_hz*duration)), ...
    'Choose a coherent tone with an integer number of cycles.');

n = 0:sample_count-1;
t = n/fs;
tone = tone_amplitude*cos(2*pi*tone_frequency_hz*t + tone_phase_rad);
noise_names = {'Gaussian white', 'Low-pass colored', ...
    'Co-channel narrowband', 'Impulsive outliers'};

%% Generate four raw processes with explicit operations
% White noise has independent Gaussian samples. The colored process is the
% one-pole recursion y[n] = alpha*y[n-1] + (1-alpha)*w[n]. The narrowband
% process is a sinusoid exactly at the target frequency, representing an
% interferer that a frequency-only detector cannot separate. The impulsive
% process is usually zero but contains sparse, signed, heavy outliers.
white_raw = randn(random_stream, 1, sample_count);
colored_driver = randn(random_stream, 1, sample_count);
colored_raw = zeros(1, sample_count);
colored_raw(1) = (1-colored_alpha)*colored_driver(1);
for sample_index = 2:sample_count
    colored_raw(sample_index) = colored_alpha*colored_raw(sample_index-1) + ...
        (1-colored_alpha)*colored_driver(sample_index);
end
narrowband_phase_rad = 2*pi*rand(random_stream, 1);
narrowband_raw = cos(2*pi*tone_frequency_hz*t + narrowband_phase_rad);
impulse_selector = rand(random_stream, 1, sample_count);
impulse_polarity = 2*(rand(random_stream, 1, sample_count) >= 0.5)-1;
impulse_size = 1 + abs(randn(random_stream, 1, sample_count));
impulse_mask = impulse_selector < impulse_probability;
impulse_mask(64) = true;         % guarantee one outlier in the short-time view
impulsive_raw = impulse_mask.*impulse_polarity.*impulse_size;
impulse_count = sum(impulse_mask);
assert(impulse_count >= 8, ...
    'The seeded impulsive record must contain at least eight outliers.');

raw_noise = [white_raw; colored_raw; narrowband_raw; impulsive_raw];
noise = zeros(noise_type_count, sample_count);
raw_rms_v = zeros(1, noise_type_count);
noise_mean_v = zeros(1, noise_type_count);
noise_rms_v = zeros(1, noise_type_count);
crest_factor = zeros(1, noise_type_count);

% Equal-RMS normalization is x_equal = target_rms*(x-mean(x))/rms(x-mean(x)).
% This removes total power as a confound while preserving each shape.
for noise_index = 1:noise_type_count
    raw_centered = raw_noise(noise_index,:) - mean(raw_noise(noise_index,:));
    raw_rms_v(noise_index) = sqrt(mean(raw_centered.^2));
    assert(raw_rms_v(noise_index) > 100*eps(noise_rms_target), ...
        'Every raw process must have nonzero finite RMS before normalization.');
    noise(noise_index,:) = ...
        noise_rms_target*raw_centered/raw_rms_v(noise_index);
    noise_mean_v(noise_index) = mean(noise(noise_index,:));
    noise_rms_v(noise_index) = sqrt(mean(noise(noise_index,:).^2));
    crest_factor(noise_index) = ...
        max(abs(noise(noise_index,:)))/noise_rms_v(noise_index);
end
normalization_tolerance_v = 1e-12*noise_rms_target;
assert(all(abs(noise_rms_v-noise_rms_target) < normalization_tolerance_v), ...
    'All four baseline records must have the same RMS after normalization.');
assert(crest_factor(4) > 5, ...
    'The impulsive record must retain visible high-crest-factor outliers.');

%% Short time records and common-scale histograms
view_sample_count = min(160, sample_count);
view = 1:view_sample_count;
figure('Name', 'P05 baseline 1: equal RMS does not mean equal time behavior', ...
    'Tag', p05_figure_tag);
for noise_index = 1:noise_type_count
    subplot(noise_type_count,1,noise_index);
    plot(t(view), noise(noise_index,view), 'LineWidth', 1.0);
    grid on;
    xlabel('Time (s)');
    ylabel('Noise (V)');
    title(sprintf('%s: RMS %.3f V, crest factor %.2f', ...
        noise_names{noise_index}, noise_rms_v(noise_index), ...
        crest_factor(noise_index)));
end

% A histogram estimates probability by counting samples inside each voltage
% bin. Common edges make central shape and long tails directly comparable.
histogram_limit_v = 12*noise_rms_target;
histogram_edges_v = linspace(-histogram_limit_v, histogram_limit_v, ...
    histogram_bin_count+1);
histogram_overflow_count = zeros(1, noise_type_count);
figure('Name', 'P05 baseline 2: distributions share RMS but not shape', ...
    'Tag', p05_figure_tag);
for noise_index = 1:noise_type_count
    histogram_overflow_count(noise_index) = ...
        sum(abs(noise(noise_index,:)) > histogram_limit_v);
    subplot(2,2,noise_index);
    histogram(noise(noise_index,:), histogram_edges_v, ...
        'Normalization', 'probability');
    grid on;
    xlabel('Noise amplitude (V)');
    ylabel('Sample probability');
    title(sprintf('%s; outside view: %d', noise_names{noise_index}, ...
        histogram_overflow_count(noise_index)));
end

%% Autocorrelation - measure memory directly
% For lag ell, r[ell] = mean_n x[n]*x[n+ell]. Divide by r[0] so every
% equal-RMS record begins at one and correlation shape remains visible.
lags = 0:max_lag_samples;
autocorrelation = zeros(noise_type_count, numel(lags));
for noise_index = 1:noise_type_count
    for lag_index = 1:numel(lags)
        lag = lags(lag_index);
        autocorrelation(noise_index,lag_index) = ...
            mean(noise(noise_index,1:sample_count-lag).* ...
            noise(noise_index,1+lag:sample_count));
    end
    autocorrelation(noise_index,:) = ...
        autocorrelation(noise_index,:)/autocorrelation(noise_index,1);
end
lag_one_correlation = autocorrelation(:,2).';
assert(lag_one_correlation(2) > lag_one_correlation(1) + 0.5, ...
    'The low-pass process must have much more one-sample memory than white noise.');

figure('Name', 'P05 baseline 3: autocorrelation exposes memory', ...
    'Tag', p05_figure_tag);
for noise_index = 1:noise_type_count
    subplot(2,2,noise_index);
    stem(lags, autocorrelation(noise_index,:), 'filled');
    grid on;
    xlabel('Lag (samples)');
    ylabel('Normalized autocorrelation');
    title(sprintf('%s; r[1]/r[0] = %.3f', ...
        noise_names{noise_index}, lag_one_correlation(noise_index)));
end

%% One-sided PSD - measure where the same power lives
% The DFT is X[k] = sum_n x[n]*exp(-j*2*pi*k*n/N). Base MATLAB fft
% evaluates that sum. The raw rectangular-window periodogram is
% Sxx[k] = |X[k]|^2/(fs*N), with non-DC/non-Nyquist bins doubled for a
% one-sided PSD in V^2/Hz. No Welch averaging is used in this module.
one_sided_bins = 0:sample_count/2;
frequency_hz = one_sided_bins*fs/sample_count;
noise_fft = fft(noise, [], 2);
noise_psd_v2_per_hz = ...
    abs(noise_fft(:,1:sample_count/2+1)).^2/(fs*sample_count);
noise_psd_v2_per_hz(:,2:end-1) = ...
    2*noise_psd_v2_per_hz(:,2:end-1);
psd_floor_v2_per_hz = 1e-15;
noise_psd_db_v2_per_hz = ...
    10*log10(max(noise_psd_v2_per_hz, psd_floor_v2_per_hz));
low_frequency_band_hz = 200;
low_frequency_bins = frequency_hz <= low_frequency_band_hz;
low_frequency_power_fraction = ...
    sum(noise_psd_v2_per_hz(:,low_frequency_bins),2).' ./ ...
    sum(noise_psd_v2_per_hz,2).';
assert(low_frequency_power_fraction(2) > ...
    2*low_frequency_power_fraction(1), ...
    'The colored process must concentrate more power below 200 Hz than white noise.');

figure('Name', 'P05 baseline 4: equal power occupies different frequencies', ...
    'Tag', p05_figure_tag);
for noise_index = 1:noise_type_count
    subplot(2,2,noise_index);
    plot(frequency_hz, noise_psd_db_v2_per_hz(noise_index,:), ...
        'LineWidth', 1.0);
    grid on;
    xlabel('Frequency (Hz)');
    ylabel('PSD (dB V^2/Hz)');
    title(sprintf('%s; power below %d Hz = %.1f%%', ...
        noise_names{noise_index}, low_frequency_band_hz, ...
        100*low_frequency_power_fraction(noise_index)));
end

%% Add every equal-RMS record to the same tone
received = noise + repmat(tone, noise_type_count, 1);
tone_reference_phasor = tone_amplitude*exp(1j*tone_phase_rad);
tone_oscillator = exp(-1j*2*pi*tone_frequency_hz*t);
estimated_tone_phasor = zeros(1, noise_type_count);
tone_phasor_error_v = zeros(1, noise_type_count);
estimated_tone_amplitude_v = zeros(1, noise_type_count);
estimated_tone_phase_rad = zeros(1, noise_type_count);
for noise_index = 1:noise_type_count
    % Coherent projection: c_hat = (2/N)*sum_n y[n]*exp(-j*2*pi*f0*n/fs).
    estimated_tone_phasor(noise_index) = ...
        (2/sample_count)*sum(received(noise_index,:).*tone_oscillator);
    tone_phasor_error_v(noise_index) = ...
        abs(estimated_tone_phasor(noise_index)-tone_reference_phasor);
    estimated_tone_amplitude_v(noise_index) = ...
        abs(estimated_tone_phasor(noise_index));
    estimated_tone_phase_rad(noise_index) = ...
        angle(estimated_tone_phasor(noise_index));
end
time_domain_snr_db = ...
    20*log10(sqrt(mean(tone.^2))/noise_rms_target);
assert(tone_phasor_error_v(3) > 0.9*sqrt(2)*noise_rms_target, ...
    'A co-channel narrowband interferer must strongly bias the tone estimate.');

received_fft = fft(received, [], 2);
received_psd_v2_per_hz = ...
    abs(received_fft(:,1:sample_count/2+1)).^2/(fs*sample_count);
received_psd_v2_per_hz(:,2:end-1) = ...
    2*received_psd_v2_per_hz(:,2:end-1);
received_psd_db_v2_per_hz = ...
    10*log10(max(received_psd_v2_per_hz, psd_floor_v2_per_hz));

figure('Name', 'P05 baseline 5: the same tone is not equally trustworthy', ...
    'Tag', p05_figure_tag);
for noise_index = 1:noise_type_count
    subplot(2,2,noise_index);
    plot(frequency_hz, received_psd_db_v2_per_hz(noise_index,:), ...
        'LineWidth', 1.0);
    hold on;
    tone_bin_index = round(tone_frequency_hz*sample_count/fs)+1;
    plot(tone_frequency_hz, ...
        received_psd_db_v2_per_hz(noise_index,tone_bin_index), ...
        'ro', 'MarkerSize', 6);
    grid on;
    xlabel('Frequency (Hz)');
    ylabel('PSD (dB V^2/Hz)');
    title(sprintf('%s; tone phasor error %.4f V', ...
        noise_names{noise_index}, tone_phasor_error_v(noise_index)));
end

fprintf('P05 equal-RMS baseline metrics\n');
fprintf('  random seed                     = %d\n', random_seed);
fprintf('  sample rate / record            = %.1f samples/s / %.3f s\n', ...
    fs, duration);
fprintf('  target tone                     = %.3f V peak at %.1f Hz\n', ...
    tone_amplitude, tone_frequency_hz);
fprintf('  common noise RMS                = %.6f V RMS\n', noise_rms_target);
fprintf('  common time-domain tone SNR     = %.3f dB\n', time_domain_snr_db);
for noise_index = 1:noise_type_count
    fprintf(['  %-24s mean = %+.3e V, RMS = %.6f V, crest = %.2f, ' ...
        'r1/r0 = %+.3f, below %d Hz = %.1f%%, tone error = %.6f V\n'], ...
        noise_names{noise_index}, noise_mean_v(noise_index), ...
        noise_rms_v(noise_index), crest_factor(noise_index), ...
        lag_one_correlation(noise_index), low_frequency_band_hz, ...
        100*low_frequency_power_fraction(noise_index), ...
        tone_phasor_error_v(noise_index));
end
fprintf('  impulsive outliers              = %d samples\n', impulse_count);

%% Parameter sweep 1 - change only colored-noise memory
colored_alphas = [0 0.70 0.95];
assert(isvector(colored_alphas) && isnumeric(colored_alphas) && ...
    ~islogical(colored_alphas) && isreal(colored_alphas) && ...
    all(isfinite(colored_alphas)) && all(colored_alphas >= 0) && ...
    all(colored_alphas < 1), ...
    'colored_alphas must contain finite real coefficients in [0,1).');
assert(numel(colored_alphas) >= 2 && ...
    numel(colored_alphas) <= max_sweep_cases, ...
    'The colored-memory sweep requires from two through eight cases.');
assert(isequal(colored_alphas, [0 0.70 0.95]), ...
    'Keep the canonical colored-memory comparison at 0, 0.70, and 0.95.');

colored_sweep_lag_one = zeros(size(colored_alphas));
colored_sweep_low_power_fraction = zeros(size(colored_alphas));
colored_sweep_psd = zeros(numel(colored_alphas), numel(frequency_hz));
for alpha_index = 1:numel(colored_alphas)
    alpha_case = colored_alphas(alpha_index);
    colored_case = zeros(1, sample_count);
    colored_case(1) = (1-alpha_case)*colored_driver(1);
    for sample_index = 2:sample_count
        colored_case(sample_index) = ...
            alpha_case*colored_case(sample_index-1) + ...
            (1-alpha_case)*colored_driver(sample_index);
    end
    colored_case = colored_case-mean(colored_case);
    colored_case_rms = sqrt(mean(colored_case.^2));
    colored_case = noise_rms_target*colored_case/colored_case_rms;
    colored_sweep_lag_one(alpha_index) = ...
        mean(colored_case(1:end-1).*colored_case(2:end)) / ...
        mean(colored_case.^2);
    colored_case_fft = fft(colored_case);
    colored_case_psd = ...
        abs(colored_case_fft(1:sample_count/2+1)).^2/(fs*sample_count);
    colored_case_psd(2:end-1) = 2*colored_case_psd(2:end-1);
    colored_sweep_psd(alpha_index,:) = colored_case_psd;
    colored_sweep_low_power_fraction(alpha_index) = ...
        sum(colored_case_psd(low_frequency_bins))/sum(colored_case_psd);
    fprintf(['P05 memory sweep: alpha = %.2f, r1/r0 = %.3f, ' ...
        'power below %d Hz = %.1f%%, RMS = %.6f V\n'], ...
        alpha_case, colored_sweep_lag_one(alpha_index), ...
        low_frequency_band_hz, ...
        100*colored_sweep_low_power_fraction(alpha_index), ...
        sqrt(mean(colored_case.^2)));
end
assert(all(diff(colored_sweep_lag_one) > 0.15), ...
    'Increasing alpha must visibly increase one-sample correlation.');
assert(all(diff(colored_sweep_low_power_fraction) > 0), ...
    'Increasing alpha must move more of this seeded record below 200 Hz.');

figure('Name', 'P05 sweep 1: one coefficient moves power and memory', ...
    'Tag', p05_figure_tag);
subplot(2,1,1);
for alpha_index = 1:numel(colored_alphas)
    plot(frequency_hz, ...
        10*log10(max(colored_sweep_psd(alpha_index,:), ...
        psd_floor_v2_per_hz)), 'LineWidth', 1.0, ...
        'DisplayName', sprintf('alpha = %.2f', colored_alphas(alpha_index)));
    hold on;
end
grid on;
xlabel('Frequency (Hz)');
ylabel('PSD (dB V^2/Hz)');
title('All cases keep the same RMS; larger alpha concentrates low-frequency power');
legend('Location', 'best');
subplot(2,1,2);
plot(colored_alphas, colored_sweep_lag_one, 'o-', 'LineWidth', 1.2, ...
    'DisplayName', 'lag-one correlation');
hold on;
plot(colored_alphas, colored_sweep_low_power_fraction, 's-', ...
    'LineWidth', 1.2, 'DisplayName', 'fraction below 200 Hz');
grid on;
xlabel('One-pole memory coefficient alpha (unitless)');
ylabel('Correlation or power fraction (unitless)');
title('Memory in time and concentration in frequency are the same mechanism');
legend('Location', 'best');

%% Parameter sweep 2 - change only narrowband offset from the target
interference_offsets_hz = [0 16 128];
assert(isvector(interference_offsets_hz) && ...
    isnumeric(interference_offsets_hz) && ...
    ~islogical(interference_offsets_hz) && isreal(interference_offsets_hz) && ...
    all(isfinite(interference_offsets_hz)) && ...
    all(interference_offsets_hz >= 0), ...
    'interference_offsets_hz must contain finite nonnegative offsets.');
assert(numel(interference_offsets_hz) >= 2 && ...
    numel(interference_offsets_hz) <= max_sweep_cases, ...
    'The narrowband sweep requires from two through eight cases.');
assert(isequal(interference_offsets_hz, [0 16 128]), ...
    'Keep the canonical narrowband offsets at 0, 16, and 128 Hz.');
assert(all(tone_frequency_hz+interference_offsets_hz < fs/2), ...
    'Every swept interferer must remain below Nyquist.');
assert(all(abs(interference_offsets_hz*duration - ...
    round(interference_offsets_hz*duration)) < ...
    10*eps(max(1, max(interference_offsets_hz*duration)))), ...
    'Use coherent integer-bin offsets for an unambiguous comparison.');

offset_tone_error_v = zeros(size(interference_offsets_hz));
offset_received_psd = zeros(numel(interference_offsets_hz), numel(frequency_hz));
for offset_index = 1:numel(interference_offsets_hz)
    offset_hz = interference_offsets_hz(offset_index);
    interference_case = cos(2*pi*(tone_frequency_hz+offset_hz)*t + ...
        narrowband_phase_rad);
    interference_case = interference_case-mean(interference_case);
    interference_case = noise_rms_target*interference_case / ...
        sqrt(mean(interference_case.^2));
    received_case = tone+interference_case;
    estimated_case = ...
        (2/sample_count)*sum(received_case.*tone_oscillator);
    offset_tone_error_v(offset_index) = ...
        abs(estimated_case-tone_reference_phasor);
    offset_fft = fft(received_case);
    offset_psd = ...
        abs(offset_fft(1:sample_count/2+1)).^2/(fs*sample_count);
    offset_psd(2:end-1) = 2*offset_psd(2:end-1);
    offset_received_psd(offset_index,:) = offset_psd;
    fprintf(['P05 offset sweep: interferer offset = %.1f Hz, ' ...
        'tone phasor error = %.9f V\n'], ...
        offset_hz, offset_tone_error_v(offset_index));
end
assert(offset_tone_error_v(1) > 0.9*sqrt(2)*noise_rms_target, ...
    'The zero-offset interferer must bias the target-tone estimate.');
assert(all(offset_tone_error_v(2:end) < 1e-10), ...
    'Coherent nonzero-bin interferers must be orthogonal to the target tone.');

figure('Name', 'P05 sweep 2: spectral location changes tone ambiguity', ...
    'Tag', p05_figure_tag);
subplot(2,1,1);
zoom_bins = frequency_hz >= tone_frequency_hz-32 & ...
    frequency_hz <= tone_frequency_hz+160;
for offset_index = 1:numel(interference_offsets_hz)
    plot(frequency_hz(zoom_bins), ...
        10*log10(max(offset_received_psd(offset_index,zoom_bins), ...
        psd_floor_v2_per_hz)), 'LineWidth', 1.1, ...
        'DisplayName', sprintf('offset = %.0f Hz', ...
        interference_offsets_hz(offset_index)));
    hold on;
end
grid on;
xlabel('Frequency (Hz)');
ylabel('PSD (dB V^2/Hz)');
title('The target and a co-channel interferer occupy the same frequency bin');
legend('Location', 'best');
subplot(2,1,2);
semilogy(interference_offsets_hz, ...
    max(offset_tone_error_v, 1e-15), 'o-', 'LineWidth', 1.2);
grid on;
xlabel('Interferer offset from target (Hz)');
ylabel('Target phasor error (V)');
title('Moving a coherent interferer off the target bin removes its projection');

%% Deliberately broken case - compare raw generators without equal RMS
% This is an invalid type comparison: the generators have different natural
% scales, so any apparent winner mixes noise type with total noise power.
raw_received = raw_noise + repmat(tone, noise_type_count, 1);
raw_tone_error_v = zeros(1, noise_type_count);
for noise_index = 1:noise_type_count
    raw_estimated_phasor = ...
        (2/sample_count)*sum(raw_received(noise_index,:).*tone_oscillator);
    raw_tone_error_v(noise_index) = ...
        abs(raw_estimated_phasor-tone_reference_phasor);
end
raw_rms_ratio = max(raw_rms_v)/min(raw_rms_v);
assert(raw_rms_ratio > 3, ...
    'The broken case must visibly confound noise type with unequal RMS.');

figure('Name', 'P05 broken case: generator scale is not a fair comparison', ...
    'Tag', p05_figure_tag);
subplot(2,1,1);
bar(raw_rms_v);
grid on;
set(gca, 'XTick', 1:noise_type_count, 'XTickLabel', noise_names);
