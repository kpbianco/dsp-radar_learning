results = struct();

%% Baseline: explicit monostatic radar range equation
% Pt leaves the transmitter, spreads as 1/(4*pi*R^2), illuminates radar
% cross section sigma, and the echo spreads over another 4*pi*R^2 before
% the receiving aperture collects it. With gains and wavelength explicit:
% Pr = Pt*Gt*Gr*lambda^2*sigma / ((4*pi)^3*R^4*L).
transmit_gain_linear = 10^(transmit_gain_dbi/10);
receive_gain_linear = 10^(receive_gain_dbi/10);
system_loss_linear = 10^(system_loss_db/10);
noise_factor_linear = 10^(noise_figure_db/10);
wavelength_m = speed_of_light_mps/carrier_frequency_hz;
range_m = range_km*1e3;
radar_equation_numerator = transmit_power_w*transmit_gain_linear* ...
    receive_gain_linear*wavelength_m^2*target_rcs_m2;
received_power_w = radar_equation_numerator ./ ...
    ((4*pi)^3*range_m.^4*system_loss_linear);
received_power_dbw = 10*log10(received_power_w);
received_power_dbm = received_power_dbw + 30;
assert(all(isfinite(received_power_w)) && all(received_power_w > 0) && ...
    all(diff(received_power_w) < 0), ...
    'The baseline received-power curve must be finite, positive, and decreasing.');

%% Receiver noise floor and detection margin
% Available thermal-noise power is N = k*T0*B*F, where T0 is the input
% reference/source temperature and F is receiver noise factor referred to it.
% The illustrative detector requires echo power to exceed N by required_snr_db.
noise_power_w = boltzmann_j_per_k*input_reference_temperature_k* ...
    receiver_bandwidth_hz*noise_factor_linear;
noise_power_dbw = 10*log10(noise_power_w);
noise_power_dbm = noise_power_dbw + 30;
detection_threshold_w = noise_power_w*10^(required_snr_db/10);
detection_threshold_dbm = 10*log10(detection_threshold_w) + 30;
detection_margin_db = received_power_dbm-detection_threshold_dbm;
baseline_max_detectable_range_m = (radar_equation_numerator/( ...
    (4*pi)^3*system_loss_linear*detection_threshold_w))^(1/4);
baseline_max_detectable_range_km = baseline_max_detectable_range_m/1e3;
reference_index = find(range_km == reference_range_km, 1, 'first');
reference_received_power_dbm = received_power_dbm(reference_index);
reference_detection_margin_db = detection_margin_db(reference_index);
required_power_multiplier_at_reference = ...
    10^(max(0, -reference_detection_margin_db)/10);

% A private stream makes the finite receiver-noise measurement reproducible
% without changing the caller's global random stream.
private_stream = RandStream('mt19937ar', 'Seed', random_seed);
noise_i_unit = randn(private_stream, 1, noise_sample_count);
noise_q_unit = randn(private_stream, 1, noise_sample_count);
complex_noise_sqrt_w = ...
    sqrt(noise_power_w/2)*(noise_i_unit + 1i*noise_q_unit);
measured_noise_power_w = mean(abs(complex_noise_sqrt_w).^2);
measured_noise_power_dbm = 10*log10(measured_noise_power_w) + 30;
assert(abs(measured_noise_power_w/noise_power_w-1) < 0.1, ...
    'The seeded finite receiver-noise estimate must stay near k*T*B*F.');

%% Sweep 1: target RCS and carrier frequency, one at a time
% RCS changes only sigma. Frequency changes only lambda=c/f while both
% antenna gains remain fixed; fixed physical apertures would be a different
% experiment because their gains change with wavelength.
received_power_rcs_dbm = zeros(numel(rcs_sweep_m2), numel(range_km));
for rcs_index = 1:numel(rcs_sweep_m2)
    sweep_numerator = transmit_power_w*transmit_gain_linear* ...
        receive_gain_linear*wavelength_m^2*rcs_sweep_m2(rcs_index);
    sweep_received_power_w = sweep_numerator ./ ...
        ((4*pi)^3*range_m.^4*system_loss_linear);
    received_power_rcs_dbm(rcs_index, :) = ...
        10*log10(sweep_received_power_w) + 30;
end

received_power_frequency_dbm = ...
    zeros(numel(frequency_sweep_ghz), numel(range_km));
for frequency_index = 1:numel(frequency_sweep_ghz)
    sweep_frequency_hz = frequency_sweep_ghz(frequency_index)*1e9;
    sweep_wavelength_m = speed_of_light_mps/sweep_frequency_hz;
    sweep_numerator = transmit_power_w*transmit_gain_linear* ...
        receive_gain_linear*sweep_wavelength_m^2*target_rcs_m2;
    sweep_received_power_w = sweep_numerator ./ ...
        ((4*pi)^3*range_m.^4*system_loss_linear);
    received_power_frequency_dbm(frequency_index, :) = ...
        10*log10(sweep_received_power_w) + 30;
end
assert(all(diff(received_power_rcs_dbm(:, reference_index)) > 0) && ...
    all(diff(received_power_frequency_dbm(:, reference_index)) < 0), ...
    'At fixed gains, larger RCS raises power and higher frequency lowers it.');

%% Sweep 2: transmit power changes margin, but range grows by a fourth root
transmit_power_margin_db = ...
    zeros(numel(transmit_power_sweep_kw), numel(range_km));
transmit_power_max_range_km = zeros(size(transmit_power_sweep_kw));
for power_index = 1:numel(transmit_power_sweep_kw)
    sweep_transmit_power_w = transmit_power_sweep_kw(power_index)*1e3;
    sweep_numerator = sweep_transmit_power_w*transmit_gain_linear* ...
        receive_gain_linear*wavelength_m^2*target_rcs_m2;
    sweep_received_power_w = sweep_numerator ./ ...
        ((4*pi)^3*range_m.^4*system_loss_linear);
    transmit_power_margin_db(power_index, :) = ...
        10*log10(sweep_received_power_w) + 30-detection_threshold_dbm;
    transmit_power_max_range_km(power_index) = (sweep_numerator/( ...
        (4*pi)^3*system_loss_linear*detection_threshold_w))^(1/4)/1e3;
end
assert(all(diff(transmit_power_max_range_km) > 0) && ...
    abs(transmit_power_max_range_km(3)/transmit_power_max_range_km(2)- ...
    4^(1/4)) < 1e-12, ...
    'A fourfold power increase must grow maximum range by only fourth-root(4).');

%% One-at-a-time budget changes at the reference range
% The first element is the unchanged baseline. Every later case changes one
% named physical input while all other inputs stay fixed.
one_at_a_time_labels = {'Baseline', 'Pt x2', 'Gt +3 dB', ...
    'Gr +3 dB', 'Wavelength x2', 'Loss /2', 'RCS x2'};
case_transmit_power_w = transmit_power_w*[1 2 1 1 1 1 1];
case_transmit_gain_linear = ...
    transmit_gain_linear*[1 1 10^(3/10) 1 1 1 1];
case_receive_gain_linear = ...
    receive_gain_linear*[1 1 1 10^(3/10) 1 1 1];
case_wavelength_m = wavelength_m*[1 1 1 1 2 1 1];
case_system_loss_linear = system_loss_linear*[1 1 1 1 1 0.5 1];
case_target_rcs_m2 = target_rcs_m2*[1 1 1 1 1 1 2];
one_at_a_time_received_power_w = zeros(size(case_transmit_power_w));
for case_index = 1:numel(case_transmit_power_w)
    case_numerator = case_transmit_power_w(case_index)* ...
        case_transmit_gain_linear(case_index)* ...
        case_receive_gain_linear(case_index)* ...
        case_wavelength_m(case_index)^2*case_target_rcs_m2(case_index);
    one_at_a_time_received_power_w(case_index) = case_numerator/( ...
        (4*pi)^3*(reference_range_km*1e3)^4* ...
        case_system_loss_linear(case_index));
end
one_at_a_time_power_ratio = ...
    one_at_a_time_received_power_w/one_at_a_time_received_power_w(1);
one_at_a_time_change_db = 10*log10(one_at_a_time_power_ratio);
one_at_a_time_margin_db = ...
    reference_detection_margin_db + one_at_a_time_change_db;
assert(abs(one_at_a_time_change_db(2)-10*log10(2)) < 1e-12 && ...
    abs(one_at_a_time_change_db(3)-3) < 1e-12 && ...
    abs(one_at_a_time_change_db(5)-10*log10(4)) < 1e-12 && ...
    abs(one_at_a_time_change_db(6)-10*log10(2)) < 1e-12 && ...
    abs(one_at_a_time_change_db(7)-10*log10(2)) < 1e-12, ...
    'One-at-a-time sensitivities must follow the explicit range equation.');

%% Range-doubling cost
power_at_reference_w = radar_equation_numerator/( ...
    (4*pi)^3*(reference_range_km*1e3)^4*system_loss_linear);
power_at_double_range_w = radar_equation_numerator/( ...
    (4*pi)^3*(2*reference_range_km*1e3)^4*system_loss_linear);
range_doubling_power_ratio = power_at_double_range_w/power_at_reference_w;
range_doubling_penalty_db = -10*log10(range_doubling_power_ratio);
required_power_multiplier_for_double_range = 1/range_doubling_power_ratio;
required_single_gain_multiplier_for_double_range = ...
    required_power_multiplier_for_double_range;
required_each_reciprocal_gain_multiplier_for_double_range = ...
    sqrt(required_power_multiplier_for_double_range);
required_combined_antenna_gain_db_for_double_range = ...
    10*log10(required_single_gain_multiplier_for_double_range);
required_each_reciprocal_gain_db_for_double_range = ...
    10*log10(required_each_reciprocal_gain_multiplier_for_double_range);

double_range_recovered_power_w = [ ...
    required_power_multiplier_for_double_range*transmit_power_w* ...
        transmit_gain_linear*receive_gain_linear; ...
    transmit_power_w*required_single_gain_multiplier_for_double_range* ...
        transmit_gain_linear*receive_gain_linear; ...
    transmit_power_w*required_each_reciprocal_gain_multiplier_for_double_range* ...
        transmit_gain_linear*required_each_reciprocal_gain_multiplier_for_double_range* ...
        receive_gain_linear] * wavelength_m^2*target_rcs_m2 ./ ...
    ((4*pi)^3*(2*reference_range_km*1e3)^4*system_loss_linear);
double_range_recovery_power_ratio = ...
    double_range_recovered_power_w/power_at_reference_w;
assert(abs(range_doubling_power_ratio-1/16) < 1e-12 && ...
    abs(range_doubling_penalty_db-10*log10(16)) < 1e-12 && ...
    abs(required_power_multiplier_for_double_range-16) < 1e-12 && ...
    abs(required_single_gain_multiplier_for_double_range-16) < 1e-12 && ...
    abs(required_each_reciprocal_gain_multiplier_for_double_range-4) < 1e-12 && ...
    all(abs(double_range_recovery_power_ratio-1) < 1e-12), ...
    ['Doubling range must cost 16x power or gain product; each reciprocal ' ...
    'antenna gain must rise 4x when they share the recovery.']);

%% Intentionally broken case: replace the two-way R^-4 law with R^-2
% Anchoring both curves at 40 km hides the error there. Away from the anchor,
% the broken model predicts only one spreading trip and a false -20 dB/decade.
broken_received_power_w = received_power_w(reference_index) .* ...
    ((reference_range_km*1e3)^2 ./ range_m.^2);
broken_received_power_dbm = 10*log10(broken_received_power_w) + 30;
broken_model_valid = false;
ten_km_index = find(range_km == 10, 1, 'first');
hundred_km_index = find(range_km == 100, 1, 'first');
correct_decade_change_db = received_power_dbm(hundred_km_index)- ...
    received_power_dbm(ten_km_index);
broken_decade_change_db = broken_received_power_dbm(hundred_km_index)- ...
    broken_received_power_dbm(ten_km_index);
assert(abs(correct_decade_change_db+40) < 1e-10 && ...
    abs(broken_decade_change_db+20) < 1e-10 && ~broken_model_valid, ...
    'The broken case must expose -20 rather than -40 dB per range decade.');

%% Recovery: restore both spreading trips and reproduce the private seed
recovered_received_power_w = ...
    (transmit_power_w*transmit_gain_linear*receive_gain_linear* ...
    wavelength_m^2*target_rcs_m2) ./ ...
    ((4*pi)^3*range_m.^4*system_loss_linear);
recovery_stream = RandStream('mt19937ar', 'Seed', random_seed);
recovery_noise_i_unit = randn(recovery_stream, 1, noise_sample_count);
recovery_noise_q_unit = randn(recovery_stream, 1, noise_sample_count);
recovery_exact_match = isequal(recovered_received_power_w, received_power_w) && ...
    isequal(recovery_noise_i_unit, noise_i_unit) && ...
    isequal(recovery_noise_q_unit, noise_q_unit);
assert(recovery_exact_match, ...
    'Clean recovery must restore R^-4 power and exact private-stream samples.');

