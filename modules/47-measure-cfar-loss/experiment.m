    baseline_training_cell_count)^(-baseline_training_cell_count);
broken_claim_is_valid = false;

broken_pd_monotone = broken_pd_raw;
for snr_index = 2:snr_case_count
    if broken_pd_monotone(snr_index) < broken_pd_monotone(snr_index-1)
        broken_pd_monotone(snr_index) = broken_pd_monotone(snr_index-1);
    end
end
broken_upper = find(broken_pd_monotone >= ...
    target_detection_probability, 1, 'first');
assert(~isempty(broken_upper) && broken_upper > 1);
broken_lower = broken_upper-1;
broken_gap = broken_pd_monotone(broken_upper)-...
    broken_pd_monotone(broken_lower);
assert(broken_gap > 0);
broken_snr_at_target_pd_db = snr_db(broken_lower)+...
    (target_detection_probability-broken_pd_monotone(broken_lower))*...
    (snr_db(broken_upper)-snr_db(broken_lower))/broken_gap;
broken_apparent_cfar_loss_db = ...
    broken_snr_at_target_pd_db-known_snr_at_target_pd_db;

recovered_scale_factor = baseline_training_cell_count*(...
    design_false_alarm_probability^(-1/baseline_training_cell_count)-1);
recovered_cfar_threshold_power = recovered_scale_factor*...
    baseline_noise_estimate_power;
recovered_pd_raw = zeros(1, snr_case_count);
for snr_index = 1:snr_case_count
    recovered_pd_raw(snr_index) = sum(target_present_power(:, snr_index) > ...
        recovered_cfar_threshold_power)/trial_count;
end
recovery_exact = recovered_scale_factor == baseline_cfar_scale_factor && ...
    isequal(recovered_cfar_threshold_power, baseline_cfar_threshold_power) && ...
    isequal(recovered_pd_raw, baseline_pd_raw);
assert(recovery_exact);
assert(~broken_claim_is_valid);
assert(broken_actual_false_alarm_probability > ...
    2*design_false_alarm_probability);
assert(abs(broken_empirical_pfa-broken_actual_false_alarm_probability) <= ...
    probability_tolerance_sigma*sqrt(broken_actual_false_alarm_probability*...
    (1-broken_actual_false_alarm_probability)/trial_count)+2/trial_count);
assert(broken_apparent_cfar_loss_db < baseline_cfar_loss_db);

figure('Name', 'P47 broken calibration and recovery', 'Tag', 'P47');
subplot(2, 1, 1);
plot(snr_db, pd_known_raw, 'k--', 'LineWidth', 1.4);
hold on;
plot(snr_db, broken_pd_raw, 'Color', [0.85 0.55 0.1], ...
    'LineWidth', 1.4);
plot(snr_db, recovered_pd_raw, 'Color', [0.15 0.55 0.25], ...
    'LineWidth', 1.4);
plot([snr_db(1) snr_db(end)], target_detection_probability*[1 1], ...
    'k:', 'LineWidth', 1.0);
grid on;
xlabel('Target SNR (dB power ratio)');
ylabel('Empirical probability of detection P_d');
title('Broken multiplier appears cheaper because it changes P_{FA}');
legend('Known noise', 'Broken CA multiplier', ...
    'Recovered finite-N multiplier', 'Target P_d', 'Location', 'southeast');
ylim([0 1]);
subplot(2, 1, 2);
semilogy(1:3, [design_false_alarm_probability ...
    broken_actual_false_alarm_probability ...
    design_false_alarm_probability], 'o-', 'LineWidth', 1.4);
hold on;
semilogy(2, broken_empirical_pfa, 'rx', 'MarkerSize', 10, ...
    'LineWidth', 1.5);
grid on;
xlim([0.7 3.3]);
set(gca, 'XTick', 1:3, 'XTickLabel', ...
    {'Known', 'Broken CA', 'Recovered CA'});
ylabel('H0 false-alarm probability');
title('Equal-P_{FA} is restored before loss is reported');
legend('Theoretical P_{FA}', 'Broken empirical H0 rate', ...
    'Location', 'best');

