trial_count = 50000;
block_trial_count = 2000;
snr_db = 3:0.5:17;
design_false_alarm_probability = 1e-3;
target_detection_probability = 0.80;
baseline_training_cell_count = 16;
training_cell_count_sweep = [8 16 32 64];
false_alarm_probability_sweep = [1e-2 1e-3 1e-4];
example_snr_db = 10;
display_trial_count = 240;
monotone_adjustment_tolerance = 0.01;
probability_tolerance_sigma = 5;
max_trial_count = 60000;
max_block_trial_count = 5000;
max_snr_case_count = 40;
max_training_cell_count = 64;
max_sweep_case_count = 5;
max_figure_groups = 5;
max_generated_random_real_values = 7000000;
max_stored_numeric_values = 2000000;

%% Reject malformed, ambiguous, or unbounded controls before allocation
scalar_controls = [random_seed trial_count block_trial_count ...
    design_false_alarm_probability target_detection_probability ...
    baseline_training_cell_count example_snr_db display_trial_count ...
    monotone_adjustment_tolerance probability_tolerance_sigma ...
    max_trial_count max_block_trial_count max_snr_case_count ...
    max_training_cell_count max_sweep_case_count max_figure_groups ...
    max_generated_random_real_values max_stored_numeric_values];
assert(all(isfinite(scalar_controls)) && all(isfinite(snr_db)) && ...
    all(isfinite(training_cell_count_sweep)) && ...
    all(isfinite(false_alarm_probability_sweep)));
assert(isreal(scalar_controls) && isreal(snr_db) && ...
    isreal(training_cell_count_sweep) && ...
    isreal(false_alarm_probability_sweep));
assert(~islogical(random_seed) && ~islogical(trial_count) && ...
    ~islogical(block_trial_count) && ~islogical(snr_db) && ...
    ~islogical(design_false_alarm_probability) && ...
    ~islogical(target_detection_probability) && ...
    ~islogical(training_cell_count_sweep) && ...
    ~islogical(false_alarm_probability_sweep));
integer_controls = [random_seed trial_count block_trial_count ...
    baseline_training_cell_count training_cell_count_sweep ...
    display_trial_count max_trial_count max_block_trial_count ...
    max_snr_case_count max_training_cell_count max_sweep_case_count ...
    max_figure_groups max_generated_random_real_values ...
    max_stored_numeric_values];
assert(all(integer_controls == floor(integer_controls)));
assert(random_seed == 4701);
assert(trial_count == 50000 && trial_count <= max_trial_count);
assert(block_trial_count >= 100 && ...
    block_trial_count <= max_block_trial_count && ...
    mod(trial_count, block_trial_count) == 0);
assert(numel(snr_db) >= 5 && numel(snr_db) <= max_snr_case_count && ...
    all(diff(snr_db) > 0) && any(snr_db == example_snr_db));
assert(design_false_alarm_probability > 0 && ...
    design_false_alarm_probability < 0.1);
assert(target_detection_probability > 0 && ...
    target_detection_probability < 1);
assert(numel(training_cell_count_sweep) >= 3 && ...
    numel(training_cell_count_sweep) <= max_sweep_case_count && ...
    all(training_cell_count_sweep >= 4) && ...
    all(training_cell_count_sweep <= max_training_cell_count) && ...
    all(diff(training_cell_count_sweep) > 0) && ...
    any(training_cell_count_sweep == baseline_training_cell_count));
assert(numel(false_alarm_probability_sweep) >= 3 && ...
    numel(false_alarm_probability_sweep) <= max_sweep_case_count && ...
    all(false_alarm_probability_sweep > 0) && ...
    all(false_alarm_probability_sweep < 0.1) && ...
    all(diff(false_alarm_probability_sweep) < 0) && ...
    any(false_alarm_probability_sweep == ...
    design_false_alarm_probability));
assert(display_trial_count >= 50 && display_trial_count <= block_trial_count);
assert(monotone_adjustment_tolerance > 0 && ...
    monotone_adjustment_tolerance <= 0.02);
assert(probability_tolerance_sigma >= 3 && ...
    probability_tolerance_sigma <= 8);
assert(max_trial_count == 60000 && max_block_trial_count == 5000 && ...
    max_snr_case_count == 40 && max_training_cell_count == 64 && ...
    max_sweep_case_count == 5 && max_figure_groups == 5 && ...
    max_generated_random_real_values == 7000000 && ...
    max_stored_numeric_values == 2000000);

snr_case_count = numel(snr_db);
training_case_count = numel(training_cell_count_sweep);
false_alarm_case_count = numel(false_alarm_probability_sweep);
largest_training_cell_count = max(training_cell_count_sweep);
estimated_generated_random_real_values = ...
    2*trial_count*(largest_training_cell_count+2);
estimated_stored_numeric_values = trial_count*(snr_case_count+...
    training_case_count+4)+10000;
assert(estimated_generated_random_real_values <= ...
    max_generated_random_real_values);
assert(estimated_stored_numeric_values <= max_stored_numeric_values);

%% Generate paired CUT trials and independent reference estimates in blocks
private_stream = RandStream('mt19937ar', 'Seed', random_seed);
unit_cut_noise = (randn(private_stream, trial_count, 1)+...
    1i*randn(private_stream, trial_count, 1))/sqrt(2);
target_phase_rad = 2*pi*rand(private_stream, trial_count, 1);
unit_target_phasor = exp(1i*target_phase_rad);
h0_cut_power = abs(unit_cut_noise).^2;

training_noise_estimate_power = zeros(trial_count, training_case_count);
for block_first_trial = 1:block_trial_count:trial_count
    block_last_trial = block_first_trial+block_trial_count-1;
    block_rows = block_first_trial:block_last_trial;
    reference_noise_block = (randn(private_stream, block_trial_count, ...
        largest_training_cell_count)+1i*randn(private_stream, ...
        block_trial_count, largest_training_cell_count))/sqrt(2);
    reference_power_cumulative = cumsum(abs(reference_noise_block).^2, 2);
    for training_index = 1:training_case_count
        training_cell_count = training_cell_count_sweep(training_index);
        training_noise_estimate_power(block_rows, training_index) = ...
            reference_power_cumulative(:, training_cell_count)/...
            training_cell_count;
    end
end
clear reference_noise_block reference_power_cumulative block_rows;

target_present_power = zeros(trial_count, snr_case_count);
for snr_index = 1:snr_case_count
    snr_linear = 10^(snr_db(snr_index)/10);
    target_present_power(:, snr_index) = abs(unit_cut_noise+...
        sqrt(snr_linear)*unit_target_phasor).^2;
end
assert(all(isfinite(h0_cut_power)) && all(h0_cut_power >= 0));
assert(all(isfinite(training_noise_estimate_power(:))) && ...
    all(training_noise_estimate_power(:) >= 0));
assert(all(isfinite(target_present_power(:))) && ...
    all(target_present_power(:) >= 0));

training_sweep_noise_estimate_std = ...
    std(training_noise_estimate_power, 1, 1);
assert(all(diff(training_sweep_noise_estimate_std) < 0));

%% Form equal-Pfa known-noise and finite-N CA-CFAR curves explicitly
known_noise_threshold_power = -log(design_false_alarm_probability);
training_sweep_scale_factor = zeros(1, training_case_count);
training_sweep_pd_raw = zeros(training_case_count, snr_case_count);
training_sweep_empirical_pfa = zeros(1, training_case_count);
training_sweep_theoretical_pfa = zeros(1, training_case_count);

pd_known_raw = zeros(1, snr_case_count);
for snr_index = 1:snr_case_count
    pd_known_raw(snr_index) = sum(target_present_power(:, snr_index) > ...
        known_noise_threshold_power)/trial_count;
end
empirical_known_pfa = sum(h0_cut_power > ...
    known_noise_threshold_power)/trial_count;

for training_index = 1:training_case_count
    training_cell_count = training_cell_count_sweep(training_index);
    cfar_scale_factor = training_cell_count*(...
        design_false_alarm_probability^(-1/training_cell_count)-1);
    training_sweep_scale_factor(training_index) = cfar_scale_factor;
    cfar_threshold_power = cfar_scale_factor*...
        training_noise_estimate_power(:, training_index);
    training_sweep_empirical_pfa(training_index) = ...
        sum(h0_cut_power > cfar_threshold_power)/trial_count;
    training_sweep_theoretical_pfa(training_index) = ...
        (1+cfar_scale_factor/training_cell_count)^(-training_cell_count);
    for snr_index = 1:snr_case_count
        training_sweep_pd_raw(training_index, snr_index) = sum(...
            target_present_power(:, snr_index) > cfar_threshold_power)/...
            trial_count;
    end
end

assert(all(training_sweep_scale_factor > known_noise_threshold_power));
assert(all(diff(training_sweep_scale_factor) < 0));
assert(max(abs(training_sweep_theoretical_pfa-...
    design_false_alarm_probability)) < 1e-12);
pfa_sampling_tolerance = probability_tolerance_sigma*sqrt(...
    design_false_alarm_probability*(1-design_false_alarm_probability)/...
    trial_count)+2/trial_count;
assert(abs(empirical_known_pfa-design_false_alarm_probability) <= ...
    pfa_sampling_tolerance);
assert(all(abs(training_sweep_empirical_pfa-...
    design_false_alarm_probability) <= pfa_sampling_tolerance));

%% Invert raw empirical Pd curves with a disclosed monotone envelope
pd_known_monotone = pd_known_raw;
for snr_index = 2:snr_case_count
    if pd_known_monotone(snr_index) < pd_known_monotone(snr_index-1)
        pd_known_monotone(snr_index) = pd_known_monotone(snr_index-1);
    end
end
known_monotone_adjustment = max(abs(pd_known_monotone-pd_known_raw));
assert(known_monotone_adjustment <= monotone_adjustment_tolerance);
known_upper_index = find(pd_known_monotone >= ...
    target_detection_probability, 1, 'first');
assert(~isempty(known_upper_index) && known_upper_index > 1);
known_lower_index = known_upper_index-1;
known_pd_gap = pd_known_monotone(known_upper_index)-...
    pd_known_monotone(known_lower_index);
assert(known_pd_gap > 0);
known_snr_at_target_pd_db = snr_db(known_lower_index)+...
    (target_detection_probability-pd_known_monotone(known_lower_index))*...
    (snr_db(known_upper_index)-snr_db(known_lower_index))/known_pd_gap;

training_sweep_pd_monotone = training_sweep_pd_raw;
training_sweep_monotone_adjustment = zeros(1, training_case_count);
training_sweep_snr_at_target_pd_db = zeros(1, training_case_count);
for training_index = 1:training_case_count
    for snr_index = 2:snr_case_count
        if training_sweep_pd_monotone(training_index, snr_index) < ...
                training_sweep_pd_monotone(training_index, snr_index-1)
            training_sweep_pd_monotone(training_index, snr_index) = ...
                training_sweep_pd_monotone(training_index, snr_index-1);
        end
    end
    training_sweep_monotone_adjustment(training_index) = max(abs(...
        training_sweep_pd_monotone(training_index, :)-...
        training_sweep_pd_raw(training_index, :)));
    upper_index = find(training_sweep_pd_monotone(training_index, :) >= ...
        target_detection_probability, 1, 'first');
    assert(~isempty(upper_index) && upper_index > 1);
    lower_index = upper_index-1;
    pd_gap = training_sweep_pd_monotone(training_index, upper_index)-...
        training_sweep_pd_monotone(training_index, lower_index);
    assert(pd_gap > 0);
    training_sweep_snr_at_target_pd_db(training_index) = ...
        snr_db(lower_index)+(target_detection_probability-...
        training_sweep_pd_monotone(training_index, lower_index))*...
        (snr_db(upper_index)-snr_db(lower_index))/pd_gap;
end
assert(all(training_sweep_monotone_adjustment <= ...
    monotone_adjustment_tolerance));
training_sweep_cfar_loss_db = training_sweep_snr_at_target_pd_db-...
    known_snr_at_target_pd_db;
assert(all(training_sweep_cfar_loss_db > 0));
assert(all(diff(training_sweep_cfar_loss_db) < 0));

baseline_training_index = find(training_cell_count_sweep == ...
    baseline_training_cell_count, 1);
baseline_cfar_scale_factor = ...
    training_sweep_scale_factor(baseline_training_index);
baseline_noise_estimate_power = ...
    training_noise_estimate_power(:, baseline_training_index);
baseline_cfar_threshold_power = baseline_cfar_scale_factor*...
    baseline_noise_estimate_power;
baseline_pd_raw = training_sweep_pd_raw(baseline_training_index, :);
baseline_cfar_snr_at_target_pd_db = ...
    training_sweep_snr_at_target_pd_db(baseline_training_index);
baseline_cfar_loss_db = ...
    baseline_cfar_snr_at_target_pd_db-known_snr_at_target_pd_db;

