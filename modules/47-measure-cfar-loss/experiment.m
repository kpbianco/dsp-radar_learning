%% Sweep 2: change only requested Pfa at fixed N and Pd
pfa_sweep_known_threshold_power = zeros(1, false_alarm_case_count);
pfa_sweep_cfar_scale_factor = zeros(1, false_alarm_case_count);
pfa_sweep_pd_known_raw = zeros(false_alarm_case_count, snr_case_count);
pfa_sweep_pd_cfar_raw = zeros(false_alarm_case_count, snr_case_count);
pfa_sweep_known_snr_at_target_pd_db = zeros(1, false_alarm_case_count);
pfa_sweep_cfar_snr_at_target_pd_db = zeros(1, false_alarm_case_count);
pfa_sweep_monotone_adjustment = zeros(false_alarm_case_count, 2);

for probability_index = 1:false_alarm_case_count
    requested_pfa = false_alarm_probability_sweep(probability_index);
    pfa_sweep_known_threshold_power(probability_index) = ...
        -log(requested_pfa);
    pfa_sweep_cfar_scale_factor(probability_index) = ...
        baseline_training_cell_count*(...
        requested_pfa^(-1/baseline_training_cell_count)-1);
    pfa_case_cfar_threshold = pfa_sweep_cfar_scale_factor(...
        probability_index)*baseline_noise_estimate_power;
    for snr_index = 1:snr_case_count
        pfa_sweep_pd_known_raw(probability_index, snr_index) = sum(...
            target_present_power(:, snr_index) > ...
            pfa_sweep_known_threshold_power(probability_index))/trial_count;
        pfa_sweep_pd_cfar_raw(probability_index, snr_index) = sum(...
            target_present_power(:, snr_index) > ...
            pfa_case_cfar_threshold)/trial_count;
    end
    known_curve = pfa_sweep_pd_known_raw(probability_index, :);
    cfar_curve = pfa_sweep_pd_cfar_raw(probability_index, :);
    known_curve_monotone = known_curve;
    cfar_curve_monotone = cfar_curve;
    for snr_index = 2:snr_case_count
        if known_curve_monotone(snr_index) < ...
                known_curve_monotone(snr_index-1)
            known_curve_monotone(snr_index) = ...
                known_curve_monotone(snr_index-1);
        end
        if cfar_curve_monotone(snr_index) < ...
                cfar_curve_monotone(snr_index-1)
            cfar_curve_monotone(snr_index) = ...
                cfar_curve_monotone(snr_index-1);
        end
    end
    pfa_sweep_monotone_adjustment(probability_index, :) = ...
        [max(abs(known_curve_monotone-known_curve)) ...
        max(abs(cfar_curve_monotone-cfar_curve))];

    known_upper = find(known_curve_monotone >= ...
        target_detection_probability, 1, 'first');
    cfar_upper = find(cfar_curve_monotone >= ...
        target_detection_probability, 1, 'first');
    assert(~isempty(known_upper) && known_upper > 1 && ...
        ~isempty(cfar_upper) && cfar_upper > 1);
    known_lower = known_upper-1;
    cfar_lower = cfar_upper-1;
    known_gap = known_curve_monotone(known_upper)-...
        known_curve_monotone(known_lower);
    cfar_gap = cfar_curve_monotone(cfar_upper)-...
        cfar_curve_monotone(cfar_lower);
    assert(known_gap > 0 && cfar_gap > 0);
    pfa_sweep_known_snr_at_target_pd_db(probability_index) = ...
        snr_db(known_lower)+(target_detection_probability-...
        known_curve_monotone(known_lower))*(snr_db(known_upper)-...
        snr_db(known_lower))/known_gap;
    pfa_sweep_cfar_snr_at_target_pd_db(probability_index) = ...
        snr_db(cfar_lower)+(target_detection_probability-...
        cfar_curve_monotone(cfar_lower))*(snr_db(cfar_upper)-...
        snr_db(cfar_lower))/cfar_gap;
end

pfa_sweep_cfar_loss_db = pfa_sweep_cfar_snr_at_target_pd_db-...
    pfa_sweep_known_snr_at_target_pd_db;
assert(all(pfa_sweep_monotone_adjustment(:) <= ...
