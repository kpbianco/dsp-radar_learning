%% Local validation helpers: explicit, bounded, and global-RNG independent
function validate_controls(c)
    scalar_names = {'baseline_seed', 'speed_of_light_mps', ...
        'carrier_frequency_hz', 'number_elements', 'arrival_angle_deg', ...
        'initial_phase_deg', 'signal_to_noise_ratio_db', ...
        'element_spacing_m', 'broken_spacing_wavelengths', ...
        'broken_true_angle_deg', 'broken_alias_angle_deg', ...
        'maximum_elements', ...
        'maximum_sweep_cases', 'maximum_random_values', ...
        'maximum_stored_numeric_values', 'maximum_figures', ...
        'comparison_tolerance'};
    for name_index = 1:numel(scalar_names)
        value = c.(scalar_names{name_index});
        assert(isnumeric(value) && isreal(value) && isscalar(value) && ...
            isfinite(value), 'P61:MalformedScalarControl');
    end
    integer_values = [c.baseline_seed c.number_elements ...
        c.maximum_elements c.maximum_sweep_cases c.maximum_random_values ...
        c.maximum_stored_numeric_values c.maximum_figures];
    assert(all(integer_values == floor(integer_values)), ...
        'P61:NonintegerControl');
    assert(c.baseline_seed == 6101 && c.baseline_seed > 0 && ...
        c.baseline_seed < 2147483647, 'P61:SeedContract');
    assert(c.speed_of_light_mps > 0 && c.carrier_frequency_hz > 0 && ...
        c.element_spacing_m > 0 && c.comparison_tolerance > 0, ...
        'P61:NonpositivePhysicalControl');
    assert(c.number_elements >= 2 && ...
        c.number_elements <= c.maximum_elements && ...
        c.maximum_elements == 32, 'P61:ElementBound');
    assert(abs(c.arrival_angle_deg) < 90 && ...
        abs(c.broken_true_angle_deg) < 90 && ...
        abs(c.broken_alias_angle_deg) < 90, 'P61:AngleDomain');
    assert(c.broken_spacing_wavelengths == 1.0 && ...
        abs(sind(c.broken_true_angle_deg)-0.6) < ...
            c.comparison_tolerance && ...
        abs(sind(c.broken_alias_angle_deg)+0.4) < ...
            c.comparison_tolerance && ...
        abs(sind(c.broken_true_angle_deg)-...
            sind(c.broken_alias_angle_deg)-1.0) < ...
            c.comparison_tolerance, 'P61:BrokenAliasFixture');
    assert(c.maximum_sweep_cases == 7 && c.maximum_random_values == 64 && ...
        c.maximum_stored_numeric_values == 5000 && ...
        c.maximum_figures == 5, 'P61:ImmutableResourceCeiling');

    validate_sweep(c.arrival_angle_sweep_deg, c.maximum_sweep_cases, ...
        -90, 90, c.arrival_angle_deg);
    validate_sweep(c.spacing_sweep_wavelengths, c.maximum_sweep_cases, ...
        0, 0.5+eps, 0.5);
    validate_sweep(c.frequency_sweep_hz, c.maximum_sweep_cases, ...
        0, c.carrier_frequency_hz+eps(c.carrier_frequency_hz), ...
        c.carrier_frequency_hz);

    requested_random_values = 2*c.number_elements;
    requested_numeric_values = 20*c.number_elements + ...
        12*(numel(c.arrival_angle_sweep_deg) + ...
        numel(c.spacing_sweep_wavelengths) + numel(c.frequency_sweep_hz));
    assert(requested_random_values <= c.maximum_random_values, ...
        'P61:RandomResourceBound');
    assert(requested_numeric_values <= c.maximum_stored_numeric_values, ...
        'P61:NumericResourceBound');
end

function validate_sweep(values, maximum_cases, lower_bound, upper_bound, baseline)
    assert(isnumeric(values) && isreal(values) && isvector(values) && ...
        isrow(values) && ...
        ~isempty(values) && all(isfinite(values)) && ...
        numel(values) <= maximum_cases, 'P61:MalformedSweep');
    assert(all(diff(values) > 0) && all(values > lower_bound) && ...
        all(values < upper_bound), 'P61:SweepDomainOrOrder');
    assert(sum(values == baseline) == 1, 'P61:SweepBaseline');
end

function values = private_standard_normal(seed, count, maximum_count)
    modulus = 2147483647;
    multiplier = 16807;
    assert(isnumeric(seed) && isreal(seed) && isscalar(seed) && ...
        isfinite(seed) && seed == floor(seed) && ...
        seed >= 1 && seed < modulus, 'P61:InvalidPrivateSeed');
    assert(isnumeric(count) && isreal(count) && isscalar(count) && ...
        isfinite(count) && count == floor(count) && count >= 1 && ...
        count <= maximum_count, 'P61:PrivateRandomBound');
    state = seed;
    values = zeros(1, 2*ceil(count/2));
    output_index = 1;
    for pair_index = 1:ceil(count/2)
        state = mod(multiplier*state, modulus);
        uniform_1 = (state+0.5)/modulus;
        state = mod(multiplier*state, modulus);
        uniform_2 = (state+0.5)/modulus;
        radius = sqrt(-2*log(uniform_1));
        angle_rad = 2*pi*uniform_2;
        values(output_index) = radius*cos(angle_rad);
        values(output_index+1) = radius*sin(angle_rad);
        output_index = output_index+2;
    end
    values = values(1:count);
end
