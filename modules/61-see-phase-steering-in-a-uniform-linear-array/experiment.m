%% P61 - See Phase Steering in a Uniform Linear Array
% How does a direction of arrival become a phase slope across sensors?
% Convention: elements m=0,...,M-1 lie on +x, angle is measured from
% broadside toward +x, and the analytic carrier is exp(+j*2*pi*f*t).

clearvars;
clc;
close(findall(0, 'Type', 'figure', 'Tag', 'P61'));

%% Visible deterministic controls and immutable resource ceilings
baseline_seed = 6101;
speed_of_light_mps = 299792458;
carrier_frequency_hz = 3.0e9;
number_elements = 8;
arrival_angle_deg = 30.0;
initial_phase_deg = 20.0;
signal_to_noise_ratio_db = 35.0;
wavelength_m = speed_of_light_mps/carrier_frequency_hz;
element_spacing_m = 0.5*wavelength_m;

arrival_angle_sweep_deg = [-60 -30 0 30 60];
spacing_sweep_wavelengths = [0.25 0.375 0.50];
frequency_sweep_hz = [1.5e9 2.25e9 3.0e9];

broken_spacing_wavelengths = 1.0;
broken_true_angle_deg = asind(0.6);
broken_alias_angle_deg = asind(-0.4);

maximum_elements = 32;
maximum_sweep_cases = 7;
maximum_random_values = 64;
maximum_stored_numeric_values = 5000;
maximum_figures = 5;
comparison_tolerance = 1e-10;

controls = struct( ...
    'baseline_seed', baseline_seed, ...
    'speed_of_light_mps', speed_of_light_mps, ...
    'carrier_frequency_hz', carrier_frequency_hz, ...
    'number_elements', number_elements, ...
    'arrival_angle_deg', arrival_angle_deg, ...
    'initial_phase_deg', initial_phase_deg, ...
    'signal_to_noise_ratio_db', signal_to_noise_ratio_db, ...
    'element_spacing_m', element_spacing_m, ...
    'arrival_angle_sweep_deg', arrival_angle_sweep_deg, ...
    'spacing_sweep_wavelengths', spacing_sweep_wavelengths, ...
    'frequency_sweep_hz', frequency_sweep_hz, ...
    'broken_spacing_wavelengths', broken_spacing_wavelengths, ...
    'broken_true_angle_deg', broken_true_angle_deg, ...
    'broken_alias_angle_deg', broken_alias_angle_deg, ...
    'maximum_elements', maximum_elements, ...
    'maximum_sweep_cases', maximum_sweep_cases, ...
    'maximum_random_values', maximum_random_values, ...
    'maximum_stored_numeric_values', maximum_stored_numeric_values, ...
    'maximum_figures', maximum_figures, ...
    'comparison_tolerance', comparison_tolerance);
validate_controls(controls);

%% Baseline geometry: convert path advance into phase advance
element_index = 0:number_elements-1;
element_position_m = element_index*element_spacing_m;
initial_phase_rad = initial_phase_deg*pi/180;

% A source at positive angle is toward the +x end. The wavefront reaches later
% elements earlier, so a fixed snapshot samples a later carrier phase there;
% their relative propagation delay is negative.
geometric_delay_s = -element_position_m*sind(arrival_angle_deg)/...
    speed_of_light_mps;
ideal_phase_rad = initial_phase_rad - ...
    2*pi*carrier_frequency_hz*geometric_delay_s;
theoretical_phase_slope_rad_per_element = ...
    2*pi*(element_spacing_m/wavelength_m)*sind(arrival_angle_deg);
assert(abs(theoretical_phase_slope_rad_per_element-pi/2) < ...
    comparison_tolerance, 'P61:BaselineSlope');

ideal_snapshot = exp(1j*ideal_phase_rad);
noise_rms = 10^(-signal_to_noise_ratio_db/20);
private_noise = private_standard_normal(baseline_seed, ...
    2*number_elements, maximum_random_values);
complex_noise = noise_rms/sqrt(2)*(private_noise(1:number_elements) + ...
    1j*private_noise(number_elements+1:2*number_elements));
received_snapshot = ideal_snapshot + complex_noise;

figure('Name', 'P61 baseline geometry and complex samples', 'Tag', 'P61');
subplot(2, 2, [1 2]);
plot(element_position_m, 1e12*geometric_delay_s, 'o-', 'LineWidth', 1.2);
grid on;
xlabel('Element position x (m)');
ylabel('Relative propagation delay (ps)');
title('Positive bearing advances arrival time toward +x');
subplot(2, 2, 3);
plot(element_index, real(received_snapshot), 'o-', 'LineWidth', 1.1);
hold on;
plot(element_index, imag(received_snapshot), 's-', 'LineWidth', 1.1);
grid on;
xlabel('Element index m');
ylabel('Complex voltage (normalized)');
title('One simultaneous narrowband snapshot');
legend('I', 'Q', 'Location', 'best');
subplot(2, 2, 4);
plot(real(received_snapshot), imag(received_snapshot), 'o-', ...
    'LineWidth', 1.1);
grid on;
axis equal;
xlabel('In-phase I (normalized)');
ylabel('Quadrature Q (normalized)');
title('Phasor advances with element index');

%% Measure the baseline phase slope and infer one unambiguous angle
wrapped_phase_rad = angle(received_snapshot);
unwrapped_phase_rad = unwrap(wrapped_phase_rad);
centered_index = element_index-mean(element_index);
centered_phase_rad = unwrapped_phase_rad-mean(unwrapped_phase_rad);
estimated_phase_slope_rad_per_element = ...
    sum(centered_index.*centered_phase_rad)/sum(centered_index.^2);
adjacent_phase_slope_rad_per_element = angle(sum( ...
    conj(received_snapshot(1:end-1)).*received_snapshot(2:end)));

angle_argument = estimated_phase_slope_rad_per_element*wavelength_m/...
    (2*pi*element_spacing_m);
assert(abs(angle_argument) <= 1, 'P61:AngleOutsidePhysicalDomain');
estimated_arrival_angle_deg = asind(angle_argument);
angle_error_deg = estimated_arrival_angle_deg-arrival_angle_deg;
phase_fit_rad = mean(unwrapped_phase_rad) + ...
    estimated_phase_slope_rad_per_element*centered_index;
phase_fit_rmse_rad = sqrt(mean((unwrapped_phase_rad-phase_fit_rad).^2));

assert(abs(angle_error_deg) < 1.0, 'P61:BaselineAngleError');
assert(abs(estimated_phase_slope_rad_per_element-...
    theoretical_phase_slope_rad_per_element) < 0.05, ...
    'P61:BaselineSlopeError');
assert(abs(adjacent_phase_slope_rad_per_element-...
    theoretical_phase_slope_rad_per_element) < 0.05, ...
    'P61:AdjacentSlopeError');
assert(phase_fit_rmse_rad < 0.08, 'P61:BaselinePhaseFitError');

figure('Name', 'P61 baseline phase slope', 'Tag', 'P61');
subplot(2, 1, 1);
plot(element_index, wrapped_phase_rad, 'o-', 'LineWidth', 1.1);
grid on;
xlabel('Element index m');
ylabel('Principal phase (rad)');
title('Principal phase wraps at +/-pi');
subplot(2, 1, 2);
plot(element_index, unwrapped_phase_rad, 'o-', 'LineWidth', 1.1);
hold on;
plot(element_index, ideal_phase_rad, '--', 'LineWidth', 1.2);
plot(element_index, phase_fit_rad, ':', 'LineWidth', 1.3);
grid on;
xlabel('Element index m');
ylabel('Unwrapped phase (rad)');
title(sprintf('Slope %.3f rad/element -> angle %.2f deg', ...
    estimated_phase_slope_rad_per_element, estimated_arrival_angle_deg));
legend('Noisy measurement', 'Geometric model', 'Least-squares fit', ...
    'Location', 'best');

%% Sweep 1: change only arrival angle
angle_sweep_theoretical_slope = 2*pi*(element_spacing_m/wavelength_m)*...
    sind(arrival_angle_sweep_deg);
angle_sweep_measured_slope = zeros(size(arrival_angle_sweep_deg));
angle_sweep_estimated_angle_deg = zeros(size(arrival_angle_sweep_deg));
angle_sweep_phase_rad = zeros(numel(arrival_angle_sweep_deg), ...
    number_elements);
for case_index = 1:numel(arrival_angle_sweep_deg)
    candidate_angle_deg = arrival_angle_sweep_deg(case_index);
    candidate_phase_rad = initial_phase_rad + ...
        2*pi*(element_position_m/wavelength_m)*sind(candidate_angle_deg);
    angle_sweep_phase_rad(case_index,:) = candidate_phase_rad;
    candidate_centered_phase = candidate_phase_rad-mean(candidate_phase_rad);
    candidate_slope = sum(centered_index.*candidate_centered_phase)/...
        sum(centered_index.^2);
    angle_sweep_measured_slope(case_index) = candidate_slope;
    angle_sweep_estimated_angle_deg(case_index) = asind( ...
        candidate_slope*wavelength_m/(2*pi*element_spacing_m));
end
assert(max(abs(angle_sweep_measured_slope-...
    angle_sweep_theoretical_slope)) < comparison_tolerance, ...
    'P61:AngleSweepModelMismatch');
assert(max(abs(angle_sweep_estimated_angle_deg-...
    arrival_angle_sweep_deg)) < comparison_tolerance, ...
    'P61:AngleSweepInferenceMismatch');
assert(all(diff(angle_sweep_measured_slope) > 0), ...
    'P61:AngleSweepNotMonotonic');

figure('Name', 'P61 arrival-angle sweep', 'Tag', 'P61');
subplot(1, 2, 1);
plot(element_index, angle_sweep_phase_rad.', 'LineWidth', 1.1);
grid on;
xlabel('Element index m');
ylabel('Ideal unwrapped phase (rad)');
title('Direction controls the sign and steepness');
legend(compose('%g deg', arrival_angle_sweep_deg), 'Location', 'best');
subplot(1, 2, 2);
plot(arrival_angle_sweep_deg, angle_sweep_measured_slope, ...
    'o-', 'LineWidth', 1.2);
hold on;
plot(arrival_angle_sweep_deg, angle_sweep_theoretical_slope, ...
    '--', 'LineWidth', 1.2);
grid on;
xlabel('Arrival angle from broadside (deg)');
ylabel('Spatial phase slope (rad/element)');
title('Slope follows sin(theta), not theta itself');
legend('Measured from samples', '2*pi*(d/lambda)*sin(theta)', ...
    'Location', 'best');

%% Sweep 2: reach the same electrical spacing by changing d or frequency
spacing_sweep_m = spacing_sweep_wavelengths*wavelength_m;
spacing_sweep_delay_ps = -1e12*spacing_sweep_m*...
    sind(arrival_angle_deg)/speed_of_light_mps;
spacing_sweep_slope = 2*pi*spacing_sweep_wavelengths*...
    sind(arrival_angle_deg);

% Physical spacing stays fixed here. Changing frequency changes wavelength,
% not geometric delay, and therefore changes phase accumulated over that delay.
frequency_sweep_wavelength_m = speed_of_light_mps./frequency_sweep_hz;
frequency_sweep_electrical_spacing = element_spacing_m./...
    frequency_sweep_wavelength_m;
frequency_sweep_delay_ps = -1e12*element_spacing_m*...
    sind(arrival_angle_deg)/speed_of_light_mps*...
    ones(size(frequency_sweep_hz));
frequency_sweep_slope = 2*pi*frequency_sweep_electrical_spacing*...
    sind(arrival_angle_deg);

assert(all(diff(spacing_sweep_slope) > 0), ...
    'P61:SpacingSweepNotMonotonic');
assert(all(diff(frequency_sweep_slope) > 0), ...
    'P61:FrequencySweepNotMonotonic');
assert(max(abs(spacing_sweep_slope-frequency_sweep_slope)) < ...
    comparison_tolerance, 'P61:ElectricalSpacingMismatch');
assert(max(abs(frequency_sweep_delay_ps-frequency_sweep_delay_ps(1))) < ...
    comparison_tolerance, 'P61:FrequencyChangedDelay');

figure('Name', 'P61 spacing and frequency sweep', 'Tag', 'P61');
subplot(1, 2, 1);
plot(spacing_sweep_wavelengths, spacing_sweep_slope, ...
    'o-', 'LineWidth', 1.2);
hold on;
plot(frequency_sweep_electrical_spacing, frequency_sweep_slope, ...
    's--', 'LineWidth', 1.2);
grid on;
xlabel('Electrical spacing d/lambda (wavelengths)');
ylabel('Spatial phase slope (rad/element)');
title('Spacing and frequency act through d/lambda');
legend('Change physical d at 3 GHz', 'Change f at fixed physical d', ...
    'Location', 'best');
subplot(1, 2, 2);
plot(spacing_sweep_wavelengths, spacing_sweep_delay_ps, ...
    'o-', 'LineWidth', 1.2);
hold on;
plot(frequency_sweep_electrical_spacing, frequency_sweep_delay_ps, ...
    's--', 'LineWidth', 1.2);
grid on;
xlabel('Electrical spacing d/lambda (wavelengths)');
ylabel('Adjacent geometric delay (ps)');
title('Frequency changes phase without changing path delay');
legend('Change physical d', 'Change f only', 'Location', 'best');

%% Intentionally broken case: spacing aliases two different directions
broken_spacing_m = broken_spacing_wavelengths*wavelength_m;
broken_true_phase_rad = initial_phase_rad + 2*pi*element_index*...
    broken_spacing_wavelengths*sind(broken_true_angle_deg);
broken_alias_phase_rad = initial_phase_rad + 2*pi*element_index*...
    broken_spacing_wavelengths*sind(broken_alias_angle_deg);
broken_true_snapshot = exp(1j*broken_true_phase_rad);
broken_alias_snapshot = exp(1j*broken_alias_phase_rad);
broken_snapshot_mismatch = max(abs( ...
    broken_true_snapshot-broken_alias_snapshot));

broken_wrapped_step_rad = angle(sum(conj( ...
    broken_true_snapshot(1:end-1)).*broken_true_snapshot(2:end)));
broken_inferred_angle_deg = asind(broken_wrapped_step_rad/...
    (2*pi*broken_spacing_wavelengths));
broken_angle_error_deg = broken_inferred_angle_deg-broken_true_angle_deg;

assert(broken_snapshot_mismatch < comparison_tolerance, ...
    'P61:AliasSnapshotsDiffer');
assert(abs(broken_inferred_angle_deg-broken_alias_angle_deg) < ...
    comparison_tolerance, 'P61:WrongAliasAngle');
assert(abs(broken_angle_error_deg) > 50, 'P61:AliasFailureNotVisible');

% Recovery restores half-wavelength spacing, preserving source angle,
% carrier, phase, and sensor count. The adjacent step returns inside +/-pi.
recovered_spacing_wavelengths = 0.5;
recovered_phase_rad = initial_phase_rad + 2*pi*element_index*...
    recovered_spacing_wavelengths*sind(broken_true_angle_deg);
recovered_snapshot = exp(1j*recovered_phase_rad);
recovered_step_rad = angle(sum(conj(recovered_snapshot(1:end-1)).*...
    recovered_snapshot(2:end)));
recovered_angle_deg = asind(recovered_step_rad/...
    (2*pi*recovered_spacing_wavelengths));
assert(abs(recovered_angle_deg-broken_true_angle_deg) < ...
    comparison_tolerance, 'P61:RecoveryAngleMismatch');

figure('Name', 'P61 spatial alias and recovery', 'Tag', 'P61');
subplot(1, 2, 1);
plot(element_index, angle(broken_true_snapshot), 'o-', 'LineWidth', 1.2);
hold on;
plot(element_index, angle(broken_alias_snapshot), 's--', 'LineWidth', 1.2);
grid on;
xlabel('Element index m');
ylabel('Principal phase (rad)');
title(sprintf('d/lambda=1: %.2f deg and %.2f deg are identical', ...
    broken_true_angle_deg, broken_alias_angle_deg));
legend('True direction samples', 'Alias direction samples', ...
    'Location', 'best');
subplot(1, 2, 2);
bar([broken_true_angle_deg broken_inferred_angle_deg recovered_angle_deg]);
grid on;
set(gca, 'XTickLabel', {'True', 'Aliased inference', 'd/lambda=0.5 recovery'});
ylabel('Arrival angle from broadside (deg)');
title('Unwrap cannot restore a missing spatial cycle');

